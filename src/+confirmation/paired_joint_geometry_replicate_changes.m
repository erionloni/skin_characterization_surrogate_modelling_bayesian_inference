function changes = paired_joint_geometry_replicate_changes(pairs,metrics)
%PAIRED_JOINT_GEOMETRY_REPLICATE_CHANGES Paired change of the replicate geometry, reference against selected protocol.
%   CHANGES = confirmation.paired_joint_geometry_replicate_changes(PAIRS,
%   METRICS) reads, for every comparison of PAIRS (PairIndex,
%   MaterialCaseID, DefaultProtocol, SelectedProtocol, ComparisonRole;
%   confirmation.build_confirmation_grid) and each geometry scope (full_4d,
%   weak_pair), the replicate geometry metrics METRICS of its reference and
%   selected cell (the largest eigenvalue of replicates 1 and 2) and
%   returns one row per pair and scope: availability (both cells with a
%   replicate pair) or the reasons it is missing, the four eigenvalues, the
%   selected-minus-reference change per replicate and the absolute
%   difference of the two changes.
%   A summary of saved values: it defines no direction agreement,
%   tolerance, pass/fail state or scientific interpretation.
%   Side effects: none.

    requiredPairs={'PairIndex','MaterialCaseID','DefaultProtocol','SelectedProtocol','ComparisonRole'};
    requiredMetrics={'MaterialCaseID','Protocol','GeometryScope', ...
        'ReplicatePairAvailable','AvailabilityReason', ...
        'LambdaMaxReplicate1','LambdaMaxReplicate2'};
    assert(istable(pairs)&&istable(metrics)&& ...
        all(ismember(requiredPairs,pairs.Properties.VariableNames))&& ...
        all(ismember(requiredMetrics,metrics.Properties.VariableNames)), ...
        'confirmation:paired_joint_geometry_replicate_changes:Schema', ...
        ['The comparisons need the columns %s and the geometry metrics the ' ...
         'columns %s.'],strjoin(requiredPairs,', '),strjoin(requiredMetrics,', '));
    scopes=["full_4d" "weak_pair"];
    parts=cell(2*height(pairs),1);cursor=0;
    for i=1:height(pairs)
        material=double(pairs.MaterialCaseID(i));
        for s=1:2
            cursor=cursor+1;scope=scopes(s);
            d=metrics.MaterialCaseID==material& ...
                string(metrics.Protocol)==string(pairs.DefaultProtocol(i))& ...
                string(metrics.GeometryScope)==scope;
            q=metrics.MaterialCaseID==material& ...
                string(metrics.Protocol)==string(pairs.SelectedProtocol(i))& ...
                string(metrics.GeometryScope)==scope;
            assert(nnz(d)==1&&nnz(q)==1, ...
                'confirmation:paired_joint_geometry_replicate_changes:Pair', ...
                ['The geometry metrics need one row for the reference and one for the ' ...
                 'selected protocol of every material of the comparisons.']);
            available=logical(metrics.ReplicatePairAvailable(d))&& ...
                logical(metrics.ReplicatePairAvailable(q));
            delta1=NaN;delta2=NaN;difference=NaN;reason="";
            if available
                delta1=double(metrics.LambdaMaxReplicate1(q))- ...
                    double(metrics.LambdaMaxReplicate1(d));
                delta2=double(metrics.LambdaMaxReplicate2(q))- ...
                    double(metrics.LambdaMaxReplicate2(d));
                difference=abs(delta1-delta2);
            else
                reason=strjoin(unique([string( ...
                    metrics.AvailabilityReason(d));string( ...
                    metrics.AvailabilityReason(q))],'stable'),'|');
            end
            parts{cursor}=table(double(pairs.PairIndex(i)),material,scope, ...
                string(pairs.DefaultProtocol(i)),string(pairs.SelectedProtocol(i)), ...
                logical(metrics.ReplicatePairAvailable(d)), ...
                logical(metrics.ReplicatePairAvailable(q)),available,reason, ...
                double(metrics.LambdaMaxReplicate1(d)), ...
                double(metrics.LambdaMaxReplicate2(d)), ...
                double(metrics.LambdaMaxReplicate1(q)), ...
                double(metrics.LambdaMaxReplicate2(q)),delta1,delta2,difference, ...
                string(pairs.ComparisonRole(i)), ...
                'VariableNames',{'PairIndex','MaterialCaseID', ...
                'GeometryScope','DefaultProtocol','SelectedProtocol', ...
                'DefaultReplicatePairAvailable', ...
                'SelectedReplicatePairAvailable','MatchedGeometryAvailable', ...
                'AvailabilityReason','LambdaMaxDefaultReplicate1', ...
                'LambdaMaxDefaultReplicate2','LambdaMaxSelectedReplicate1', ...
                'LambdaMaxSelectedReplicate2','DeltaLambdaMaxReplicate1', ...
                'DeltaLambdaMaxReplicate2', ...
                'DeltaLambdaMaxReplicateDifference','ComparisonRole'});
        end
    end
    changes=vertcat(parts{:});
end
