function status = finalize_confirmation_campaign(preparation,provider)
%FINALIZE_CONFIRMATION_CAMPAIGN Certification index, summaries and comparisons of a run campaign.
%   STATUS = confirmation.finalize_confirmation_campaign(PREPARATION, PROVIDER)
%   collects the saved terminal decision of every cell of the prepared
%   campaign PREPARATION (every cell with an accepted observation must have
%   run, confirmation.run_confirmation_cell; a cell without one is
%   unavailable) and writes, below the campaign folder:
%     - certification/aies_certification_index.csv: per cell, certified,
%       unresolved or unavailable, with its provider (replicate and level)
%       and reason;
%     - summaries/: the posterior summaries of the providers, certified or
%       healthy fallbacks, and the paired comparisons of each selected
%       protocol with the shared reference (confirmation.summarize_confirmation),
%       in the confirmation's observation design; summaries/complete_pairs/:
%       the same for the descriptive design of the complete pairs (settings
%       B.7 completePairsDesign), when the campaign has one;
%     - reports/confirmation_report.md and status/confirmation_status.json:
%       the counts of the campaign, per design.
%   PROVIDER (screening.generalized_provider) is the approved generalized
%   package of the configuration; the summaries evaluate the frozen GP at
%   saved posterior draws and the local information at the posterior
%   means. No sampler runs. A second call recomputes the same files.
%   Computation: minutes.
%   Side effects: writes certification/, summaries/, reports/ and status/
%   below the campaign folder, replacing earlier versions.

    started=tic;
    grid=preparation.grid;
    count=grid.cellCount;
    records=cell(count,1);missing=false(1,count);
    unavailable=false(1,count);
    for i=1:count
        cellRecord=grid.cells(i);
        if isfield(cellRecord,'available')&&~cellRecord.available
            % No accepted observation: never run, unavailable (nothing imputed).
            unavailable(i)=true;
            records{i}=confirmation.confirmation_campaign_support('campaign_record',cellRecord, ...
                struct('certified',false,'status','unavailable','reason', ...
                cellRecord.unavailableReason),[]);
            continue;
        end
        cellCfg=preparation.protocolConfigurations.(cellRecord.protocol);
        outcome=confirmation.confirmation_campaign_support('cell_outcome',cellCfg,cellRecord);
        missing(i)=outcome.missing;
        if ~outcome.missing
            records{i}=confirmation.confirmation_campaign_support('campaign_record', ...
                cellRecord,outcome.decision,outcome.decision.executedEvidence);
        end
    end
    assert(~any(missing),'confirmation:finalize_confirmation_campaign:MissingCells', ...
        ['%d of %d confirmation cells have not run (task indices %s of %s): run them ' ...
         'with the step ''run_cells'' first.'],nnz(missing),count, ...
        mat2str(find(missing)),preparation.paths.taskTableCSV);
    entries=vertcat(records{:});

    paths=preparation.paths;
    certificationIndex=confirmation.confirmation_campaign_support( ...
        'certification_table',entries);
    utils.atomic_write_table(paths.certificationIndexCSV,certificationIndex);
    % One summary per observation design: the confirmation's design in
    % summaries/, the descriptive design of the complete pairs in
    % summaries/complete_pairs/. A summary reads the cells of its design only.
    designs=grid.designs;
    summaries=cell(1,numel(designs));
    for d=1:numel(designs)
        sub=confirmation.confirmation_campaign_support('design_grid',grid,designs(d).name);
        index=certificationIndex(ismember(certificationIndex.ConfirmationCellIndex, ...
            [sub.cells.cellIndex]),:);
        folder='summaries';
        if strcmp(designs(d).role,'complete_pairs'),folder=fullfile('summaries','complete_pairs');end
        summaries{d}=confirmation.summarize_confirmation(preparation.baseConfiguration,provider, ...
            sub,preparation.protocolConfigurations,index,'OutputRoot',paths.root, ...
            'SummaryFolder',folder);
    end
    summary=summaries{1};
    primary=confirmation.confirmation_campaign_support('design_grid',grid,designs(1).name);
    elapsed=toc(started);
    report=confirmation.confirmation_campaign_support('confirmation_report', ...
        grid,summaries,elapsed);
    utils.atomic_write_text(paths.reportMD,report);
    E=summary.pairedEligibility;
    status=struct( ...
        'schema_version','real_extended_confirmation_status_v6', ...
        'status','complete', ...
        'protocols',{cellstr(grid.protocols.Protocol)}, ...
        'design',designs(1).name, ...
        'planned_cell_count',primary.cellCount, ...
        'material_count',numel(unique(grid.table.MaterialCaseID)), ...
        'certified_cell_count',summary.certifiedCellCount, ...
        'unresolved_cell_count',summary.unresolvedCellCount, ...
        'unavailable_cell_count_no_observation',nnz(unavailable), ...
        'sampler_failure_cell_count',nnz([entries.failedRequestCount]>0), ...
        'aies_request_count',sum([entries.executionCount]), ...
        'successful_aies_request_count',sum([entries.successfulRequestCount]), ...
        'failed_aies_request_count',sum([entries.failedRequestCount]), ...
        'adaptive_metropolis_request_count',sum([entries.amRequestCount]), ...
        'planned_comparison_count',height(primary.comparisons), ...
        'paired_comparison_count',summary.pairedCount, ...
        'paired_certified_comparison_count',summary.pairedCertifiedCount, ...
        'paired_material_count',numel(unique(E.MaterialCaseID(E.IncludedInPairedSummary))), ...
        'paired_certified_material_count',numel(unique(E.MaterialCaseID( ...
            E.DefaultCertified&E.SelectedCertified))), ...
        'common_all_arms_certified_material_count', ...
            nnz(summary.objectives.commonAllArmCohort.AllArmsCertified), ...
        'complete_pairs',complete_pairs_status(grid,designs,summaries), ...
        'posterior_samples_pooled',false, ...
        'elapsed_seconds',elapsed, ...
        'environment',utils.environment_line());
    utils.atomic_write_json(paths.statusJSON,status,'AllowReplace',true);
end

function value=complete_pairs_status(grid,designs,summaries)
%COMPLETE_PAIRS_STATUS The counts of the descriptive design of the complete pairs (empty without one).
    value=struct([]);
    d=find(strcmp({designs.role},'complete_pairs'));
    if isempty(d),return;end
    sub=confirmation.confirmation_campaign_support('design_grid',grid,designs(d).name);
    S=summaries{d};
    value=struct('design',designs(d).name, ...
        'note','the complete pairs only: descriptive, not representative of the protocols', ...
        'cell_count',sub.cellCount,'certified_cell_count',S.certifiedCellCount, ...
        'comparison_count',height(sub.comparisons),'paired_comparison_count',S.pairedCount, ...
        'paired_certified_comparison_count',S.pairedCertifiedCount);
end
