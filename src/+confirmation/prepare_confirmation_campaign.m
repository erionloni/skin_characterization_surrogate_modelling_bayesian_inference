function preparation = prepare_confirmation_campaign(cfg,provider,observationsFile,outputRoot)
%PREPARE_CONFIRMATION_CAMPAIGN The confirmation campaign's cells, seeds and tasks, written once.
%   PREPARATION = confirmation.prepare_confirmation_campaign(CFG, PROVIDER, OBSERVATIONSFILE, OUTPUTROOT)
%   prepares the confirmation campaign from
%     CFG               the confirmation configuration (study.native_config),
%                       whose settings define the design (B.7,
%                       confirmation.confirmation_design);
%     PROVIDER          the approved generalized model (screening.generalized_provider):
%                       the material parameters, their prior bounds and the outputs;
%     OBSERVATIONSFILE  the accepted observations of the design
%                       (confirmation.read_confirmation_observations: one row
%                       per design row, joined by its exact values);
%   and writes it below OUTPUTROOT, the campaign folder:
%     - the cell grid (confirmation.build_confirmation_grid): one inverse
%       cell per material and protocol in the confirmation's observation
%       design (B.7 design), the cell of the reference protocol shared by
%       the comparisons of its material, and the paired comparisons; the
%       cells of a design row without accepted observations (the reviewer's
%       exclusion) are unavailable and never run; with a descriptive design
%       of the complete pairs (B.7 completePairsDesign) also its cells and
%       comparisons on the pairs that have all its pressures;
%     - the request seed of every cell, level and replicate
%       (seeds.confirmation: the rule of the settings, from the material's
%       CaseID, the protocol's row and the cell's design);
%     - one configuration per protocol and the task table (with the
%       demonstration chain lengths of a demonstration campaign,
%       CFG.mcmc.demonstrationSteps, which every cell runs with);
%     - the protocols and observations it used (inputs/), the preparation
%       (configuration/confirmation_preparation.mat) and a description of
%       the campaign (configuration/*.json).
%   A campaign folder is prepared once. Nothing is sampled.
%   Computation: about a minute.
%   Side effects: writes the prepared campaign below its root folder.

    assert(strcmp(cfg.dataMode,'real_extended')&& ...
        ~logical(cfg.mcmc.enableAdaptiveMetropolisValidation)&& ...
        isempty(cfg.mcmc.amValidationCaseIDs), ...
        'confirmation:prepare_confirmation_campaign:Configuration', ...
        ['The confirmation runs on the generalized route with AIES only ' ...
         '(no adaptive-Metropolis validation).']);
    outputRoot=utils.absolute_path(char(string(outputRoot)));
    design=confirmation.confirmation_design(cfg);
    % The pressures of the confirmation's observation design (settings B.7)
    % must be accepted; a row the reviewer excluded has unavailable cells.
    observationDesign=inversion.design_registry(cfg.stage9bConfirmation.design);
    outputNames=cellstr(string(provider.outputNames));
    observations=confirmation.read_confirmation_observations(design,observationsFile, ...
        outputNames,outputNames(observationDesign.sourceOutputIndices));
    policy=confirmation.confirmation_campaign_support('portable_policy',cfg.stage9bConfirmation);
    demonstrationSteps=[];
    if isfield(cfg.mcmc,'demonstrationSteps')
        % A demonstration campaign ('DemonstrationSteps'): its configurations
        % carry the shortened chains, which every cell runs with.
        demonstrationSteps=reshape(double(cfg.mcmc.demonstrationSteps),1,[]);
    end
    aiesPolicy=struct('productionSampler',cfg.mcmc.productionSampler, ...
        'productionReplicateIDs',cfg.mcmc.productionReplicateIDs, ...
        'levels',cfg.mcmc.levels,'burnIn',cfg.mcmc.burn_in, ...
        'thinning',cfg.mcmc.thinning,'initialization',cfg.mcmc.initialization, ...
        'aies',cfg.mcmc.aies,'continuationSemantics', ...
            cfg.mcmc.continuationSemantics, ...
        'adaptiveMetropolisEnabled',false, ...
        'diagnosticThresholds',inversion.mcmc_diagnostic_thresholds(cfg), ...
        'demonstrationSteps',demonstrationSteps);
    grid=confirmation.build_confirmation_grid(cfg,provider,design,observations,outputRoot);
    [seedRecords,seedScheduleTable]=confirmation.confirmation_campaign_support( ...
        'seed_schedule',cfg,grid);
    configurations=confirmation.confirmation_campaign_support( ...
        'request_configurations',cfg,provider,outputRoot,grid);
    taskTable=confirmation.confirmation_campaign_support('task_table',grid, ...
        configurations,outputRoot);
    configuration=struct( ...
        'schema_version','real_extended_confirmation_configuration_v4', ...
        'route','real_extended', ...
        'materials',design.materials.MaterialCaseID.', ...
        'protocols',{table2struct(design.protocols)}, ...
        'seed_rule',cfg.seeds.rules.confirmation, ...
        'parameter_names',{provider.materialParameterNames}, ...
        'prior_bounds',provider.materialBounds, ...
        'output_names',{provider.outputNames}, ...
        'measurement_cv',double(cfg.meas_cv), ...
        'numerical_floor_sd',double(cfg.likelihood.minSigma), ...
        'scenario','measurement_plus_gp','design',observationDesign.name, ...
        'complete_pairs_design',complete_pairs_design(grid), ...
        'cell_count',grid.cellCount, ...
        'planned_comparison_count',nnz(grid.comparisons.DesignRole=="primary"), ...
        'complete_pairs_comparison_count',nnz(grid.comparisons.DesignRole=="complete_pairs"), ...
        'policy',policy,'aies_policy',aiesPolicy);
    preparation=struct( ...
        'schemaVersion','confirmation_campaign_preparation_v5', ...
        'design',design,'observations',observations,'grid',grid, ...
        'protocolConfigurations',configurations,'policy',policy, ...
        'aiesPolicy',aiesPolicy,'seedRecords',seedRecords, ...
        'seedScheduleTable',seedScheduleTable,'taskTable',taskTable, ...
        'configuration',configuration,'baseConfiguration',cfg, ...
        'paths',confirmation.confirmation_campaign_support('paths',outputRoot));
    confirmation.confirmation_campaign_support('publish_preparation',preparation);
end

function name=complete_pairs_design(grid)
%COMPLETE_PAIRS_DESIGN The descriptive design of the complete pairs, '' when the campaign has none.
    name='';
    roles={grid.designs.role};
    if any(strcmp(roles,'complete_pairs')),name=grid.designs(strcmp(roles,'complete_pairs')).name;end
end
