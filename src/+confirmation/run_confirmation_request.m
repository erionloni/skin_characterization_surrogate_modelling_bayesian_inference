function execution=run_confirmation_request(cellRecord,gp,P,cfg,varargin)
%RUN_CONFIRMATION_REQUEST One MCMC request of a confirmation cell: its protocol and its direct observation.
%   EXECUTION = confirmation.run_confirmation_request(CELLRECORD, GP, P, CFG,
%   'Sampler', S, 'ReplicateID', R, 'StepCount', N) runs one request of the
%   cell CELLRECORD (a prepared cell of the confirmation grid, scenario
%   measurement_plus_gp, its observation design all_six or d2_only): the four
%   material parameters are inferred from the observed closing pressures of
%   the cell's design (the direct COMSOL observation; a pressure outside the
%   design may be missing), the cell's protocol (three inputs) is known and
%   fixed. The
%   generalized GP (GP, surrogates.evaluate_generalized_gp) is evaluated at
%   the material parameters and the cell's protocol; the parameter space P
%   has the four material parameters. The seed is that of the confirmation's
%   rule for the cell's material, protocol, design, level and replicate
%   (seeds.confirmation). A request that an earlier call finished is reused
%   when CFG.resume is true.
%   Sampling, diagnostics, saving and certification are those of the fixed
%   route (inversion.bayes_invert, inversion.save_posterior_artifact).
%   EXECUTION: state ('executed' or 'resumed_complete_request'), the
%   request, its seed record and sampler settings, the retained sample
%   array, the draws in model coordinates and the health record.
%   Side effects: writes the request's files below the cell folder of the
%   campaign; the random number generator is restored afterwards.
%   Computation: minutes to an hour (one MCMC request).

    parser=inputParser;
    parser.FunctionName='confirmation.run_confirmation_request';
    addParameter(parser,'Sampler','AIES',@text_scalar);
    addParameter(parser,'ReplicateID',1,@positive_integer);
    addParameter(parser,'StepCount',cfg.mcmc.levels(1),@positive_integer);
    parse(parser,varargin{:});
    sampler=upper(char(string(parser.Results.Sampler)));
    replicateID=double(parser.Results.ReplicateID);
    stepCount=double(parser.Results.StepCount);
    assert(strcmp(cfg.dataMode,'real_extended')&&P.M==4&& ...
        isfield(cfg,'stage9bConfirmation')&& ...
        isfield(cfg.stage9bConfirmation,'runtime'), ...
        'confirmation:run_confirmation_request:Configuration', ...
        ['A confirmation request needs the protocol''s configuration of a prepared ' ...
         'campaign and four material parameters.']);
    runtime=cfg.stage9bConfirmation.runtime;
    require_fields(runtime,{'protocol'});
    requiredCell={'caseID','scenario','design','truth','heldout_response', ...
        'protocol','protocolIndex','protocolRole','protocolVector','MaterialCaseID'};
    require_fields(cellRecord,requiredCell);
    assert(strcmp(cellRecord.scenario,'measurement_plus_gp')&& ...
        ismember(cellRecord.design,{'all_six','d2_only'})&& ...
        ismember(cellRecord.protocolRole,{'default','selected'})&& ...
        strcmp(cellRecord.protocol,runtime.protocol), ...
        'confirmation:run_confirmation_request:CellAxes', ...
        'The cell %s of protocol %s does not belong to the configuration of protocol %s.', ...
        cellRecord.cellID,cellRecord.protocol,runtime.protocol);
    design=inversion.design_registry(cellRecord.design);
    truth=reshape(double(cellRecord.truth),1,[]);
    observation=reshape(double(cellRecord.heldout_response),1,[]);
    protocol=reshape(double(cellRecord.protocolVector),1,[]);
    % The pressures of the cell's design are observed; the others may be
    % missing (NaN) and are not read.
    assert(numel(truth)==4&&numel(observation)==6&&numel(protocol)==3&& ...
        all(isfinite([truth observation(design.sourceOutputIndices) protocol]))&& ...
        all(truth>=double(cfg.paramBounds(:,1)).')&& ...
        all(truth<=double(cfg.paramBounds(:,2)).'), ...
        'confirmation:run_confirmation_request:CellData');

    [requestCfg,samplerSettings]=inversion.sampler_request_config( ...
        cfg,sampler,stepCount);
    [seed,seedRecord]=seeds.confirmation(cfg,cellRecord.MaterialCaseID, ...
        cellRecord.protocolIndex,sampler,replicateID,stepCount,cellRecord.design);
    [cached,cachedStatus]=inversion.load_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    if logical(cfg.resume)&&cachedStatus.valid
        % A request that an earlier call finished is reused.
        execution=execution_from_artifact(cached,cachedStatus,seedRecord, ...
            samplerSettings,'resumed_complete_request');
        return
    end

    scenario=inversion.scenario_registry('measurement_plus_gp');
    opts=struct( ...
        'outputs',design.sourceOutputIndices, ...
        'observationTransform',design.observationTransform, ...
        'thetaTrue',truth,'keepAnalysis',false, ...
        'scenarioTag',scenario.tag, ...
        'observationSource',scenario.observationSource, ...
        'uncertaintyMode',scenario.uncertaintyMode, ...
        'measurementCV',cfg.meas_cv, ...
        'emulatorErrorCalibrationVersion', ...
            cfg.inversion.emulatorErrorCalibrationVersion, ...
        'replicateID',replicateID, ...
        'continuationStage',sprintf('fresh_total_%d',stepCount), ...
        'initialization',requestCfg.mcmc.initialization, ...
        'initializationParameters',struct(), ...
        'caseID',char(string(cellRecord.MaterialCaseID)), ...
        'seed',seed, ...
        'predictionEvaluator',@(model,theta,configuration) ...
            protocol_prediction(model,theta,configuration,protocol));
    previousRng=rng;
    restoreRng=onCleanup(@()rng(previousRng));
    rng(seed,'twister');
    try
        result=inversion.bayes_invert(gp,observation,P,requestCfg,opts);
    catch exception
        if fail_closed_exception(exception),rethrow(exception);end
        wrapper=MException('inversion:run_cell:SamplerExecutionFailure', ...
            '%s sampler execution failed for %s.',sampler,cellRecord.cellID);
        wrapper=addCause(wrapper,exception);
        throw(wrapper);
    end
    result.directSamplerSettings=samplerSettings;
    result.directSeedRecord=seedRecord;
    health=result.singleAnalysisHealth;
    inversion.save_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount,seed,result, ...
        truth,observation,health);
    [posterior,status]=inversion.load_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    execution=execution_from_artifact(posterior,status,seedRecord, ...
        samplerSettings,'executed');
end

function prediction=protocol_prediction(model,theta,cfg,protocol)
    validateattributes(theta,{'numeric'},{'2d','real','finite','ncols',4});
    X=[double(theta) repmat(double(protocol),size(theta,1),1)];
    prediction=surrogates.evaluate_generalized_gp(model,X,cfg);
end

function execution=execution_from_artifact(artifact,status,seedRecord, ...
        samplerSettings,state)
    execution=struct( ...
        'schemaVersion','direct_mcmc_cell_execution_v1', ...
        'state',state,'succeeded',true,'request',artifact.request, ...
        'sampler',artifact.request.sampler, ...
        'replicateID',artifact.request.replicateID, ...
        'stepCount',artifact.request.stepCount,'seed',artifact.request.seed, ...
        'seedRecord',seedRecord,'samplerSettings',samplerSettings, ...
        'sampleArray',artifact.sampleArray, ...
        'drawsPhysical',artifact.drawsPhysical,'health',artifact.health, ...
        'artifact',artifact,'paths',status.paths,'samplesPooled',false, ...
        'failure',struct([]));
end

function require_fields(value,names)
    assert(isstruct(value)&&isscalar(value)&&all(isfield(value,names)), ...
        'confirmation:run_confirmation_request:RequiredFields', ...
        'A confirmation request needs the fields %s.',strjoin(names,', '));
end

function tf=fail_closed_exception(exception)
    identifiers=string(exception.identifier);
    queue=exception.cause;
    while ~isempty(queue)
        current=queue{1};queue(1)=[];
        identifiers(end+1)=string(current.identifier); %#ok<AGROW>
        queue=[queue current.cause]; %#ok<AGROW>
    end
    tf=any(startsWith(identifiers,"screening:")| ...
        startsWith(identifiers,"confirmation:")| ...
        startsWith(identifiers,"surrogates:evaluate_generalized_gp:")| ...
        startsWith(identifiers,"inversion:gp_log_likelihood:")| ...
        startsWith(identifiers,"inversion:raw_observation_variance:")| ...
        startsWith(identifiers,"inversion:uncertainty_mode:")| ...
        startsWith(identifiers,"inversion:physics_floor:"));
end

function tf=text_scalar(value)
    tf=ischar(value)||(isstring(value)&&isscalar(value));
end

function tf=positive_integer(value)
    tf=isnumeric(value)&&isscalar(value)&&isfinite(value)&& ...
        value==fix(value)&&value>=1;
end
