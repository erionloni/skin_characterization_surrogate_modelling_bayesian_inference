function summary=summarize_confirmation( ...
        cfg,provider,grid,configurations,certificationIndex,varargin)
%SUMMARIZE_CONFIRMATION The posterior summaries and paired comparisons of a run confirmation campaign.
%   SUMMARY = confirmation.summarize_confirmation(CFG, PROVIDER, GRID,
%   CONFIGURATIONS, CERTIFICATIONINDEX, ...) reads the provider of every
%   cell of the campaign GRID (confirmation.build_confirmation_grid;
%   CONFIGURATIONS: one per protocol; the certified AIES replicate 1,
%   unpooled, or for a cell that was not certified its healthy completed
%   fallback, confirmation.load_available_posterior)
%   and computes the posterior
%   parameter summaries, the weak-pair covariance and the full covariance
%   and correlation of every cell, the posterior reconstruction of the six
%   pressures and the marginal densities; per material, the paired
%   differences of each selected protocol against the shared reference,
%   with the eligibility of every pair; the replicate geometry of cells
%   with a replicate pair at the accepted level (replicate 2 contributes
%   this geometry only); the FIM-predicted against the AIES-observed
%   weak-pair change (confirmation.multiarm_fim_comparison) and the six
%   objectives of the posteriors (confirmation.posterior_objective_comparisons).
%   A cell is named by its index, material (MaterialCaseID) and protocol
%   (Protocol, ProtocolRole), a comparison by its PairIndex, material and
%   protocols. CERTIFICATIONINDEX is the campaign's certification index;
%   unmatched and unresolved cells stay explicit.
%   The cell status (summaries/confirmation_cell_status.csv) names every
%   cell's provider kind: certified, healthy_completed_fallback or
%   unavailable.
%   GRID holds the cells of one observation design
%   (confirmation.confirmation_campaign_support 'design_grid'); the FIM proxy
%   uses the pressures of that design.
%   Options: 'OutputRoot' (default GRID.outputRoot; the campaign folder, to
%   which the selected posterior paths are relative), 'SummaryFolder'
%   (default 'summaries', below 'OutputRoot'), 'WriteOutputs' (default true).
%   SUMMARY: the tables above and the cell counts.
%   Side effects: with 'WriteOutputs', writes the tables to 'SummaryFolder'
%   below 'OutputRoot'.
%   Computation: minutes (the GP at saved posterior draws and the local
%   information at the posterior means).

    parser=inputParser;
    parser.FunctionName='confirmation.summarize_confirmation';
    addParameter(parser,'OutputRoot',grid.outputRoot,@text_scalar);
    addParameter(parser,'SummaryFolder','summaries',@text_scalar);
    addParameter(parser,'WriteOutputs',true,@logical_scalar);
    parse(parser,varargin{:});options=parser.Results;
    validate_inputs(cfg,provider,grid,configurations,certificationIndex);
    bounds=double(provider.materialBounds);
    names=cellstr(string(provider.materialParameterNames));
    targetNames=cellstr(string(provider.targetParameterNames));
    target=double(provider.targetIndices);
    nCell=numel(grid.cells);
    parameterParts=cell(nCell,1);weakParts=cell(nCell,1);
    matrixParts=cell(nCell,1);
    densityParts=cell(nCell,1);reconstructionParts=cell(nCell,1);
    loadParts=cell(nCell,1);
    jointGeometryParts=cell(nCell,1);
    for i=1:nCell
        cellRecord=grid.cells(i);
        cellCfg=configurations.(cellRecord.protocol);
        if isfield(cellRecord,'available')&&~cellRecord.available
            % No accepted observation (the reviewer's exclusion): never run,
            % unavailable; the status fields of a cell without a posterior.
            [artifact,status]=inversion.load_certified_posterior(cellCfg,cellRecord);
            assert(~status.loaded,'confirmation:summarize_confirmation:UnavailableCell', ...
                'Cell %s has no accepted observation but a posterior.',cellRecord.cellID);
            status.certified=false;
            status.state='no_accepted_observation';status.reason=cellRecord.unavailableReason;
        else
            [artifact,status]=confirmation.load_available_posterior(cellCfg,cellRecord);
        end
        indexRow=certificationIndex.ConfirmationCellIndex==cellRecord.cellIndex;
        assert(nnz(indexRow)==1, ...
            'confirmation:summarize_confirmation:CertificationIndex', ...
            'The certification index has %d rows for confirmation cell %d, not one.', ...
            nnz(indexRow),cellRecord.cellIndex);
        certified=logical(status.loaded)&&logical(status.certified);
        loadParts{i}=load_row(cellRecord,status,artifact,options.OutputRoot);
        if status.loaded
            [parameterParts{i},densityParts{i}]=parameter_rows( ...
                cellRecord,artifact,names,bounds,status);
            [weakParts{i},matrixParts{i}]=weak_row( ...
                cellRecord,artifact,names,bounds,target,status, ...
                cellCfg.analysis.posteriorEigendecomposition);
            reconstructionParts{i}=reconstruction_rows( ...
                cellRecord,artifact,provider.outputNames, ...
                provider.evaluateMean,cfg.stage9bConfirmation. ...
                    posteriorReconstructionBatchSize,status);
            comparison=struct([]);
            if certified
            comparison=recovery.accepted_replicate_joint_geometry( ...
                cellCfg,cellRecord,artifact, ...
                'ParameterNames',names,'Bounds',bounds, ...
                'WeakPairIndices',target);
            end
            jointGeometryParts{i}=joint_geometry_rows( ...
                cellRecord,comparison,status);
        else
            parameterParts{i}=missing_parameter_rows( ...
                cellRecord,names,status);
            densityParts{i}=empty_density_table();
            [weakParts{i},matrixParts{i}]=missing_weak_row( ...
                cellRecord,names,target,status);
            reconstructionParts{i}=missing_reconstruction_rows( ...
                cellRecord,provider.outputNames,status);
            jointGeometryParts{i}=joint_geometry_rows( ...
                cellRecord,struct([]),status);
        end
    end
    cellStatus=vertcat(loadParts{:});
    cellStatus.ProviderKind=repmat("unavailable",height(cellStatus),1);
    cellStatus.ProviderKind(cellStatus.Certified)="certified";
    cellStatus.ProviderKind(cellStatus.ArtifactLoaded&~cellStatus.Certified)="healthy_completed_fallback";
    parameterSummary=vertcat(parameterParts{:});
    weakPairCovariance=vertcat(weakParts{:});
    fullCovarianceCorrelation=vertcat(matrixParts{:});
    posteriorDensity=vertcat(densityParts{:});
    reconstruction=vertcat(reconstructionParts{:});
    jointGeometryReplicateMetrics=vertcat(jointGeometryParts{:});
    [pairedDifferences,pairedEligibility]=paired_differences( ...
        grid.pairs,parameterSummary,weakPairCovariance,cellStatus,names);
    pairedJointGeometryReplicateChanges= ...
        confirmation.paired_joint_geometry_replicate_changes( ...
        grid.pairs,jointGeometryReplicateMetrics);
    aggregate=aggregate_paired( ...
        pairedDifferences,pairedEligibility,names,targetNames);
    [fimComparison,fimAggregate]=confirmation.multiarm_fim_comparison( ...
        cfg,provider,grid,weakPairCovariance,@screening.evaluate_local_information);
    outputRoot=utils.absolute_path(char(string(options.OutputRoot)));
    summary=struct( ...
        'schemaVersion','confirmation_summary_v4', ...
        'cellStatus',cellStatus,'parameterSummary',parameterSummary, ...
        'weakPairCovariance',weakPairCovariance, ...
        'posteriorCovarianceCorrelation',fullCovarianceCorrelation, ...
        'jointGeometryReplicateMetrics',jointGeometryReplicateMetrics, ...
        'pairedJointGeometryReplicateChanges', ...
            pairedJointGeometryReplicateChanges, ...
        'pairedDifferences',pairedDifferences, ...
        'pairedEligibility',pairedEligibility, ...
        'matchedCohortAggregate',aggregate, ...
        'fimVersusAIES',fimComparison, ...
        'fimVersusAIESAggregate',fimAggregate, ...
        'reconstruction',reconstruction, ...
        'posteriorMarginalDensity',posteriorDensity, ...
        'plannedCellCount',nCell, ...
        'certifiedCellCount',nnz(cellStatus.Certified), ...
        'unresolvedCellCount',nnz(~cellStatus.Certified& ...
            cellStatus.ExecutionStatus~="no_accepted_observation"), ...
        'noObservationCellCount',nnz(cellStatus.ExecutionStatus=="no_accepted_observation"), ...
        'matchedPairCount',height(grid.pairs), ...
        'pairedCount',nnz(pairedEligibility.IncludedInPairedSummary), ...
        'pairedCertifiedCount',nnz(pairedEligibility.DefaultCertified& ...
            pairedEligibility.SelectedCertified), ...
        'jointGeometryReplicatePairAvailableCount',nnz( ...
            jointGeometryReplicateMetrics.ReplicatePairAvailable), ...
        'jointGeometryAcceptanceThresholdDefined',false, ...
        'jointGeometryChangesCertification',false, ...
        'scientificInterpretationGenerated',false);
    summary.objectives=confirmation.posterior_objective_comparisons(grid, ...
        fullCovarianceCorrelation,cellStatus,fimComparison,cfg.stage9bScreening.comparisonTolerance);
    if options.WriteOutputs
        write_outputs(fullfile(outputRoot,char(string(options.SummaryFolder))),summary);
    end
end

function validate_inputs(cfg,provider,grid,configurations,index)
    assert(strcmp(cfg.dataMode,'real_extended')&& ...
        isequal(provider.targetParameterNames,{'m3_e_RD','log10_k0_RD'})&& ...
        isequal(double(provider.targetIndices),[2 3])&& ...
        isstruct(grid)&&all(isfield(grid,{'cells','comparisons','pairs','protocols'}))&& ...
        all(isfield(configurations,cellstr(grid.protocols.Protocol)))&&istable(index)&& ...
        height(index)==grid.cellCount, ...
        'confirmation:summarize_confirmation:Inputs', ...
        ['The confirmation summary needs the generalized provider (targets m3_e_RD ' ...
         'and log10_k0_RD), the grid with its comparisons, one configuration per ' ...
         'protocol and one certification-index row per cell.']);
    require_columns(index,{'ConfirmationCellIndex','MaterialCaseID','Protocol', ...
        'ProtocolRole','Certified','State','ProviderSampler','ProviderReplicateID', ...
        'ProviderStepCount','CertificationMechanism'});
end

function T=key_table(cellRecord,n)
%KEY_TABLE The columns that name a cell: its index, material and protocol (N rows).
    T=table(repmat(double(cellRecord.cellIndex),n,1),repmat(double(cellRecord.MaterialCaseID),n,1), ...
        repmat(string(cellRecord.protocol),n,1),repmat(string(cellRecord.protocolRole),n,1), ...
        'VariableNames',{'ConfirmationCellIndex','MaterialCaseID','Protocol','ProtocolRole'});
end

function [rows,densities]=parameter_rows(cellRecord,A,names,bounds,status)
    saved=A.summary;
    require_columns(saved,{'Parameter','Truth','Mean','Median','SD', ...
        'NormalizedPosteriorSD','ContractionAmount','SDOverPriorRange', ...
        'Q025','Q975','Covered95','PosteriorMeanNormalizedRecoveryError', ...
        'PosteriorMedianNormalizedRecoveryError'});
    assert(height(saved)==4&&isequal(cellstr(string(saved.Parameter)).',names), ...
        'confirmation:summarize_confirmation:SavedParameterSummary', ...
        'A saved parameter summary must have one row for each of the four parameters, in order.');
    parts=cell(4,1);densityParts=cell(4,1);
    for j=1:4
        estimate=plotting.posterior_marginal_density( ...
            A.drawsPhysical(:,j),'Bounds',bounds(j,:));
        truth=double(saved.Truth(j));
        coverage50=double(truth>=estimate.q25&&truth<=estimate.q75);
        errors=recovery.loss_consistent_point_errors( ...
            truth,estimate.posteriorMean,estimate.posteriorMedian, ...
            diff(bounds(j,:)));
        [sampler,replicate,steps,mechanism]=provider_axes(A);
        parts{j}=[key_table(cellRecord,1),table(string(names{j}),truth, ...
            estimate.posteriorMean,estimate.posteriorMedian, ...
            estimate.marginalMode,double(saved.SD(j)), ...
            double(saved.NormalizedPosteriorSD(j)), ...
            double(saved.ContractionAmount(j)),double(saved.SDOverPriorRange(j)), ...
            estimate.q025,estimate.q25,estimate.q75,estimate.q975, ...
            estimate.q75-estimate.q25,estimate.q975-estimate.q025, ...
            coverage50,double(saved.Covered95(j)), ...
            errors.normalizedAbsoluteErrorFromPosteriorMedian, ...
            errors.normalizedSquaredErrorFromPosteriorMean, ...
            string(sampler),replicate,steps,string(mechanism), ...
            true,string(status.state),"", ...
            'VariableNames',parameter_columns())];
        densityParts{j}=[key_table(cellRecord,numel(estimate.grid)),table( ...
            repmat(string(names{j}),numel(estimate.grid),1), ...
            estimate.grid,estimate.density, ...
            'VariableNames',{'Parameter','GridValue','Density'})];
    end
    rows=vertcat(parts{:});densities=vertcat(densityParts{:});
end

