    row=[key_table(cellRecord,1),table( ...
        m,m,m,m,m,m,m,m,m,m,m,false,m,m,false,m,m,"",m,m,"",false, ...
        string(status.state),string(status.reason), ...
        'VariableNames',weak_columns())];
    matrixRows=missing_full_covariance_rows(cellRecord,names,target,status);
end

function rows=full_covariance_rows(cellRecord,C,names,target,status,A)
    sd=sqrt(max(diag(C),0));denominator=sd*sd.';
    correlation=C./denominator;
    correlation(denominator==0)=NaN;
    [sampler,replicate,steps,mechanism]=provider_axes(A);
    [rowIndex,columnIndex]=ndgrid(1:4,1:4);
    targetEntry=ismember(rowIndex(:),target)&ismember(columnIndex(:),target);
    n=16;
    rows=[key_table(cellRecord,n),table(rowIndex(:),columnIndex(:), ...
        reshape(string(names(rowIndex(:))),[],1), ...
        reshape(string(names(columnIndex(:))),[],1), ...
        C(:),correlation(:),targetEntry, ...
        repmat(string(sampler),n,1),repmat(replicate,n,1), ...
        repmat(steps,n,1),repmat(string(mechanism),n,1),true(n,1), ...
        repmat(string(status.state),n,1),repmat("",n,1), ...
        'VariableNames',full_covariance_columns())];
end

