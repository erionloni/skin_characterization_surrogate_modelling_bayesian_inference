function rows=reconstruction_rows(cellRecord,A,outputNames,evaluator,batchSize,status)
    draws=double(A.drawsPhysical);n=size(draws,1);protocol=double(cellRecord.protocolVector);
    mu=nan(n,6);
    for first=1:batchSize:n
        block=first:min(first+batchSize-1,n);
        mu(block,:)=evaluator([draws(block,:) repmat(protocol,numel(block),1)]);
    end
    assert(all(isfinite(mu),'all'), ...
        'confirmation:summarize_confirmation:ReconstructionMean', ...
        'The surrogate returned non-finite means for the posterior draws.');
    [sampler,replicate,steps,mechanism]=provider_axes(A);
    parts=cell(6,1);
    for j=1:6
        q=utils.weighted_quantile(mu(:,j),[0.025 0.25 0.5 0.75 0.975]);
        truth=double(cellRecord.heldout_response(j));meanValue=mean(mu(:,j));
        errors=recovery.loss_consistent_point_errors( ...
            truth,meanValue,q(3),1);
        % A pressure that was not observed (outside the cell's design, no
        % QC-valid COMSOL value) has no coverage.
        covered50=double(truth>=q(2)&&truth<=q(4));
        covered95=double(truth>=q(1)&&truth<=q(5));
        if ~isfinite(truth),covered50=NaN;covered95=NaN;end
        parts{j}=[key_table(cellRecord,1),table( ...
            double(j),string(outputNames{j}),truth,meanValue,q(3), ...
            q(1),q(2),q(4),q(5),q(4)-q(2),q(5)-q(1), ...
            covered50,covered95, ...
            errors.signedErrorFromPosteriorMean, ...
            errors.signedErrorFromPosteriorMedian, ...
            errors.absoluteErrorFromPosteriorMedian, ...
            errors.squaredErrorFromPosteriorMean,double(n),true, ...
            string(sampler),replicate,steps,string(mechanism), ...
            string(status.state),"", ...
            'VariableNames',reconstruction_columns())];
    end
    rows=vertcat(parts{:});
end

