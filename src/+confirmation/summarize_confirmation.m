function value=mean_nan(x)
    x=double(x);x=x(isfinite(x));
    if isempty(x),value=NaN;else,value=mean(x);end
end

function value=median_nan(x)
    x=double(x);x=x(isfinite(x));
    if isempty(x),value=NaN;else,value=median(x);end
end

