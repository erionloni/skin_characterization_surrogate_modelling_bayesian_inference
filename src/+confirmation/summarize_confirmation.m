function [paired,eligibility]=paired_differences( ...
        pairs,parameters,weak,status,names)
    n=height(pairs);eligibility=table();
    eligibility.PairIndex=double(pairs.PairIndex);
    eligibility.MaterialCaseID=double(pairs.MaterialCaseID);
    eligibility.DefaultCertified=false(n,1);
    eligibility.SelectedCertified=false(n,1);
    eligibility.IncludedInPairedSummary=false(n,1);
    eligibility.ContainsFallback=false(n,1);
    eligibility.ExclusionReason=strings(n,1);
    eligibility.DefaultProtocol=string(pairs.DefaultProtocol);
    eligibility.SelectedProtocol=string(pairs.SelectedProtocol);
    weakParts=cell(n,1);parameterParts=cell(n,1);
    weakCount=0;parameterCount=0;
    for i=1:n
        id=double(pairs.MaterialCaseID(i));
        dp=string(pairs.DefaultProtocol(i));sp=string(pairs.SelectedProtocol(i));
        d=status.MaterialCaseID==id&status.Protocol==dp;
        s=status.MaterialCaseID==id&status.Protocol==sp;
        assert(nnz(d)==1&&nnz(s)==1, ...
            'confirmation:summarize_confirmation:PairStatus', ...
            'The cell status needs one row for the protocols %s and %s of material case %d.',dp,sp,id);
        eligibility.DefaultCertified(i)=status.Certified(d);
        eligibility.SelectedCertified(i)=status.Certified(s);
        defaultAvailable=logical(status.Certified(d));
        selectedAvailable=logical(status.Certified(s));
        if ismember('ArtifactLoaded',status.Properties.VariableNames)
            % A cell with a posterior: certified or a healthy fallback.
            defaultAvailable=logical(status.ArtifactLoaded(d));
            selectedAvailable=logical(status.ArtifactLoaded(s));
        end
        eligibility.IncludedInPairedSummary(i)=defaultAvailable&&selectedAvailable;
        eligibility.ContainsFallback(i)=eligibility.IncludedInPairedSummary(i)&& ...
            ~(eligibility.DefaultCertified(i)&&eligibility.SelectedCertified(i));
        if ~defaultAvailable&&~selectedAvailable
            eligibility.ExclusionReason(i)="DEFAULT_AND_SELECTED_UNAVAILABLE";
        elseif ~defaultAvailable
            eligibility.ExclusionReason(i)="DEFAULT_UNAVAILABLE";
        elseif ~selectedAvailable
            eligibility.ExclusionReason(i)="SELECTED_UNAVAILABLE";
        end
        if ~eligibility.IncludedInPairedSummary(i),continue;end
        dw=weak.MaterialCaseID==id&weak.Protocol==dp;
        sw=weak.MaterialCaseID==id&weak.Protocol==sp;
        assert(nnz(dw)==1&&nnz(sw)==1, ...
            'confirmation:summarize_confirmation:WeakPair', ...
            ['The weak-pair summary needs one row for the protocols %s and %s ' ...
             'of material case %d.'],dp,sp,id);
        weakCount=weakCount+1;
        weakParts{weakCount}=paired_weak_row(pairs.PairIndex(i),weak(dw,:),weak(sw,:));
        for j=1:numel(names)
            dr=parameters.MaterialCaseID==id&parameters.Protocol==dp& ...
                parameters.Parameter==string(names{j});
            sr=parameters.MaterialCaseID==id&parameters.Protocol==sp& ...
                parameters.Parameter==string(names{j});
            assert(nnz(dr)==1&&nnz(sr)==1, ...
                'confirmation:summarize_confirmation:ParameterPair', ...
                ['The parameter summary needs one row for the protocols %s and %s ' ...
                 'of material case %d and parameter %s.'],dp,sp,id,string(names{j}));
            parameterCount=parameterCount+1;
            parameterParts{parameterCount}=paired_parameter_row( ...
                pairs.PairIndex(i),parameters(dr,:),parameters(sr,:));
        end
    end
    weakParts=weakParts(1:weakCount);parameterParts=parameterParts(1:parameterCount);
    paired=struct('weakPair',empty_paired_weak(), ...
        'parameters',empty_paired_parameters());
    if ~isempty(weakParts),paired.weakPair=vertcat(weakParts{:});end
    if ~isempty(parameterParts),paired.parameters=vertcat(parameterParts{:});end
    eligibility.ComparisonRole=string(pairs.ComparisonRole);
    for field={'weakPair','parameters'}
        T=paired.(field{1});[found,idx]=ismember(T.PairIndex,pairs.PairIndex);
        assert(all(found),'confirmation:summarize_confirmation:ComparisonJoin','Pair join failed.');
        T.ComparisonRole=string(pairs.ComparisonRole(idx));paired.(field{1})=T;
    end
end

function row=paired_weak_row(pairIndex,d,s)
    metrics={'LambdaMax_Cq','Var_z_m3_e','Var_z_log10_k0','Trace_Cq','LogDet_Cq'};
    row=table(double(pairIndex),double(d.MaterialCaseID), ...
        string(d.Protocol),string(s.Protocol), ...
        'VariableNames',{'PairIndex','MaterialCaseID', ...
        'DefaultProtocol','SelectedProtocol'});
    for i=1:numel(metrics)
        name=metrics{i};row.(['Default_' name])=double(d.(name));
        row.(['Selected_' name])=double(s.(name));
        row.(['Delta_' name])=double(s.(name))-double(d.(name));
    end
    row.DefaultCorrelation=double(d.Correlation_m3_e_log10_k0);
    row.SelectedCorrelation=double(s.Correlation_m3_e_log10_k0);
    row.DeltaCorrelation=row.SelectedCorrelation-row.DefaultCorrelation;
end

function row=paired_parameter_row(pairIndex,d,s)
    metrics={'PosteriorMean','PosteriorMedian','MarginalMode','PosteriorSD', ...
        'PosteriorSDOverPriorSD','ContractionAmount','IntervalWidth50', ...
        'IntervalWidth95','TruthCovered50','TruthCovered95'};
    row=table(double(pairIndex),double(d.MaterialCaseID), ...
        string(d.Parameter),double(d.Truth), ...
        'VariableNames',{'PairIndex','MaterialCaseID','Parameter','Truth'});
    for i=1:numel(metrics)
        name=metrics{i};row.(['Default_' name])=double(d.(name));
        row.(['Selected_' name])=double(s.(name));
        row.(['Delta_' name])=double(s.(name))-double(d.(name));
    end
end

function aggregate=aggregate_paired(paired,eligibility,names,targetNames)
    if ismember('ComparisonRole',eligibility.Properties.VariableNames)
        aggregate=table();roles=unique(eligibility.ComparisonRole,'stable');
        for r=reshape(roles,1,[])
            e=eligibility(eligibility.ComparisonRole==r,:);e.ComparisonRole=[];p=paired;
            for f={'weakPair','parameters'}
                p.(f{1})=p.(f{1})(p.(f{1}).ComparisonRole==r,:);p.(f{1}).ComparisonRole=[];
            end
            a=aggregate_paired(p,e,names,targetNames);a.ComparisonRole=repmat(r,height(a),1);
            aggregate=[aggregate;a]; %#ok<AGROW>
        end
        return
    end
    included=string(eligibility.MaterialCaseID(eligibility.IncludedInPairedSummary));
    parts=cell(21,1);cursor=0;
    weakMetrics={'LambdaMax_Cq','Var_z_m3_e','Var_z_log10_k0', ...
        'Trace_Cq','LogDet_Cq'};
    for i=1:numel(weakMetrics)
        cursor=cursor+1;parts{cursor}=aggregate_metric( ...
            paired.weakPair,weakMetrics{i},"weak_pair",included);
    end
    parameterMetrics={'PosteriorSDOverPriorSD','ContractionAmount', ...
        'IntervalWidth50','IntervalWidth95'};
    for p=1:numel(names)
        rows=paired.parameters.Parameter==string(names{p});
        for i=1:numel(parameterMetrics)
            cursor=cursor+1;parts{cursor}=aggregate_metric( ...
                paired.parameters(rows,:),parameterMetrics{i}, ...
                string(names{p}),included);
        end
    end
    assert(cursor==numel(parts), ...
        'confirmation:summarize_confirmation:AggregateAllocation', ...
        'Internal error: %d of %d aggregate rows were filled.',cursor,numel(parts));
    aggregate=vertcat(parts{:});
    aggregate.TargetPair=repmat(string(strjoin(targetNames,' | ')), ...
        height(aggregate),1);
end

function row=aggregate_metric(T,metric,scope,included)
    defaultName=['Default_' metric];selectedName=['Selected_' metric];
    deltaName=['Delta_' metric];
    if isempty(T)
        d=[];s=[];delta=[];
    else
        d=double(T.(defaultName));s=double(T.(selectedName));
        delta=double(T.(deltaName));
    end
    row=table(string(scope),string(metric),numel(delta), ...
        mean_nan(d),median_nan(d),mean_nan(s),median_nan(s), ...
        mean_nan(delta),median_nan(delta),mean_nan(delta<0), ...
        strjoin(included,';'), ...
        'VariableNames',{'Scope','Metric','IncludedPairCount','DefaultMean', ...
        'DefaultMedian','SelectedMean','SelectedMedian','MeanPairedDifference', ...
        'MedianPairedDifference','FractionSelectedMinusDefaultNegative', ...
        'IncludedMaterialCaseIDs'});
end

function row=load_row(cellRecord,status,A,root)
    sampler="";replicate=NaN;steps=NaN;mechanism="";
    if status.loaded
        [sampler,replicate,steps,mechanism]=provider_axes(A);
    end
    row=[key_table(cellRecord,1),table( ...
        logical(status.loaded)&&logical(status.certified), ...
        string(status.state),string(status.reason),string(status.errorIdentifier), ...
        string(sampler),double(replicate),double(steps),string(mechanism), ...
        'VariableNames',{'Certified','ExecutionStatus', ...
        'FailureReason','ErrorIdentifier','CertifiedSampler', ...
        'CertifiedReplicate','CertifiedStepCount','CertificationMechanism'})];
    row.ArtifactLoaded=logical(status.loaded);
    row.SelectedArtifactPath="";
    row.StructuralHealthPass=false;row.SameLevelVerificationStatus="UNAVAILABLE";
    row.TerminationReason=string(status.reason);
    if status.loaded
        % The provider's posterior file, relative to the campaign folder (the
        % compact tier enters the results: no path of this computer).
        row.SelectedArtifactPath=string(relative_inside(A.paths.posteriorPath,root));
        row.StructuralHealthPass=logical(A.health.pass);
        if status.certified
            row.SameLevelVerificationStatus="PASSED_CERTIFIED";
        else
            row.SameLevelVerificationStatus=string(A.providerEvidence.sameLevelVerificationStatus);
            row.TerminationReason=string(A.providerEvidence.terminationReason);
        end
    end
end

function relative=relative_inside(pathValue,root)
%RELATIVE_INSIDE A path inside ROOT, relative to it with '/'.
    pathValue=utils.absolute_path(pathValue);root=utils.absolute_path(root);
    assert(strncmpi(pathValue,[root filesep],numel(root)+1), ...
        'confirmation:summarize_confirmation:OutsideCampaign', ...
        'The provider file %s is not inside the campaign folder %s.',pathValue,root);
    relative=strrep(pathValue(numel(root)+2:end),'\','/');
end

function [sampler,replicate,steps,mechanism]=provider_axes(A)
    if isfield(A,'providerEvidence')&&~A.providerEvidence.certified
        sampler=A.providerEvidence.sampler;replicate=A.providerEvidence.replicateID;
        steps=A.providerEvidence.stepCount;mechanism='NON_CERTIFIED_HEALTHY_COMPLETED';return
    end
    sampler=char(string(A.certification.provider.sampler));
    replicate=double(A.certification.provider.replicateID);
    steps=double(A.certification.provider.stepCount);
    mechanism=char(string(A.certification.certificationMechanism));
end

