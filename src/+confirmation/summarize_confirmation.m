function rows=joint_geometry_rows(cellRecord,comparison,status)
    scopes={'full_4d','weak_pair'};indices={1:4,[2 3]};
    canonical={'m3_f_RD','m3_e_RD','log10_k0_RD','Thickness_RD'};
    parts=cell(2,1);
    for i=1:2
        available=~isempty(comparison)&&logical(comparison.available);
        if available
            if i==1
                G=comparison.diagnostics.full4D;
            else
                G=comparison.diagnostics.weakPair;
            end
            reason="";step=comparison.acceptedStepCount;
        else
            G=empty_joint_geometry(numel(indices{i}));
            step=NaN;
            if isempty(comparison)
                reason=string(status.reason);
                if strlength(reason)==0
                    reason="certified_posterior_unavailable";
                end
            else
                reason=string(comparison.reason);
            end
        end
        parts{i}=[key_table(cellRecord,1),table(string(scopes{i}), ...
            string(strjoin(canonical(indices{i}),'|')), ...
            logical(available),reason,step, ...
            "independent_uniform_prior_mean_sd_standardized", ...
            G.lambdaMaxReplicate1,G.lambdaMaxReplicate2, ...
            G.lambdaMaxAbsoluteDifference,G.lambdaMaxRelativeDifference, ...
            G.normalizedCovarianceFrobeniusDifference, ...
            G.leadingEigenvectorAbsoluteAlignment, ...
            G.leadingEigenvectorAngleDegrees,G.leadingEigengapReplicate1, ...
            G.leadingEigengapReplicate2,G.traceReplicate1,G.traceReplicate2, ...
            G.logDeterminantReplicate1,G.logDeterminantReplicate2, ...
            G.retainedDrawCountReplicate1,G.retainedDrawCountReplicate2, ...
            false,false, ...
            'VariableNames',{'GeometryScope','ParameterOrder','ReplicatePairAvailable', ...
            'AvailabilityReason','AcceptedStepCount','ParameterCoordinateSystem', ...
            'LambdaMaxReplicate1','LambdaMaxReplicate2', ...
            'LambdaMaxAbsoluteDifference', ...
            'SymmetricLambdaMaxRelativeDifference', ...
            'NormalizedCovarianceFrobeniusDifference', ...
            'LeadingEigenvectorAbsoluteAlignment', ...
            'LeadingEigenvectorAngleDegrees','LeadingEigengapReplicate1', ...
            'LeadingEigengapReplicate2','TraceReplicate1','TraceReplicate2', ...
            'LogDeterminantReplicate1','LogDeterminantReplicate2', ...
            'RetainedDrawCountReplicate1','RetainedDrawCountReplicate2', ...
            'ReplicatesPooled','CertificationChanged'})];
        for replicate=1:2
            C=G.(['covarianceReplicate' num2str(replicate)]);
            for rowIndex=1:4
                for columnIndex=1:4
                    name=sprintf('CovarianceReplicate%d_%d%d', ...
                        replicate,rowIndex,columnIndex);
                    if rowIndex<=size(C,1)&&columnIndex<=size(C,2)
                        parts{i}.(name)=C(rowIndex,columnIndex);
                    else
                        parts{i}.(name)=NaN;
                    end
                end
            end
        end
    end
    rows=vertcat(parts{:});
end

