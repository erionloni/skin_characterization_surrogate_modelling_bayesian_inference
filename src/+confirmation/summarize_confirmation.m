function [row,matrixRows]=weak_row(cellRecord,A,names,bounds,target,status,policy)
    % The eigensystem thresholds of the settings (A.7).
    E=recovery.posterior_covariance_eigensystem( ...
        A.drawsPhysical,bounds,'ParameterNames',names, ...
        'NearDegenerateGap',policy.nearDegenerateGapThreshold, ...
        'NegativeEigenvalueTolerance',policy.negativeEigenvalueTolerance, ...
        'SymmetryTolerance',policy.symmetryTolerance);
    assert(E.eigensystem.valid, ...
        'confirmation:summarize_confirmation:PosteriorCovariance', ...
        'A certified posterior has no valid covariance eigensystem.');
    C=E.covarianceStandardizedDirect;
    Cq=(C(target,target)+C(target,target).')/2;
    [vectors,values]=eig(Cq);[lambda,order]=sort(diag(values),'ascend');
    vectors=vectors(:,order);
    gapEpsilon=eps(max(1,max(abs(lambda))));
    targetRelativeGap=(lambda(2)-lambda(1))/max(lambda(2),gapEpsilon);
    targetGapThreshold=double(E.eigensystem.nearDegenerateGapThreshold);
    targetNearDegenerate=targetRelativeGap<=targetGapThreshold;
    [weakVector,flipped,pivot]=recovery.align_vector_sign(vectors(:,2));
    correlation=Cq(1,2)/sqrt(Cq(1,1)*Cq(2,2));
    [sampler,replicate,steps,mechanism]=provider_axes(A);
    row=[key_table(cellRecord,1),table( ...
        Cq(1,1),Cq(1,2),Cq(2,2),lambda(2),trace(Cq), ...
        design_study.posterior_covariance_logdet(Cq,E.standardizedDraws(:,target)),correlation,lambda(1),lambda(2), ...
        targetRelativeGap,targetGapThreshold,logical(targetNearDegenerate), ...
        weakVector(1),weakVector(2),logical(flipped),double(pivot), ...
        E.directUnitBoxConsistencyMaximumAbsoluteError, ...
        string(sampler),replicate,steps,string(mechanism), ...
        true,string(status.state),"", ...
        'VariableNames',weak_columns())];
    matrixRows=full_covariance_rows( ...
        cellRecord,E.covarianceStandardizedDirect,names,target,status,A);
end

function [row,matrixRows]=missing_weak_row(cellRecord,names,target,status)
