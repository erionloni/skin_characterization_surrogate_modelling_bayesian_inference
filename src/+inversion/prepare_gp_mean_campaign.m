function preparation = prepare_gp_mean_campaign(cfg)
%PREPARE_GP_MEAN_CAMPAIGN Prepare the GP-mean inversion campaign (grid, seeds, tasks), once.
%   PREPARATION = inversion.prepare_gp_mean_campaign(CFG) prepares the
%   GP-mean inversion of the settings (A.13): one cell per case of
%   CFG.gpMeanInversion.caseIDs in the scenario gp_mean_det, design all_six
%   (inversion.build_gp_mean_inversion_grid), each bound to its case's truth
%   and held-out COMSOL observation (data.inversion_cases: the observation
%   vectors of measurement_plus_gp and gp_only), the seed of every request
%   (inversion.gp_mean_seed_schedule: checked against every seed used so far,
%   with the shipped results of CFG.native.results), and writes below
%   CFG.paths.gpMeanInversion, as the canonical campaign does below its
%   folder (inversion.gp_mean_campaign_config, inversion.grid_campaign_support):
%   the grid (grid.csv), the task table (cell_task_table.csv: one task per
%   cell, for running cells separately), the seed schedule, the MCMC policy
%   record, the preparation (campaign_preparation.mat) and its summary
%   (campaign_preparation.json, with the demonstration chain lengths of a
%   demonstration campaign, which every later call keeps).
%   A campaign is prepared once: an existing preparation is returned
%   unchanged; a call with other cases is refused.
%   This function loads no GP and runs no sampler.
%   Side effects: writes the prepared campaign when it is new.
%   Computation: seconds.

    assert(isstruct(cfg)&&isscalar(cfg)&&strcmp(cfg.dataMode,'real'), ...
        'inversion:prepare_gp_mean_campaign:Route', ...
        'The GP-mean inversion is defined for the fixed route only.');
    if isfield(cfg,'parallelWorkers')&&double(cfg.parallelWorkers)>0
        error('inversion:prepare_gp_mean_campaign:ParallelNotEnabled', ...
            ['Run the GP-mean inversion with ''ParallelWorkers'' 0: cells run in parallel as ' ...
             'separate MATLAB processes (''GPMeanCells''), not inside one.']);
    end
    assert(isfile(cfg.files.gp)&&isfile(cfg.files.dataset), ...
        'inversion:prepare_gp_mean_campaign:Inputs', ...
        'The GP-mean inversion needs the dataset (%s) and the GP (%s).', ...
        cfg.files.dataset,cfg.files.gp);
    assert(isfield(cfg.inversion,'cohortResolved')&&logical(cfg.inversion.cohortResolved), ...
        'inversion:prepare_gp_mean_campaign:InversionCohortUnresolved', ...
        'The inversion cases did not resolve from the dataset %s.',cfg.files.dataset);
    campaignCfg=inversion.gp_mean_campaign_config(cfg);
    paths=inversion.grid_campaign_support('preparation_paths',campaignCfg);
    caseIDs=reshape(double(cfg.gpMeanInversion.caseIDs),1,[]);
    if isfile(paths.preparationMAT)
        preparation=inversion.grid_campaign_support('load_preparation',campaignCfg);
        assert(isequal(reshape(double(preparation.inversionCaseIDs),1,[]),caseIDs), ...
            'inversion:prepare_gp_mean_campaign:CasesDiffer', ...
            ['The GP-mean campaign in %s holds the cases %s; this call has %s. Use the same ' ...
             'cases, or a new run folder for another campaign.'],paths.stageRoot, ...
            mat2str(preparation.inversionCaseIDs),mat2str(caseIDs));
        return
    end

    P=parameters.parameter_space(cfg);
    inversionCases=data.inversion_cases(cfg,P);
    ids=reshape(double([inversionCases.case_id]),1,[]);
    [present,where]=ismember(caseIDs,ids);
    assert(all(present)&&~isempty(caseIDs), ...
        'inversion:prepare_gp_mean_campaign:Cases', ...
        'The GP-mean cases %s must be cases of the inversion (%s).',mat2str(caseIDs),mat2str(ids));
    cases=inversionCases(where);
    grid=inversion.build_gp_mean_inversion_grid(cfg,cases);
    cellRecords=inversion.grid_campaign_support('attach_cases',grid,cases);
    assert(isfield(cfg,'native')&&isfield(cfg.native,'results'), ...
        'inversion:prepare_gp_mean_campaign:Results', ...
        'The shipped results folder (cfg.native.results) is needed for the seed check.');
    [seedRecords,seedTable]=inversion.gp_mean_seed_schedule(cfg,grid,inversionCases, ...
        cfg.native.results);
    demonstrationSteps=[];
    if isfield(cfg.mcmc,'demonstrationSteps')
        demonstrationSteps=reshape(double(cfg.mcmc.demonstrationSteps),1,[]);
    end
    preparation=struct( ...
        'schemaVersion','gp_mean_campaign_preparation_v1', ...
        'route','real','grid',grid,'cellRecords',cellRecords, ...
        'inversionCohortSelectionMode',char(string(cfg.inversion.cohortSelectionMode)), ...
        'inversionCaseIDs',caseIDs, ...
        'levels',reshape(double(cfg.mcmc.levels),1,[]), ...
        'demonstrationSteps',demonstrationSteps, ...
        'policy',inversion.grid_campaign_support('policy_summary',campaignCfg,grid), ...
        'seedRecords',seedRecords, ...
        'seedScheduleTable',seedTable, ...
        'taskTable',inversion.grid_campaign_support('task_table',campaignCfg,cellRecords), ...
        'gridTable',inversion.grid_campaign_support('grid_table',grid), ...
        'paths',paths);
    inversion.grid_campaign_support('publish_preparation',preparation);
end
