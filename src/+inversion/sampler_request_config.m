function [requestCfg,settings] = sampler_request_config(cfg,sampler,stepCount)
%SAMPLER_REQUEST_CONFIG Apply one predeclared direct-MCMC sampler policy.
%   [REQUESTCFG, SETTINGS] = inversion.sampler_request_config(CFG, SAMPLER,
%   STEPCOUNT) returns the configuration of one request of SAMPLER ('AIES' or
%   'AM') at STEPCOUNT steps (a configured level) and the record of its
%   sampler settings.
%   Settings are copied from cfg.mcmc.aies or
%   cfg.mcmc.adaptiveMetropolis. No scientific defaults are defined here.
%   For demonstrations only, cfg.mcmc.demonstrationSteps (one length per
%   level, each shorter than its level) shortens the chain the sampler runs;
%   the settings record it (demonstrationStepCount). Absent, the request is
%   exactly the configured level.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'mcmc'), ...
        'inversion:sampler_request_config:Configuration', ...
        'A scalar project configuration with cfg.mcmc is required.');
    required={'levels','aies','adaptiveMetropolis','burn_in','thinning', ...
        'continuationSemantics'};
    assert(all(isfield(cfg.mcmc,required)), ...
        'inversion:sampler_request_config:Configuration', ...
        'The centralized direct-MCMC configuration is incomplete.');
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    assert(isequal(levels,[2000 5000])&&ismember(stepCount,levels), ...
        'inversion:sampler_request_config:Level', ...
        'Requested total length must be one of cfg.mcmc.levels.');
    sampler=upper(strtrim(char(string(sampler))));
    if strcmp(sampler,'ADAPTIVE_METROPOLIS'),sampler='AM';end
    switch sampler
        case 'AIES'
            policy=cfg.mcmc.aies;
        case 'AM'
            policy=cfg.mcmc.adaptiveMetropolis;
        otherwise
            error('inversion:sampler_request_config:Sampler', ...
                'Only AIES and Adaptive Metropolis (AM) are supported.');
    end
    requiredPolicy={'sampler','n_chains','samplerOptions','initialization'};
    assert(isstruct(policy)&&isscalar(policy)&&all(isfield(policy,requiredPolicy)), ...
        'inversion:sampler_request_config:Policy', ...
        'The configured sampler policy is incomplete.');
    assert(strcmpi(char(string(policy.sampler)),sampler), ...
        'inversion:sampler_request_config:PolicySampler', ...
        'Configured sampler policy does not match the requested sampler.');
    assert(isnumeric(policy.n_chains)&&isscalar(policy.n_chains)&& ...
        isfinite(policy.n_chains)&&policy.n_chains==fix(policy.n_chains)&& ...
        policy.n_chains>=2, ...
        'inversion:sampler_request_config:StateCount', ...
        'The number of walkers/chains must be an integer of at least two.');
    effective=utils.effective_sampler_settings(policy);

    requestCfg=cfg;
    requestCfg.mcmc.sampler=sampler;
    requestCfg.mcmc.samplerOptions=policy.samplerOptions;
    requestCfg.mcmc.n_chains=double(policy.n_chains);
    requestCfg.mcmc.n_steps=double(stepCount);
    requestCfg.mcmc.initialization=char(string(policy.initialization));
    semantics=utils.sampler_semantics(sampler);
    settings=struct( ...
        'schemaVersion','direct_mcmc_sampler_request_v1', ...
        'sampler',sampler, ...
        'stepCount',double(stepCount), ...
        'nChainsOrWalkers',double(policy.n_chains), ...
        'initialization',char(string(policy.initialization)), ...
        'samplerOptions',effective, ...
        'burnIn',double(cfg.mcmc.burn_in), ...
        'thinning',double(cfg.mcmc.thinning), ...
        'uqlabAnalysisVisibility','private_not_session_registered', ...
        'stateSemantics',semantics.stateSemantics, ...
        'thirdDimensionSemantics',semantics.thirdDimension, ...
        'walkersTreatedAsIndependentChains',false, ...
        'continuationSemantics',char(string( ...
            cfg.mcmc.continuationSemantics)), ...
        'parentSamplerStateLoaded',false, ...
        'samplesAppendedAcrossLevels',false, ...
        'samplesPooledAcrossReplicatesOrSamplers',false);
    steps=demonstration_steps(cfg,stepCount);
    if ~isempty(steps)
        % Demonstration only (the small example and the inversion smoke):
        % the request keeps its level, seed, file names
        % and certification policy; the sampler runs this shorter chain.
        % Thesis configurations never set cfg.mcmc.demonstrationSteps.
        requestCfg.mcmc.n_steps=steps;
        settings.demonstrationStepCount=steps;
        settings.demonstrationNote=['chain shortened for a demonstration; ' ...
            'not thesis evidence'];
    end
end

function steps=demonstration_steps(cfg,stepCount)
%DEMONSTRATION_STEPS Chain length of a demonstration request at level STEPCOUNT.
%   [] unless cfg.mcmc.demonstrationSteps gives one shorter length per level.
    steps=[];
    if ~isfield(cfg.mcmc,'demonstrationSteps')||isempty(cfg.mcmc.demonstrationSteps)
        return;
    end
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    lengths=reshape(double(cfg.mcmc.demonstrationSteps),1,[]);
    assert(numel(lengths)==numel(levels)&&all(isfinite(lengths))&& ...
        all(lengths==fix(lengths))&&all(lengths>=2)&&all(lengths<levels), ...
        'inversion:sampler_request_config:DemonstrationSteps', ...
        ['cfg.mcmc.demonstrationSteps must give one chain length per ' ...
         'configured level, each shorter than its level.']);
    steps=lengths(levels==stepCount);
end
