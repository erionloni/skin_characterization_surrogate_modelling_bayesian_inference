function decision = direct_mcmc_decision(cfg,stepCount,evidence)
%DIRECT_MCMC_DECISION Deterministic AIES replicate-pair decision tree.
%   Normal production certification depends only on two independent AIES
%   analyses at the same configured total-length level. The pair evaluator
%   distinguishes hard sampler pathology/distribution-reproducibility gates
%   from supporting Monte-Carlo-efficiency warnings. Optional Adaptive
%   Metropolis evidence may be carried in EVIDENCE, but it cannot certify,
%   veto, rank, or replace the predeclared AIES replicate-1 posterior.
%
%   DECISION = inversion.direct_mcmc_decision(CFG, STEPCOUNT, EVIDENCE)
%   decides, from the evidence of the requests at the level STEPCOUNT
%   (EVIDENCE: the executed requests, their health and the AIES replicate
%   pair's reliability), whether the cell is certified, escalates to the
%   next level or is unresolved, with the provider (AIES replicate 1), the
%   reason and the evidence. Draws are never pooled across samplers,
%   replicates or levels.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'mcmc')&& ...
        isfield(cfg.mcmc,'productionSampler')&& ...
        strcmpi(char(string(cfg.mcmc.productionSampler)),'AIES'), ...
        'inversion:direct_mcmc_decision:ProductionSampler', ...
        'The predeclared production sampler must be AIES.');
    assert(isstruct(evidence)&&isscalar(evidence)&& ...
        isfield(evidence,'aiesPairReliability'), ...
        'inversion:direct_mcmc_decision:Evidence', ...
        'A same-level AIES replicate-pair record is required.');
    pair=evidence.aiesPairReliability;
    validate_pair(pair);

    pairPass=validated_hard_pair_pass(pair);
    if pairPass
        decision=certify(stepCount);
    else
        decision=escalate(cfg,stepCount,pair);
    end

    decision.productionSamplerPolicy= ...
        'AIES_replicate_1_primary_replicate_2_reproducibility_v2';
    decision.adaptiveMetropolisRole= ...
        'optional_secondary_validation_never_certification';
    decision.warningDiagnosticsAffectCertification=false;
    decision.samplesPooledAcrossSamplers=false;
    decision.samplesPooledAcrossReplicates=false;
    decision.samplesPooledAcrossLevels=false;
    decision.evidence=evidence;
end

function decision=escalate(cfg,steps,pair)
    policy=inversion.mcmc_escalation_policy( ...
        cfg,steps,{'AIES'},[1 2]);
    if policy.maximumReached
        decision=base_decision(steps,'unresolved');
        decision.action='reject_or_report_unresolved';
        decision.reason=sprintf( ...
            '%s; hard AIES pair criteria still failed at maximum %dk level', ...
            pair_reason(pair),steps/1000);
        decision.terminalStatus=sprintf('UNRESOLVED_AFTER_%dK',steps/1000);
        decision.requests=struct([]);
    else
        decision=base_decision(steps,'escalation_required');
        decision.action='run_fresh_total_length_at_next_level';
        decision.reason=pair_reason(pair);
        decision.requests=policy.requests;
        decision.nextStepCount=policy.nextSteps;
    end
    decision.escalationPolicy=policy;
end

function decision=certify(steps)
    decision=base_decision(steps,'certified');
    decision.action='certify_without_escalation';
    decision.reason=[ ...
        'two independent AIES analyses passed all hard structural and ' ...
        'posterior-distribution reproducibility criteria'];
    decision.certified=true;
    decision.downstreamUsePermitted=true;
    decision.certificationMechanism='CERTIFIED_AIES_REPLICATE_AGREEMENT';
    decision.provider=struct( ...
        'sampler','AIES', ...
        'replicateID',1, ...
        'stepCount',double(steps), ...
        'selectionBasis', ...
            'predeclared_AIES_replicate_1_after_pair_reproducibility', ...
        'selectionUsesDiagnosticRanking',false, ...
        'samplesPooled',false);
end

function decision=base_decision(steps,status)
    decision=struct( ...
        'schemaVersion','direct_mcmc_aies_first_reliability_decision_v2', ...
        'caseCode','AIES_PAIR', ...
        'stepCount',double(steps), ...
        'status',status, ...
        'terminalStatus','', ...
        'action','', ...
        'reason','', ...
        'certified',false, ...
        'downstreamUsePermitted',false, ...
        'certificationMechanism','NOT_CERTIFIED', ...
        'provider',struct([]), ...
        'requests',struct([]), ...
        'nextStepCount',NaN, ...
        'escalationPolicy',struct([]));
end

function validate_pair(value)
    assert(isstruct(value)&&isscalar(value)&& ...
        all(isfield(value,{'sampler','reliable'}))&& ...
        strcmpi(char(string(value.sampler)),'AIES')&& ...
        scalar_truth(value.reliable), ...
        'inversion:direct_mcmc_decision:Pair', ...
        'Invalid AIES same-level replicate-pair reliability record.');
end

function pass=validated_hard_pair_pass(pair)
    required={'structuralHealthPass','independenceVerified', ...
        'hardCriteriaPass','posteriorReproducibility'};
    if ~all(isfield(pair,required))
        assert(~logical(pair.reliable), ...
            'inversion:direct_mcmc_decision:ReliablePairContract', ...
            ['An AIES pair cannot be reliable without bound structural, ' ...
             'independence, and posterior-reproducibility evidence.']);
        pass=false;
        return;
    end
    posterior=pair.posteriorReproducibility;
    posteriorRequired={'hardDistributionAgreementPass','wassersteinPass', ...
        'q025Pass','q975Pass'};
    assert(isstruct(posterior)&&isscalar(posterior)&& ...
        all(isfield(posterior,posteriorRequired))&& ...
        scalar_truth(pair.structuralHealthPass)&& ...
        scalar_truth(pair.independenceVerified)&& ...
        scalar_truth(pair.hardCriteriaPass)&& ...
        scalar_truth(posterior.hardDistributionAgreementPass)&& ...
        boolean_vector(posterior.wassersteinPass)&& ...
        boolean_vector(posterior.q025Pass)&& ...
        boolean_vector(posterior.q975Pass), ...
        'inversion:direct_mcmc_decision:ReliablePairContract', ...
        'The AIES pair hard-evidence contract is incomplete.');
    distributionPass=logical(posterior.hardDistributionAgreementPass)&& ...
        all(logical(posterior.wassersteinPass(:)))&& ...
        all(logical(posterior.q025Pass(:)))&& ...
        all(logical(posterior.q975Pass(:)));
    pass=logical(pair.structuralHealthPass)&& ...
        logical(pair.independenceVerified)&& ...
        logical(pair.hardCriteriaPass)&&distributionPass;
    assert(logical(pair.reliable)==pass, ...
        'inversion:direct_mcmc_decision:ReliablePairContract', ...
        'Pair reliability disagrees with its bound hard evidence.');
end

function tf=scalar_truth(value)
    tf=(islogical(value)||isnumeric(value))&&isscalar(value)&& ...
        isfinite(double(value))&&ismember(double(value),[0 1]);
end

function tf=boolean_vector(value)
    tf=(islogical(value)||isnumeric(value))&&~isempty(value)&& ...
        all(isfinite(double(value(:))))&& ...
        all(ismember(double(value(:)),[0 1]));
end

function value=pair_reason(pair)
    value='AIES replicate pair failed one or more hard criteria';
    if isfield(pair,'reasons')&&~isempty(pair.reasons)
        reasons=cellstr(string(pair.reasons));
        value=strjoin(reasons,'; ');
    elseif isfield(pair,'status')&&strlength(string(pair.status))>0
        value=sprintf('AIES pair status: %s',char(string(pair.status)));
    end
end
