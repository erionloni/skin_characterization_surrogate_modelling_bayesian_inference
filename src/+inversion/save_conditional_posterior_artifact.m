function [posteriorArtifact,receipt] = save_conditional_posterior_artifact( ...
        cfg,cellRecord,condition,adapter,execution)
%SAVE_CONDITIONAL_POSTERIOR_ARTIFACT Persist one reduced-space AIES request.
%   [POSTERIORARTIFACT, RECEIPT] = inversion.save_conditional_posterior_artifact(
%   CFG, CELLRECORD, CONDITION, ADAPTER, EXECUTION) saves the request EXECUTION
%   (inversion.run_conditional_request) of the conditional cell CELLRECORD
%   under CONDITION and its parameter ADAPTER, and returns the saved posterior
%   artifact and the request's metadata record with its file paths.
%   Reduced sampler states remain reduced. Canonical coordinate rows restore
%   fixed truth columns for alignment/reconstruction only; parameter roles
%   prevent those constants from being misread as inferred posterior draws.
%   No samples are pooled across replicates or levels.
%   Writes, below the conditional cell folder, the cell's truth and
%   observation (once per cell), the checkpoint, the posterior, its summary
%   and diagnostics tables and the metadata JSON, written last: a request
%   with all its files is complete.
%   Side effects: writes the request's files below the conditional cell
%   folder.

    requiredExecution={'request','sampler','replicateID', ...
        'stepCount','seed','sampleArray','drawsFree','drawsCanonical','health'};
    assert(isstruct(execution)&&isscalar(execution)&& ...
        all(isfield(execution,requiredExecution))&& ...
        ismember(upper(char(string(execution.sampler))),{'AIES','AM'}), ...
        'inversion:save_conditional_posterior_artifact:Execution', ...
        'A completed conditional AIES or optional AM execution is required.');
    condition=inversion.conditional_inversion_conditions(cfg,condition.tag);
    paths=inversion.conditional_posterior_artifact_paths(cfg,cellRecord, ...
        execution.sampler,execution.replicateID,execution.stepCount);
    truth=reshape(double(pick(cellRecord,{'truth','thetaTrue'})),1,[]);
    observation=reshape(double(pick(cellRecord, ...
        {'heldout_response','heldoutResponse','observation'})),1,[]);
    assert(numel(truth)==4&&numel(observation)==6&& ...
        all(isfinite([truth observation])), ...
        'inversion:save_conditional_posterior_artifact:CaseData', ...
        'Canonical four-parameter truth and six-output observation are required.');
    free=condition.freeParameterIndices;fixed=condition.fixedParameterIndices;
    drawsFree=double(execution.drawsFree);
    drawsCanonical=double(execution.drawsCanonical);
    sampleArray=double(execution.sampleArray);
    assert(~isempty(drawsFree)&&size(drawsFree,2)==numel(free)&& ...
        ~isempty(sampleArray)&&size(sampleArray,2)==numel(free)&& ...
        size(drawsCanonical,1)==size(drawsFree,1)&& ...
        size(drawsCanonical,2)==4&&all(isfinite(drawsFree),'all')&& ...
        all(isfinite(sampleArray),'all')&&all(isfinite(drawsCanonical),'all')&& ...
        isequaln(drawsFree,reshape(permute(sampleArray,[1 3 2]),[],numel(free)))&& ...
        max(abs(drawsCanonical(:,free)-drawsFree),[],'all')<=1e-12&& ...
        (isempty(fixed)||max(abs(drawsCanonical(:,fixed)-truth(fixed)), ...
        [],'all')<=1e-12), ...
        'inversion:save_conditional_posterior_artifact:DrawBinding', ...
        'Reduced states and reconstructed canonical draws are inconsistent.');
    bounds=double(cfg.paramBounds);freeBounds=bounds(free,:);
    assert(all(drawsFree>=freeBounds(:,1).'&drawsFree<=freeBounds(:,2).','all'), ...
        'inversion:save_conditional_posterior_artifact:Bounds', ...
        'Conditional draws leave the configured free-parameter prior bounds.');
    parameterNames=cellstr(string(cfg.paramNames(:))).';
    freeParameterNames=parameterNames(free);
    parameterRoles=repmat({'FREE'},1,4);
    parameterRoles(fixed)=repmat({'FIXED_TO_TRUTH'},1,numel(fixed));
    resultState=execution_result_state(execution);
    checkpointArtifact=struct( ...
        'schemaVersion','conditional_mcmc_completed_checkpoint_v1', ...
        'request',execution.request,'condition',condition,'adapter',adapter, ...
        'parameterNames',{parameterNames},'parameterRoles',{parameterRoles}, ...
        'freeParameterNames',{freeParameterNames}, ...
        'bounds',bounds,'freeBounds',freeBounds,'truth',truth, ...
        'observation',observation,'retainedDrawsFree',drawsFree, ...
        'retainedCanonicalCoordinates',drawsCanonical, ...
        'retainedSampleArrayFree',sampleArray,'health',execution.health, ...
        'resultState',resultState,'terminalState','complete', ...
        'resumeSemantics','reuse_complete_request_only', ...
        'continuationSemantics',char(string(cfg.mcmc.continuationSemantics)), ...
        'samplesPooled',false);
    summary=posterior_summary(drawsCanonical,truth,bounds,parameterNames,free,fixed);
    posteriorArtifact=struct( ...
        'schemaVersion','conditional_mcmc_posterior_samples_v1', ...
        'request',execution.request,'condition',condition,'adapter',adapter, ...
        'parameterNames',{parameterNames},'parameterRoles',{parameterRoles}, ...
        'freeParameterNames',{freeParameterNames}, ...
        'bounds',bounds,'freeBounds',freeBounds, ...
        'freeParameterIndices',free,'fixedParameterIndices',fixed, ...
        'drawsFree',drawsFree, ...
        'drawsCanonicalCoordinates',drawsCanonical, ...
        'truth',truth,'observation',observation,'summary',summary, ...
        'health',execution.health,'samplesPooled',false, ...
        'providerStatus','single_analysis_pending_cell_certification');
    truthArtifact=struct( ...
        'schemaVersion','conditional_mcmc_truth_v1','cellID',paths.cellID, ...
        'caseID',paths.caseID,'conditionTag',condition.tag,'truth',truth, ...
        'parameterNames',{parameterNames},'bounds',bounds);
    observationArtifact=struct( ...
        'schemaVersion','conditional_mcmc_observation_v1', ...
        'cellID',paths.cellID,'caseID',paths.caseID, ...
        'scenario',paths.scenario,'design','all_six', ...
        'conditionTag',condition.tag,'observation',observation);
    publish_mat(paths.truthPath,'truthArtifact',truthArtifact,true);
    publish_mat(paths.observationPath,'observationArtifact',observationArtifact,true);
    publish_mat(paths.checkpointPath,'checkpointArtifact',checkpointArtifact,false);
    publish_mat(paths.posteriorPath,'posteriorArtifact',posteriorArtifact,false);
    utils.atomic_write_table(paths.summaryPath,summary);
    utils.atomic_write_table(paths.diagnosticsPath, ...
        diagnostic_table(execution.health,freeParameterNames));
    metadata=struct( ...
        'schemaVersion','conditional_mcmc_sampler_artifact_metadata_v2', ...
        'request',execution.request, ...
        'retainedDrawCount',size(drawsFree,1), ...
        'retainedIterationCount',size(sampleArray,1), ...
        'samplerStateCount',size(sampleArray,3), ...
        'freeParameterCount',numel(free), ...
        'parameterRoles',{parameterRoles}, ...
        'canonicalCoordinateRowsSavedForReconstruction',true, ...
        'fixedCoordinatesRestoredFromCaseTruth',true, ...
        'completeRequestReusable',true,'midChainResumeAvailable',false);
    write_json(paths.metadataPath,metadata);
    receipt=metadata;receipt.paths=paths;
end

function state=execution_result_state(execution)
    state=struct();
    if isfield(execution,'result')&&isstruct(execution.result)
        names={'logLikelihoodTrace','rawSample','initialSamplerStates', ...
            'terminalSamplerStates','acceptancePerSamplerState','acceptance', ...
            'sampleSemantics','outputs','observationTransform'};
        for i=1:numel(names)
            if isfield(execution.result,names{i})
                state.(names{i})=execution.result.(names{i});
            end
        end
    end
    if isfield(execution,'logLikelihoodTrace')
        state.logLikelihoodTrace=execution.logLikelihoodTrace;
    end
    assert(isfield(state,'logLikelihoodTrace')&& ...
        isnumeric(state.logLikelihoodTrace)&&~isempty(state.logLikelihoodTrace)&& ...
        all(isfinite(state.logLikelihoodTrace),'all'), ...
        'inversion:save_conditional_posterior_artifact:LogLikelihood', ...
        'Completed conditional request lacks a finite likelihood trace.');
end

function T=posterior_summary(draws,truth,bounds,names,free,fixed)
    n=4;priorWidth=bounds(:,2)-bounds(:,1);priorSD=priorWidth/sqrt(12);
    [meanValue,medianValue,sdValue,normSD,sdOverPriorRange, ...
        contraction,q025,q975,covered, ...
        meanError,medianError]=deal(nan(n,1));
    for j=free
        x=draws(:,j);meanValue(j)=mean(x);medianValue(j)=median(x);
        sdValue(j)=std(x,0);normSD(j)=sdValue(j)/priorSD(j);
        sdOverPriorRange(j)=sdValue(j)/priorWidth(j);
        contraction(j)=1-normSD(j);q=quantile(x,[0.025 0.975]);
        q025(j)=q(1);q975(j)=q(2);
        covered(j)=double(truth(j)>=q(1)&&truth(j)<=q(2));
        meanError(j)=abs(meanValue(j)-truth(j))/priorWidth(j);
        medianError(j)=abs(medianValue(j)-truth(j))/priorWidth(j);
    end
    role=repmat("FREE",n,1);
    role(fixed)="FIXED_TO_TRUTH";
    T=table(string(names(:)),role,truth(:),meanValue,medianValue,sdValue, ...
        normSD,sdOverPriorRange,contraction,q025,q975,covered, ...
        meanError,medianError, ...
        'VariableNames',{'Parameter','ParameterRole','Truth','Mean','Median', ...
        'SD','NormalizedPosteriorSD','SDOverPriorRange', ...
        'ContractionAmount','Q025','Q975', ...
        'Covered95','PosteriorMeanNormalizedRecoveryError', ...
        'PosteriorMedianNormalizedRecoveryError'});
end

function T=diagnostic_table(health,names)
    n=numel(names);
    T=table(string(names(:)),column(health,'rankSplitRhat',n), ...
        column(health,'bulkESS',n),column(health,'tailESS',n), ...
        column(health,'relativeSdMCSE',n), ...
        repmat(logical(health.pass),n,1), ...
        'VariableNames',{'Parameter','RankSplitRhat','BulkESS','TailESS', ...
        'RelativeSdMCSE','SingleAnalysisHealthPass'});
end

function value=column(source,name,n)
    if isfield(source,name)&&numel(source.(name))==n
        value=reshape(double(source.(name)),[],1);
    else
        value=nan(n,1);
    end
end

function publish_mat(pathValue,name,value,once)
%PUBLISH_MAT Write one artifact MAT. The truth and observation of a cell are
%   written by its first request (ONCE); a request's own files are replaced.
    if once&&isfile(pathValue),return;end
    payload=struct();payload.(name)=value;
    utils.atomic_save_struct(pathValue,payload,'-v7');
end

function write_json(pathValue,value)
    try
        text=jsonencode(value,'PrettyPrint',true);
    catch
        text=jsonencode(value);
    end
    utils.atomic_write_text(pathValue,[text newline]);
end

function value=pick(source,names)
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
    error('inversion:save_conditional_posterior_artifact:CellField', ...
        'Cell record lacks one of: %s.',strjoin(names,', '));
end
