function varargout = conditional_campaign_contract(action,varargin)
%CONDITIONAL_CAMPAIGN_CONTRACT Shared parts of the conditional inversion campaign.
%   Used by inversion.prepare_conditional_campaign, run_conditional_cell and
%   finalize_conditional_campaign: the files of the campaign, the cell and
%   task tables, the written preparation, the outcome of a cell and the
%   campaign records. It has no sampler, likelihood, GP or
%   reliability-controller call.
%
%   Actions (inversion.conditional_campaign_contract(ACTION, ...)):
%     'paths'             CFG -> the campaign's files
%     'attach_case'       CELL, CASES -> the cell with its truth and observation
%     'canonical_record'  CELL -> the record of its canonical all_six cell
%     'seed_map'          SCHEDULE -> seed -> the request it seeds
%     'grid_table', 'seed_table', 'task_table', 'action_table', 'barrier_table'
%                         the campaign's tables (the action table: every cell
%                         of the grid with its action, run, reuse or skip)
%     'load_preparation'  CFG -> the prepared campaign
%     'baseline_for_task' PREPARATION, TASK -> its canonical baseline and status
%     'cell_outcome_path' CFG, CELL -> the cell's outcome record
%     'cell_entry'        CFG, CELL, BASELINE -> its row of the certification
%                         index (empty when it has no terminal decision)
%     'write_cell_outcome'  CFG, CELL, ENTRY -> writes the outcome record
%     'entry_table'       ENTRIES -> the certification index
%     'build_campaign'    CFG, PREPARATION, ENTRIES, SUMMARY -> the campaign record
%     'status_payload'    CAMPAIGN, FILES -> the campaign status
%     'run_relative'      PATH, ROOT -> PATH relative to ROOT with '/'
%
%   Side effects: 'write_cell_outcome' writes the cell's outcome record; the
%   other actions only read.

    action=lower(strtrim(char(string(action))));
    switch action
        case 'paths'
            varargout{1}=output_files(varargin{1});
        case 'attach_case'
            varargout{1}=attach_case(varargin{1},varargin{2});
        case 'canonical_record'
            varargout{1}=canonical_record(varargin{1});
        case 'seed_map'
            varargout{1}=seed_map(varargin{1});
        case 'grid_table'
            varargout{1}=grid_table(varargin{1});
        case 'seed_table'
            varargout{1}=seed_table(varargin{1});
        case 'task_table'
            varargout{1}=task_table(varargin{1});
        case 'action_table'
            varargout{1}=action_table(varargin{1});
        case 'barrier_table'
            varargout{1}=barrier_table(varargin{1});
        case 'load_preparation'
            varargout{1}=load_preparation(varargin{1});
        case 'baseline_for_task'
            varargout{1}=baseline_for_task(varargin{1},varargin{2});
        case 'cell_outcome_path'
            varargout{1}=cell_outcome_path(varargin{1},varargin{2});
        case 'cell_entry'
            varargout{1}=cell_entry(varargin{:});
        case 'write_cell_outcome'
            write_cell_outcome(varargin{:});
        case 'entry_table'
            varargout{1}=entry_table(varargin{1});
        case 'build_campaign'
            varargout{1}=build_campaign(varargin{:});
        case 'status_payload'
            varargout{1}=status_payload(varargin{1},varargin{2});
        case 'run_relative'
            varargout{1}=run_relative(varargin{1},varargin{2});
        otherwise
            error('inversion:conditional_campaign_contract:Action', ...
                'Unsupported conditional campaign action: %s.',action);
    end
end

function files=output_files(cfg)
    root=cfg.paths.conditionalInversion;
    orchestration=fullfile(root,'orchestration');
    files=struct('runRoot',cfg.paths.runRoot,'root',root, ...
        'orchestration',orchestration, ...
        'grid',fallback(cfg,'conditionalInversionGrid', ...
        fullfile(root,'conditional_grid.csv')), ...
        'seedSchedule',fullfile(root,'certification', ...
        'conditional_seed_schedule.csv'), ...
        'certificationIndex',fallback(cfg,'conditionalCertificationIndex', ...
        fullfile(root,'certification','conditional_certification_index.csv')), ...
        'comparison',fallback(cfg,'conditionalComparison', ...
        fullfile(root,'reports','conditional_inversion_comparison.csv')), ...
        'availability',fallback(cfg,'conditionalAvailability', ...
        fullfile(root,'reports','conditional_inversion_availability.csv')), ...
        'matchedCohorts',fallback(cfg,'conditionalMatchedCohorts', ...
        fullfile(root,'reports','conditional_inversion_matched_cohorts.csv')), ...
        'matchedSummary',fallback(cfg,'conditionalMatchedSummary', ...
        fullfile(root,'reports','conditional_inversion_matched_summary.csv')), ...
        'campaign',fallback(cfg,'conditionalCampaign', ...
        fullfile(root,'conditional_inversion_campaign.mat')), ...
        'status',fallback(cfg,'conditionalStatus', ...
        fullfile(root,'conditional_inversion_status.json')), ...
        'preparation',fullfile(orchestration, ...
        'conditional_campaign_preparation.mat'), ...
        'preparationJSON',fullfile(orchestration, ...
        'conditional_campaign_preparation.json'), ...
        'taskTable',fullfile(orchestration,'conditional_tasks.csv'), ...
        'cellActions',fullfile(orchestration,'conditional_cells.csv'), ...
        'canonicalBarrier',fullfile(orchestration, ...
        'canonical_baseline_barrier.csv'));
end

function value=fallback(cfg,name,defaultValue)
    value=defaultValue;
    if isfield(cfg,'files')&&isfield(cfg.files,name),value=cfg.files.(name);end
end

function record=attach_case(record,cases)
    if isfield(cases,'case_id'),ids=[cases.case_id];else,ids=[cases.caseID];end
    hit=find(double(ids)==double(record.caseID));
    assert(isscalar(hit), ...
        'inversion:conditional_campaign_contract:CaseBinding', ...
        'Case %d of the conditional grid is not exactly once in the inversion cases.', ...
        record.caseID);
    one=cases(hit);record.case_id=record.caseID;record.truth=one.truth;
    record.heldout_response=pick(one,{'heldout_response','heldoutResponse'});
    if isfield(one,'validation_index')
        record.validation_index=one.validation_index;
    end
    if isfield(one,'source_row'),record.source_row=one.source_row;end
end

function record=canonical_record(conditional)
    record=conditional;
    remove={'conditionCode','conditionID','conditionLabel', ...
        'conditionRole','freeParameterIndices','fixedParameterIndices', ...
        'fixedValueSource'};
    remove=remove(isfield(record,remove));record=rmfield(record,remove);
    record.cellID=sprintf('case_%d|%s|all_six', ...
        record.caseID,record.scenario);
end

function map=seed_map(schedule)
    map=containers.Map('KeyType','char','ValueType','char');
    for i=1:numel(schedule.records)
        one=schedule.records(i);
        map(sprintf('%d',double(one.seed)))=char(string(one.request));
    end
end

