function campaign=build_campaign(cfg,prep,entries,summary)
%BUILD_CAMPAIGN The campaign record: the grid, the run cells' entries, the reused and skipped cells.
    seedSummary=rmfield(prep.seedSchedule,{'records','numericSeeds'});
    if isempty(entries),entries=repmat(base_entry(prep.grid.cells(1)),0,1);end
    actions=string({prep.actions.action});
    campaign=struct('schemaVersion','conditional_inversion_campaign_v3', ...
        'grid',prep.grid,'seedSchedule',seedSummary, ...
        'selectedCellIndices',reshape([prep.tasks.cellIndex],1,[]),'entries',entries, ...
        'actions',prep.actions, ...
        'baselineRecords',prep.canonicalBarrier.records, ...
        'scheduledNewCellCount',prep.grid.cellCount, ...
        'selectedNewCellCount',numel(prep.tasks), ...
        'reusedCellCount',nnz(actions=="reuse"), ...
        'skippedCellCount',nnz(actions=="skip"), ...
        'complete',numel(entries)==numel(prep.tasks), ...
        'notRunCount',numel(prep.tasks)-numel(entries), ...
        'certifiedCount',nnz([entries.certified]), ...
        'unresolvedCount',nnz(~[entries.certified]), ...
        'successfulRequestCount',sum([entries.successfulRequestCount]), ...
        'failedRequestCount',sum([entries.failedRequestCount]), ...
        'failedCellCount',nnz([entries.failedRequestCount]>0), ...
        'canonicalReferenceCopiesCreated',0, ...
        'adaptiveMetropolisValidationEnabled',logical( ...
        cfg.mcmc.enableAdaptiveMetropolisValidation), ...
        'adaptiveMetropolisValidationRequestCount',sum( ...
        [entries.amValidationExecutionCount]),'summary',summary);
end

