    value=table([records.caseID].', ...
        string({records.scenario}).',string({records.design}).', ...
        string({records.cellID}).',logical([records.certified]).', ...
        string({records.status}).',logical([records.accepted]).', ...
        string({records.source}).',string({records.reason}).', ...
        'VariableNames',{'CaseID','Scenario','Design', ...
        'CellID','Certified','Status','Accepted','Source','Reason'});
end

function prep=load_preparation(cfg)
    files=output_files(cfg);
    assert(isfile(files.preparation), ...
        'inversion:conditional_campaign_contract:MissingPreparation', ...
        ['No prepared conditional campaign in %s: run the step ' ...
         '''conditional_inversion'' (it prepares the campaign first).'],files.root);
    saved=load(files.preparation,'preparation');
    prep=saved.preparation;
end

function baseline=baseline_for_task(prep,task)
    records=prep.canonicalBarrier.records;
    one=records(strcmp({records.cellID},task.canonicalBaselineCellID));
    baseline=struct('cellID',one.cellID,'caseID',one.caseID, ...
        'scenario',one.scenario,'design','all_six','certified',one.certified, ...
        'status',one.status,'reason',one.reason, ...
        'canonicalPathInvoked',false, ...
        'executionCount',0);
end

function pathValue=cell_outcome_path(cfg,cellRecord)
    paths=inversion.conditional_posterior_artifact_paths( ...
        cfg,cellRecord,'AIES',1,cfg.mcmc.levels(1));
    pathValue=fullfile(paths.cellRoot,'cell_outcome.json');
end

function entry=cell_entry(cfg,cellRecord,baseline)
%CELL_ENTRY The row of the certification index of one conditional cell.
%   From its certified provider (inversion.load_conditional_certified_posterior)
%   or its terminal unresolved decision at the last level; empty when the
%   cell has neither. BASELINE: its canonical baseline (baseline_for_task).
    entry=struct([]);
    [artifact,status]=inversion.load_conditional_certified_posterior(cfg,cellRecord);
    if status.valid
        decision=artifact.certification.reliabilityDecision;
        terminalState='certified';
    else
        assert(strcmp(status.state,'unresolved'), ...
            'inversion:conditional_campaign_contract:Certification', ...
            'The certification of %s did not load: %s',cellRecord.cellID, ...
            status.reason);
        paths=inversion.conditional_posterior_artifact_paths( ...
            cfg,cellRecord,'AIES',1,cfg.mcmc.levels(end));
        if ~isfile(paths.reliabilityPath),return;end
        decision=jsondecode(fileread(paths.reliabilityPath));
        terminalState='unresolved';
    end
    evidence=reshape(decision.executedEvidence,1,[]);
    [success,failure,am,identifiers]=counts(evidence);
    entry=base_entry(cellRecord);entry.selected=true;
    if failure>0
        entry.state='complete_with_sampler_failures';
    else
        entry.state=terminalState;
    end
    entry.certified=strcmp(terminalState,'certified');
    if entry.certified
        entry.providerSampler=char(string(decision.provider.sampler));
        entry.providerReplicateID=double(decision.provider.replicateID);
        entry.providerStepCount=double(decision.provider.stepCount);
        entry.certificationMechanism=char(string( ...
            decision.certificationMechanism));
    end
    entry.reason=char(string(decision.reason));
    entry.executionCount=numel(evidence);
    entry.successfulRequestCount=success;
    entry.failedRequestCount=failure;
    entry.amValidationExecutionCount=am;
    entry.samplerFailureIdentifiers=identifiers;
    entry.canonicalBaselineCertified=logical(baseline.certified);
end

function write_cell_outcome(cfg,cellRecord,entry)
%WRITE_CELL_OUTCOME The record of a finished conditional cell; its presence marks the cell as run.
    record=struct('schemaVersion','conditional_campaign_cell_outcome_v1', ...
        'cellIndex',double(cellRecord.cellIndex),'cellID',cellRecord.cellID, ...
        'caseID',double(cellRecord.caseID), ...
        'scenario',cellRecord.scenario,'conditionCode',cellRecord.conditionCode, ...
        'terminalState',ternary(entry.certified,'certified','unresolved'), ...
        'certified',logical(entry.certified), ...
        'providerReplicateID',entry.providerReplicateID, ...
        'providerStepCount',entry.providerStepCount,'reason',entry.reason, ...
        'executionCount',entry.executionCount, ...
        'failedRequestCount',entry.failedRequestCount, ...
        'environment',utils.environment_line(),'finishedUTC',utc_now());
    utils.atomic_write_json(cell_outcome_path(cfg,cellRecord),record, ...
        'AllowReplace',true);
end

function [success,failure,am,identifiers]=counts(evidence)
    ok=logical([evidence.executionSucceeded]);
    success=nnz(ok);failure=nnz(~ok);
    am=nnz(strcmp(cellstr(string({evidence.sampler})),'AM'));
    identifiers=cellstr(string({evidence(~ok).failureIdentifier}));
    identifiers=identifiers(~cellfun(@isempty,identifiers));
    identifiers=strjoin(unique(identifiers,'stable'),';');
end

