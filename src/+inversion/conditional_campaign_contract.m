    status=struct('schemaVersion','conditional_inversion_status_v3', ...
        'expectedNewCellCount',campaign.grid.cellCount,'selectedNewCellCount', ...
        campaign.selectedNewCellCount,'reusedCellCount',campaign.reusedCellCount, ...
        'skippedCellCount',campaign.skippedCellCount,'complete',campaign.complete, ...
        'notRunCount',campaign.notRunCount,'certifiedCount',campaign.certifiedCount, ...
        'unresolvedCount',campaign.unresolvedCount, ...
        'successfulRequestCount',campaign.successfulRequestCount, ...
        'failedRequestCount',campaign.failedRequestCount, ...
        'failedCellCount',campaign.failedCellCount, ...
        'canonicalReferenceCopiesCreated',0, ...
        'adaptiveMetropolisValidationEnabled', ...
        campaign.adaptiveMetropolisValidationEnabled, ...
        'adaptiveMetropolisValidationRequestCount', ...
        campaign.adaptiveMetropolisValidationRequestCount, ...
        'comparisonRunRelative',run_relative(files.comparison,files.runRoot), ...
        'missingAndUnresolvedRetainedExplicitly',true, ...
        'environment',utils.environment_line(),'finalizedUTC',utc_now());
end

function value=run_relative(pathValue,root)
    pathValue=utils.absolute_path(pathValue);root=utils.absolute_path(root);
    value=strrep(pathValue(numel(root)+2:end),'\','/');
end

function value=ternary(condition,whenTrue,whenFalse)
    if condition,value=whenTrue;else,value=whenFalse;end
end

function value=utc_now()
    value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z'''));
end

function value=pick(source,names)
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return
        end
    end
    error('inversion:conditional_campaign_contract:Field', ...
        'Record lacks one of: %s.',strjoin(names,', '));
end
