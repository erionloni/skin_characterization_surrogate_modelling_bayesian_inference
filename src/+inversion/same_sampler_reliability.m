function reliability = same_sampler_reliability(runs,bounds,cfg,sampler,varargin)
%SAME_SAMPLER_RELIABILITY Reliability evidence from two independent analyses.
%   RELIABILITY = inversion.same_sampler_reliability(RUNS, BOUNDS, CFG,
%   SAMPLER, ...) compares the two analyses RUNS (a 1-by-2 cell of retained
%   iteration x parameter x sampler-state arrays) of SAMPLER ('AIES' or 'AM')
%   within the parameter BOUNDS (M-by-2, model coordinates) and returns the
%   record: the health of each analysis, the independence of the pair, the
%   reproducibility criteria and the warnings. Options (name-value), all
%   needed for a pass: 'Seeds' and 'ReplicateIDs' (two distinct values each)
%   and 'HealthRecords' (the two saved single-analysis health records; the
%   health is also recomputed here from the samples, and both must pass).
%   For AIES, certification uses hard sampler-pathology checks plus posterior
%   distribution reproducibility (Wasserstein, Q025, and Q975). Whole-
%   ensemble time-series diagnostics, median differences, and correlation
%   differences remain visible warnings and cannot veto an otherwise passing
%   AIES pair. Interacting walkers are never treated as independent chains.
%
%   Adaptive Metropolis retains the prior strict independent-chain policy:
%   R-hat, bulk/tail ESS, relative SD-MCSE, structural checks, and legacy
%   posterior-summary agreement remain hard diagnostics for AM.
%   Side effects: none.

    parser=inputParser;
    parser.FunctionName='inversion.same_sampler_reliability';
    addParameter(parser,'Seeds',[],@(x)isnumeric(x)&&isvector(x));
    addParameter(parser,'ReplicateIDs',[],@(x)isnumeric(x)&&isvector(x));
    addParameter(parser,'HealthRecords',struct([]),@isstruct);
    parse(parser,varargin{:});
    assert(iscell(runs)&&numel(runs)==2, ...
        'inversion:same_sampler_reliability:RunCount', ...
        'Exactly two independently executed analyses are required.');
    for i=1:2,validate_run(runs{i},bounds);end
    assert(size(runs{1},2)==size(runs{2},2), ...
        'inversion:same_sampler_reliability:Dimension', ...
        'Both analyses must have the same parameter dimension.');

    semantics=utils.sampler_semantics(sampler);
    sampler=semantics.sampler;
    thresholds=inversion.mcmc_diagnostic_thresholds(cfg);
    [healthRecords,bothSingleAnalysesPass,healthReasons]= ...
        verify_health_records(parser.Results.HealthRecords,runs,bounds,cfg,sampler);
    [independenceVerified,independenceReasons,seeds,replicateIDs]= ...
        verify_independence(parser.Results);
    duplicates=inversion.duplicate_state_detector( ...
        runs,bounds,thresholds.duplicateSampleTolerance);
    movements=cell(1,2);

    switch semantics.stateSemantics
        case 'interacting_walkers'
            for i=1:2
                movements{i}=inversion.movement(runs{i},bounds,cfg);
            end
            functionals=inversion.ensemble_functionals(runs);
            functionalRhat=inversion.ensemble_rhat(functionals);
            functionalESS=inversion.ensemble_ess(functionals);
            rankSplitRhat=functionalRhat.maximum;
            bulkESS=functionalESS.bulkESS;
            tailESS=functionalESS.tailESS;
            mcse=inversion.mcse(runs,bulkESS,functionals);
            nIndependentStates=2;
            maximumIndependentTimeStates= ...
                functionals.nIterations*functionals.nIndependentReplicates;
            definition= ...
                'two_independent_AIES_posterior_reproducibility_v2';
            ensembleTimeHardGate=false;
        case 'independent_chains'
            chains=inversion.conventional_chains(runs);
            for i=1:2
                movements{i}=inversion.chain_movement( ...
                    chains.alignedRuns{i},bounds,cfg);
            end
            rankSplitRhat=inversion.rhat_rank_split(chains.combinedChains);
            [bulkESS,tailESS]=inversion.ess_bulk_tail(chains.combinedChains);
            mcse=inversion.mcse_chains(chains.combinedChains,bulkESS);
            functionalRhat=struct('names',{{'independent_chain_state'}}, ...
                'values',rankSplitRhat,'maximum',rankSplitRhat, ...
                'definition','rank_normalized_folded_split_Rhat_v1');
            functionalESS=struct('bulkESS',bulkESS,'tailESS',tailESS, ...
                'maximumIndependentTimeStates', ...
                chains.maximumIndependentTimeStates, ...
                'definition','independent_chain_bulk_tail_ESS_v1');
            nIndependentStates=chains.nIndependentChains;
            maximumIndependentTimeStates=chains.maximumIndependentTimeStates;
            definition='two_independent_AM_analyses_and_chains_v1';
            ensembleTimeHardGate=true;
        otherwise
            error('inversion:same_sampler_reliability:Sampler', ...
                'Unsupported sampler semantics "%s".',semantics.stateSemantics);
    end

    parameterNames=parameter_names(cfg,size(bounds,1));
    posteriorReproducibility=inversion.posterior_reproducibility( ...
        runs{1},runs{2},bounds,thresholds,'ParameterNames',parameterNames);
    % Retain the old median/tail record for explicit old-policy replay. It is
    % supporting evidence only for AIES and remains a hard record for AM.
    legacyAgreement=inversion.posterior_agreement( ...
        runs{1},runs{2},bounds,cfg);
    ensembleTimeDiagnostics=ensemble_time_record(rankSplitRhat,bulkESS, ...
        tailESS,mcse.relativeSD,thresholds,ensembleTimeHardGate);

    anyFrozen=false;
    anyLowMovement=false;
    for i=1:2
        anyFrozen=anyFrozen||any(movements{i}.uniqueStateCount< ...
            thresholds.minimumUniqueStates);
        anyLowMovement=anyLowMovement||movements{i}.anyLowMovement;
    end
    structuralReasons=healthReasons;
    if anyFrozen
        structuralReasons{end+1}= ...
            'one or more sampler-state trajectories are frozen';
    end
    if anyLowMovement
        structuralReasons{end+1}= ...
            'one or more sampler-state trajectories have insufficient movement';
    end
    if duplicates.anyDuplicate|| ...
            duplicates.duplicateStateFraction>thresholds.maxDuplicateFraction
        structuralReasons{end+1}= ...
            'duplicated analysis or sampler-state trajectory detected';
    end
    structuralReasons=unique(structuralReasons,'stable');
    structuralHealthPass=bothSingleAnalysesPass&&isempty(structuralReasons);

    hardReasons=[structuralReasons independenceReasons];
    warningReasons={};
    if strcmp(sampler,'AIES')
        if ~all(posteriorReproducibility.wassersteinPass)
            hardReasons{end+1}= ...
                'normalized Wasserstein posterior reproducibility failed';
        end
        if ~all(posteriorReproducibility.q025Pass)
            hardReasons{end+1}= ...
                'normalized Q025 posterior reproducibility failed';
        end
        if ~all(posteriorReproducibility.q975Pass)
            hardReasons{end+1}= ...
                'normalized Q975 posterior reproducibility failed';
        end
        warningReasons=ensembleTimeDiagnostics.warningReasons;
        if posteriorReproducibility.medianWarning
            warningReasons{end+1}= ...
                'prior-scaled posterior median reference exceeded';
        end
        if posteriorReproducibility.correlationWarning
            warningReasons{end+1}= ...
                'posterior correlation-difference reference exceeded';
        end
    else
        % Adaptive Metropolis keeps its validated strict independent-chain
        % diagnostics and the historical median/tail summary gate.
        if ~all(ensembleTimeDiagnostics.rankSplitRhatPass)
            hardReasons{end+1}='rank-normalized split R-hat failed';
        end
        if ~all(ensembleTimeDiagnostics.bulkESSPass)
            hardReasons{end+1}='bulk ESS failed';
        end
        if ~all(ensembleTimeDiagnostics.tailESSPass)
            hardReasons{end+1}='tail ESS failed';
        end
        if ~all(ensembleTimeDiagnostics.relativeSdMCSEPass)
            hardReasons{end+1}= ...
                'relative MCSE of posterior SD failed';
        end
        hardReasons=[hardReasons legacyAgreement.reasons];
    end
    hardReasons=unique(hardReasons,'stable');
    warningReasons=unique(warningReasons,'stable');
    hardCriteriaPass=isempty(hardReasons)&&structuralHealthPass&& ...
        independenceVerified;

    reliability=struct( ...
        'schemaVersion','direct_mcmc_same_sampler_reliability_v2', ...
        'sampler',sampler, ...
        'definition',definition, ...
        'stateSemantics',semantics.stateSemantics, ...
        'thirdDimensionSemantics',semantics.thirdDimension, ...
        'walkersTreatedAsIndependentChains',false, ...
        'independentAnalysisCount',2, ...
        'independentStateCount',nIndependentStates, ...
        'maximumIndependentTimeStates',maximumIndependentTimeStates, ...
        'independenceVerified',independenceVerified, ...
        'seeds',seeds, ...
        'replicateIDs',replicateIDs, ...
        'singleAnalysisHealth',healthRecords, ...
        'bothSingleAnalysesPass',bothSingleAnalysesPass, ...
        'structuralHealthPass',structuralHealthPass, ...
        'rankSplitRhat',rankSplitRhat, ...
        'bulkESS',bulkESS, ...
        'tailESS',tailESS, ...
        'mcse',mcse, ...
        'relativeSdMCSE',mcse.relativeSD, ...
        'functionalRhat',functionalRhat, ...
        'functionalESS',functionalESS, ...
        'ensembleTimeDiagnostics',ensembleTimeDiagnostics, ...
        'ensembleTimeDiagnosticWarning', ...
            ensembleTimeDiagnostics.warning, ...
        'ensemble_time_diagnostic_warning', ...
            ensembleTimeDiagnostics.warning, ...
        'ensemble_time_rhat_pass', ...
            ensembleTimeDiagnostics.rankSplitRhatPass, ...
        'ensemble_time_bulk_ess_pass', ...
            ensembleTimeDiagnostics.bulkESSPass, ...
        'ensemble_time_tail_ess_pass', ...
            ensembleTimeDiagnostics.tailESSPass, ...
        'ensemble_time_mcse_pass', ...
            ensembleTimeDiagnostics.relativeSdMCSEPass, ...
        'movement',{movements}, ...
        'anyFrozen',anyFrozen, ...
        'anyLowMovement',anyLowMovement, ...
        'duplicates',duplicates, ...
        'posteriorReproducibility',posteriorReproducibility, ...
        'posteriorAgreement',legacyAgreement, ...
        'thresholds',thresholds, ...
        'hardCriteriaPass',hardCriteriaPass, ...
        'warningDiagnosticsAffectReliability',false, ...
        'samplesPooledAcrossAnalyses',false, ...
        'reliable',hardCriteriaPass, ...
        'status',status_value(hardCriteriaPass), ...
        'reasons',{hardReasons}, ...
        'warningReasons',{warningReasons});
end

function record=ensemble_time_record(rhat,bulk,tail,relativeMCSE,t,hardGate)
    rhatPass=isfinite(rhat)&rhat<=t.maxRankSplitRhat;
    bulkPass=isfinite(bulk)&bulk>=t.minBulkESS;
    tailPass=isfinite(tail)&tail>=t.minTailESS;
    mcsePass=isfinite(relativeMCSE)&relativeMCSE<=t.maxRelativeSdMCSE;
    reasons={};
    if ~all(rhatPass),reasons{end+1}='ensemble-time R-hat warning';end
    if ~all(bulkPass),reasons{end+1}='ensemble-time bulk ESS warning';end
    if ~all(tailPass),reasons{end+1}='ensemble-time tail ESS warning';end
    if ~all(mcsePass),reasons{end+1}='ensemble-time MCSE warning';end
    record=struct( ...
        'schemaVersion','ensemble_time_supporting_diagnostics_v1', ...
        'rankSplitRhat',rhat, ...
        'rankSplitRhatThreshold',double(t.maxRankSplitRhat), ...
        'rankSplitRhatPass',rhatPass, ...
        'bulkESS',bulk, ...
        'bulkESSThreshold',double(t.minBulkESS), ...
        'bulkESSPass',bulkPass, ...
        'tailESS',tail, ...
        'tailESSThreshold',double(t.minTailESS), ...
        'tailESSPass',tailPass, ...
        'relativeSdMCSE',relativeMCSE, ...
        'relativeSdMCSEThreshold',double(t.maxRelativeSdMCSE), ...
        'relativeSdMCSEPass',mcsePass, ...
        'allPass',all(rhatPass)&&all(bulkPass)&&all(tailPass)&&all(mcsePass), ...
        'warning',~isempty(reasons), ...
        'warningReasons',{reasons}, ...
        'hardGateForSampler',logical(hardGate), ...
        'walkersTreatedAsIndependentChains',false);
end

function [records,bothPass,reasons]=verify_health_records( ...
        supplied,runs,bounds,cfg,sampler)
    records=reshape(supplied,1,[]);
    reasons={};
    if numel(records)~=2
        bothPass=false;
        reasons{end+1}= ...
            'two bound single-analysis health records are required';
        return;
    end
    required={'sampler','pass'};
    if ~all(isfield(records,required))
        bothPass=false;
        reasons{end+1}= ...
            'single-analysis health records are incomplete';
        return;
    end
    messages=cell(1,4);
    messageCount=0;
    for i=1:2
        recomputed=inversion.single_analysis_health(runs{i},bounds,cfg,sampler);
        if ~strcmpi(char(string(records(i).sampler)),sampler)
            messageCount=messageCount+1;
            messages{messageCount}=sprintf( ...
                'replicate %d health record belongs to another sampler',i);
        end
        if ~logical(records(i).pass)||~logical(recomputed.pass)
            messageCount=messageCount+1;
            messages{messageCount}=sprintf( ...
                'replicate %d failed its single-analysis health check',i);
        end
    end
    reasons=[reasons messages(1:messageCount)];
    bothPass=all([records.pass])&&isempty(reasons);
end

function [verified,reasons,seeds,replicateIDs]=verify_independence(value)
    seeds=reshape(double(value.Seeds),1,[]);
    replicateIDs=reshape(double(value.ReplicateIDs),1,[]);
    reasons={};
    if numel(seeds)~=2||numel(unique(seeds))~=2||any(~isfinite(seeds))
        reasons{end+1}= ...
            'two distinct deterministic seed records are required';
    end
    if numel(replicateIDs)~=2||numel(unique(replicateIDs))~=2|| ...
            any(~isfinite(replicateIDs))
        reasons{end+1}= ...
            'two distinct replicate IDs are required';
    end
    verified=isempty(reasons);
end

function validate_run(run,bounds)
    assert(isnumeric(run)&&size(run,1)>=4&&size(run,2)==size(bounds,1)&& ...
        size(run,3)>=1&&all(isfinite(run),'all'), ...
        'inversion:same_sampler_reliability:Samples', ...
        'Each run must be a finite retained-iteration x parameter x state array.');
    assert(isnumeric(bounds)&&size(bounds,2)==2&&all(isfinite(bounds),'all')&& ...
        all(bounds(:,2)>bounds(:,1)), ...
        'inversion:same_sampler_reliability:Bounds','Invalid parameter bounds.');
end

function names=parameter_names(cfg,count)
    if isfield(cfg,'paramNames')&&numel(cfg.paramNames)==count
        names=cellstr(string(cfg.paramNames(:))).';
    else
        names=arrayfun(@(i)sprintf('theta_%02d',i),1:count, ...
            'UniformOutput',false);
    end
end

function value=status_value(reliable)
    if reliable,value='reliable';else,value='mcmc_unreliable';end
end
