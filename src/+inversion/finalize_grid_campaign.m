function campaign = finalize_grid_campaign(cfg,varargin)
%FINALIZE_GRID_CAMPAIGN The certification index and campaign record of a complete canonical campaign.
%   CAMPAIGN = inversion.finalize_grid_campaign(CFG) reads the terminal
%   decision of every cell of the prepared campaign (certified provider or
%   unresolved decision; inversion.grid_campaign_support 'cell_entry') and
%   writes, below CFG.paths.stage04:
%     certification/certification_index.csv   one row per cell in grid order:
%         certified or not, provider, reason, request counts
%     inversion_campaign.mat                   the campaign: grid, entries
%         and counts (the conditional inversion starts from it)
%     certification/canonical_campaign_status.json   counts and the
%         MATLAB/UQLab line
%   'Preparation',PREPARATION passes the prepared campaign instead of
%   reading it. Every cell must have run (it refuses otherwise, naming the
%   cells to run). It evaluates no GP and runs no sampler.
%   Side effects: writes the three files, replacing earlier versions.

    parser=inputParser;
    parser.FunctionName='inversion.finalize_grid_campaign';
    addParameter(parser,'Preparation',struct([]), ...
        @(x)isempty(x)||(isstruct(x)&&isscalar(x)));
    parse(parser,varargin{:});
    preparation=parser.Results.Preparation;
    if isempty(preparation)
        preparation=inversion.grid_campaign_support('load_preparation',cfg);
    end
    count=preparation.grid.cellCount;
    records=cell(count,1);
    for i=1:count
        records{i}=inversion.grid_campaign_support('cell_entry',cfg, ...
            preparation.cellRecords(i));
    end
    missing=find(cellfun(@isempty,records)).';
    assert(isempty(missing), ...
        'inversion:finalize_grid_campaign:MissingCells', ...
        ['The campaign in %s is complete when every cell has run; cells %s have ' ...
         'not (grid indices of cell_task_table.csv).'], ...
        preparation.paths.stageRoot,mat2str(missing));
    entries=vertcat(records{:});

    index=inversion.grid_campaign_support('certification_table',entries);
    utils.atomic_write_table(cfg.files.certificationIndex,index);
    campaign=struct( ...
        'schemaVersion','direct_mcmc_campaign_v3_aies_first', ...
        'grid',preparation.grid, ...
        'selectedCellIndices',1:count, ...
        'entries',entries, ...
        'certifiedCount',nnz([entries.certified]), ...
        'unresolvedCount',nnz(~[entries.certified]), ...
        'successfulRequestCount',sum([entries.successfulRequestCount]), ...
        'failedRequestCount',sum([entries.failedRequestCount]), ...
        'adaptiveMetropolisValidationEnabled',logical( ...
            cfg.mcmc.enableAdaptiveMetropolisValidation), ...
        'adaptiveMetropolisValidationRequestCount',sum( ...
            [entries.amValidationExecutionCount]), ...
        'certificationIndex','certification/certification_index.csv');
    utils.atomic_save_struct(fullfile(cfg.paths.stage04,'inversion_campaign.mat'), ...
        struct('campaign',campaign),'-v7');
    status=struct( ...
        'schemaVersion','direct_mcmc_grid_campaign_status_v2', ...
        'status','complete', ...
        'cellCount',count, ...
        'certifiedCount',campaign.certifiedCount, ...
        'unresolvedCount',campaign.unresolvedCount, ...
        'failedRequestCount',campaign.failedRequestCount, ...
        'failedCellCount',nnz([entries.failedRequestCount]>0), ...
        'environment',utils.environment_line(), ...
        'finalizedUTC',char(datetime('now','TimeZone','UTC', ...
            'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
    utils.atomic_write_json(fullfile(cfg.paths.stage04,'certification', ...
        'canonical_campaign_status.json'),status,'AllowReplace',true);
end
