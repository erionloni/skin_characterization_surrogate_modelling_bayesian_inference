function [features,jacobian,covariance] = ...
        physics_guided_full_rank_transform(y,rawCovariance,denominatorFloor)
%PHYSICS_GUIDED_FULL_RANK_TRANSFORM Transform, analytic Jacobian, covariance.
%   [F,J,SIGMAF] = inversion.physics_guided_full_rank_transform(Y,SIGMAP)
%   evaluates the invertible physics-guided six-vector and its exact 6-by-6
%   Jacobian. If a complete 6-by-6 raw pressure covariance is supplied, the
%   delta-method covariance is SIGMAF = J*SIGMAP*J'. Correlations introduced
%   by the shared raw pressures are retained.
%   Y: 1-by-6 closing pressures (mbar); F: 6-by-1 features; J: 6-by-6;
%   SIGMAF: 6-by-6 (empty without SIGMAP).
%   Side effects: none.

    if nargin<2,rawCovariance=[];end
    if nargin<3 || isempty(denominatorFloor),denominatorFloor=1e-12;end
    assert(isnumeric(y)&&isreal(y)&&isvector(y)&&numel(y)==6&& ...
        all(isfinite(y)), ...
        'inversion:physics_guided_full_rank_transform:InvalidOutput', ...
        'y must be one finite real six-pressure vector.');
    y=y(:);
    features=inversion.physics_guided_full_rank_values( ...
        y.',denominatorFloor).';

    y1=y(1);y3=y(3);y4=y(4);y5=y(5);y6=y(6);
    jacobian=[ ...
        0,          0, 1,           0,    0,          0; ...
        -y3/y1^2,   0, 1/y1,        0,    0,          0; ...
        1,         -1, 0,           0,    0,          0; ...
        1/y6,       0, 0,           0,    0, -y1/y6^2; ...
        0,          0, 0, -y6/y4^2, 0,       1/y4; ...
        0,          0, 0, -y5/y4^2, 1/y4,    0];
    assert(all(isfinite(jacobian),'all'), ...
        'inversion:physics_guided_full_rank_transform:NonFiniteJacobian', ...
        'The analytic transform Jacobian is nonfinite.');

    if isempty(rawCovariance)
        covariance=[];
        return;
    end
    assert(isnumeric(rawCovariance)&&isreal(rawCovariance)&& ...
        isequal(size(rawCovariance),[6 6])&& ...
        all(isfinite(rawCovariance),'all'), ...
        'inversion:physics_guided_full_rank_transform:InvalidCovariance', ...
        'rawCovariance must be one finite real 6-by-6 matrix.');
    symmetryError=norm(rawCovariance-rawCovariance.','fro')/ ...
        max(norm(rawCovariance,'fro'),eps);
    assert(symmetryError<=1e-10, ...
        'inversion:physics_guided_full_rank_transform:NonSymmetricCovariance', ...
        'rawCovariance must be symmetric.');
    rawCovariance=(rawCovariance+rawCovariance.')/2;
    covariance=jacobian*rawCovariance*jacobian.';
    covariance=(covariance+covariance.')/2;
    assert(isequal(size(covariance),[6 6])&& ...
        all(isfinite(covariance),'all'), ...
        'inversion:physics_guided_full_rank_transform:TransformedCovariance', ...
        'The complete transformed covariance must be finite and 6-by-6.');
end
