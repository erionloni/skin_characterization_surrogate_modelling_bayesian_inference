function design = design_registry(name)
%DESIGN_REGISTRY Canonical six-design direct-inversion registry.
%   With no input, return the ordered six-design production axis.
%
%   Raw output order is [p1_D2 p2_D2 p3_D2 p1_D6 p2_D6 p3_D6]. The
%   physics-guided six-vector is an invertible representation of those same
%   six measurements, not a source of additional experimental information.
%
%   DESIGN = inversion.design_registry() returns the six active designs in
%   order (all_six, d2_only, d6_only, cycle_1_only, ratios_only,
%   physics_guided_full_rank_six); DESIGN = inversion.design_registry(NAME)
%   the design NAME: its output indices, observation transform and its
%   version, dimensions and whether it is rankable.
%   Side effects: none.

    active = [ ...
        make_design('all_six','All six','raw',1:6,1:6, ...
            'none','raw_subset_v1',6, ...
            'raw_full_reference',true), ...
        make_design('d2_only','D2 only','raw',1:3,1:3, ...
            'none','raw_subset_v1',3, ...
            'measurement_subset_or_transform_experiment',true), ...
        make_design('d6_only','D6 only','raw',4:6,4:6, ...
            'none','raw_subset_v1',3, ...
            'measurement_subset_or_transform_experiment',true), ...
        make_design('cycle_1_only','Cycle 1 only','raw',[1 4],[1 4], ...
            'none','raw_subset_v1',2, ...
            'measurement_subset_or_transform_experiment',true), ...
        make_design('ratios_only','Ratios only','ratio',[],1:6, ...
            'ratios','shared_noisy_raw_ratio_transform_v1',4, ...
            'measurement_subset_or_transform_experiment',true), ...
        make_design('physics_guided_full_rank_six', ...
            'Physics-guided full-rank six','transformed_full_rank',[],1:6, ...
            'physics_guided_full_rank_six', ...
            'physics_guided_full_rank_six_full_delta_cov_v1',6, ...
            'full_rank_representation_check_not_new_measurement_information', ...
            true)];

    activeNames = {active.name};
    assert(numel(active)==6 && numel(unique(activeNames))==6 && ...
        isequal(activeNames,{'all_six','d2_only','d6_only','cycle_1_only', ...
        'ratios_only','physics_guided_full_rank_six'}), ...
        'inversion:design_registry:Cardinality', ...
        'The direct-inversion registry must contain exactly six active designs.');

    if nargin<1 || isempty(name)
        design = active;
        return;
    end
    name = char(string(name));
    hit = find(strcmp(activeNames,name));
    assert(isscalar(hit),'inversion:design_registry:UnknownDesign', ...
        'Unknown inversion design "%s".',name);
    design = active(hit);
end

function value = make_design(name,label,type,outputIndices,sourceIndices, ...
        transform,transformVersion,likelihoodDimension,scientificRole,active)
    value = struct( ...
        'name',name, ...
        'label',label, ...
        'type',type, ...
        'outputIndices',outputIndices, ...
        'sourceOutputIndices',sourceIndices, ...
        'observationTransform',transform, ...
        'transformVersion',transformVersion, ...
        'rankable',true, ...
        'sourceOutputDimension',numel(sourceIndices), ...
        'likelihoodOutputDimension',likelihoodDimension, ...
        'scientificRole',scientificRole, ...
        'active',logical(active));
end
