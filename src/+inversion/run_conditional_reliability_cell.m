function [decision,executions,seedMap] = run_conditional_reliability_cell( ...
        cfg,cellRecord,gp,condition,seedMap)
%RUN_CONDITIONAL_RELIABILITY_CELL AIES-pair controller in reduced space.
%   [DECISION, EXECUTIONS, SEEDMAP] = inversion.run_conditional_reliability_cell(
%   CFG, CELLRECORD, GP, CONDITION, SEEDMAP) runs the conditional cell
%   CELLRECORD (truth, scenario, design) under CONDITION
%   (inversion.conditional_inversion_conditions) with the GP GP. DECISION is
%   the cell's certification decision, EXECUTIONS the requests run or reused,
%   SEEDMAP the register of used seeds with theirs added.
%   Two fresh independent AIES requests are evaluated at each configured
%   level.  Only free dimensions enter reproducibility diagnostics.  Optional
%   AM evidence is saved separately at 2k and can never certify, veto, replace,
%   or be pooled with the AIES replicate-1 scientific posterior.
%   Every request is saved below the conditional cell folder
%   (inversion.save_conditional_posterior_artifact); a request that an
%   earlier call finished is reused.
%   Side effects: writes every request's files below the conditional cell
%   folder.
%   Computation: two to five MCMC requests (minutes to hours).

    condition=inversion.conditional_inversion_conditions(cfg,condition.tag);
    assert(condition.supplementaryExecution&& ...
        strcmpi(char(string(cfg.mcmc.productionSampler)),'AIES')&& ...
        isequal(reshape(double(cfg.mcmc.productionReplicateIDs),1,[]),[1 2]), ...
        'inversion:run_conditional_reliability_cell:Policy', ...
        'Supplementary production requires two AIES replicates; A is canonical.');
    truth=reshape(double(pick(cellRecord,{'truth','thetaTrue'})),1,[]);
    adapter=inversion.conditional_adapter(cfg,condition,truth);
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    assert(isequal(levels,[2000 5000]), ...
        'inversion:run_conditional_reliability_cell:Levels', ...
        'Conditional execution requires the configured fresh-total-length levels.');

    steps=levels(1);
    first=execute_request(cfg,cellRecord,gp,condition,adapter,'AIES',1,steps);
    seedMap=register_seed(seedMap,first);
    second=execute_request(cfg,cellRecord,gp,condition,adapter,'AIES',2,steps);
    seedMap=register_seed(seedMap,second);
    executions=[first second];
    pair=pair_evidence(first,second,adapter,cfg,@default_pair_evaluator);
    evidence=struct('aiesPairReliability',pair);
    optionalAM=struct([]);
    if should_run_am(cfg,cellRecord)
        am=execute_request(cfg,cellRecord,gp,condition,adapter,'AM', ...
            cfg.mcmc.amValidationReplicateID,cfg.mcmc.amValidationStepCount);
        seedMap=register_seed(seedMap,am);executions(end+1)=am;
        optionalAM=am_evidence(first,am,adapter,cfg,@inversion.posterior_agreement);
        evidence.optionalAdaptiveMetropolisValidation=optionalAM;
    end
    decision=inversion.direct_mcmc_decision(cfg,steps,evidence);
    while ~decision.certified&&~strcmp(decision.status,'unresolved')
        assert(strcmp(decision.action,'run_fresh_total_length_at_next_level')&& ...
            numel(decision.requests)==2&& ...
            all(strcmp({decision.requests.sampler},'AIES'))&& ...
            isequal(sort([decision.requests.replicateID]),[1 2])&& ...
            isscalar(unique([decision.requests.stepCount])), ...
            'inversion:run_conditional_reliability_cell:Escalation', ...
            'Escalation must request one fresh independent AIES pair.');
        nextExecutions=repmat(first,1,0);
        for r=1:numel(decision.requests)
            request=decision.requests(r);
            next=execute_request(cfg,cellRecord,gp,condition,adapter, ...
                request.sampler,request.replicateID,request.stepCount);
            seedMap=register_seed(seedMap,next);
            nextExecutions(end+1)=next; %#ok<AGROW>
            executions(end+1)=next; %#ok<AGROW>
        end
        [~,order]=sort([nextExecutions.replicateID]);
        first=nextExecutions(order(1));second=nextExecutions(order(2));
        steps=first.stepCount;
        pair=pair_evidence(first,second,adapter,cfg,@default_pair_evaluator);
        evidence=struct('aiesPairReliability',pair);
        if ~isempty(optionalAM)
            evidence.optionalAdaptiveMetropolisValidation=optionalAM;
        end
        decision=inversion.direct_mcmc_decision(cfg,steps,evidence);
    end
    decision=bind_execution_evidence(decision,executions,adapter);
end

function execution=execute_request(cfg,cellRecord,gp,condition,adapter, ...
        sampler,replicateID,stepCount)
    [saved,status]=inversion.load_conditional_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    if status.valid
        execution=from_saved(saved,status,cfg,adapter,sampler, ...
            replicateID,stepCount);return;
    end
    assert(strcmp(status.state,'missing'), ...
        'inversion:run_conditional_reliability_cell:InvalidSavedArtifact', ...
        'Refusing to overwrite invalid conditional artifact: %s',status.reason);
    try
        execution=inversion.run_conditional_request(cellRecord,gp,cfg,condition, ...
            'Sampler',sampler,'ReplicateID',replicateID, ...
            'StepCount',stepCount);
        inversion.save_conditional_posterior_artifact( ...
            cfg,cellRecord,condition,adapter,execution);
        [saved,status]=inversion.load_conditional_posterior_artifact( ...
            cfg,cellRecord,sampler,replicateID,stepCount);
        assert(status.valid, ...
            'inversion:run_conditional_reliability_cell:Persistence', ...
            'Fresh conditional request did not reload: %s',status.reason);
        execution=from_saved(saved,status,cfg,adapter,sampler, ...
            replicateID,stepCount);
        execution.state='executed_saved_and_verified';
    catch exception
        if ~strcmp(exception.identifier, ...
                'inversion:run_conditional_request:SamplerExecutionFailure')
            rethrow(exception);
        end
        execution=failed_execution(cfg,cellRecord,adapter,sampler, ...
            replicateID,stepCount,exception);
    end
    execution=normalize_execution(execution);
end

function value=normalize_execution(source)
    fields={'schemaVersion','state','succeeded','request', ...
        'sampler','replicateID','stepCount','seed','seedRecord', ...
        'samplerSettings','parameterAdapter','sampleArray','drawsFree', ...
        'drawsCanonical','health','result','samplesPooled','artifact','paths', ...
        'failure'};
    assert(all(isfield(source,fields)), ...
        'inversion:run_conditional_reliability_cell:ExecutionFields', ...
        'Conditional execution lacks normalized controller fields.');
    values=cell(1,numel(fields));
    for i=1:numel(fields),values{i}=source.(fields{i});end
    value=cell2struct(values,fields,2);
end

function execution=from_saved(artifact,status,cfg,adapter,sampler,replicateID,steps)
    [seed,seedRecord]=seeds.mcmc(cfg,artifact.request.caseID, ...
        artifact.request.scenario,artifact.request.design, ...
        adapter.fixedParameterIndices,sampler,replicateID,steps);
    [~,samplerSettings]=inversion.sampler_request_config(cfg,sampler,steps);
    execution=struct( ...
        'schemaVersion','conditional_mcmc_request_execution_v1', ...
        'state','complete_request_reused','succeeded',true, ...
        'request',artifact.request, ...
        'sampler',sampler,'replicateID',double(replicateID), ...
        'stepCount',double(steps),'seed',double(seed),'seedRecord',seedRecord, ...
        'samplerSettings',samplerSettings,'parameterAdapter',adapter, ...
        'sampleArray',artifact.sampleArray,'drawsFree',artifact.drawsFree, ...
        'drawsCanonical',artifact.drawsCanonicalCoordinates, ...
        'health',artifact.health,'result',struct([]),'samplesPooled',false, ...
        'artifact',artifact,'paths',status.paths,'failure',struct([]));
end

function execution=failed_execution(cfg,cellRecord,adapter,sampler, ...
        replicateID,stepCount,exception)
    [~,settings]=inversion.sampler_request_config(cfg,sampler,stepCount);
    caseID=double(pick(cellRecord,{'caseID','case_id'}));
    scenario=inversion.scenario_registry(pick(cellRecord,{'scenario'}));
    design=inversion.design_registry(pick(cellRecord,{'design'}));
    [seed,seedRecord]=seeds.mcmc(cfg,caseID,scenario.tag, ...
        design.name,adapter.fixedParameterIndices,sampler,replicateID,stepCount);
    cellID=sprintf('case_%d|%s|%s|condition_%s',caseID,scenario.tag, ...
        design.name,adapter.conditionTag);
    request=struct('schemaVersion','conditional_mcmc_request_v1', ...
        'cellID',cellID,'caseID',caseID, ...
        'scenario',scenario.tag, ...
        'design',design.name, ...
        'conditionCode',adapter.conditionCode, ...
        'conditionTag',adapter.conditionTag, ...
        'freeParameterIndices',adapter.freeParameterIndices, ...
        'freeParameterNames',{adapter.freeParameterNames}, ...
        'fixedParameterIndices',adapter.fixedParameterIndices, ...
        'fixedParameterValues',adapter.fixedParameterValues, ...
        'fixedValueSemantics',adapter.fixedValueSemantics, ...
        'samplerDimension',adapter.samplerDimension, ...
        'canonicalDimension',adapter.canonicalDimension, ...
        'sampler',sampler,'replicateID',double(replicateID), ...
        'stepCount',double(stepCount),'seed',double(seed), ...
        'runMode','fresh_total_length', ...
        'loadParentState',false,'appendParentSamples',false,'poolSamples',false);
    original=exception;if ~isempty(exception.cause),original=exception.cause{1};end
    identifier=char(string(original.identifier));
    if isempty(identifier),identifier='unidentified_sampler_exception';end
    failure=struct('schemaVersion','conditional_mcmc_sampler_failure_v1', ...
        'sampler',sampler, ...
        'replicateID',double(replicateID),'stepCount',double(stepCount), ...
        'seed',double(seed),'exceptionIdentifier',identifier, ...
        'classification','scientific_sampler_execution_failure', ...
        'posteriorArtifactAvailable',false, ...
        'retrySemantics','fresh_deterministic_request_on_pipeline_resume');
    health=struct('schemaVersion','conditional_mcmc_failed_request_health_v1', ...
        'sampler',sampler,'executionSucceeded',false, ...
        'singleAnalysisDiagnosticsAvailable',false,'pass',false, ...
        'healthy',false,'cellCertified',false, ...
        'exceptionIdentifier',identifier, ...
        'reasons',{{sprintf('%s conditional sampler execution failed (%s)', ...
        sampler,identifier)}});
    execution=struct('schemaVersion','conditional_mcmc_request_execution_v1', ...
        'state','sampler_execution_failed','succeeded',false, ...
        'request',request,'sampler',sampler, ...
        'replicateID',double(replicateID),'stepCount',double(stepCount), ...
        'seed',double(seed),'seedRecord',seedRecord,'samplerSettings',settings, ...
        'parameterAdapter',adapter, ...
        'sampleArray',zeros(0,adapter.samplerDimension,0), ...
        'drawsFree',zeros(0,adapter.samplerDimension), ...
        'drawsCanonical',zeros(0,4),'health',health,'result',struct([]), ...
        'samplesPooled',false,'artifact',struct(), ...
        'paths',struct([]),'failure',failure);
end

function pair=pair_evidence(first,second,adapter,cfg,evaluator)
    if succeeded(first)&&succeeded(second)
        pair=evaluator(first,second,adapter,cfg);
        assert(isstruct(pair)&&isscalar(pair)&&isfield(pair,'sampler')&& ...
            isfield(pair,'reliable')&&strcmp(pair.sampler,'AIES'), ...
            'inversion:run_conditional_reliability_cell:PairContract', ...
            'Pair evaluator returned an invalid AIES reliability record.');
    else
        success=[succeeded(first) succeeded(second)];
        identifiers={};both={first second};
        for i=find(~success)
            identifiers{end+1}=both{i}.failure.exceptionIdentifier; %#ok<AGROW>
        end
        pair=struct('schemaVersion','conditional_mcmc_failed_pair_v1', ...
            'sampler','AIES','replicateIDs',[1 2], ...
            'requestExecutionSucceeded',success, ...
            'allRequestsExecutedSuccessfully',all(success), ...
            'allSingleAnalysisHealthChecksPassed',false, ...
            'failureIdentifiers',{identifiers}, ...
            'reliable',false,'status','sampler_execution_failure', ...
            'reasons',{{'one or more conditional AIES requests failed'}});
    end
    pair.conditionTag=adapter.conditionTag;
end

function pair=default_pair_evaluator(first,second,adapter,cfg)
    pair=inversion.conditional_same_sampler_reliability( ...
        {first.sampleArray,second.sampleArray},adapter,cfg,'AIES', ...
        'Seeds',[first.seed second.seed], ...
        'ReplicateIDs',[first.replicateID second.replicateID], ...
        'HealthRecords',[first.health second.health]);
end

function evidence=am_evidence(aies,am,adapter,cfg,evaluator)
    evidence=struct('schemaVersion', ...
        'conditional_optional_adaptive_metropolis_validation_v1', ...
        'enabled',true,'selectedForCell',true,'sampler','AM', ...
        'stepCount',double(am.stepCount), ...
        'aiesPrimaryReplicateID',double(aies.replicateID), ...
        'amReplicateID',double(am.replicateID), ...
        'amExecutionSucceeded',succeeded(am),'amHealth',am.health, ...
        'affectsProductionCertification',false, ...
        'canReplacePrimaryPosterior',false,'samplesPooled',false, ...
        'posteriorComparison',struct([]));
    if succeeded(aies)&&succeeded(am)
        localCfg=cfg;localCfg.paramNames=adapter.freeParameterNames;
        localCfg.paramBounds=adapter.freeBounds;
        comparison=evaluator(aies.sampleArray,am.sampleArray, ...
            adapter.freeBounds,localCfg);
        comparison.leftSampler='AIES';comparison.rightSampler='AM';
        evidence.posteriorComparison=comparison;
    elseif ~succeeded(am)
        evidence.amFailureIdentifier=am.failure.exceptionIdentifier;
    end
end

function tf=should_run_am(cfg,cellRecord)
    if ~logical(cfg.mcmc.enableAdaptiveMetropolisValidation),tf=false;return;end
    selected=reshape(double(cfg.mcmc.amValidationCaseIDs),1,[]);
    caseID=double(pick(cellRecord,{'caseID','case_id'}));
    tf=isempty(selected)||ismember(caseID,selected);
end

function decision=bind_execution_evidence(decision,executions,adapter)
    template=struct('sampler','','replicateID',NaN,'stepCount',NaN, ...
        'seed',NaN,'request','','executionState','', ...
        'executionSucceeded',false,'failureIdentifier','');
    records=repmat(template,1,numel(executions));
    for i=1:numel(executions)
        one=executions(i);ok=succeeded(one);failureIdentifier='';
        if ~ok,failureIdentifier=one.failure.exceptionIdentifier;end
        records(i)=struct('sampler',one.sampler, ...
            'replicateID',double(one.replicateID),'stepCount',double(one.stepCount), ...
            'seed',double(one.seed),'request',one.seedRecord.request, ...
            'executionState',one.state, ...
            'executionSucceeded',ok,'failureIdentifier',failureIdentifier);
    end
    decision.schemaVersion='conditional_mcmc_reliability_decision_v1';
    decision.conditionTag=adapter.conditionTag;
    decision.freeParameterIndices=adapter.freeParameterIndices;
    decision.fixedParameterIndices=adapter.fixedParameterIndices;
    decision.fixedValuesSetToTruth=true;
    decision.executedEvidence=records;
    if decision.certified
        provider=decision.provider;
        hit=strcmp({records.sampler},provider.sampler)& ...
            [records.replicateID]==provider.replicateID& ...
            [records.stepCount]==provider.stepCount& ...
            logical([records.executionSucceeded]);
        assert(nnz(hit)==1&&strcmp(provider.sampler,'AIES')&& ...
            provider.replicateID==1, ...
            'inversion:run_conditional_reliability_cell:Provider', ...
            'Certified provider must bind uniquely to AIES replicate 1.');
    end
    decision.optionalAMEvidenceAffectsCertification=false;
end

function tf=succeeded(execution)
    tf=isstruct(execution)&&isscalar(execution)&&isfield(execution,'succeeded')&& ...
        logical(execution.succeeded);
end

function map=register_seed(map,execution)
    key=sprintf('%d',double(execution.seed));request=execution.seedRecord.request;
    if isKey(map,key)
        assert(strcmp(map(key),request), ...
            'inversion:run_conditional_reliability_cell:SeedCollision', ...
            'Two different conditional requests have the same RNG seed %s.',key);
    else
        map(key)=request;
    end
end

function value=pick(source,names)
    value=optional(source,names,[]);
    assert(~isempty(value), ...
        'inversion:run_conditional_reliability_cell:CellField', ...
        'Cell record lacks one of: %s.',strjoin(names,', '));
end

function value=optional(source,names,fallback)
    value=fallback;
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
end
