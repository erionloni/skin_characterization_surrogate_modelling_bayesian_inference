function [decision,executions,seedMap] = run_reliability_cell( ...
        cfg,cellRecord,gp,P,seedMap,varargin)
%RUN_RELIABILITY_CELL Execute one cell under the AIES-first policy.
%   [DECISION, EXECUTIONS, SEEDMAP] = inversion.run_reliability_cell(CFG,
%   CELLRECORD, GP, P, SEEDMAP, 'RequestRunner', F) runs the cell CELLRECORD
%   (truth, scenario, design) with the GP GP over the parameter space P.
%   DECISION is the cell's certification decision, EXECUTIONS the requests
%   run or reused, SEEDMAP the register of used seeds with theirs added.
%   Every configured level runs two fresh, independent AIES analyses. Their
%   hard structural health and posterior-distribution reproducibility decide
%   certification or escalation. Optional AM validation is one separate 2k
%   analysis; it is saved as secondary evidence and never affects the AIES
%   certification decision or primary-posterior selection.
%
%   RequestRunner runs one request: inversion.run_cell (default) for the
%   fixed route; the confirmation passes confirmation.run_confirmation_request,
%   which evaluates the generalized GP at the cell's protocol.
%   Side effects: the request runner writes every request's files below the
%   cell folder.
%   Computation: two to five MCMC requests (minutes to hours).

    parser=inputParser;
    parser.FunctionName='inversion.run_reliability_cell';
    addParameter(parser,'RequestRunner',@inversion.run_cell, ...
        @(x)isa(x,'function_handle'));
    parse(parser,varargin{:});
    runner=parser.Results.RequestRunner;
    agreementEvaluator=@inversion.posterior_agreement;
    pairEvaluator=@default_pair_evaluator;

    steps=cfg.mcmc.levels(1);
    replicateIDs=reshape(double(cfg.mcmc.productionReplicateIDs),1,[]);
    assert(isequal(replicateIDs,[1 2]), ...
        'inversion:run_reliability_cell:ProductionReplicates', ...
        'The AIES production policy requires replicate IDs [1 2].');
    first=execute_request(runner,cellRecord,gp,P,cfg,'AIES', ...
        replicateIDs(1),steps);
    seedMap=register_seed(seedMap,first);
    second=execute_request(runner,cellRecord,gp,P,cfg,'AIES', ...
        replicateIDs(2),steps);
    seedMap=register_seed(seedMap,second);
    executions=[first second];
    pair=pair_evidence(first,second,P.bounds,cfg,pairEvaluator);
    evidence=struct('aiesPairReliability',pair);
    optionalAM=struct([]);
    if should_run_am_validation(cfg,cellRecord)
        am=execute_request(runner,cellRecord,gp,P,cfg,'AM', ...
            cfg.mcmc.amValidationReplicateID, ...
            cfg.mcmc.amValidationStepCount);
        seedMap=register_seed(seedMap,am);
        executions(end+1)=am;
        optionalAM=optional_am_evidence( ...
            first,am,P.bounds,cfg,agreementEvaluator);
        evidence.optionalAdaptiveMetropolisValidation=optionalAM;
    end
    decision=inversion.direct_mcmc_decision(cfg,steps,evidence);
    while ~decision.certified&&~strcmp(decision.status,'unresolved')
        switch decision.action
            case 'run_fresh_total_length_at_next_level'
                requests=decision.requests;
                assert(numel(requests)==2&& ...
                    all(strcmp({requests.sampler},'AIES'))&& ...
                    isequal(sort([requests.replicateID]),[1 2])&& ...
                    isscalar(unique([requests.stepCount])), ...
                    'inversion:run_reliability_cell:EscalationRequests', ...
                    ['AIES-first escalation must request exactly independent ' ...
                     'replicates 1 and 2 at one fresh total-length level.']);
                nextExecutions=repmat(first,1,0);
                for r=1:numel(requests)
                    next=execute_request(runner,cellRecord,gp,P,cfg, ...
                        requests(r).sampler,requests(r).replicateID, ...
                        requests(r).stepCount);
                    seedMap=register_seed(seedMap,next);
                    nextExecutions(end+1)=next; %#ok<AGROW>
                    executions(end+1)=next; %#ok<AGROW>
                end
                steps=requests(1).stepCount;
                [~,order]=sort([nextExecutions.replicateID]);
                nextExecutions=nextExecutions(order);
                first=nextExecutions(1);
                second=nextExecutions(2);
                pair=pair_evidence( ...
                    first,second,P.bounds,cfg,pairEvaluator);
                evidence=struct('aiesPairReliability',pair);
                if ~isempty(optionalAM)
                    evidence.optionalAdaptiveMetropolisValidation=optionalAM;
                end
                decision=inversion.direct_mcmc_decision(cfg,steps,evidence);
            otherwise
                error('inversion:run_reliability_cell:DecisionAction', ...
                    'Unsupported reliability action "%s".',decision.action);
        end
    end
    decision=bind_execution_evidence(decision,executions);
end

function execution=execute_request(runner,cellRecord,gp,P,cfg, ...
        sampler,replicateID,stepCount)
    try
        execution=runner(cellRecord,gp,P,cfg, ...
            'Sampler',sampler,'ReplicateID',replicateID, ...
            'StepCount',stepCount);
        validate_successful_execution( ...
            execution,sampler,replicateID,stepCount);
    catch exception
        if ~strcmp(exception.identifier, ...
                'inversion:run_cell:SamplerExecutionFailure')
            rethrow(exception);
        end
        execution=failed_execution( ...
            cfg,cellRecord,P,sampler,replicateID,stepCount,exception);
    end
end

function validate_successful_execution(execution,sampler,replicateID,stepCount)
    required={'succeeded','request','sampler', ...
        'replicateID','stepCount','seed','seedRecord','sampleArray', ...
        'health','artifact','paths','failure'};
    assert(isstruct(execution)&&isscalar(execution)&& ...
        all(isfield(execution,required))&&logical(execution.succeeded)&& ...
        strcmp(execution.sampler,sampler)&& ...
        double(execution.replicateID)==double(replicateID)&& ...
        double(execution.stepCount)==double(stepCount)&& ...
        logical(execution.health.pass)==logical(execution.health.healthy)&& ...
        isempty(execution.failure), ...
        'inversion:run_reliability_cell:ExecutionContract', ...
        'Request runner returned an invalid successful-execution record.');
end

function execution=failed_execution(cfg,cellRecord,P,sampler, ...
        replicateID,stepCount,exception)
    [~,samplerSettings]=inversion.sampler_request_config( ...
        cfg,sampler,stepCount);
    paths=inversion.posterior_artifact_paths( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    if isfield(cellRecord,'MaterialCaseID')
        % A confirmation cell: the seed of the confirmation's rule for its
        % material, protocol and design (confirmation.run_confirmation_request).
        [seed,seedRecord]=seeds.confirmation(cfg,cellRecord.MaterialCaseID, ...
            cellRecord.protocolIndex,sampler,replicateID,stepCount,cellRecord.design);
    else
        [seed,seedRecord]=seeds.mcmc(cfg,paths.caseID,paths.scenario, ...
            paths.design,[],sampler,replicateID,stepCount);
    end
    request=struct( ...
        'schemaVersion','direct_mcmc_request_reference_v1', ...
        'cellID',paths.cellID, ...
        'caseID',paths.caseID, ...
        'scenario',paths.scenario, ...
        'design',paths.design, ...
        'sampler',paths.sampler, ...
        'replicateID',paths.replicateID, ...
        'stepCount',paths.stepCount, ...
        'seed',double(seed), ...
        'runMode','fresh_total_length', ...
        'loadParentState',false, ...
        'appendParentSamples',false, ...
        'poolSamples',false);

    original=exception;
    if ~isempty(exception.cause),original=exception.cause{1};end
    identifier=char(string(original.identifier));
    if isempty(identifier),identifier='unidentified_sampler_exception';end
    failure=struct( ...
        'schemaVersion','direct_mcmc_sampler_failure_v1', ...
        'sampler',paths.sampler, ...
        'replicateID',paths.replicateID, ...
        'stepCount',paths.stepCount, ...
        'seed',double(seed), ...
        'exceptionIdentifier',identifier, ...
        'classification','scientific_sampler_execution_failure', ...
        'posteriorArtifactAvailable',false, ...
        'retrySemantics','fresh_deterministic_request_on_pipeline_resume');
    % Vendor diagnostic text is deliberately omitted because it may embed
    % machine-local paths. The stable exception identifier remains available.
    health=struct( ...
        'schemaVersion','direct_mcmc_failed_request_health_v1', ...
        'sampler',paths.sampler, ...
        'executionSucceeded',false, ...
        'singleAnalysisDiagnosticsAvailable',false, ...
        'pass',false, ...
        'healthy',false, ...
        'cellCertified',false, ...
        'exceptionIdentifier',identifier, ...
        'reasons',{{sprintf('%s sampler execution failed (%s)', ...
            paths.sampler,identifier)}});
    execution=struct( ...
        'schemaVersion','direct_mcmc_cell_execution_v1', ...
        'state','sampler_execution_failed', ...
        'succeeded',false, ...
        'request',request, ...
        'sampler',paths.sampler, ...
        'replicateID',paths.replicateID, ...
        'stepCount',paths.stepCount, ...
        'seed',double(seed), ...
        'seedRecord',seedRecord, ...
        'samplerSettings',samplerSettings, ...
        'sampleArray',zeros(0,P.M,0), ...
        'drawsPhysical',zeros(0,P.M), ...
        'health',health, ...
        'artifact',struct(), ...
        'paths',paths, ...
        'samplesPooled',false, ...
        'failure',failure);
end

function evidence=optional_am_evidence(aies,am,bounds,cfg,evaluator)
    evidence=struct( ...
        'schemaVersion','optional_adaptive_metropolis_validation_v1', ...
        'enabled',true, ...
        'selectedForCell',true, ...
        'sampler','AM', ...
        'stepCount',double(am.stepCount), ...
        'aiesPrimaryReplicateID',double(aies.replicateID), ...
        'amReplicateID',double(am.replicateID), ...
        'amExecutionSucceeded',execution_succeeded(am), ...
        'amHealth',am.health, ...
        'affectsProductionCertification',false, ...
        'canReplacePrimaryPosterior',false, ...
        'samplesPooled',false, ...
        'posteriorComparison',struct([]));
    if execution_succeeded(aies)&&execution_succeeded(am)
        agreement=evaluator(aies.sampleArray,am.sampleArray,bounds,cfg);
        evidence.posteriorComparison=bind_cross_agreement(agreement);
    elseif ~execution_succeeded(am)
        evidence.amFailureIdentifier=am.failure.exceptionIdentifier;
    end
end

function agreement=bind_cross_agreement(agreement)
    assert(isstruct(agreement)&&isscalar(agreement)&& ...
        isfield(agreement,'agrees'), ...
        'inversion:run_reliability_cell:AgreementContract', ...
        'Agreement evaluator returned an invalid record.');
    agreement.leftSampler='AIES';
    agreement.rightSampler='AM';
end

function tf=should_run_am_validation(cfg,cellRecord)
    assert(isfield(cfg,'mcmc')&&all(isfield(cfg.mcmc,{ ...
        'enableAdaptiveMetropolisValidation','amValidationCaseIDs', ...
        'amValidationStepCount','amValidationReplicateID'})), ...
        'inversion:run_reliability_cell:AMValidationConfiguration', ...
        'Optional AM validation configuration is incomplete.');
    if ~logical(cfg.mcmc.enableAdaptiveMetropolisValidation)
        tf=false;
        return;
    end
    caseID=optional_field(cellRecord,{'caseID','case_id'},NaN);
    assert(isnumeric(caseID)&&isscalar(caseID)&&isfinite(caseID), ...
        'inversion:run_reliability_cell:AMValidationCase', ...
        'The inversion cell lacks a numeric CaseID.');
    selected=reshape(double(cfg.mcmc.amValidationCaseIDs),1,[]);
    tf=isempty(selected)||ismember(double(caseID),selected);
end

function decision=bind_execution_evidence(decision,executions)
    template=struct('sampler','','replicateID',NaN,'stepCount',NaN, ...
        'seed',NaN,'request','','executionState','', ...
        'executionSucceeded',false,'failureIdentifier','');
    records=repmat(template,1,numel(executions));
    for i=1:numel(executions)
        execution=executions(i);
        succeeded=execution_succeeded(execution);
        failureIdentifier='';
        if ~succeeded
            failureIdentifier=execution.failure.exceptionIdentifier;
        end
        records(i)=struct( ...
            'sampler',execution.sampler, ...
            'replicateID',double(execution.replicateID), ...
            'stepCount',double(execution.stepCount), ...
            'seed',double(execution.seed), ...
            'request',execution.seedRecord.request, ...
            'executionState',execution.state, ...
            'executionSucceeded',succeeded, ...
            'failureIdentifier',failureIdentifier);
    end
    decision.executedEvidence=records;
    if decision.certified
        provider=decision.provider;
        hit=strcmp({records.sampler},provider.sampler)& ...
            [records.replicateID]==provider.replicateID& ...
            [records.stepCount]==provider.stepCount& ...
            logical([records.executionSucceeded]);
        assert(nnz(hit)==1, ...
            'inversion:run_reliability_cell:ProviderEvidence', ...
            ['Certified provider does not bind to exactly one successful ' ...
             'executed request.']);
    end
end

function pair=pair_evidence(first,second,bounds,cfg,evaluator)
    assert(strcmp(first.sampler,second.sampler), ...
        'inversion:run_reliability_cell:PairSampler', ...
        'Same-sampler evidence requires matching samplers.');
    if execution_succeeded(first)&&execution_succeeded(second)
        pair=evaluator(first,second,bounds,cfg);
        assert(isstruct(pair)&&isscalar(pair)&& ...
            all(isfield(pair,{'sampler','reliable'}))&& ...
            strcmp(pair.sampler,first.sampler), ...
            'inversion:run_reliability_cell:PairContract', ...
            'Pair evaluator returned an invalid reliability record.');
    else
        successes=[execution_succeeded(first) execution_succeeded(second)];
        failed={first second};
        failureIdentifiers={};
        for i=find(~successes)
            failureIdentifiers{end+1}= ...
                failed{i}.failure.exceptionIdentifier; %#ok<AGROW>
        end
        pair=struct( ...
            'schemaVersion','direct_mcmc_failed_pair_reliability_v1', ...
            'sampler',first.sampler, ...
            'replicateIDs',[first.replicateID second.replicateID], ...
            'requestExecutionSucceeded',successes, ...
            'allRequestsExecutedSuccessfully',all(successes), ...
            'allSingleAnalysisHealthChecksPassed',false, ...
            'failureIdentifiers',{failureIdentifiers}, ...
            'reliable',false, ...
            'status','sampler_execution_failure', ...
            'reasons',{{'one or more same-sampler requests failed to execute'}});
    end
end

function pair=default_pair_evaluator(first,second,bounds,cfg)
    pair=inversion.same_sampler_reliability( ...
        {first.sampleArray,second.sampleArray},bounds,cfg,first.sampler, ...
        'Seeds',[first.seed second.seed], ...
        'ReplicateIDs',[first.replicateID second.replicateID], ...
        'HealthRecords',[first.health second.health]);
end

function tf=execution_succeeded(execution)
    tf=isstruct(execution)&&isscalar(execution)&& ...
        isfield(execution,'succeeded')&&logical(execution.succeeded);
end

function map=register_seed(map,execution)
    key=sprintf('%d',execution.seed);
    request=execution.seedRecord.request;
    if isKey(map,key)
        assert(strcmp(map(key),request), ...
            'inversion:run_reliability_cell:SeedCollision', ...
            'Two different direct-MCMC requests have the same RNG seed %s.',key);
    else
        map(key)=request;
    end
end

function value=optional_field(source,names,fallback)
    value=fallback;
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
end
