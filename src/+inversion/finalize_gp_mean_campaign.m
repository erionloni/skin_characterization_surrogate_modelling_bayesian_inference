function campaign = finalize_gp_mean_campaign(cfg,varargin)
%FINALIZE_GP_MEAN_CAMPAIGN The certification index and campaign record of a complete GP-mean campaign.
%   CAMPAIGN = inversion.finalize_gp_mean_campaign(CFG) reads the terminal
%   decision of every cell of the prepared GP-mean campaign (certified
%   provider or unresolved decision; inversion.grid_campaign_support
%   'cell_entry', with the campaign's configuration
%   inversion.gp_mean_campaign_config) and writes, below
%   CFG.paths.gpMeanInversion:
%     certification/certification_index.csv  one row per cell in grid order:
%         certified or not, provider, reason, request counts
%     gp_mean_campaign.mat                   the campaign: grid, entries and counts
%     certification/gp_mean_campaign_status.json  counts and the MATLAB/UQLab line
%   'Preparation',PREPARATION passes the prepared campaign instead of
%   reading it. Every cell must have run (it refuses otherwise, naming the
%   cells to run). It evaluates no GP and runs no sampler.
%   Side effects: writes the three files, replacing earlier versions.

    parser=inputParser;
    parser.FunctionName='inversion.finalize_gp_mean_campaign';
    addParameter(parser,'Preparation',struct([]), ...
        @(x)isempty(x)||(isstruct(x)&&isscalar(x)));
    parse(parser,varargin{:});
    campaignCfg=inversion.gp_mean_campaign_config(cfg);
    preparation=parser.Results.Preparation;
    if isempty(preparation)
        preparation=inversion.grid_campaign_support('load_preparation',campaignCfg);
    end
    count=preparation.grid.cellCount;
    records=cell(count,1);
    for i=1:count
        records{i}=inversion.grid_campaign_support('cell_entry',campaignCfg, ...
            preparation.cellRecords(i));
    end
    missing=find(cellfun(@isempty,records)).';
    assert(isempty(missing), ...
        'inversion:finalize_gp_mean_campaign:MissingCells', ...
        ['The GP-mean campaign in %s is complete when every cell has run; cells %s have ' ...
         'not (task indices of cell_task_table.csv).'],preparation.paths.stageRoot,mat2str(missing));
    entries=vertcat(records{:});
    utils.atomic_write_table(campaignCfg.files.certificationIndex, ...
        inversion.grid_campaign_support('certification_table',entries));
    campaign=struct( ...
        'schemaVersion','gp_mean_campaign_v1', ...
        'grid',preparation.grid, ...
        'entries',entries, ...
        'certifiedCount',nnz([entries.certified]), ...
        'unresolvedCount',nnz(~[entries.certified]), ...
        'successfulRequestCount',sum([entries.successfulRequestCount]), ...
        'failedRequestCount',sum([entries.failedRequestCount]), ...
        'certificationIndex','certification/certification_index.csv');
    root=cfg.paths.gpMeanInversion;
    utils.atomic_save_struct(fullfile(root,'gp_mean_campaign.mat'),struct('campaign',campaign),'-v7');
    status=struct( ...
        'schemaVersion','gp_mean_campaign_status_v1', ...
        'status','complete', ...
        'cellCount',count, ...
        'certifiedCount',campaign.certifiedCount, ...
        'unresolvedCount',campaign.unresolvedCount, ...
        'failedRequestCount',campaign.failedRequestCount, ...
        'failedCellCount',nnz([entries.failedRequestCount]>0), ...
        'environment',utils.environment_line(), ...
        'finalizedUTC',char(datetime('now','TimeZone','UTC', ...
            'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
    utils.atomic_write_json(fullfile(root,'certification','gp_mean_campaign_status.json'), ...
        status,'AllowReplace',true);
end
