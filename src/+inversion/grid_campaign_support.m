function varargout = grid_campaign_support(action,varargin)
%GRID_CAMPAIGN_SUPPORT Shared parts of the canonical inversion campaign.
%   Used by inversion.prepare_grid_campaign, run_grid_cell and
%   finalize_grid_campaign and by study.write_inversion_results: the files of
%   the campaign, the cell records, the seed schedule, the task table, the
%   written preparation, the outcome of a cell and the certification index.
%   It contains no sampler, likelihood or GP call.
%
%   Actions (inversion.grid_campaign_support(ACTION, ...)):
%     'preparation_paths'   CFG -> the campaign's files below CFG.paths.stage04
%     'attach_cases'        GRID, CASES -> cell records with truth and observation
%     'seed_schedule'       CFG, GRID -> [records, table]: the seed of every
%                           request of every cell (seeds.mcmc)
%     'seed_map'            PREPARATION -> seed -> the request it seeds
%     'grid_table'          GRID -> one row per cell
%     'task_table'          CFG, CELLRECORDS -> one task per cell, with its folder
%     'policy_summary'      CFG, GRID -> the MCMC policy record
%     'publish_preparation' PREPARATION -> writes it below the campaign folder
%     'load_preparation'    CFG -> the prepared campaign
%     'cell_outcome_path'   CFG, CELL -> the cell's outcome record
%     'cell_outcome'        CFG, CELL -> its saved terminal decision, or missing
%     'cell_entry'          CFG, CELL -> its row of the certification index
%                           (empty when the cell has no terminal decision)
%     'write_cell_outcome'  CFG, CELL, ENTRY -> writes the outcome record
%     'write_unresolved_decision'  CFG, CELL, DECISION -> writes it
%     'campaign_record'     CELL, DECISION, EVIDENCE, STATE, ERROR -> the cell's
%                           row of the certification index
%     'certification_table' ENTRIES -> the certification index
%
%   Side effects: 'publish_preparation', 'write_cell_outcome' and
%   'write_unresolved_decision' write below the campaign folder; the other
%   actions only read.

    action=char(string(action));
    switch action
        case 'preparation_paths'
            varargout{1}=preparation_paths(varargin{1});
        case 'attach_cases'
            varargout{1}=attach_cases(varargin{1},varargin{2});
        case 'seed_schedule'
            [varargout{1:nargout}]=seed_schedule(varargin{1},varargin{2});
        case 'seed_map'
            varargout{1}=seed_map(varargin{1});
        case 'grid_table'
            varargout{1}=grid_table(varargin{1});
        case 'task_table'
            varargout{1}=task_table(varargin{:});
        case 'policy_summary'
            varargout{1}=policy_summary(varargin{:});
        case 'publish_preparation'
            publish_preparation(varargin{1});
        case 'load_preparation'
            varargout{1}=load_preparation(varargin{1});
        case 'cell_outcome_path'
            varargout{1}=cell_outcome_path(varargin{1},varargin{2});
        case 'cell_outcome'
            varargout{1}=cell_outcome(varargin{1},varargin{2});
        case 'cell_entry'
            varargout{1}=cell_entry(varargin{1},varargin{2});
        case 'write_cell_outcome'
            write_cell_outcome(varargin{:});
        case 'write_unresolved_decision'
            varargout{1}=write_unresolved_decision(varargin{:});
        case 'campaign_record'
            varargout{1}=campaign_record(varargin{:});
        case 'certification_table'
            varargout{1}=certification_table(varargin{1});
        otherwise
            error('inversion:grid_campaign_support:Action', ...
                'Unsupported canonical grid-campaign action "%s".',action);
    end
end

function paths=preparation_paths(cfg)
    stageRoot=utils.absolute_path(cfg.paths.stage04);
    paths=struct( ...
        'stageRoot',stageRoot, ...
        'gridCSV',utils.absolute_path(cfg.files.inversionGrid), ...
        'taskTableCSV',fullfile(stageRoot,'cell_task_table.csv'), ...
        'seedScheduleCSV',fullfile(stageRoot,'certification', ...
            'direct_mcmc_seed_schedule.csv'), ...
        'policyMAT',fullfile(stageRoot,'certification', ...
            'mcmc_reliability_policy.mat'), ...
        'preparationMAT',fullfile(stageRoot,'campaign_preparation.mat'), ...
        'preparationJSON',fullfile(stageRoot, ...
            'campaign_preparation.json'));
end

function records=attach_cases(grid,cases)
    records=grid.cells;
    for i=1:numel(records)
        hit=find([cases.case_id]==records(i).caseID);
        assert(isscalar(hit), ...
            'inversion:grid_campaign_support:CaseBinding', ...
            'Case %d of the grid is not exactly once in the inversion cases.', ...
            records(i).caseID);
        records(i).case_id=cases(hit).case_id;
        records(i).validation_index=cases(hit).validation_index;
        records(i).source_row=cases(hit).source_row;
        records(i).truth=cases(hit).truth;
        records(i).heldout_response=cases(hit).heldout_response;
    end
end

function [records,value]=seed_schedule(cfg,grid)
    replicates=reshape(double(cfg.mcmc.productionReplicateIDs),1,[]);
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    assert(isequal(replicates,[1 2])&&isequal(levels,[2000 5000]), ...
        'inversion:grid_campaign_support:ProductionSeedAxes', ...
        ['The production policy runs two independent replicates per level ' ...
         'at 2000 and 5000 steps.']);
    template=struct('CellIndex',NaN,'CellID','','CaseID',NaN, ...
        'Scenario','','Design','','Sampler','','ReplicateID',NaN, ...
        'StepCount',NaN,'Seed',NaN,'Request','');
    records=repmat(template,1,grid.cellCount*numel(levels)* ...
        numel(replicates)+grid.cellCount);
    usedSeeds=containers.Map('KeyType','char','ValueType','char');
    cursor=0;
    for c=1:grid.cellCount
        cellRecord=grid.cells(c);
        for level=levels
            for replicate=replicates
                [seed,record]=seeds.mcmc(cfg, ...
                    cellRecord.caseID,cellRecord.scenario,cellRecord.design, ...
                    [],'AIES',replicate,level);
                [records,usedSeeds,cursor]=register_seed_record( ...
                    records,usedSeeds,cursor,cellRecord,seed,record);
            end
        end
        if am_validation_selected(cfg,cellRecord.caseID)
            [seed,record]=seeds.mcmc(cfg, ...
                cellRecord.caseID,cellRecord.scenario,cellRecord.design, ...
                [],'AM',cfg.mcmc.amValidationReplicateID, ...
                cfg.mcmc.amValidationStepCount);
            [records,usedSeeds,cursor]=register_seed_record( ...
                records,usedSeeds,cursor,cellRecord,seed,record);
        end
    end
    records=records(1:cursor);
    value=struct2table(records);
end

function [records,usedSeeds,cursor]=register_seed_record( ...
        records,usedSeeds,cursor,cellRecord,seed,record)
    key=sprintf('%d',seed);
    % Two requests with one seed would not be independent ensembles.
    assert(~isKey(usedSeeds,key), ...
        'inversion:grid_campaign_support:GlobalSeedCollision', ...
        'Two inversion requests have the same seed %s.',key);
    usedSeeds(key)=record.request;cursor=cursor+1;
    records(cursor)=struct('CellIndex',double(cellRecord.cellIndex), ...
        'CellID',cellRecord.cellID,'CaseID',double(cellRecord.caseID), ...
        'Scenario',cellRecord.scenario,'Design',cellRecord.design, ...
        'Sampler',record.sampler,'ReplicateID',double(record.replicateID), ...
        'StepCount',double(record.stepCount),'Seed',double(seed), ...
        'Request',record.request);
end

function tf=am_validation_selected(cfg,caseID)
    if ~logical(cfg.mcmc.enableAdaptiveMetropolisValidation)
        tf=false;return
    end
    selected=reshape(double(cfg.mcmc.amValidationCaseIDs),1,[]);
    tf=isempty(selected)||ismember(double(caseID),selected);
end

function map=seed_map(preparation)
    records=preparation.seedRecords;
    map=containers.Map('KeyType','char','ValueType','char');
    for i=1:numel(records)
        map(sprintf('%d',records(i).Seed))=records(i).Request;
    end
end

function value=grid_table(grid)
    cells=grid.cells;
    value=table([cells.cellIndex].',string({cells.cellID}).', ...
        [cells.caseID].',string({cells.scenario}).', ...
        string({cells.scenarioLabel}).',string({cells.design}).', ...
        string({cells.designLabel}).',logical([cells.primaryScenario]).', ...
        'VariableNames',{'CellIndex','CellID','CaseID','Scenario', ...
        'ScenarioLabel','Design','DesignLabel','PrimaryScenario'});
end

function value=task_table(cfg,cellRecords)
%TASK_TABLE One task per grid cell: its index, axes and folder below the campaign.
    stageRoot=utils.absolute_path(cfg.paths.stage04);
    template=struct('TaskIndex',NaN,'CellIndex',NaN,'CellID','', ...
        'CaseID',NaN,'Scenario','','Design','', ...
        'CellFolder','');
    records=repmat(template,1,numel(cellRecords));
    for i=1:numel(cellRecords)
        cellRecord=cellRecords(i);
        paths=inversion.posterior_artifact_paths(cfg,cellRecord,'AIES',1, ...
            cfg.mcmc.levels(1));
        records(i)=struct('TaskIndex',double(i), ...
            'CellIndex',double(cellRecord.cellIndex), ...
            'CellID',cellRecord.cellID, ...
            'CaseID',double(cellRecord.caseID), ...
            'Scenario',cellRecord.scenario, ...
            'Design',cellRecord.design, ...
            'CellFolder',relative_inside(paths.cellRoot,stageRoot));
    end
    value=struct2table(records);
end

