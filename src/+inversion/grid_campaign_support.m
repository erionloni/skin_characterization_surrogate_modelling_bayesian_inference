function publish_preparation(preparation)
%PUBLISH_PREPARATION Write the prepared campaign: tables, policy, preparation and its summary.
    paths=preparation.paths;
    utils.atomic_write_table(paths.gridCSV,preparation.gridTable);
    utils.atomic_write_table(paths.taskTableCSV,preparation.taskTable);
    utils.atomic_write_table(paths.seedScheduleCSV,preparation.seedScheduleTable);
    utils.atomic_save_struct(paths.policyMAT,struct('policy',preparation.policy),'-v7');
    utils.atomic_save_struct(paths.preparationMAT, ...
        struct('preparation',preparation),'-v7');
    summary=struct( ...
        'schemaVersion','direct_mcmc_grid_campaign_preparation_v2', ...
        'inversionCohortSelectionMode',preparation.inversionCohortSelectionMode, ...
        'inversionCaseIDs',reshape(double(preparation.inversionCaseIDs),1,[]), ...
        'cellCount',preparation.grid.cellCount, ...
        'requestSeedCount',numel(preparation.seedRecords), ...
        'levels',reshape(double(preparation.levels),1,[]), ...
        'demonstrationSteps',reshape(double(preparation.demonstrationSteps),1,[]), ...
        'taskTable',relative_inside(paths.taskTableCSV,paths.stageRoot), ...
        'seedSchedule',relative_inside(paths.seedScheduleCSV,paths.stageRoot), ...
        'environment',utils.environment_line(), ...
        'preparedUTC',utc_now());
    utils.atomic_write_json(paths.preparationJSON,summary,'AllowReplace',true);
end

function preparation=load_preparation(cfg)
    paths=preparation_paths(cfg);
    assert(isfile(paths.preparationMAT), ...
        'inversion:grid_campaign_support:MissingPreparation', ...
        ['No prepared inversion campaign in %s: run the step ''inversion'' ' ...
         '(it prepares the campaign first).'],paths.stageRoot);
    saved=load(paths.preparationMAT,'preparation');
    preparation=saved.preparation;
    preparation.paths=paths;
end

function pathValue=cell_outcome_path(cfg,cellRecord)
    paths=inversion.posterior_artifact_paths( ...
        cfg,cellRecord,'AIES',1,cfg.mcmc.levels(1));
    pathValue=fullfile(paths.cellRoot,'cell_outcome.json');
end

function outcome=cell_outcome(cfg,cellRecord)
%CELL_OUTCOME The saved terminal decision of one cell, or missing.
%   A certified cell has its certified posterior (inversion.save_certified_posterior);
%   an uncertified one its terminal decision at the last level
%   (write_unresolved_decision). OUTCOME has fields missing, certified,
%   terminalState and decision.
    outcome=struct('missing',true,'certified',false,'terminalState','', ...
        'decision',struct([]));
    [artifact,status]=inversion.load_certified_posterior(cfg,cellRecord);
    if status.valid
        outcome.decision=artifact.certification.reliabilityDecision;
        outcome.certified=true;outcome.terminalState='certified';
    else
        assert(strcmp(status.state,'unresolved'), ...
            'inversion:grid_campaign_support:Certification', ...
            'The certification of %s did not load: %s',status.cellID,status.reason);
        paths=inversion.posterior_artifact_paths(cfg,cellRecord,'AIES',1, ...
            cfg.mcmc.levels(end));
        if ~isfile(paths.reliabilityPath),return;end
        outcome.decision=jsondecode(fileread(paths.reliabilityPath));
        outcome.terminalState='unresolved';
    end
    outcome.missing=false;
end

function entry=cell_entry(cfg,cellRecord)
%CELL_ENTRY The row of the certification index of one cell, from its terminal decision.
    entry=struct([]);
    outcome=cell_outcome(cfg,cellRecord);
    if outcome.missing,return;end
    evidence=outcome.decision.executedEvidence;
    entry=campaign_record(cellRecord,outcome.decision,evidence, ...
        completion_state(evidence),'');
end

function write_cell_outcome(cfg,cellRecord,entry)
%WRITE_CELL_OUTCOME The record of a finished cell: its outcome and where it ran.
%   Written last, once the terminal decision is saved; its presence marks
%   the cell as run.
    record=struct('schemaVersion','direct_mcmc_grid_cell_outcome_v1', ...
        'cellIndex',double(cellRecord.cellIndex),'cellID',cellRecord.cellID, ...
        'caseID',double(cellRecord.caseID), ...
        'scenario',cellRecord.scenario,'design',cellRecord.design, ...
        'terminalState',ternary(entry.certified,'certified','unresolved'), ...
        'certified',logical(entry.certified), ...
        'providerSampler',entry.providerSampler, ...
        'providerReplicateID',entry.providerReplicateID, ...
        'providerStepCount',entry.providerStepCount,'reason',entry.reason, ...
        'executionCount',entry.executionCount, ...
        'failedRequestCount',entry.failedRequestCount, ...
        'environment',utils.environment_line(),'finishedUTC',utc_now());
    utils.atomic_write_json(cell_outcome_path(cfg,cellRecord),record, ...
        'AllowReplace',true);
end

function pathValue=write_unresolved_decision(cfg,cellRecord,decision)
%WRITE_UNRESOLVED_DECISION The terminal decision of a cell that was not certified.
    paths=inversion.posterior_artifact_paths( ...
        cfg,cellRecord,'AIES',1,decision.stepCount);
    pathValue=paths.reliabilityPath;
    utils.atomic_write_json(pathValue,decision,'AllowReplace',true);
end

function value=campaign_record(cellRecord,decision,evidence, ...
        state,errorMessage)
    certified=~isempty(decision)&&logical(decision.certified);
    if certified
        providerSampler=char(string(decision.provider.sampler));
        providerReplicate=double(decision.provider.replicateID);
        providerSteps=double(decision.provider.stepCount);
        reason=char(string(decision.reason));
        certificationMechanism=char(string( ...
            decision.certificationMechanism));
    elseif ~isempty(decision)
        providerSampler='';providerReplicate=NaN;providerSteps=NaN;
        reason=char(string(decision.reason));
        certificationMechanism='NOT_CERTIFIED';
    else
        providerSampler='';providerReplicate=NaN;providerSteps=NaN;
        reason=errorMessage;
        certificationMechanism='NOT_CERTIFIED';
    end
    [executionCount,successCount,failureCount,amCount,identifiers]= ...
        evidence_counts(evidence);
    value=struct( ...
        'cellID',cellRecord.cellID, ...
        'caseID',cellRecord.caseID, ...
        'scenario',cellRecord.scenario, ...
        'design',cellRecord.design, ...
        'state',state, ...
        'certified',certified, ...
        'providerSampler',providerSampler, ...
        'providerReplicateID',providerReplicate, ...
        'providerStepCount',providerSteps, ...
        'reason',reason, ...
        'certificationMechanism',certificationMechanism, ...
        'executionCount',executionCount, ...
        'successfulRequestCount',successCount, ...
        'failedRequestCount',failureCount, ...
        'amValidationExecutionCount',amCount, ...
        'samplerFailureIdentifiers',identifiers, ...
        'errorMessage',errorMessage);
end

function value=certification_table(entries)
    value=table(string({entries.cellID}).',[entries.caseID].', ...
        string({entries.scenario}).',string({entries.design}).', ...
        logical([entries.certified]).',string({entries.state}).', ...
        string({entries.providerSampler}).',[entries.providerReplicateID].', ...
        [entries.providerStepCount].',string({entries.reason}).', ...
        string({entries.certificationMechanism}).', ...
        [entries.executionCount].',[entries.successfulRequestCount].', ...
        [entries.failedRequestCount].', ...
        [entries.amValidationExecutionCount].', ...
        string({entries.samplerFailureIdentifiers}).', ...
        'VariableNames',{'CellID','CaseID','Scenario','Design','Certified', ...
        'State','ProviderSampler','ProviderReplicateID','ProviderStepCount', ...
        'Reason','CertificationMechanism','ExecutionCount', ...
        'SuccessfulRequestCount','FailedRequestCount', ...
        'AMValidationExecutionCount','SamplerFailureIdentifiers'});
end

function [count,successCount,failureCount,amCount,identifiers]= ...
        evidence_counts(evidence)
    if isempty(evidence)
        count=0;successCount=0;failureCount=0;amCount=0;identifiers='';
        return
    end
    if isfield(evidence,'succeeded')
        succeeded=logical([evidence.succeeded]);
        samplers={evidence.sampler};
        failureIDs=cell(1,nnz(~succeeded));cursor=0;
        for i=find(~succeeded)
            cursor=cursor+1;
            failureIDs{cursor}=evidence(i).failure.exceptionIdentifier;
        end
    else
        succeeded=logical([evidence.executionSucceeded]);
        samplers=cellstr(string({evidence.sampler}));
        failureIDs=cellstr(string({evidence(~succeeded).failureIdentifier}));
    end
    count=numel(evidence);successCount=nnz(succeeded);
    failureCount=nnz(~succeeded);amCount=nnz(strcmp(samplers,'AM'));
    identifiers=strjoin(unique(failureIDs,'stable'),';');
end

function state=completion_state(evidence)
    if isempty(evidence)
        state='complete';
    elseif isfield(evidence,'succeeded')
        if all([evidence.succeeded])
            state='complete';
        else
            state='complete_with_sampler_failures';
        end
    else
        if all([evidence.executionSucceeded])
            state='complete';
        else
            state='complete_with_sampler_failures';
        end
    end
end

function value=ternary(condition,whenTrue,whenFalse)
    if condition,value=whenTrue;else,value=whenFalse;end
end

function relative=relative_inside(pathValue,root)
    pathValue=utils.absolute_path(pathValue);root=utils.absolute_path(root);
    relative=strrep(pathValue(numel(root)+2:end),'\','/');
end

function value=utc_now()
    value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z'''));
end
