function execution = run_cell(cellRecord,gp,P,cfg,varargin)
%RUN_CELL Run or resume one sampler analysis for one inversion-grid cell.
%   EXECUTION = inversion.run_cell(CELL,GP,P,CFG,'Sampler','AIES', ...
%       'ReplicateID',1,'StepCount',2000)
%   CELL must include case/scenario/design axes plus truth and
%   heldout_response. All requests are fresh total-length analyses. With
%   CFG.resume, a request that an earlier call finished (its files below
%   the cell folder, inversion.load_posterior_artifact) is reused as a whole.
%   Side effects: writes the request's files below the cell folder
%   (inversion.save_posterior_artifact); the random number generator's
%   state is restored afterwards.
%   Computation: minutes to an hour (one MCMC request).

    parser=inputParser;
    parser.FunctionName='inversion.run_cell';
    addParameter(parser,'Sampler','AIES',@(x)ischar(x)|| ...
        (isstring(x)&&isscalar(x)));
    addParameter(parser,'ReplicateID',1,@(x)isnumeric(x)&&isscalar(x)&& ...
        isfinite(x)&&x==fix(x)&&x>=1);
    addParameter(parser,'StepCount',cfg.mcmc.levels(1), ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x==fix(x));
    parse(parser,varargin{:});
    sampler=char(string(parser.Results.Sampler));
    replicateID=double(parser.Results.ReplicateID);
    stepCount=double(parser.Results.StepCount);
    [requestCfg,samplerSettings]=inversion.sampler_request_config( ...
        cfg,sampler,stepCount);
    caseID=case_field(cellRecord,{'caseID','case_id'});
    scenario=char(string(case_field(cellRecord,{'scenario','likelihoodMode'})));
    designName=char(string(case_field(cellRecord, ...
        {'design','outputDesign','design_name'})));
    truth=reshape(double(case_field(cellRecord,{'truth','thetaTrue'})),1,[]);
    heldout=reshape(double(case_field(cellRecord, ...
        {'heldout_response','heldoutResponse','observation'})),1,[]);
    assert(numel(truth)==P.M&&numel(heldout)==6&& ...
        all(isfinite(truth))&&all(isfinite(heldout)), ...
        'inversion:run_cell:CaseData', ...
        'Cell truth and six-output held-out observation are required.');
    [seed,seedRecord]=seeds.mcmc( ...
        cfg,caseID,scenario,designName,[],sampler,replicateID,stepCount);
    [cached,cachedStatus]=inversion.load_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    if isfield(cfg,'resume')&&logical(cfg.resume)&&cachedStatus.valid
        execution=execution_from_artifact(cached,cachedStatus, ...
            seedRecord,samplerSettings,'resumed_complete_request');
        return;
    end

    design=inversion.design_registry(designName);
    scenarioEntry=inversion.scenario_registry(scenario);
    opts=struct( ...
        'outputs',design.sourceOutputIndices, ...
        'observationTransform',design.observationTransform, ...
        'thetaTrue',truth, ...
        'keepAnalysis',false, ...
        'scenarioTag',scenarioEntry.tag, ...
        'observationSource',scenarioEntry.observationSource, ...
        'uncertaintyMode',scenarioEntry.uncertaintyMode, ...
        'measurementCV',cfg.meas_cv, ...
        'emulatorErrorCalibrationVersion', ...
            cfg.inversion.emulatorErrorCalibrationVersion, ...
        'replicateID',replicateID, ...
        'continuationStage',sprintf('fresh_total_%d',stepCount), ...
        'initialization',requestCfg.mcmc.initialization, ...
        'initializationParameters',struct(), ...
        'caseID',caseID, ...
        'seed',seed);
    switch scenarioEntry.tag
        case 'measurement_plus_gp'
            opts.uncertaintyMode='measurement_plus_gp';
            observation=heldout;
        case 'gp_only'
            opts.uncertaintyMode='gp_only';
            opts.measurementCV=0;
            observation=heldout;
        case 'gp_self_det'
            opts.uncertaintyMode='numerical_floor_only';
            opts.measurementCV=0;
            [selfMean,~]=surrogates.evaluate(gp,truth,'gp');
            observation=reshape(selfMean,1,[]);
            assert(numel(observation)==6&&all(isfinite(observation)), ...
                'inversion:run_cell:SelfObservation', ...
                'The GP self-consistency observation must have six finite outputs.');
        case 'gp_mean_det'
            % The likelihood of gp_self_det (the GP mean, the numerical
            % floor only) on the held-out COMSOL observation of
            % measurement_plus_gp and gp_only (the GP-mean inversion, A.13).
            opts.uncertaintyMode='numerical_floor_only';
            opts.measurementCV=0;
            observation=heldout;
        otherwise
            error('inversion:run_cell:Scenario','Unsupported scenario.');
    end

    previousRng=rng;
    restoreRng=onCleanup(@()rng(previousRng));
    rng(seed,'twister');
    try
        result=inversion.bayes_invert(gp,observation,P,requestCfg,opts);
    catch exception
        % A sampler/UQLab failure is scientific evidence about this request,
        % not a failure of the whole campaign. Give the reliability
        % controller one precise identifier it can record. Errors outside
        % this block (input and persistence errors) stop the cell.
        wrapped=MException('inversion:run_cell:SamplerExecutionFailure', ...
            '%s request failed at %d steps: %s',sampler,stepCount, ...
            exception.message);
        wrapped=addCause(wrapped,exception);
        throw(wrapped);
    end
    result.directSamplerSettings=samplerSettings;
    result.directSeedRecord=seedRecord;
    health=result.singleAnalysisHealth;
    inversion.save_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount,seed,result, ...
        truth,observation,health);
    [posterior,savedStatus]=inversion.load_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    assert(savedStatus.valid,'inversion:run_cell:SavedArtifact', ...
        'The request just saved below %s did not load: %s', ...
        savedStatus.paths.replicateRoot,savedStatus.reason);
    execution=execution_from_artifact(posterior,savedStatus,seedRecord, ...
        samplerSettings,'executed');
end

function execution=execution_from_artifact(artifact,status,seedRecord, ...
        samplerSettings,state)
    execution=struct( ...
        'schemaVersion','direct_mcmc_cell_execution_v1', ...
        'state',state, ...
        'succeeded',true, ...
        'request',artifact.request, ...
        'sampler',artifact.request.sampler, ...
        'replicateID',artifact.request.replicateID, ...
        'stepCount',artifact.request.stepCount, ...
        'seed',artifact.request.seed, ...
        'seedRecord',seedRecord, ...
        'samplerSettings',samplerSettings, ...
        'sampleArray',artifact.sampleArray, ...
        'drawsPhysical',artifact.drawsPhysical, ...
        'health',artifact.health, ...
        'artifact',artifact, ...
        'paths',status.paths, ...
        'samplesPooled',false, ...
        'failure',struct([]));
end

function value=case_field(source,names)
    assert(isstruct(source)&&isscalar(source), ...
        'inversion:run_cell:Cell','CELL must be a scalar struct.');
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
    error('inversion:run_cell:CellField','CELL is missing one of: %s.', ...
        strjoin(names,', '));
end
