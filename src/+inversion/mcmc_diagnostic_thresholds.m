function thresholds = mcmc_diagnostic_thresholds(cfg)
%MCMC_DIAGNOSTIC_THRESHOLDS The thresholds of the MCMC health checks and warnings.
%   THRESHOLDS = inversion.mcmc_diagnostic_thresholds(CFG) returns the
%   configured thresholds (CFG.mcmcDiagnostics.v2): the hard gates of the
%   structural health and of the replicate agreement (normalized
%   Wasserstein distance, 2.5%/97.5% quantile differences, frozen movement,
%   duplicates) and the warning thresholds (R-hat, ESS, correlation
%   differences), after checking that they satisfy the policy.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'mcmcDiagnostics')&& ...
        isfield(cfg.mcmcDiagnostics,'v2'), ...
        'inversion:mcmc_diagnostic_thresholds:Configuration', ...
        'cfg.mcmcDiagnostics.v2 is required.');
    thresholds=cfg.mcmcDiagnostics.v2;
    required={'maxRankSplitRhat','minBulkESS','minTailESS', ...
        'maxRelativeSdMCSE','maxMedianRangeDifference', ...
        'maxQuantileRangeDifference','maxNormalizedWasserstein', ...
        'correlationDifferenceWarning','minIndependentReplicates', ...
        'frozenMovementFraction','minimumUniqueStates', ...
        'duplicateSampleTolerance','maxDuplicateFraction'};
    assert(all(isfield(thresholds,required)), ...
        'inversion:mcmc_diagnostic_thresholds:Fields', ...
        'The direct-MCMC diagnostic threshold configuration is incomplete.');
    values=cellfun(@(name)double(thresholds.(name)),required);
    assert(all(isfinite(values))&&all(values>=0), ...
        'inversion:mcmc_diagnostic_thresholds:Values', ...
        'All diagnostic thresholds must be finite and nonnegative.');
    assert(thresholds.maxRankSplitRhat>=1&& ...
        thresholds.minIndependentReplicates==2&& ...
        thresholds.minimumUniqueStates==2&& ...
        thresholds.maxNormalizedWasserstein<=1&& ...
        thresholds.maxQuantileRangeDifference<=1&& ...
        thresholds.correlationDifferenceWarning<=2&& ...
        thresholds.frozenMovementFraction<=1&& ...
        thresholds.maxDuplicateFraction<=1, ...
        'inversion:mcmc_diagnostic_thresholds:Policy', ...
        'The centralized thresholds violate the direct-MCMC policy contract.');
end
