function [scenario, number] = scenario_registry(tag)
%SCENARIO_REGISTRY The uncertainty scenarios of the inversion.
%   SCENARIO = inversion.scenario_registry() returns the three canonical
%   scenarios: measurement_plus_gp (held-out COMSOL observation; measurement
%   and GP uncertainty; the primary scenario), gp_only (held-out observation;
%   GP uncertainty only) and gp_self_det (the GP mean as observation;
%   numerical floor only: a self-consistency diagnostic). SCENARIO =
%   inversion.scenario_registry(TAG) returns the one with the tag TAG, also
%   the side scenario gp_mean_det of the fixed route's GP-mean inversion
%   (settings A.13; not a scenario of the canonical grid): the held-out
%   COMSOL observation, the GP mean as the forward model and the numerical
%   floor only, the likelihood of gp_self_det with the observations of
%   measurement_plus_gp and gp_only. Each has its label, observation source,
%   uncertainty mode, claim scope, likelihood and certification class.
%   [SCENARIO, NUMBER] also returns the scenario's number: its position in
%   the canonical order, then the side scenarios after them (gp_mean_det 4),
%   the number of the seed rules (seeds.mcmc).
%   Side effects: none.

    tags = {'measurement_plus_gp','gp_only','gp_self_det','gp_mean_det'};
    labels = {'Measurement + GP uncertainty','GP uncertainty only', ...
        'Deterministic GP self-consistency','GP mean, COMSOL data'};
    observationSources = {'heldout_comsol','heldout_comsol','gp_mean','heldout_comsol'};
    uncertaintyModes = {'measurement_plus_gp','gp_only','numerical_floor_only', ...
        'numerical_floor_only'};
    measurementNoise = [true false false false];
    gpUncertainty = [true true false false];
    primary = [true false false false];
    claimScopes = {'PRIMARY_REALISTIC', ...
        'STRUCTURAL_NO_MEASUREMENT_NOISE', ...
        'NUMERICAL_SELF_CONSISTENCY_DIAGNOSTIC', ...
        'GP_MEAN_FORWARD_MODEL_ON_COMSOL_DATA_DIAGNOSTIC'};
    likelihoods = { ...
        'measurement_plus_tempered_emulator_diagonal_direct_v2', ...
        'tempered_emulator_diagonal_only_direct_v2', ...
        'gp_self_det_gp_mean_floor_direct_v1', ...
        'gp_mean_det_comsol_observation_floor_direct_v1'};
    certifications = {'real_certified', ...
        'real_certified_structural_diagnostic', ...
        'real_certified_self_consistency_diagnostic', ...
        'real_certified_gp_mean_diagnostic'};
    canonicalCount = 3;

    template = struct('tag','','label','','observationSource','', ...
        'uncertaintyMode','','includesMeasurementNoise',false, ...
        'includesGPUncertainty',false,'includesNumericalFloor',true, ...
        'primaryScientificScenario',false,'claimScope','', ...
        'likelihood','','certification','');
    scenarios = repmat(template,1,numel(tags));
    for i = 1:numel(tags)
        scenarios(i) = struct( ...
            'tag',tags{i}, ...
            'label',labels{i}, ...
            'observationSource',observationSources{i}, ...
            'uncertaintyMode',uncertaintyModes{i}, ...
            'includesMeasurementNoise',measurementNoise(i), ...
            'includesGPUncertainty',gpUncertainty(i), ...
            'includesNumericalFloor',true, ...
            'primaryScientificScenario',primary(i), ...
            'claimScope',claimScopes{i}, ...
            'likelihood',likelihoods{i}, ...
            'certification',certifications{i});
    end

    if nargin<1 || isempty(tag)
        scenario = scenarios(1:canonicalCount);
        number = 1:canonicalCount;
        return;
    end
    tag = char(string(tag));
    hit = find(strcmp({scenarios.tag},tag));
    assert(isscalar(hit),'inversion:scenario_registry:UnknownScenario', ...
        'Unknown active inversion scenario "%s".',tag);
    scenario = scenarios(hit);
    number = hit;
end
