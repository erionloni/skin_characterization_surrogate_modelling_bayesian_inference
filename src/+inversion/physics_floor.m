function value = physics_floor(cfg)
%PHYSICS_FLOOR Denominator floor of the physics-guided full-rank transform.
%   VALUE = inversion.physics_floor(CFG) returns
%   CFG.physicsGuidedFullRankSix.denominatorFloor after checking that CFG
%   configures the canonical transform
%   (physics_guided_full_rank_six_full_delta_cov_v1). The observation
%   transform (inversion.bayes_invert) and the likelihood
%   (inversion.gp_log_likelihood) use the same floor.
%   Side effects: none.
    assert(isfield(cfg,'physicsGuidedFullRankSix')&& ...
        isfield(cfg.physicsGuidedFullRankSix,'denominatorFloor')&& ...
        isfield(cfg.physicsGuidedFullRankSix,'transformVersion')&& ...
        strcmp(cfg.physicsGuidedFullRankSix.transformVersion, ...
        'physics_guided_full_rank_six_full_delta_cov_v1'), ...
        'inversion:physics_floor:PhysicsTransformConfiguration', ...
        'The canonical physics-guided full-rank transform is not configured.');
    value=double(cfg.physicsGuidedFullRankSix.denominatorFloor);
end
