function [execution,P] = run_conditional_request( ...
        cellRecord,gp,cfg,condition,varargin)
%RUN_CONDITIONAL_REQUEST Execute one unsaved reduced-parameter MCMC request.
%   [EXECUTION, P] = inversion.run_conditional_request(CELLRECORD, GP, CFG,
%   CONDITION, ...) runs one request of the conditional cell CELLRECORD, with
%   the parameters that CONDITION fixes held at the truth, and returns the
%   execution (request, seed, sampler settings, the draws in the free and in
%   the canonical coordinates, health) and the reduced parameter space P
%   (inversion.conditional_parameter_space).
%   Options (name-value): 'Sampler' ('AIES', the default, or 'AM'),
%   'ReplicateID' (default 1), 'StepCount' (default CFG.mcmc.levels(1)).
%   Persistence, escalation, and supplementary-grid orchestration deliberately
%   remain outside this core adapter. The returned sampler state is reduced;
%   DRAWSCANONICAL is reconstructed solely for scientific consumption.
%   Side effects: none on files (the caller saves the request); creates the
%   request's UQLab inversion analysis (inversion.bayes_invert); the random
%   number generator's state is restored afterwards.
%   Computation: minutes to an hour (one MCMC request).

    parser=inputParser;
    parser.FunctionName='inversion.run_conditional_request';
    addParameter(parser,'Sampler','AIES',@(x)ischar(x)|| ...
        (isstring(x)&&isscalar(x)));
    addParameter(parser,'ReplicateID',1,@(x)isnumeric(x)&&isscalar(x)&& ...
        isfinite(x)&&x==fix(x)&&x>=1);
    addParameter(parser,'StepCount',cfg.mcmc.levels(1), ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x==fix(x));
    parse(parser,varargin{:});
    assert(strcmp(cfg.dataMode,'real'), ...
        'inversion:run_conditional_request:Route', ...
        'Conditional inversion is defined only for the real route.');

    caseID=case_field(cellRecord,{'caseID','case_id'});
    scenario=char(string(case_field(cellRecord,{'scenario','likelihoodMode'})));
    designName=char(string(case_field(cellRecord, ...
        {'design','outputDesign','design_name'})));
    truth=reshape(double(case_field(cellRecord,{'truth','thetaTrue'})),1,[]);
    heldout=reshape(double(case_field(cellRecord, ...
        {'heldout_response','heldoutResponse','observation'})),1,[]);
    assert(numel(truth)==4&&numel(heldout)==6&& ...
        all(isfinite(truth))&&all(isfinite(heldout)), ...
        'inversion:run_conditional_request:CaseData', ...
        'Canonical four-parameter truth and six-output observation are required.');
    assert(strcmp(designName,'all_six')&& ...
        ismember(scenario,{'gp_only','measurement_plus_gp'}), ...
        'inversion:run_conditional_request:StudyScope', ...
        ['The supplementary conditional study is restricted to all_six under ' ...
         'gp_only or measurement_plus_gp.']);

    P=inversion.conditional_parameter_space(cfg,condition,truth);
    adapter=P.adapter;
    conditionEntry=inversion.conditional_inversion_conditions(cfg,adapter.conditionTag);
    assert(conditionEntry.supplementaryExecution&& ...
        ismember(scenario,conditionEntry.scheduledScenarios), ...
        'inversion:run_conditional_request:ConditionScope', ...
        'Condition %s is not run in the scenario %s (the campaign of the settings, A.9).', ...
        adapter.conditionTag,scenario);
    sampler=upper(char(string(parser.Results.Sampler)));
    if strcmp(sampler,'ADAPTIVE_METROPOLIS'),sampler='AM';end
    replicateID=double(parser.Results.ReplicateID);
    stepCount=double(parser.Results.StepCount);
    [requestCfg,samplerSettings]=inversion.sampler_request_config( ...
        cfg,sampler,stepCount);
    [seed,seedRecord]=seeds.mcmc(cfg,caseID,scenario, ...
        designName,adapter.fixedParameterIndices,sampler,replicateID,stepCount);
    scenarioEntry=inversion.scenario_registry(scenario);
    design=inversion.design_registry(designName);
    cellID=sprintf('case_%d|%s|%s|condition_%s',double(caseID), ...
        scenario,designName,adapter.conditionTag);
    request=struct( ...
        'schemaVersion','conditional_mcmc_request_v1', ...
        'cellID',cellID, ...
        'caseID',double(caseID), ...
        'scenario',scenarioEntry.tag, ...
        'design',design.name, ...
        'conditionCode',adapter.conditionCode, ...
        'conditionTag',adapter.conditionTag, ...
        'freeParameterIndices',adapter.freeParameterIndices, ...
        'freeParameterNames',{adapter.freeParameterNames}, ...
        'fixedParameterIndices',adapter.fixedParameterIndices, ...
        'fixedParameterValues',adapter.fixedParameterValues, ...
        'fixedValueSemantics',adapter.fixedValueSemantics, ...
        'samplerDimension',adapter.samplerDimension, ...
        'canonicalDimension',adapter.canonicalDimension, ...
        'sampler',sampler, ...
        'replicateID',replicateID, ...
        'stepCount',stepCount, ...
        'seed',seed, ...
        'runMode','fresh_total_length', ...
        'loadParentState',false, ...
        'appendParentSamples',false, ...
        'poolSamples',false);

    opts=struct( ...
        'outputs',design.sourceOutputIndices, ...
        'observationTransform',design.observationTransform, ...
        'thetaTrue',truth, ...
        'parameterAdapter',adapter, ...
        'keepAnalysis',false, ...
        'scenarioTag',scenarioEntry.tag, ...
        'observationSource',scenarioEntry.observationSource, ...
        'uncertaintyMode',scenarioEntry.uncertaintyMode, ...
        'measurementCV',cfg.meas_cv, ...
        'emulatorErrorCalibrationVersion', ...
            cfg.inversion.emulatorErrorCalibrationVersion, ...
        'replicateID',replicateID, ...
        'continuationStage',sprintf('fresh_total_%d',stepCount), ...
        'initialization',requestCfg.mcmc.initialization, ...
        'initializationParameters',struct(), ...
        'caseID',caseID, ...
        'seed',seed);
    switch scenarioEntry.tag
        case 'measurement_plus_gp'
            observation=heldout;
        case 'gp_only'
            opts.measurementCV=0;
            observation=heldout;
        otherwise
            error('inversion:run_conditional_request:Scenario', ...
                'Unsupported conditional-inversion scenario.');
    end

    previousRng=rng;restoreRng=onCleanup(@()rng(previousRng));
    rng(seed,'twister');
    try
        result=inversion.bayes_invert(gp,observation,P,requestCfg,opts);
    catch exception
        wrapped=MException( ...
            'inversion:run_conditional_request:SamplerExecutionFailure', ...
            '%s conditional request failed at %d steps: %s', ...
            sampler,stepCount,exception.message);
        wrapped=addCause(wrapped,exception);
        throw(wrapped);
    end
    result.directSamplerSettings=samplerSettings;
    result.directSeedRecord=seedRecord;
    execution=struct( ...
        'schemaVersion','conditional_mcmc_request_execution_v1', ...
        'state','executed_unsaved', ...
        'succeeded',true, ...
        'request',request, ...
        'sampler',sampler, ...
        'replicateID',replicateID, ...
        'stepCount',stepCount, ...
        'seed',seed, ...
        'seedRecord',seedRecord, ...
        'samplerSettings',samplerSettings, ...
        'parameterAdapter',adapter, ...
        'sampleArray',result.sampleArray, ...
        'drawsFree',result.postSample, ...
        'drawsCanonical',result.canonicalPostSample, ...
        'health',result.singleAnalysisHealth, ...
        'result',result, ...
        'samplesPooled',false, ...
        'artifactPersistenceOwnedByCaller',true, ...
        'failure',struct([]));
end

function value=case_field(source,names)
    assert(isstruct(source)&&isscalar(source), ...
        'inversion:run_conditional_request:Cell', ...
        'CELLRECORD must be a scalar struct.');
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
    error('inversion:run_conditional_request:CellField', ...
        'CELLRECORD is missing one of: %s.',strjoin(names,', '));
end
