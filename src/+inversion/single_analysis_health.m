function health = single_analysis_health(samples,bounds,cfg,sampler)
%SINGLE_ANALYSIS_HEALTH Sampler-aware health for one UQLab analysis.
%   HEALTH = inversion.single_analysis_health(SAMPLES, BOUNDS, CFG, SAMPLER)
%   checks the retained SAMPLES (iteration x parameter x sampler state) of one
%   analysis of SAMPLER ('AIES' or 'AM') against the parameter BOUNDS (M-by-2)
%   and the thresholds of CFG (inversion.mcmc_diagnostic_thresholds).
%   AIES walkers are interacting and are never treated as independent
%   chains. Consequently, a single AIES analysis receives structural
%   movement/bounds/duplication checks but no R-hat/ESS/MCSE certification.
%   Its PASS field means absence of sampler/execution pathology; posterior
%   reproducibility is assessed only across two independent ensembles. One AM
%   analysis uses its genuinely independent chains for the strict internal
%   R-hat, ESS, and MCSE gates. In either case this function never certifies a
%   posterior cell by itself.
%   Side effects: none.

    validate_samples(samples,bounds);
    thresholds=inversion.mcmc_diagnostic_thresholds(cfg);
    semantics=utils.sampler_semantics(sampler);
    sampler=semantics.sampler;
    duplicates=inversion.duplicate_state_detector( ...
        {samples},bounds,thresholds.duplicateSampleTolerance);
    reasons={};
    lower=reshape(bounds(:,1),1,[],1);
    upper=reshape(bounds(:,2),1,[],1);
    if any(samples<lower|samples>upper,'all')
        reasons{end+1}= ...
            'one or more retained posterior samples are outside prior bounds';
    end

    switch semantics.stateSemantics
        case 'interacting_walkers'
            assert(size(samples,3)>=2, ...
                'inversion:single_analysis_health:AIESStateCount', ...
                'AIES requires at least two interacting walkers.');
            movement=inversion.movement(samples,bounds,cfg);
            tooFewUnique=movement.uniqueStateCount< ...
                thresholds.minimumUniqueStates;
            if any(tooFewUnique)
                reasons{end+1}='one or more AIES walkers are frozen';
            end
            if movement.anyLowMovement
                reasons{end+1}= ...
                    'one or more AIES walkers have insufficient movement';
            end
            if duplicates.anyDuplicate
                reasons{end+1}='duplicated AIES walker trajectory detected';
            end
            rankSplitRhat=nan(1,size(samples,2));
            bulkESS=nan(1,size(samples,2));
            tailESS=nan(1,size(samples,2));
            relativeSdMCSE=nan(1,size(samples,2));
            convergenceApplicable=false;
            passScope= ...
                'single_AIES_structural_health_for_replicate_reproducibility_v2';
            independentStateCount=0;
        case 'independent_chains'
            chains=inversion.conventional_chains({samples});
            movement=inversion.chain_movement(samples,bounds,cfg);
            tooFewUnique=movement.uniqueStateCount< ...
                thresholds.minimumUniqueStates;
            rankSplitRhat=inversion.rhat_rank_split(chains.combinedChains);
            [bulkESS,tailESS]=inversion.ess_bulk_tail(chains.combinedChains);
            mcse=inversion.mcse_chains(chains.combinedChains,bulkESS);
            relativeSdMCSE=mcse.relativeSD;
            if chains.nIndependentChains<2
                reasons{end+1}='fewer than two independent AM chains';
            end
            if any(rankSplitRhat>thresholds.maxRankSplitRhat| ...
                    ~isfinite(rankSplitRhat))
                reasons{end+1}='rank-normalized split R-hat failed';
            end
            if any(bulkESS<thresholds.minBulkESS|~isfinite(bulkESS))
                reasons{end+1}='bulk ESS failed';
            end
            if any(tailESS<thresholds.minTailESS|~isfinite(tailESS))
                reasons{end+1}='tail ESS failed';
            end
            if any(relativeSdMCSE>thresholds.maxRelativeSdMCSE| ...
                    ~isfinite(relativeSdMCSE))
                reasons{end+1}='relative MCSE of posterior SD failed';
            end
            if any(tooFewUnique)
                reasons{end+1}= ...
                    'one or more independent AM chains are frozen';
            end
            if movement.anyLowMovement
                reasons{end+1}= ...
                    'one or more independent AM chains have insufficient movement';
            end
            if duplicates.anyDuplicate
                reasons{end+1}='duplicated AM chain trajectory detected';
            end
            convergenceApplicable=true;
            passScope='single_AM_independent_chain_health_v1';
            independentStateCount=chains.nIndependentChains;
        otherwise
            error('inversion:single_analysis_health:Sampler', ...
                'Unsupported sampler semantics "%s".',semantics.stateSemantics);
    end

    health=struct( ...
        'schemaVersion','direct_mcmc_single_analysis_health_v1', ...
        'sampler',sampler, ...
        'stateSemantics',semantics.stateSemantics, ...
        'thirdDimensionSemantics',semantics.thirdDimension, ...
        'walkersTreatedAsIndependentChains',false, ...
        'retainedIterations',size(samples,1), ...
        'parameterCount',size(samples,2), ...
        'samplerStateCount',size(samples,3), ...
        'independentStateCount',independentStateCount, ...
        'convergenceDiagnosticsApplicable',convergenceApplicable, ...
        'rankSplitRhat',rankSplitRhat, ...
        'bulkESS',bulkESS, ...
        'tailESS',tailESS, ...
        'relativeSdMCSE',relativeSdMCSE, ...
        'movement',movement, ...
        'duplicates',duplicates, ...
        'thresholds',thresholds, ...
        'pass',isempty(reasons), ...
        'healthy',isempty(reasons), ...
        'cellCertified',false, ...
        'passScope',passScope, ...
        'reasons',{unique(reasons,'stable')});
end

function validate_samples(samples,bounds)
    assert(isnumeric(samples)&&size(samples,1)>=4&&size(samples,2)>=1&& ...
        size(samples,3)>=1&&all(isfinite(samples),'all'), ...
        'inversion:single_analysis_health:Samples', ...
        'Samples must be a finite retained-iteration x parameter x state array.');
    assert(isnumeric(bounds)&&size(bounds,1)==size(samples,2)&& ...
        size(bounds,2)==2&&all(isfinite(bounds),'all')&& ...
        all(bounds(:,2)>bounds(:,1)), ...
        'inversion:single_analysis_health:Bounds', ...
        'Bounds must be a finite parameter x 2 matrix with positive widths.');
end
