function [artifact,status] = load_conditional_certified_posterior(cfg,cellRecord)
%LOAD_CONDITIONAL_CERTIFIED_POSTERIOR The certified provider of one conditional cell, or none.
%   [ARTIFACT,STATUS] = inversion.load_conditional_certified_posterior(CFG,CELL)
%   reads the pointer of a conditional cell (conditions B-D;
%   inversion.save_conditional_certified_posterior) and its provider request.
%   Only a certification by the agreement of two independent AIES
%   replicates, with the unpooled replicate 1 as provider, is consumed.
%   ARTIFACT.drawsFree contains only inferred coordinates. The N-by-4
%   drawsCanonicalCoordinates field restores fixed truth coordinates solely for
%   reconstruction/alignment; parameterRoles prevents treating them as inferred.
%   STATUS.state is 'unresolved' (no pointer), 'certified_loaded' or
%   'invalid_certification' (with the reason). Condition A is the canonical
%   all_six cell: load it with inversion.load_certified_posterior.
%   The function does not throw.
%   Side effects: none.

    artifact=struct([]);
    status=struct('state','unresolved','loaded',false,'valid',false, ...
        'certified',false,'reason','no certified conditional posterior', ...
        'errorIdentifier','','paths',struct([]));
    try
        condition=inversion.conditional_inversion_conditions(cfg,pick(cellRecord, ...
            {'conditionCode','conditionID','conditionTag'}));
        assert(~condition.canonicalReference, ...
            'inversion:load_conditional_certified_posterior:CanonicalBaseline', ...
            'Condition A must be loaded from the canonical inversion API.');
        paths=inversion.conditional_posterior_artifact_paths( ...
            cfg,cellRecord,'AIES',1,cfg.mcmc.levels(1));
        status.paths=paths;
        if ~isfile(paths.certifiedPosteriorPath),return;end
        certification=jsondecode(fileread(paths.certifiedPosteriorPath));
        required={'certified','downstreamUsePermitted', ...
            'provider','certificationMechanism','reliabilityDecision', ...
            'parameterRoles','freeParameterIndices','fixedParameterIndices', ...
            'fixedParameterValues','samplesPooledAcrossSamplers', ...
            'samplesPooledAcrossReplicates','samplesPooledAcrossLevels'};
        missing=required(~isfield(certification,required));
        assert(isempty(missing), ...
            'inversion:load_conditional_certified_posterior:Certification', ...
            'The conditional certification pointer %s lacks: %s.', ...
            paths.certifiedPosteriorPath,strjoin(missing,', '));
        provider=certification.provider;
        assert(logical(certification.certified)&& ...
            logical(certification.downstreamUsePermitted)&& ...
            ~logical(certification.samplesPooledAcrossSamplers)&& ...
            ~logical(certification.samplesPooledAcrossReplicates)&& ...
            ~logical(certification.samplesPooledAcrossLevels)&& ...
            strcmp(char(string(certification.certificationMechanism)), ...
                'CERTIFIED_AIES_REPLICATE_AGREEMENT')&& ...
            strcmp(char(string(provider.sampler)),'AIES')&& ...
            double(provider.replicateID)==1, ...
            'inversion:load_conditional_certified_posterior:Certification', ...
            ['%s is not a certification by the agreement of two independent ' ...
             'AIES replicates with the unpooled replicate 1 as provider.'], ...
            paths.certifiedPosteriorPath);
        [posterior,posteriorStatus]=inversion.load_conditional_posterior_artifact( ...
            cfg,cellRecord,'AIES',1,double(provider.stepCount));
        assert(posteriorStatus.valid, ...
            'inversion:load_conditional_certified_posterior:Provider', ...
            'The certified provider of %s did not load: %s',paths.cellID, ...
            posteriorStatus.reason);
        artifact=posterior;artifact.truth=posterior.truthMetadata.truth;
        artifact.observation=posterior.observationMetadata.observation;
        artifact.certification=certification;
        artifact.certificationPath=paths.certifiedPosteriorPath;
        status=posteriorStatus;status.state='certified_loaded';
        status.loaded=true;status.valid=true;status.certified=true;status.reason='';
    catch exception
        artifact=struct([]);status.state='invalid_certification';
        status.loaded=false;status.valid=false;status.certified=false;
        status.reason=exception.message;status.errorIdentifier=exception.identifier;
    end
end

function value=pick(source,names)
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
    error('inversion:load_conditional_certified_posterior:CellField', ...
        'Cell record lacks its condition.');
end
