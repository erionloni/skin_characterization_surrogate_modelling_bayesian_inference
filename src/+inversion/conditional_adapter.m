function adapter = conditional_adapter(cfg,condition,thetaTruth)
%CONDITIONAL_ADAPTER Canonical reduced-to-four-parameter inversion mapping.
%   ADAPTER = inversion.conditional_adapter(CFG, CONDITION, THETATRUTH)
%   defines the mapping of one condition of the conditional inversion
%   (CONDITION, a condition of inversion.conditional_inversion_conditions
%   or its code, id or tag): its free and fixed parameter indices, e.g. in
%   the thesis
%
%     thickness_fixed             free [1 2 3], fixed 4
%     m3f_fixed                   free [2 3 4], fixed 1
%     m3f_and_thickness_fixed     free [2 3],   fixed [1 4]
%     m3e_fixed                   free [1 3 4], fixed 2
%     log10k0_fixed               free [1 2 4], fixed 3
%
%   Fixed values are always taken exactly from the supplied canonical truth.
%   The sampler therefore operates only in the free coordinates, while
%   EXPAND_CONDITIONAL_PARAMETERS reconstructs the canonical four-vector used
%   by the existing pressure-trained GP likelihood.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&strcmp(cfg.dataMode,'real')&& ...
        isfield(cfg,'paramNames')&&isfield(cfg,'paramUnits')&& ...
        isfield(cfg,'paramBounds'), ...
        'inversion:conditional_adapter:Configuration', ...
        'Conditional inversion is defined only for the four-parameter real route.');
    names=cellstr(string(cfg.paramNames(:))).';
    units=cellstr(string(cfg.paramUnits(:))).';
    bounds=double(cfg.paramBounds);
    assert(numel(names)==4&&numel(units)==4&&isequal(size(bounds),[4 2])&& ...
        all(isfinite(bounds),'all')&&all(bounds(:,2)>bounds(:,1)), ...
        'inversion:conditional_adapter:CanonicalSpace', ...
        'The canonical real-route parameter space must contain four valid bounds.');

    [tag,code,free,fixed]=canonical_condition(cfg,condition);
    truth=reshape(double(thetaTruth),1,[]);
    assert(numel(truth)==4&&all(isfinite(truth))&& ...
        all(truth>=bounds(:,1).'&truth<=bounds(:,2).'), ...
        'inversion:conditional_adapter:Truth', ...
        'thetaTruth must be a finite canonical four-vector inside prior bounds.');

    adapter=struct( ...
        'schemaVersion','conditional_parameter_adapter_v1', ...
        'conditionCode',code, ...
        'conditionTag',tag, ...
        'fixedValueSemantics','oracle_fixed_exactly_to_case_truth', ...
        'canonicalParameterNames',{names}, ...
        'canonicalParameterUnits',{units}, ...
        'canonicalBounds',bounds, ...
        'canonicalDimension',4, ...
        'freeParameterIndices',free, ...
        'fixedParameterIndices',fixed, ...
        'freeParameterNames',{names(free)}, ...
        'freeParameterUnits',{units(free)}, ...
        'freeBounds',bounds(free,:), ...
        'fixedParameterNames',{names(fixed)}, ...
        'fixedParameterValues',truth(fixed), ...
        'canonicalTruth',truth, ...
        'freeTruth',truth(free), ...
        'samplerDimension',numel(free), ...
        'expansionVersion','free_state_to_canonical_four_v1');
end

function [tag,code,free,fixed]=canonical_condition(cfg,value)
%CANONICAL_CONDITION The tag, code and free and fixed indices of a condition of the settings (A.9).
%   A condition passed as a struct must agree with the settings' condition
%   of its tag.
    if ischar(value)||(isstring(value)&&isscalar(value))
        entry=inversion.conditional_inversion_conditions(cfg,char(string(value)));
        value=struct('tag',entry.tag);
    end
    assert(isstruct(value)&&isscalar(value)&&isfield(value,'tag'), ...
        'inversion:conditional_adapter:Condition', ...
        'CONDITION must be a tag or a scalar struct containing tag.');
    tag=lower(strtrim(char(string(value.tag))));
    entry=inversion.conditional_inversion_conditions(cfg,tag);
    assert(~entry.canonicalReference, ...
        'inversion:conditional_adapter:ConditionTag', ...
        'Condition %s fixes nothing: it is the canonical cell, not a conditional inversion.',tag);
    code=entry.code;free=entry.freeParameterIndices;fixed=entry.fixedParameterIndices;
    assert(~isempty(free)&&isempty(intersect(free,fixed))&& ...
        isequal(sort([free fixed]),1:numel(cfg.paramNames)), ...
        'inversion:conditional_adapter:Indices', ...
        'Condition %s must split the four parameters into free and fixed ones.',tag);
    suppliedFree=[];suppliedFixed=[];suppliedCode='';
    if isfield(value,'freeParameterIndices')
        suppliedFree=reshape(double(value.freeParameterIndices),1,[]);
    elseif isfield(value,'free_parameter_indices')
        suppliedFree=reshape(double(value.free_parameter_indices),1,[]);
    end
    if isfield(value,'fixedParameterIndices')
        suppliedFixed=reshape(double(value.fixedParameterIndices),1,[]);
    elseif isfield(value,'fixed_parameter_indices')
        suppliedFixed=reshape(double(value.fixed_parameter_indices),1,[]);
    end
    if isfield(value,'code'),suppliedCode=char(string(value.code));end
    assert(isempty(suppliedFree)||isequal(suppliedFree,free), ...
        'inversion:conditional_adapter:FreeIndices', ...
        'Condition %s must use free parameter indices [%s].',tag,num2str(free));
    assert(isempty(suppliedFixed)||isequal(suppliedFixed,fixed), ...
        'inversion:conditional_adapter:FixedIndices', ...
        'Condition %s must use fixed parameter indices [%s].',tag,num2str(fixed));
    assert(isempty(suppliedCode)||strcmp(strtrim(suppliedCode),code), ...
        'inversion:conditional_adapter:ConditionCode', ...
        'Condition tag %s must use condition code %s.',tag,code);
end
