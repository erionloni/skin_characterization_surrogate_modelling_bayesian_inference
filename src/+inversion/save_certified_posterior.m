function certification = save_certified_posterior(cfg,cellRecord,decision)
%SAVE_CERTIFIED_POSTERIOR Publish a pointer to the certified provider of one cell.
%   CERTIFICATION = inversion.save_certified_posterior(CFG,CELL,DECISION)
%   records that the cell is certified: DECISION (the reliability
%   controller's, inversion.run_reliability_cell) must be a certification by
%   the agreement of two independent AIES replicates, and its provider the
%   predeclared AIES replicate 1, unpooled. The provider remains one
%   sampler/replicate request; samples from samplers or independent
%   replicates are never pooled.
%   Writes certified_posterior.json (the pointer: provider, relative path of
%   its posterior and the decision) and reliability_<steps>.json (the
%   decision) in the cell folder; CERTIFICATION is the pointer.
%   Side effects: writes the two files, replacing earlier versions.

    assert(isstruct(decision)&&isscalar(decision)&& ...
        all(isfield(decision,{'certified','downstreamUsePermitted', ...
        'provider','stepCount','certificationMechanism'}))&& ...
        logical(decision.certified)&& ...
        logical(decision.downstreamUsePermitted), ...
        'inversion:save_certified_posterior:Decision', ...
        'A certified reliability decision is required.');
    certificationMechanism=char(string(decision.certificationMechanism));
    assert(strcmp(certificationMechanism, ...
        'CERTIFIED_AIES_REPLICATE_AGREEMENT'), ...
        'inversion:save_certified_posterior:CertificationMechanism', ...
        ['Production certification requires two independent AIES ' ...
         'replicates under the posterior-reproducibility policy.']);
    provider=decision.provider;
    assert(isstruct(provider)&&isscalar(provider)&& ...
        all(isfield(provider,{'sampler','replicateID','stepCount', ...
        'samplesPooled'}))&&~logical(provider.samplesPooled)&& ...
        strcmpi(char(string(provider.sampler)),'AIES')&& ...
        double(provider.replicateID)==1, ...
        'inversion:save_certified_posterior:Provider', ...
        ['The decision must identify unpooled AIES replicate 1 as the ' ...
         'predeclared production provider.']);
    [~,status]=inversion.load_posterior_artifact( ...
        cfg,cellRecord,provider.sampler,provider.replicateID, ...
        provider.stepCount);
    assert(status.valid, ...
        'inversion:save_certified_posterior:ProviderArtifact', ...
        'The provider request of %s did not load: %s',status.paths.cellID, ...
        status.reason);
    paths=status.paths;
    certification=struct( ...
        'schemaVersion','direct_mcmc_certified_posterior_pointer_v4', ...
        'certified',true, ...
        'downstreamUsePermitted',true, ...
        'cellID',paths.cellID, ...
        'caseID',paths.caseID, ...
        'scenario',paths.scenario, ...
        'design',paths.design, ...
        'provider',provider, ...
        'certificationMechanism',certificationMechanism, ...
        'providerSelectionUsesDiagnosticRanking',false, ...
        'posteriorRelativePath',relative_inside(paths.posteriorPath,paths.cellRoot), ...
        'physicalRetainedDrawsAvailable',true, ...
        'samplesPooledAcrossSamplers',false, ...
        'samplesPooledAcrossReplicates',false, ...
        'reliabilityDecision',decision);
    utils.atomic_write_json(paths.certifiedPosteriorPath,certification, ...
        'AllowReplace',true);
    utils.atomic_write_json(paths.reliabilityPath,decision,'AllowReplace',true);
end

function relative=relative_inside(pathValue,root)
    pathValue=utils.absolute_path(pathValue);
    root=utils.absolute_path(root);
    relative=strrep(pathValue(numel(root)+2:end),'\','/');
end
