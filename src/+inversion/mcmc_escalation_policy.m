function policy = mcmc_escalation_policy(cfg,currentSteps,samplers,replicateIDs)
%MCMC_ESCALATION_POLICY Describe one fresh-total-length escalation.
%   Escalation never restores a parent sampler state and never appends or
%   pools samples. The next request uses a new deterministic seed and
%   reapplies the configured burn-in to a fresh total-length analysis.
%   POLICY = inversion.mcmc_escalation_policy(CFG, CURRENTSTEPS, SAMPLERS,
%   REPLICATEIDS) returns the next level after CURRENTSTEPS (the levels
%   are 2000 and 5000; none after the last) and one fresh request per
%   sampler and replicate at that level, with the burn-in.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'mcmc')&& ...
        all(isfield(cfg.mcmc,{'levels','continuationSemantics','burn_in'})), ...
        'inversion:mcmc_escalation_policy:Configuration', ...
        'The centralized escalation configuration is incomplete.');
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    assert(isequal(levels,[2000 5000]), ...
        'inversion:mcmc_escalation_policy:Levels', ...
        'cfg.mcmc.levels must be [2000 5000] (the two escalation levels).');
    index=find(levels==currentSteps);
    assert(isscalar(index),'inversion:mcmc_escalation_policy:CurrentLevel', ...
        'currentSteps is not a configured continuation level.');
    if nargin<3||isempty(samplers),samplers={'AIES'};end
    samplers=cellstr(string(samplers(:))).';
    samplers=cellfun(@canonical_sampler,samplers,'UniformOutput',false);
    assert(numel(unique(samplers))==numel(samplers), ...
        'inversion:mcmc_escalation_policy:Samplers', ...
        'Escalation sampler names must be unique.');
    if nargin<4||isempty(replicateIDs),replicateIDs=1;end
    replicateIDs=reshape(double(replicateIDs),1,[]);
    assert(all(isfinite(replicateIDs))&&all(replicateIDs>=1)&& ...
        all(replicateIDs==fix(replicateIDs))&& ...
        numel(unique(replicateIDs))==numel(replicateIDs), ...
        'inversion:mcmc_escalation_policy:Replicates', ...
        'Replicate IDs must be distinct positive integers.');
    maximumReached=index==numel(levels);
    if maximumReached,nextSteps=NaN;else,nextSteps=levels(index+1);end
    requests=repmat(struct('sampler','','replicateID',NaN, ...
        'stepCount',NaN,'runMode','','loadParentState',false, ...
        'appendParentSamples',false,'poolSamples',false), ...
        1,numel(samplers)*numel(replicateIDs));
    cursor=0;
    if ~maximumReached
        for s=1:numel(samplers)
            for r=1:numel(replicateIDs)
                cursor=cursor+1;
                requests(cursor)=struct( ...
                    'sampler',samplers{s}, ...
                    'replicateID',replicateIDs(r), ...
                    'stepCount',nextSteps, ...
                    'runMode','fresh_total_length', ...
                    'loadParentState',false, ...
                    'appendParentSamples',false, ...
                    'poolSamples',false);
            end
        end
    else
        requests=struct([]);
    end
    policy=struct( ...
        'schemaVersion','direct_mcmc_escalation_policy_v1', ...
        'configuredLevels',levels, ...
        'currentSteps',double(currentSteps), ...
        'nextSteps',nextSteps, ...
        'maximumReached',maximumReached, ...
        'continuationSemantics',char(string( ...
            cfg.mcmc.continuationSemantics)), ...
        'runMode','fresh_total_length_rerun', ...
        'newIndependentSeedRequired',true, ...
        'loadParentSamplerState',false, ...
        'appendParentSamples',false, ...
        'poolAcrossLevels',false, ...
        'burnInReapplied',true, ...
        'burnIn',double(cfg.mcmc.burn_in), ...
        'requests',requests);
end

function sampler=canonical_sampler(sampler)
    sampler=upper(strtrim(char(string(sampler))));
    if strcmp(sampler,'ADAPTIVE_METROPOLIS'),sampler='AM';end
    assert(ismember(sampler,{'AIES','AM'}), ...
        'inversion:mcmc_escalation_policy:Sampler', ...
        ['Only AIES production requests and explicitly configured AM ' ...
         'validation requests are supported.']);
end
