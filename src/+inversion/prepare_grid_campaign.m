function preparation = prepare_grid_campaign(cfg)
%PREPARE_GRID_CAMPAIGN Prepare the canonical inversion campaign (grid, seeds, tasks), once.
%   PREPARATION = inversion.prepare_grid_campaign(CFG) builds the grid of
%   CFG.inversion.caseIDs x 3 scenarios x 6 designs, binds every cell to its
%   case (truth and held-out observation, data.inversion_cases), takes the
%   seed of every request (seeds.mcmc: two independent AIES replicates per
%   level, all seeds distinct), and writes below
%   CFG.paths.stage04 the grid, the cell task table (cell_task_table.csv:
%   the grid index of every cell, for running cells separately), the seed
%   schedule, the MCMC policy record, the preparation (campaign_preparation.mat)
%   and its summary (campaign_preparation.json).
%   A campaign is prepared once: when the campaign folder already holds a
%   preparation, it is returned unchanged, so that further calls continue
%   the same campaign (the entry point refuses other cases or chain lengths
%   for a run's campaign, study.run).
%   This function loads no GP and runs no sampler.
%   Side effects: writes the files above when the campaign is new.

    assert(isstruct(cfg)&&isscalar(cfg)&&strcmp(cfg.dataMode,'real'), ...
        'inversion:prepare_grid_campaign:Route', ...
        'The canonical inversion campaign is defined for the fixed route only.');
    if isfield(cfg,'parallelWorkers')&&double(cfg.parallelWorkers)>0
        error('inversion:prepare_grid_campaign:ParallelNotEnabled', ...
            ['Run the inversion with ''ParallelWorkers'' 0: cells run in parallel as ' ...
             'separate MATLAB processes (''InversionCells''), not inside one.']);
    end
    assert(isfile(cfg.files.gp)&&isfile(cfg.files.dataset), ...
        'inversion:prepare_grid_campaign:Inputs', ...
        ['The inversion needs the dataset (%s) and the GP (%s): run the ' ...
         'steps ''dataset'' and ''surrogates'', or use the shipped results.'], ...
        cfg.files.dataset,cfg.files.gp);
    assert(isfield(cfg.inversion,'cohortResolved')&& ...
        logical(cfg.inversion.cohortResolved), ...
        'inversion:prepare_grid_campaign:InversionCohortUnresolved', ...
        ['The inversion cases did not resolve from the dataset %s; build ' ...
         'the configuration with that dataset (study.project_config ''DatasetFile'').'], ...
        cfg.files.dataset);
    paths=inversion.grid_campaign_support('preparation_paths',cfg);
    if isfile(paths.preparationMAT)
        preparation=inversion.grid_campaign_support('load_preparation',cfg);
        return
    end

    P=parameters.parameter_space(cfg);
    cases=data.inversion_cases(cfg,P);
    grid=inversion.build_inversion_grid(cfg,cases);
    cellRecords=inversion.grid_campaign_support('attach_cases',grid,cases);
    [seedRecords,seedScheduleTable]= ...
        inversion.grid_campaign_support('seed_schedule',cfg,grid);
    demonstrationSteps=[];
    if isfield(cfg.mcmc,'demonstrationSteps')
        demonstrationSteps=reshape(double(cfg.mcmc.demonstrationSteps),1,[]);
    end
    preparation=struct( ...
        'schemaVersion','direct_mcmc_grid_campaign_preparation_v2', ...
        'route','real','grid',grid,'cellRecords',cellRecords, ...
        'inversionCohortSelectionMode',char(string(cfg.inversion.cohortSelectionMode)), ...
        'inversionCaseIDs',reshape(double([cases.case_id]),1,[]), ...
        'levels',reshape(double(cfg.mcmc.levels),1,[]), ...
        'demonstrationSteps',demonstrationSteps, ...
        'policy',inversion.grid_campaign_support('policy_summary',cfg,grid), ...
        'seedRecords',seedRecords, ...
        'seedScheduleTable',seedScheduleTable, ...
        'taskTable',inversion.grid_campaign_support('task_table',cfg,cellRecords), ...
        'gridTable',inversion.grid_campaign_support('grid_table',grid), ...
        'paths',paths);
    inversion.grid_campaign_support('publish_preparation',preparation);
end
