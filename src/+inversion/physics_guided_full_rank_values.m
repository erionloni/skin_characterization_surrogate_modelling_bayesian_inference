function features = physics_guided_full_rank_values(outputs,denominatorFloor)
%PHYSICS_GUIDED_FULL_RANK_VALUES Vectorized invertible six-feature transform.
%   FEATURES = inversion.physics_guided_full_rank_values(OUTPUTS,
%   DENOMINATORFLOOR) returns, for the N-by-6 pressures OUTPUTS (mbar) in the
%   raw order [p1_D2 p2_D2 p3_D2 p1_D6 p2_D6 p3_D6], the N-by-6 features
%       [p3_D2,
%        p3_D2/p1_D2,
%        p1_D2-p2_D2,
%        p1_D2/p3_D6,
%        p3_D6/p1_D6,
%        p2_D6/p1_D6].
%   Every denominator must exceed DENOMINATORFLOOR (default 1e-12).
%   This is a change of representation of all six measurements. It does not
%   create additional experimental information.
%   Side effects: none.

    if nargin<2 || isempty(denominatorFloor),denominatorFloor=1e-12;end
    assert(isnumeric(outputs)&&isreal(outputs)&&size(outputs,2)==6&& ...
        all(isfinite(outputs),'all'), ...
        'inversion:physics_guided_full_rank_values:Shape', ...
        'outputs must be a finite real N-by-6 pressure matrix.');
    assert(isnumeric(denominatorFloor)&&isscalar(denominatorFloor)&& ...
        isreal(denominatorFloor)&&isfinite(denominatorFloor)&& ...
        denominatorFloor>0, ...
        'inversion:physics_guided_full_rank_values:Floor', ...
        'denominatorFloor must be a positive finite scalar.');
    denominators=outputs(:,[1 6 4 4]);
    assert(all(denominators>denominatorFloor,'all'), ...
        'inversion:physics_guided_full_rank_values:UnsafeDenominator', ...
        ['p1_D2, p3_D6, and p1_D6 denominators must be positive and ' ...
         'strictly above the configured safety floor.']);

    features=[outputs(:,3), ...
        outputs(:,3)./outputs(:,1), ...
        outputs(:,1)-outputs(:,2), ...
        outputs(:,1)./outputs(:,6), ...
        outputs(:,6)./outputs(:,4), ...
        outputs(:,5)./outputs(:,4)];
    assert(all(isfinite(features),'all'), ...
        'inversion:physics_guided_full_rank_values:NonFiniteTransform', ...
        'The physics-guided full-rank transform produced a nonfinite value.');
end
