function paths = conditional_posterior_artifact_paths(cfg,cellRecord, ...
        sampler,replicateID,stepCount)
%CONDITIONAL_POSTERIOR_ARTIFACT_PATHS The file paths of one conditional-inversion request.
%   PATHS = inversion.conditional_posterior_artifact_paths(CFG, CELLRECORD,
%   SAMPLER, REPLICATEID, STEPCOUNT) returns the paths of the request's
%   files (checkpoint, posterior, diagnostics, summary, metadata, truth,
%   observation, reliability and certification records) in the conditional
%   campaign's own tree, below the condition's folder: never inside the
%   canonical campaign.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'paths')&& ...
        isfield(cfg.paths,'stage04')&&isfield(cfg,'mcmc'), ...
        'inversion:conditional_posterior_artifact_paths:Configuration', ...
        'Inversion paths and MCMC configuration are required.');
    caseID=pick(cellRecord,{'caseID','case_id'});
    scenario=inversion.scenario_registry(pick(cellRecord, ...
        {'scenario','likelihoodMode'})).tag;
    design=inversion.design_registry(pick(cellRecord, ...
        {'design','outputDesign','design_name'})).name;
    assert(strcmp(design,'all_six'), ...
        'inversion:conditional_posterior_artifact_paths:Design', ...
        'Supplementary conditional inversion is defined only for all_six.');
    condition=inversion.conditional_inversion_conditions(cfg,pick(cellRecord, ...
        {'conditionCode','conditionID','conditionTag'}));
    assert(~condition.canonicalReference, ...
        'inversion:conditional_posterior_artifact_paths:CanonicalBaseline', ...
        'Condition A must remain in the canonical inversion tree.');
    assert(ismember(scenario,condition.scheduledScenarios), ...
        'inversion:conditional_posterior_artifact_paths:StudyScope', ...
        'The requested condition is not scheduled for this scenario.');
    sampler=upper(char(string(sampler)));
    if strcmp(sampler,'ADAPTIVE_METROPOLIS'),sampler='AM';end
    assert(ismember(sampler,{'AIES','AM'}), ...
        'inversion:conditional_posterior_artifact_paths:Sampler', ...
        'Only AIES production and optional AM validation paths are supported.');
    assert(isnumeric(replicateID)&&isscalar(replicateID)&& ...
        isfinite(replicateID)&&replicateID==fix(replicateID)&&replicateID>=1&& ...
        (~strcmp(sampler,'AIES')||ismember(double(replicateID),[1 2])), ...
        'inversion:conditional_posterior_artifact_paths:Replicate', ...
        'The conditional replicate must be 1 or 2 for AIES and positive for AM.');
    assert(ismember(double(stepCount),reshape(double(cfg.mcmc.levels),1,[])), ...
        'inversion:conditional_posterior_artifact_paths:StepCount', ...
        'Step count must be one of the configured canonical levels.');
    cellID=sprintf('case_%d|%s|all_six|condition_%s', ...
        double(caseID),scenario,condition.tag);
    if isfield(cellRecord,'cellID')&&~isempty(cellRecord.cellID)
        assert(strcmp(char(string(cellRecord.cellID)),cellID), ...
            'inversion:conditional_posterior_artifact_paths:CellID', ...
            'Conditional cell ID disagrees with its scientific axes.');
    end
    root=utils.absolute_path(fullfile(cfg.paths.stage04,'conditional_inversion'));
    posteriorRoot=fullfile(root,'posteriors');
    cellRoot=fullfile(posteriorRoot,scenario,'all_six',condition.tag, ...
        sprintf('case_%d',double(caseID)));
    samplerFolder='aies';if strcmp(sampler,'AM'),samplerFolder='adaptive_metropolis';end
    replicateRoot=fullfile(cellRoot,samplerFolder, ...
        sprintf('replicate_%02d',double(replicateID)));
    suffix=sprintf('%d',double(stepCount));
    paths=struct( ...
        'schemaVersion','conditional_mcmc_artifact_paths_v1', ...
        'root',root,'posteriorRoot',posteriorRoot,'cellRoot',cellRoot, ...
        'replicateRoot',replicateRoot, ...
        'checkpointPath',fullfile(replicateRoot, ...
            ['checkpoint_' suffix '.mat']), ...
        'posteriorPath',fullfile(replicateRoot, ...
            ['posterior_samples_' suffix '.mat']), ...
        'diagnosticsPath',fullfile(replicateRoot, ...
            ['diagnostics_' suffix '.csv']), ...
        'summaryPath',fullfile(replicateRoot,['summary_' suffix '.csv']), ...
        'metadataPath',fullfile(replicateRoot,['metadata_' suffix '.json']), ...
        'truthPath',fullfile(cellRoot,'truth.mat'), ...
        'observationPath',fullfile(cellRoot,'observation.mat'), ...
        'reliabilityPath',fullfile(cellRoot,['reliability_' suffix '.json']), ...
        'certifiedPosteriorPath',fullfile(cellRoot,'certified_posterior.json'), ...
        'caseID',double(caseID),'scenario',scenario,'design','all_six', ...
        'conditionCode',condition.code,'conditionTag',condition.tag, ...
        'cellID',cellID, ...
        'sampler',sampler,'replicateID',double(replicateID), ...
        'stepCount',double(stepCount));
end

function value=pick(source,names)
    assert(isstruct(source)&&isscalar(source), ...
        'inversion:conditional_posterior_artifact_paths:Cell', ...
        'Cell record must be a scalar struct.');
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
    error('inversion:conditional_posterior_artifact_paths:CellField', ...
        'Cell record lacks one of: %s.',strjoin(names,', '));
end
