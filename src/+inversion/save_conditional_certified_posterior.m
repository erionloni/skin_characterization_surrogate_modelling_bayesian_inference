function certification = save_conditional_certified_posterior( ...
        cfg,cellRecord,condition,decision)
%SAVE_CONDITIONAL_CERTIFIED_POSTERIOR Publish a pointer to the certified provider of a conditional cell.
%   CERTIFICATION = inversion.save_conditional_certified_posterior(CFG,CELL,
%   CONDITION,DECISION) records that the conditional cell is certified:
%   DECISION (inversion.run_conditional_reliability_cell) must be a
%   certification by the agreement of two independent AIES replicates, with
%   the unpooled AIES replicate 1 as provider. Condition A is the canonical
%   all_six cell and has no conditional pointer.
%   Writes certified_posterior.json (provider, posterior path, parameter
%   roles, fixed values, decision) and the decision reliability_<steps>.json
%   in the conditional cell folder, replacing earlier versions;
%   CERTIFICATION is the pointer.
%   Side effects: writes the cell's certification pointer.

    condition=inversion.conditional_inversion_conditions(cfg,condition.tag);
    assert(~condition.canonicalReference&&isstruct(decision)&& ...
        isscalar(decision)&&logical(decision.certified)&& ...
        logical(decision.downstreamUsePermitted)&& ...
        strcmp(decision.certificationMechanism, ...
        'CERTIFIED_AIES_REPLICATE_AGREEMENT'), ...
        'inversion:save_conditional_certified_posterior:Decision', ...
        'A certified conditional AIES-replicate decision is required.');
    provider=decision.provider;
    assert(strcmp(provider.sampler,'AIES')&&provider.replicateID==1&& ...
        ~logical(provider.samplesPooled), ...
        'inversion:save_conditional_certified_posterior:Provider', ...
        'The provider must be unpooled predeclared AIES replicate 1.');
    [posterior,status]=inversion.load_conditional_posterior_artifact( ...
        cfg,cellRecord,'AIES',1,provider.stepCount);
    assert(status.valid, ...
        'inversion:save_conditional_certified_posterior:Artifact', ...
        'The provider request of %s did not load: %s',status.paths.cellID, ...
        status.reason);
    paths=status.paths;
    certification=struct( ...
        'schemaVersion','conditional_mcmc_certified_posterior_pointer_v2', ...
        'certified',true,'downstreamUsePermitted',true, ...
        'cellID',paths.cellID,'caseID',paths.caseID, ...
        'scenario',paths.scenario,'design','all_six', ...
        'conditionCode',condition.code,'conditionTag',condition.tag, ...
        'provider',provider, ...
        'certificationMechanism','CERTIFIED_AIES_REPLICATE_AGREEMENT', ...
        'providerSelectionUsesDiagnosticRanking',false, ...
        'posteriorRelativePath',relative_inside( ...
        paths.posteriorPath,paths.cellRoot), ...
        'canonicalCoordinateRowsAvailableForReconstruction',true, ...
        'fixedCoordinateRowsAreNotInferredPosteriorDraws',true, ...
        'parameterRoles',{posterior.parameterRoles}, ...
        'freeParameterIndices',posterior.freeParameterIndices, ...
        'fixedParameterIndices',posterior.fixedParameterIndices, ...
        'fixedParameterValues',posterior.truth( ...
            posterior.fixedParameterIndices), ...
        'fixedValueSemantics','oracle_fixed_exactly_to_case_truth', ...
        'reducedSamplerStatesAvailable',true, ...
        'fixedCoordinatesRestoredFromCaseTruth',true, ...
        'samplesPooledAcrossSamplers',false, ...
        'samplesPooledAcrossReplicates',false, ...
        'samplesPooledAcrossLevels',false, ...
        'reliabilityDecision',decision);
    utils.atomic_write_json(paths.certifiedPosteriorPath,certification, ...
        'AllowReplace',true);
    utils.atomic_write_json(paths.reliabilityPath,decision,'AllowReplace',true);
end

function relative=relative_inside(pathValue,root)
    pathValue=utils.absolute_path(pathValue);root=utils.absolute_path(root);
    relative=strrep(pathValue(numel(root)+2:end),'\','/');
end
