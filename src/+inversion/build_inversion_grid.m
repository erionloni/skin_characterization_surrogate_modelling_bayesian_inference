function grid = build_inversion_grid(cfg,cases)
%BUILD_INVERSION_GRID Build the configured N-case x 3 x 6 direct-MCMC grid.
%   GRID = inversion.build_inversion_grid(CFG, CASES) returns the cells
%   (case, scenario and design, named case_<CaseID>|<scenario>|<design>) of
%   every configured case, the three scenarios (inversion.scenario_registry)
%   and the six designs (inversion.design_registry), and the counts. CASES
%   is the configured list of CaseIDs or the case records (with caseID or
%   case_id); it must name the configured cases in their order.
%   Side effects: none.

    requiredCfg = {'inversion','physicsGuidedFullRankSix'};
    assert(isstruct(cfg) && isscalar(cfg) && all(isfield(cfg,requiredCfg)), ...
        'inversion:build_inversion_grid:Configuration', ...
        'A scalar project configuration is required.');
    requiredInversion = {'caseIDs','designNames','activeScenarioTags', ...
        'expectedCellCount'};
    assert(all(isfield(cfg.inversion,requiredInversion)), ...
        'inversion:build_inversion_grid:Configuration', ...
        'The inversion grid configuration is incomplete.');
    if nargin<2 || isempty(cases),cases=cfg.inversion.caseIDs;end

    expectedScenarios = {'measurement_plus_gp','gp_only','gp_self_det'};
    expectedDesigns = {'all_six','d2_only','d6_only','cycle_1_only', ...
        'ratios_only','physics_guided_full_rank_six'};
    configuredCases = reshape(double(cfg.inversion.caseIDs),1,[]);
    configuredScenarios = cellstr(string( ...
        cfg.inversion.activeScenarioTags(:))).';
    configuredDesigns = cellstr(string(cfg.inversion.designNames(:))).';
    assert(~isempty(configuredCases)&&all(isfinite(configuredCases))&& ...
        all(configuredCases==fix(configuredCases))&& ...
        numel(unique(configuredCases))==numel(configuredCases), ...
        'inversion:build_inversion_grid:CasePolicy', ...
        'cfg.inversion.caseIDs must be a nonempty ordered unique integer list.');
    assert(isequal(configuredScenarios,expectedScenarios), ...
        'inversion:build_inversion_grid:ScenarioPolicy', ...
        'Exactly the three canonical scenarios are required in canonical order.');
    assert(isequal(configuredDesigns,expectedDesigns), ...
        'inversion:build_inversion_grid:DesignPolicy', ...
        'Exactly the six canonical designs are required in canonical order.');
    expectedCellCount=numel(configuredCases)*numel(expectedScenarios)* ...
        numel(expectedDesigns);
    assert(double(cfg.inversion.expectedCellCount)==expectedCellCount, ...
        'inversion:build_inversion_grid:ExpectedCount', ...
        ['cfg.inversion.expectedCellCount must equal the configured case, ' ...
         'scenario, and design product.']);

    caseIDs = case_ids(cases);
    assert(isequal(caseIDs,configuredCases), ...
        'inversion:build_inversion_grid:CaseOrder', ...
        'Case records must match the configured ordered inversion cohort.');
    scenarioRegistry = inversion.scenario_registry();
    designRegistry = inversion.design_registry();
    assert(isequal({scenarioRegistry.tag},configuredScenarios) && ...
        isequal({designRegistry.name},configuredDesigns), ...
        'inversion:build_inversion_grid:RegistryBinding', ...
        'Configured scenario/design names differ from their active registries.');
    transformedDesign=designRegistry(strcmp( ...
        {designRegistry.name},'physics_guided_full_rank_six'));
    assert(isscalar(transformedDesign)&& ...
        isfield(cfg.physicsGuidedFullRankSix,'transformVersion')&& ...
        strcmp(transformedDesign.transformVersion, ...
        cfg.physicsGuidedFullRankSix.transformVersion), ...
        'inversion:build_inversion_grid:TransformVersion', ...
        ['The physics-guided design of the registry and the configured ' ...
         'transform must have the same version.']);

    nCell = numel(caseIDs)*numel(scenarioRegistry)*numel(designRegistry);
    cells = repmat(empty_cell(),nCell,1);
    cursor = 0;
    for c = 1:numel(caseIDs)
        for s = 1:numel(scenarioRegistry)
            for d = 1:numel(designRegistry)
                cursor = cursor+1;
                scenario = scenarioRegistry(s);
                design = designRegistry(d);
                cells(cursor) = struct( ...
                    'cellIndex',cursor, ...
                    'cellID',sprintf('case_%d|%s|%s',caseIDs(c), ...
                        scenario.tag,design.name), ...
                    'caseID',caseIDs(c), ...
                    'scenario',scenario.tag, ...
                    'scenarioLabel',scenario.label, ...
                    'primaryScenario',scenario.primaryScientificScenario, ...
                    'design',design.name, ...
                    'designLabel',design.label, ...
                    'requiredConsumers',{{'stage05_coverage_recovery', ...
                        'stage06_stage9a_oed','stage07_figures'}});
            end
        end
    end
    assert(cursor==expectedCellCount&& ...
        cursor==double(cfg.inversion.expectedCellCount), ...
        'inversion:build_inversion_grid:CellCount', ...
        'The direct-MCMC grid cardinality differs from its configured axes.');
    grid = struct( ...
        'schemaVersion','direct_mcmc_grid_v2_six_design', ...
        'caseCount',numel(caseIDs), ...
        'scenarioCount',numel(scenarioRegistry), ...
        'designCount',numel(designRegistry), ...
        'cellCount',nCell, ...
        'initialAnalysisCount',2*nCell, ...
        'cells',cells);
end

function ids = case_ids(cases)
    if isnumeric(cases)
        ids = reshape(double(cases),1,[]);
    elseif isstruct(cases) && isfield(cases,'case_id')
        ids = reshape(double([cases.case_id]),1,[]);
    elseif isstruct(cases) && isfield(cases,'caseID')
        ids = reshape(double([cases.caseID]),1,[]);
    else
        error('inversion:build_inversion_grid:Cases', ...
            'CASES must be CaseIDs or case records with case_id or caseID.');
    end
end

function value = empty_cell()
    value=struct('cellIndex',0,'cellID','', ...
        'caseID',NaN,'scenario','', ...
        'scenarioLabel','', ...
        'primaryScenario',false,'design','','designLabel','', ...
        'requiredConsumers',{{}});
end
