function canonical = expand_conditional_parameters(freeValues,adapter)
%EXPAND_CONDITIONAL_PARAMETERS The four model parameters of conditional sampler states.
%   CANONICAL = inversion.expand_conditional_parameters(FREEVALUES, ADAPTER)
%   places the free parameters FREEVALUES (N-by-K) at their indices and the
%   fixed parameters at their truth (ADAPTER, inversion.conditional_adapter)
%   and returns the N-by-4 rows in the model's parameter order.
%   Side effects: none.

    validate_adapter(adapter);
    values=double(freeValues);
    assert(isnumeric(freeValues)&&ismatrix(values)&& ...
        size(values,2)==double(adapter.samplerDimension)&& ...
        all(isfinite(values),'all'), ...
        'inversion:expand_conditional_parameters:FreeValues', ...
        'Free values must be a finite N-by-samplerDimension matrix.');
    canonical=repmat(reshape(double(adapter.canonicalTruth),1,4),size(values,1),1);
    canonical(:,adapter.freeParameterIndices)=values;
    expected=repmat(reshape(double(adapter.fixedParameterValues),1,[]), ...
        size(values,1),1);
    assert(isequaln(canonical(:,adapter.fixedParameterIndices),expected), ...
        'inversion:expand_conditional_parameters:FixedValues', ...
        'Canonical reconstruction did not preserve the oracle fixed values.');
end

function validate_adapter(value)
    required={'schemaVersion','conditionTag','canonicalTruth', ...
        'canonicalDimension','freeParameterIndices','fixedParameterIndices', ...
        'freeBounds','fixedParameterValues','samplerDimension'};
    assert(isstruct(value)&&isscalar(value)&&all(isfield(value,required))&& ...
        strcmp(value.schemaVersion,'conditional_parameter_adapter_v1')&& ...
        double(value.canonicalDimension)==4&& ...
        numel(value.freeParameterIndices)==double(value.samplerDimension)&& ...
        isequal(sort([reshape(double(value.freeParameterIndices),1,[]) ...
        reshape(double(value.fixedParameterIndices),1,[])]),1:4), ...
        'inversion:expand_conditional_parameters:Adapter', ...
        'The conditional parameter adapter is incomplete or malformed.');
end
