function schedule = conditional_seed_schedule(cfg,conditionalGrid,cases)
%CONDITIONAL_SEED_SCHEDULE Preflight canonical and supplementary RNG seeds.
%   The complete numeric seed schedule is checked, so that no conditional
%   request shares its seed with any canonical inversion request.
%   SCHEDULE = inversion.conditional_seed_schedule(CFG, CONDITIONALGRID,
%   CASES) returns the seed of every request of the conditional cells
%   (CONDITIONALGRID, inversion.build_conditional_inversion_grid) and of the
%   canonical cells of the inversion cases CASES (seeds.mcmc) and checks
%   that no two seeds coincide. SCHEDULE.records holds per request its
%   cell, axes, seed and the seed's source: 'recorded' (the frozen record
%   of the thesis, config/seeds/mcmc_seeds.csv) or 'rule' (the seed rule of
%   the settings, for new conditions or cases).
%   Side effects: none.

    expectedConditionalCellCount=numel(cfg.conditionalInversion.schedule)* ...
        numel(cfg.conditionalInversion.caseIDs);
    assert(isstruct(conditionalGrid)&&isscalar(conditionalGrid)&& ...
        conditionalGrid.cellCount==expectedConditionalCellCount&& ...
        numel(conditionalGrid.cells)==expectedConditionalCellCount, ...
        'inversion:conditional_seed_schedule:Grid', ...
        'The complete conditional grid of the settings (A.9) is required.');
    [caseIDs,~]=case_truth(cases);
    assert(isequal(caseIDs,reshape(double(cfg.inversion.caseIDs),1,[])), ...
        'inversion:conditional_seed_schedule:Cases', ...
        'Case truth records must match the configured canonical cohort.');
    canonicalGrid=inversion.build_inversion_grid(cfg,cases);
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    replicates=reshape(double(cfg.mcmc.productionReplicateIDs),1,[]);
    assert(isequal(levels,[2000 5000])&&isequal(replicates,[1 2]), ...
        'inversion:conditional_seed_schedule:Policy', ...
        'The preflight requires fresh AIES pairs at every configured level.');

    optionalCanonicalAM=sum(arrayfun(@(x)am_selected(cfg,x.caseID), ...
        canonicalGrid.cells));
    optionalConditionalAM=sum(arrayfun(@(x)am_selected(cfg,x.caseID), ...
        conditionalGrid.cells));
    canonicalAIESCount=canonicalGrid.cellCount*numel(levels)*numel(replicates);
    conditionalAIESCount=conditionalGrid.cellCount*numel(levels)*numel(replicates);
    expectedCount=canonicalAIESCount+conditionalAIESCount+ ...
        optionalCanonicalAM+optionalConditionalAM;
    records=repmat(empty_record(),expectedCount,1);
    numericSeeds=zeros(expectedCount,1);
    map=containers.Map('KeyType','char','ValueType','char');
    cursor=0;

    for c=1:canonicalGrid.cellCount
        one=canonicalGrid.cells(c);
        for stepCount=levels
            for replicateID=replicates
                [seed,seedRecord]=seeds.mcmc(cfg,one.caseID, ...
                    one.scenario,one.design,[],'AIES',replicateID,stepCount);
                [map,records,numericSeeds,cursor]=register(map,records, ...
                    numericSeeds,cursor,'canonical',one.cellID,'', ...
                    one.caseID,one.scenario,one.design,'AIES',replicateID, ...
                    stepCount,seed,seedRecord);
            end
        end
        if am_selected(cfg,one.caseID)
            [seed,seedRecord]=seeds.mcmc(cfg,one.caseID, ...
                one.scenario,one.design,[],'AM',cfg.mcmc.amValidationReplicateID, ...
                cfg.mcmc.amValidationStepCount);
            [map,records,numericSeeds,cursor]=register(map,records, ...
                numericSeeds,cursor,'canonical',one.cellID,'', ...
                one.caseID,one.scenario,one.design,'AM', ...
                cfg.mcmc.amValidationReplicateID, ...
                cfg.mcmc.amValidationStepCount,seed,seedRecord);
        end
    end

    for c=1:conditionalGrid.cellCount
        one=conditionalGrid.cells(c);
        caseIndex=find(caseIDs==one.caseID);
        assert(isscalar(caseIndex), ...
            'inversion:conditional_seed_schedule:CaseBinding', ...
            'Conditional grid cell lacks one canonical truth record.');
        condition=inversion.conditional_inversion_conditions(cfg,one.conditionCode);
        fixed=condition.fixedParameterIndices;
        for stepCount=levels
            for replicateID=replicates
                [seed,seedRecord]=seeds.mcmc(cfg,one.caseID, ...
                    one.scenario,one.design,fixed,'AIES',replicateID,stepCount);
                [map,records,numericSeeds,cursor]=register(map,records, ...
                    numericSeeds,cursor,'conditional',one.cellID,condition.tag, ...
                    one.caseID,one.scenario,one.design,'AIES',replicateID, ...
                    stepCount,seed,seedRecord);
            end
        end
        if am_selected(cfg,one.caseID)
            [seed,seedRecord]=seeds.mcmc(cfg,one.caseID, ...
                one.scenario,one.design,fixed,'AM', ...
                cfg.mcmc.amValidationReplicateID, ...
                cfg.mcmc.amValidationStepCount);
            [map,records,numericSeeds,cursor]=register(map,records, ...
                numericSeeds,cursor,'conditional',one.cellID,condition.tag, ...
                one.caseID,one.scenario,one.design,'AM', ...
                cfg.mcmc.amValidationReplicateID, ...
                cfg.mcmc.amValidationStepCount,seed,seedRecord);
        end
    end
    assert(cursor==expectedCount&&map.Count==expectedCount&& ...
        numel(unique(numericSeeds))==expectedCount&& ...
        canonicalAIESCount==numel(levels)*numel(replicates)*canonicalGrid.cellCount&& ...
        conditionalAIESCount==numel(levels)*numel(replicates)*conditionalGrid.cellCount, ...
        'inversion:conditional_seed_schedule:Collision', ...
        ['The combined schedule must contain the configured canonical and ' ...
         'conditional AIES seeds per cell, all numerically distinct, plus distinct ' ...
         'seeds for any enabled optional AM requests.']);
    records=records(1:cursor);numericSeeds=numericSeeds(1:cursor);
    scope=string({records.scope});sampler=string({records.sampler});
    schedule=struct( ...
        'schemaVersion','conditional_inversion_combined_seed_schedule_v1', ...
        'canonicalAIESRequestCount',canonicalAIESCount, ...
        'conditionalAIESRequestCount',conditionalAIESCount, ...
        'canonicalAMRequestCount',nnz(scope=="canonical"&sampler=="AM"), ...
        'conditionalAMRequestCount',nnz(scope=="conditional"&sampler=="AM"), ...
        'numericSeeds',numericSeeds.');
    schedule.requestCount=cursor;
    schedule.numericSeedsUnique=true;
    schedule.conditionalSeedsDisjointFromCanonical=true;
    schedule.records=records;
end

function [map,records,seeds,cursor]=register(map,records,seeds,cursor, ...
        scope,cellID,conditionTag,caseID,scenario,design,sampler, ...
        replicateID,stepCount,seed,seedRecord)
    key=sprintf('%d',double(seed));
    assert(~isKey(map,key), ...
        'inversion:conditional_seed_schedule:NumericSeedCollision', ...
        'Two different canonical or conditional requests have the same RNG seed %d.', ...
        double(seed));
    map(key)=seedRecord.request;cursor=cursor+1;
    seeds(cursor)=double(seed);
    records(cursor)=struct('scope',scope,'cellID',cellID, ...
        'conditionTag',conditionTag,'caseID',double(caseID), ...
        'scenario',scenario,'design',design,'sampler',sampler, ...
        'replicateID',double(replicateID),'stepCount',double(stepCount), ...
        'seed',double(seed),'source',seedRecord.source,'request',seedRecord.request);
end

function tf=am_selected(cfg,caseID)
    assert(all(isfield(cfg.mcmc,{'enableAdaptiveMetropolisValidation', ...
        'amValidationCaseIDs','amValidationStepCount', ...
        'amValidationReplicateID'})), ...
        'inversion:conditional_seed_schedule:AMConfiguration', ...
        'Optional Adaptive Metropolis validation configuration is incomplete.');
    if ~logical(cfg.mcmc.enableAdaptiveMetropolisValidation),tf=false;return;end
    selected=reshape(double(cfg.mcmc.amValidationCaseIDs),1,[]);
    tf=isempty(selected)||ismember(double(caseID),selected);
end

function [ids,truth]=case_truth(cases)
    assert(isstruct(cases)&&~isempty(cases)&&isfield(cases,'truth'), ...
        'inversion:conditional_seed_schedule:Cases', ...
        'A nonempty configured set of case records with truth values is required.');
    if isfield(cases,'case_id')
        ids=reshape(double([cases.case_id]),1,[]);
    elseif isfield(cases,'caseID')
        ids=reshape(double([cases.caseID]),1,[]);
    else
        error('inversion:conditional_seed_schedule:Cases', ...
            'Case records lack canonical CaseIDs.');
    end
    truth=vertcat(cases.truth);
    assert(isequal(size(truth),[numel(cases) 4])&&all(isfinite(truth),'all'), ...
        'inversion:conditional_seed_schedule:Truth', ...
        'Case truth values must be a finite N-by-4 matrix.');
end

function value=empty_record()
    value=struct('scope','','cellID','','conditionTag','','caseID',NaN, ...
        'scenario','','design','','sampler','','replicateID',NaN, ...
        'stepCount',NaN,'seed',NaN,'source','','request','');
end
