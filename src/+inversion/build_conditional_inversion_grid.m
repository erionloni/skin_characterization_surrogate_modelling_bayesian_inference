function grid = build_conditional_inversion_grid(cfg,cases)
%BUILD_CONDITIONAL_INVERSION_GRID The cells of the conditional inversion.
%   GRID = inversion.build_conditional_inversion_grid(CFG, CASES) returns the
%   cells of the conditional campaign of the settings (A.9) for the
%   conditional cases CASES (data.inversion_cases, or CaseIDs): per case,
%   in the order of the case list, the (scenario, condition) pairs of the
%   campaign rows in their order (cfg.conditionalInversion.schedule), design
%   all_six. The condition that fixes nothing is the canonical all_six cell:
%   it is referenced from the canonical campaign and is not a cell of this
%   grid.
%   GRID: the conditions, the schedule, the cells (case, scenario, design
%   and condition, named case_<CaseID>|<scenario>|all_six|condition_<id>)
%   and the counts.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'conditionalInversion')&& ...
        all(isfield(cfg.conditionalInversion,{'caseIDs','design','conditions', ...
        'schedule','referenceCode'})), ...
        'inversion:build_conditional_inversion_grid:Configuration', ...
        'The conditional-inversion configuration (settings A.9) is required.');
    C=cfg.conditionalInversion;
    if nargin<2||isempty(cases),cases=C.caseIDs;end
    configuredCases=reshape(double(C.caseIDs),1,[]);
    caseIDs=case_ids(cases);
    assert(isequal(caseIDs,configuredCases)&&~isempty(caseIDs), ...
        'inversion:build_conditional_inversion_grid:CaseOrder', ...
        'Cases must be the configured cases of the conditional inversion, in their order.');
    assert(strcmp(C.design,'all_six'), ...
        'inversion:build_conditional_inversion_grid:Design', ...
        'The conditional inversion is defined for the design all_six.');

    conditions=inversion.conditional_inversion_conditions(cfg);
    schedule=C.schedule;
    design=inversion.design_registry('all_six');
    nCell=numel(caseIDs)*numel(schedule);
    cells=repmat(empty_cell(),nCell,1);cursor=0;
    for c=1:numel(caseIDs)
        for p=1:numel(schedule)
            scenario=inversion.scenario_registry(schedule(p).scenario);
            condition=inversion.conditional_inversion_conditions(cfg,schedule(p).code);
            cursor=cursor+1;
            cellID=sprintf('case_%d|%s|all_six|condition_%s', ...
                caseIDs(c),scenario.tag,condition.id);
            cells(cursor)=struct( ...
                'cellIndex',cursor,'cellID',cellID, ...
                'caseID',caseIDs(c), ...
                'scenario',scenario.tag,'scenarioLabel',scenario.label, ...
                'primaryScenario',scenario.primaryScientificScenario, ...
                'design','all_six','designLabel',design.label, ...
                'conditionCode',condition.code, ...
                'conditionID',condition.id, ...
                'conditionLabel',condition.label, ...
                'conditionRole',condition.role, ...
                'freeParameterIndices',condition.freeParameterIndices, ...
                'fixedParameterIndices',condition.fixedParameterIndices, ...
                'fixedValueSource',condition.fixedValueSource, ...
                'requiredConsumers',{{ ...
                'conditional_inversion_report','stage07_figures'}});
        end
    end
    assert(cursor==nCell&&numel(unique({cells.cellID}))==nCell&& ...
        ~any(strcmp({cells.conditionCode},C.referenceCode)), ...
        'inversion:build_conditional_inversion_grid:Schedule', ...
        'Every conditional cell must be scheduled once and none may be the canonical reference.');
    scheduleRows=[{schedule.scenario};{schedule.code}].';
    grid=struct( ...
        'schemaVersion','conditional_inversion_grid_v2', ...
        'caseCount',numel(caseIDs),'designCount',1, ...
        'scenarioCount',numel(unique({schedule.scenario})), ...
        'conditionCount',numel(unique({schedule.code})),'cellCount',nCell, ...
        'initialAnalysisCount',2*nCell, ...
        'canonicalReferenceCondition',C.referenceCode, ...
        'canonicalReferenceStoredInSupplementaryTree',false, ...
        'conditions',conditions,'schedule',{scheduleRows},'cells',cells);
end

function ids=case_ids(cases)
    if isnumeric(cases)
        ids=reshape(double(cases),1,[]);
    elseif isstruct(cases)&&isfield(cases,'case_id')
        ids=reshape(double([cases.case_id]),1,[]);
    elseif isstruct(cases)&&isfield(cases,'caseID')
        ids=reshape(double([cases.caseID]),1,[]);
    else
        error('inversion:build_conditional_inversion_grid:Cases', ...
            'CASES must be CaseIDs or case records with case_id or caseID.');
    end
end

function value=empty_cell()
    value=struct('cellIndex',0,'cellID','', ...
        'caseID',NaN,'scenario','', ...
        'scenarioLabel','','primaryScenario',false, ...
        'design','','designLabel','', ...
        'conditionCode','','conditionID','','conditionLabel','', ...
        'conditionRole','', ...
        'freeParameterIndices',[],'fixedParameterIndices',[], ...
        'fixedValueSource','','requiredConsumers',{{}});
end
