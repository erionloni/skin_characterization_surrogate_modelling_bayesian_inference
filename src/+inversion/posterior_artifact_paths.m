function paths = posterior_artifact_paths(cfg,cellRecord,sampler, ...
        replicateID,stepCount)
%POSTERIOR_ARTIFACT_PATHS The file paths of one inversion request.
%   PATHS = inversion.posterior_artifact_paths(CFG, CELLRECORD, SAMPLER,
%   REPLICATEID, STEPCOUNT) returns, below CFG.paths.stage04/posteriors/
%   <scenario>/<design>/case_<case number>/, the cell folder with the
%   truth, the observation, the reliability decision of each level and
%   the certification pointer, and the request's files below
%   <aies|adaptive_metropolis>/replicate_<RR>/: checkpoint, posterior
%   samples, diagnostics, summary and metadata of the level STEPCOUNT.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'paths')&& ...
        isfield(cfg.paths,'stage04')&&isfield(cfg,'mcmc')&& ...
        isfield(cfg.mcmc,'levels'), ...
        'inversion:posterior_artifact_paths:Configuration', ...
        'cfg.paths.stage04 and cfg.mcmc.levels are required.');
    [caseID,scenario,design,cellID]=cell_axes(cellRecord);
    scenario=inversion.scenario_registry(scenario).tag;
    design=inversion.design_registry(design).name;
    sampler=upper(strtrim(char(string(sampler))));
    if strcmp(sampler,'ADAPTIVE_METROPOLIS'),sampler='AM';end
    assert(ismember(sampler,{'AIES','AM'}), ...
        'inversion:posterior_artifact_paths:Sampler', ...
        'Only AIES and AM artifact paths are supported.');
    assert(isnumeric(replicateID)&&isscalar(replicateID)&& ...
        isfinite(replicateID)&&replicateID==fix(replicateID)&&replicateID>=1, ...
        'inversion:posterior_artifact_paths:Replicate', ...
        'replicateID must be a positive integer.');
    levels=reshape(double(cfg.mcmc.levels),1,[]);
    assert(ismember(stepCount,levels), ...
        'inversion:posterior_artifact_paths:StepCount', ...
        'stepCount must be one of cfg.mcmc.levels.');
    if strcmp(sampler,'AIES')
        samplerFolder='aies';
    else
        samplerFolder='adaptive_metropolis';
    end

    stageRoot=utils.absolute_path(cfg.paths.stage04);
    posteriorRoot=fullfile(stageRoot,'posteriors');
    cellRoot=fullfile(posteriorRoot,scenario,design, ...
        sprintf('case_%d',caseID));
    samplerRoot=fullfile(cellRoot,samplerFolder);
    replicateRoot=fullfile(samplerRoot,sprintf('replicate_%02d',replicateID));
    suffix=sprintf('%d',stepCount);
    paths=struct( ...
        'schemaVersion','direct_mcmc_artifact_paths_v1', ...
        'stageRoot',stageRoot, ...
        'posteriorRoot',posteriorRoot, ...
        'cellRoot',cellRoot, ...
        'samplerRoot',samplerRoot, ...
        'replicateRoot',replicateRoot, ...
        'checkpointPath',fullfile(replicateRoot, ...
            ['checkpoint_' suffix '.mat']), ...
        'posteriorPath',fullfile(replicateRoot, ...
            ['posterior_samples_' suffix '.mat']), ...
        'diagnosticsPath',fullfile(replicateRoot, ...
            ['diagnostics_' suffix '.csv']), ...
        'summaryPath',fullfile(replicateRoot, ...
            ['summary_' suffix '.csv']), ...
        'metadataPath',fullfile(replicateRoot, ...
            ['metadata_' suffix '.json']), ...
        'truthPath',fullfile(cellRoot,'truth.mat'), ...
        'observationPath',fullfile(cellRoot,'observation.mat'), ...
        'reliabilityPath',fullfile(cellRoot, ...
            ['reliability_' suffix '.json']), ...
        'certifiedPosteriorPath',fullfile(cellRoot, ...
            'certified_posterior.json'), ...
        'caseID',caseID, ...
        'scenario',scenario, ...
        'design',design, ...
        'cellID',cellID, ...
        'sampler',sampler, ...
        'replicateID',double(replicateID), ...
        'stepCount',double(stepCount));
end

function [caseID,scenario,design,cellID]=cell_axes(cellRecord)
    assert(isstruct(cellRecord)&&isscalar(cellRecord), ...
        'inversion:posterior_artifact_paths:Cell','cellRecord must be scalar.');
    caseID=pick(cellRecord,{'caseID','case_id'});
    scenario=pick(cellRecord,{'scenario','likelihoodMode'});
    design=pick(cellRecord,{'design','outputDesign','design_name'});
    assert(isnumeric(caseID)&&isscalar(caseID)&&isfinite(caseID)&& ...
        caseID==fix(caseID), ...
        'inversion:posterior_artifact_paths:CaseID','caseID must be an integer.');
    caseID=double(caseID);
    scenario=char(string(scenario));
    design=char(string(design));
    canonical=sprintf('case_%d|%s|%s',caseID,scenario,design);
    if isfield(cellRecord,'cellID')&&~isempty(cellRecord.cellID)
        assert(strcmp(char(string(cellRecord.cellID)),canonical), ...
            'inversion:posterior_artifact_paths:CellID', ...
            'cellRecord.cellID does not match its scientific axes.');
    end
    cellID=canonical;
end

function value=pick(source,names)
    for i=1:numel(names)
        if isfield(source,names{i})&&~isempty(source.(names{i}))
            value=source.(names{i});return;
        end
    end
    error('inversion:posterior_artifact_paths:CellField', ...
        'Cell record is missing one of: %s.',strjoin(names,', '));
end
