function grid = build_gp_mean_inversion_grid(cfg,cases)
%BUILD_GP_MEAN_INVERSION_GRID The cells of the GP-mean inversion: one per case, scenario gp_mean_det.
%   GRID = inversion.build_gp_mean_inversion_grid(CFG, CASES) returns the
%   cells of the GP-mean inversion of the settings (A.13): one cell per case
%   of CFG.gpMeanInversion.caseIDs, in that order, in the scenario
%   gp_mean_det (inversion.scenario_registry) and the design
%   CFG.gpMeanInversion.design (all_six), named case_<CaseID>|gp_mean_det|
%   all_six, with the fields of the canonical grid's cells
%   (inversion.build_inversion_grid), and the counts. CASES is the list of
%   CaseIDs or the case records (with case_id or caseID); it must name the
%   configured cases in their order.
%   Side effects: none.

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'gpMeanInversion')&& ...
        all(isfield(cfg.gpMeanInversion,{'caseIDs','design','scenario'})), ...
        'inversion:build_gp_mean_inversion_grid:Configuration', ...
        'The GP-mean inversion configuration (settings A.13) is required.');
    configured=reshape(double(cfg.gpMeanInversion.caseIDs),1,[]);
    assert(~isempty(configured)&&all(isfinite(configured))&& ...
        all(configured==fix(configured))&&numel(unique(configured))==numel(configured), ...
        'inversion:build_gp_mean_inversion_grid:Cases', ...
        'cfg.gpMeanInversion.caseIDs must be a nonempty ordered unique integer list.');
    if nargin<2||isempty(cases),cases=configured;end
    caseIDs=case_ids(cases);
    assert(isequal(caseIDs,configured), ...
        'inversion:build_gp_mean_inversion_grid:CaseOrder', ...
        'The case records must be the configured cases of the GP-mean inversion, in their order.');
    scenario=inversion.scenario_registry(cfg.gpMeanInversion.scenario);
    design=inversion.design_registry(cfg.gpMeanInversion.design);
    assert(strcmp(scenario.tag,'gp_mean_det')&&strcmp(design.name,'all_six'), ...
        'inversion:build_gp_mean_inversion_grid:Axes', ...
        'The GP-mean inversion is implemented for the scenario gp_mean_det and the design all_six.');

    n=numel(caseIDs);
    cells=repmat(struct('cellIndex',0,'cellID','','caseID',NaN,'scenario','', ...
        'scenarioLabel','','primaryScenario',false,'design','','designLabel','', ...
        'requiredConsumers',{{}}),n,1);
    for c=1:n
        cells(c)=struct( ...
            'cellIndex',c, ...
            'cellID',sprintf('case_%d|%s|%s',caseIDs(c),scenario.tag,design.name), ...
            'caseID',caseIDs(c), ...
            'scenario',scenario.tag, ...
            'scenarioLabel',scenario.label, ...
            'primaryScenario',scenario.primaryScientificScenario, ...
            'design',design.name, ...
            'designLabel',design.label, ...
            'requiredConsumers',{{'gp_mean_inversion'}});
    end
    grid=struct( ...
        'schemaVersion','gp_mean_inversion_grid_v1', ...
        'caseCount',n, ...
        'scenarioCount',1, ...
        'designCount',1, ...
        'cellCount',n, ...
        'initialAnalysisCount',2*n, ...
        'cells',cells);
end

function ids=case_ids(cases)
    if isnumeric(cases)
        ids=reshape(double(cases),1,[]);
    elseif isstruct(cases)&&isfield(cases,'case_id')
        ids=reshape(double([cases.case_id]),1,[]);
    elseif isstruct(cases)&&isfield(cases,'caseID')
        ids=reshape(double([cases.caseID]),1,[]);
    else
        error('inversion:build_gp_mean_inversion_grid:CaseRecords', ...
            'CASES must be CaseIDs or case records with case_id or caseID.');
    end
end
