function report = posterior_reproducibility(left,right,bounds,thresholds,varargin)
%POSTERIOR_REPRODUCIBILITY Compare two complete posterior distributions.
%   REPORT = inversion.posterior_reproducibility(LEFT,RIGHT,BOUNDS,T)
%   flattens each analysis separately, computes exact empirical one-
%   dimensional Wasserstein distances and summary differences, and never
%   pools the two analyses into a scientific posterior. LEFT and RIGHT are
%   iteration-by-parameter-by-sampler-state arrays. The sampler states may
%   be interacting AIES walkers.
%
%   The hard project criteria are normalized Wasserstein, normalized Q025,
%   and normalized Q975 agreement for every parameter. Median and Pearson-
%   correlation comparisons are descriptive warnings only.
%   Option (name-value): 'ParameterNames', one name per parameter for the
%   report (default theta_01, theta_02, ...).
%   Side effects: none.

    parser=inputParser;
    parser.FunctionName='inversion.posterior_reproducibility';
    addParameter(parser,'ParameterNames',{},@(x)iscell(x)||isstring(x));
    parse(parser,varargin{:});
    validate_inputs(left,right,bounds,thresholds);

    parameterCount=size(bounds,1);
    names=cellstr(string(parser.Results.ParameterNames(:))).';
    if isempty(names)
        names=arrayfun(@(i)sprintf('theta_%02d',i),1:parameterCount, ...
            'UniformOutput',false);
    end
    assert(numel(names)==parameterCount&&all(~cellfun(@isempty,names)), ...
        'inversion:posterior_reproducibility:ParameterNames', ...
        'ParameterNames must contain one nonempty name per parameter.');

    leftDraws=flatten(left);
    rightDraws=flatten(right);
    priorWidth=reshape(double(bounds(:,2)-bounds(:,1)),1,[]);
    wassersteinDistance=zeros(1,parameterCount);
    for j=1:parameterCount
        wassersteinDistance(j)=wasserstein_1d( ...
            leftDraws(:,j),rightDraws(:,j));
    end
    normalizedWassersteinDistance=wassersteinDistance./priorWidth;
    wassersteinPass=isfinite(normalizedWassersteinDistance)& ...
        normalizedWassersteinDistance<=thresholds.maxNormalizedWasserstein;

    medians=[median(leftDraws,1);median(rightDraws,1)];
    posteriorSD=[std(leftDraws,0,1);std(rightDraws,0,1)];
    posteriorSDScale=mean(posteriorSD,1);
    medianAbsoluteDifference=abs(medians(1,:)-medians(2,:));
    normalizedMedianDifference=medianAbsoluteDifference./priorWidth;
    posteriorSdScaledMedianDifference=scaled_difference( ...
        medianAbsoluteDifference,posteriorSDScale);
    medianReferencePass=isfinite(normalizedMedianDifference)& ...
        normalizedMedianDifference<=thresholds.maxMedianRangeDifference;

    qLeft=quantile(leftDraws,[0.025 0.975],1);
    qRight=quantile(rightDraws,[0.025 0.975],1);
    q025AbsoluteDifference=abs(qLeft(1,:)-qRight(1,:));
    q975AbsoluteDifference=abs(qLeft(2,:)-qRight(2,:));
    normalizedQ025Difference=q025AbsoluteDifference./priorWidth;
    normalizedQ975Difference=q975AbsoluteDifference./priorWidth;
    q025Pass=isfinite(normalizedQ025Difference)& ...
        normalizedQ025Difference<=thresholds.maxQuantileRangeDifference;
    q975Pass=isfinite(normalizedQ975Difference)& ...
        normalizedQ975Difference<=thresholds.maxQuantileRangeDifference;

    correlationMatrixReplicate1=corrcoef(leftDraws);
    correlationMatrixReplicate2=corrcoef(rightDraws);
    correlationAbsoluteDifference=abs( ...
        correlationMatrixReplicate1-correlationMatrixReplicate2);
    maximumCorrelationDifference=max_off_diagonal( ...
        correlationAbsoluteDifference);
    correlationFinite=all(isfinite(correlationAbsoluteDifference),'all');
    correlationWarning=~correlationFinite|| ...
        maximumCorrelationDifference>thresholds.correlationDifferenceWarning;

    hardDistributionAgreementPass=all(wassersteinPass)&& ...
        all(q025Pass)&&all(q975Pass);
    report=struct( ...
        'schemaVersion','posterior_distribution_reproducibility_v1', ...
        'parameterNames',{names}, ...
        'priorBounds',double(bounds), ...
        'priorWidth',priorWidth, ...
        'replicateDrawCounts',[size(leftDraws,1) size(rightDraws,1)], ...
        'wassersteinDistance',wassersteinDistance, ...
        'normalizedWassersteinDistance',normalizedWassersteinDistance, ...
        'maximumNormalizedWasserstein', ...
            max(normalizedWassersteinDistance), ...
        'wassersteinThreshold',double( ...
            thresholds.maxNormalizedWasserstein), ...
        'wassersteinPass',wassersteinPass, ...
        'q025Replicate1',qLeft(1,:), ...
        'q025Replicate2',qRight(1,:), ...
        'q025AbsoluteDifference',q025AbsoluteDifference, ...
        'normalizedQ025Difference',normalizedQ025Difference, ...
        'maximumNormalizedQ025Difference',max(normalizedQ025Difference), ...
        'q025Pass',q025Pass, ...
        'q975Replicate1',qLeft(2,:), ...
        'q975Replicate2',qRight(2,:), ...
        'q975AbsoluteDifference',q975AbsoluteDifference, ...
        'normalizedQ975Difference',normalizedQ975Difference, ...
        'maximumNormalizedQ975Difference',max(normalizedQ975Difference), ...
        'q975Pass',q975Pass, ...
        'quantileThreshold',double( ...
            thresholds.maxQuantileRangeDifference), ...
        'medians',medians, ...
        'medianAbsoluteDifference',medianAbsoluteDifference, ...
        'normalizedMedianDifference',normalizedMedianDifference, ...
        'maximumNormalizedMedianDifference', ...
            max(normalizedMedianDifference), ...
        'posteriorSD',posteriorSD, ...
        'posteriorSDScale',posteriorSDScale, ...
        'posteriorSDScaleDefinition', ...
            'arithmetic_mean_of_replicate_posterior_SD', ...
        'posteriorSdScaledMedianDifference', ...
            posteriorSdScaledMedianDifference, ...
        'maximumPosteriorSdScaledMedianDifference', ...
            max(posteriorSdScaledMedianDifference), ...
        'medianReferenceThreshold',double( ...
            thresholds.maxMedianRangeDifference), ...
        'medianReferencePass',medianReferencePass, ...
        'medianWarning',~all(medianReferencePass), ...
        'correlationMatrixReplicate1',correlationMatrixReplicate1, ...
        'correlationMatrixReplicate2',correlationMatrixReplicate2, ...
        'correlationAbsoluteDifference',correlationAbsoluteDifference, ...
        'maximumCorrelationDifference',maximumCorrelationDifference, ...
        'correlationReferenceThreshold',double( ...
            thresholds.correlationDifferenceWarning), ...
        'correlationFinite',correlationFinite, ...
        'correlationWarning',correlationWarning, ...
        'hardDistributionAgreementPass',hardDistributionAgreementPass, ...
        'samplesPooled',false, ...
        'wassersteinDefinition', ...
            'exact_empirical_one_dimensional_first_Wasserstein_v1', ...
        'interpretation',[ ...
            'Project-specific posterior reproducibility evidence; the ' ...
            'configured tolerance is not a universal MCMC theorem.']);
end

function validate_inputs(left,right,bounds,thresholds)
    assert(isnumeric(bounds)&&size(bounds,2)==2&& ...
        all(isfinite(bounds),'all')&&all(bounds(:,2)>bounds(:,1)), ...
        'inversion:posterior_reproducibility:Bounds', ...
        'Bounds must be a finite parameter-by-two matrix with positive widths.');
    parameterCount=size(bounds,1);
    for value={left,right}
        run=value{1};
        assert(isnumeric(run)&&~isempty(run)&& ...
            size(run,2)==parameterCount&&size(run,3)>=1&& ...
            all(isfinite(run),'all'), ...
            'inversion:posterior_reproducibility:Samples', ...
            ['Each posterior must be a finite, nonempty ' ...
             'iteration-by-parameter-by-state array.']);
    end
    required={'maxNormalizedWasserstein','maxQuantileRangeDifference', ...
        'maxMedianRangeDifference','correlationDifferenceWarning'};
    assert(isstruct(thresholds)&&isscalar(thresholds)&& ...
        all(isfield(thresholds,required)), ...
        'inversion:posterior_reproducibility:Thresholds', ...
        'Distribution-reproducibility thresholds are incomplete.');
end

function draws=flatten(run)
    draws=reshape(permute(double(run),[1 3 2]),[],size(run,2));
end

function distance=wasserstein_1d(left,right)
% Exact integral of |F_left-F_right| for two empirical one-dimensional CDFs.
    left=sort(double(left(:)));
    right=sort(double(right(:)));
    % Production AIES replicates at a common level have equal retained draw
    % counts. For equally weighted empirical measures in one dimension, the
    % exact W1 distance is the mean absolute difference of the order
    % statistics; this avoids a large merged-support loop for every cell.
    if numel(left)==numel(right)
        distance=mean(abs(left-right));
        return;
    end
    support=unique([left;right]);
    if numel(support)<2,distance=0;return;end
    leftCursor=0;
    rightCursor=0;
    distance=0;
    for k=1:numel(support)-1
        while leftCursor<numel(left)&&left(leftCursor+1)<=support(k)
            leftCursor=leftCursor+1;
        end
        while rightCursor<numel(right)&&right(rightCursor+1)<=support(k)
            rightCursor=rightCursor+1;
        end
        interval=support(k+1)-support(k);
        distance=distance+abs(leftCursor/numel(left)- ...
            rightCursor/numel(right))*interval;
    end
end

function value=scaled_difference(difference,scale)
    value=zeros(size(difference));
    positive=scale>0&isfinite(scale);
    value(positive)=difference(positive)./scale(positive);
    value(~positive&difference>0)=Inf;
    value(~positive&difference==0)=0;
end

function value=max_off_diagonal(matrix)
    if size(matrix,1)<2,value=0;return;end
    selected=matrix(triu(true(size(matrix)),1));
    if isempty(selected),value=0;else,value=max(selected);end
end
