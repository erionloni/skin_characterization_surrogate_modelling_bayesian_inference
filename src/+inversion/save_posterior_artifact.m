function [posteriorArtifact,receipt] = save_posterior_artifact( ...
        cfg,cellRecord,sampler,replicateID,stepCount,seed,result, ...
        truth,observation,health)
%SAVE_POSTERIOR_ARTIFACT Save one complete, resumable sampler execution.
%   [POSTERIORARTIFACT, RECEIPT] = inversion.save_posterior_artifact(CFG,
%   CELLRECORD, SAMPLER, REPLICATEID, STEPCOUNT, SEED, RESULT, TRUTH,
%   OBSERVATION, HEALTH) saves one request of the cell CELLRECORD: the sampler
%   RESULT (inversion.bayes_invert), the TRUTH (1-by-4, model coordinates), the
%   OBSERVATION (1-by-6, mbar; NaN allowed only outside the cell's design) and
%   the HEALTH record
%   (inversion.single_analysis_health; computed here when empty). It returns
%   the saved posterior artifact and the request's metadata record.
%   RESULT must contain postSample (the retained draws in model coordinates:
%   log10(k0) for the permeability) and sampleArray (retained iteration x
%   parameter x sampler-state array). The checkpoint
%   is a completed fresh-total-length request; it is reusable as a whole but
%   is never appended to a later 5000-step request.
%   Writes, below the cell folder (inversion.posterior_artifact_paths): the
%   cell's truth and observation (once per cell), the checkpoint, the
%   posterior draws, their summary and diagnostics tables, and the request's
%   metadata JSON, written last: a request with all its files is complete.
%   Side effects: writes the request's files below the cell folder.

    if nargin<10||isempty(health)
        health=inversion.single_analysis_health( ...
            result.sampleArray,cfg.paramBounds,cfg,sampler);
    end
    paths=inversion.posterior_artifact_paths( ...
        cfg,cellRecord,sampler,replicateID,stepCount);
    requiredResult={'postSample','sampleArray','logLikelihoodTrace'};
    assert(isstruct(result)&&isscalar(result)&& ...
        all(isfield(result,requiredResult)), ...
        'inversion:save_posterior_artifact:Result', ...
        ['RESULT must contain retained samples and the required UQLab ' ...
         'sampler-state log-likelihood trace.']);
    draws=double(result.postSample);
    sampleArray=double(result.sampleArray);
    bounds=double(cfg.paramBounds);
    parameterNames=cellstr(string(cfg.paramNames(:))).';
    assert(isnumeric(draws)&&size(draws,2)==size(bounds,1)&& ...
        ~isempty(draws)&&all(isfinite(draws),'all'), ...
        'inversion:save_posterior_artifact:Draws', ...
        'The retained draws are missing, nonfinite, or misdimensioned.');
    assert(isnumeric(sampleArray)&&size(sampleArray,2)==size(bounds,1)&& ...
        all(isfinite(sampleArray),'all'), ...
        'inversion:save_posterior_artifact:SampleArray', ...
        'Retained sampler-state array is nonfinite or misdimensioned.');
    lower=reshape(bounds(:,1),1,[]);
    upper=reshape(bounds(:,2),1,[]);
    assert(all(draws>=lower&draws<=upper,'all'), ...
        'inversion:save_posterior_artifact:DrawBounds', ...
        'The retained draws fall outside the configured prior bounds.');
    arrayLower=reshape(bounds(:,1),1,[],1);
    arrayUpper=reshape(bounds(:,2),1,[],1);
    assert(all(sampleArray>=arrayLower&sampleArray<=arrayUpper,'all'), ...
        'inversion:save_posterior_artifact:SampleBounds', ...
        'Retained sampler-state values fall outside configured prior bounds.');
    assert(isnumeric(result.logLikelihoodTrace)&& ...
        ~isempty(result.logLikelihoodTrace)&& ...
        all(isfinite(result.logLikelihoodTrace),'all'), ...
        'inversion:save_posterior_artifact:NonFiniteLikelihood', ...
        ['The required completed sampler-state log-likelihood trace is ' ...
         'missing or nonfinite.']);
    flattened=reshape(permute(sampleArray,[1 3 2]),[],size(bounds,1));
    assert(isequaln(draws,flattened), ...
        'inversion:save_posterior_artifact:DrawBinding', ...
        'postSample must exactly equal the flattened retained sampleArray.');
    truth=reshape(double(truth),1,[]);
    observation=reshape(double(observation),1,[]);
    assert(numel(truth)==size(bounds,1)&&all(isfinite(truth)), ...
        'inversion:save_posterior_artifact:Truth', ...
        'Truth must contain one finite value per parameter.');
    % The pressures of the cell's design are observed and finite; a pressure
    % outside the design may be missing (NaN: a direct observation whose
    % other probe has none), never another non-finite value.
    used=inversion.design_registry(paths.design).sourceOutputIndices;
    assert(~isempty(observation)&&all(isfinite(observation(used)))&& ...
        all(isfinite(observation)|isnan(observation)), ...
        'inversion:save_posterior_artifact:Observation', ...
        'Observation must be a finite nonempty vector (NaN only outside the cell''s design).');
    assert(isnumeric(seed)&&isscalar(seed)&&isfinite(seed)&& ...
        seed==fix(seed)&&seed>0, ...
        'inversion:save_posterior_artifact:Seed','Seed must be a positive integer.');

    assert(isfield(result,'directSamplerSettings')&& ...
        isstruct(result.directSamplerSettings)&& ...
        isfield(result,'directSeedRecord')&& ...
        isstruct(result.directSeedRecord), ...
        'inversion:save_posterior_artifact:SamplerSettings', ...
        'Result must carry the sampler settings and the seed record of the request.');
    request=struct( ...
        'schemaVersion','direct_mcmc_request_reference_v1', ...
        'cellID',paths.cellID, ...
        'caseID',paths.caseID, ...
        'scenario',paths.scenario, ...
        'design',paths.design, ...
        'sampler',paths.sampler, ...
        'replicateID',paths.replicateID, ...
        'stepCount',paths.stepCount, ...
        'seed',double(seed), ...
        'runMode','fresh_total_length', ...
        'loadParentState',false, ...
        'appendParentSamples',false, ...
        'poolSamples',false);
    summary=posterior_summary(draws,truth,bounds,parameterNames);
    resultState=scientific_result_state(result);
    checkpointArtifact=struct( ...
        'schemaVersion','direct_mcmc_completed_checkpoint_v1', ...
        'request',request, ...
        'parameterNames',{parameterNames}, ...
        'bounds',bounds, ...
        'truth',truth, ...
        'observation',observation, ...
        'retainedDrawsPhysical',draws, ...
        'retainedSampleArray',sampleArray, ...
        'health',health, ...
        'resultState',resultState, ...
        'terminalState','complete', ...
        'resumeSemantics','reuse_complete_request_only', ...
        'continuationSemantics',char(string( ...
            cfg.mcmc.continuationSemantics)), ...
        'samplesPooled',false);
    posteriorArtifact=struct( ...
        'schemaVersion','direct_mcmc_posterior_samples_v1', ...
        'request',request, ...
        'parameterNames',{parameterNames}, ...
        'bounds',bounds, ...
        'drawsPhysical',draws, ... recorded name: model coordinates, log10(k0) (CLN-025)
        'truth',truth, ...
        'observation',observation, ...
        'summary',summary, ...
        'health',health, ...
        'samplesPooled',false, ...
        'providerStatus','single_analysis_pending_cell_certification');
    truthArtifact=struct('schemaVersion','direct_mcmc_truth_v1', ...
        'cellID',paths.cellID,'caseID',paths.caseID,'truth',truth, ...
        'parameterNames',{parameterNames},'bounds',bounds);
    observationArtifact=struct( ...
        'schemaVersion','direct_mcmc_observation_v1', ...
        'cellID',paths.cellID,'caseID',paths.caseID, ...
        'scenario',paths.scenario,'design',paths.design, ...
        'observation',observation);

    publish_mat(paths.truthPath,'truthArtifact',truthArtifact,true);
    publish_mat(paths.observationPath,'observationArtifact',observationArtifact,true);
    publish_mat(paths.checkpointPath,'checkpointArtifact',checkpointArtifact,false);
    publish_mat(paths.posteriorPath,'posteriorArtifact',posteriorArtifact,false);
    utils.atomic_write_table(paths.summaryPath,summary);
    utils.atomic_write_table(paths.diagnosticsPath, ...
        diagnostic_table(health,parameterNames));
    metadata=struct( ...
        'schemaVersion','direct_mcmc_sampler_artifact_metadata_v2', ...
        'request',request, ...
        'retainedDrawCount',size(draws,1), ...
        'retainedIterationCount',size(sampleArray,1), ...
        'samplerStateCount',size(sampleArray,3), ...
        'physicalDrawsSaved',true, ...
        'completeRequestReusable',true, ...
        'midChainResumeAvailable',false);
    write_json(paths.metadataPath,metadata);
    receipt=metadata;
    receipt.paths=paths;
end

function state=scientific_result_state(result)
    names={'rawSample','logLikelihoodTrace','initialSamplerStates', ...
        'terminalSamplerStates','acceptancePerSamplerState','acceptance', ...
        'pointEstimate','outputs','observationTransform','paramQ025', ...
        'paramMedian','paramQ975','paramMean','paramInside95', ...
        'paramNormError','sampleSemantics','directSamplerSettings', ...
        'directSeedRecord'};
    state=struct();
    for i=1:numel(names)
        if isfield(result,names{i}),state.(names{i})=result.(names{i});end
    end
end

function summary=posterior_summary(draws,truth,bounds,names)
    width=(bounds(:,2)-bounds(:,1)).';
    priorSD=width/sqrt(12); % independent uniform-box prior
    meanValue=mean(draws,1);
    medianValue=median(draws,1);
    sdValue=std(draws,0,1);
    q=quantile(draws,[0.025 0.975],1);
    covered=truth>=q(1,:)&truth<=q(2,:);
    normalizedPosteriorSD=sdValue./priorSD;
    contractionAmount=1-normalizedPosteriorSD;
    sdOverPriorRange=sdValue./width;
    meanNormalizedRecoveryError=abs(meanValue-truth)./width;
    medianNormalizedRecoveryError=abs(medianValue-truth)./width;
    summary=table(string(names(:)),truth(:),meanValue(:),medianValue(:), ...
        sdValue(:),normalizedPosteriorSD(:),contractionAmount(:), ...
        sdOverPriorRange(:),q(1,:).',q(2,:).',covered(:), ...
        meanNormalizedRecoveryError(:),medianNormalizedRecoveryError(:), ...
        'VariableNames',{'Parameter','Truth','Mean','Median','SD', ...
        'NormalizedPosteriorSD','ContractionAmount','SDOverPriorRange', ...
        'Q025','Q975','Covered95','PosteriorMeanNormalizedRecoveryError', ...
        'PosteriorMedianNormalizedRecoveryError'});
end

function value=diagnostic_table(health,names)
    n=numel(names);
    value=table(string(names(:)),column(health,'rankSplitRhat',n), ...
        column(health,'bulkESS',n),column(health,'tailESS',n), ...
        column(health,'relativeSdMCSE',n), ...
        repmat(logical(health.pass),n,1), ...
        'VariableNames',{'Parameter','RankSplitRhat','BulkESS','TailESS', ...
        'RelativeSdMCSE','SingleAnalysisHealthPass'});
end

function value=column(source,name,n)
    if isfield(source,name)&&numel(source.(name))==n
        value=reshape(double(source.(name)),[],1);
    else
        value=nan(n,1);
    end
end

function publish_mat(pathValue,variableName,value,once)
%PUBLISH_MAT Write one artifact MAT. The truth and observation of a cell are
%   written by its first request (ONCE); a request's own files are replaced.
    if once&&isfile(pathValue),return;end
    variables=struct();variables.(variableName)=value;
    utils.atomic_save_struct(pathValue,variables,'-v7');
end

function write_json(pathValue,value)
    try
        text=jsonencode(value,'PrettyPrint',true);
    catch
        text=jsonencode(value);
    end
    utils.atomic_write_text(pathValue,[text newline]);
end
