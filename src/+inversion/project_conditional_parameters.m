function freeValues = project_conditional_parameters(canonicalValues,adapter)
%PROJECT_CONDITIONAL_PARAMETERS The free parameters of four-parameter rows.
%   FREEVALUES = inversion.project_conditional_parameters(CANONICALVALUES,
%   ADAPTER) returns the free coordinates (N-by-K) of the four-parameter
%   rows CANONICALVALUES, after checking that their fixed coordinates hold
%   the adapter's truth values.
%   Side effects: none.

    values=double(canonicalValues);
    assert(isstruct(adapter)&&isscalar(adapter)&& ...
        isfield(adapter,'schemaVersion')&& ...
        strcmp(adapter.schemaVersion,'conditional_parameter_adapter_v1')&& ...
        isfield(adapter,'freeParameterIndices')&& ...
        isfield(adapter,'fixedParameterIndices')&& ...
        isfield(adapter,'fixedParameterValues')&& ...
        isnumeric(canonicalValues)&&ismatrix(values)&&size(values,2)==4&& ...
        all(isfinite(values),'all'), ...
        'inversion:project_conditional_parameters:Inputs', ...
        'Canonical values must be a finite N-by-4 matrix and adapter valid.');
    fixed=values(:,adapter.fixedParameterIndices);
    expected=repmat(reshape(double(adapter.fixedParameterValues),1,[]), ...
        size(values,1),1);
    tolerance=32*eps(max(1,max(abs(expected),[],'all')));
    assert(all(abs(fixed-expected)<=tolerance,'all'), ...
        'inversion:project_conditional_parameters:FixedValues', ...
        'Canonical rows do not contain the adapter''s exact fixed values.');
    freeValues=values(:,adapter.freeParameterIndices);
end
