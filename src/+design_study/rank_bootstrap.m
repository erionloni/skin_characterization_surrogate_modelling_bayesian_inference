function result = rank_bootstrap(scores,designNames,direction,nReplicates,seed)
%RANK_BOOTSTRAP Paired case bootstrap with tie-aware rank uncertainty.
%   Tied ranks use midranks. ProbabilityRank1 is fractional first-place
%   credit (one divided by the number tied for best), whereas
%   ProbabilityBestOrTied reports membership in the best tie. The summary
%   deliberately distinguishes MedianCaseScore from the median of the
%   bootstrap replicate means (MedianBootstrapMeanScore).
%
%   RESULT = design_study.rank_bootstrap(SCORES, DESIGNNAMES, DIRECTION,
%   NREPLICATES, SEED) resamples the cases (rows of SCORES, cases-by-designs)
%   NREPLICATES times with the seed SEED (seeds.design_study), ranks the
%   designs in each replicate (DIRECTION: 'higher_is_better' or
%   'lower_is_better') and
%   returns the rank distribution, the first-place credit, the pairwise win
%   probabilities, the leave-one-case-out ranks and a summary table.
%   Side effects: none (the random number generator's state is restored).
    assert(nargin == 5 && ~isempty(seed), 'design_study:rank_bootstrap:Seed', ...
        'The rank bootstrap needs its seed (seeds.design_study).');
    assert(isnumeric(scores) && ismatrix(scores) && all(isfinite(scores(:))), ...
        'design_study:rank_bootstrap:Scores', ...
        'scores must be a finite cases-by-design matrix.');
    [nCases,nDesigns] = size(scores);
    assert(numel(designNames)==nDesigns && nCases>=1, ...
        'design_study:rank_bootstrap:Shape', ...
        'Design names and score matrix shape disagree.');
    direction = char(lower(string(direction)));
    assert(any(strcmp(direction,{'higher_is_better','lower_is_better'})), ...
        'design_study:rank_bootstrap:Direction', ...
        'Metric direction must be explicit.');
    assert(isscalar(nReplicates) && nReplicates==fix(nReplicates) && ...
        nReplicates>=1,'design_study:rank_bootstrap:Replicates', ...
        'nReplicates must be a positive integer.');
    previous = rng; cleanup = onCleanup(@() rng(previous));
    rng(seed,'twister');
    bootstrapScores = zeros(nReplicates,nDesigns);
    ranks = zeros(nReplicates,nDesigns);
    bestCredit = zeros(nReplicates,nDesigns);
    bestOrTied = false(nReplicates,nDesigns);
    tiedForBest = false(nReplicates,nDesigns);
    for b = 1:nReplicates
        index = randi(nCases,nCases,1);
        bootstrapScores(b,:) = mean(scores(index,:),1);
        ranks(b,:) = rank_row(bootstrapScores(b,:),direction);
        [bestCredit(b,:),bestOrTied(b,:),tiedForBest(b,:)] = ...
            best_assignment(bootstrapScores(b,:),direction);
    end
    pairwise = zeros(nDesigns);
    for i = 1:nDesigns
        for j = 1:nDesigns
            tieMask=arrayfun(@(a,b)tied(a,b), ...
                bootstrapScores(:,i),bootstrapScores(:,j));
            if strcmp(direction,'higher_is_better')
                pairwise(i,j) = mean( ...
                    bootstrapScores(:,i)>bootstrapScores(:,j) & ~tieMask) + ...
                    0.5*mean(tieMask);
            else
                pairwise(i,j) = mean( ...
                    bootstrapScores(:,i)<bootstrapScores(:,j) & ~tieMask) + ...
                    0.5*mean(tieMask);
            end
        end
    end
    leaveOneOut = nan(nCases,nDesigns);
    if nCases>1
        for c = 1:nCases
            leaveOneOut(c,:) = rank_row( ...
                mean(scores(setdiff(1:nCases,c),:),1),direction);
        end
    end
    lowerBound = column_quantile(bootstrapScores,0.025);
    upperBound = column_quantile(bootstrapScores,0.975);
    summary = table( ...
        string(designNames(:)), ...
        mean(scores,1).', ...
        median(scores,1).', ...
        median(bootstrapScores,1).', ...
        lowerBound.',upperBound.', ...
        mean(bestCredit,1).', ...
        mean(bestOrTied,1).', ...
        mean(tiedForBest,1).', ...
        mean(ranks<=min(3,nDesigns),1).', ...
        min(leaveOneOut,[],1).', ...
        max(leaveOneOut,[],1).', ...
        'VariableNames',{'Design','MeanScore','MedianCaseScore', ...
        'MedianBootstrapMeanScore','BootstrapCI025','BootstrapCI975', ...
        'ProbabilityRank1','ProbabilityBestOrTied', ...
        'ProbabilityTiedForBest','ProbabilityTop3', ...
        'LeaveOneOutBestRank','LeaveOneOutWorstRank'});
    result = struct( ...
        'schema_version','stage9_rank_bootstrap_v1_tie_aware', ...
        'direction',direction, ...
        'n_cases',nCases, ...
        'n_replicates',nReplicates, ...
        'seed',seed, ...
        'design_names',{cellstr(string(designNames))}, ...
        'bootstrap_scores',bootstrapScores, ...
        'rank_distribution',ranks, ...
        'best_rank_credit',bestCredit, ...
        'best_or_tied_for_best',bestOrTied, ...
        'tied_for_best',tiedForBest, ...
        'pairwise_win_probability',pairwise, ...
        'leave_one_case_out_ranks',leaveOneOut, ...
        'summary',summary);
end

function ranks = rank_row(values,direction)
    if strcmp(direction,'higher_is_better')
        [~,order] = sort(values,'descend');
    else
        [~,order] = sort(values,'ascend');
    end
    sorted=values(order);
    ranks=zeros(1,numel(values));
    first=1;
    while first<=numel(values)
        last=first;
        while last<numel(values) && tied(sorted(first),sorted(last+1))
            last=last+1;
        end
        ranks(order(first:last))=mean(first:last);
        first=last+1;
    end
end

function [credit,isBest,isTiedBest] = best_assignment(values,direction)
    if strcmp(direction,'higher_is_better')
        optimum=max(values);
    else
        optimum=min(values);
    end
    isBest=arrayfun(@(value) tied(value,optimum),values);
    count=sum(isBest);
    credit=zeros(size(values));
    credit(isBest)=1/count;
    isTiedBest=isBest & count>1;
end

function yes=tied(a,b)
    scale=max([1 abs(a) abs(b)]);
    yes=abs(a-b)<=64*eps(scale);
end

function value = column_quantile(matrix,p)
    sorted = sort(matrix,1);
    position = 1+(size(sorted,1)-1)*p;
    low = floor(position); high = ceil(position);
    weight = position-low;
    value = (1-weight)*sorted(max(low,1),:) + ...
        weight*sorted(min(high,size(sorted,1)),:);
end
