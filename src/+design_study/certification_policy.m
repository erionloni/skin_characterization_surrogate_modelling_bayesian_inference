function policy = certification_policy(name)
%CERTIFICATION_POLICY The posterior-certification classes of the design study.
%   The three entries correspond exactly to the direct-MCMC uncertainty
%   scenarios. Local Jacobian/FIM calculations use the same provider and do
%   not define a separate posterior-certification route.
%
%   POLICY = design_study.certification_policy(NAME) returns the entry NAME
%   (real_certified, real_certified_structural_diagnostic,
%   real_certified_self_consistency_diagnostic): its claim scope and
%   whether scientific and posterior claims are allowed and the entry is
%   eligible for the thesis.
%   Side effects: none.

    name = char(lower(string(name)));
    entries = struct( ...
        'name', { ...
            'real_certified', ...
            'real_certified_structural_diagnostic', ...
            'real_certified_self_consistency_diagnostic'}, ...
        'claim_scope', { ...
            'PRIMARY_REALISTIC', ...
            'STRUCTURAL_NO_MEASUREMENT_NOISE', ...
            'NUMERICAL_SELF_CONSISTENCY_DIAGNOSTIC'}, ...
        'scientific_claims_allowed', ...
            {true,true,true}, ...
        'posterior_claims_allowed', ...
            {true,true,true}, ...
        'thesis_eligible', ...
            {true,false,false});
    index = find(strcmp({entries.name},name),1);
    assert(~isempty(index),'design_study:certification_policy:UnknownClass', ...
        'Unknown posterior certification class "%s".',name);
    policy = entries(index);
    policy.schema_version = ...
        'stage9_direct_mcmc_certification_taxonomy_v1';
end
