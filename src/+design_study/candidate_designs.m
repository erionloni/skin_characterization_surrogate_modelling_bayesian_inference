function designs = candidate_designs()
%CANDIDATE_DESIGNS The six observation designs of the design study.
%   DESIGNS = design_study.candidate_designs() returns the six rankable
%   designs of the inversion grid (inversion.design_registry: all_six,
%   d2_only, d6_only, cycle_1_only, ratios_only,
%   physics_guided_full_rank_six), each with its output subset or
%   transform, its dimensions and its role in the design study
%   (design_study.design_semantics). Only the output-subset definitions are
%   taken from the registry, so the design study never asks for a
%   posterior outside the inversion grid.
%   Side effects: none.

    source=inversion.design_registry();
    empty=struct('name','','label','','type','','indices',[], ...
        'source_indices',[],'observation_transform','', ...
        'transform_version','','rankable',true, ...
        'source_output_dimension',0,'likelihood_output_dimension',0, ...
        'analysis_role','','comparison_class','', ...
        'reference_design','','information_claim','');
    designs=repmat(empty,1,numel(source));
    for i=1:numel(source)
        semantics=design_study.design_semantics(source(i).name);
        designs(i)=struct('name',source(i).name,'label',source(i).label, ...
            'type',source(i).type,'indices',source(i).outputIndices, ...
            'source_indices',source(i).sourceOutputIndices, ...
            'observation_transform',source(i).observationTransform, ...
            'transform_version',source(i).transformVersion, ...
            'rankable',logical(source(i).rankable), ...
            'source_output_dimension',double(source(i).sourceOutputDimension), ...
            'likelihood_output_dimension', ...
                double(source(i).likelihoodOutputDimension), ...
            'analysis_role',semantics.role, ...
            'comparison_class',semantics.comparison_class, ...
            'reference_design',semantics.reference_design, ...
            'information_claim',semantics.information_claim);
    end
    expected={'all_six','d2_only','d6_only','cycle_1_only', ...
        'ratios_only','physics_guided_full_rank_six'};
    assert(numel(designs)==6&&isequal({designs.name},expected)&& ...
        all([designs.rankable]), ...
        'design_study:candidate_designs:RegistryCardinality', ...
        ['The design registry must hold the six rankable designs all_six, d2_only, ' ...
         'd6_only, cycle_1_only, ratios_only and physics_guided_full_rank_six.']);
end
