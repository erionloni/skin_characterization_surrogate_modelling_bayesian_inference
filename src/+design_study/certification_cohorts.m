function cohorts = certification_cohorts(coverage,caseIDs,designNames,scenarioTag)
%CERTIFICATION_COHORTS The matched certified cohorts of one scenario of the design study.
%   COHORTS = design_study.certification_cohorts(COVERAGE, CASEIDS,
%   DESIGNNAMES, SCENARIOTAG) reads the certification coverage of the
%   inversion grid (COVERAGE: one row per case, scenario and design with
%   explicit ArtifactLoaded and Certified flags) for the scenario
%   SCENARIOTAG, the cases CASEIDS and the six designs DESIGNNAMES, and
%   builds, for every comparison of the design study, the cohort of cases
%   certified in exactly the designs it uses (the ranking of all designs,
%   each subset against all_six, the transformed designs against all_six).
%   Missing certifications stay explicit in the returned N-case-by-6
%   coverage; they are never turned into zero-valued observations.
%   COHORTS: the canonical coverage table, and one record per comparison
%   (its cases and count).
%   Side effects: none.

    assert(istable(coverage)&&all(ismember( ...
        {'CaseID','Scenario','Design','ArtifactLoaded','Certified'}, ...
        coverage.Properties.VariableNames)), ...
        'design_study:certification_cohorts:CoverageSchema', ...
        ['Coverage must contain CaseID, Scenario, Design, ArtifactLoaded, ' ...
         'and explicit Certified flags; loading does not imply certification.']);
    % CSV round-trips may return numeric 0/1 columns. Normalize once at the
    % shared boundary before either cohort construction or row selection.
    coverage.ArtifactLoaded=boolean_column(coverage.ArtifactLoaded, ...
        height(coverage),'ArtifactLoaded');
    coverage.Certified=boolean_column(coverage.Certified, ...
        height(coverage),'Certified');
    caseText=string(caseIDs(:));
    designText=string(designNames(:)).';
    scenarioText=string(scenarioTag);
    assert(isscalar(scenarioText)&&strlength(scenarioText)>0&& ...
        numel(unique(caseText))==numel(caseText)&& ...
        numel(unique(designText))==numel(designText)&& ...
        isequal(cellstr(designText),{'all_six','d2_only','d6_only', ...
        'cycle_1_only','ratios_only','physics_guided_full_rank_six'}), ...
        'design_study:certification_cohorts:Axes', ...
        'Cases, scenario, and the exact ordered six-design registry are required.');

    selected=coverage(string(coverage.Scenario)==scenarioText,:);
    assert(height(selected)==numel(caseText)*numel(designText), ...
        'design_study:certification_cohorts:ScenarioShape', ...
        'Scenario %s must have one explicit row for every planned cell.', ...
        scenarioText);
    canonicalRows=cell(numel(caseText)*numel(designText),1);
    available=false(numel(caseText),numel(designText));
    cursor=0;
    for c=1:numel(caseText)
        for d=1:numel(designText)
            cursor=cursor+1;
            hit=string(selected.CaseID)==caseText(c)& ...
                string(selected.Design)==designText(d);
            assert(nnz(hit)==1, ...
                'design_study:certification_cohorts:CellMultiplicity', ...
                'Coverage cell %s/%s/%s is missing or duplicated.', ...
                scenarioText,caseText(c),designText(d));
            canonicalRows{cursor}=selected(hit,:);
            available(c,d)=selected.ArtifactLoaded(hit);
        end
    end
    canonical=vertcat(canonicalRows{:});

    allDesignMask=all(available,2);
    d2Names=["d2_only" "all_six"];
    d6Names=["d6_only" "all_six"];
    cycle1Names=["cycle_1_only" "all_six"];
    ratioNames=["ratios_only" "all_six"];
    parityNames=["all_six" "physics_guided_full_rank_six"];
    d2Mask=intersection_mask(available,designText,d2Names);
    d6Mask=intersection_mask(available,designText,d6Names);
    cycle1Mask=intersection_mask(available,designText,cycle1Names);
    ratioMask=intersection_mask(available,designText,ratioNames);
    parityMask=intersection_mask(available,designText,parityNames);

    canonical.PlannedCell=true(height(canonical),1);
    caseCertified=sum(reshape(logical(canonical.Certified), ...
        numel(designText),numel(caseText)),1).';
    canonical.MissingCertification=~canonical.Certified;
    canonical.CaseCertifiedDesignCount=repelem(caseCertified(:),numel(designText),1);
    canonical.AllDesignMatched=repelem(allDesignMask(:),numel(designText),1);
    canonical.D2ToAllSixMatched=repelem(d2Mask(:),numel(designText),1);
    canonical.D6ToAllSixMatched=repelem(d6Mask(:),numel(designText),1);
    canonical.Cycle1ToAllSixMatched=repelem(cycle1Mask(:),numel(designText),1);
    canonical.RatiosToAllSixMatched=repelem(ratioMask(:),numel(designText),1);
    canonical.RepresentationParityMatched=repelem( ...
        parityMask(:),numel(designText),1);
    inclusionReason=strings(numel(caseText),1);
    for c=1:numel(caseText)
        caseRows=(c-1)*numel(designText)+(1:numel(designText));
        inclusionReason(c)=all_design_reason( ...
            canonical(caseRows,:),designText,allDesignMask(c));
    end
    canonical.included_in_all_design_ranking=repelem( ...
        allDesignMask(:),numel(designText),1);
    canonical.all_design_inclusion_reason=repelem( ...
        inclusionReason(:),numel(designText),1);

    allDesign=cohort_record('all_design_ranking','all_design', ...
        designText,allDesignMask,caseText);
    d2ToAllSix=cohort_record('subset_reference__d2_to_all_six', ...
        'subset_reference',d2Names,d2Mask,caseText);
    d6ToAllSix=cohort_record('subset_reference__d6_to_all_six', ...
        'subset_reference',d6Names,d6Mask,caseText);
    cycle1ToAllSix=cohort_record('subset_reference__cycle1_to_all_six', ...
        'subset_reference',cycle1Names,cycle1Mask,caseText);
    ratiosToAllSix=cohort_record('transform_reference__ratios_to_all_six', ...
        'transform_reference',ratioNames,ratioMask,caseText);
    representationParity=cohort_record( ...
        'representation_parity__physics_guided_to_all_six', ...
        'representation_parity',parityNames,parityMask,caseText);
    singleCells=cell(1,numel(designText));
    for d=1:numel(designText)
        singleCells{d}=cohort_record(['single_design__' char(designText(d))], ...
            'single_design',designText(d),available(:,d),caseText);
    end
    singles=[singleCells{:}];
    pairCells=cell(1,nchoosek(numel(designText),2));
    pairCursor=0;
    for a=1:numel(designText)-1
        for b=a+1:numel(designText)
            pairCursor=pairCursor+1;
            required=designText([a b]);
            pairCells{pairCursor}=cohort_record( ...
                ['design_pair__' char(required(1)) '__vs__' char(required(2))], ...
                'design_pair',required,all(available(:,[a b]),2),caseText);
            pairCells{pairCursor}.design_indices=[a b];
        end
    end
    pairs=[pairCells{:}];
    summary=vertcat(allDesign.summary,d2ToAllSix.summary, ...
        d6ToAllSix.summary,cycle1ToAllSix.summary, ...
        ratiosToAllSix.summary,representationParity.summary, ...
        singles.summary,pairs.summary);

    cohorts=struct( ...
        'schema_version','stage9_certification_cohorts_v2_six_design', ...
        'scenario',char(scenarioText), ...
        'case_ids',{cellstr(caseText)}, ...
        'design_names',{cellstr(designText)}, ...
        'planned_case_count',numel(caseText), ...
        'planned_cell_count',numel(available), ...
        'certified_cell_count',nnz(canonical.Certified), ...
        'available_cell_count',nnz(available), ...
        'missing_cell_count',nnz(~available), ...
        'all_cells_certified',all(canonical.Certified), ...
        'available_matrix',available, ...
        'coverage_table',canonical, ...
        'all_design',allDesign, ...
        'd2_to_all_six',d2ToAllSix,'d6_to_all_six',d6ToAllSix, ...
        'cycle1_to_all_six',cycle1ToAllSix, ...
        'ratios_to_all_six',ratiosToAllSix, ...
        'representation_parity',representationParity, ...
        'single_designs',singles,'pairs',pairs, ...
        'summary',summary);
end

function value=boolean_column(value,n,name)
    assert((islogical(value)||isnumeric(value))&&isreal(value)&& ...
        ~issparse(value)&&isequal(size(value),[n 1]), ...
        'design_study:certification_cohorts:BooleanColumnShape', ...
        '%s must be one logical or numeric 0/1 value per coverage row.',name);
    assert(all(isfinite(value))&&all(value==0|value==1), ...
        'design_study:certification_cohorts:BooleanColumnValue', ...
        '%s must contain only finite, nonmissing logical or numeric 0/1 flags.',name);
    value=logical(value);
end

function reason=all_design_reason(caseRows,designNames,included)
    if included
        reason="included_all_six_designs_certified";
        if ismember('Certified',caseRows.Properties.VariableNames)&& ...
                ~all(caseRows.Certified)
            reason="included_all_six_providers_available";
        end
        return
    end
    missing=~logical(caseRows.ArtifactLoaded);
    missingDesigns=designNames(missing);
    details=strings(1,nnz(missing));cursor=0;
    % MATLAB for iterates columns: visit one missing design index at a time.
    for d=reshape(find(missing),1,[])
        cursor=cursor+1;
        if ismember('CellStatus',caseRows.Properties.VariableNames)
            status=string(caseRows.CellStatus(d));
        elseif ismember('ExecutionStatus',caseRows.Properties.VariableNames)
            status=string(caseRows.ExecutionStatus(d));
        else
            status="unavailable";
        end
        identifier="none";
        if ismember('FailureIdentifiers',caseRows.Properties.VariableNames)&& ...
                strlength(string(caseRows.FailureIdentifiers(d)))>0
            identifier=string(caseRows.FailureIdentifiers(d));
        end
        details(cursor)=missingDesigns(cursor)+"[status="+status+ ...
            ",failure_identifier="+identifier+"]";
    end
    reason="excluded_missing_designs="+strjoin(missingDesigns,'|')+ ...
        "; details="+strjoin(details,' | ');
end

function indices=design_indices(registry,names)
    indices=zeros(1,numel(names));
    for i=1:numel(names)
        hit=find(registry==names(i));
        assert(isscalar(hit),'design_study:certification_cohorts:RequiredDesign', ...
            'Required design %s is absent or duplicated.',names(i));
        indices(i)=hit;
    end
end

function mask=intersection_mask(available,registry,names)
    mask=all(available(:,design_indices(registry,names)),2);
end

function value=cohort_record(name,type,required,mask,caseIDs)
    mask=logical(mask(:));
    matched=caseIDs(mask);missing=caseIDs(~mask);
    nPlanned=numel(mask);nMatched=nnz(mask);
    if nMatched==0
        status='unavailable_zero_matched_cases';
    elseif nMatched<nPlanned
        status='available_partial';
    else
        status='available_complete';
    end
    value=struct('schema_version','stage9_matched_cohort_v1', ...
        'analysis',name,'analysis_type',type, ...
        'required_designs',{cellstr(string(required))}, ...
        'case_mask',mask,'case_indices',find(mask).', ...
        'matched_case_ids',{cellstr(string(matched))}, ...
        'missing_case_ids',{cellstr(string(missing))}, ...
        'planned_case_count',nPlanned,'matched_case_count',nMatched, ...
        'missing_case_count',nPlanned-nMatched, ...
        'coverage_fraction',nMatched/nPlanned, ...
        'status',status,'warning_below_planned_n',nMatched<nPlanned);
    value.summary=table(string(name),string(type), ...
        string(strjoin(string(required),'|')),numel(required),nPlanned, ...
        nMatched,nPlanned-nMatched,nMatched/nPlanned,string(status), ...
        nMatched<nPlanned,string(strjoin(string(matched),'|')), ...
        string(strjoin(string(missing),'|')), ...
        'VariableNames',{'Analysis','AnalysisType','RequiredDesigns', ...
        'RequiredDesignCount','PlannedCaseCount','MatchedCaseCount', ...
        'MissingCaseCount','CoverageFraction','Status','WarningBelowPlannedN', ...
        'MatchedCaseIDs','MissingCaseIDs'});
end
