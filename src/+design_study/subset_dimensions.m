function tableOut = subset_dimensions(designs)
%SUBSET_DIMENSIONS Mathematical dimensions of registered output subsets.
%   These fields describe only likelihood and source-vector dimensions.
%
%   TABLEOUT = design_study.subset_dimensions(DESIGNS) returns one row per
%   design: its source-output and likelihood-output dimensions.
%   Side effects: none.

    if nargin<1||isempty(designs),designs=design_study.candidate_designs();end
    tableOut=table(string({designs.name}).',string({designs.label}).', ...
        string({designs.type}).',[designs.source_output_dimension].', ...
        [designs.likelihood_output_dimension].', ...
        string({designs.observation_transform}).', ...
        string({designs.transform_version}).', ...
        string({designs.analysis_role}).', ...
        string({designs.comparison_class}).', ...
        string({designs.reference_design}).', ...
        string({designs.information_claim}).', ...
        string(arrayfun(@source_text,designs,'UniformOutput',false)).', ...
        string(arrayfun(@likelihood_text,designs,'UniformOutput',false)).', ...
        [designs.rankable].', ...
        'VariableNames',{'Design','Label','SubsetType', ...
        'SourceOutputDimension','LikelihoodOutputDimension', ...
        'ObservationTransform','TransformVersion','AnalysisRole', ...
        'ComparisonClass','ReferenceDesign','InformationClaim', ...
        'SourceOutputIndices','LikelihoodOutputIndices','Rankable'});
end

function text=source_text(design)
    text=strjoin(string(design.source_indices),',');
end

function text=likelihood_text(design)
    switch design.type
        case 'ratio'
            text='transformed_ratio_outputs_1_to_4';
        case 'transformed_full_rank'
            text='physics_guided_transformed_outputs_1_to_6';
        otherwise
            text=strjoin(string(design.indices),',');
    end
end
