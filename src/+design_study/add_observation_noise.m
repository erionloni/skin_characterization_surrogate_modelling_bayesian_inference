function perturbed = add_observation_noise(observation,noise)
%ADD_OBSERVATION_NOISE One pressure vector plus each row of a noise matrix.
%   PERTURBED = design_study.add_observation_noise(OBSERVATION, NOISE) adds
%   the six closing pressures OBSERVATION (1-by-6, mbar) to every row of
%   NOISE (N-by-6, mbar) and returns the N-by-6 perturbed observations.
%   Side effects: none.
    assert(isnumeric(observation)&&isreal(observation)&& ...
        isvector(observation)&&numel(observation)==6&& ...
        all(isfinite(observation(:))), ...
        'design_study:add_observation_noise:ObservationShape', ...
        'observation must be one finite real six-pressure vector.');
    assert(isnumeric(noise)&&isreal(noise)&&ismatrix(noise)&& ...
        size(noise,1)>0&&size(noise,2)==6&&all(isfinite(noise(:))), ...
        'design_study:add_observation_noise:NoiseShape', ...
        'noise must be a finite real N-by-6 matrix with N positive.');
    observation=observation(:).';
    perturbed=observation+noise;
end
