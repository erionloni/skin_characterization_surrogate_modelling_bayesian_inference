function T=empty_schema(names,stringNames,logicalNames)
    values=cell(1,numel(names));
    for i=1:numel(names)
        if ismember(names{i},stringNames)
            values{i}=strings(0,1);
        elseif ismember(names{i},logicalNames)
            values{i}=false(0,1);
        else
            values{i}=nan(0,1);
        end
    end
    T=table(values{:},'VariableNames',names);
end

function options=parse_options(options,varargin)
    assert(mod(numel(varargin),2)==0,'design_study:generate:Options', ...
        'Optional inputs must be name/value pairs.');
    fields=fieldnames(options);
    for i=1:2:numel(varargin)
        hit=find(strcmpi(char(string(varargin{i})),fields),1);
        assert(~isempty(hit),'design_study:generate:UnknownOption', ...
            'Unknown option "%s".',char(string(varargin{i})));
        options.(fields{hit})=varargin{i+1};
    end
end
