function report = generate(provider,outputRoot,varargin)
%GENERATE The design study of one scenario, from the posteriors of the selected providers.
%   The provider supplies the real cases, GP forward evaluations, local
%   observation covariances, and saved posteriors for six active designs.
%   Writes the tables of one scenario below OUTPUTROOT/tables, its narrative
%   report, the provider definition and the result MAT (design_study.mat),
%   replacing earlier versions. The figures are drawn by the renderers.
%
%   REPORT = design_study.generate(PROVIDER, OUTPUTROOT, ...) evaluates, for
%   every case and design of the provider (recovery.design_study_provider),
%   the posterior reference metrics, the local FIM metrics and the SVD
%   directions, the covariance decomposition and ratio validation, the
%   bootstrap rank uncertainty (design_study.rank_bootstrap), the
%   sequential information and the matched cohorts, and returns their
%   summary. Options, every one required (the settings of the design study,
%   A.8, and its seeds, seeds.design_study): 'BootstrapReplicates',
%   'BootstrapSeed', 'RatioValidationDraws', 'RatioValidationSeeds' (the
%   seed of the ratio check of every case of the provider, in its order),
%   'RatioValidationTolerance' (the largest relative Frobenius difference
%   of the delta-method and Monte Carlo ratio covariances that passes),
%   'FiniteDifferenceStep' (the step of the FIM metrics in the unit box) and
%   'FiniteDifferenceCheckSteps' (the two steps of their step check);
%   'RunCovarianceDecomposition' and 'RunRatioValidation' (true).
%   Side effects: writes the files above below OUTPUTROOT.
%   Computation: minutes per scenario.

    options = struct('BootstrapReplicates',[],'BootstrapSeed',[], ...
        'RatioValidationDraws',[],'RatioValidationSeeds',[], ...
        'RatioValidationTolerance',[],'FiniteDifferenceStep',[], ...
        'FiniteDifferenceCheckSteps',[], ...
        'RunCovarianceDecomposition',true,'RunRatioValidation',true);
    options = parse_options(options,varargin{:});
    required = {'BootstrapReplicates','BootstrapSeed','RatioValidationDraws', ...
        'RatioValidationTolerance','FiniteDifferenceStep','FiniteDifferenceCheckSteps'};
    missing = required(cellfun(@(name) isempty(options.(name)), required));
    assert(isempty(missing),'design_study:generate:Options', ...
        'The design study needs the options %s (settings A.8).',strjoin(missing,', '));
    assert(numel(options.FiniteDifferenceCheckSteps)==2, ...
        'design_study:generate:FiniteDifferenceCheckSteps', ...
        'The step check of the FIM metrics needs two steps.');
    assert(isscalar(options.BootstrapReplicates)&& ...
        isfinite(options.BootstrapReplicates)&& ...
        options.BootstrapReplicates==fix(options.BootstrapReplicates)&& ...
        options.BootstrapReplicates>=1&&isscalar(options.BootstrapSeed)&& ...
        isfinite(options.BootstrapSeed)&& ...
        options.BootstrapSeed==fix(options.BootstrapSeed)&& ...
        options.BootstrapSeed>0&& ...
        isscalar(options.RatioValidationDraws)&& ...
        isfinite(options.RatioValidationDraws)&& ...
        options.RatioValidationDraws==fix(options.RatioValidationDraws)&& ...
        options.RatioValidationDraws>=2, ...
        'design_study:generate:RandomizationOptions', ...
        'Bootstrap and ratio-validation counts/seeds must be positive integers.');
    certification = design_study.certification_policy( ...
        provider.posterior_certification);
    realScenarioPolicy=design_study.real_scenario_policy();
    realCertifications=realScenarioPolicy.certifications;
    assert(any(strcmp(provider.posterior_certification,realCertifications)), ...
        'design_study:generate:PosteriorNotCertified', ...
        'The design study needs posteriors of one of the three direct-MCMC scenario classes.');
    tableDir = fullfile(outputRoot,'tables');
    if ~isfolder(tableDir), mkdir(tableDir); end

    rankable = provider.designs([provider.designs.rankable]);
    assert(numel(rankable)==6,'design_study:generate:DesignCount', ...
        'The design study needs exactly the six canonical designs.');
    nCases = provider.n_cases;
    nDesigns = numel(rankable);
    available=provider.certification_cohorts.available_matrix;
    assert(isequal(size(available),[nCases nDesigns]), ...
        'design_study:generate:CertificationCoverageShape', ...
        ['The certification coverage of the provider must be %d cases x %d designs; ' ...
         'it is %d x %d.'],nCases,nDesigns,size(available,1),size(available,2));
    qInfo = nan(nCases,nDesigns);
    fullInfo = nan(nCases,nDesigns);
    posteriorTrace = nan(nCases,nDesigns);
    posteriorQTrace = nan(nCases,nDesigns);
    DUtility = nan(nCases,nDesigns);
    ALoss = nan(nCases,nDesigns);
    cM3e = nan(nCases,nDesigns);
    cK0 = nan(nCases,nDesigns);
    condition = nan(nCases,nDesigns);
    rankValue = nan(nCases,nDesigns);
    fimPosteriorError = nan(nCases,nDesigns);
    meanWidth = nan(nCases,nDesigns);
    meanContraction = nan(nCases,nDesigns);
    meanRecovery = nan(nCases,nDesigns);
    coverage = nan(nCases,nDesigns);
    stepErrorLow = nan(nCases,nDesigns);
    stepErrorHigh = nan(nCases,nDesigns);
    cellReliable=false(nCases,nDesigns);
    cellEligible=false(nCases,nDesigns);
    cellReliabilityReason=cell(nCases,nDesigns);
    posteriorRows = cell(nCases*nDesigns,1);
    fimRows = cell(nCases*nDesigns,1);
    svdRows = cell(nCases*nDesigns*4,1);
    parameterRows = cell(nCases*nDesigns*4,1);
    covarianceRows = cell(nCases*nDesigns*16,1);
    eigenvalueRows = cell(nCases*nDesigns*4,1);
    if options.RunCovarianceDecomposition
        decompositionRows=cell(nCases*nDesigns*4,1);
        decompositionPairRows=cell(nCases*nDesigns*4*nchoosek(4,2),1);
        decompositionTraceRows=cell(nCases*nDesigns*10,1);
    else
        decompositionRows=cell(0,1);
        decompositionPairRows=cell(0,1);
        decompositionTraceRows=cell(0,1);
    end
    row = 0; svdRow = 0; parameterRow=0;
    covarianceRow=0; eigenvalueRow=0;
    decompositionRow=0;decompositionPairRow=0;
    decompositionTraceRow=0;

    for c = 1:nCases
        for d = 1:nDesigns
            design = rankable(d);
            if ~available(c,d)
                cellReliabilityReason{c,d}=coverage_reason(provider,c,d);
                continue
            end
            row = row+1;
            posterior = design_study.posterior_metrics(provider,c,design);
            posteriorReference = provider.posterior_provider(c,design);
            [cellReliable(c,d),cellReliabilityReason{c,d}]= ...
                posterior_cell_reliability(posteriorReference);
            % Every cell with a selected provider counts, certified or a healthy
            % fallback of the shipped draws (as the thesis's analysis of the
            % combined cells); its reliability stays recorded.
            cellEligible(c,d)=logical(posteriorReference.reliability.analysisEligible);
            fim = design_study.fim_metrics(provider,c,design,options.FiniteDifferenceStep);
            fimLow = design_study.fim_metrics(provider,c,design, ...
                options.FiniteDifferenceCheckSteps(1));
            fimHigh = design_study.fim_metrics(provider,c,design, ...
                options.FiniteDifferenceCheckSteps(2));
            qInfo(c,d) = posterior.q_information_gain;
            fullInfo(c,d) = posterior.full_information_gain;
            posteriorTrace(c,d) = posterior.full_trace;
            posteriorQTrace(c,d) = posterior.q_trace;
            DUtility(c,d) = fim.D_optimal_utility;
            ALoss(c,d) = fim.A_optimal_loss;
            cM3e(c,d) = fim.c_m3e_loss;
            cK0(c,d) = fim.c_k0_loss;
            condition(c,d) = fim.condition_number;
            rankValue(c,d) = fim.numerical_rank;
            fimPosteriorError(c,d) = ...
                fim.fim_to_posterior_covariance_relative_error;
            meanWidth(c,d) = mean(posterior.normalized_posterior_sd);
            meanContraction(c,d) = mean(posterior.contraction_amount);
            meanRecovery(c,d) = ...
                mean(posterior.posterior_mean_recovery_error_u);
            coverage(c,d) = mean(posterior.truth_covered_95);
            stepErrorLow(c,d) = norm(fimLow.jacobian-fim.jacobian,'fro')/ ...
                max(norm(fim.jacobian,'fro'),eps);

            scale=provider.parameter_bounds(:,2)- ...
                provider.parameter_bounds(:,1);
            truthU=provider.cases(c).truth_u(:);
            % ...U: the unit cube; ...Physical (the recorded column names): the
            % parameter's model coordinates, log10(k0) for the permeability.
            truthPhysical=provider.parameter_bounds(:,1)+scale.*truthU;
            meanPhysical=provider.parameter_bounds(:,1)+ ...
                scale.*posteriorReference.mean_u;
            sdPhysical=scale.*posteriorReference.sd_u;
            ciPhysical=provider.parameter_bounds(:,1)+ ...
                scale.*posteriorReference.credible_interval_95_u;
            for p=1:4
                parameterRow=parameterRow+1;
                parameterRows{parameterRow}=table( ...
                    string(provider.case_ids{c}),string(design.name), ...
                    string(provider.parameter_names{p}),p,truthU(p), ...
                    truthPhysical(p),posteriorReference.mean_u(p), ...
                    meanPhysical(p),posteriorReference.sd_u(p), ...
                    sdPhysical(p), ...
                    posteriorReference.credible_interval_95_u(p,1), ...
                    posteriorReference.credible_interval_95_u(p,2), ...
                    ciPhysical(p,1),ciPhysical(p,2), ...
                    posterior.normalized_posterior_sd(p), ...
                    posterior.contraction_amount(p), ...
                    posterior.posterior_mean_recovery_error_u(p), ...
                    posterior.truth_covered_95(p), ...
                    'VariableNames',{'CaseID','Design','Parameter', ...
                    'ParameterIndex','TruthU','TruthPhysical','PosteriorMeanU', ...
                    'PosteriorMeanPhysical','PosteriorSDU','PosteriorSDPhysical', ...
                    'CI025U','CI975U','CI025Physical','CI975Physical', ...
                    'NormalizedPosteriorSD','ContractionAmount', ...
                    'RecoveryErrorU','TruthCovered95'});
                eigenvalueRow=eigenvalueRow+1;
                eigenvalueRows{eigenvalueRow}=table( ...
                    string(provider.case_ids{c}),string(design.name),p, ...
                    fim.eigenvalues(p), ...
                    'VariableNames',{'CaseID','Design','EigenvalueIndex', ...
                    'FIMEigenvalue'});
                for qIndex=1:4
                    covarianceRow=covarianceRow+1;
                    covarianceRows{covarianceRow}=table( ...
                        string(provider.case_ids{c}),string(design.name), ...
                        string(provider.parameter_names{p}), ...
                        string(provider.parameter_names{qIndex}),p,qIndex, ...
                        posteriorReference.covariance_u(p,qIndex), ...
                        scale(p)*scale(qIndex)* ...
                            posteriorReference.covariance_u(p,qIndex), ...
                        posteriorReference.correlation(p,qIndex), ...
                        'VariableNames',{'CaseID','Design','RowParameter', ...
                        'ColumnParameter','RowIndex','ColumnIndex', ...
                        'CovarianceU','CovariancePhysical','Correlation'});
                end
            end
            stepErrorHigh(c,d) = norm(fimHigh.jacobian-fim.jacobian,'fro')/ ...
                max(norm(fim.jacobian,'fro'),eps);

            posteriorRows{row} = table( ...
                string(provider.case_ids{c}),string(design.name), ...
                posterior.full_information_gain,posterior.q_information_gain, ...
                posterior.full_trace,posterior.q_trace, ...
                mean(posterior.normalized_posterior_sd), ...
                mean(posterior.contraction_amount), ...
                mean(posterior.posterior_mean_recovery_error_u), ...
                mean(posterior.truth_covered_95), ...
                string(posterior.posterior_kind), ...
                'VariableNames',{'CaseID','Design', ...
                'FullInformationGain','QInformationGain','FullTrace','QTrace', ...
                'MeanNormalizedPosteriorSD','MeanContractionAmount', ...
                'MeanPosteriorMeanRecoveryErrorU','Coverage95', ...
                'PosteriorKind'});
            fimRows{row} = table( ...
                string(provider.case_ids{c}),string(design.name), ...
                fim.D_optimal_utility,fim.A_optimal_loss, ...
                fim.c_m3e_loss,fim.c_k0_loss,fim.q_trace,fim.q_logdet, ...
                fim.q_log_volume_reduction,fim.information_gain, ...
                fim.condition_number,fim.numerical_rank, ...
                fim.q_subspace_alignment, ...
                fim.fim_to_posterior_covariance_relative_error, ...
                stepErrorLow(c,d),stepErrorHigh(c,d), ...
                'VariableNames',{'CaseID','Design','DOptimalUtility', ...
                'AOptimalLoss','CM3eLoss','CK0Loss','QTrace','QLogDet', ...
                'QLogVolumeReduction','InformationGain','ConditionNumber', ...
                'NumericalRank','QSubspaceAlignment', ...
                'FIMToPosteriorCovarianceRelativeError', ...
                'JacobianErrorH5e4','JacobianErrorH2e3'});
            for k = 1:4
                svdRow = svdRow+1;
                svdRows{svdRow} = table( ...
                    string(provider.case_ids{c}),string(design.name),k, ...
                    fim.singular_values(k),fim.normalized_singular_spectrum(k), ...
                    fim.right_singular_vectors(1,k), ...
                    fim.right_singular_vectors(2,k), ...
                    fim.right_singular_vectors(3,k), ...
                    fim.right_singular_vectors(4,k), ...
                    'VariableNames',{'CaseID','Design','DirectionIndex', ...
                    'SingularValue','NormalizedSingularValue','Loading_m3f', ...
                    'Loading_m3e','Loading_log10k0','Loading_Thickness'});
            end
            if options.RunCovarianceDecomposition
                decomposition = design_study.covariance_decomposition( ...
                    provider,c,design,'Step',options.FiniteDifferenceStep);
                for ratio = 1:4
                    decompositionRow=decompositionRow+1;
                    decompositionRows{decompositionRow} = table( ...
                        string(provider.case_ids{c}),string(design.name),ratio, ...
                        decomposition.linearized_ratio_covariance(ratio,ratio), ...
                        decomposition.monte_carlo_ratio_covariance(ratio,ratio), ...
                        decomposition.absolute_variance_error(ratio), ...
                        decomposition.relative_variance_error(ratio), ...
                        decomposition.own_variance_contributions(ratio,1), ...
                        decomposition.own_variance_contributions(ratio,2), ...
                        decomposition.own_variance_contributions(ratio,3), ...
                        decomposition.own_variance_contributions(ratio,4), ...
                        sum(decomposition.signed_covariance_contributions(ratio,:)), ...
                        'VariableNames',{'CaseID','Design','RatioIndex', ...
                        'LinearizedVariance','MonteCarloVariance','AbsoluteError', ...
                        'RelativeError','Own_m3f','Own_m3e','Own_log10k0', ...
                        'Own_Thickness','SignedCovarianceTotal'});
                    for pair=1:size(decomposition.parameter_pairs,1)
                        indices=decomposition.parameter_pairs(pair,:);
                        decompositionPairRow=decompositionPairRow+1;
                        decompositionPairRows{decompositionPairRow}=table( ...
                            string(provider.case_ids{c}), ...
                            string(design.name),ratio,pair,indices(1),indices(2), ...
                            string(provider.parameter_names{indices(1)}), ...
                            string(provider.parameter_names{indices(2)}), ...
                            decomposition.signed_covariance_contributions( ...
                                ratio,pair), ...
                            'VariableNames',{'CaseID','Design','RatioIndex', ...
                            'PairIndex','ParameterIndex1','ParameterIndex2', ...
                            'Parameter1','Parameter2','SignedContribution'});
                    end
                end
                labels=[string(provider.parameter_names) ...
                    "cov_m3f_m3e" "cov_m3f_log10k0" ...
                    "cov_m3f_Thickness" "cov_m3e_log10k0" ...
                    "cov_m3e_Thickness" "cov_log10k0_Thickness"];
                signed=[decomposition.aggregate_own_trace_contributions; ...
                    decomposition.aggregate_signed_covariance_trace_contributions];
                for component=1:numel(labels)
                    decompositionTraceRow=decompositionTraceRow+1;
                    decompositionTraceRows{decompositionTraceRow}=table( ...
                        string(provider.case_ids{c}),string(design.name), ...
                        component,labels(component),signed(component), ...
                        decomposition.normalized_absolute_trace_contributions( ...
                            component), ...
                        'VariableNames',{'CaseID','Design','ComponentIndex', ...
                        'Component','SignedTraceContribution', ...
                        'NormalizedAbsoluteTraceShare'});
                end
            end
        end
    end
    assert(all(cellEligible(available))&&~any(cellEligible(~available)), ...
        'design_study:generate:UnreliableRealCell', ...
        ['Every cell the design study uses must have a selected provider (certified ' ...
         'or a healthy fallback); unavailable cells stay explicit and unused.']);

    posteriorTable = stack_rows(posteriorRows,row,empty_posterior_table());
    fimTable = stack_rows(fimRows,row,empty_fim_table());
    svdTable = stack_rows(svdRows,svdRow,empty_svd_table());
    parameterTable=stack_rows( ...
        parameterRows,parameterRow,empty_parameter_table());
    covarianceTable=stack_rows( ...
        covarianceRows,covarianceRow,empty_covariance_table());
    eigenvalueTable=stack_rows( ...
        eigenvalueRows,eigenvalueRow,empty_eigenvalue_table());
    metadata = design_study.make_metadata(provider);
    posteriorTable = design_study.attach_metadata(posteriorTable,metadata);
    fimTable = design_study.attach_metadata(fimTable,metadata);
    svdTable = design_study.attach_metadata(svdTable,metadata);
    parameterTable=design_study.attach_metadata(parameterTable,metadata);
    covarianceTable=design_study.attach_metadata(covarianceTable,metadata);
    eigenvalueTable=design_study.attach_metadata(eigenvalueTable,metadata);
    write_table(posteriorTable,fullfile(tableDir,'posterior_reference.csv'));
    write_table(fimTable,fullfile(tableDir,'fim_metrics.csv'));
    write_table(svdTable,fullfile(tableDir,'svd_directions.csv'));
    write_table(parameterTable, ...
        fullfile(tableDir,'posterior_parameter_reference.csv'));
    write_table(covarianceTable, ...
        fullfile(tableDir,'posterior_covariance_reference.csv'));
    write_table(eigenvalueTable, ...
        fullfile(tableDir,'fim_eigenvalues.csv'));

    if options.RunCovarianceDecomposition
        decompositionTable = design_study.attach_metadata(stack_rows( ...
            decompositionRows,decompositionRow,empty_decomposition_table()), ...
            metadata);
        decompositionPairTable=design_study.attach_metadata(stack_rows( ...
            decompositionPairRows,decompositionPairRow, ...
            empty_decomposition_pair_table()),metadata);
        decompositionTraceTable=design_study.attach_metadata(stack_rows( ...
            decompositionTraceRows,decompositionTraceRow, ...
            empty_decomposition_trace_table()),metadata);
        write_table(decompositionTable, ...
            fullfile(tableDir,'covariance_decomposition_variance.csv'));
        write_table(decompositionPairTable, ...
            fullfile(tableDir,'covariance_decomposition_pairs.csv'));
        write_table(decompositionTraceTable, ...
            fullfile(tableDir,'covariance_decomposition_trace_shares.csv'));
    else
        decompositionTable = table();
        decompositionPairTable=table();
        decompositionTraceTable=table();
    end

    designNames = {rankable.name};
    scoreSet=struct('q_information',qInfo,'D_optimal',DUtility, ...
        'A_optimal',ALoss,'q_trace',posteriorQTrace);
    directions=struct('q_information','higher_is_better', ...
        'D_optimal','higher_is_better','A_optimal','lower_is_better', ...
        'q_trace','lower_is_better');
    [bootstraps,bootstrapTable]=all_design_bootstraps( ...
        scoreSet,directions,designNames,provider.certification_cohorts.all_design, ...
        options.BootstrapReplicates,options.BootstrapSeed,metadata);
    pairwiseTable=pairwise_bootstraps(scoreSet,directions,designNames, ...
        provider.certification_cohorts,options.BootstrapReplicates, ...
        options.BootstrapSeed);
    bootstrapTable = design_study.attach_metadata(bootstrapTable,metadata);
    pairwiseTable = design_study.attach_metadata(pairwiseTable,metadata);
    write_table(bootstrapTable,fullfile(tableDir,'rank_bootstrap_summary.csv'));
    write_table(pairwiseTable,fullfile(tableDir,'rank_pairwise_probability.csv'));

    sequences = make_sequence_table(provider,provider.certification_cohorts);
    sequences = design_study.attach_metadata(sequences,metadata);
    write_table(sequences,fullfile(tableDir,'sequential_information.csv'));

    dimensions = provider.subset_dimensions;
    dimensions.InformationPerLikelihoodOutput = nan(height(dimensions),1);
    dimensions.QInformationPerLikelihoodOutput = nan(height(dimensions),1);
    dimensions.MatchedCaseCount=repmat( ...
        provider.certification_cohorts.all_design.matched_case_count, ...
        height(dimensions),1);
    dimensions.PlannedCaseCount=repmat( ...
        provider.n_cases,height(dimensions),1);
    for d = 1:nDesigns
        hit = find(dimensions.Design==string(designNames{d}),1);
        matched=provider.certification_cohorts.all_design.case_mask;
        if any(matched)
            dimensions.InformationPerLikelihoodOutput(hit) = ...
                mean(fullInfo(matched,d))/ ...
                dimensions.LikelihoodOutputDimension(hit);
            dimensions.QInformationPerLikelihoodOutput(hit) = ...
                mean(qInfo(matched,d))/ ...
                dimensions.LikelihoodOutputDimension(hit);
        end
    end
    dimensions = design_study.attach_metadata(dimensions,metadata);
    write_table(dimensions,fullfile(tableDir,'subset_dimensionality.csv'));

    comparisonSemantics=design_semantics_table(rankable);
    comparisonSemantics=design_study.attach_metadata(comparisonSemantics,metadata);
    write_table(comparisonSemantics,fullfile(tableDir, ...
        'design_comparison_semantics.csv'));

    referenceDifferences=design_reference_differences( ...
        parameterTable,rankable,provider.certification_cohorts,provider);
    referenceDifferences=design_study.attach_metadata(referenceDifferences,metadata);
    write_table(referenceDifferences,fullfile(tableDir, ...
        'design_reference_differences.csv'));

    cases = case_table(provider,available);
    cases = design_study.attach_metadata(cases,metadata);
    write_table(cases,fullfile(tableDir,'case_registry.csv'));

    reliabilityTable=cell_reliability_table(provider,rankable, ...
        cellReliable,cellReliabilityReason);
    reliabilityTable=design_study.attach_metadata(reliabilityTable,metadata);
    write_table(reliabilityTable, ...
        fullfile(tableDir,'posterior_reliability_eligibility.csv'));

    scenarioCoverage=design_study.attach_metadata( ...
        provider.certification_coverage,metadata);
    cohortSummary=provider.certification_cohorts.summary;
    cohortSummary.Scenario=repmat(string(provider.scenario_tag), ...
        height(cohortSummary),1);
    cohortSummary=movevars(cohortSummary,'Scenario','Before',1);
    cohortSummary=design_study.attach_metadata(cohortSummary,metadata);
    write_table(scenarioCoverage,fullfile(tableDir, ...
        'certification_coverage.csv'));
    write_table(cohortSummary,fullfile(tableDir, ...
        'matched_analysis_summary.csv'));

    if options.RunRatioValidation
        [ratioValidation,ratioValidationEntries] = ratio_validation( ...
            provider,options.RatioValidationSeeds,options.RatioValidationDraws, ...
            options.RatioValidationTolerance);
        ratioValidation = design_study.attach_metadata(ratioValidation,metadata);
        ratioValidationEntries=design_study.attach_metadata( ...
            ratioValidationEntries,metadata);
        write_table(ratioValidation, ...
            fullfile(tableDir,'ratio_delta_method_validation.csv'));
        write_table(ratioValidationEntries, ...
            fullfile(tableDir,'ratio_delta_method_covariance_entries.csv'));
    else
        ratioValidation = table();
        ratioValidationEntries=table();
    end

    aggregate=aggregate_design_table(designNames, ...
        provider.certification_cohorts.all_design,qInfo,fullInfo,DUtility, ...
        ALoss,cM3e,cK0,meanWidth,meanContraction,meanRecovery,coverage, ...
        condition,rankValue,fimPosteriorError,stepErrorLow,stepErrorHigh);
    aggregate = design_study.attach_metadata(aggregate,metadata);
    write_table(aggregate,fullfile(tableDir,'design_summary.csv'));

    narrativeName=narrative_name(provider);
    narrativePath = fullfile(outputRoot,narrativeName);
    write_narrative(narrativePath,provider,aggregate,bootstraps,metadata);

    resultPayload = struct( ...
        'schema_version','direct_mcmc_stage9a_result_v1', ...
        'route',provider.route, ...
        'posterior_certification',provider.posterior_certification, ...
        'design_names',{designNames}, ...
        'case_ids',{provider.case_ids}, ...
        'bootstrap_replicates',options.BootstrapReplicates, ...
        'certified_cell_count',provider.certification_cohorts.certified_cell_count, ...
        'missing_cell_count',provider.certification_cohorts.missing_cell_count, ...
        'all_design_matched_case_count', ...
            provider.certification_cohorts.all_design.matched_case_count, ...
        'metadata',metadata, ...
        'aggregate_table',aggregate, ...
        'posterior_table',posteriorTable, ...
        'posterior_parameter_table',parameterTable, ...
        'posterior_covariance_table',covarianceTable, ...
        'fim_table',fimTable, ...
        'fim_eigenvalue_table',eigenvalueTable, ...
        'svd_table',svdTable, ...
        'sequential_table',sequences, ...
        'subset_dimension_table',dimensions, ...
        'design_comparison_semantics_table',comparisonSemantics, ...
        'design_reference_differences_table',referenceDifferences, ...
        'reliability_table',reliabilityTable, ...
        'certification_coverage_table',scenarioCoverage, ...
        'matched_analysis_summary_table',cohortSummary, ...
        'pairwise_probability_table',pairwiseTable, ...
        'ratio_validation_table',ratioValidation, ...
        'ratio_validation_entry_table',ratioValidationEntries, ...
