function T=design_reference_differences(parameterTable,designs,cohorts,provider)
%DESIGN_REFERENCE_DIFFERENCES Pair-matched parameter metrics vs all_six.
%   No unavailable cell is materialized as a numerical zero. Every row is
%   supported by both exact certified posteriors in the named pair cohort.
    reference='all_six';rows=cell(0,1);cursor=0;
    for d=1:numel(designs)
        if strcmp(designs(d).name,reference),continue;end
        cohort=find_pair_cohort(cohorts,reference,designs(d).name);
        for c=cohort.case_indices
            caseID=string(provider.case_ids{c});
            for p=1:numel(provider.parameter_names)
                parameter=string(provider.parameter_names{p});
                base=string(parameterTable.CaseID)==caseID& ...
                    string(parameterTable.Design)==reference& ...
                    string(parameterTable.Parameter)==parameter;
                compared=string(parameterTable.CaseID)==caseID& ...
                    string(parameterTable.Design)==string(designs(d).name)& ...
                    string(parameterTable.Parameter)==parameter;
                assert(nnz(base)==1&&nnz(compared)==1, ...
                    'design_study:generate:ReferenceDifferenceCell', ...
                    'A pair-matched posterior parameter row is unavailable.');
                baseSD=parameterTable.NormalizedPosteriorSD(base);
                designSD=parameterTable.NormalizedPosteriorSD(compared);
                baseContraction=parameterTable.ContractionAmount(base);
                designContraction=parameterTable.ContractionAmount(compared);
                cursor=cursor+1;
                rows{cursor}=table(caseID,parameter,string(reference), ...
                    string(designs(d).name),string(designs(d).analysis_role), ...
                    string(designs(d).comparison_class),baseSD,designSD, ...
                    designSD-baseSD,baseContraction,designContraction, ...
                    designContraction-baseContraction, ...
                    cohort.planned_case_count,cohort.matched_case_count, ...
                    cohort.missing_case_count,string(cohort.status), ...
                    'VariableNames',{'CaseID','Parameter','ReferenceDesign', ...
                    'ComparedDesign','AnalysisRole','ComparisonClass', ...
                    'ReferenceNormalizedPosteriorSD', ...
                    'ComparedNormalizedPosteriorSD', ...
                    'DeltaNormalizedPosteriorSD', ...
                    'ReferenceContractionAmount','ComparedContractionAmount', ...
                    'DeltaContractionAmount','PlannedCaseCount', ...
                    'MatchedCaseCount','MissingCaseCount','AnalysisStatus'});
            end
        end
    end
    if cursor==0
        names={'CaseID','Parameter','ReferenceDesign','ComparedDesign', ...
            'AnalysisRole','ComparisonClass','ReferenceNormalizedPosteriorSD', ...
            'ComparedNormalizedPosteriorSD','DeltaNormalizedPosteriorSD', ...
            'ReferenceContractionAmount','ComparedContractionAmount', ...
            'DeltaContractionAmount','PlannedCaseCount','MatchedCaseCount', ...
            'MissingCaseCount','AnalysisStatus'};
        T=empty_schema(names,{'CaseID','Parameter','ReferenceDesign', ...
            'ComparedDesign','AnalysisRole','ComparisonClass', ...
            'AnalysisStatus'},{});
    else
        T=vertcat(rows{:});
    end
end

function cohort=find_pair_cohort(cohorts,a,b)
    wanted=sort(string({a,b}));
    hit=arrayfun(@(one)isequal(sort(string(one.required_designs)),wanted), ...
        cohorts.pairs);
    assert(nnz(hit)==1,'design_study:generate:ReferencePairCohort', ...
        'The provider has %d certification cohorts for the design pair %s and %s, not one.', ...
        nnz(hit),string(a),string(b));
    cohort=cohorts.pairs(hit);
end

