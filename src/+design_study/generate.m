function tableOut=pairwise_bootstraps( ...
        scoreSet,directions,designNames,cohorts,nReplicates,seed)
    names=fieldnames(scoreSet);
    rows=cell(numel(names)*numel(cohorts.pairs),1);row=0;
    modulus=2147483646;
    for i=1:numel(names)
        name=names{i};direction=directions.(name);
        for p=1:numel(cohorts.pairs)
            cohort=cohorts.pairs(p);indices=cohort.design_indices;
            probabilityAB=NaN;probabilityBA=NaN;
            pairSeed=mod(double(seed)+i*10000+p,modulus)+1;
            if cohort.matched_case_count>0
                one=design_study.rank_bootstrap( ...
                    scoreSet.(name)(cohort.case_mask,indices), ...
                    designNames(indices),direction,nReplicates,pairSeed);
                probabilityAB=one.pairwise_win_probability(1,2);
                probabilityBA=one.pairwise_win_probability(2,1);
            end
            row=row+1;
            pairClass=pair_comparison_class( ...
                designNames{indices(1)},designNames{indices(2)});
            rows{row}=table(string(name),string(direction), ...
                string(designNames{indices(1)}), ...
                string(designNames{indices(2)}),string(pairClass), ...
                probabilityAB,probabilityBA, ...
                cohort.planned_case_count,cohort.matched_case_count, ...
                cohort.missing_case_count,cohort.coverage_fraction, ...
                string(strjoin(string(cohort.matched_case_ids),'|')), ...
                string(strjoin(string(cohort.missing_case_ids),'|')), ...
                string(cohort.status),pairSeed, ...
                'VariableNames',{'Metric','Direction','DesignA','DesignB', ...
                'ComparisonClass', ...
                'ProbabilityAOutperformsB','ProbabilityBOutperformsA', ...
                'PlannedCaseCount','MatchedCaseCount','MissingCaseCount', ...
                'CoverageFraction','MatchedCaseIDs','MissingCaseIDs', ...
                'AnalysisStatus','BootstrapSeed'});
        end
    end
    tableOut=vertcat(rows{:});
end

function value=pair_comparison_class(a,b)
    names=string({a,b});
    if all(ismember(["all_six" "physics_guided_full_rank_six"],names))
        value='representation_parity_not_information_gain';
    elseif any(names=="physics_guided_full_rank_six")
        value='cross_representation_exploratory';
    elseif any(names=="all_six")
        value='reference_subset_or_transform_comparison';
    else
        value='subset_or_transform_pair_comparison';
    end
end

