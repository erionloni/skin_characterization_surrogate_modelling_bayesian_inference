function [tableOut,entryTable] = ratio_validation(provider,caseSeeds,nDraws,tolerance)
    assert(numel(caseSeeds)==provider.n_cases&&all(isfinite(caseSeeds)), ...
        'design_study:generate:RatioValidationSeeds', ...
        'The ratio check needs one seed per case (%d cases, %d seeds).', ...
        provider.n_cases,numel(caseSeeds));
    rows = cell(provider.n_cases,1);
    entryRows=cell(provider.n_cases*16,1);
    entryRow=0;
    for c = 1:provider.n_cases
        one = provider.cases(c);
        [~,~,delta] = design_study.ratio_transform(one.observation,one.Sigma);
        noise = design_study.gaussian_draws(zeros(6,1),one.Sigma,nDraws,caseSeeds(c));
        transformed = design_study.ratio_values( ...
            design_study.add_observation_noise(one.observation,noise));
        empirical = cov(transformed);
        difference=delta-empirical;
        offDiagonal=~eye(4);
        relativeFrobenius=norm(difference,'fro')/ ...
            max(norm(empirical,'fro'),eps);
        rows{c}=table(string(one.case_id), ...
            norm(difference,'fro'), ...
            relativeFrobenius, ...
            max(abs(difference(offDiagonal))), ...
            max(abs(diag(difference))), ...
            min(abs(one.observation([1 1 4 4]))), ...
            tolerance,relativeFrobenius<=tolerance, ...
            'VariableNames',{'CaseID','FrobeniusAbsoluteError', ...
            'FrobeniusRelativeError','MaximumOffDiagonalAbsoluteError', ...
            'MaximumDiagonalAbsoluteError','MinimumDenominatorMagnitude', ...
            'DevelopmentTolerance','WithinDevelopmentTolerance'});
        for r=1:4
            for k=1:4
                entryRow=entryRow+1;
                entryRows{entryRow}=table(string(one.case_id),r,k, ...
                    delta(r,k),empirical(r,k),difference(r,k), ...
                    abs(difference(r,k))/max(abs(empirical(r,k)),eps), ...
                    r~=k, ...
                    'VariableNames',{'CaseID','RowRatio','ColumnRatio', ...
                    'DeltaCovariance','MonteCarloCovariance','Difference', ...
                    'RelativeEntryError','OffDiagonal'});
            end
        end
    end
    tableOut = vertcat(rows{:});
    entryTable=vertcat(entryRows{:});
end

