function write_narrative(path,provider,aggregate,bootstraps,metadata)
    q=bootstraps.q_information.summary;
    scenario=design_study.real_scenario_policy(provider.posterior_certification);
    if scenario.thesisPrimary
        heading='# Stage 9A primary measurement-plus-GP report';
        routeDescription=[ ...
            'This primary report uses the realistic measurement-plus-GP ' ...
            'uncertainty scenario and certified saved posteriors.'];
    elseif strcmp(scenario.tag,'gp_only')
        heading='# Stage 9A GP-only structural diagnostic';
        routeDescription=[ ...
            'This report removes measurement noise but retains GP ' ...
            'uncertainty. It is not the primary likelihood for conclusions.'];
    else
        heading='# Stage 9A deterministic GP self-consistency diagnostic';
        routeDescription=[ ...
            'This report uses the canonical GP mean as the observation and ' ...
            'the numerical covariance floor only. It is a numerical ' ...
            'self-consistency diagnostic, not measurement evidence.'];
    end
    matched=provider.certification_cohorts.all_design.matched_case_count;
    if bootstraps.q_information.available
        [~,best]=max(q.ProbabilityRank1);
        rankingSentence=sprintf([ ...
            'The all-design ranking used the exact six-design intersection ' ...
            '(%d/%d persistent cases). Within that matched cohort, `%s` had ' ...
            'the largest overall rank probability (%.3f) for Gaussian-moment ' ...
            'target-q covariance reduction. The six entries are mathematical ' ...
            'output representations or subsets. In particular, the physics-' ...
            'guided full-rank vector is an invertible representation-parity ' ...
            'check against all_six and creates no new measurement information. ' ...
            'Diagnostic scenarios ' ...
            'are not promoted to the primary measurement likelihood.'], ...
            matched,provider.n_cases,q.Design(best),q.ProbabilityRank1(best));
    else
        rankingSentence=sprintf([ ...
            'The all-design ranking is unavailable because zero of %d cases ' ...
            'have certified posteriors for all six designs. Pair and ' ...
            'sequence analyses retain their own explicitly reported matched ' ...
            'cohorts and are not promoted to an all-design ranking.'], ...
            provider.n_cases);
    end
    text=sprintf([ ...
        '%s\n\nRoute: `%s`\n\nCertification: `%s`\n\n%s\n\n' ...
        'The provider contains %d planned persistent cases and %d rankable designs. ' ...
        '%s%s\n\n' ...
        'Scientific claims allowed: `%s`, restricted to `%s`.\n'], ...
        heading,provider.route,provider.posterior_certification, ...
        routeDescription,provider.n_cases,height(aggregate), ...
        '',rankingSentence, ...
        string(metadata.scientific_claims_allowed),metadata.claim_scope);
    utils.atomic_write_text(path,text);
end

