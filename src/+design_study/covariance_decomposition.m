function result = covariance_decomposition(provider,caseIndex,design,varargin)
%COVARIANCE_DECOMPOSITION Linearized cycle-ratio posterior uncertainty.
%   Separates diagonal parameter-variance terms from signed parameter
%   covariance terms and validates the linearization with exact posterior
%   draws. Negative covariance terms are preserved rather than normalized
%   away.
%
%   RESULT = design_study.covariance_decomposition(PROVIDER, CASEINDEX,
%   DESIGN, 'Step', H, 'DenominatorFloor', F) linearizes the four cycle
%   ratios at the posterior mean of the case CASEINDEX and design DESIGN
%   (finite differences of step H in unit-box coordinates, required: the
%   design study's step, settings A.8; F is a numerical safety floor of the
%   ratio denominators, 1e-10 unless given), splits the
%   linearized variance of each ratio into the parameters' own terms and the
%   signed covariance terms of every parameter pair, and compares it with
%   the Monte Carlo variance of the ratios over every posterior draw.
%   Side effects: none.
%   Computation: seconds (the GP at every posterior draw of the cell).

    options = struct('Step',[],'DenominatorFloor',1e-10);
    options = parse_options(options,varargin{:});
    assert(~isempty(options.Step),'design_study:covariance_decomposition:Step', ...
        'The linearization needs its finite-difference step (''Step'', settings A.8).');
    design = design_study.get_design(provider,design);
    posterior = provider.posterior_provider(caseIndex,design);
    meanU = posterior.mean_u;
    C = posterior.covariance_u;
    rawForward = @(u) provider.forward_evaluator(caseIndex,u);
    jacobianRaw = design_study.finite_difference_jacobian(rawForward,meanU(:).', ...
        options.Step).rawMatrix;
    meanOutput = rawForward(meanU);
    [meanRatio,G] = design_study.ratio_transform( ...
        meanOutput,[],options.DenominatorFloor);
    Jz = G*jacobianRaw;
    linearCovariance = Jz*C*Jz.';
    linearCovariance = (linearCovariance+linearCovariance.')/2;

    diagonalContributions = Jz.^2.*diag(C).';
    pairs = nchoosek(1:4,2);
    covarianceContributions = zeros(4,size(pairs,1));
    for pair = 1:size(pairs,1)
        i = pairs(pair,1); j = pairs(pair,2);
        covarianceContributions(:,pair) = ...
            2*Jz(:,i).*Jz(:,j)*C(i,j);
    end
    reconstructedVariance = sum(diagonalContributions,2)+ ...
        sum(covarianceContributions,2);
    assert(norm(reconstructedVariance-diag(linearCovariance),inf) <= ...
        1e-10*max(norm(diag(linearCovariance),inf),1), ...
        'design_study:covariance_decomposition:SumMismatch', ...
        'Variance and covariance contributions do not reconstruct the variance.');

    draws = posterior.draws_u;
    outputs = evaluate_draws(provider,caseIndex,draws);
    ratioDraws = design_study.ratio_values(outputs,options.DenominatorFloor);
    monteCarloCovariance = cov(ratioDraws);
    absoluteError = abs(diag(linearCovariance)-diag(monteCarloCovariance));
    relativeError = absoluteError./max(abs(diag(monteCarloCovariance)),eps);
    aggregateOwn = sum(diagonalContributions,1).';
    aggregateCovariance = sum(covarianceContributions,1).';
    allMagnitude = [aggregateOwn;abs(aggregateCovariance)];
    absoluteShares = allMagnitude/max(sum(allMagnitude),eps);

    metadata = design_study.make_metadata(provider);

    result = struct( ...
        'schema_version','stage9_covariance_decomposition_v1', ...
        'case_id',provider.case_ids{caseIndex}, ...
        'design_name',design.name, ...
        'local_point','posterior_mean', ...
        'posterior_mean_u',meanU, ...
        'mean_ratio',meanRatio, ...
        'ratio_jacobian_theta',Jz, ...
        'parameter_covariance_u',C, ...
        'linearized_ratio_covariance',linearCovariance, ...
        'monte_carlo_ratio_covariance',monteCarloCovariance, ...
        'own_variance_contributions',diagonalContributions, ...
        'parameter_pairs',pairs, ...
        'signed_covariance_contributions',covarianceContributions, ...
        'aggregate_own_trace_contributions',aggregateOwn, ...
        'aggregate_signed_covariance_trace_contributions', ...
            aggregateCovariance, ...
        'normalized_absolute_trace_contributions',absoluteShares, ...
        'reconstructed_variance',reconstructedVariance, ...
        'absolute_variance_error',absoluteError, ...
        'relative_variance_error',relativeError, ...
        'denominator_floor',options.DenominatorFloor, ...
        'n_monte_carlo_draws',size(draws,1), ...
        'metadata',metadata);
end

function outputs = evaluate_draws(provider,caseIndex,draws)
    outputs = zeros(size(draws,1),6);
    % The publication real-route provider is vectorized. Evaluate in bounded
    % chunks so covariance decomposition remains practical for saved AIES
    % ensembles without requiring excessive transient memory or one UQLab
    % call per posterior draw.
    chunkSize=5000;
    for first=1:chunkSize:size(draws,1)
        last=min(first+chunkSize-1,size(draws,1));
        block=provider.forward_evaluator(caseIndex,draws(first:last,:));
        assert(isequal(size(block),[last-first+1 6])&& ...
            all(isfinite(block),'all'), ...
            'design_study:covariance_decomposition:ForwardShape', ...
            'The provider must return one finite six-output row per draw.');
        outputs(first:last,:)=block;
    end
end

function options = parse_options(options,varargin)
    assert(mod(numel(varargin),2)==0, ...
        'design_study:covariance_decomposition:Options', ...
        'Optional inputs must be name/value pairs.');
    fields = fieldnames(options);
    for i = 1:2:numel(varargin)
        hit = find(strcmpi(char(string(varargin{i})),fields),1);
        assert(~isempty(hit),'design_study:covariance_decomposition:UnknownOption', ...
            'Unknown option "%s".',char(string(varargin{i})));
        options.(fields{hit}) = varargin{i+1};
    end
end
