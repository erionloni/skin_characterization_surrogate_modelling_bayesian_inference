function result = run_design_study(cfg)
%RUN_DESIGN_STUDY The design study: Fisher-information comparison of the six observation designs.
%   RESULT = design_study.run_design_study(CFG) uses the posteriors of the
%   selected providers of the inversion grid (a run's own certified
%   posteriors below CFG.paths.stage04, or the shipped draws, certified or
%   healthy fallback) and the GP CFG.files.gp; no
%   sampler runs. Per scenario it builds the matched cohorts, the
%   local Fisher information (finite-difference Jacobian), the posterior
%   covariance and the ranking of the six designs with rank-bootstrap
%   uncertainty (seeded per scenario), and the Fisher information computed
%   without posteriors. These are design-analysis diagnostics, never gates
%   before an MCMC run. It writes the scenario analyses and their indexes
%   below CFG.paths.stage06. RESULT summarizes the analyses.
%   The body of the pre-publication script
%   (s06_run_stage9a_oed), moved unchanged.
%   Computation: about 20 minutes (22 min recorded).
%   Side effects: writes the files above below the design study's folder.
    assert(strcmp(cfg.dataMode,'real'),'design_study:run_design_study:Route', ...
        'The design study belongs to the fixed route.');
    roots=make_roots(cfg.paths.stage06);
    P=parameters.parameter_space(cfg);
    cases=data.inversion_cases(cfg,P);
    grid=inversion.build_inversion_grid(cfg,cases);
    loadedGP=load(cfg.files.gp,'gp');
    assert(isfield(loadedGP,'gp'),'design_study:run_design_study:GPArtifact');

    dependency=dependency_table(cfg,grid);
    dependencyPath=fullfile(roots.tables,'inversion_dependency_status.csv');
    utils.atomic_write_table(dependencyPath,dependency);
    scenarios=inversion.scenario_registry();
    designs=design_study.candidate_designs();
    assert(height(dependency)==numel(cases)*numel(scenarios)*numel(designs), ...
        'design_study:run_design_study:DependencyShape', ...
        'The inversion coverage must list every planned grid cell explicitly.');
    assert(numel(cases)==grid.caseCount&&numel(scenarios)==grid.scenarioCount&& ...
        numel(designs)==grid.designCount&&height(dependency)==grid.cellCount&& ...
        grid.cellCount==double(cfg.inversion.expectedCellCount), ...
        'design_study:run_design_study:ActiveGridShape', ...
        ['The design study needs the complete configured inversion grid ' ...
         '(N cases x 3 scenarios x 6 designs).']);
    coverageParts=cell(numel(scenarios),1);
    summaryParts=cell(numel(scenarios),1);
    cohortsByScenario=cell(numel(scenarios),1);
    for i=1:numel(scenarios)
        cohorts=design_study.certification_cohorts(dependency, ...
            [cases.case_id],{designs.name},scenarios(i).tag);
        cohortsByScenario{i}=cohorts;
        oneCoverage=cohorts.coverage_table;
        oneCoverage.ScenarioPlannedCellCount=repmat( ...
            cohorts.planned_cell_count,height(oneCoverage),1);
        oneCoverage.ScenarioCertifiedCellCount=repmat( ...
            cohorts.certified_cell_count,height(oneCoverage),1);
        oneCoverage.ScenarioMissingCellCount=repmat( ...
            cohorts.missing_cell_count,height(oneCoverage),1);
        coverageParts{i}=oneCoverage;
        oneSummary=cohorts.summary;
        oneSummary.Scenario=repmat(string(scenarios(i).tag), ...
            height(oneSummary),1);
        summaryParts{i}=movevars(oneSummary,'Scenario','Before',1);
        deficient=oneSummary.WarningBelowPlannedN;
        if any(deficient)
            warning('design_study:run_design_study:PartialCertification', ...
                ['Scenario %s has %d/%d certified cells. %d matched-set ' ...
                 'analyses use fewer than %d planned cases; exact N and ' ...
                 'missing case IDs are persisted.'],scenarios(i).tag, ...
                cohorts.certified_cell_count,cohorts.planned_cell_count, ...
                nnz(deficient),cohorts.planned_case_count);
        end
    end
    certificationCoverage=vertcat(coverageParts{:});
    matchedSummary=vertcat(summaryParts{:});
    statusCounts=certification_status_counts(certificationCoverage, ...
        {scenarios.tag},{designs.name});
    utils.atomic_write_table(fullfile(roots.tables, ...
        'certification_coverage.csv'),certificationCoverage);
    utils.atomic_write_table(fullfile(roots.tables, ...
        'matched_analysis_summary.csv'),matchedSummary);
    utils.atomic_write_table(fullfile(roots.tables, ...
        'certification_status_counts.csv'),statusCounts);

    reportParts=cell(numel(scenarios),1);manifestParts=cell(numel(scenarios),1);
    for i=1:numel(scenarios)
        scenario=scenarios(i);
        cohorts=cohortsByScenario{i};
        bootstrapSeed=seeds.design_study(cfg,'rank_bootstrap',scenario.tag);
        provider=recovery.design_study_provider( ...
            cfg,grid,loadedGP.gp,P,cases,scenario.tag,dependency);
        scenarioRoot=fullfile(roots.scenarios,scenario.tag);
        [report,reportPath]=scenario_report(provider,scenarioRoot,cfg, ...
            bootstrapSeed);
        reportParts{i}=report;
        scenarioCells=certificationCoverage( ...
            certificationCoverage.Scenario==string(scenario.tag),:);
        manifestParts{i}=table(string(scenario.tag),string(scenario.label), ...
            logical(scenario.primaryScientificScenario), ...
            string(scenario.claimScope), ...
            string(relative_path(reportPath,cfg.paths.stage06)), ...
            string(relative_path(fullfile(scenarioRoot,'tables'), ...
                cfg.paths.stage06)), ...
            cohorts.planned_cell_count,cohorts.certified_cell_count, ...
            cohorts.missing_cell_count, ...
            sum(scenarioCells.CellStatus=="unresolved"), ...
            sum(scenarioCells.CellStatus=="failed"), ...
            cohorts.all_design.matched_case_count, ...
            cohorts.d2_to_all_six.matched_case_count, ...
            cohorts.d6_to_all_six.matched_case_count, ...
            cohorts.cycle1_to_all_six.matched_case_count, ...
            cohorts.ratios_to_all_six.matched_case_count, ...
            cohorts.representation_parity.matched_case_count, ...
            cohorts.all_design.matched_case_count>0, ...
            'VariableNames',{'Scenario','ScenarioLabel','ThesisPrimary', ...
            'ClaimScope','ResultMAT','TableDirectory','PlannedCells','CertifiedCells', ...
            'MissingCells','UnresolvedCells','FailedCells', ...
            'AllDesignMatchedCases','D2ToAllSixMatchedCases', ...
            'D6ToAllSixMatchedCases','Cycle1ToAllSixMatchedCases', ...
            'RatiosToAllSixMatchedCases','RepresentationParityMatchedCases', ...
            'AllDesignRankingAvailable'});
    end
    scenarioManifest=vertcat(manifestParts{:});
    utils.atomic_write_table(fullfile(roots.tables, ...
        'scenario_manifest.csv'),scenarioManifest);
    write_subject_indexes(roots,scenarios,cfg.paths.stage06);
    reports=reportParts;
    utils.atomic_save_struct(cfg.files.stage9,struct( ...
        'reports',{reports},'scenarioManifest',scenarioManifest, ...
        'certificationCoverage',certificationCoverage, ...
        'matchedAnalysisSummary',matchedSummary, ...
        'certificationStatusCounts',statusCounts),'-v7.3');
    scope=struct('schema_version','stage9a_scope_v2_six_design', ...
        'primary_scenario','measurement_plus_gp', ...
        'diagnostic_scenarios',{{'gp_only','gp_self_det'}}, ...
        'posterior_information_metric', ...
        ['Gaussian-moment covariance log-volume reduction; not exact EIG ' ...
         'for sampled nonlinear posteriors.'], ...
        'fim_role','local_OED_design_diagnostic_only_not_MCMC_gate', ...
        'mcmc_runs_performed',0,'design_count',6, ...
        'all_design_cohort_policy', ...
            'intersection_across_exact_six_designs_within_scenario', ...
        'pair_cohort_policy','intersection_across_exact_design_pair', ...
        'sequence_cohort_policy','intersection_across_exact_sequence_designs', ...
        'missing_cell_policy','explicit_never_zero_imputed', ...
        'inactive_designs_present',false, ...
        'subset_sequence_1','d2_only_to_all_six_registered_grid_only', ...
        'subset_sequence_2','d6_only_to_all_six_registered_grid_only', ...
        'subset_sequence_3','cycle_1_only_to_all_six_registered_grid_only', ...
        'representation_parity_pair', ...
            'all_six_vs_physics_guided_full_rank_six', ...
        'representation_parity_interpretation', ...
            'invertible_reexpression_same_six_pressures_no_new_information', ...
        'design_interpretation', ...
            'mathematical_subsets_transforms_and_full_rank_representation');
    utils.atomic_write_json(fullfile(cfg.paths.stage06, ...
        'analysis_scope.json'),scope,'AllowReplace',true);
    certifiedCount=sum(dependency.Certified);
    failedCount=sum(dependency.CellStatus=="failed");
    unresolvedCount=sum(dependency.CellStatus=="unresolved");
    if certifiedCount==height(dependency)
        completionState='completed_complete_grid';
    else
        completionState='completed_partial_certification';
    end
    rankingAvailable=scenarioManifest.AllDesignRankingAvailable;
    result=struct('status',completionState, ...
        'scenario_count',grid.scenarioCount, ...
        'cell_count',grid.cellCount,'design_count',grid.designCount, ...
        'mcmc_run_count',0, ...
        'certified_cell_count',certifiedCount, ...
        'unresolved_cell_count',unresolvedCount, ...
        'failed_cell_count',failedCount, ...
        'missing_cell_count',unresolvedCount+failedCount, ...
        'all_scenario_rankings_available',all(rankingAvailable), ...
        'artifact',cfg.files.stage9);
    completionStatus=struct('schema_version', ...
        'stage9a_certification_coverage_v4_six_design', ...
        'status',completionState,'planned_cells',height(dependency), ...
        'certified_cells',certifiedCount, ...
        'unresolved_cells',unresolvedCount,'failed_cells',failedCount, ...
        'mcmc_runs_performed',0, ...
        'all_scenario_rankings_available',all(rankingAvailable), ...
        'scenario_ranking_available',cellstr(string( ...
            scenarioManifest.Scenario(rankingAvailable))), ...
        'counts_by_scope',table2struct(statusCounts), ...
        'matched_analysis_counts',table2struct(matchedSummary(:, ...
            {'Scenario','Analysis','AnalysisType','RequiredDesigns', ...
             'PlannedCaseCount','MatchedCaseCount','MissingCaseCount', ...
             'Status'})), ...
        'environment',utils.environment_line());
    utils.atomic_write_json(fullfile(cfg.paths.stage06, ...
        'design_study_status.json'),completionStatus,'AllowReplace',true);
    fprintf(['[design study] Completed on the saved posteriors: %d of %d cells ' ...
        'certified; each analysis states its matched N.\n'], ...
        certifiedCount,height(dependency));
end

function [report,reportPath]=scenario_report(provider,scenarioRoot,cfg,bootstrapSeed)
%SCENARIO_REPORT The design study of one scenario, computed in its own folder.
%   The scenario folder is replaced: a rerun of the step computes the
%   analysis again (about a minute per scenario and case).
    reportPath=fullfile(scenarioRoot,'design_study.mat');
    if isfolder(scenarioRoot),rmdir(scenarioRoot,'s');end
    ratioSeeds=cellfun(@(caseID)seeds.design_study(cfg,'ratio_validation', ...
        provider.scenario_tag,str2double(caseID)),provider.case_ids);
    report=design_study.generate(provider,scenarioRoot, ...
            'BootstrapReplicates',cfg.stage9.bootstrapReplicates, ...
            'BootstrapSeed',bootstrapSeed, ...
            'RatioValidationDraws',cfg.stage9.ratioValidationDraws, ...
            'RatioValidationSeeds',ratioSeeds, ...
            'RatioValidationTolerance',cfg.stage9.ratioValidationTolerance, ...
            'FiniteDifferenceStep',cfg.stage9.finiteDifferenceStep, ...
            'FiniteDifferenceCheckSteps',cfg.stage9.finiteDifferenceCheckSteps, ...
            'RunCovarianceDecomposition',true, ...
            'RunRatioValidation',true);
end

function roots=make_roots(root)
    roots=struct('tables',fullfile(root,'tables'), ...
        'posterior',fullfile(root,'posterior_information'), ...
        'fim',fullfile(root,'fim'),'ranking',fullfile(root,'ranking'), ...
        'scenarios',fullfile(root,'scenarios'));
    values=struct2cell(roots);
    for i=1:numel(values),if ~isfolder(values{i}),mkdir(values{i});end,end
end

function T=dependency_table(cfg,grid)
    campaign=table();
    if isfile(cfg.files.certificationIndex)
        campaign=read_certification_index(cfg.files.certificationIndex);
        assert(all(ismember({'CellID','Certified','State','Reason', ...
            'SuccessfulRequestCount','FailedRequestCount', ...
            'SamplerFailureIdentifiers'},campaign.Properties.VariableNames))&& ...
            numel(unique(campaign.CellID))==height(campaign), ...
            'design_study:run_design_study:CertificationIndexSchema');
    end
    parts=cell(numel(grid.cells),1);
    for i=1:numel(grid.cells)
        cellRecord=grid.cells(i);
        designSemantics=design_study.design_semantics(cellRecord.design);
        [artifact,status]=recovery.load_posterior_provider(cfg,cellRecord);
        mechanism="";sampler="";replicate=NaN;steps=NaN;
        campaignState="not_recorded";failureReason=string(status.reason);
        failureIdentifiers=string(status.errorIdentifier);successful=0;failed=0;
        campaignRecord=false;
        if ~isempty(campaign)
            campaignHit=campaign.CellID==string(cellRecord.cellID);
            assert(nnz(campaignHit)<=1, ...
                'design_study:run_design_study:CertificationIndexCell');
            if any(campaignHit)
                campaignRecord=true;
                campaignState=campaign.State(campaignHit);
                successful=double(campaign.SuccessfulRequestCount(campaignHit));
                failed=double(campaign.FailedRequestCount(campaignHit));
                failureIdentifiers=campaign.SamplerFailureIdentifiers(campaignHit);
                if strlength(campaign.Reason(campaignHit))>0
                    failureReason=campaign.Reason(campaignHit);
                end
            end
        end
        if status.loaded
            provenance=recovery.posterior_provider_provenance(artifact);
            mechanism=string(provenance.certificationMechanism);
            sampler=string(provenance.provider.sampler);
            replicate=double(provenance.provider.replicateID);
            steps=double(provenance.provider.stepCount);
        end
        if status.loaded&&status.certified
            cellStatus="certified";
        elseif status.loaded
            cellStatus="exploratory_noncertified";
        elseif strcmp(status.state,'invalid_certification')||failed>0|| ...
                campaignState=="execution_error"
            cellStatus="failed";
        else
            cellStatus="unresolved";
        end
        parts{i}=table(double(cellRecord.cellIndex), ...
            double(cellRecord.caseID),string(cellRecord.scenario), ...
            string(cellRecord.design),string(designSemantics.role), ...
            string(designSemantics.comparison_class), ...
            string(cellRecord.cellID), ...
            logical(status.loaded),string(status.state),cellStatus, ...
            campaignRecord,campaignState,failureReason,failureIdentifiers, ...
            successful,failed,sampler,replicate,steps,mechanism, ...
            'VariableNames',{'CellIndex','CaseID','Scenario','Design', ...
            'DesignRole','ComparisonClass','CellID','ArtifactLoaded', ...
            'ExecutionStatus','CellStatus', ...
            'CampaignRecordAvailable','CampaignState','FailureReason', ...
            'FailureIdentifiers','SuccessfulRequestCount','FailedRequestCount', ...
            'CertifiedSampler','CertifiedReplicate','CertifiedStepCount', ...
            'CertificationMechanism'});
        parts{i}.Certified=logical(status.loaded&&status.certified);
    end
    T=vertcat(parts{:});
end

function T=read_certification_index(pathValue)
%READ_CERTIFICATION_INDEX The campaign's certification index with its text columns as text.
%   A text column that is empty in every row (SamplerFailureIdentifiers when
%   no request failed) would otherwise be read as numbers.
    T=utils.read_csv_table(pathValue,{'CellID','Scenario','Design', ...
        'State','ProviderSampler','Reason','CertificationMechanism', ...
        'SamplerFailureIdentifiers'});
end

function T=certification_status_counts(coverage,scenarioNames,designNames)
    rows=cell(1+numel(scenarioNames)+numel(designNames)+ ...
        numel(scenarioNames)*numel(designNames),1);cursor=0;
    [rows,cursor]=add_count(rows,cursor,coverage,'overall','all','all');
    for s=1:numel(scenarioNames)
        tag=string(scenarioNames{s});selected=coverage(coverage.Scenario==tag,:);
        [rows,cursor]=add_count(rows,cursor,selected,'scenario',tag,'all');
    end
    for d=1:numel(designNames)
        name=string(designNames{d});selected=coverage(coverage.Design==name,:);
        [rows,cursor]=add_count(rows,cursor,selected,'design','all',name);
    end
    for s=1:numel(scenarioNames)
        for d=1:numel(designNames)
            tag=string(scenarioNames{s});name=string(designNames{d});
            selected=coverage(coverage.Scenario==tag&coverage.Design==name,:);
            [rows,cursor]=add_count(rows,cursor,selected, ...
                'scenario_design',tag,name);
        end
    end
    T=vertcat(rows{1:cursor});
end

function [rows,cursor]=add_count(rows,cursor,T,scope,scenario,design)
    cursor=cursor+1;
    mechanisms=string(T.CertificationMechanism);
    rows{cursor}=table(string(scope),string(scenario),string(design), ...
        height(T),sum(T.CellStatus=="certified"), ...
        sum(T.CellStatus=="unresolved"),sum(T.CellStatus=="failed"), ...
        sum(mechanisms=="CERTIFIED_AIES_REPLICATE_AGREEMENT"), ...
        string(strjoin(unique(T.FailureReason(T.CellStatus~="certified"& ...
            strlength(T.FailureReason)>0),'stable'),' | ')), ...
        string(strjoin(unique(T.FailureIdentifiers( ...
            T.CellStatus~="certified"&strlength(T.FailureIdentifiers)>0), ...
            'stable'),' | ')), ...
        'VariableNames',{'Scope','Scenario','Design','ExpectedCells', ...
        'CertifiedCells','UnresolvedCells','FailedCells', ...
        'AIESReplicateCertifiedCells','MissingReasons','FailureIdentifiers'});
end

function write_subject_indexes(roots,scenarios,stageRoot)
    subjects={ ...
        roots.posterior,{'posterior_reference.csv', ...
            'posterior_parameter_reference.csv', ...
            'posterior_covariance_reference.csv', ...
            'certification_coverage.csv'}; ...
        roots.fim,{'fim_metrics.csv','fim_eigenvalues.csv','svd_directions.csv', ...
            'covariance_decomposition_variance.csv', ...
            'covariance_decomposition_pairs.csv', ...
            'covariance_decomposition_trace_shares.csv'}; ...
        roots.ranking,{'design_summary.csv','rank_bootstrap_summary.csv', ...
            'rank_pairwise_probability.csv','sequential_information.csv', ...
            'subset_dimensionality.csv','design_comparison_semantics.csv', ...
            'design_reference_differences.csv', ...
            'matched_analysis_summary.csv'}};
    for subject=1:size(subjects,1)
        rows=cell(numel(scenarios)*numel(subjects{subject,2}),1);cursor=0;
        for i=1:numel(scenarios)
            for j=1:numel(subjects{subject,2})
                cursor=cursor+1;file=subjects{subject,2}{j};
                target=fullfile(roots.scenarios,scenarios(i).tag,'tables',file);
                rows{cursor}=table(string(scenarios(i).tag),string(file), ...
                    string(relative_path(target,stageRoot)),isfile(target), ...
                    'VariableNames',{'Scenario','Artifact','RelativePath', ...
                    'Available'});
            end
        end
        utils.atomic_write_table(fullfile(subjects{subject,1}, ...
            'artifact_index.csv'),vertcat(rows{:}));
    end
end

function relative=relative_path(pathValue,root)
    pathValue=utils.absolute_path(pathValue);root=utils.absolute_path(root);
    prefix=[root filesep];
    assert(startsWith(lower(pathValue),lower(prefix)), ...
        'design_study:run_design_study:PathBoundary');
    relative=strrep(pathValue(numel(prefix)+1:end),'\','/');
end
