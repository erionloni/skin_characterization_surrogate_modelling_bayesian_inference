function score = score_fim(jacobianResult, priorCovariance, targetIndices)
%SCORE_FIM The D-, A-, c- and target-q criteria of one whitened Jacobian.
%   SCORE = design_study.score_fim(G,C0,Q) consumes the output of
%   design_study.finite_difference_jacobian, a Gaussian-moment covariance C0 for the
%   normalized prior, and the two target-q parameter indices Q. The
%   resulting covariance is the documented local Gaussian-moment
%   approximation inv(inv(C0)+J'*Sigma^-1*J), not an observed posterior.
%   Side effects: none.

    required = {'fisherInformation','singularValues','V', ...
        'continuousConditionNumber','conditionNumber','numericalRank', ...
        'relativeStepDifferenceWhitened'};
    assert(isstruct(jacobianResult) && ...
        all(isfield(jacobianResult,required)), ...
        'design_study:score_fim:IncompleteJacobian', ...
        'jacobianResult is missing a required whitened-Jacobian field.');
    validateattributes(priorCovariance,{'numeric'}, ...
        {'2d','real','finite','square'});
    nParameter = size(priorCovariance,1);
    assert(isequal(size(jacobianResult.fisherInformation), ...
        [nParameter nParameter]), ...
        'design_study:score_fim:DimensionMismatch', ...
        'FIM and prior-covariance dimensions differ.');
    targetIndices = targetIndices(:).';
    assert(numel(targetIndices)==2 && ...
        all(targetIndices==round(targetIndices)) && ...
        all(targetIndices>=1 & targetIndices<=nParameter) && ...
        numel(unique(targetIndices))==2, ...
        'design_study:score_fim:InvalidTargetIndices', ...
        'targetIndices must contain two distinct valid parameter indices.');

    C0 = symmetric_spd(priorCovariance,'prior covariance');
    priorPrecision = inverse_spd(C0);
    F = (jacobianResult.fisherInformation + ...
        jacobianResult.fisherInformation.')/2;
    approximatePrecision = priorPrecision+F;
    approximateCovariance = inverse_spd(approximatePrecision);

    cFirst = zeros(nParameter,1);
    cFirst(targetIndices(1)) = 1;
    cSecond = zeros(nParameter,1);
    cSecond(targetIndices(2)) = 1;
    qCovariance = approximateCovariance(targetIndices,targetIndices);
    priorQ = C0(targetIndices,targetIndices);
    singularValues = jacobianResult.singularValues(:);
    if isempty(singularValues)
        normalizedSpectrum = singularValues;
    else
        normalizedSpectrum = singularValues/max(singularValues(1),eps);
    end
    weakest = jacobianResult.V(:,end);

    score = struct( ...
        'schema_version','stage9_local_fim_score_v1', ...
        'covariance_treatment','frozen_local_covariance', ...
        'prior_treatment','Gaussian_moment_approximation_to_configured_prior', ...
        'fisher_information',F, ...
        'prior_precision',priorPrecision, ...
        'approximate_posterior_precision',approximatePrecision, ...
        'approximate_posterior_covariance',approximateCovariance, ...
        'D_optimal_utility',design_study.logdet_spd(approximatePrecision), ...
        'A_optimal_loss',trace(approximateCovariance), ...
        'c_target_1_loss',cFirst.'*approximateCovariance*cFirst, ...
        'c_target_2_loss',cSecond.'*approximateCovariance*cSecond, ...
        'full_theta_trace',trace(approximateCovariance), ...
        'full_theta_logdet',design_study.logdet_spd(approximateCovariance), ...
        'q_trace',trace(qCovariance), ...
        'q_logdet',design_study.logdet_spd(qCovariance), ...
        'q_log_volume_reduction',0.5*( ...
            design_study.logdet_spd(priorQ)-design_study.logdet_spd(qCovariance)), ...
        'information_gain',0.5*(design_study.logdet_spd(C0)- ...
            design_study.logdet_spd(approximateCovariance)), ...
        'eigenvalues',sort(eig(F),'descend'), ...
        'singular_values',singularValues, ...
        'normalized_singular_spectrum',normalizedSpectrum, ...
        'condition_number',jacobianResult.continuousConditionNumber, ...
        'thresholded_condition_number',jacobianResult.conditionNumber, ...
        'numerical_rank',jacobianResult.numericalRank, ...
        'right_singular_vectors',jacobianResult.V, ...
        'weakest_direction',weakest, ...
        'weakest_direction_absolute_loadings',abs(weakest), ...
        'q_subspace_alignment',sum(weakest(targetIndices).^2), ...
        'step_relative_difference', ...
            jacobianResult.relativeStepDifferenceWhitened, ...
        'target_indices',targetIndices);
end

function matrix = symmetric_spd(matrix,label)
    scale=max(norm(matrix,'fro'),eps);
    assert(norm(matrix-matrix.','fro')/scale<=1e-10, ...
        'design_study:score_fim:NonSymmetric', ...
        'The %s is not symmetric.',label);
    matrix=(matrix+matrix.')/2;
    [~,flag]=chol(matrix,'lower');
    assert(flag==0,'design_study:score_fim:PositiveDefinite', ...
        'The %s must be positive definite.',label);
end

function inverse = inverse_spd(matrix)
    matrix=symmetric_spd(matrix,'covariance or precision matrix');
    L=chol(matrix,'lower');
    inverse=L.'\(L\eye(size(matrix)));
    inverse=(inverse+inverse.')/2;
end
