function result = fim_metrics(provider,caseIndex,design,step)
%FIM_METRICS Normalized weighted-Jacobian D/A/c/q metrics and SVD.
%   Observation covariance is frozen at the provider's named local
%   covariance. The result is an explicitly local weighted-Jacobian
%   approximation and is compared with the saved MCMC posterior covariance.
%
%   RESULT = design_study.fim_metrics(PROVIDER, CASEINDEX, DESIGN, STEP)
%   differentiates the design's forward map at the case's truth (unit-box
%   coordinates, finite-difference step STEP: the settings' step, A.8;
%   design_study.finite_difference_jacobian), whitens it with the design's
%   observation covariance and scores it with the prior
%   (design_study.score_fim): Fisher information, D-, A- and c-optimal
%   criteria, trace and log determinant of the full and the target (q)
%   covariance, information gain, singular spectrum, condition number,
%   weakest direction, and the relative difference of the FIM-approximated
%   posterior covariance from the saved MCMC posterior covariance.
%   Side effects: none.
%   Computation: seconds.

    assert(nargin == 4 && ~isempty(step), 'design_study:fim_metrics:Step', ...
        'The FIM metrics need their finite-difference step (settings A.8).');
    model = design_study.design_model(provider,caseIndex,design);
    design = model.design;
    posterior = provider.posterior_provider(caseIndex,design);
    u = provider.cases(caseIndex).truth_u(:).';
    jacobianResult = design_study.finite_difference_jacobian( ...
        model.forward,u,step,model.covariance, ...
        'RankRelativeTolerance',1e-3);
    C0 = provider.prior_definition.covariance_u;
    q = provider.target_indices;
    score = design_study.score_fim(jacobianResult,C0,q);
    metadata = design_study.make_metadata(provider);

    result = struct( ...
        'schema_version','stage9_local_fim_metrics_v1', ...
        'case_id',model.case_id, ...
        'design_name',design.name, ...
        'likelihood',provider.likelihood, ...
        'covariance_treatment','frozen_local_covariance', ...
        'parameter_coordinate_system','normalized_unit_box', ...
        'target_indices',q, ...
        'step',step, ...
        'jacobian',jacobianResult.rawMatrix, ...
        'output_covariance',model.covariance, ...
        'output_covariance_inverse',invert_spd(model.covariance), ...
        'whitened_jacobian',jacobianResult.whitenedMatrix, ...
        'fisher_information',score.fisher_information, ...
        'prior_precision',score.prior_precision, ...
        'approximate_posterior_covariance', ...
            score.approximate_posterior_covariance, ...
        'D_optimal_utility',score.D_optimal_utility, ...
        'A_optimal_loss',score.A_optimal_loss, ...
        'c_m3e_loss',score.c_target_1_loss, ...
        'c_k0_loss',score.c_target_2_loss, ...
        'full_theta_trace',score.full_theta_trace, ...
        'full_theta_logdet',score.full_theta_logdet, ...
        'q_trace',score.q_trace, ...
        'q_logdet',score.q_logdet, ...
        'q_log_volume_reduction',score.q_log_volume_reduction, ...
        'information_gain',score.information_gain, ...
        'eigenvalues',score.eigenvalues, ...
        'singular_values',score.singular_values, ...
        'normalized_singular_spectrum', ...
            score.normalized_singular_spectrum, ...
        'condition_number',score.condition_number, ...
        'thresholded_condition_number', ...
            score.thresholded_condition_number, ...
        'numerical_rank',score.numerical_rank, ...
        'right_singular_vectors',score.right_singular_vectors, ...
        'weakest_direction',score.weakest_direction, ...
        'weakest_direction_absolute_loadings', ...
            score.weakest_direction_absolute_loadings, ...
        'q_subspace_alignment',score.q_subspace_alignment, ...
        'step_relative_difference',score.step_relative_difference, ...
        'posterior_covariance',posterior.covariance_u, ...
        'fim_to_posterior_covariance_relative_error',norm( ...
            score.approximate_posterior_covariance-posterior.covariance_u,'fro')/ ...
            max(norm(posterior.covariance_u,'fro'),eps), ...
        'metadata',metadata);
end

function inverse=invert_spd(matrix)
    matrix=(matrix+matrix.')/2;
    lower=chol(matrix,'lower');
    inverse=lower.'\(lower\eye(size(matrix)));
    inverse=(inverse+inverse.')/2;
end
