function metadata = make_metadata(provider, varargin)
%MAKE_METADATA The certification and provenance record of the design-study artifacts.
%   METADATA = design_study.make_metadata(PROVIDER, ...) returns the fields
%   of design_study.required_metadata_fields for the artifacts of the
%   provider PROVIDER: route, posterior certification and its claim scope
%   (design_study.certification_policy; a caller cannot change the
%   provider's certification), execution and reliability status (a
%   provider whose consumed posteriors are not all certified is
%   exploratory), failure reasons, the likelihood and the MATLAB/UQLab line.
%   Options: 'ExecutionStatus', 'ReliabilityStatus', 'FailureReasons',
%   'Certification'.
%   Side effects: none.

    options = struct( ...
        'ExecutionStatus','completed', ...
        'ReliabilityStatus','reliable', ...
        'FailureReasons',{{}}, ...
        'Certification','');
    options = parse_options(options,varargin{:});
    if isempty(options.Certification)
        options.Certification = provider.posterior_certification;
    else
        assert(strcmp(char(string(options.Certification)), ...
            char(string(provider.posterior_certification))), ...
            'design_study:make_metadata:CertificationOverride', ...
            ['Artifact certification must equal the provider certification; ' ...
             'a caller may not promote or reclassify a provider.']);
    end
    cert = design_study.certification_policy(options.Certification);
    reasons = options.FailureReasons;
    if ischar(reasons) || isstring(reasons), reasons = cellstr(reasons); end

    % The MATLAB/UQLab line of the run (utils.environment_line).
    environment = char(string(provider.environment));
    % A completed calculation is not proof that its consumed posteriors are
    % certified. Keep mixed recovered-provider evidence explicitly exploratory.
    if ~provider.reliability_metadata.all_consumed_posteriors_certified&& ...
            strcmp(options.ReliabilityStatus,'reliable')
        options.ReliabilityStatus='exploratory_noncertified';
    end
    claimsAllowed = cert.scientific_claims_allowed && ...
        strcmp(options.ExecutionStatus,'completed') && ...
        strcmp(options.ReliabilityStatus,'reliable');
    aggregateInputValidated = strcmp(options.ExecutionStatus,'completed') && ...
        strcmp(options.ReliabilityStatus,'reliable') && ...
        provider.reliability_metadata.all_consumed_posteriors_certified;
    metadata = struct( ...
        'route',provider.route, ...
        'posterior_certification',cert.name, ...
        'execution_status',char(string(options.ExecutionStatus)), ...
        'reliability_status',char(string(options.ReliabilityStatus)), ...
        'claim_scope',cert.claim_scope, ...
        'scientific_claims_allowed',logical(claimsAllowed), ...
        'failure_reasons',{reasons(:).'}, ...
        'environment',environment, ...
        'likelihood',char(string(provider.likelihood)), ...
        'scientific_version',provider.scientific_version, ...
        'diagnostic_version',provider.diagnostic_version, ...
        'use_scope',cert.claim_scope, ...
        ... % Reporting's checkpoint contract also covers validated aggregates.
        'checkpoint_validated',logical(aggregateInputValidated), ...
        'design_comparison_policy', ...
            'six_active_designs_exact_matched_certified_cases', ...
        'full_rank_representation_interpretation', ...
            'invertible_same_six_pressures_no_new_experimental_information', ...
        'certified_posteriors_validated', ...
            logical(aggregateInputValidated), ...
        'report_mode','stage9_direct_mcmc');
    scenarioFields={'scenario_tag','observation_source','uncertainty_mode', ...
        'thesis_primary'};
    for i=1:numel(scenarioFields)
        field=scenarioFields{i};
        if isfield(provider,field),metadata.(field)=provider.(field);end
    end
end

function options = parse_options(options,varargin)
    assert(mod(numel(varargin),2)==0, ...
        'design_study:make_metadata:NameValuePairs', ...
        'Optional inputs must be name/value pairs.');
    names = fieldnames(options);
    for i = 1:2:numel(varargin)
        hit = find(strcmpi(char(string(varargin{i})),names),1);
        assert(~isempty(hit),'design_study:make_metadata:UnknownOption', ...
            'Unknown metadata option "%s".',char(string(varargin{i})));
        options.(names{hit}) = varargin{i+1};
    end
end
