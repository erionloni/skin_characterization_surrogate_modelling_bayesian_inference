function policy = real_scenario_policy(selector)
%REAL_SCENARIO_POLICY The inversion's scenarios as the design study reports them.
%   The inversion and the design study share inversion.scenario_registry; this
%   adapter adds report names but does not redefine the scenarios.
%
%   POLICY = design_study.real_scenario_policy() returns every scenario
%   (tag, label, certification, claim scope, report folder, likelihood);
%   POLICY = design_study.real_scenario_policy(SELECTOR) the one whose tag,
%   likelihood or certification is SELECTOR.
%   Side effects: none.

    scenarios=inversion.scenario_registry();
    reportFolders={'measurement_plus_gp', ...
        'gp_only_structural_diagnostic', ...
        'gp_self_det_self_consistency_diagnostic'};
    narrativeFiles=repmat({'design_study_report.md'},1,3);
    template=struct('tag','','label','','certification','', ...
        'providerClaimScope','','thesisPrimary',false,'reportFolder','', ...
        'narrativeFile','','likelihood','', ...
        'observationSource','','uncertaintyMode','', ...
        'scenarioClaimScope','');
    entries=repmat(template,1,numel(scenarios));
    for i=1:numel(scenarios)
        s=scenarios(i);
        certification=design_study.certification_policy(s.certification);
        assert(strcmp(certification.claim_scope,s.claimScope), ...
            'design_study:real_scenario_policy:CertificationClaimScopeDrift','Check failed: design_study:real_scenario_policy:CertificationClaimScopeDrift.');
        entries(i)=struct('tag',s.tag,'label',s.label, ...
            'certification',s.certification, ...
            'providerClaimScope',s.claimScope, ...
            'thesisPrimary',logical(s.primaryScientificScenario), ...
            'reportFolder',reportFolders{i}, ...
            'narrativeFile',narrativeFiles{i}, ...
            'likelihood',s.likelihood, ...
            'observationSource',s.observationSource, ...
            'uncertaintyMode',s.uncertaintyMode, ...
            'scenarioClaimScope',s.claimScope);
    end
    result=struct('schemaVersion','stage9_direct_mcmc_scenario_policy_v1', ...
        'entries',entries, ...
        'tags',{{entries.tag}},'certifications',{{entries.certification}});

    if nargin<1||isempty(selector),policy=result;return;end
    value=char(string(selector));
    hit=find(strcmp({entries.tag},value)| ...
        strcmp({entries.likelihood},value)| ...
        strcmp({entries.certification},value),1);
    assert(~isempty(hit),'design_study:real_scenario_policy:UnknownScenario', ...
        'Unknown design-study scenario, likelihood or certification "%s".',value);
    policy=entries(hit);
    policy.schemaVersion=result.schemaVersion;
end
