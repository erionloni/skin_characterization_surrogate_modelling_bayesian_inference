function result = posterior_metrics(provider,caseIndex,design)
%POSTERIOR_METRICS The posterior reference metrics of one case and design.
%   RESULT = design_study.posterior_metrics(PROVIDER, CASEINDEX, DESIGN)
%   summarizes the saved posterior of the cell in unit-box coordinates:
%   mean, covariance and standard deviations, the standard deviations
%   relative to the prior's, contraction, recovery error of the mean, 95%
%   coverage of the truth, trace and log determinant of the full and the
%   target (q) covariance, and the information gain over the prior (nats),
%   with the artifact metadata.
%   Side effects: none.
    design = design_study.get_design(provider,design);
    posterior = provider.posterior_provider(caseIndex,design);
    C0 = provider.prior_definition.covariance_u;
    q = provider.target_indices;
    truth = provider.cases(caseIndex).truth_u(:);
    width = sqrt(diag(posterior.covariance_u));
    priorWidth = sqrt(diag(C0));
    qCovariance = posterior.covariance_u(q,q);
    fullLogdet=design_study.posterior_covariance_logdet( ...
        posterior.covariance_u,posterior.draws_u);
    qLogdet=design_study.posterior_covariance_logdet( ...
        qCovariance,posterior.draws_u(:,q));
    [metricKind,fullMetricLabel,qMetricLabel,metricExact] = ...
        information_metric_semantics();
    metadata = design_study.make_metadata(provider);
    result = struct( ...
        'case_id',provider.case_ids{caseIndex}, ...
        'design_name',design.name, ...
        'posterior_mean_u',posterior.mean_u, ...
        'posterior_covariance_u',posterior.covariance_u, ...
        'posterior_sd_u',width, ...
        'normalized_posterior_sd',width./priorWidth, ...
        'contraction_amount',1-width./priorWidth, ...
        'posterior_mean_recovery_error_u',abs(posterior.mean_u-truth), ...
        'truth_covered_95',truth>=posterior.credible_interval_95_u(:,1) & ...
            truth<=posterior.credible_interval_95_u(:,2), ...
        'full_trace',trace(posterior.covariance_u), ...
        'full_logdet',fullLogdet, ...
        'q_trace',trace(qCovariance), ...
        'q_logdet',qLogdet, ...
        'full_information_gain',0.5*(design_study.logdet_spd(C0)- ...
            fullLogdet), ...
        'q_information_gain',0.5*(design_study.logdet_spd(C0(q,q))- ...
            qLogdet), ...
        'metric_kind',metricKind, ...
        'full_information_gain_label',fullMetricLabel, ...
        'q_information_gain_label',qMetricLabel, ...
        'information_metric_units','nats', ...
        'information_metric_exact',metricExact, ...
        'information_metric_definition', ...
            '0.5*(logdet(prior covariance)-logdet(posterior covariance))', ...
        'posterior_kind',posterior.posterior_kind, ...
        'metadata',metadata);
end

function [kind,fullLabel,qLabel,isExact] = information_metric_semantics()
%INFORMATION_METRIC_SEMANTICS Prevent covariance summaries becoming EIG claims.
%   Saved direct-MCMC posteriors are summarized by Gaussian moments. The
%   half-log-determinant reduction is therefore a covariance-volume summary,
%   not an exact expected information gain.
    isExact = false;
    kind = 'gaussian_moment_covariance_log_volume_reduction';
    fullLabel = [ ...
        'Gaussian-moment full-theta covariance log-volume reduction ' ...
        '(not exact EIG)'];
    qLabel = [ ...
        'Gaussian-moment q-block covariance log-volume reduction ' ...
        '(not exact EIG)'];
end
