function validate_stage2_gate(cfg)
%VALIDATE_STAGE2_GATE The approved package, or a surrogate refit that allows the sensitivity.
%   The approved generalized models are used with the shipped dataset. A
%   rerun's own models are used when its surrogate step recorded that they
%   allow the sensitivity (stage2_gate_decision.json).
    if cfg.realExtended.packageBound,return;end
    pathValue=fullfile(cfg.paths.stage02,'metadata','stage2', ...
        'stage2_gate_decision.json');
    assert(isfile(pathValue),'sensitivity:run_generalized:MissingStage2Gate', ...
        ['The record of the surrogate step (stage2_gate_decision.json) is ' ...
         'missing; run the step ''surrogates'' first.']);
    gate=jsondecode(fileread(pathValue));
    if isfield(gate,'stage3Allowed')
        allowed=gate.stage3Allowed;
    elseif isfield(gate,'stage3_allowed')
        allowed=gate.stage3_allowed;
    else
        error('sensitivity:run_generalized:Stage2GateSchema', ...
            'The gate record does not say whether the sensitivity may run.');
    end
    assert(islogical(allowed)&&isscalar(allowed)&&allowed, ...
        'sensitivity:run_generalized:Stage2GateHeld', ...
        'The gate record does not allow the sensitivity to run.');
end

