        "mean_ratio_total_order",mean(StDerived(ratioRows,2)), ...
        mean(SfDerived(ratioRows,2)), ...
        'VariableNames',T.Properties.VariableNames)];
    T=[T;table("weak_parameter_ratio_sensitivity","log10_k0_RD", ...
        "mean_ratio_total_order",mean(StDerived(ratioRows,3)), ...
        mean(SfDerived(ratioRows,3)), ...
        'VariableNames',T.Properties.VariableNames)];
