function p=relative_path(value,root)
    if isempty(value),p='';return;end
    p=utils.absolute_path(value);root=utils.absolute_path(root);
    prefix=[root filesep];
    if ispc
        contained=strcmpi(p,root)||startsWith(lower(p),lower(prefix));
    else
        contained=strcmp(p,root)||startsWith(p,prefix);
    end
    assert(contained,'sensitivity:run_generalized:PathOutsideRun', ...
        'A path of the sensitivity lies outside the run folder: %s',p);
    if strcmpi(p,root),p='';else,p=p(numel(prefix)+1:end);end
    p=strrep(char(p),'\','/');
end
