function result = run_generalized(cfg,varargin)
%RUN_GENERALIZED Sensitivity of the generalized surrogates to the seven inputs.
%   RESULT = sensitivity.run_generalized(CFG) computes, for the GP CFG.files.gp and
%   (when present) the PCE CFG.files.pce of the generalized route: the first,
%   total and second-order Sobol indices of the six closing pressures with
%   respect to the four material and three protocol inputs (GP by sampling,
%   PCE analytically), the indices of the derived cycle-drop and ratio
%   features, the ARD importance of the GP, the fixed-surrogate bootstrap of
%   the indices, the material/protocol group summaries, the GP-PCE ranking
%   comparison and the support audit of the Sobol sample against each
%   output's development cases. It writes the tables and the result record
%   below CFG.paths.results/sensitivity and the resolver
%   CFG.files.sensitivity. A later call in the same folder reuses the saved
%   components of the same request (the models' content,
%   surrogates.model_content; the dataset's development and held-out
%   arrays; its snapshot, inputs, outputs, PCE state and policy). Seeds: the
%   master seed plus fixed offsets, and the policy's support and bootstrap
%   seeds.
%   sensitivity.run_generalized(CFG,'FinalizeOnly',true) only writes the tables from
%   an existing result (no Sobol computation). It needs the dataset the
%   models were fitted on, and evaluates no posterior.
%   Computation: tens of minutes at the thesis settings.
%   Side effects: writes the files above and the sensitivity figures
%   (plotting.saved_generalized_sensitivity_figures); the random number
%   generator's state is restored afterwards.

    assert(strcmp(cfg.dataMode,'real_extended'), ...
        'sensitivity:run_generalized:WrongRoute', ...
        'The generalized sensitivity needs the generalized route (dataMode=real_extended).');
    assert(~cfg.realExtended.stage4PlusEnabled && ...
        ~cfg.realExtended.stage3.posteriorEnabled, ...
        'sensitivity:run_generalized:PosteriorGuard', ...
        'The generalized sensitivity runs no posterior or inversion step; the configuration enables one.');
    assert(isfile(cfg.files.dataset), ...
        'sensitivity:run_generalized:MissingDataset', ...
        'The generalized dataset is missing: run the step ''dataset'' before the sensitivity.');
    assert(isfile(cfg.files.gp), ...
        'sensitivity:run_generalized:MissingGP', ...
        ['The generalized GP is missing: bind the approved package or run the ' ...
         'step ''surrogates'' first.']);
    dataset=utils.load_plain_mat(cfg.files.dataset);
    validate_dataset(dataset,cfg);
    % The sensitivity uses the surrogate means only; it does not need the
    % emulator-error calibration.
    context=dataset_context(dataset);
    cfg.realExtended.stage3Context=context;
    validate_stage2_gate(cfg);
    gp=surrogates.load_ensemble(cfg.files.gp,'gp');
    surrogates.validate_surrogate_ensemble_scope(gp,dataset,cfg,'gp');
    [pce,pceState]=load_optional_pce(cfg,dataset);
    P=parameters.parameter_space(cfg);
    assert(P.M==7 && isequal(P.names,cfg.realExtended.learningInputNames), ...
        'sensitivity:run_generalized:ParameterContract', ...
        'The sensitivity needs the seven canonical inputs of the generalized route.');
    assert(isequal(size(P.bounds),size(dataset.inputBounds)) && ...
        max(abs(P.bounds-dataset.inputBounds),[],'all') <= ...
            cfg.realExtended.stage3.campaignBoundsAbsoluteTolerance, ...
        'sensitivity:run_generalized:CampaignDistributionBounds', ...
        ['The Sobol input distribution bounds do not match the immutable ' ...
        'dataset contract.']);

    policy=cfg.realExtended.stage3;
    localCfg=cfg;
    localCfg.N_sobol=policy.sobolSampleSize;
    secondOrderRows=nchoosek(P.M,2)*localCfg.N_sobol;
    assert(~(secondOrderRows>1e6 && secondOrderRows<2e6), ...
        'sensitivity:run_generalized:UQLabGreaterOrderUnsafeBatchBand', ...
        ['The configured seven-input second-order Sobol workload (%d rows) ' ...
        'falls in the verified unsafe UQLab 2.3 batching band (1e6,2e6).'], ...
        secondOrderRows);
    request=stage3_request(cfg,dataset,gp,pce,pceState,policy,context);
    roots=make_roots(cfg);
    checkpoint=fullfile(roots.results,'sensitivity.mat');
    parser=inputParser;
    addParameter(parser,'FinalizeOnly',false,@(x)islogical(x)&&isscalar(x));
    parse(parser,varargin{:});
    finalizeOnly=parser.Results.FinalizeOnly;

    if isfile(checkpoint)
        loaded=load(checkpoint,'core');
        assert(isfield(loaded,'core')&&isfield(loaded.core,'request')&& ...
            isequaln(loaded.core.request,request), ...
            'sensitivity:run_generalized:CheckpointRequest', ...
            ['The saved sensitivity result %s belongs to another request (models, ' ...
             'dataset, inputs, outputs, PCE state or policy); remove it to recompute.'], ...
            checkpoint);
        core=loaded.core;
    else
        assert(~finalizeOnly, ...
            'sensitivity:run_generalized:FinalizeCheckpointMissing', ...
            'FinalizeOnly needs the saved sensitivity result %s.',checkpoint);
        core=compute_core(gp,pce,pceState,P,dataset,localCfg,policy, ...
            request,roots,cfg,context);
        publish_mat(checkpoint,struct('core',core));
    end
    resolverPath=publish_sensitivity_resolver(cfg.files.sensitivity, ...
        checkpoint,context,cfg);

    publish_tables(core,roots,cfg);
    coreTables=publish_core_parity_tables(core,cfg);
    figureManifest=plotting.saved_generalized_sensitivity_figures( ...
        cfg,roots.results);
    figureInventory=fullfile(cfg.paths.stage03,'metadata', ...
        'stage3_figure_inventory.csv');
    if ~isfolder(fileparts(figureInventory)),mkdir(fileparts(figureInventory));end
    utils.atomic_write_table(figureInventory,figureManifest);
    publish_reports(core,roots,cfg,pceState);

    result=struct( ...
        'schema_version','real_extended_stage3_result_v2', ...
        'status','STAGE3_COMPLETE', ...
        'route','real_extended', ...
        'pce_state',pceState.status, ...
        'calibration_requirement','not_consumed_by_stage3_mean_sensitivity', ...
        'support_interpretation',core.support_interpretation, ...
        'posterior_certification','supporting_validation_no_posterior', ...
        'claim_scope','configured_generalized_surrogate_and_sensitivity', ...
        'checkpoint',relative_path(checkpoint,cfg.paths.runRoot), ...
        'resolver',relative_path(resolverPath,cfg.paths.runRoot), ...
        'source_snapshot_id',context.snapshot_id, ...
        'missing_probe_runids',context.missing_probe_runids, ...
        'sobol_sample_size',localCfg.N_sobol, ...
        'uqlab_second_order_workload_rows',secondOrderRows, ...
        'core_parity_table_count',numel(coreTables), ...
        'bounded_figure_count',height(figureManifest), ...
        'stop_point','STOP_AFTER_STAGE_3', ...
        'environment',utils.environment_line());
    utils.atomic_write_json(fullfile(roots.reports,'sensitivity_result.json'), ...
        result,'AllowReplace',true);
    latest=struct('schema_version','real_extended_stage3_resolver_v2', ...
        'checkpoint_path',relative_path(checkpoint,cfg.paths.runRoot), ...
        'status',result.status,'stop_point',result.stop_point);
    utils.atomic_write_json(fullfile(cfg.paths.reports, ...
        'sensitivity_latest.json'),latest,'AllowReplace',true);
end

function core=compute_core(gp,pce,pceState,P,dataset,cfg,policy,request,roots,fullCfg,context)
    started=datetime('now','TimeZone','UTC');
    seeds=sensitivity.generalized_seeds(fullCfg);

    previous=rng;cleanup=onCleanup(@() rng(previous));
    gpRawPath=fullfile(roots.results,'components','gp_raw_sobol.mat');
    if isfile(gpRawPath)
        component=load_component(gpRawPath,request,'gp_raw_sobol');
        SfGP=component.first;StGP=component.total;S2GP=component.second;
        AGP=component.ard;
    else
        rng(seeds.gp_raw,'twister');
        [SfGP,StGP,S2GP]=sensitivity.sobol(gp,P,cfg);
        AGP=sensitivity.ard(gp,P);
        publish_component(gpRawPath,request,'gp_raw_sobol',struct( ...
            'first',SfGP,'total',StGP,'second',S2GP,'ard',AGP),context);
    end
    gpGroups=sensitivity.generalized_group_summary(SfGP,StGP,S2GP, ...
        P.names,P.outputNames);

    gpComplete=complete_family(gp,6);
    assert(gpComplete,'sensitivity:run_generalized:IncompleteGP', ...
        'All six GP output models are required for derived-output sensitivity.');
    gpDerivedPath=fullfile(roots.results,'components','gp_derived_sobol.mat');
    if isfile(gpDerivedPath)
        component=load_component(gpDerivedPath,request,'gp_derived_sobol');
        SfDerivedGP=component.first;StDerivedGP=component.total;
        S2DerivedGP=component.second;derivedNames=component.output_names;
        derivedGroups=component.groups;
    else
        rng(seeds.gp_derived,'twister');
        [SfDerivedGP,StDerivedGP,S2DerivedGP,derivedNames,derivedGroups]= ...
            sensitivity.derived_sobol(gp,P,cfg);
        publish_component(gpDerivedPath,request,'gp_derived_sobol',struct( ...
            'first',SfDerivedGP,'total',StDerivedGP,'second',S2DerivedGP, ...
            'output_names',{derivedNames},'groups',derivedGroups),context);
    end

    SfPCE=nan(6,7);StPCE=SfPCE;
    S2PCE=empty_second(P,6);
    SfDerivedPCE=nan(numel(derivedNames),7);
    StDerivedPCE=SfDerivedPCE;
    S2DerivedPCE=empty_second(P,numel(derivedNames));
    pceGroups=struct('group',table(),'theta_phi',table(),'protocol',table());
    if pceState.loaded
        pceRawPath=fullfile(roots.results,'components','pce_raw_sobol.mat');
        if isfile(pceRawPath)
            component=load_component(pceRawPath,request,'pce_raw_sobol');
            SfPCE=component.first;StPCE=component.total;S2PCE=component.second;
        else
            [SfPCE,StPCE,S2PCE]=sensitivity.pce_sobol_analytic(pce,P,cfg);
            publish_component(pceRawPath,request,'pce_raw_sobol',struct( ...
                'first',SfPCE,'total',StPCE,'second',S2PCE),context);
        end
        pceGroups=sensitivity.generalized_group_summary(SfPCE,StPCE,S2PCE, ...
            P.names,P.outputNames);
        if complete_family(pce,6)
            pceDerivedPath=fullfile(roots.results,'components', ...
                'pce_derived_sobol.mat');
            if isfile(pceDerivedPath)
                component=load_component(pceDerivedPath,request, ...
                    'pce_derived_sobol');
                SfDerivedPCE=component.first;StDerivedPCE=component.total;
                S2DerivedPCE=component.second;
            else
                rng(seeds.pce_derived,'twister');
                [SfDerivedPCE,StDerivedPCE,S2DerivedPCE]= ...
                    sensitivity.derived_sobol(pce,P,cfg);
                publish_component(pceDerivedPath,request, ...
                    'pce_derived_sobol',struct('first',SfDerivedPCE, ...
                    'total',StDerivedPCE,'second',S2DerivedPCE),context);
            end
        end
    end

    [rankComparison,rankSummary]=ranking_comparison(StGP,StPCE, ...
        P.names,P.outputNames);
    [derivedRankComparison,derivedRankSummary]=ranking_comparison( ...
        StDerivedGP,StDerivedPCE,P.names,derivedNames);
    ardComparison=ard_comparison(AGP.importance,StGP,P.names,P.outputNames);

    caseRegistry=readtable(fullfile(fullCfg.realExtended.paths.registries, ...
        'case_registry.csv'),'Delimiter',',', ...
        'TextType','string','VariableNamingRule','preserve');
    [feasibilitySummary,feasibilityBins,missingnessSummary,missingnessBins]= ...
        sensitivity.feasibility_sensitivity(caseRegistry,P.names);

    bounds=dataset.inputBounds;
    plannedX=caseRegistry{:,P.names};
    [found,plannedLoc]=ismember(caseRegistry.CaseID,dataset.supportRegistry.CaseID);
    assert(all(found),'sensitivity:run_generalized:SupportJoin', ...
        'The support registry of the dataset does not cover all planned CaseIDs.');
    rng(seeds.support,'twister');
    supportX=P.denormalize(rand(policy.supportAuditSampleSize,P.M));
    supportAudit=output_specific_support_audit(supportX,dataset,plannedX, ...
        plannedLoc,caseRegistry.CaseID,bounds);
    summary=supportAudit.category_summary;
    unsupported=sum(summary.fraction(ismember(summary.support_class, ...
        ["extrapolative","inside_known_noncomplete_region", ...
        "unresolved_due_to_missing_outcome"])));
    if unsupported>0
        supportInterpretation='full_box_contains_non_well_supported_points';
    else
        supportInterpretation='full_box_within_declared_support_radius';
    end

    bootstrap=struct('status','not_requested');
    bootstrapPath='';
    if policy.fixedSurrogateBootstrapEnabled
        % The saved bootstrap of this folder is reused for the same request,
        % base size, replicate count, seed and features.
        bootstrapRequest=struct('request',request, ...
            'n_base',policy.fixedSurrogateBootstrapBaseSize, ...
            'n_replicates',policy.fixedSurrogateBootstrapReplicates, ...
            'seed',policy.fixedSurrogateBootstrapSeed,'n_inputs',P.M, ...
            'derived_features','pressure_ratio_and_cycle_drop_v1');
        bootstrapPath=fullfile(roots.results,'fixed_surrogate_bootstrap.mat');
        if isfile(bootstrapPath)
            loaded=load(bootstrapPath,'bootstrap','bootstrapRequest');
            assert(isfield(loaded,'bootstrapRequest') && ...
                isequaln(loaded.bootstrapRequest,bootstrapRequest), ...
                'sensitivity:run_generalized:BootstrapRequest', ...
                ['The saved fixed-surrogate bootstrap %s belongs to another request ' ...
                 '(base size, replicates, seed or sensitivity request); remove it to ' ...
                 'recompute.'],bootstrapPath);
            bootstrap=loaded.bootstrap;
        else
            evaluator=@(U) bootstrap_outputs(gp,P,U,fullCfg.realExtended.predictionBatchSize);
            bootstrap=sensitivity.sobol_bootstrap(evaluator,P.M, ...
                policy.fixedSurrogateBootstrapBaseSize, ...
                policy.fixedSurrogateBootstrapReplicates, ...
                policy.fixedSurrogateBootstrapSeed);
            bootstrap.status=sprintf( ...
                'complete_%d_fixed_surrogate_development_replicates', ...
                policy.fixedSurrogateBootstrapReplicates);
            bootstrap.output_names=[P.outputNames derivedNames];
            bootstrap.artifact_scope='GENERALIZED SURROGATE';
            bootstrap.source_snapshot_id=context.snapshot_id;
            bootstrap.missing_probe_runids=context.missing_probe_runids;
            bootstrap.posterior_certification='supporting_validation_no_posterior';
            publish_mat(bootstrapPath,struct('bootstrap',bootstrap, ...
                'bootstrapRequest',bootstrapRequest));
        end
    end

    protocolReport=protocol_report(SfGP,StGP,gpGroups,SfDerivedGP, ...
        StDerivedGP,P.outputNames,derivedNames);
    m3Report=m3_report(StGP,gpGroups.theta_phi,StDerivedGP, ...
        P.outputNames,derivedNames);
    clear cleanup

    core=struct( ...
        'schema_version','real_extended_stage3_core_v1', ...
        'request',request,'route','real_extended', ...
        'source_snapshot_id',context.snapshot_id, ...
        'pce_state',pceState, ...
        'input_names',{P.names},'output_names',{P.outputNames}, ...
        'derived_output_names',{derivedNames}, ...
        'derived_groups',derivedGroups, ...
        'sobol_sample_size',cfg.N_sobol,'seeds',seeds, ...
        'gp',struct('first',SfGP,'total',StGP,'second',S2GP, ...
            'groups',gpGroups,'ard',AGP), ...
        'pce',struct('first',SfPCE,'total',StPCE,'second',S2PCE, ...
            'groups',pceGroups), ...
        'derived_gp',struct('first',SfDerivedGP,'total',StDerivedGP, ...
            'second',S2DerivedGP), ...
        'derived_pce',struct('first',SfDerivedPCE,'total',StDerivedPCE, ...
            'second',S2DerivedPCE), ...
        'rank_comparison',rankComparison,'rank_summary',rankSummary, ...
        'derived_rank_comparison',derivedRankComparison, ...
        'derived_rank_summary',derivedRankSummary, ...
        'ard_comparison',ardComparison, ...
        'feasibility_summary',feasibilitySummary, ...
        'feasibility_bins',feasibilityBins, ...
        'missingness_summary',missingnessSummary, ...
        'missingness_bins',missingnessBins, ...
        'support_audit',supportAudit, ...
        'planned_case_count',height(caseRegistry), ...
        'support_interpretation',supportInterpretation, ...
        'unsupported_full_box_fraction',unsupported, ...
        'bootstrap',bootstrap, ...
        'bootstrap_checkpoint',relative_path( ...
            bootstrapPath,fullCfg.paths.runRoot), ...
        'protocol_report',protocolReport,'m3_report',m3Report, ...
        'posterior_certification','supporting_validation_no_posterior', ...
        'claim_scope','configured_generalized_surrogate_and_sensitivity', ...
        'missing_probe_runids',context.missing_probe_runids, ...
        'created_utc',char(datetime('now','TimeZone','UTC', ...
            'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')), ...
        'elapsed_seconds',seconds(datetime('now','TimeZone','UTC')-started), ...
        'stop_point','STOP_AFTER_STAGE_3');
end

function audit=output_specific_support_audit( ...
        queryX,data,plannedX,plannedLoc,plannedCaseIDs,bounds)
%OUTPUT_SPECIFIC_SUPPORT_AUDIT Use each scalar model's exact development set.
    if all(isfield(data,{'X_development_all','Y_development_all', ...
            'developmentOutputAvailabilityMask'}))
        developmentX=double(data.X_development_all);
        developmentY=double(data.Y_development_all);
        availability=logical(data.developmentOutputAvailabilityMask);
        assert(isequal(availability,isfinite(developmentY)), ...
            'sensitivity:run_generalized:DevelopmentAvailabilityMask', ...
            ['A missing development output must be NaN in Y_development_all ' ...
             'and unmarked in the availability mask; rerun the step ''dataset''.']);
    else
        developmentX=double(data.X_train);
        developmentY=double(data.Y_train);
        availability=isfinite(developmentY);
    end
    assert(size(developmentX,2)==size(bounds,1)&& ...
        size(developmentY,1)==size(developmentX,1)&& ...
        size(developmentY,2)==numel(data.outputNames)&& ...
        all(isfinite(developmentX),'all')&&~any(isinf(developmentY),'all'), ...
        'sensitivity:run_generalized:OutputSupportDevelopmentContract', ...
        ['The development cases must have one finite value per input and one ' ...
         'finite or missing value per output.']);
    plannedValid=all(isfinite(plannedX),2);
    assert(any(plannedValid), ...
        'sensitivity:run_generalized:NoValidPlannedInputs', ...
        'No finite planned seven-input row is available for support auditing.');
    validPlannedX=plannedX(plannedValid,:);
    validRegistryRows=find(plannedValid);
    nOutput=numel(data.outputNames);
    pieces=cell(nOutput,1);summaryPieces=cell(nOutput,1);
    wellByOutput=nan(1,nOutput);weakByOutput=nan(1,nOutput);
    trainingCounts=zeros(1,nOutput);
    plannedClass=strings(size(plannedX,1),nOutput);
    for outputIndex=1:nOutput
        outputName=data.outputNames{outputIndex};
        suffix=matlab.lang.makeValidName(outputName);
        className=['support_class_' suffix];
        wellName=['well_supported_threshold_' suffix];
        weakName=['weakly_supported_threshold_' suffix];
        if ismember(className,data.supportRegistry.Properties.VariableNames)
            plannedClass(:,outputIndex)=string( ...
                data.supportRegistry.(className)(plannedLoc));
            well=median(double(data.supportRegistry.(wellName)),'omitnan');
            weak=median(double(data.supportRegistry.(weakName)),'omitnan');
        else
            plannedClass(:,outputIndex)=string( ...
                data.supportRegistry.support_class(plannedLoc));
            well=median(double( ...
                data.supportRegistry.well_supported_threshold),'omitnan');
            weak=median(double( ...
                data.supportRegistry.weakly_supported_threshold),'omitnan');
        end
        trainingX=developmentX(availability(:,outputIndex),:);
        trainingCounts(outputIndex)=size(trainingX,1);
        assert(trainingCounts(outputIndex)>=2, ...
            'sensitivity:run_generalized:OutputSupportTrainingCount', ...
            'Output %d has fewer than two finite development rows.',outputIndex);
        one=sensitivity.generalized_support_audit(queryX,trainingX,validPlannedX, ...
            plannedClass(plannedValid,outputIndex),bounds, ...
            'WellThreshold',well,'WeakThreshold',weak);
        wellByOutput(outputIndex)=one.well_supported_threshold;
        weakByOutput(outputIndex)=one.weakly_supported_threshold;
        point=one.point_table;
        point.nearest_planned_row=validRegistryRows( ...
            point.nearest_planned_row);
        point.nearest_planned_case_id=double(plannedCaseIDs( ...
            point.nearest_planned_row));
        point.OutputIndex=repmat(outputIndex,height(point),1);
        point.Output=repmat(string(outputName),height(point),1);
        point=movevars(point,{'OutputIndex','Output'},'Before',1);
        pieces{outputIndex}=point;
        summary=one.category_summary;
        summary.OutputIndex=repmat(outputIndex,height(summary),1);
        summary.Output=repmat(string(outputName),height(summary),1);
        summary=movevars(summary,{'OutputIndex','Output'},'Before',1);
        summaryPieces{outputIndex}=summary;
    end
    pointTable=vertcat(pieces{:});
    perOutputSummary=vertcat(summaryPieces{:});
    categories=["well_supported";"weakly_supported";"extrapolative"; ...
        "inside_known_noncomplete_region"; ...
        "unresolved_due_to_missing_outcome"];
    count=zeros(numel(categories),1);fraction=count;
    for index=1:numel(categories)
        count(index)=sum(pointTable.support_class==categories(index));
        fraction(index)=count(index)/height(pointTable);
    end
    plannedAvailability=planned_availability_table(plannedCaseIDs, ...
        plannedValid,plannedClass,data.outputNames);
    audit=struct( ...
        'schema_version','real_extended_stage3_support_audit_v2_output_specific', ...
        'guard_definition', ...
            'normalized_7d_output_specific_development_plus_planned_outcome_v2', ...
        'query_count',size(queryX,1), ...
        'output_count',nOutput, ...
        'output_names',{data.outputNames}, ...
        'well_supported_threshold',max(wellByOutput), ...
        'weakly_supported_threshold',max(weakByOutput), ...
        'well_supported_threshold_by_output',wellByOutput, ...
        'weakly_supported_threshold_by_output',weakByOutput, ...
        'training_count_by_output',trainingCounts, ...
        'category_summary',table(categories,count,fraction, ...
            'VariableNames',{'support_class','count','fraction'}), ...
        'per_output_category_summary',perOutputSummary, ...
        'point_table',pointTable, ...
        'planned_case_availability',plannedAvailability, ...
        'invalid_planned_input_count',sum(~plannedValid));
end

function T=planned_availability_table(caseIDs,inputValid,classes,outputNames)
    nCase=numel(caseIDs);nOutput=numel(outputNames);
    CaseID=repmat(double(caseIDs(:)),nOutput,1);
    InputValid=repmat(logical(inputValid(:)),nOutput,1);
    OutputIndex=kron((1:nOutput).',ones(nCase,1));
    Output=strings(nCase*nOutput,1);SupportClass=Output;
    IncludedAsPlannedCandidate=InputValid;
    for outputIndex=1:nOutput
        rows=(outputIndex-1)*nCase+(1:nCase);
        Output(rows)=string(outputNames{outputIndex});
        SupportClass(rows)=classes(:,outputIndex);
    end
    T=table(OutputIndex,Output,CaseID,InputValid,SupportClass, ...
        IncludedAsPlannedCandidate);
end

function tables=publish_tables(C,roots,cfg)
    tables=strings(0,1);
    tables(end+1)=write_matrix(C.gp.first,C.output_names,C.input_names, ...
        fullfile(roots.results,'sobol_gp_first.csv'),cfg);
    tables(end+1)=write_matrix(C.gp.total,C.output_names,C.input_names, ...
        fullfile(roots.results,'sobol_gp_total.csv'),cfg);
    tables(end+1)=write_second(C.gp.second,C.output_names, ...
        fullfile(roots.results,'sobol_gp_second_order.csv'),cfg);
    tables(end+1)=write_matrix(max(C.gp.total-C.gp.first,0), ...
        C.output_names,C.input_names, ...
        fullfile(roots.results,'sobol_gp_interaction_gap.csv'),cfg);
    tables(end+1)=write_matrix(C.pce.first,C.output_names,C.input_names, ...
        fullfile(roots.results,'sobol_pce_first_analytic.csv'),cfg);
    tables(end+1)=write_matrix(C.pce.total,C.output_names,C.input_names, ...
        fullfile(roots.results,'sobol_pce_total_analytic.csv'),cfg);
    tables(end+1)=write_second(C.pce.second,C.output_names, ...
        fullfile(roots.results,'sobol_pce_second_order_analytic.csv'),cfg);
    % PCE indices are analytic and have exactly one canonical table set.
    tables(end+1)=write_matrix(max(C.pce.total-C.pce.first,0), ...
        C.output_names,C.input_names, ...
        fullfile(roots.results,'sobol_pce_interaction_gap.csv'),cfg);
    tables(end+1)=write_matrix(C.derived_gp.first,C.derived_output_names, ...
        C.input_names,fullfile(roots.results,'derived_sobol_gp_first.csv'),cfg);
    tables(end+1)=write_matrix(C.derived_gp.total,C.derived_output_names, ...
        C.input_names,fullfile(roots.results,'derived_sobol_gp_total.csv'),cfg);
    tables(end+1)=write_matrix(C.derived_pce.first,C.derived_output_names, ...
        C.input_names,fullfile(roots.results,'derived_sobol_pce_first.csv'),cfg);
