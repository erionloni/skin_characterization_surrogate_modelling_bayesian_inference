                "cycle_"+string(cycle),mean(Stotal([cycle cycle+3],j)),NaN, ...
                'VariableNames',T.Properties.VariableNames)]; %#ok<AGROW>
        end
    end
    holdPauseCorrelation=correlation_safe(Stotal(:,6),Stotal(:,7));
    T=[T;table("hold_pause_distinguishability","profile_comparison", ...
        "correlation_and_max_absolute_difference",holdPauseCorrelation, ...
        max(abs(Stotal(:,6)-Stotal(:,7))), ...
        'VariableNames',T.Properties.VariableNames)];
