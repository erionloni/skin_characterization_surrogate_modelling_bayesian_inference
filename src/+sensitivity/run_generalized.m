    dropTable=table(repmat("cycle_drop_protocol_sensitivity",3,1), ...
        protocolNames(:),repmat("mean_derived_drop_total_order",3,1), ...
        dropValues,nan(3,1),'VariableNames',T.Properties.VariableNames);
    T=[T;dropTable];
    T=[T;table("material_vs_protocol_variance","raw_pressures", ...
        "mean_material_first_vs_protocol_first", ...
        mean(G.group.material_first_order_sum), ...
        mean(G.group.protocol_first_order_sum), ...
        'VariableNames',T.Properties.VariableNames)];
