function [comparison,summary]=ranking_comparison(GP,PCE,inputNames,outputNames)
    comparison=table();summary=table();
    for o=1:numel(outputNames)
        rg=ordinal_rank(GP(o,:));rp=ordinal_rank(PCE(o,:));
        for j=1:numel(inputNames)
            comparison=[comparison;table(string(outputNames{o}), ...
                string(inputNames{j}),GP(o,j),PCE(o,j), ...
                abs(GP(o,j)-PCE(o,j)),rg(j),rp(j), ...
                'VariableNames',{'output','input','gp_total','pce_total', ...
                'absolute_difference','gp_rank','pce_rank'})]; %#ok<AGROW>
        end
        take=isfinite(rg)&isfinite(rp);
        rho=NaN;
        maxDifference=NaN;meanDifference=NaN;topAgree=false;
        if sum(take)>=2,rho=correlation_safe(rg(take),rp(take));end
        if any(take)
            differences=abs(GP(o,take)-PCE(o,take));
            maxDifference=max(differences,[],'omitnan');
            meanDifference=mean(differences,'omitnan');
            [~,gpTop]=max(GP(o,:));[~,pceTop]=max(PCE(o,:));
            topAgree=gpTop==pceTop;
        end
        summary=[summary;table(string(outputNames{o}),rho,sum(take), ...
            maxDifference,meanDifference,topAgree, ...
            'VariableNames',{'output','rank_correlation','rankable_inputs', ...
            'max_absolute_difference','mean_absolute_difference', ...
            'top_rank_agreement'})]; %#ok<AGROW>
    end
end

