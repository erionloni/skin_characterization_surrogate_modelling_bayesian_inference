function rank=ordinal_rank(values)
    rank=nan(size(values));
    valid=find(isfinite(values));
    [~,order]=sort(values(valid),'descend');
    rank(valid(order))=1:numel(valid);
end

function rho=correlation_safe(a,b)
    a=a(:);b=b(:);
    if numel(a)<2||std(a)==0||std(b)==0,rho=NaN;return;end
    rho=sum((a-mean(a)).*(b-mean(b)))/ ...
        sqrt(sum((a-mean(a)).^2)*sum((b-mean(b)).^2));
end

function T=protocol_report(~,Stotal,G,SfDerived,StDerived,outputNames,derivedNames)
    protocolNames=["log10_abs_suction_rate","hold_dur_s","pause_dur_s"];
    T=table();
