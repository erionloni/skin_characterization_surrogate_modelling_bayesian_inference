function [pce,state]=load_optional_pce(cfg,dataset)
    pce=[];
    state=struct('loaded',false,'status','UNAVAILABLE_NO_PCE_ARTIFACT', ...
        'reason','cfg.files.pce does not exist');
    if ~isfile(cfg.files.pce),return;end
    try
        pce=surrogates.load_ensemble(cfg.files.pce,'pce');
        surrogates.validate_surrogate_ensemble_scope(pce,dataset,cfg,'pce');
        state.loaded=true;
        if complete_family(pce,6)
            state.status='AVAILABLE_ALL_SIX_OUTPUTS';
            state.reason='';
        else
            state.status='PARTIAL_PCE_RAW_ONLY';
            state.reason='One or more independently trained PCE outputs are unavailable.';
        end
    catch exception
        state.status='UNAVAILABLE_INVALID_PCE_ARTIFACT';
        state.reason=exception.message;
        pce=[];
    end
end

function validate_dataset(D,cfg)
    required={'X_train','Y_train','X_test','Y_test','inputNames','outputNames', ...
        'inputBounds','supportRegistry','dataProvenance'};
    assert(all(isfield(D,required)), ...
        'sensitivity:run_generalized:DatasetSchema', ...
        'The dataset MAT file does not satisfy the contract of the generalized route.');
    assert(size(D.X_train,2)==7&&size(D.Y_train,2)==6&& ...
        size(D.X_test,2)==7&&size(D.Y_test,2)==6&& ...
        isequal(D.inputNames,cfg.realExtended.learningInputNames)&& ...
        isequal(D.outputNames,cfg.realExtended.outputNames), ...
        'sensitivity:run_generalized:DatasetShape', ...
        'The input/output contract of the dataset is invalid.');
    assert(strcmp(D.dataProvenance.cohort_decision,'all_complete_primary') || ...
        strcmp(D.dataProvenance.cohort_decision,'monotonic_qc_primary'), ...
        'sensitivity:run_generalized:CohortGate', ...
        'The sensitivity needs an unambiguous cohort decision of the dataset.');
    outputAware={'X_development_all','Y_development_all', ...
        'developmentCaseIDsAll','developmentOutputAvailabilityMask', ...
        'outputTrainingEvidence'};
    present=cellfun(@(name)isfield(D,name),outputAware);
    assert(~any(present)||all(present), ...
        'sensitivity:run_generalized:PartialOutputAwareSchema', ...
        'The per-output training evidence of the dataset must be complete when present.');
    if all(present)
        assert(size(D.X_development_all,2)==7&& ...
            size(D.Y_development_all,2)==6&& ...
            size(D.X_development_all,1)==size(D.Y_development_all,1)&& ...
            size(D.X_development_all,1)==numel(D.developmentCaseIDsAll)&& ...
            isequal(size(D.developmentOutputAvailabilityMask), ...
                size(D.Y_development_all))&& ...
            isequal(logical(D.developmentOutputAvailabilityMask), ...
                isfinite(double(D.Y_development_all)))&& ...
            all(isfinite(double(D.X_development_all)),'all')&& ...
            numel(D.outputTrainingEvidence)==6, ...
            'sensitivity:run_generalized:OutputAwareDatasetContract', ...
            'Output-aware generalized development evidence is inconsistent.');
    end
end

