function [D,names,groups] = derived_features(Y)
%DERIVED_FEATURES Ratios and cycle-pressure drops from the same raw prediction.
%   Y must follow the canonical six-pressure ordering. No feature is treated as
%   an independent measurement or independently trained surrogate output.
%   The drops of each probe are ordered 12, 23, 13; the feature
%   reconstruction registry (recovery.reconstruction_feature_registry)
%   orders them 12, 13, 23. Features are therefore joined by name
%   (feature ID), never by position (CLN-026).
%   [D, NAMES, GROUPS] = sensitivity.derived_features(Y) returns, for Y
%   (N-by-6 closing pressures), the 16 derived features (N-by-16: four
%   ratios, six absolute and six relative cycle drops), their names and the
%   column groups.
%   Side effects: none.

    assert(isnumeric(Y) && size(Y,2)==6 && all(isfinite(Y),'all'), ...
        'sensitivity:derived_features:Shape', ...
        'Expected a finite N-by-6 canonical pressure matrix.');
    assert(all(abs(Y(:,[1 2 4 5]))>1e-12,'all'), ...
        'sensitivity:derived_features:Denominator', ...
        'Cycle-ratio/drop denominators must be nonzero.');

    ratios = design_study.ratio_values(Y,1e-12);
    absolute = [Y(:,1)-Y(:,2), Y(:,2)-Y(:,3), Y(:,1)-Y(:,3), ...
                Y(:,4)-Y(:,5), Y(:,5)-Y(:,6), Y(:,4)-Y(:,6)];
    relative = [absolute(:,1)./Y(:,1), absolute(:,2)./Y(:,2), ...
                absolute(:,3)./Y(:,1), absolute(:,4)./Y(:,4), ...
                absolute(:,5)./Y(:,5), absolute(:,6)./Y(:,4)];
    D = [ratios absolute relative];
    names = { ...
        'pcl2_D2_over_pcl1_D2','pcl3_D2_over_pcl1_D2', ...
        'pcl2_D6_over_pcl1_D6','pcl3_D6_over_pcl1_D6', ...
        'drop12_D2_mbar','drop23_D2_mbar','drop13_D2_mbar', ...
        'drop12_D6_mbar','drop23_D6_mbar','drop13_D6_mbar', ...
        'rel_drop12_D2','rel_drop23_D2','rel_drop13_D2', ...
        'rel_drop12_D6','rel_drop23_D6','rel_drop13_D6'};
    groups = struct('ratio',1:4,'absolute_drop',5:10,'relative_drop',11:16, ...
        'relative_denominator_rule', ...
        'drop12/pcl1; drop23/pcl2; drop13/pcl1 within each probe');
end
