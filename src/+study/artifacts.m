function A = artifacts(entry)
%ARTIFACTS Saved files that one step writes and later steps read.
%   A = study.artifacts(ENTRY) returns a struct array, one element per
%   artifact of the route ENTRY ('fixed' or 'generalized'):
%     key      name used by the steps, e.g. 'gp'
%     step     step that writes it
%     path     location below a run folder and below thesis_results/ (the same
%              layout), with '/'
%     setting  '' when the shipped copy is thesis_results/<path>; otherwise the
%              setting that names the file used when the run does not write
%              it (the accepted confirmation observations:
%              generalized.confirmation.observations)
%   and A = study.artifacts() returns those of both routes.
%   A step reads an artifact from this run when its writing step ran here,
%   otherwise from the shipped results or the setting's file
%   (study.resolve_input).
%   Side effects: none.

    all = [ ...
        a('fixed', 'dataset', 'dataset', 'fixed/01_dataset/data/dataset.mat'), ...
        a('fixed', 'gp', 'surrogates', 'fixed/02_surrogates/data/models/gp_surrogate.mat'), ...
        a('fixed', 'pce', 'surrogates', 'fixed/02_surrogates/data/models/pce_surrogate.mat'), ...
        a('fixed', 'validation', 'surrogate_assessment', 'fixed/02_surrogates/data/assessment/surrogate_validation.mat'), ...
        a('fixed', 'inversion_status', 'inversion', 'fixed/04_inversion/data/cell_status.csv'), ...
        a('fixed', 'inversion_draws', 'inversion', 'fixed/04_inversion/data/draws/index.csv'), ...
        a('generalized', 'dataset', 'dataset', 'generalized/01_dataset/data/dataset.mat'), ...
        a('generalized', 'gp', 'surrogates', 'generalized/02_surrogates/data/models/gp_surrogate.mat'), ...
        a('generalized', 'pce', 'surrogates', 'generalized/02_surrogates/data/models/pce_surrogate.mat'), ...
        a('generalized', 'validation_predictions', 'surrogate_assessment', ...
            'generalized/02_surrogates/data/assessment/validation_predictions.csv'), ...
        a('generalized', 'local_information', 'screen', ...
            'generalized/05_protocol_screening/data/screen/local_information/local_information.mat'), ...
        a('generalized', 'full_covariance', 'objective_supplement', ...
            'generalized/05_protocol_screening/data/six_objective/full_covariance_supplement.mat'), ...
        a('generalized', 'rankings', 'rankings', ...
            'generalized/05_protocol_screening/data/six_objective/six_objective_rankings.csv'), ...
        a('generalized', 'observations', 'import_observations', ...
            'generalized/06_confirmation/data/observations/confirmation_observations.csv', ...
            'generalized.confirmation.observations')];
    if nargin < 1 || isempty(entry)
        A = all;
    else
        A = all(strcmp({all.entry}, char(string(entry))));
    end
end

function s = a(entry, key, step, pathValue, setting)
    if nargin < 5, setting = ''; end
    s = struct('entry', entry, 'key', key, 'step', step, 'path', pathValue, 'setting', setting);
end
