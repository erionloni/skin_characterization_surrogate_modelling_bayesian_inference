function s = src(route, key, folder, legacy)
    s = struct('route', route, 'key', key, 'folder', folder, 'legacy', {legacy});
end

function c = cat(route, category, analysis, prefix)
    c = struct('route', route, 'category', category, 'analysis', analysis, 'prefix', prefix);
end
