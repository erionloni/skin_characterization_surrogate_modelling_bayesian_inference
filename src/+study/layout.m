%                the pre-publication stages (used while those stages still write runs)
%
%   L.categories  one element per figure category used by the renderers
%       category category passed to plotting.export_saved_figure; the longest
%                matching category wins, deeper levels become part of the name;
%                a category of two analyses goes to the one being rendered
%       route    route of the analysis folder the figures go to
%       analysis analysis folder, e.g. '05_recovery'
%       prefix   file-name prefix that keeps names unique in the flat figures/
%                folder of that analysis
%       A category 'case/<step>' holds the per-case outputs of its analysis:
%       they go to <route>/cases/case_<CaseID>/<step>/{figures,tables}
%       (study.figure_target), and the analysis's README lists them.
%
