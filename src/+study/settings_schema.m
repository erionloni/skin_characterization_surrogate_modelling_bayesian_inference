function s = e(name, section, check)
    s = struct('name', name, 'section', section, 'check', check);
end

function S = switch_entries(route)
%SWITCH_ENTRIES The run switches of one route (section 0.2): one per step and analysis (study.switches).
    W = study.switches(route);
    S = arrayfun(@(w) e(sprintf('run.%s.%s', route, w.name), '0.2', @flag), W);
end

function S = rule(prefix, fields)
    S = e('', '', []);
    S = S([]);
    for f = fields
        S(end+1) = e([prefix '.' f{1}], '0.6', integer(1)); %#ok<AGROW>
    end
end

