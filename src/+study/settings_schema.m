function f = case_rows(varargin)
%CASE_ROWS Rows {cases, names...} of a case output: CaseIDs or 'all', then lists of names or 'all'; {} for none.
    allowed = varargin;
    f = @check;
    function m = check(v)
        m = '';
        if (isnumeric(v) || iscell(v)) && isempty(v), return; end
        ok = iscell(v) && ismatrix(v) && size(v, 2) == 1 + numel(allowed);
        for r = 1:size(v, 1) * ok
            ok = ok && isempty(case_selection(v{r, 1}));
            for k = 1:numel(allowed)
                ok = ok && isempty(feval(selection(allowed{k}), v{r, 1 + k}));
            end
        end
        if ~ok
            parts = {'scenarios', 'designs'};
            lists = cellfun(@(p, a) sprintf('%s a list of names among %s or ''all''', p, ...
                strjoin(strcat('''', a, ''''), ', ')), parts(1:numel(allowed)), allowed, ...
                'UniformOutput', false);
            m = sprintf('rows {cases, %s}: cases distinct positive CaseIDs or ''all'', %s; {} for none', ...
                strjoin(parts(1:numel(allowed)), ', '), strjoin(lists, ', '));
        end
    end
end

function m = condition_table(v)
%CONDITION_TABLE Rows {label, description, fixed parameters}: the conditions of the conditional inversion (A.9).
%   The names of the fixed parameters are checked against the parameters of
%   A.1 when the configuration is built (study.conditional_design, which
%   names the closest valid name).
    form = ['rows {label, description, fixed parameters}: a distinct label (letters, digits and ''_'', ' ...
        'at most 40, starting with a letter), a description, and a list of distinct parameter names that ' ...
        'leaves at least one of the four free; exactly one row fixes nothing (the canonical cell) and no ' ...
        'two rows fix the same parameters'];
    m = '';
    if ~(iscell(v) && ismatrix(v) && size(v, 2) == 3 && size(v, 1) >= 2)
        m = form;
        return;
    end
    labels = v(:, 1);
    fixed = v(:, 3);
    if ~all(cellfun(@(x) ischar(x) && ~isempty(regexp(x, '^[A-Za-z][A-Za-z0-9_]{0,39}$', 'once')), labels))
        m = [form '; a label is not of that form'];
    elseif numel(unique(labels)) < numel(labels)
        m = sprintf('%s; the label ''%s'' is used twice', form, first_repeat(labels));
    elseif ~all(cellfun(@(x) ischar(x) && ~isempty(strtrim(x)), v(:, 2)))
        m = [form '; a description is empty'];
    elseif ~all(cellfun(@(x) iscell(x) && (isempty(x) || isvector(x)) && all(cellfun(@ischar, x)), fixed))
        m = [form '; the fixed parameters of a row are not a list of names ({} for none)'];
    elseif any(cellfun(@(x) numel(unique(x)) < numel(x), fixed))
        m = sprintf('%s; condition ''%s'' names a parameter twice', form, ...
            labels{find(cellfun(@(x) numel(unique(x)) < numel(x), fixed), 1)});
    elseif any(cellfun(@numel, fixed) >= 4)
        m = sprintf('%s; condition ''%s'' fixes every parameter', form, ...
            labels{find(cellfun(@numel, fixed) >= 4, 1)});
    elseif nnz(cellfun(@isempty, fixed)) ~= 1
        m = sprintf('%s; %d rows fix nothing', form, nnz(cellfun(@isempty, fixed)));
    else
        sets = cellfun(@(x) strjoin(sort(x), '|'), fixed, 'UniformOutput', false);
        if numel(unique(sets)) < numel(sets)
            repeated = first_repeat(sets);
            rows = labels(strcmp(sets, repeated));
            m = sprintf('%s; conditions ''%s'' and ''%s'' fix the same parameters (the same inverse problem)', ...
                form, rows{1}, rows{2});
        end
    end
end

function f = condition_rows(scenarios)
%CONDITION_ROWS Rows {conditions, scenarios}: the campaign of the conditional inversion (A.9).
%   The labels are checked against the condition table when the
%   configuration is built (study.conditional_design).
    f = @check;
    function m = check(v)
        m = '';
        ok = iscell(v) && ismatrix(v) && size(v, 2) == 2 && size(v, 1) >= 1;
        for r = 1:size(v, 1) * ok
            labels = v{r, 1};
            if isstring(labels), labels = cellstr(labels); end
            ok = ok && ((ischar(labels) && strcmp(labels, 'all')) || (iscell(labels) && ~isempty(labels) && ...
                all(cellfun(@ischar, labels)) && numel(unique(labels)) == numel(labels))) && ...
                isempty(feval(selection(scenarios), v{r, 2}));
        end
        if ~ok
            m = sprintf(['rows {conditions, scenarios}: conditions ''all'' or a list of distinct labels of ' ...
                'the condition table, scenarios ''all'' or a list of distinct names among %s (the scenarios ' ...
                'the conditional inversion is implemented for)'], ...
                strjoin(strcat('''', scenarios, ''''), ', '));
        end
    end
end

function value = first_repeat(values)
%FIRST_REPEAT The first value of a list that occurs more than once.
    for k = 1:numel(values)
        if nnz(strcmp(values, values{k})) > 1
            value = values{k};
            return;
        end
    end
    value = '';
end

