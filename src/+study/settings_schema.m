function m = feature_catalog(v)
%FEATURE_CATALOG Rows {name, family, type, weights, unit, status, hypothesis} (settings 0.7).
    m = '';
    families = {'F1_ratios', 'F2_differences', 'F3_levels', 'F4_decline_shape'};
    if ~iscell(v) || isempty(v) || size(v, 2) ~= 7
        m = 'a cell array with one row per feature: {name, family, type, weights, unit, status, hypothesis}';
        return;
    end
    six = @(w) isnumeric(w) && numel(w) == 6 && all(isfinite(w)) && any(w);
    for k = 1:size(v, 1)
        row = v(k, :);
        if ~((ischar(row{1}) || isstring(row{1})) && isvarname(char(row{1})))
            m = sprintf('row %d: a name that is a valid MATLAB name', k);
        elseif ~((ischar(row{2}) || isstring(row{2})) && ismember(char(row{2}), families))
            m = sprintf('row %d (%s): a family of %s', k, char(row{1}), strjoin(families, ', '));
        elseif ~((ischar(row{3}) || isstring(row{3})) && ismember(char(row{3}), {'loglinear', 'raw'}))
            m = sprintf('row %d (%s): the type loglinear or raw', k, char(row{1}));
        elseif strcmp(char(row{3}), 'loglinear') && ~six(row{4})
            m = sprintf('row %d (%s): weights w of six finite numbers, not all zero', k, char(row{1}));
        elseif strcmp(char(row{3}), 'raw') && ~(iscell(row{4}) && any(numel(row{4}) == [1 2]) && ...
                all(cellfun(six, row{4})))
            m = sprintf(['row %d (%s): weights {a} or {a, b}, each of six finite numbers, not all ' ...
                'zero'], k, char(row{1}));
        elseif ~(ischar(row{5}) || isstring(row{5}))
            m = sprintf('row %d (%s): the unit as text', k, char(row{1}));
        elseif ~((ischar(row{6}) || isstring(row{6})) && ismember(char(row{6}), {'core', 'exploratory'}))
            m = sprintf('row %d (%s): the status core or exploratory', k, char(row{1}));
        elseif ~((ischar(row{7}) || isstring(row{7})) && strlength(string(row{7})) > 0)
            m = sprintf('row %d (%s): the physical hypothesis as text', k, char(row{1}));
        end
        if ~isempty(m), return; end
    end
    names = cellfun(@char, v(:, 1), 'UniformOutput', false);
    if numel(unique(names)) ~= numel(names)
        m = 'distinct feature names';
    end
end

