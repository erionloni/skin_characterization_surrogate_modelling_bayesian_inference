function text = data_description(analysis, entry)
%DATA_DESCRIPTION One-line meaning of a first-level entry of an analysis's data/ folder.
%   TEXT = study.data_description(ANALYSIS, ENTRY) returns what the folder
%   ENTRY below <route>/<NN_analysis>/data holds, for ANALYSIS given as
%   '<route>/<NN_analysis>', or '' when no description is registered. The
%   analysis READMEs show it next to the folder (study.write_readme).
%   Side effects: none.
    draws = ['every retained draw of both replicates of the provider''s level, at full ' ...
        'precision, for each certified cell and healthy fallback: one file per cell, with index.csv'];
    features = ['the Sobol indices of the derived features of the feature catalog ' ...
        '(feature_indices.csv: per feature and input S1, ST, the gap, the variance and the effect ' ...
        'size; the six pressures with their variance only) and the stability of the raw quotients ' ...
        '(feature_stability.csv)'];
    accuracy = ['the surrogates'' accuracy in feature space on the external cases ' ...
        '(feature_metrics.csv: per surrogate, subset and feature; feature_errors.csv: per case, ' ...
        'feature and surrogate; relative_errors.csv, error_correlation.csv, ' ...
        'error_decomposition.csv, top_errors.csv)'];
    D = {
    'fixed/05_recovery', 'combinations', ...
        ['the parameter combinations the posteriors determine, per cell and replicate (cohort.csv, ' ...
         'cells.csv, directions.csv, marginals.csv, densities.csv: the marginal figures; consensus.csv); ' ...
         'the projected draws are not stored (the shipped draws give them again)']
    'fixed/02_surrogates', 'feature_accuracy', accuracy
    'generalized/02_surrogates', 'feature_accuracy', accuracy
    'fixed/03_sensitivity', 'features', features
    'generalized/03_sensitivity', 'features', features
    'fixed/04_inversion', 'draws', draws
    'fixed/07_conditional_inversion', 'draws', draws
    'fixed/07_conditional_inversion', 'seeds', ...
        ['the campaign''s seed record (seed_record.csv): the seed of every request of its cells, ' ...
         'recorded (the frozen record config/seeds/mcmc_seeds.csv) or by the seed rule of the settings']
    'fixed/09_gp_mean_inversion', 'draws', draws
    'fixed/09_gp_mean_inversion', 'seeds', ...
        ['the campaign''s seed record (seed_record.csv): the seed of every request of its cells, ' ...
         'by the MCMC seed rule of the settings with scenario number 4']
    'fixed/09_gp_mean_inversion', 'best_fit', ...
        ['the best fit of every case, theta* = argmin of the sum of squared residuals between the six ' ...
         'COMSOL pressures and the GP mean within the prior bounds (settings A.13; no sampler): ' ...
         'best_fit.csv (per case and parameter theta*, the truth, the error, the prior bounds, the ' ...
         'objective at theta* and at the truth, the search), residuals.csv (per case and output the ' ...
         'pressure, the GP mean at theta* and at the truth, the residuals) and local_minima.csv (per ' ...
         'case every distinct minimum the starts reached)']
    'fixed/08_ratio_error_curves', 'draws', ...
        ['per cell and replicate, in the row order of the cell''s posterior draws: the draw index, ' ...
         'walker, retained iteration and sampler step, the ratio discrepancy d, the level ' ...
         'discrepancy and the four log-ratio errors e1..e4 (full precision; the GP means are not ' ...
         'stored: the shipped draws and model give them again)']
    'generalized/06_confirmation', 'draws', draws
    'generalized/02_surrogates', 'assessment', ...
        'the assessment of the approved GP and PCE on the 82 external cases'
    'generalized/02_surrogates', 'audit', ...
        'the original 1,050-fit development audit of the generalized surrogate'
    'generalized/02_surrogates', 'models', ...
        'the resolvers of the approved GP and PCE'
    'generalized/02_surrogates', 'selection_review', ...
        ['the review that selected the approved GP for outputs 1 and 3: the candidates'' ' ...
         'objectives, the matched out-of-fold errors and the calibration cross-fit metrics']
    'generalized/02_surrogates', 'surrogates', ...
        ['the approved GP and PCE ensembles and the approved GP''s hyperparameters ' ...
         '(final_candidate_hyperparameters.csv)']
    'generalized/06_confirmation', 'design', ...
        ['what the step export_design writes: the screen''s proxy of the design''s protocols in ' ...
         'the confirmation''s observation designs (design_predictions.csv) and, in a rerun, the ' ...
         'design of the settings (materials.csv, protocols.csv, design_rows.csv) and the COMSOL ' ...
         'run list (probe_solves.csv)']
    'generalized/06_confirmation', 'observations', ...
        ['the accepted COMSOL observations of the design (confirmation_observations.csv), the QC ' ...
         'of every design row (observation_qc.csv), how the COMSOL solves ended per protocol and ' ...
         'probe (comsol_outcomes.csv) and the reviewed inputs']
    'generalized/06_confirmation', 'campaign', ...
        ['the confirmation campaign: status, certification, summaries, cell grid and seed ' ...
         'schedule, pairing, inputs, configuration and reports']
    'generalized/06_confirmation', 'combinations', ...
        ['the weak-pair combinations the confirmation''s posteriors determine, per material, ' ...
         'protocol, design and replicate (cohort.csv, cells.csv, marginals.csv, densities.csv: the ' ...
         'marginal figures; consensus.csv), and what each focused protocol changes against the ' ...
         'default (protocols.csv, protocol_summary.csv); the projected draws are not stored (the ' ...
         'draws give them again)']
    };
    hit = strcmp(D(:, 1), char(analysis)) & strcmp(D(:, 2), char(entry));
    text = '';
    if any(hit), text = D{find(hit, 1), 3}; end
end
