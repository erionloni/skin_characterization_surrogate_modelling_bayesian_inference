function check_fixed_dataset(csvFile, calibrationFile, groupColumn)
%CHECK_FIXED_DATASET Refuse a fixed dataset that does not belong to the calibration (CLN-006).
%   study.check_fixed_dataset(CSVFILE, CALIBRATIONFILE, GROUPCOLUMN) checks,
%   before any computation, that the fixed dataset CSVFILE is the dataset
%   the fixed emulator calibration CALIBRATIONFILE was estimated on (the
%   settings' fixed.dataset.file and fixed.surrogates.emulatorCalibration):
%   the calibration record lists the development and external CaseIDs of its
%   split (thesis: 391 and 61), and the CaseIDs of CSVFILE must be exactly
%   these. A mismatched dataset/calibration pair (for example the legacy
%   178-case file) fails immediately instead of after the surrogate fits.
%   The dataset must also hold its split groups in the column GROUPCOLUMN
%   (setting fixed.dataset.groupColumn; data/README.md).
%   The check uses the recorded case lists (metadata), not file hashes.
%   Side effects: none.
    assert(isfile(csvFile), 'study:FixedDatasetMissing', ...
        'Fixed dataset not found: %s', csvFile);
    calibration = jsondecode(fileread(calibrationFile));
    assert(all(isfield(calibration, {'development_case_ids', 'external_holdout_case_ids_excluded'})), ...
        'study:CalibrationWithoutDataset', ...
        'The calibration record %s does not list the cases it was estimated on.', calibrationFile);
    expected = sort([double(calibration.development_case_ids(:)); ...
        double(calibration.external_holdout_case_ids_excluded(:))]);
    T = readtable(csvFile, 'Delimiter', ',', 'TextType', 'string', 'VariableNamingRule', 'preserve');
    assert(ismember('CaseID', T.Properties.VariableNames), 'study:DatasetCalibrationMismatch', ...
        'The fixed dataset %s has no CaseID column.', csvFile);
    cases = sort(double(T.CaseID(:)));
    assert(isequal(cases, expected), 'study:DatasetCalibrationMismatch', ...
        ['The fixed dataset does not belong to the frozen emulator calibration.\n' ...
         '  dataset:     %s (%d cases)\n  calibration: %s (estimated on %d cases: %d ' ...
         'development + %d external)\nUse the 452-case dataset in data/fixed/ or a ' ...
         'calibration estimated on your dataset.'], csvFile, numel(cases), calibrationFile, ...
        numel(expected), numel(calibration.development_case_ids), ...
        numel(calibration.external_holdout_case_ids_excluded));
    assert(ismember(groupColumn, T.Properties.VariableNames), 'study:FixedDatasetGroups', ...
        ['The fixed dataset %s has no split-group column %s (setting ' ...
         'fixed.dataset.groupColumn): give cases with equal material inputs one label ' ...
         '(data/README.md).'], csvFile, groupColumn);
end
