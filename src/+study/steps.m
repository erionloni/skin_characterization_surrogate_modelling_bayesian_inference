function registry = steps(entry)
%STEPS Named steps of one route, in dependency order.
%   REGISTRY = study.steps(ENTRY) returns a struct array describing the
%   steps of the route ENTRY: 'fixed' (run_fixed_study) or 'generalized'
%   (run_generalized_study, with the protocol screening and the
%   confirmation). REGISTRY = study.steps() returns the steps of both.
%
%   Fields of each step:
%     name          step name used in 'Steps', e.g. 'sensitivity'
%     entry         route it belongs to ('fixed' or 'generalized')
%     group         part of the route: 'fixed', 'generalized', 'screening'
%                   or 'confirmation' (selects the step's folders,
%                   study.native_config)
%     fn            the step function, study.steps.<group>_<name>
%                   (study.render_run for the step 'figures' of a rerun)
%     summary       one line saying what the step does
%     requires      steps whose results it needs (same route)
%     expensive     true: needs 'ConfirmExpensive',true in rerun mode
%     readsHeldOut  true: reads the outcomes of the held-out external cases
%     cost          estimated cost of a rerun on one workstation
%     stage         number of the configuration section the step uses
%                   (study.project_config 'Stage'; 0 = none)
%     available     false for a step whose results are shipped as evidence
%                   only and which this version does not rerun
%     example       false for a step without an example version (no
%                   'Scale','example' reduction): left out of an example
%                   run's default selection
%     endToEnd      true: run_all_studies runs it (the steps a route's
%                   later results build on; not the side analyses: the
%                   surrogate audits, the generalized refit, the conditional
%                   inversion, the ratio-error curves, the parameter
%                   combinations of both routes, the feature sensitivity
%                   and accuracy, the GP-mean inversion)
%     needs         what the step needs besides a workstation: '' (nothing),
%                   'cluster' (an MCMC campaign: a computing cluster) or
%                   'decision' (a human decision: accepting the reviewed
%                   COMSOL observations); run_all_studies stops before it
%     options       further name-value arguments that a call of the step
%                   needs, as text for the commands run_all_studies prints
%     note          what else to know to run it ('' when nothing)
%
%   The costs are rough guides taken from recorded runs; they are printed
%   by the 'Plan' option.
%   Side effects: none.

    all = [fixed_steps(), generalized_steps(), screening_steps(), ...
        confirmation_steps(), figures_step('generalized')];
    if nargin < 1 || isempty(entry)
        registry = all;
        return;
    end
    entry = char(string(entry));
    registry = all(strcmp({all.entry}, entry));
    assert(~isempty(registry), 'study:steps:UnknownEntry', ...
        'Unknown route "%s". Use fixed or generalized.', entry);
end

