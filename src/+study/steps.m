function s = figures_step(entry)
    if strcmp(entry, 'fixed')
        s = step('fixed', 'fixed', 'figures', ...
            'Render the fixed-route figures and tables from the saved results.', ...
            {'recovery', 'design_study'}, false, false, 'about 10 min (9 min recorded)', 7, true);
    else
        s = step('generalized', 'generalized', 'figures', ...
            'Render the generalized-route figures and tables (screening and confirmation included) from the saved results.', ...
            {'dataset'}, false, false, 'minutes', 0, true);
    end
    s.fn = 'study.render_run';
end

function s = step(entry, group, name, summary, requires, expensive, ...
        readsHeldOut, cost, stage, available)
    s = struct('name', name, 'entry', entry, 'group', group, ...
        'fn', sprintf('study.steps.%s_%s', group, name), 'summary', summary, ...
        'requires', {requires}, ...
        'expensive', expensive, 'readsHeldOut', readsHeldOut, ...
        'cost', cost, 'stage', stage, 'available', available, 'example', true, 'endToEnd', true, ...
        'needs', '', 'options', '', 'note', '');
end

function s = needing(s, needs, options, note)
%NEEDING A step that needs a computing cluster or a human decision.
    s.needs = needs;
    s.options = options;
    s.note = note;
end
