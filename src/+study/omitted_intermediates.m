function I = omitted_intermediates(route, folder)
%OMITTED_INTERMEDIATES Full-size intermediate outputs that thesis_results/ does not ship.
%   I = study.omitted_intermediates(ROUTE, FOLDER) lists, for one analysis
%   folder (e.g. 'fixed', '05_recovery'), the full-size intermediate outputs
%   that a run of the step writes into its data/ folder but that thesis_results/
%   does not ship (size). Each element has:
%     path     location below the analysis data/ folder, with '/'
%     count    number of files (checkpoints are many files of one kind)
%     what     what the file holds
%     entry    route of the steps that write it
%     steps    the steps that regenerate it, in order; empty when this
%              version of the code does not rerun it
%   The results README of the analysis lists them with the command that
%   regenerates them and its approximate runtime (study.write_readme).
%   Later steps read them from a run folder like any output of the run
%   (study.resolve_input).
%   I = study.omitted_intermediates() lists every analysis's.
%   Side effects: none.

    all = [ ...
        audit('fixed', 'fixed', 'surrogate_audit'), ...
        audit('generalized', 'generalized', ''), ...
        fixed_items('05_recovery', { ...
            'coverage_recovery_summary.mat', 1, ...
                'coverage and recovery summaries of every cell (the tables in tables/ come from it)'; ...
            'eigen_analysis/posterior_eigendecomposition_summary.mat', 1, ...
                'the posterior covariance eigensystems of every cell and replicate pair'; ...
            'feature_reconstruction/error_budget/downstream_error_budget_long_form.csv', 1, ...
                'the downstream error budget of every case, feature and evaluation space'}, 'recovery'), ...
        fixed_items('06_design_study', { ...
            'design_study.mat', 1, 'the design-study result of every scenario together'; ...
            'scenarios/<scenario>/design_study.mat', 3, 'the design-study result of one scenario'; ...
            'scenarios/<scenario>/provider_definition.mat', 3, ...
                'the posterior provider of one scenario (cells, draws in unit coordinates)'}, 'design_study'), ...
        item('generalized', '05_protocol_screening', ...
            'screen/local_information/local_information.mat', 1, ...
            'the local Fisher information of 730 protocols at 1,000 material points', ...
            'generalized', 'screen'), ...
        item('generalized', '05_protocol_screening', ...
            'six_objective/full_covariance_supplement.mat', 1, ...
            'the full posterior covariances of the six-objective supplement', ...
            'generalized', {'screen', 'objective_supplement'}), ...
        item('generalized', '05_protocol_screening', ...
            'six_objective/checkpoints/block_<first protocol>.mat', 146, ...
            'the supplement''s checkpoints, five protocols each', ...
            'generalized', {'screen', 'objective_supplement'})];
    if nargin < 2
        I = all;
    else
        I = all(strcmp({all.route}, route) & strcmp({all.folder}, folder));
    end
end

function I = audit(route, entry, step)
%AUDIT The per-row tables and the result record of the surrogate audit.
    rows = { ...
        'surrogate_quality_audit_result.mat', 'the complete audit record'; ...
        'calibration_crossfit/variance_calibration_crossfit_predictions.csv', ...
            'the cross-fitted predictions of the variance calibration'; ...
        'kernel_cross_validation/kernel_cv_folds.csv', 'the cross-validation folds'; ...
        'kernel_cross_validation/kernel_cv_predictions.csv', 'the cross-validated predictions'; ...
        'oof_residuals/development_oof_residuals.csv', 'the out-of-fold residuals'; ...
        'residual_distribution/pit_data.csv', ...
            'the PIT values (shipped as the compressed MAT next to it)'; ...
        'residual_distribution/qq_data.csv', ...
            'the Q-Q values (shipped as the compressed MAT next to it)'; ...
        'same_data_seed_stability/same_data_probe_predictions.csv', ...
            'the probe predictions of the seed-stability check'; ...
        'training_convergence/training_convergence_membership.csv', ...
            'the training subsets of the convergence study'; ...
        'training_convergence/training_convergence_roles.csv', 'the roles of those subsets'; ...
        'variance_semantics/variance_factorization_check.csv', 'the variance factorization check'};
    I = struct('route', {}, 'folder', {}, 'path', {}, 'count', {}, 'what', {}, 'entry', {}, 'steps', {});
    for r = 1:size(rows, 1)
        I(end+1) = item(route, '02_surrogates', ['audit/' rows{r, 1}], 1, rows{r, 2}, entry, step); %#ok<AGROW>
    end
end

function I = fixed_items(folder, rows, step)
%FIXED_ITEMS One item per file of a fixed-route analysis that the step STEP writes.
    I = struct('route', {}, 'folder', {}, 'path', {}, 'count', {}, 'what', {}, 'entry', {}, 'steps', {});
    for r = 1:size(rows, 1)
        I(end+1) = item('fixed', folder, rows{r, 1}, rows{r, 2}, rows{r, 3}, 'fixed', step); %#ok<AGROW>
    end
end

function s = item(route, folder, pathValue, count, what, entry, steps)
    if ischar(steps), steps = {steps}; end
    steps = steps(~cellfun(@isempty, steps));
    s = struct('route', route, 'folder', folder, 'path', pathValue, 'count', count, ...
        'what', what, 'entry', entry, 'steps', {steps});
end
