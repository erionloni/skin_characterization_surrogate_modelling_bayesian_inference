function D = fixed_data_contract(cfg,P,varargin)
%FIXED_DATA_CONTRACT The fixed route's case contract from its model-ready CSV.
%   D = data.fixed_data_contract(CFG, P) reads the fixed CSV
%   (CFG.realData.csv; D = data.fixed_data_contract(CFG, P, T) takes it read
%   as the table T), maps its input columns to the model coordinates of the
%   parameter space P (log10 permeability) and builds the contract of
%   data.final_data_contract: source rows are grouped by exact material
%   vector, complementary finite outputs are merged only when duplicates
%   agree, complete cases alone are eligible for the external test, partial
%   cases are development only, and the split keeps each split group (the
%   CSV's column CFG.realData.groupCol, setting fixed.dataset.groupColumn;
%   thesis: the frozen labels of data/README.md) on one side. Non-positive
%   or non-finite pressures are missing (NaN).
%   D: the development and external inputs, outputs and CaseIDs (X_train,
%   Y_train, X_validation, Y_validation, ...), their output availability,
%   the per-output training evidence, the split manifest, the excluded
%   cases and the counts.
%   Side effects: none.

    assert(strcmp(cfg.dataMode,'real'),'data:fixed_data_contract:Route', ...
        ['This function works on the fixed route (study.project_config(S,''Route'',''real'')); ' ...
         'the configuration is for route ''%s''.'],cfg.dataMode);
    if isempty(varargin)
        T=readtable(cfg.realData.csv,'Delimiter',',','TreatAsMissing', ...
            {'-','NA','N/A','nan','NaN'});
    else
        T=varargin{1};
        assert(istable(T)&&isscalar(varargin), ...
            'data:fixed_data_contract:SourceTable', ...
            'The optional source argument must be one table: the fixed-route CSV, read.');
    end
    required=[{'CaseID'} cfg.realData.inputCols cfg.realData.outputCols {cfg.realData.groupCol}];
    missing=setdiff(required,T.Properties.VariableNames,'stable');
    assert(isempty(missing),'data:fixed_data_contract:Columns', ...
        'The fixed dataset lacks the columns %s (settings A.1).',strjoin(missing,', '));
    Xraw=numeric_matrix(T,cfg.realData.inputCols);
    Y=numeric_matrix(T,cfg.realData.outputCols);
    Y(~isfinite(Y)|Y<=0)=NaN;
    caseIDs=numeric_matrix(T,{'CaseID'});
    sourceRows=(1:height(T)).';
    X=Xraw;
    if cfg.realData.k0Col>0
        c=cfg.realData.k0Col;
        valid=isfinite(X(:,c))&X(:,c)>0;
        X(~valid,c)=NaN;X(valid,c)=log10(X(valid,c));
    end
    bounds=double(P.bounds);
    within=all(X>=bounds(:,1).'&X<=bounds(:,2).',2);
    X(~within,:)=NaN;
    % The cases the split keeps external when they are complete (settings
    % A.1: the inversion truths, then the other external cases of the
    % earlier 178-case split).
    preferred=reshape(double(cfg.realData.preferredExternalCaseIDs),1,[]);
    contract=data.final_data_contract(caseIDs,sourceRows,X,Y, ...
        'InputNames',P.names,'OutputNames',P.outputNames, ...
        'SplitSeed',cfg.realData.splitSeed, ...
        'TestFraction',cfg.realData.validationFraction, ...
        'SplitAlgorithmVersion',cfg.realData.splitAlgorithmVersion, ...
        'RequiredExternalCaseIDs',[], ...
        'PreferredExternalCaseIDs',preferred, ...
        'SplitGroupIdentities',string(T.(cfg.realData.groupCol)));

    manifest=contract.caseManifest;
    legacyRole=repmat("train",height(manifest),1);
    legacyRole(manifest.MethodologicalRole=="external_test")="validation";
    realizedAnchor=manifest.MethodologicalRole=="external_test"& ...
        ismember(double(manifest.CaseID),double( ...
            cfg.inversion.defaultAnchorCaseIDs));
    splitManifest=table(double(manifest.CaseID),double(manifest.SourceRow), ...
        legacyRole,manifest.MethodologicalRole, ...
        realizedAnchor,string(manifest.Classification), ...
        string(manifest.AvailabilityPattern), ...
        string(manifest.DuplicateGroup),string(manifest.SplitGroup), ...
        string(manifest.SourceRows), ...
        string(manifest.CaseIDAliases),double(manifest.DuplicateSourceCount), ...
        double(manifest.SplitSeed),string(manifest.SplitAlgorithmVersion), ...
        'VariableNames',{'CaseID','SourceRow','Role','MethodologicalRole', ...
        'CanonicalInversionCase','Classification','AvailabilityPattern', ...
        'DuplicateGroup','SplitGroup','SourceRows','CaseIDAliases', ...
        'DuplicateSourceCount','SplitSeed','SplitAlgorithmVersion'});

    tr=contract.developmentIndices;te=contract.externalTestIndices;
    D=struct( ...
        'schemaVersion','routeR_fixed_dataset_v3_partial_output', ...
        'X_train',contract.X_all(tr,:), ...
        'Y_train',contract.Y_all(tr,:), ...
        'X_validation',contract.X_all(te,:), ...
        'Y_validation',contract.Y_all(te,:), ...
        'inputNames',{P.names},'outputNames',{P.outputNames}, ...
        'inputBounds',P.bounds, ...
        'trainIndices',tr,'validationIndices',te, ...
        'trainSourceRows',double(manifest.SourceRow(tr)), ...
        'validationSourceRows',double(manifest.SourceRow(te)), ...
        'trainCaseIDs',contract.developmentCaseIDs, ...
        'validationCaseIDs',contract.externalTestCaseIDs, ...
        'developmentCaseIDs',contract.developmentCaseIDs, ...
        'externalTestCaseIDs',contract.externalTestCaseIDs, ...
        'completeCaseIDs',contract.completeCaseIDs, ...
        'partialCaseIDs',contract.partialCaseIDs, ...
        'outputAvailabilityMask',contract.outputAvailabilityMask, ...
        'developmentOutputAvailability', ...
            contract.outputAvailabilityMask(tr,:), ...
        'externalOutputAvailability',contract.outputAvailabilityMask(te,:), ...
        'outputTrainingEvidence',{contract.perOutput}, ...
        'availabilityPatterns',contract.availabilityPatterns, ...
        'splitManifest',splitManifest, ...
        'excludedCaseManifest',contract.excludedManifest, ...
        'sourceMap',contract.sourceMap, ...
        'counts',contract.counts, ...
        'rawRowCount',height(T),'usableRowCount',contract.counts.usableCases, ...
        'usableOriginalRows',double(manifest.SourceRow), ...
        'splitSeed',contract.splitSeed, ...
        'splitAlgorithmVersion',contract.splitAlgorithmVersion);
    % Every output has enough development observations for its GP and PCE.
    surrogates.output_training_contract(D,cfg);
end

function X=numeric_matrix(T,names)
    X=nan(height(T),numel(names));
    for j=1:numel(names)
        value=T.(names{j});
        if isnumeric(value)||islogical(value)
            X(:,j)=double(value);
        else
            text=strtrim(string(value));
            text(ismissing(text)|text==""|text=="-"| ...
                strcmpi(text,"NA")|strcmpi(text,"N/A"))="NaN";
            X(:,j)=str2double(text);
        end
    end
end
