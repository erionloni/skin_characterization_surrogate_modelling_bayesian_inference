function cases = inversion_cases(cfg,P)
%INVERSION_CASES The fixed route's inversion cases: truths and held-out observations.
%   CASES = data.inversion_cases(CFG, P) returns, in the configured order
%   (CFG.inversion.caseIDs, resolved by data.resolve_inversion_cohort from
%   the run's dataset), one record per inversion case of the external test
%   split: case_id, validation_index, source_row, truth (1-by-4, model
%   coordinates of P) and heldout_response (1-by-6 closing pressures, mbar),
%   and the same fields in camel case.
%   It checks that the configured cases are the realized cohort and that
%   the emulator-error calibration fits the dataset.
%   Side effects: none.
    assert(strcmp(cfg.dataMode,'real'),'data:inversion_cases:Route', ...
        ['This function works on the fixed route (study.project_config(S,''Route'',''real'')); ' ...
         'the configuration is for route ''%s''.'],cfg.dataMode);
    d=utils.load_plain_mat(cfg.files.dataset,'X_train','Y_train','trainCaseIDs', ...
        'X_validation','Y_validation','validationCaseIDs', ...
        'validationSourceRows','inputNames','outputNames');
    assert(isfield(cfg.inversion,'cohortResolved')&& ...
        logical(cfg.inversion.cohortResolved), ...
        'data:inversion_cases:UnresolvedCohort', ...
        ['The inversion cases are not resolved: build the configuration with the ' ...
         'realized dataset (study.project_config ''DatasetFile'') first.']);
    realized=data.resolve_inversion_cohort(cfg);
    assert(isequal(reshape(double(cfg.inversion.caseIDs),1,[]), ...
            reshape(double(realized.caseIDs),1,[])), ...
        'data:inversion_cases:Cohort', ...
        'The configured inversion cases differ from the cohort of the realized dataset.');
    surrogates.validate_calibration_data_contract( ...
        cfg.emulatorErrorCalibration,d,P.outputNames);
    requested=double(cfg.inversion.caseIDs(:).');
    assert(~isempty(requested)&&all(isfinite(requested))&& ...
        all(requested==fix(requested))&&numel(unique(requested))==numel(requested), ...
        'data:inversion_cases:ConfiguredCases', ...
        'Configured inversion CaseIDs must be a nonempty ordered unique list.');
    available=double(d.validationCaseIDs(:).');
    index=zeros(size(requested));
    for i=1:numel(requested)
        hit=find(available==requested(i));
        assert(isscalar(hit),'data:inversion_cases:CasePolicy', ...
            'Case %d is not uniquely present in the frozen test split.',requested(i));
        index(i)=hit;
    end
    template=struct('case_id',NaN,'validation_index',NaN, ...
        'source_row',NaN,'truth',zeros(1,P.M), ...
        'heldout_response',zeros(1,6), ...
        'caseID',NaN,'validationIndex',NaN,'sourceRow',NaN, ...
        'heldoutResponse',zeros(1,6));
    cases=repmat(template,1,numel(index));
    for i=1:numel(index)
        truth=d.X_validation(index(i),:);observation=d.Y_validation(index(i),:);
        record=struct('case_id',requested(i), ...
            'validation_index',index(i), ...
            'source_row',double(d.validationSourceRows(index(i))), ...
            'truth',truth,'heldout_response',observation);
        % Camel-case aliases of the snake-case fields, for the readers that
        % use them.
        record.caseID=record.case_id;
        record.validationIndex=record.validation_index;
        record.sourceRow=record.source_row;
        record.heldoutResponse=record.heldout_response;
        cases(i)=record;
    end
end
