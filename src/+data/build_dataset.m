function result = build_dataset(cfg)
%BUILD_DATASET Build the analysis dataset of one route, with its split.
%   RESULT = data.build_dataset(CFG) builds, with the seed CFG.seed:
%     fixed route (CFG.dataMode 'real'): the dataset of the CSV
%       CFG.realData.csv (setting fixed.dataset.file;
%       data.prepare_fixed_dataset): complete/partial/unusable
%       classification, the constrained development/external split and the
%       per-output training support. It writes CFG.files.dataset and, below
%       CFG.paths.datasetMetadata, dataset_audit.json, split_manifest.csv,
%       the development/external role manifest, the output availability
%       patterns, the per-output development support and the output
%       training-cohort overlap (and the excluded unusable cases, if any).
%     generalized route ('real_extended'): the dataset of the table
%       CFG.realExtended.csv (setting generalized.dataset.file;
%       data.build_generalized_dataset) with its split, registries and audit.
%   RESULT counts the cases of the split and names the dataset. The fixed
%   route's figures are drawn by the renderers; the generalized build also
%   draws the dataset figures.
%   The body of the pre-publication script
%   (s01_generate_dataset), moved unchanged.
%   Computation: about 30 s (fixed) or 1-1.5 min (generalized).
%   Side effects: writes the dataset and its metadata tables (above) and,
%   on the generalized route, the dataset figures.
    ensure_dirs({fileparts(cfg.files.dataset),cfg.paths.datasetMetadata});
    state=rng;restore=onCleanup(@()rng(state));
    rng(cfg.seed,'twister');
    if strcmp(cfg.dataMode,'real_extended')
        % The extended builder retains its audited nine-file reconstruction;
        % paths are rebound to this stage's readable run namespace.
        cfg.paths.results=cfg.paths.stage01;
        cfg.paths.reports=fullfile(cfg.paths.stage01,'metadata');
        stage1=data.build_generalized_dataset(cfg);
        result=struct('route','real_extended','dataset',cfg.files.dataset, ...
            'complete_case_count',stage1.complete_case_count, ...
            'partial_case_count',stage1.partial_development_count, ...
            'train_count',stage1.train_count, ...
            'validation_count',stage1.test_count, ...
            'per_output_training_counts', ...
                stage1.per_output_training_counts, ...
            'methodological_role_manifest', ...
                cfg.files.methodologicalRoleManifest, ...
            'adopted',logical(stage1.dataset_adopted), ...
            'source_snapshot',cfg.realExtended.snapshotID);
        return;
    end

    P=parameters.parameter_space(cfg);
    [dataset,audit,adopted]=data.prepare_fixed_dataset(cfg,P);
    metadataPath=fullfile(cfg.paths.datasetMetadata,'dataset_audit.json');
    utils.atomic_write_json(metadataPath,audit,'AllowReplace',cfg.resume);
    splitPath=fullfile(cfg.paths.datasetMetadata,'split_manifest.csv');
    utils.atomic_write_table(splitPath,dataset.splitManifest);
    roleManifest=methodological_role_manifest(dataset.splitManifest);
    rolePath=cfg.files.methodologicalRoleManifest;
    utils.atomic_write_table(rolePath,roleManifest);
    utils.atomic_write_table(fullfile(cfg.paths.datasetMetadata, ...
        'output_availability_patterns.csv'),dataset.availabilityPatterns);
    support=output_support_table(dataset,cfg);
    utils.atomic_write_table(fullfile(cfg.paths.datasetMetadata, ...
        'per_output_development_support.csv'),support);
    utils.atomic_write_table(fullfile(cfg.paths.datasetMetadata, ...
        'output_training_cohort_overlap.csv'),output_overlap_table(dataset,cfg));
    if ~isempty(dataset.excludedCaseManifest)
        utils.atomic_write_table(fullfile(cfg.paths.datasetMetadata, ...
            'excluded_unusable_cases.csv'),dataset.excludedCaseManifest);
    end
    result=struct('route','real','dataset',cfg.files.dataset, ...
        'complete_case_count',dataset.counts.completeCases, ...
        'partial_case_count',dataset.counts.partialCases, ...
        'unusable_case_count',dataset.counts.unusableCases, ...
        'train_count',size(dataset.X_train,1), ...
        'validation_count',size(dataset.X_validation,1), ...
        'per_output_training_counts', ...
            dataset.counts.perOutputObservedDevelopment, ...
        'default_inversion_anchor_count', ...
            nnz(dataset.splitManifest.CanonicalInversionCase), ...
        'split_manifest',splitPath, ...
        'methodological_role_manifest',rolePath, ...
        'adopted',logical(adopted));
    fprintf(['[dataset] fixed dataset: %d development (%d partial) + ' ...
        '%d complete external test; %d canonical anchors retained external.\n'], ...
        result.train_count,result.partial_case_count, ...
        result.validation_count,result.default_inversion_anchor_count);
end

function T=methodological_role_manifest(legacy)
    assert(istable(legacy)&&all(ismember( ...
        {'CaseID','SourceRow','Role','CanonicalInversionCase', ...
        'SplitSeed','SplitAlgorithmVersion'},legacy.Properties.VariableNames)), ...
        'data:build_dataset:SplitManifestSchema');
    SplitRole=string(legacy.Role);
    if ismember('MethodologicalRole',legacy.Properties.VariableNames)
        MethodologicalRole=string(legacy.MethodologicalRole);
    else
        MethodologicalRole=repmat("development",height(legacy),1);
        MethodologicalRole(SplitRole=="validation")="external_test";
    end
    assert(all(ismember(SplitRole,["train" "validation"]))&& ...
        all(ismember(MethodologicalRole,["development" "external_test"]))&& ...
        all(MethodologicalRole(SplitRole=="train")=="development")&& ...
        all(MethodologicalRole(SplitRole=="validation")=="external_test")&& ...
        all(MethodologicalRole(logical(legacy.CanonicalInversionCase))== ...
            "external_test"), ...
        'data:build_dataset:MethodologicalRoles', ...
        'The methodological roles violate the complete/partial split contract.');
    T=table(double(legacy.CaseID),double(legacy.SourceRow),SplitRole, ...
        MethodologicalRole,logical(legacy.CanonicalInversionCase), ...
        double(legacy.SplitSeed),string(legacy.SplitAlgorithmVersion), ...
        'VariableNames',{'CaseID','SourceRow','SplitRole', ...
        'MethodologicalRole','CanonicalInversionCase','SplitSeed', ...
        'SplitAlgorithmVersion'});
end

function T=output_support_table(dataset,cfg)
    evidence=dataset.outputTrainingEvidence;
    n=numel(evidence);OutputIndex=(1:n).';Output=string(cfg.outputNames(:));
    ValidDevelopmentCount=reshape([evidence.trainingCount],[],1);
    CompleteContributorCount=reshape([evidence.completeContributorCount],[],1);
    PartialContributorCount=reshape([evidence.partialContributorCount],[],1);
    MissingDevelopmentCount=reshape([evidence.unavailableDevelopmentCount],[],1);
    TrainingCaseIDs=strings(n,1);
    for j=1:n
        TrainingCaseIDs(j)=strjoin(string(evidence(j).trainingCaseIDs.'),';');
    end
    T=table(OutputIndex,Output,ValidDevelopmentCount, ...
        CompleteContributorCount,PartialContributorCount, ...
        MissingDevelopmentCount,TrainingCaseIDs);
    for k=1:numel(cfg.paramNames)
        label=matlab.lang.makeValidName(cfg.paramNames{k});
        T.(['ObservedMin_' label])=arrayfun( ...
            @(j)evidence(j).inputSupportMinMax(k,1),(1:n).');
        T.(['ObservedMax_' label])=arrayfun( ...
            @(j)evidence(j).inputSupportMinMax(k,2),(1:n).');
    end
end

function T=output_overlap_table(dataset,cfg)
    evidence=dataset.outputTrainingEvidence;n=numel(evidence);
    rows=n*n;Output1Index=zeros(rows,1);Output2Index=zeros(rows,1);
    Output1=strings(rows,1);Output2=strings(rows,1);
    ObservedOverlapCount=zeros(rows,1);Output1Count=zeros(rows,1);
    Output2Count=zeros(rows,1);row=0;
    for first=1:n
        ids1=double(evidence(first).trainingCaseIDs(:));
        for second=1:n
            row=row+1;
            ids2=double(evidence(second).trainingCaseIDs(:));
            Output1Index(row)=first;Output2Index(row)=second;
            Output1(row)=string(cfg.outputNames{first});
            Output2(row)=string(cfg.outputNames{second});
            ObservedOverlapCount(row)=numel(intersect(ids1,ids2));
            Output1Count(row)=numel(ids1);Output2Count(row)=numel(ids2);
        end
    end
    T=table(Output1Index,Output2Index,Output1,Output2, ...
        ObservedOverlapCount,Output1Count,Output2Count);
end

function ensure_dirs(paths)
    for i=1:numel(paths),if ~isfolder(paths{i}),mkdir(paths{i});end,end
end
