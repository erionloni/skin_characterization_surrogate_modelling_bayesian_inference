function value=relative_to_root(pathValue,root)
    pathText=utils.absolute_path(pathValue);
    rootText=utils.absolute_path(root);
    prefix=[rootText filesep];
    if ispc
        contained=strcmpi(pathText,rootText)|| ...
            startsWith(lower(pathText),lower(prefix));
    else
        contained=strcmp(pathText,rootText)||startsWith(pathText,prefix);
    end
    assert(contained,'data:build_generalized_dataset:PathOutsideRun', ...
        'A path of the dataset build lies outside the run folder: %s',pathText);
    if strcmpi(pathText,rootText)
        value="";
    else
        value=string(pathText(numel(prefix)+1:end));
    end
    value=replace(value,"\","/");
end
