function result = build_generalized_dataset(cfg)
%BUILD_GENERALIZED_DATASET Build the generalized dataset from its dataset table.
%   RESULT = data.build_generalized_dataset(CFG) reads the dataset table
%   CFG.realExtended.csv (setting generalized.dataset.file: one row per
%   designed case with its requested inputs, the outcomes of its D2 and D6
%   runs and its closing pressures; data/README.md), reconstructs the probe
%   and case registries, applies the quality control (strict cycle
%   monotonicity), decides the
%   primary cohort, classifies complete, partial and unusable cases, draws
%   the complete-case development / external split by material group and
%   assembles the per-output training evidence (data.reconstruct_generalized_tables).
%   It writes the registries, processed and exclusion tables, the split,
%   the support and feasibility tables, the cohort decision and the gate
%   of the refit (metadata/surrogates_gate.json), the core contract
%   and the dataset CFG.files.dataset (dataset.mat).
%   An existing dataset at that path is kept when it equals the rebuilt one,
%   and refused otherwise.
%   RESULT summarizes the counts and names the dataset.
%   Computation: about 1-1.5 min.
%   Side effects: writes the files above and the dataset figures
%   (plotting.saved_generalized_dataset_figures) below the run's dataset
%   folders.

    assert(~cfg.realExtended.packageBound, ...
        'data:build_generalized_dataset:ApprovedPackageBound', ...
        ['The dataset is built from the dataset table: call the build without ' ...
         'binding the approved package.']);

    assert(strcmp(cfg.dataMode,'real_extended'), ...
        'data:build_generalized_dataset:WrongRoute', ...
        'The generalized dataset needs the generalized route (cfg.dataMode=''real_extended'').');
    started = datetime('now','TimeZone','UTC');
    T = read_dataset(cfg.realExtended.csv);
    [~,name,extension] = fileparts(cfg.realExtended.csv);
    source = [name extension];
    roots = make_roots(cfg);
    R = data.reconstruct_generalized_tables(T,cfg);
    check_output_training(R.finalDataContract,cfg);

    paths = struct();
    paths.probeRegistry = fullfile(roots.registries, ...
        'probe_registry.csv');
    paths.caseRegistry = fullfile(roots.registries, ...
        'case_registry.csv');
    paths.pairedClassified = fullfile(roots.processed, ...
        "paired_classified.csv");
    paths.completeAll = fullfile(roots.processed, ...
        "complete_cases.csv");
    paths.qc = fullfile(roots.processed, ...
        "cycle_pressure_drop_qc.csv");
    paths.monotonic = fullfile(roots.processed, ...
        "monotonic_cases.csv");
    paths.exclusions = fullfile(roots.exclusions, ...
        "monotonic_exclusions.csv");
    paths.decision = fullfile(roots.processed, ...
        "cohort_decision.json");
    paths.split = fullfile(roots.splits, ...
        'split_registry.csv');
    paths.selected = fullfile(roots.processed, ...
        "selected_cases.csv");
    % This is the one data contract that the surrogates and the sensitivity read.
    % Do not publish a historical alias beside it: cfg.files.dataset is the
    % readable, run-local path advertised by study.project_config.
    paths.dataset = cfg.files.dataset;
    paths.support = fullfile(roots.feasibility, ...
        "support_registry.csv");
    paths.countAudit = fullfile(roots.datasetResults, ...
        "filter_counts.csv");
    paths.finalCaseManifest = fullfile(roots.processed, ...
        "final_case_manifest.csv");
    paths.finalExcludedManifest = fullfile(roots.exclusions, ...
        "unusable_cases.csv");
    paths.finalSourceMap = fullfile(roots.processed, ...
        "source_map.csv");
    paths.availabilityPatterns = fullfile(roots.datasetResults, ...
        "output_availability_patterns.csv");
    paths.outputTrainingEvidence = fullfile(roots.datasetResults, ...
        "output_training_evidence.csv");
    paths.outputTrainingOverlap = fullfile(roots.datasetResults, ...
        "output_training_cohort_overlap.csv");
    paths.completionEffects = fullfile(roots.feasibility, ...
        'completion_input_effect_sizes.csv');
    paths.completionBins = fullfile(roots.feasibility, ...
        'completion_input_bins_recorded_cases.csv');
    paths.missingnessEffects = fullfile(roots.feasibility, ...
        'missingness_input_effect_sizes_all_cases.csv');
    paths.missingnessBins = fullfile(roots.feasibility, ...
        'missingness_input_bins_all_cases.csv');

    utils.atomic_write_table(paths.probeRegistry,R.probeRegistry);
    utils.atomic_write_table(paths.caseRegistry,R.caseRegistry);
    utils.atomic_write_table(paths.pairedClassified,R.pairedClassified);
    utils.atomic_write_table(paths.completeAll,R.completeAll);
    utils.atomic_write_table(paths.qc,R.qc);
    utils.atomic_write_table(paths.monotonic,R.monotonic);
    utils.atomic_write_table(paths.exclusions,R.exclusions);
    utils.atomic_write_table(paths.split,R.split);
    utils.atomic_write_table(paths.support,R.support);
    utils.atomic_write_table(paths.countAudit,R.countAudit);
    utils.atomic_write_table(paths.finalCaseManifest, ...
        R.finalDataContract.caseManifest);
    utils.atomic_write_table(paths.finalExcludedManifest, ...
        R.finalDataContract.excludedManifest);
    utils.atomic_write_table(paths.finalSourceMap,R.finalDataContract.sourceMap);
    utils.atomic_write_table(paths.availabilityPatterns, ...
        R.finalDataContract.availabilityPatterns);
    utils.atomic_write_table(paths.outputTrainingEvidence, ...
        output_training_evidence_table(R.finalDataContract.perOutput, ...
            cfg.realExtended.learningInputNames));
    utils.atomic_write_table(paths.outputTrainingOverlap, ...
        output_overlap_table(R.finalDataContract.perOutput, ...
            cfg.realExtended.outputNames));
    if ~isempty(R.selected), utils.atomic_write_table(paths.selected,R.selected); end
    utils.atomic_write_json(paths.decision,R.decision,'AllowReplace',true);

    schema = schema_mapping();
    schemaPath = fullfile(roots.stage1Reports,'schema_mapping.csv');
    utils.atomic_write_table(schemaPath,schema);
    [completionEffects,completionBins,missingnessEffects,missingnessBins] = ...
        sensitivity.feasibility_sensitivity( ...
        R.caseRegistry,cfg.realExtended.learningInputNames);
    utils.atomic_write_table(paths.completionEffects,completionEffects);
    utils.atomic_write_table(paths.completionBins,completionBins);
    utils.atomic_write_table(paths.missingnessEffects,missingnessEffects);
    utils.atomic_write_table(paths.missingnessBins,missingnessBins);
    selectionEffect = selection_effect_table(R.decisionEvidence);
    selectionEffectPath = fullfile(roots.feasibility, ...
        'monotonic_selection_effect_sizes.csv');
    utils.atomic_write_table(selectionEffectPath,selectionEffect);
    statusCounts = group_count(R.probeRegistry.classification,'probe_classification');
    utils.atomic_write_table(fullfile(roots.feasibility,'probe_classification_counts.csv'), ...
        statusCounts);
    pairCounts = group_count(R.caseRegistry.pair_status,'pair_status');
    utils.atomic_write_table(fullfile(roots.feasibility,'pair_status_counts.csv'),pairCounts);
    supportCounts = group_count(R.support.support_class,'support_class');
    utils.atomic_write_table(fullfile(roots.feasibility,'support_class_counts.csv'),supportCounts);

    gate = stage1_gate(R,paths,cfg,source);
    gatePath = fullfile(roots.stage1Reports,'surrogates_gate.json');
    utils.atomic_write_json(gatePath,gate,'AllowReplace',true);
    write_reports(R,gate,paths,roots,cfg,source);

    datasetAdopted=false;
    if ~strcmp(R.decision.decision,'ambiguous_requires_review')
        arrays=dataset_arrays(R.finalDataContract);
        X_train=arrays.XCompleteDevelopment;
        Y_train=arrays.YCompleteDevelopment;
        X_test=arrays.XExternalTest;
        Y_test=arrays.YExternalTest;
        trainIndices=arrays.completeDevelopmentIndices;
        testIndices=arrays.externalTestIndices;
        trainCaseIDs=arrays.completeDevelopmentCaseIDs;
        testCaseIDs=arrays.externalTestCaseIDs;
        inputNames=cfg.realExtended.learningInputNames;
        outputNames=cfg.realExtended.outputNames;
        inputBounds=cfg.realExtended.learningBounds;
        selectedCohort=R.selected;
        splitRegistry=R.split;
        supportRegistry=R.support;
        roleManifest=methodological_role_manifest( ...
            R.finalDataContract.caseManifest,cfg);
        inputSchema=input_schema(cfg,R.finalDataContract.caseManifest);
        outputSchema=output_schema(cfg);
        outputTrainingEvidence=R.finalDataContract.perOutput;
        missingProbeRunIDs=sum(R.probeRegistry.missing_flag);
        dataProvenance=struct( ...
            'route','real_extended', ...
            'snapshot_id',cfg.realExtended.snapshotID, ...
            'requested_input_source',source, ...
            'protocol_realization_verification', ...
                'unavailable_from_selected_snapshot', ...
            'cohort_decision',R.decision.decision, ...
            'missing_probe_runids',missingProbeRunIDs, ...
            'partial_outputs_used_for_scalar_training',true, ...
            'external_test_complete_only',true, ...
            'output_imputation_used',false, ...
            'posterior_certification','not_applicable', ...
            'claim_scope','configured_dataset_and_feasibility_audit');
        datasetPayload=struct( ...
            'X_train',X_train,'Y_train',Y_train, ...
            'X_test',X_test,'Y_test',Y_test, ...
            'inputNames',{inputNames},'outputNames',{outputNames}, ...
            'inputBounds',inputBounds,'trainIndices',trainIndices, ...
            'testIndices',testIndices,'trainCaseIDs',trainCaseIDs, ...
            'testCaseIDs',testCaseIDs,'selectedCohort',selectedCohort, ...
            'splitRegistry',splitRegistry, ...
            'supportRegistry',supportRegistry, ...
            'roleManifest',roleManifest, ...
            'inputSchema',inputSchema,'outputSchema',outputSchema, ...
            'X_validation',X_test,'Y_validation',Y_test, ...
            'validationCaseIDs',testCaseIDs, ...
            'developmentCaseIDs',trainCaseIDs, ...
            'X_development_all',arrays.XDevelopmentAll, ...
            'Y_development_all',arrays.YDevelopmentAll, ...
            'developmentCaseIDsAll',arrays.developmentCaseIDs, ...
            'developmentMaterialGroupIdentities', ...
                arrays.developmentMaterialGroupIdentities, ...
            'developmentSplitGroupIdentities', ...
                arrays.developmentSplitGroupIdentities, ...
            'developmentOutputAvailabilityMask', ...
                arrays.developmentOutputAvailabilityMask, ...
            'outputTrainingEvidence',{outputTrainingEvidence}, ...
            'completeDevelopmentCaseIDs',trainCaseIDs, ...
            'externalTestCaseIDs',testCaseIDs, ...
            'noOutputImputation',true, ...
            'dataProvenance',dataProvenance);
        datasetAdopted=publish_or_adopt_dataset(paths.dataset,datasetPayload);
        latest=struct('schema_version','real_extended_dataset_resolver_v4', ...
            'dataset_path',relative_to_root(paths.dataset,cfg.paths.runRoot), ...
            'cohort_decision',R.decision.decision);
        utils.atomic_write_json(fullfile(roots.data,'dataset_latest.json'), ...
            latest,'AllowReplace',true);
        publish_core_contract(roleManifest,inputSchema,outputSchema,R, ...
            paths,cfg,source);
    end

    elapsed=seconds(datetime('now','TimeZone','UTC')-started);
    result=struct('schema_version','real_extended_stage1_result_v4', ...
        'status',gate.status,'gate',gate, ...
        'paths',relative_struct(paths,cfg.paths.runRoot), ...
        'dataset_path',relative_to_root(paths.dataset,cfg.paths.runRoot), ...
        'dataset_adopted',datasetAdopted, ...
        'qc_selected_complete_count',height(R.selected), ...
        'complete_case_count',R.finalDataContract.counts.completeCases, ...
        'train_count',R.finalDataContract.counts.developmentCases, ...
        'test_count',R.finalDataContract.counts.externalTestCases, ...
        'complete_development_count', ...
            R.finalDataContract.counts.completeDevelopmentCases, ...
        'all_development_count',R.finalDataContract.counts.developmentCases, ...
        'partial_development_count', ...
            R.finalDataContract.counts.partialDevelopmentCases, ...
        'per_output_training_counts', ...
            R.finalDataContract.counts.perOutputObservedDevelopment, ...
        'elapsed_seconds',elapsed, ...
        'environment',utils.environment_line());
    utils.atomic_write_json(fullfile(roots.stage1Reports,'dataset_result.json'), ...
        result,'AllowReplace',true);
end

function T=read_dataset(file)
%READ_DATASET The generalized dataset table (data/README.md), with its columns and CaseIDs checked.
    assert(isfile(file),'data:build_generalized_dataset:MissingDataset', ...
        'The generalized dataset is missing: %s (setting generalized.dataset.file).',file);
    T=readtable(file,'Delimiter',',','VariableNamingRule','preserve','TextType','string');
    required={'CaseID','m3_f_RD_source','m3_f_RD','m3_e_RD','k0_RD','log10_k0_RD', ...
        'Thickness_RD','suction_rate_kPa_s','log10_abs_suction_rate','hold_dur_s', ...
        'pause_dur_s','pair_status'};
    for probe={'D2','D6'}
        required=[required,strcat(probe{1},{'_available','_classification', ...
            '_phase_reached','_production_complete'}), ...
            arrayfun(@(c) sprintf('pcl%d_%s_mbar',c,probe{1}),1:3,'UniformOutput',false)]; %#ok<AGROW>
    end
    missing=setdiff(required,T.Properties.VariableNames,'stable');
    assert(isempty(missing),'data:build_generalized_dataset:DatasetColumns', ...
        'The generalized dataset %s lacks the columns %s.',file,strjoin(missing,', '));
    caseID=double(T.CaseID);
    assert(all(isfinite(caseID)&caseID==fix(caseID))&&numel(unique(caseID))==height(T), ...
        'data:build_generalized_dataset:DatasetCaseIDs', ...
        'The generalized dataset %s needs one row per CaseID (whole numbers).',file);
end

function adopted=publish_or_adopt_dataset(pathValue,payload)
%PUBLISH_OR_ADOPT_DATASET Write the dataset, or keep an existing one that equals it.
%   A dataset already at PATHVALUE (an earlier call in the same run folder)
%   is kept when every variable equals the rebuilt one; one that differs is
%   refused, so that a run folder never mixes two datasets.
    expectedFields=sort(fieldnames(payload));
    adopted=isfile(pathValue);
    if adopted
        saved=utils.load_plain_mat(pathValue);
        assert(isequal(sort(fieldnames(saved)),expectedFields), ...
            'data:build_generalized_dataset:ExistingDatasetSchema', ...
            ['The run folder already holds a dataset %s with other variables ' ...
             'than the rebuilt one; use a new run folder.'],pathValue);
        for i=1:numel(expectedFields)
            name=expectedFields{i};
            assert(isequaln(saved.(name),payload.(name)), ...
                'data:build_generalized_dataset:ExistingDatasetChanged', ...
                ['The run folder already holds a dataset %s whose variable %s ' ...
                 'differs from the rebuilt one; use a new run folder.'],pathValue,name);
        end
    else
        % Tables and strings as plain values, format -v7: the file opens
        % without MATLAB (scipy.io.loadmat reads -v7, not -v7.3).
        utils.atomic_save_struct(pathValue,utils.plain_mat_encode(payload),'-v7');
    end
end

function roots=make_roots(cfg)
    roots.data=cfg.realExtended.paths.data;
    roots.registries=cfg.realExtended.paths.registries;
    roots.processed=cfg.realExtended.paths.processed;
    roots.splits=cfg.realExtended.paths.splits;
    roots.exclusions=cfg.realExtended.paths.exclusions;
    roots.results=cfg.realExtended.paths.results;
    roots.datasetResults=fullfile(roots.results,'dataset');
    roots.feasibility=fullfile(roots.results,'feasibility');
    roots.reports=cfg.realExtended.paths.reports;
    roots.stage1Reports=roots.reports;
    values=struct_values(roots);
    for i=1:numel(values),if ~isfolder(values(i)),mkdir(values(i));end,end
end

function values=struct_values(S)
    fields=fieldnames(S);values=strings(numel(fields),1);
    for i=1:numel(fields),values(i)=string(S.(fields{i}));end
end

function output=relative_struct(input,runRoot)
    names=fieldnames(input);output=struct();
    for i=1:numel(names)
        output.(names{i})=relative_to_root(input.(names{i}),runRoot);
    end
end

function arrays=dataset_arrays(contract)
    manifest=contract.caseManifest;
    development=string(manifest.MethodologicalRole)=="development";
    external=string(manifest.MethodologicalRole)=="external_test";
    complete=string(manifest.Classification)=="complete";
    completeDevelopment=development&complete;
    assert(any(completeDevelopment)&&any(external)&& ...
        all(complete(external))&&~any(external&~complete), ...
        'data:build_generalized_dataset:Split','Effective split is invalid.');
    assert(all(development(string(manifest.Classification)=="partial")), ...
        'data:build_generalized_dataset:PartialExternalLeakage', ...
        'Every partial-output case must remain development-only.');
    arrays=struct( ...
        'XCompleteDevelopment',contract.X_all(completeDevelopment,:), ...
        'YCompleteDevelopment',contract.Y_all(completeDevelopment,:), ...
        'XExternalTest',contract.X_all(external,:), ...
        'YExternalTest',contract.Y_all(external,:), ...
        'XDevelopmentAll',contract.X_all(development,:), ...
        'YDevelopmentAll',contract.Y_all(development,:), ...
        'completeDevelopmentIndices',find(completeDevelopment), ...
        'externalTestIndices',find(external), ...
        'completeDevelopmentCaseIDs',double(manifest.CaseID(completeDevelopment)), ...
        'externalTestCaseIDs',double(manifest.CaseID(external)), ...
        'developmentCaseIDs',double(manifest.CaseID(development)), ...
        'developmentMaterialGroupIdentities', ...
            string(manifest.DuplicateGroup(development)), ...
        'developmentSplitGroupIdentities', ...
            string(manifest.SplitGroup(development)), ...
        'developmentOutputAvailabilityMask', ...
            logical(contract.outputAvailabilityMask(development,:)));
    assert(all(isfinite(arrays.XDevelopmentAll),'all')&& ...
        all(isfinite(arrays.YExternalTest),'all')&& ...
        all(isfinite(arrays.YCompleteDevelopment),'all'), ...
        'data:build_generalized_dataset:FiniteCompleteContract', ...
        ['The development inputs and the outputs of the complete development and ' ...
         'external cases must be finite.']);
end

function check_output_training(contract,cfg)
%CHECK_OUTPUT_TRAINING Every output has enough development observations for its GP and PCE.
    arrays=dataset_arrays(contract);
    dataSet=struct( ...
        'X_train',arrays.XDevelopmentAll, ...
        'Y_train',arrays.YDevelopmentAll, ...
        'trainCaseIDs',arrays.developmentCaseIDs, ...
        'validationCaseIDs',arrays.externalTestCaseIDs, ...
        'inputNames',{cfg.realExtended.learningInputNames}, ...
        'outputNames',{cfg.realExtended.outputNames}, ...
        'inputBounds',cfg.realExtended.learningBounds, ...
        'developmentSplitGroupIdentities', ...
            arrays.developmentSplitGroupIdentities, ...
        'outputTrainingEvidence',{contract.perOutput});
    surrogates.output_training_contract(dataSet,cfg);
end

function gate=stage1_gate(R,paths,cfg,source)
    selectedExists=~strcmp(R.decision.decision,'ambiguous_requires_review');
    contract=R.finalDataContract;
    gate=struct();
    gate.schema_version='real_extended_stage1_gate_v3';
    gate.route='real_extended';
    gate.snapshot_id=cfg.realExtended.snapshotID;
    gate.seven_requested_inputs_authoritative=true;
    gate.requested_input_source=source;
    gate.transforms_consistent=true;
    gate.protocol_realization_verification='unavailable_from_selected_snapshot';
    gate.complete_case_protocol_mismatch_detected=false;
    gate.cohort_decision=R.decision.decision;
    expectedCaseCount=numel(unique(double(R.probeRegistry.CaseID)));
    expectedTestCount=contract.counts.externalTestCases;
    externalCanonicalIDs=unique(double(R.split.CanonicalCaseID( ...
        R.split.split_role=="test"&isfinite(R.split.CanonicalCaseID))), ...
        'stable');
    gate.all_case_split_valid=height(R.split)==expectedCaseCount && ...
        numel(externalCanonicalIDs)==expectedTestCount && ...
        all(R.split.split_role(R.split.Classification=="partial")=="train");
    gate.selected_primary_count=height(R.selected);
    gate.effective_train_count=contract.counts.completeDevelopmentCases;
    gate.effective_test_count=contract.counts.externalTestCases;
    gate.all_development_count=contract.counts.developmentCases;
    gate.partial_development_count=contract.counts.partialDevelopmentCases;
    gate.unusable_count=contract.counts.unusableCases;
    gate.per_output_training_counts=contract.counts.perOutputObservedDevelopment;
    gate.external_test_complete_only=true;
    gate.partial_cases_development_only=true;
    gate.output_imputation_used=false;
    gate.selected_case_fraction=height(R.selected)/max(height(R.completeAll),1);
    gate.support_assessment='reported_by_nearest_training_distance_without_count_threshold';
    gate.selected_csv_path=relative_to_root(paths.selected,cfg.paths.runRoot);
    gate.posterior_certification='not_applicable';
    gate.claim_scope='configured_dataset_and_feasibility_audit';
    gate.missing_probe_runids=sum(R.probeRegistry.missing_flag);
    if selectedExists && gate.all_case_split_valid
        gate.status='STAGE1_COMPLETE';
        gate.stage2_allowed=true;
    else
        gate.status='STAGE1_COMPLETE_STAGE2_REQUIRES_COHORT_REVIEW';
        gate.stage2_allowed=false;
    end
end

