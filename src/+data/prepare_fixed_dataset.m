function [dataset,audit,adopted] = prepare_fixed_dataset(cfg,P)
%PREPARE_FIXED_DATASET Build the fixed dataset, or keep an existing one that equals it.
%   [DATASET,AUDIT,ADOPTED] = data.prepare_fixed_dataset(CFG,P) builds the
%   fixed dataset from the model-ready CSV CFG.realData.csv
%   (utils.import_comsol_csv: complete, partial and unusable cases, the
%   constrained development/external split, the per-output training
%   cohorts) and saves it as CFG.files.dataset. A dataset already at that
%   path (an earlier call in the same run folder) is kept when every variable
%   equals the rebuilt one (ADOPTED true) and refused otherwise, so that a
%   run folder never mixes two datasets. AUDIT summarizes the dataset:
%   counts, case IDs, the split seed, the source CSV's file name and the
%   orders of the parameters and outputs; data.build_dataset writes it as
%   dataset_audit.json.
%   Side effects: writes CFG.files.dataset unless an equal dataset is there.
%   Computation: seconds.
    assert(strcmp(cfg.dataMode,'real'),'data:prepare_fixed_dataset:Route', ...
        ['This function works on the fixed route (study.project_config(S,''Route'',''real'')); ' ...
         'the configuration is for route ''%s''.'],cfg.dataMode);
    dataset=utils.import_comsol_csv(cfg.realData.csv,P,cfg);
    [~,sourceName,sourceExtension]=fileparts(cfg.realData.csv);
    dataset.dataProvenance=struct( ...
        'schemaVersion','routeR_fixed_data_provenance_v3', ...
        'rawRowCount',dataset.rawRowCount, ...
        'usableCaseCount',dataset.usableRowCount, ...
        'completeCaseCount',dataset.counts.completeCases, ...
        'partialCaseCount',dataset.counts.partialCases, ...
        'unusableCaseCount',dataset.counts.unusableCases, ...
        'completeDevelopmentCount',dataset.counts.completeDevelopmentCases, ...
        'partialDevelopmentCount',dataset.counts.partialDevelopmentCases, ...
        'developmentCount',dataset.counts.developmentCases, ...
        'externalTestCount',dataset.counts.externalTestCases, ...
        'perOutputObservedDevelopment', ...
            dataset.counts.perOutputObservedDevelopment, ...
        'trainFraction',cfg.realData.trainFraction, ...
        'validationFraction',cfg.realData.validationFraction, ...
        'splitSeed',cfg.realData.splitSeed, ...
        'splitAlgorithmVersion',cfg.realData.splitAlgorithmVersion, ...
        'sourceFile',[sourceName sourceExtension]);
    adopted=isfile(cfg.files.dataset);
    if adopted
        saved=utils.load_plain_mat(cfg.files.dataset);
        names=fieldnames(dataset);
        differing=names(~cellfun(@(name)isfield(saved,name)&& ...
            isequaln(saved.(name),dataset.(name)),names));
        assert(isempty(differing),'data:prepare_fixed_dataset:ExistingDatasetChanged', ...
            ['The run folder already holds a dataset %s that differs from the ' ...
             'rebuilt one (%s); use a new run folder.'],cfg.files.dataset, ...
            strjoin(differing,', '));
        dataset=saved;
    else
        % Tables and strings as plain values: the file opens without MATLAB.
        utils.atomic_save_struct(cfg.files.dataset,utils.plain_mat_encode(dataset),'-v7');
    end
    audit=audit_record(dataset,cfg,P);
end

function audit=audit_record(dataset,cfg,P)
%AUDIT_RECORD The summary of the fixed dataset (dataset_audit.json).
    development=double(dataset.trainCaseIDs(:));
    external=double(dataset.validationCaseIDs(:));
    anchors=reshape(double(cfg.inversion.defaultAnchorCaseIDs),[],1);
    audit=struct( ...
        'schema_version','routeR_fixed_dataset_audit_v5', ...
        'source_file',char(string(dataset.dataProvenance.sourceFile)), ...
        'split_seed',cfg.realData.splitSeed, ...
        'split_algorithm_version',cfg.realData.splitAlgorithmVersion, ...
        'complete_case_integer_rule',sprintf('round(%s*N_complete)', ...
            fraction_text(cfg.realData.validationFraction)), ...
        'counts',dataset.counts, ...
        'development_case_ids',reshape(development,1,[]), ...
        'external_test_case_ids',reshape(external,1,[]), ...
        'canonical_anchor_case_ids',reshape(anchors,1,[]), ...
        'per_output_training_counts',reshape(double( ...
            [dataset.outputTrainingEvidence.trainingCount]),1,[]), ...
        'parameter_order',{P.names},'output_order',{P.outputNames});
end

function text=fraction_text(fraction)
%FRACTION_TEXT A fraction with two decimals when that is exact (0.20), else in full.
    text=sprintf('%.2f',fraction);
    if str2double(text)~=fraction,text=sprintf('%.17g',fraction);end
end
