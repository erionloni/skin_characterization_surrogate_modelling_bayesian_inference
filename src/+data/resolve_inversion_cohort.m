function cohort = resolve_inversion_cohort(cfg,varargin)
%RESOLVE_INVERSION_COHORT The ordered inversion cases of the fixed route.
%   COHORT = data.resolve_inversion_cohort(CFG) reads the run's dataset
%   (CFG.files.dataset; COHORT = data.resolve_inversion_cohort(CFG, D) takes
%   it loaded as D) and resolves the cases to invert among the complete
%   external-test cases: an explicit list (CFG.inversion.explicitCaseIDs)
%   exactly as given, or a count (CFG.inversion.requestedCaseCount): the
%   configured canonical anchors (CFG.inversion.defaultAnchorCaseIDs, 20)
%   first, then further external cases in the order of the split manifest;
%   the setting 'all' (CFG.inversion.allExternalCases) counts every
%   complete external case.
%   Every case must have all six pressures. The cohort is chosen after the
%   surrogates and does not enter their training.
%   COHORT: selectionMode, requestedCount, caseIDs and externalRowIndices.
%   Side effects: none.

    assert(strcmp(cfg.dataMode,'real'),'data:resolve_inversion_cohort:Route', ...
        ['This function works on the fixed route (study.project_config(S,''Route'',''real'')); ' ...
         'the configuration is for route ''%s''.'],cfg.dataMode);
    if isempty(varargin)
        assert(isfile(cfg.files.dataset),'data:resolve_inversion_cohort:Dataset', ...
            ['The realized dataset (cfg.files.dataset) is required to resolve the ' ...
             'inversion cases; run the step ''dataset''.']);
        D=utils.load_plain_mat(cfg.files.dataset,'validationCaseIDs','externalTestCaseIDs', ...
            'X_validation','Y_validation','externalOutputAvailability', ...
            'splitManifest');
    else
        D=varargin{1};
        assert(isstruct(D)&&isscalar(D), ...
            'data:resolve_inversion_cohort:DatasetStruct', ...
            'The dataset argument must be one struct: the loaded fixed dataset.');
    end
    if isfield(D,'externalTestCaseIDs')
        external=double(D.externalTestCaseIDs(:));
    else
        external=double(D.validationCaseIDs(:));
    end
    assert(numel(unique(external))==numel(external)&&~isempty(external), ...
        'data:resolve_inversion_cohort:ExternalCases', ...
        ['The fixed dataset must list its external test cases once each; it lists ' ...
         '%d, of which %d are distinct.'],numel(external),numel(unique(external)));
    assert(isfield(D,'Y_validation')&&size(D.Y_validation,1)==numel(external)&& ...
        size(D.Y_validation,2)==6&&all(isfinite(D.Y_validation),'all'), ...
        'data:resolve_inversion_cohort:CompleteExternalCases', ...
        'Every inversion-eligible external case must have all six outputs.');
    requiredManifest={'CaseID','MethodologicalRole','Classification', ...
        'DuplicateGroup','SplitGroup'};
    assert(isfield(D,'X_validation')&& ...
        size(D.X_validation,1)==numel(external)&& ...
        all(isfinite(D.X_validation),'all')&& ...
        isfield(D,'externalOutputAvailability')&& ...
        isequal(logical(D.externalOutputAvailability), ...
            isfinite(double(D.Y_validation)))&& ...
        isfield(D,'splitManifest')&&istable(D.splitManifest)&& ...
        all(ismember(requiredManifest,D.splitManifest.Properties.VariableNames)), ...
        'data:resolve_inversion_cohort:ExternalContract', ...
        'The complete external-test material/availability contract is invalid.');
    manifest=D.splitManifest;
    externalRows=ismember(double(manifest.CaseID),external);
    developmentRows=string(manifest.MethodologicalRole)=="development";
    assert(nnz(externalRows)==numel(external)&& ...
        all(string(manifest.MethodologicalRole(externalRows))=="external_test")&& ...
        all(string(manifest.Classification(externalRows))=="complete")&& ...
        numel(unique(string(manifest.DuplicateGroup(externalRows))))== ...
            numel(external)&& ...
        isempty(intersect(string(manifest.SplitGroup(externalRows)), ...
            string(manifest.SplitGroup(developmentRows)))), ...
        'data:resolve_inversion_cohort:ExternalRoleOrGroupLeakage', ...
        'External cases must be complete, unique material groups disjoint from development.');

    explicit=reshape(double(cfg.inversion.explicitCaseIDs),1,[]);
    count=double(cfg.inversion.requestedCaseCount);
    if isempty(explicit)&&logical(cfg.inversion.allExternalCases)
        count=numel(external);
    end
    assert(isfinite(count)&&count==fix(count)&&count>0&&count<=numel(external), ...
        'data:resolve_inversion_cohort:Count', ...
        'InversionCaseCount must be positive and no larger than the external cohort.');
    if ~isempty(explicit)
        assert(numel(unique(explicit))==numel(explicit), ...
            'data:resolve_inversion_cohort:DuplicateExplicitCaseID', ...
            'Explicit inversion CaseIDs must be unique.');
        assert(all(ismember(explicit,external)), ...
            'data:resolve_inversion_cohort:ExplicitExternalMembership', ...
            'Every explicit inversion CaseID must be a complete external-test case.');
        ids=explicit;mode='explicit_ordered_case_ids';
        assert(numel(ids)==count, ...
            'data:resolve_inversion_cohort:ExplicitCount', ...
            'InversionCaseCount must equal the explicit CaseID-list length.');
    else
        anchors=reshape(double(cfg.inversion.defaultAnchorCaseIDs),1,[]);
        anchorCount=min(count,numel(anchors));
        requiredAnchors=anchors(1:anchorCount);
        assert(all(ismember(requiredAnchors,external)), ...
            'data:resolve_inversion_cohort:RequiredAnchorUnavailable', ...
            ['Count-based inversion selection requires the first %d configured ' ...
             'canonical anchors to be complete external-test cases; no anchor ' ...
             'may be silently replaced.'],anchorCount);
        ids=requiredAnchors;
        if count>anchorCount
            append=reshape(external(~ismember(external,ids)),1,[]);
            assert(numel(append)>=count-anchorCount, ...
                'data:resolve_inversion_cohort:InsufficientExternalCases', ...
                'The external cohort cannot supply the requested appended cases.');
            ids=[ids append(1:count-anchorCount)];
        end
        mode='count_anchor_then_external_manifest_order';
    end
    [found,loc]=ismember(ids,external);
    assert(all(found)&&all(isfinite(D.Y_validation(loc,:)),'all'), ...
        'data:resolve_inversion_cohort:CompleteSelection', ...
        ['Every inversion case must be a complete external test case of the fixed ' ...
         'dataset (all six pressures measured); check the ''Cases'' list.']);
    cohort=struct('schemaVersion','routeR_inversion_cohort_v1', ...
        'selectionMode',mode,'requestedCount',count,'caseIDs',ids, ...
        'externalRowIndices',loc);
end
