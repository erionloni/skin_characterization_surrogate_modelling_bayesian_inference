function semantics = sampler_semantics(sampler)
%SAMPLER_SEMANTICS Describe the third MCMC sample-array dimension exactly.
%   SEMANTICS = utils.sampler_semantics(SAMPLER) says, for AIES
%   (interacting walkers) or Adaptive Metropolis (independent chains), what
%   the third dimension of the sample array is and what an independent
%   replicate is.
%   Side effects: none.
    sampler = upper(char(string(sampler)));
    switch sampler
        case 'AIES'
            semantics = struct( ...
                'sampler', 'AIES', ...
                'stateSemantics', 'interacting_walkers', ...
                'thirdDimension', 'interacting_AIES_walkers', ...
                'withinAnalysisIndependent', false, ...
                'countField', 'nChainsOrWalkers');
        case 'AM'
            semantics = struct( ...
                'sampler', 'AM', ...
                'stateSemantics', 'independent_chains', ...
                'thirdDimension', 'independent_MCMC_chains', ...
                'withinAnalysisIndependent', true, ...
                'countField', 'nChainsOrWalkers');
        otherwise
            error('utils:sampler_semantics:UnsupportedSampler', ...
                'Unknown sampler semantics for "%s".', sampler);
    end
    semantics.independentReplicateUnit = ...
        'complete_uq_createAnalysis_execution';
end
