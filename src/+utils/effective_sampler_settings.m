function settings = effective_sampler_settings(mcmc)
%EFFECTIVE_SAMPLER_SETTINGS Resolve explicit UQLab MCMC options.
%   Direct-MCMC artifacts must describe the options actually passed to UQLab.
%   Every scientific setting is required explicitly; installed UQLab defaults
%   are never allowed to change a request silently.
%   SETTINGS = utils.effective_sampler_settings(MCMC) returns the options of
%   the sampler MCMC.sampler (AIES or Adaptive Metropolis) as they are
%   passed to UQLab.
%   Side effects: none.

    assert(isstruct(mcmc) && isfield(mcmc, 'sampler'), ...
        'utils:effective_sampler_settings:MissingSampler', ...
        'The MCMC configuration must name a sampler.');
    sampler = upper(char(string(mcmc.sampler)));
    supplied = struct();
    if isfield(mcmc, 'samplerOptions') && ~isempty(mcmc.samplerOptions)
        supplied = mcmc.samplerOptions;
    end

    switch sampler
        case 'AIES'
            require_options(supplied,{'a'},sampler);
            settings = struct('a', supplied.a);
            assert(isnumeric(settings.a) && isscalar(settings.a) && ...
                isfinite(settings.a) && settings.a > 1, ...
                'utils:effective_sampler_settings:InvalidAIESScale', ...
                'AIES stretch scale a must be a finite scalar greater than one.');
        case 'AM'
            require_options(supplied,{'Proposal','T0','Epsilon'},sampler);
            settings = struct( ...
                'Proposal', proposal(supplied), ...
                'T0', supplied.T0, ...
                'Epsilon', supplied.Epsilon);
            assert(isnumeric(settings.T0) && isscalar(settings.T0) && ...
                isfinite(settings.T0) && settings.T0 == fix(settings.T0) && ...
                settings.T0 > 2, ...
                'utils:effective_sampler_settings:InvalidAMT0', ...
                'AM T0 must be an integer greater than two.');
            assert(isnumeric(settings.Epsilon) && isscalar(settings.Epsilon) && ...
                isfinite(settings.Epsilon) && settings.Epsilon > 0, ...
                'utils:effective_sampler_settings:InvalidAMEpsilon', ...
                'AM Epsilon must be a positive finite scalar.');
        otherwise
            error('utils:effective_sampler_settings:UnsupportedSampler', ...
                'Only AIES and Adaptive Metropolis (AM) are supported; got "%s".', ...
                sampler);
    end
end

function value = proposal(s)
    value = s.Proposal;
    assert(isstruct(value), ...
        'utils:effective_sampler_settings:InvalidProposal', ...
        'Proposal settings must be a structure.');
    hasScale = isfield(value, 'PriorScale') && ~isempty(value.PriorScale);
    hasCov = isfield(value, 'Cov') && ~isempty(value.Cov);
    assert(xor(hasScale, hasCov), ...
        'utils:effective_sampler_settings:AmbiguousProposal', ...
        ['Direct MCMC supports exactly one explicit Gaussian proposal: ' ...
         'Proposal.PriorScale or Proposal.Cov.']);
    if hasScale
        assert(isnumeric(value.PriorScale) && isscalar(value.PriorScale) && ...
            isfinite(value.PriorScale) && value.PriorScale > 0, ...
            'utils:effective_sampler_settings:InvalidPriorScale', ...
            'Proposal.PriorScale must be a positive finite scalar.');
        value = struct('PriorScale', value.PriorScale);
    else
        assert(isnumeric(value.Cov) && ismatrix(value.Cov) && ...
            size(value.Cov, 1) == size(value.Cov, 2) && ...
            all(isfinite(value.Cov(:))) && issymmetric(value.Cov), ...
            'utils:effective_sampler_settings:InvalidCovariance', ...
            'Proposal.Cov must be a finite symmetric square matrix.');
        [~, flag] = chol(value.Cov);
        assert(flag == 0, ...
            'utils:effective_sampler_settings:NonPositiveDefiniteCovariance', ...
            'Proposal.Cov must be positive definite.');
        value = struct('Cov', value.Cov);
    end
end

function require_options(options,names,sampler)
    present=isfield(options,names);
    nonempty=false(size(names));
    for i=1:numel(names)
        if present(i),nonempty(i)=~isempty(options.(names{i}));end
    end
    assert(all(present&nonempty), ...
        'utils:effective_sampler_settings:MissingOption', ...
        '%s samplerOptions must explicitly define: %s.', ...
        sampler,strjoin(names,', '));
end
