function row = posterior_marginal_summary_row(estimate,series,parameter,truth)
%POSTERIOR_MARGINAL_SUMMARY_ROW One row of a marginal-statistics table.
%   ROW = plotting.posterior_marginal_summary_row(ESTIMATE, SERIES,
%   PARAMETER, TRUTH) returns, for the marginal density ESTIMATE
%   (plotting.posterior_marginal_density) of PARAMETER in the posterior
%   SERIES, the posterior mean, median and marginal mode, the 2.5%, 25%,
%   75% and 97.5% quantiles, the truth and whether the central 50% and 95%
%   intervals cover it, and the density's settings (bins, bandwidth,
%   truncation, retained draws, bounds, tie rule).
%   Side effects: none.
    if nargin<4||isempty(truth),truth=NaN;end
    covered50=NaN;covered95=NaN;
    if isfinite(truth)
        covered50=double(truth>=estimate.q25&&truth<=estimate.q75);
        covered95=double(truth>=estimate.q025&&truth<=estimate.q975);
    end
    row=table(string(series),string(parameter), ...
        double(estimate.posteriorMean),double(estimate.posteriorMedian), ...
        double(estimate.marginalMode),double(estimate.q025), ...
        double(estimate.q25),double(estimate.q75),double(estimate.q975), ...
        covered50,covered95,double(truth), ...
        string(estimate.centralIntervalConvention), ...
        string(estimate.method),double(estimate.binCount), ...
        double(estimate.bandwidth),string(estimate.bandwidthRule), ...
        double(estimate.kernelTruncationStandardDeviations), ...
        double(estimate.sampleCount),double(estimate.bounds(1)), ...
        double(estimate.bounds(2)),string(estimate.modeTieBreak), ...
        'VariableNames',{'Series','Parameter','PosteriorMean', ...
        'PosteriorMedian','MarginalMode','Q025','Q25','Q75','Q975', ...
        'TruthCovered50','TruthCovered95','Truth', ...
        'CentralIntervalConvention','DensityEstimationMethod', ...
        'DensityBinCount','DensityBandwidth','DensityBandwidthRule', ...
        'KernelTruncationStandardDeviations','RetainedDrawCount', ...
        'DensityLowerBound','DensityUpperBound','ModeTieBreak'});
end
