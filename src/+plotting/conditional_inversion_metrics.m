function result = conditional_inversion_metrics(cfg,comparison,matchedDetail)
%CONDITIONAL_INVERSION_METRICS The matched summaries behind the conditional-inversion figures.
%   RESULT = plotting.conditional_inversion_metrics(CFG, COMPARISON,
%   MATCHEDDETAIL) reads only the saved comparison and matched-cohort
%   tables of the conditional inversion and returns what the figures draw,
%   for the conditions that the saved results hold. A saved condition is the
%   condition of the settings' table (A.9) that fixes the same parameters
%   (the same id): it is labelled and ordered as in the table, so that a
%   renamed label relabels the figures of saved results.
%     conditions  per saved condition, in the table's order: code (the
%                 table's label), savedCode (its code in the saved tables),
%                 id, fixedNames (the fixed parameters without _RD) and
%                 fixedIndices, tick (the axis label: code and fixed
%                 parameters, e.g. "D m3_f + Thickness fixed"), rank (its row
%                 in the table) and reference (it fixes nothing)
%     cases       the CaseIDs of the saved results, in their order
%     parameters  the parameters the figures show: the weak pair of the
%                 settings (A.7, s.fixed.recovery.eigendecomposition.weakPair)
%     groups      one per figure set, in the order of the saved scenarios:
%                 kind 'conditions' for a scenario in which at least two
%                 conditions besides the reference ran (all its conditions on
%                 their common matched cohort), kind 'pair' for each
%                 condition besides the reference in the primary scenario
%                 (inversion.scenario_registry; the condition and the
%                 reference on their matched cohort). Fields: kind,
%                 scenario, members (indices into CONDITIONS, the reference
%                 first), cohort (the matched cohort, every case), and
%                 metrics: the rows of the figure parameters for the
%                 posterior spread (NormalizedPosteriorSD), the recovery
%                 error (PosteriorMedianNormalizedRecoveryError) and the
%                 50 % and 95 % truth inclusion (Covered50, Covered95)
%   It loads no model and evaluates no inverse problem.
%   Side effects: none.

    parameters=string(cfg.paramNames(:));
    requiredComparison={'CaseID','Scenario','Design','ConditionCode', ...
        'ConditionID','Parameter','ParameterFree','Scheduled', ...
        'ArtifactLoaded','CertificationStatus','FailureReason', ...
        'ErrorIdentifier','ArtifactSource','CellID', ...
        'CertificationMechanism', ...
        'PosteriorProvenanceRunRelative', ...
        'CertificationProvenanceRunRelative', ...
        'NormalizedPosteriorSD', ...
        'PosteriorMedianNormalizedRecoveryError','Covered50','Covered95'};
    requiredMatched={'AnalysisID','Scenario','RequiredConditions','CaseID', ...
        'Included','Reason'};
    assert(istable(comparison)&&all(ismember(requiredComparison, ...
        comparison.Properties.VariableNames)), ...
        'plotting:conditional_inversion_metrics:ComparisonSchema', ...
        'The saved conditional comparison table has an unsupported schema.');
    assert(istable(matchedDetail)&&all(ismember(requiredMatched, ...
        matchedDetail.Properties.VariableNames)), ...
        'plotting:conditional_inversion_metrics:MatchedSchema', ...
        'The saved conditional matched-cohort table has an unsupported schema.');

    comparison=normalize_comparison(comparison);
    matchedDetail=normalize_matched(matchedDetail);
    assert(height(comparison)>0&&all(comparison.Design=="all_six"), ...
        'plotting:conditional_inversion_metrics:Design', ...
        'Conditional reporting is defined only for the all_six design.');
    assert(all(ismember(comparison.Parameter,parameters)), ...
        'plotting:conditional_inversion_metrics:Parameter', ...
        ['The saved conditional comparison names parameters other than the four of ' ...
         'the study; rerun the step ''conditional_inversion''.']);
    key=comparison.Scenario+"|"+string(comparison.CaseID)+"|"+ ...
        comparison.ConditionCode+"|"+comparison.Parameter;
    assert(numel(unique(key))==height(comparison), ...
        'plotting:conditional_inversion_metrics:DuplicateRows', ...
        'Conditional comparison rows are not unique on scientific axes.');

    conditions=saved_conditions(cfg,comparison);
    % The figures show the weak pair of the settings (A.7, weakPair).
    figureParameters=reshape(parameters(cfg.analysis.weakPairIndices),1,[]);
    caseIDs=unique(comparison.CaseID,'stable');
    reference=find([conditions.reference]);
    metricNames=["NormalizedPosteriorSD","PosteriorMedianNormalizedRecoveryError", ...
        "Covered50","Covered95"];
    groups=struct('kind',{},'scenario',{},'members',{},'cohort',{},'metrics',{});
    for scenario=reshape(unique(comparison.Scenario,'stable'),1,[])
        scheduled=unique(comparison.ConditionCode(comparison.Scenario==scenario& ...
            comparison.Scheduled));
        members=find(ismember([conditions.savedCode],scheduled)&~[conditions.reference]);
        if numel(members)>=2
            groups(end+1)=group(comparison,matchedDetail,conditions,'conditions',scenario, ...
                [reference members],caseIDs,figureParameters,metricNames); %#ok<AGROW>
        end
        if inversion.scenario_registry(scenario).primaryScientificScenario
            for m=members
                groups(end+1)=group(comparison,matchedDetail,conditions,'pair',scenario, ...
                    [reference m],caseIDs,figureParameters,metricNames); %#ok<AGROW>
            end
        end
    end
    result=struct('schemaVersion','conditional_s07_metrics_v4_settings_conditions', ...
        'conditions',conditions,'cases',caseIDs,'parameters',figureParameters, ...
        'groups',groups);
end

function G=group(comparison,matchedDetail,conditions,kind,scenario,members,caseIDs, ...
        figureParameters,metricNames)
%GROUP One figure set: its matched cohort and the metric rows of its conditions.
    codes=[conditions(members).savedCode];
    cohort=exact_cohort(matchedDetail,scenario,codes,caseIDs);
    metrics=struct();
    for metric=metricNames
        metrics.(char(metric))=metric_rows(comparison,scenario,codes,figureParameters, ...
            cohort,metric);
    end
    G=struct('kind',kind,'scenario',scenario,'members',members,'cohort',cohort, ...
        'metrics',metrics);
end

function conditions=saved_conditions(cfg,comparison)
%SAVED_CONDITIONS The saved conditions, as the settings' table (A.9) defines them.
    table=inversion.conditional_inversion_conditions(cfg);
    [ids,first]=unique(comparison.ConditionID,'stable');
    savedCodes=comparison.ConditionCode(first);
    template=struct('code',"",'savedCode',"",'id',"",'fixedNames',strings(1,0), ...
        'fixedIndices',zeros(1,0),'tick',"",'rank',0,'reference',false);
    conditions=repmat(template,1,numel(ids));
    for i=1:numel(ids)
        rank=find(strcmp({table.id},ids(i)));
        assert(isscalar(rank),'plotting:conditional_inversion_metrics:Condition', ...
            ['The saved conditional results hold condition %s (%s), which the condition table of ' ...
             'the settings (A.9, fixed.conditionalInversion.conditions) does not define; add a row ' ...
             'that fixes the same parameters.'],ids(i),savedCodes(i));
        entry=table(rank);
        names=string(regexprep(entry.fixedParameterNames,'_RD$',''));
        if isempty(names)
            tick=string(entry.code)+" all free";
        else
            tick=string(entry.code)+" "+strjoin(names," + ")+" fixed";
        end
        conditions(i)=struct('code',string(entry.code),'savedCode',savedCodes(i), ...
            'id',ids(i),'fixedNames',reshape(names,1,[]), ...
            'fixedIndices',reshape(double(entry.fixedParameterIndices),1,[]),'tick',tick, ...
            'rank',rank,'reference',logical(entry.canonicalReference));
    end
    [~,order]=sort([conditions.rank]);
    conditions=conditions(order);
    assert(nnz([conditions.reference])==1, ...
        'plotting:conditional_inversion_metrics:Reference', ...
        ['The saved conditional results must hold the reference condition (all parameters ' ...
         'free) once; rerun the step ''conditional_inversion''.']);
end

function T=normalize_comparison(T)
    textFields={'Scenario','Design','ConditionCode','ConditionID','Parameter', ...
        'CertificationStatus','FailureReason','ErrorIdentifier','ArtifactSource', ...
        'CellID','CertificationMechanism', ...
        'PosteriorProvenanceRunRelative', ...
        'CertificationProvenanceRunRelative'};
    for i=1:numel(textFields),T.(textFields{i})=string(T.(textFields{i}));end
    logicalFields={'ParameterFree','Scheduled','ArtifactLoaded'};
    for i=1:numel(logicalFields),T.(logicalFields{i})=as_logical(T.(logicalFields{i}));end
    T.CaseID=double(T.CaseID);
    T.NormalizedPosteriorSD=double(T.NormalizedPosteriorSD);
    T.PosteriorMedianNormalizedRecoveryError=double( ...
        T.PosteriorMedianNormalizedRecoveryError);
    T.Covered50=double(T.Covered50);
    T.Covered95=double(T.Covered95);
end

function T=normalize_matched(T)
    textFields={'AnalysisID','Scenario','RequiredConditions','Reason'};
    for i=1:numel(textFields),T.(textFields{i})=string(T.(textFields{i}));end
    T.CaseID=double(T.CaseID);T.Included=as_logical(T.Included);
end

function cohort=exact_cohort(detail,scenario,requiredCodes,caseIDs)
    scenario=string(scenario);requiredCodes=string(requiredCodes(:)).';
    scenarioRows=detail.Scenario==scenario;
    analysisIDs=unique(detail.AnalysisID(scenarioRows),'stable');
    match=false(size(analysisIDs));
    for i=1:numel(analysisIDs)
        rows=scenarioRows&detail.AnalysisID==analysisIDs(i);
        declarations=unique(detail.RequiredConditions(rows));
        assert(isscalar(declarations), ...
            'plotting:conditional_inversion_metrics:MatchedDeclaration', ...
            'One matched analysis has inconsistent required conditions.');
        match(i)=isequal(sort(unique(split(declarations,"|"))),sort(unique(requiredCodes(:))));
    end
    assert(nnz(match)==1, ...
        'plotting:conditional_inversion_metrics:MatchedAnalysis', ...
        'Exactly one %s matched analysis must require conditions %s.', ...
        scenario,strjoin(requiredCodes,'|'));
    analysisID=analysisIDs(match);
    rows=scenarioRows&detail.AnalysisID==analysisID;
    selected=detail(rows,:);
    assert(height(selected)==numel(caseIDs)&& ...
        numel(unique(selected.CaseID))==numel(caseIDs)&& ...
        all(ismember(caseIDs,selected.CaseID)), ...
        'plotting:conditional_inversion_metrics:MatchedCases', ...
        'A matched analysis must report every case of the saved results exactly once.');
    [~,location]=ismember(caseIDs,selected.CaseID);selected=selected(location,:);
    included=logical(selected.Included);
    includedIDs=caseIDs(included);excludedIDs=caseIDs(~included);
    cohort=table(repmat(scenario,numel(caseIDs),1), ...
        repmat(analysisID,numel(caseIDs),1),caseIDs,included, ...
        string(selected.Reason),repmat(numel(includedIDs),numel(caseIDs),1), ...
        repmat(id_text(includedIDs),numel(caseIDs),1), ...
        repmat(id_text(excludedIDs),numel(caseIDs),1), ...
        repmat(strjoin(requiredCodes,'|'),numel(caseIDs),1), ...
        'VariableNames',{'Scenario','AnalysisID','CaseID','Included', ...
        'Reason','MatchedN','MatchedCaseIDs','ExcludedCaseIDs', ...
        'RequiredConditions'});
end

function output=metric_rows(comparison,scenario,conditions,parameters,cohort,metric)
    scenario=string(scenario);conditions=string(conditions(:)).';
    parameters=string(parameters(:)).';metric=string(metric);
    rows=comparison.Scenario==scenario& ...
        ismember(comparison.ConditionCode,conditions)& ...
        ismember(comparison.Parameter,parameters);
    source=comparison(rows,:);
    expected=height(cohort)*numel(conditions)*numel(parameters);
    assert(height(source)==expected, ...
        'plotting:conditional_inversion_metrics:ExplicitRows', ...
        ['The conditional comparison table must preserve every planned or ' ...
         'explicitly unavailable scenario/condition/parameter row.']);
    [~,caseOrder]=ismember(source.CaseID,cohort.CaseID);
    [~,conditionOrder]=ismember(source.ConditionCode,conditions);
    [~,parameterOrder]=ismember(source.Parameter,parameters);
    assert(all(caseOrder>0&conditionOrder>0&parameterOrder>0), ...
        'plotting:conditional_inversion_metrics:Axes', ...
        ['The saved conditional table has rows outside the study''s cases, conditions ' ...
         'or parameters; rerun the step ''conditional_inversion''.']);
    source.CaseOrder=caseOrder;source.ConditionOrder=conditionOrder;
    source.ParameterOrder=parameterOrder;
    source=sortrows(source,{'ParameterOrder','CaseOrder','ConditionOrder'});
    [~,cohortLocation]=ismember(source.CaseID,cohort.CaseID);
    matched=logical(cohort.Included(cohortLocation));
    value=double(source.(char(metric)));
    available=matched&source.Scheduled&source.ArtifactLoaded& ...
        source.ParameterFree&isfinite(value);
    missingReason=strings(height(source),1);
    for i=1:height(source)
        if available(i)
            missingReason(i)="available_exact_matched_cohort";
        elseif ~matched(i)
            missingReason(i)="excluded_from_exact_matched_cohort:"+ ...
                cohort.Reason(cohortLocation(i));
        elseif ~source.Scheduled(i)
            missingReason(i)="not_scheduled";
        elseif ~source.ArtifactLoaded(i)
            reason=source.FailureReason(i);
            if strlength(reason)==0,reason=source.CertificationStatus(i);end
            missingReason(i)="artifact_unavailable:"+reason;
        elseif ~source.ParameterFree(i)
            missingReason(i)="parameter_fixed_at_truth";
        else
            missingReason(i)="metric_nonfinite_or_unavailable";
        end
    end
    n=zeros(height(source),1);medianValue=nan(height(source),1);
    q25=nan(height(source),1);q75=nan(height(source),1);
    coveredCount=nan(height(source),1);coverage=nan(height(source),1);
    for p=1:numel(parameters)
        for c=1:numel(conditions)
            group=source.Parameter==parameters(p)& ...
                source.ConditionCode==conditions(c);
            valid=group&available;values=value(valid);
            count=numel(values);n(group)=count;
            if count>0
                medianValue(group)=median(values);
                quartiles=quantile(values,[0.25 0.75]);
                q25(group)=quartiles(1);q75(group)=quartiles(2);
                if ismember(metric,["Covered50" "Covered95"])
                    coveredCount(group)=sum(values~=0);
                    coverage(group)=coveredCount(find(group,1))/count;
                end
            end
        end
    end
    output=table(source.CaseID,repmat(scenario,height(source),1), ...
        source.ConditionCode,source.ConditionID,source.Parameter, ...
        source.ParameterFree,source.Scheduled,source.ArtifactLoaded, ...
        source.CertificationStatus,source.FailureReason,source.ErrorIdentifier, ...
        source.ArtifactSource,source.CellID,source.CertificationMechanism, ...
        source.PosteriorProvenanceRunRelative, ...
        source.CertificationProvenanceRunRelative, ...
        repmat(metric,height(source),1),value,matched,available,missingReason, ...
        repmat(cohort.MatchedN(1),height(source),1), ...
        repmat(cohort.MatchedCaseIDs(1),height(source),1),n,medianValue,q25,q75, ...
        coveredCount,coverage, ...
        'VariableNames',{'CaseID','Scenario','ConditionCode','ConditionID', ...
        'Parameter','ParameterFree','Scheduled','ArtifactLoaded', ...
        'CertificationStatus','FailureReason','ErrorIdentifier','ArtifactSource', ...
        'CellID','CertificationMechanism', ...
        'PosteriorProvenanceRunRelative', ...
        'CertificationProvenanceRunRelative','Metric','MetricValue', ...
        'IncludedInMatchedCohort','MetricAvailable','MetricAvailabilityReason', ...
        'MatchedN','MatchedCaseIDs','SummaryN','SummaryMedian','SummaryQ25', ...
        'SummaryQ75','CoveredCount','CoverageProportion'});
end

function value=as_logical(input)
    if islogical(input),value=input;return;end
    if isnumeric(input),value=input~=0;return;end
    value=ismember(lower(string(input)),["true" "1"]);
end

function text=id_text(ids)
    ids=reshape(double(ids),1,[]);
    if isempty(ids),text="";else,text=strjoin(string(ids),'|');end
end
