function manifest = saved_downstream_error_budget_figures(cfg,options)
%SAVED_DOWNSTREAM_ERROR_BUDGET_FIGURES The figures of the downstream error budget.
%   MANIFEST = plotting.saved_downstream_error_budget_figures(CFG, OPTIONS)
%   draws, from the saved error-budget tables of the recovery
%   (recovery.characterize_downstream_error_budget), the surrogate error
%   against the propagated measurement noise per feature: the error shares,
%   the calibrated emulator-variance share, the standardized errors and the
%   feature-family summaries, and returns the manifest.
%   Side effects: writes the figures and closes them.
%   Computation: seconds.

    if nargin<2||isempty(options),options=struct();end
    mode=option_text(options,'Mode',default_mode(cfg));
    assert(ismember(mode,{'aggregate','publication','full'}), ...
        'plotting:saved_downstream_error_budget_figures:Mode', ...
        'Mode must be aggregate, publication, or full.');
    sourceRoot=study.source_folder(cfg,'downstream_error_budget');
    paths=source_paths(sourceRoot);
    required={paths.perFeature,paths.raw,paths.active,paths.diagnostic, ...
        paths.maximum,paths.status};
    missing=required(~cellfun(@isfile,required));
    outputRoot=fullfile(cfg.paths.stage07,'reconstruction', ...
        'downstream_error_budget');
    if ~isfolder(outputRoot),mkdir(outputRoot);end
    if ~isempty(missing)
        status=struct('schema_version','downstream_error_budget_figures_status_v2', ...
            'generated_figure_count',0,'mode',mode, ...
            'missing_source_files',strjoin(string(missing),'|'), ...
            'source_tables_only',true);
        utils.atomic_write_json(fullfile(outputRoot, ...
            'downstream_error_budget_figures_status.json'),status, ...
            'AllowReplace',true);
        manifest=empty_manifest();return;
    end
    perFeature=readtable(paths.perFeature,'Delimiter',',','TextType','string');
    raw=readtable(paths.raw,'Delimiter',',','TextType','string');
    active=readtable(paths.active,'Delimiter',',','TextType','string');
    diagnostic=readtable(paths.diagnostic,'Delimiter',',','TextType','string');
    maximum=readtable(paths.maximum,'Delimiter',',','TextType','string');
    validate_tables(perFeature,raw,active,diagnostic,maximum);
    parts=cell(0,1);
    parts{end+1}=feature_metric_figure(cfg,active, ...
        'RMSErrorInMeasurementSDUnits', ...
        'RMS empirical surrogate error / measurement SD', ...
        'empirical_standardized_error',paths.active);
    parts{end+1}=feature_metric_figure(cfg,active, ...
        'MeanCalibratedEmulatorVarianceShare', ...
        'Mean calibrated emulator variance share', ...
        'calibrated_emulator_variance_share',paths.active);
    parts{end+1}=feature_metric_figure(cfg,active, ...
        'EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance', ...
        'Empirical MSE / (empirical MSE + mean measurement variance)', ...
        'empirical_error_share',paths.active);
    parts{end+1}=raw_summary_figure(cfg,raw,paths.raw);
    if ~strcmp(mode,'aggregate')
        parts{end+1}=maximum_figure(cfg,maximum,paths.maximum);
        parts{end+1}=active_summary_figure(cfg,active,paths.active);
        parts{end+1}=diagnostic_summary_figure(cfg,diagnostic,paths.diagnostic);
    end
    manifest=vertcat(parts{:});
    inventoryPath=fullfile(outputRoot, ...
        'downstream_error_budget_figure_inventory.csv');
    utils.atomic_write_table(inventoryPath,manifest);
    status=struct('schema_version','downstream_error_budget_figures_status_v2', ...
        'generated_figure_count',height(manifest),'mode',mode, ...
        'source_tables_only',true,'gp_evaluations_performed',0, ...
        'likelihood_evaluations_performed',0,'mcmc_runs_performed',0, ...
        'stage05_recomputations_performed',0, ...
        'stage06_recomputations_performed',0);
    utils.atomic_write_json(fullfile(outputRoot, ...
        'downstream_error_budget_figures_status.json'),status, ...
        'AllowReplace',true);
end

function row=feature_metric_figure(cfg,T,metric,yLabel,name,source)
    one=T(T.Cohort=="validation"&T.EvaluationClass=="core_active",:);
    spaceOrder=zeros(height(one),1);
    names=["all_six" "d2_only" "d6_only" "cycle_1_only" ...
        "ratios_only" "physics_guided_full_rank_six"];
    for i=1:numel(names),spaceOrder(one.EvaluationSpace==names(i))=i;end
    [~,order]=sortrows([spaceOrder,double(one.FeatureIndex)],[1 2]);
    one=one(order,:);labels=one.EvaluationSpace+":"+one.FeatureID;
    st=plotting.style();fig=figure('Visible','off','Position',[80 80 1300 560]);
    bar(double(one.(metric)),'FaceColor',st.palette(1,:),'EdgeColor','none');
    ylabel(yLabel);title('Held-out downstream surrogate characterization');
    xticks(1:height(one));xticklabels(labels);xtickangle(55);grid on;
    row=plotting.export_saved_figure(fig,cfg, ...
        'reconstruction/downstream_error_budget',name,{source},'aggregate',[]);
end

function row=raw_summary_figure(cfg,T,source)
    one=T(T.Cohort=="validation",:);[~,order]=sort(one.FeatureIndex);
    one=one(order,:);labels=one.FeatureID;
    st=plotting.style();fig=figure('Visible','off','Position',[80 80 1200 720]);
    layout=tiledlayout(fig,2,2,'TileSpacing','compact','Padding','compact');
    nexttile;bar([one.EmpiricalMAE one.EmpiricalRMSE]);
    ylabel('mbar');title('Native empirical error');legend({'MAE','RMSE'}, ...
        'Location','best');set(gca,'XTick',1:6,'XTickLabel',labels);xtickangle(35);
    nexttile;bar(one.RMSErrorInMeasurementSDUnits, ...
        'FaceColor',st.palette(1,:));ylabel('dimensionless');
    title('RMS error / measurement SD');set(gca,'XTick',1:6, ...
        'XTickLabel',labels);xtickangle(35);
    nexttile;bar(one.MeanCalibratedEmulatorVarianceShare, ...
        'FaceColor',st.palette(2,:));ylabel('fraction');
    title('Mean calibrated emulator variance share');set(gca,'XTick',1:6, ...
        'XTickLabel',labels);xtickangle(35);
    nexttile;bar(one. ...
        EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance, ...
        'FaceColor',st.palette(3,:));ylabel('fraction');
    title('Empirical MSE share');set(gca,'XTick',1:6, ...
        'XTickLabel',labels);xtickangle(35);
    title(layout,'Held-out raw-pressure downstream error budget');
    row=plotting.export_saved_figure(fig,cfg, ...
        'reconstruction/downstream_error_budget', ...
        'raw_output_summary',{source},'aggregate',[]);
end

function row=maximum_figure(cfg,T,source)
    one=T(T.Cohort=="validation"&T.EvaluationClass=="core_active"& ...
        T.MaximumMetric=="absolute_empirical_error_in_measurement_SD_units",:);
    [~,order]=sort(double(one.MaximumValue),'descend');one=one(order,:);
    labels=one.EvaluationSpace+":"+one.FeatureID+" (Case "+ ...
        string(one.CaseID)+")";
    st=plotting.style();fig=figure('Visible','off','Position',[80 80 1300 560]);
    bar(double(one.MaximumValue),'FaceColor',st.palette(4,:),'EdgeColor','none');
    ylabel('Absolute empirical error / measurement SD');
    title('Held-out maximum standardized-error provenance');
    xticks(1:height(one));xticklabels(labels);xtickangle(55);grid on;
    row=plotting.export_saved_figure(fig,cfg, ...
        'reconstruction/downstream_error_budget', ...
        'maximum_standardized_error_provenance',{source},'publication',[]);
end

function row=active_summary_figure(cfg,T,source)
    one=T(T.Cohort=="validation"&T.EvaluationClass=="core_active",:);
    spaces=unique(one.EvaluationSpace,'stable');values=nan(numel(spaces),3);
    for i=1:numel(spaces)
        rows=one.EvaluationSpace==spaces(i);
        values(i,:)=[mean(one.RMSErrorInMeasurementSDUnits(rows)), ...
            mean(one.MeanCalibratedEmulatorVarianceShare(rows)),mean(one. ...
            EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance(rows))];
    end
    row=summary_heatmap(cfg,values,spaces, ...
        ["RMS error / measurement SD" "Calibrated variance share" ...
         "Empirical MSE share"], ...
        'Held-out active feature-space summaries', ...
        'active_feature_summary',source);
end

function row=diagnostic_summary_figure(cfg,T,source)
    one=T(T.Cohort=="validation",:);spaces=unique(one.EvaluationSpace,'stable');
    values=nan(numel(spaces),3);
    for i=1:numel(spaces)
        rows=one.EvaluationSpace==spaces(i);
        values(i,:)=[mean(one.MeanRMSMeasurementStandardizedErrorAcrossFeatures(rows)), ...
            mean(one.MeanCalibratedEmulatorVarianceShare(rows)), ...
            mean(one.MeanEmpiricalMSEShare(rows))];
    end
    row=summary_heatmap(cfg,values,spaces, ...
        ["RMS error / measurement SD" "Calibrated variance share" ...
         "Empirical MSE share"], ...
        'Held-out diagnostic feature-family summaries', ...
        'diagnostic_feature_family_summary',source);
end

function row=summary_heatmap(cfg,values,rowLabels,columnLabels,titleText,name,source)
    figureHandle=figure('Visible','off','Position',[80 80 950 500]);
    imagesc(values);colorbar;colormap(parula);
    xticks(1:numel(columnLabels));xticklabels(columnLabels);xtickangle(25);
    yticks(1:numel(rowLabels));yticklabels(rowLabels);title(titleText);
    for i=1:size(values,1)
        for j=1:size(values,2)
            text(j,i,sprintf('%.3g',values(i,j)), ...
                'HorizontalAlignment','center','Color','k');
        end
    end
    row=plotting.export_saved_figure(figureHandle,cfg, ...
        'reconstruction/downstream_error_budget',name,{source},'publication',[]);
end

function validate_tables(perFeature,raw,active,diagnostic,maximum)
    perRequired={'Cohort','EvaluationSpace','EvaluationClass','FeatureIndex', ...
        'FeatureID','EmpiricalMAE','EmpiricalRMSE', ...
        'RMSErrorInMeasurementSDUnits', ...
        'MeanCalibratedEmulatorVarianceShare', ...
        'MeanRawUQLabFeatureVariance', ...
        'EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance'};
    rawRequired=[perRequired {'Units'}];
    diagnosticRequired={'Cohort','EvaluationSpace', ...
        'MeanRMSMeasurementStandardizedErrorAcrossFeatures', ...
        'MeanCalibratedEmulatorVarianceShare','MeanEmpiricalMSEShare'};
    maximumRequired={'Cohort','EvaluationSpace','EvaluationClass','FeatureID', ...
        'MaximumMetric','MaximumValue','CaseID'};
    assert(all(ismember(perRequired,perFeature.Properties.VariableNames))&& ...
        all(ismember(rawRequired,raw.Properties.VariableNames))&& ...
        all(ismember(perRequired,active.Properties.VariableNames))&& ...
        all(ismember(diagnosticRequired,diagnostic.Properties.VariableNames))&& ...
        all(ismember(maximumRequired,maximum.Properties.VariableNames)), ...
        'plotting:saved_downstream_error_budget_figures:Schema', ...
        'One or more saved Task-13 tables has an invalid schema.');
end

function paths=source_paths(root)
    paths=struct( ...
        'perFeature',fullfile(root,'downstream_error_budget_per_feature.csv'), ...
        'raw',fullfile(root,'raw_output_summary.csv'), ...
        'active',fullfile(root,'active_feature_summary.csv'), ...
        'diagnostic',fullfile(root,'diagnostic_feature_family_summary.csv'), ...
        'maximum',fullfile(root,'maximum_standardized_error_provenance.csv'), ...
        'status',fullfile(root,'downstream_error_budget_status.json'));
end

function value=option_text(options,name,fallback)
    value=fallback;if isfield(options,name),value=options.(name);end
    value=lower(char(string(value)));
end

function value=default_mode(cfg)
%DEFAULT_MODE The figure mode of the settings (0.4).
    value=cfg.fig.mode;
end

function T=empty_manifest()
    T=table('Size',[0 5], ...
        'VariableTypes',repmat({'string'},1,5), ...
        'VariableNames',{'Category','Figure','RelativePath','Scope', ...
        'SourceArtifacts'});
end
