function [design,metadata]=build_material_lhs(cfg)
%BUILD_MATERIAL_LHS The material points of the screen: one Latin hypercube over the material prior.
%   [DESIGN, METADATA] = screening.build_material_lhs(CFG) draws, with the
%   screen's seed, one randomized Latin hypercube of the configured size
%   over the prior box of the four material parameters and returns one row
%   per point (MaterialPointID: M0001, M0002, ... in design order; the four
%   parameters in model coordinates) and METADATA (counts, the generator
%   and seed, the standardized prior covariance).
%   Side effects: none (the random number generator's state is restored).

    assert(isstruct(cfg)&&strcmp(cfg.dataMode,'real_extended')&& ...
        isfield(cfg,'stage9bScreening'), ...
        'screening:build_material_lhs:Configuration', ...
        ['The material design needs the generalized-route configuration with ' ...
         'stage9bScreening.']);
    policy=cfg.stage9bScreening;
    names=cellstr(string(policy.materialParameterNames));
    allNames=cellstr(string(cfg.paramNames));
    [present,indices]=ismember(names,allNames);
    assert(all(present)&&numel(unique(indices))==4&&isequal(indices,1:4), ...
        'screening:build_material_lhs:ParameterOrder', ...
        ['The screening''s material parameters must be the four parameters of the ' ...
         'study, in their order.']);
    bounds=double(cfg.paramBounds(indices,:));
    count=double(policy.materialPointCount);
    seed=double(policy.materialLHSSeed);
    validateattributes(count,{'numeric'},{'scalar','integer','positive'});
    validateattributes(seed,{'numeric'},{'scalar','integer','positive'});

    previous=rng;
    cleanup=onCleanup(@()rng(previous));
    rng(seed,'twister');
    theta=utils.dispersed_initial_ensemble( ...
        bounds,count,'latin_hypercube');
    assert(isequal(size(theta),[count 4])&&all(isfinite(theta),'all')&& ...
        size(unique(theta,'rows'),1)==count&& ...
        all(theta>=bounds(:,1).'&theta<=bounds(:,2).','all'), ...
        'screening:build_material_lhs:GeneratedDesign', ...
        ['The Latin hypercube must give %d distinct, finite material points inside ' ...
         'the prior bounds.'],count);

    priorMean=mean(bounds,2).';
    priorSD=(bounds(:,2)-bounds(:,1)).'/sqrt(12);
    z=(theta-priorMean)./priorSD;
    normalized=(theta-bounds(:,1).')./(bounds(:,2)-bounds(:,1)).';
    materialPointID=compose("M%04d",(1:count).');
    assert(max(abs(z-sqrt(12)*(normalized-0.5)),[],'all')<=1e-12, ...
        'screening:build_material_lhs:Standardization', ...
        'Internal error: the material points or their standardized coordinates are inconsistent.');
    design=table(materialPointID,theta(:,1),theta(:,2),theta(:,3), ...
        theta(:,4),z(:,1),z(:,2),z(:,3),z(:,4), ...
        'VariableNames',{'MaterialPointID','m3_f_RD','m3_e_RD', ...
        'log10_k0_RD','Thickness_RD','z_m3_f_RD','z_m3_e_RD', ...
        'z_log10_k0_RD','z_Thickness_RD'});
    metadata=struct( ...
        'schema_version','stage9b_material_lhs_metadata_v2', ...
        'seed',seed,'rng_algorithm','twister', ...
        'implementation','utils.dispersed_initial_ensemble_latin_hypercube', ...
        'parameter_names',{names},'bounds',bounds, ...
        'prior_mean',priorMean,'prior_sd',priorSD, ...
        'prior_covariance_z',eye(4),'row_count',count, ...
        'unique_row_count',size(unique(theta,'rows'),1), ...
        'rng_state_restored_by_oncleanup',true);
end
