function status=run_screening(varargin)
%RUN_SCREENING The protocol screen: local Fisher information of the candidate protocols.
%   STATUS = screening.run_screening('Configuration',CFG, 'Provider',P,
%   'OutputRoot',ROOT, ...) screens the candidate protocols at the material
%   points with the provider P (the approved GP) and writes the screen into
%   ROOT (study.steps.screening_screen). 'CandidateRegistry' and
%   'MaterialDesign' restrict it to a subset (with 'RequireFullDesign',false);
%   'RenderFigures' draws its figures. An interrupted screen continues from
%   its checkpoint (blocks of candidates) in the same folder, for the same
%   inputs (screening.screen_inputs: the model provider's content, the
%   protocols, material points and policy), which the local information
%   records.
%   Side effects: writes the screen below ROOT; with 'RenderFigures', its
%   figures.
%   Computation: about 1 hour for the full screen (730 protocols at 1,000
%   material points); minutes for a subset.

    parser=inputParser;
    addParameter(parser,'OutputRoot','',@(x)ischar(x)||(isstring(x)&&isscalar(x)));
    addParameter(parser,'CandidateRegistry',table(),@istable);
    addParameter(parser,'MaterialDesign',table(),@istable);
    addParameter(parser,'RequireFullDesign',true,@(x)islogical(x)&&isscalar(x));
    addParameter(parser,'RenderFigures',true,@(x)islogical(x)&&isscalar(x));
    addParameter(parser,'Configuration',struct([]),@isstruct);
    addParameter(parser,'Provider',struct([]),@isstruct);
    parse(parser,varargin{:});
    cfg=parser.Results.Configuration;
    provider=parser.Results.Provider;
    assert(~isempty(cfg)&&strcmp(cfg.dataMode,'real_extended')&&~isempty(provider)&& ...
        strlength(string(parser.Results.OutputRoot))>0, ...
        'screening:run_screening:Invocation', ...
        'A screen needs its configuration, model provider and output folder.');
    policy=cfg.stage9bScreening;
    outputRoot=utils.absolute_path(char(string(parser.Results.OutputRoot)));

    [candidates,candidateMetadata]=resolve_candidates( ...
        cfg,parser.Results.CandidateRegistry);
    [materials,materialMetadata]=resolve_materials( ...
        cfg,parser.Results.MaterialDesign);
    if parser.Results.RequireFullDesign
        % The design of the settings (B.6): every protocol of the grid and
        % every material point (thesis: 730 and 1000).
        fullCount=height(screening.build_candidate_registry(cfg));
        assert(height(candidates)==fullCount&& ...
            height(materials)==double(policy.materialPointCount), ...
            'screening:run_screening:CompleteDesignRequired', ...
            ['The complete screen has %d protocols and %d material points (found %d and %d); ' ...
             'a subset needs ''RequireFullDesign'' false.'],fullCount, ...
            double(policy.materialPointCount),height(candidates),height(materials));
    end
    roots=create_output_tree(outputRoot);
    candidatePath=fullfile(roots.candidate_registry,'protocol_candidates.csv');
    materialPath=fullfile(roots.material_lhs,'material_lhs.csv');
    write_table_once(candidatePath,candidates);
    write_table_once(materialPath,materials);
    utils.atomic_write_json(fullfile(roots.material_lhs, ...
        'material_lhs_metadata.json'),materialMetadata,'AllowReplace',true);

    configuration=struct( ...
        'schema_version','real_extended_stage9b_screening_configuration_v1', ...
        'execution_scope','consume_only_post_s03', ...
        'complete_scientific_design',logical(parser.Results.RequireFullDesign), ...
        'candidate_registry',candidateMetadata, ...
        'material_lhs',materialMetadata, ...
        'screening_policy',policy, ...
        'environment',utils.environment_line(), ...
        'automatic_scientific_selection',false, ...
        'confirmation_action_implemented',true);
    configurationPath=fullfile(roots.configuration, ...
        'screening_configuration.json');
    utils.atomic_write_json(configurationPath,configuration,'AllowReplace',true);

    statusPath=fullfile(roots.status,'screening_status.json');

    progressPath=fullfile(roots.status,'screening_progress.mat');
    inputs=screening.screen_inputs(provider,candidates,materials,policy);
    initialize_or_verify_progress(progressPath,inputs);
    blockSize=max(1,min(double(policy.candidateBatchSize),height(candidates)));
    completed=load(progressPath,'CompletedCandidates');
    resumeCandidateCacheHits=nnz(completed.CompletedCandidates);
    executedCandidateCount=0;
    started=tic;
    for first=1:blockSize:height(candidates)
        block=first:min(first+blockSize-1,height(candidates));
        if all(completed.CompletedCandidates(block)),continue;end
        assert(~any(completed.CompletedCandidates(block)), ...
            'screening:run_screening:PartialBlockCheckpoint', ...
            'The checkpoint %s holds a partly finished block; remove it and run the screen again.', ...
            progressPath);
        [localBlock,execution]=screening.evaluate_local_information( ...
            provider,candidates(block,:),materials,policy);
        publish_progress_block(progressPath,block,localBlock,execution);
        completed.CompletedCandidates(block)=true;
        executedCandidateCount=executedCandidateCount+numel(block);
        fprintf('[screening] %d/%d protocols checkpointed; %.1f seconds in this call.\n', ...
            nnz(completed.CompletedCandidates),height(candidates),toc(started));
    end
    checkpoint=load(progressPath);
    assert(all(checkpoint.CompletedCandidates), ...
        'screening:run_screening:IncompleteCheckpoint', ...
        'The checkpoint %s is incomplete after the last block.',progressPath);
    local=local_from_checkpoint(checkpoint);
    executionTotals=sum(checkpoint.ExecutionCounts,1);
    localInformation=local;
    localInformation.CandidateOrdering=cellstr(string(candidates.CandidateID));
    localInformation.MaterialPointOrdering=cellstr(string(materials.MaterialPointID));
    localInformation.CovarianceCaseOrdering=cellstr(string(policy.covarianceCases));
    localInformation.Inputs=inputs;
    localPath=fullfile(roots.local_information,'local_information.mat');
    utils.atomic_save_struct(localPath,struct( ...
        'localInformation',localInformation),'-v7.3');

    evidence=screening.aggregate_rankings(candidates,local,policy);
    write_evidence(roots,evidence);
    elapsed=toc(started);
    reportPath=fullfile(roots.reports,'screening_report.md');
    consolePath=fullfile(roots.reports,'screening_console.log');
    report=screening_report(configuration,evidence,executionTotals,elapsed);
    utils.atomic_write_text(reportPath,report);
    utils.atomic_write_text(consolePath,report);

    if isfile(progressPath),delete(progressPath);end
    status=struct( ...
        'schema_version','real_extended_stage9b_screening_status_v1', ...
        'action','stage9b_protocol_fim_screening','status','complete', ...
        'candidate_count',height(candidates), ...
        'material_point_count',height(materials), ...
        'covariance_case_count',2, ...
        'candidate_batch_size',blockSize, ...
        'bounded_checkpoint_file_count',1, ...
        'checkpoint_removed_after_success',true, ...
        'resume_candidate_cache_hit_count',resumeCandidateCacheHits, ...
        'executed_candidate_count_this_invocation',executedCandidateCount, ...
        'gp_fit_count',0,'pce_fit_count',0,'audit_fit_count',0, ...
        's03_recomputation_count',0, ...
        'center_mean_evaluation_rows',executionTotals(1), ...
        'perturbation_mean_evaluation_rows',executionTotals(3), ...
        'mean_evaluation_rows',executionTotals(4), ...
        'active_variance_evaluation_rows',executionTotals(2), ...
        'ensemble_evaluator_call_count',executionTotals(5), ...
        'scalar_output_uqlab_call_count',6*executionTotals(5), ...
        'elapsed_seconds',elapsed, ...
        'environment',utils.environment_line(), ...
        'automatic_scientific_selection',false, ...
        'manual_selection_completed',false, ...
        'confirmation_action_implemented',true);
    utils.atomic_write_json(statusPath,status,'AllowReplace',true);
    if parser.Results.RenderFigures
        plotting.saved_screening_figures(outputRoot,cfg);
    end
end

function [tableValue,metadata]=resolve_candidates(cfg,supplied)
    if isempty(supplied)
        [tableValue,metadata]=screening.build_candidate_registry(cfg);
    else
        tableValue=supplied;
        metadata=struct('schema_version', ...
            'stage9b_candidate_registry_metadata_v1', ...
            'regular_grid_count',NaN,'default_rows_requested',1, ...
            'duplicates_removed',NaN, ...
            'unique_candidate_count',height(tableValue), ...
            'duplicate_tolerance',cfg.stage9bScreening.candidateDuplicateTolerance, ...
            'candidate_id_policy','predeclared_fixture_candidate_ids', ...
            'candidate_index_policy','stable_registry_order_never_rank');
    end
end

function [tableValue,metadata]=resolve_materials(cfg,supplied)
    if isempty(supplied)
        [tableValue,metadata]=screening.build_material_lhs(cfg);
    else
        tableValue=supplied;
        metadata=struct('schema_version','stage9b_material_lhs_metadata_v1', ...
            'seed',cfg.stage9bScreening.materialLHSSeed, ...
            'rng_algorithm','twister','implementation','private_fixture_subset', ...
            'parameter_names',{cfg.stage9bScreening.materialParameterNames}, ...
            'bounds',cfg.paramBounds(1:4,:), ...
            'prior_mean',mean(cfg.paramBounds(1:4,:),2).', ...
            'prior_sd',((cfg.paramBounds(1:4,2)- ...
                cfg.paramBounds(1:4,1))/sqrt(12)).', ...
            'prior_covariance_z',eye(4),'row_count',height(tableValue), ...
            'unique_row_count',height(unique(tableValue,'rows')), ...
            'rng_state_restored_by_oncleanup',true);
    end
end

function roots=create_output_tree(root)
    names={'configuration','candidate_registry','material_lhs','validity', ...
        'local_information','aggregate_scores','rankings', ...
        'manual_selection','figures','reports','status'};
    roots=struct();
    for i=1:numel(names)
        roots.(names{i})=fullfile(root,names{i});
        if ~isfolder(roots.(names{i})),mkdir(roots.(names{i}));end
    end
end

function write_table_once(pathValue,value)
    if isfile(pathValue)
        saved=readtable(pathValue,'Delimiter',',','TextType','string');
        assert(tables_semantically_equal(saved,value), ...
            'screening:run_screening:SavedDesignChanged', ...
            ['%s holds another candidate or material design than this screen; continue ' ...
             'a screen only with its own design, or screen into a new folder.'],pathValue);
        return
    end
    utils.atomic_write_table(pathValue,value);
end

function tf=tables_semantically_equal(left,right)
    tf=isequal(left.Properties.VariableNames,right.Properties.VariableNames)&& ...
        height(left)==height(right);
    if ~tf,return;end
    for i=1:width(right)
        a=left.(i);b=right.(i);
        if isnumeric(b)||islogical(b)
            tf=isnumeric(a)||islogical(a);
            if tf
                a=double(a);b=double(b);
                finite=isfinite(a)&isfinite(b);
                scale=max(1,max(abs([a(finite);b(finite)]),[],'all'));
                tolerance=64*eps(scale);
                tf=isequal(size(a),size(b))&& ...
                    all((finite&abs(a-b)<=tolerance)| ...
                    (isnan(a)&isnan(b)),'all');
            end
        else
            tf=isequal(string(a),string(b));
        end
        if ~tf,return;end
    end
end

function initialize_or_verify_progress(pathValue,inputs)
    candidateIDs=cellstr(string(inputs.candidates.CandidateID));
    materialIDs=cellstr(string(inputs.materials.MaterialPointID));
    if isfile(pathValue)
        saved=load(pathValue,'Inputs','CompletedCandidates');
        assert(isfield(saved,'Inputs')&&isequaln(saved.Inputs,inputs), ...
            'screening:run_screening:CheckpointInputs', ...
            ['The checkpoint %s belongs to another screen (model provider, policy, ' ...
             'protocols or material points); remove it or screen into a new folder.'],pathValue);
        return
    end
    nM=height(inputs.materials);nC=height(inputs.candidates);shape=[nM nC 2];
    variables=struct('Inputs',inputs, ...
        'CandidateIDs',{candidateIDs},'MaterialPointIDs',{materialIDs}, ...
        'CovarianceCases',{cellstr(string(inputs.policy.covarianceCases))}, ...
        'CompletedCandidates',false(1,nC), ...
        'TargetProxyLambdaMax',nan(shape), ...
        'TargetVar_m3_e',nan(shape),'TargetVar_log10_k0',nan(shape), ...
        'TargetTrace',nan(shape),'TargetLogDet',nan(shape), ...
        'Cq11',nan(shape),'Cq12',nan(shape),'Cq22',nan(shape), ...
        'FIMMinEigenvalue',nan(shape),'ProxyMinEigenvalue',nan(shape), ...
        'Valid',false(shape),'ValidityCode',zeros(shape,'uint8'), ...
        'StencilNumericCode',zeros(nM,nC,4,'int8'), ...
        'ExecutionCounts',zeros(nC,5),'FiniteDifferenceMetadata',struct());
    utils.atomic_save_struct(pathValue,variables,'-v7.3');
end

function publish_progress_block(pathValue,block,local,execution)
    file=matfile(pathValue,'Writable',true);
    fields={'TargetProxyLambdaMax','TargetVar_m3_e', ...
        'TargetVar_log10_k0','TargetTrace','TargetLogDet','Cq11','Cq12', ...
        'Cq22','FIMMinEigenvalue','ProxyMinEigenvalue','Valid','ValidityCode'};
    for i=1:numel(fields)
        file.(fields{i})(:,block,:)=local.(fields{i});
    end
    file.StencilNumericCode(:,block,:)=int8(local.StencilNumericCode);
    counts=[execution.center_mean_rows execution.center_active_variance_rows ...
        execution.perturbation_mean_rows execution.total_mean_rows ...
        execution.center_evaluator_calls+ ...
            execution.perturbation_mean_evaluator_calls];
    file.ExecutionCounts(block,:)=repmat(counts/numel(block),numel(block),1);
    file.FiniteDifferenceMetadata=local.FiniteDifference;
    file.CompletedCandidates(1,block)=true;
end

function local=local_from_checkpoint(saved)
    fields={'TargetProxyLambdaMax','TargetVar_m3_e', ...
        'TargetVar_log10_k0','TargetTrace','TargetLogDet','Cq11','Cq12', ...
        'Cq22','FIMMinEigenvalue','ProxyMinEigenvalue','Valid','ValidityCode', ...
        'StencilNumericCode'};
    local=struct();
    for i=1:numel(fields),local.(fields{i})=saved.(fields{i});end
    local.SchemaVersion='stage9b_local_information_v2';
    local.CandidateIDs=saved.CandidateIDs;
    local.MaterialPointIDs=saved.MaterialPointIDs;
    local.CovarianceCases=saved.CovarianceCases;
    local.ValidityCodeDefinitions={ ...
        '0=ELIGIBLE','1=OUT_OF_BOUNDS','2=NONFINITE_MEAN', ...
        '3=NONFINITE_VARIANCE','4=NON_PD_COVARIANCE', ...
        '5=INVALID_FINITE_DIFFERENCE','6=NON_PSD_FIM', ...
        '7=NON_PD_COVARIANCE_PROXY'};
    local.FiniteDifference=saved.FiniteDifferenceMetadata;
end

function write_evidence(roots,evidence)
    utils.atomic_write_table(fullfile(roots.validity, ...
        'validity_per_protocol.csv'),evidence.validityPerProtocol);
    utils.atomic_write_json(fullfile(roots.validity,'validity_summary.json'), ...
        evidence.validitySummary,'AllowReplace',true);
    utils.atomic_write_table(fullfile(roots.aggregate_scores, ...
        'aggregate_protocol_scores.csv'),evidence.aggregateScores);
    utils.atomic_write_table(fullfile(roots.aggregate_scores, ...
        'default_relative_metrics.csv'),evidence.defaultRelativeMetrics);
    utils.atomic_write_table(fullfile(roots.aggregate_scores, ...
        'protocol_score_gaps.csv'),evidence.scoreGaps);
    utils.atomic_write_table(fullfile(roots.aggregate_scores, ...
        'ranking_comparison_summary.csv'),evidence.rankingComparisonSummary);
    utils.atomic_write_table(fullfile(roots.aggregate_scores, ...
        'measurement_operational_rank_shifts.csv'),evidence.rankShift);
    utils.atomic_write_table(fullfile(roots.rankings, ...
        'measurement_covariance_ranking.csv'),evidence.measurementRanking);
    utils.atomic_write_table(fullfile(roots.rankings, ...
        'operational_ranking.csv'),evidence.operationalRanking);
    utils.atomic_write_table(fullfile(roots.rankings, ...
        'top10_protocols.csv'),evidence.top10Protocols);
    utils.atomic_write_json(fullfile(roots.rankings, ...
        'operational_rank1_candidate.json'),evidence.operationalRank1, ...
        'AllowReplace',true);
    utils.atomic_write_json(fullfile(roots.manual_selection, ...
        'manual_selection_template.json'),evidence.manualSelectionTemplate, ...
        'AllowReplace',true);
end

function textValue=screening_report(configuration,evidence,counts,elapsed)
    rank1=evidence.operationalRank1;
    textValue=sprintf([ ...
        '# Stage 9B generalized-protocol screening\n\n' ...
        '- Method: local mean-sensitivity FIM approximation\n' ...
        '- Covariance result: local prior-aware covariance proxy\n' ...
        '- Primary metric: mean target proxy lambda_max\n' ...
        '- Operational rank-1 grid candidate: `%s`\n' ...
        '- Candidate count: %d\n' ...
        '- Material-point count: %d\n' ...
        '- Mean evaluation rows: %.0f\n' ...
        '- Active-variance evaluation rows: %.0f\n' ...
        '- Elapsed seconds: %.6f\n' ...
        '- Automatic scientific selection: false\n' ...
        '- Manual selection completed: false\n' ...
        '- Separate confirmation action implemented: true\n'], ...
        rank1.CandidateID, ...
        configuration.candidate_registry.unique_candidate_count, ...
        configuration.material_lhs.row_count,counts(4),counts(2),elapsed);
end

