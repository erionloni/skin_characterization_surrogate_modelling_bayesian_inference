function provider=generalized_provider(cfg,sources)
%GENERALIZED_PROVIDER The approved generalized GP as the model provider of the screening and the confirmation.
%   PROVIDER = screening.generalized_provider(CFG, SOURCES) adapts the approved
%   generalized package bound in CFG (GP ensemble, emulator-variance
%   calibration, dataset contract) for the protocol screening and the
%   confirmation. SOURCES names the recorded dataset result (stage1Result)
%   and calibration application record (application) at their fixed
%   locations in the shipped results; both must be complete. PROVIDER holds
%   the parameter and output contract, the prior, the likelihood constants
%   and the evaluators of the GP (centre with the calibrated emulator
%   variance, mean only, measurement and operational observation
%   variances).
%   Side effects: loads the GP ensemble.

    assert(isstruct(cfg)&&strcmp(cfg.dataMode,'real_extended')&& ...
        cfg.realExtended.packageBound, ...
        'screening:generalized_provider:Context', ...
        'The provider binds the approved generalized package (generalized route).');
    stage1Path=sources.stage1Result;
    applicationPath=sources.application;
    required={stage1Path,applicationPath,cfg.files.gp};
    missing=required(~cellfun(@isfile,required));
    assert(isempty(missing), ...
        'screening:generalized_provider:FrozenArtifacts', ...
        ['The model provider needs the records of the approved generalized ' ...
         'package; missing: %s.'],strjoin(missing,', '));
    stage1=jsondecode(fileread(stage1Path));
    application=jsondecode(fileread(applicationPath));
    assert(strcmp(char(string(stage1.status)),'STAGE1_COMPLETE')&& ...
        strcmp(char(string(application.status)),'complete'), ...
        'screening:generalized_provider:FrozenStatus', ...
        ['The dataset result and the calibration application record of the ' ...
         'approved package must be complete.']);

    gp=surrogates.load_ensemble(cfg.files.gp,'gp');
    modelData=utils.load_plain_mat(cfg.files.dataset,'developmentCaseIDsAll', ...
        'developmentOutputAvailabilityMask');
    surrogates.validate_surrogate_ensemble_scope(gp,modelData,cfg,'gp');

    materialNames=cellstr(string(cfg.stage9bScreening.materialParameterNames));
    allNames=cellstr(string(cfg.realExtended.learningInputNames));
    [present,materialIndices]=ismember(materialNames,allNames);
    targetNames=cellstr(string(cfg.stage9bScreening.targetParameterNames));
    [targetPresent,targetIndices]=ismember(targetNames,materialNames);
    assert(all(present)&&isequal(materialIndices,1:4)&& ...
        all(targetPresent)&&numel(unique(targetIndices))==2, ...
        'screening:generalized_provider:ParameterContract', ...
        ['The screening''s material parameters must be the first four inputs ' ...
         'of the generalized route, and its two target parameters two of them.']);
    materialBounds=double(cfg.realExtended.learningBounds(materialIndices,:));
    priorMean=mean(materialBounds,2).';
    priorSD=(materialBounds(:,2)-materialBounds(:,1)).'/sqrt(12);
    outputNames=cellstr(string(cfg.realExtended.outputNames));
    assert(numel(allNames)==7&&numel(outputNames)==6&& ...
        isequal(allNames,cellstr(string(gp.inputNames)))&& ...
        isequal(outputNames,cellstr(string(gp.outputNames))), ...
        'screening:generalized_provider:SurrogateContract', ...
        'The approved GP does not have the route''s seven inputs and six outputs in order.');

    provider=struct( ...
        'schemaVersion','real_extended_stage9b_provider_v1', ...
        'route','real_extended', ...
        'inputNames',{allNames},'outputNames',{outputNames}, ...
        'materialParameterNames',{materialNames}, ...
        'protocolParameterNames',{cellstr(string( ...
            cfg.stage9bScreening.protocolParameterNames))}, ...
        'materialBounds',materialBounds,'priorMean',priorMean, ...
        'priorSD',priorSD,'priorCovarianceZ',eye(4), ...
        'targetParameterNames',{targetNames},'targetIndices',targetIndices, ...
        'measurementCV',double(cfg.meas_cv), ...
        'numericalFloorSD',double(cfg.likelihood.minSigma), ...
        'numericalFloorVariance',double(cfg.likelihood.minSigma)^2, ...
        'gp',gp,'cfg',cfg, ...
        'evaluateCenter',@(X)evaluate_center(gp,X,cfg,allNames), ...
        'evaluateMean',@(X)evaluate_mean(gp,X,allNames,outputNames,cfg), ...
        'measurementVariance',@(mu)observation_variance( ...
            mu,zeros(size(mu)),cfg), ...
        'operationalVariance',@(mu,emu)observation_variance(mu,emu,cfg));
end

function prediction=evaluate_center(gp,X,cfg,inputNames)
    validateattributes(X,{'numeric'},{'2d','real','finite', ...
        'ncols',numel(inputNames)});
    prediction=surrogates.evaluate_generalized_gp(gp,double(X),cfg);
end

function meanPrediction=evaluate_mean(gp,X,inputNames,outputNames,cfg)
    validateattributes(X,{'numeric'},{'2d','real','finite', ...
        'ncols',numel(inputNames)});
    % Points per GP call (settings 0.3).
    meanPrediction=surrogates.evaluate(gp,double(X),'gp_mean',cfg.realExtended.predictionBatchSize);
    assert(isequal(size(meanPrediction),[size(X,1) numel(outputNames)])&& ...
        all(isfinite(meanPrediction),'all'), ...
        'screening:generalized_provider:MeanEvaluation', ...
        'The GP mean prediction has the wrong size or non-finite values.');
end

function variance=observation_variance(mu,emulatorVariance,cfg)
    opts=struct('uncertaintyMode','measurement_plus_gp', ...
        'measurementCV',cfg.meas_cv);
    variance=inversion.raw_observation_variance( ...
        mu,emulatorVariance,cfg,opts,1:6);
end

