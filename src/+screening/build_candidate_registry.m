function [registry,metadata]=build_candidate_registry(cfg)
%BUILD_CANDIDATE_REGISTRY The candidate protocols of the screen.
%   [REGISTRY, METADATA] = screening.build_candidate_registry(CFG) returns the
%   bounded grid of protocols (loading rate as log10 of its absolute value,
%   hold and pause times in seconds; CFG.stage9bScreening) with one row
%   per protocol: CandidateID (P001 to P729 for the grid in registry order;
%   default for the default protocol) and its index, the three protocol
%   inputs, IsDefault, and whether each input lies on a boundary of its
%   range. METADATA counts the grid and its boundary protocols.
%   Side effects: none.

    assert(isstruct(cfg)&&strcmp(cfg.dataMode,'real_extended')&& ...
        isfield(cfg,'stage9bScreening')&& ...
        isfield(cfg,'realExtended'), ...
        'screening:build_candidate_registry:Configuration', ...
        ['The candidate registry needs the generalized-route configuration with ' ...
         'stage9bScreening and realExtended.']);
    policy=cfg.stage9bScreening;
    n=double(policy.protocolLevelCount);
    assert(n>=2&&n==fix(n)&&isequal(size(policy.protocolBounds),[3 2]), ...
        'screening:build_candidate_registry:GridPolicy', ...
        ['The screening grid needs at least 2 levels per protocol variable (settings B.6) ' ...
         'and bounds for the three variables (3 x 2).']);
    tolerance=double(policy.candidateDuplicateTolerance);
    bounds=double(policy.protocolBounds);

    logRate=linspace(bounds(1,1),bounds(1,2),n);
    hold=linspace(bounds(2,1),bounds(2,2),n);
    pause=linspace(bounds(3,1),bounds(3,2),n);
    [R,H,P]=ndgrid(logRate,hold,pause);
    coordinates=[R(:) H(:) P(:)];
    isDefault=false(size(coordinates,1),1);
    default=[double(policy.defaultProtocol.log10_abs_suction_rate) ...
        double(policy.defaultProtocol.hold_dur_s) ...
        double(policy.defaultProtocol.pause_dur_s)];
    coordinates(end+1,:)=default;
    isDefault(end+1)=true;
    [coordinates,isDefault,duplicateCount]=stable_unique( ...
        coordinates,isDefault,tolerance);
    % n^3 grid protocols and the default (thesis: 9 levels, 730 candidates);
    % a default on the grid is kept once.
    assert(size(coordinates,1)==n^3+1-duplicateCount, ...
        'screening:build_candidate_registry:GridCount', ...
        'The grid of %d levels resolved to %d candidates.',n,size(coordinates,1));

    magnitude=10.^coordinates(:,1);
    signedRate=-magnitude;
    lower=bounds(:,1).';upper=bounds(:,2).';
    scale=max(1,max(abs(bounds),[],2).');
    boundary=abs(coordinates-lower)<=tolerance.*scale| ...
        abs(coordinates-upper)<=tolerance.*scale;
    within=all(coordinates>=lower-tolerance.*scale& ...
        coordinates<=upper+tolerance.*scale,2);
    assert(all(within), ...
        'screening:build_candidate_registry:ResolvedRegistry', ...
        'The candidate protocols must lie inside the configured bounds.');

    candidateIndex=(1:size(coordinates,1)).';
    candidateID=compose("P%03d",candidateIndex);
    candidateID(isDefault)="default";
    registry=table(candidateID,candidateIndex,signedRate,magnitude, ...
        coordinates(:,1),coordinates(:,2),coordinates(:,3),isDefault, ...
        boundary(:,1),boundary(:,2),boundary(:,3),any(boundary,2),within, ...
        'VariableNames',{'CandidateID','CandidateIndex', ...
        'SignedRate_kPa_s','RateMagnitude_kPa_s','Log10AbsRate', ...
        'Hold_s','Pause_s','IsDefault','IsRateBoundary', ...
        'IsHoldBoundary','IsPauseBoundary','IsAnyProtocolBoundary', ...
        'WithinConfiguredBounds'});
    metadata=struct( ...
        'schema_version','stage9b_candidate_registry_metadata_v1', ...
        'regular_grid_count',n^3, ...
        'default_rows_requested',1,'duplicates_removed',duplicateCount, ...
        'unique_candidate_count',height(registry), ...
        'duplicate_tolerance',tolerance, ...
        'candidate_id_policy','P_and_registry_index_default_named_default', ...
        'candidate_index_policy','stable_registry_order_never_rank', ...
        'log10_abs_rate_levels',logRate,'rate_magnitude_levels',10.^logRate, ...
        'hold_levels_s',hold,'pause_levels_s',pause, ...
        'rate_boundary_count',nnz(registry.IsRateBoundary), ...
        'hold_boundary_count',nnz(registry.IsHoldBoundary), ...
        'pause_boundary_count',nnz(registry.IsPauseBoundary), ...
        'any_boundary_count',nnz(registry.IsAnyProtocolBoundary));
end

function [uniqueCoordinates,uniqueDefault,duplicateCount]=stable_unique( ...
        coordinates,isDefault,tolerance)
    keep=false(size(coordinates,1),1);
    uniqueCoordinates=zeros(0,size(coordinates,2));
    uniqueDefault=false(0,1);
    duplicateCount=0;
    for i=1:size(coordinates,1)
        hit=0;
        for j=1:size(uniqueCoordinates,1)
            scale=max(1,max(abs([coordinates(i,:);uniqueCoordinates(j,:)]), ...
                [],1));
            if all(abs(coordinates(i,:)-uniqueCoordinates(j,:))<= ...
                    tolerance.*scale)
                hit=j;break
            end
        end
        if hit==0
            keep(i)=true;
            uniqueCoordinates(end+1,:)=coordinates(i,:); %#ok<AGROW>
            uniqueDefault(end+1,1)=isDefault(i); %#ok<AGROW>
        else
            duplicateCount=duplicateCount+1;
            if isDefault(i)
                % A future tolerance-equal grid row keeps exact defaults.
                uniqueCoordinates(hit,:)=coordinates(i,:);
                uniqueDefault(hit)=true;
            end
        end
    end
    assert(nnz(keep)==size(uniqueCoordinates,1), ...
        'screening:build_candidate_registry:StableUnique', ...
        'Internal error: the distinct candidate protocols were not kept exactly once.');
end
