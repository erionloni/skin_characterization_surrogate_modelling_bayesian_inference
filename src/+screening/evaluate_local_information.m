function [local,execution]=evaluate_local_information( ...
        provider,candidates,materials,policy,varargin)
%EVALUATE_LOCAL_INFORMATION The local Fisher-information proxy of every protocol at every material point.
%   [LOCAL, EXECUTION] = screening.evaluate_local_information(PROVIDER,
%   CANDIDATES, MATERIALS, POLICY, ...) differentiates the six closing
%   pressures of the approved GP (PROVIDER, screening.generalized_provider)
%   with respect to the four material parameters at every material point
%   (MATERIALS) and protocol (CANDIDATES), in one batched evaluation per
%   finite-difference stencil (POLICY: steps and covariance views), and
%   combines each Jacobian with the observation covariance of each view
%   (measurement; operational: measurement plus emulator) and the prior
%   into a local posterior-covariance proxy in prior-standard-deviation
%   coordinates. LOCAL: per material, protocol and view the weak-pair
%   proxy's largest eigenvalue and its entries, the target variances,
%   trace and log determinant, the smallest eigenvalues, validity codes;
%   with 'RetainFullCovariance' true also the full 4-by-4 covariances and
%   the four marginal variances. 'Outputs' (default 1:6, the six pressures
%   of the screen) selects the pressures that the information sums over (an
%   observation design: d2_only 1:3); the observation covariance is
%   diagonal, so the information of a subset is the sum over its pressures.
%   EXECUTION counts the evaluator calls.
%   Side effects: none.
%   Computation: seconds per block of protocols (GP predictions).

    parser=inputParser;
    addParameter(parser,'RetainFullCovariance',false, ...
        @(x)islogical(x)&&isscalar(x));
    addParameter(parser,'Outputs',1:6,@(x)isnumeric(x)&&~isempty(x)&& ...
        all(x>=1&x<=6&x==fix(x))&&numel(unique(x))==numel(x));
    parse(parser,varargin{:});
    retainFull=parser.Results.RetainFullCovariance;
    outputs=reshape(double(parser.Results.Outputs),1,[]);

    assert(isstruct(provider)&&istable(candidates)&&istable(materials)&& ...
        isstruct(policy)&&height(candidates)>0&&height(materials)>0, ...
        'screening:evaluate_local_information:Inputs', ...
        ['The inputs must be the provider, non-empty candidate and material tables ' ...
         'and the screening policy.']);
    requiredCandidates={'CandidateID','CandidateIndex','Log10AbsRate', ...
        'Hold_s','Pause_s','WithinConfiguredBounds'};
    requiredMaterials={'MaterialPointID','m3_f_RD','m3_e_RD', ...
        'log10_k0_RD','Thickness_RD'};
    assert(all(ismember(requiredCandidates,candidates.Properties.VariableNames))&& ...
        all(ismember(requiredMaterials,materials.Properties.VariableNames)), ...
        'screening:evaluate_local_information:TableSchema', ...
        ['The candidate table needs the columns %s and the material table the ' ...
         'columns %s.'],strjoin(requiredCandidates,', '),strjoin(requiredMaterials,', '));
    covarianceCases=cellstr(string(policy.covarianceCases));
    assert(isequal(covarianceCases,{'measurement_covariance', ...
        'operational_measurement_plus_emulator'}), ...
        'screening:evaluate_local_information:CovarianceCases', ...
        ['The screening policy must list the covariance cases measurement_covariance ' ...
         'and operational_measurement_plus_emulator, in this order.']);
    nMaterial=height(materials);nCandidate=height(candidates);nCase=2;
    theta=[materials.m3_f_RD materials.m3_e_RD ...
        materials.log10_k0_RD materials.Thickness_RD];
    bounds=double(provider.materialBounds);
    unit=(theta-bounds(:,1).')./(bounds(:,2)-bounds(:,1)).';
    unitRows=repmat(unit,nCandidate,1);
    thetaRows=repmat(theta,nCandidate,1);
    protocol=reshape([candidates.Log10AbsRate candidates.Hold_s ...
        candidates.Pause_s].',3,[]);
    protocolRows=kron(protocol.',ones(nMaterial,1));
    centerInput=[thetaRows protocolRows];
    within=all(centerInput>=provider.cfg.realExtended.learningBounds(:,1).'- ...
        policy.comparisonTolerance&centerInput<= ...
        provider.cfg.realExtended.learningBounds(:,2).'+ ...
        policy.comparisonTolerance,2)& ...
        repelem(logical(candidates.WithinConfiguredBounds),nMaterial);

    prediction=provider.evaluateCenter(centerInput);
    centerMean=double(prediction.GPMean);
    emulatorVariance=double(prediction.CalibratedEmulatorVariance);
    % The evaluation uses the provider's model and calibration.
    meanForward=@(u)evaluate_perturbation_mean( ...
        provider,u,protocolRows,bounds);
    derivative=design_study.finite_difference_jacobian( ...
        meanForward,unitRows,double(policy.finiteDifferenceStepUnitBox), ...
        'PrimaryStepOnly',true,'CenterValues',centerMean);
    jacobianZ=double(derivative.matrixByPoint)/sqrt(12);
    assert(isequal(size(jacobianZ),[6 4 nMaterial*nCandidate]), ...
        'screening:evaluate_local_information:JacobianShape', ...
        'Internal error: the Jacobians must be 6 x 4 x %d.',nMaterial*nCandidate);

    measurementVariance=provider.measurementVariance(centerMean);
    operationalVariance=provider.operationalVariance( ...
        centerMean,emulatorVariance);
    varianceByCase=cat(3,measurementVariance,operationalVariance);
    shape=[nMaterial nCandidate nCase];
    fields={'TargetProxyLambdaMax','TargetVar_m3_e', ...
        'TargetVar_log10_k0','TargetTrace','TargetLogDet', ...
        'Cq11','Cq12','Cq22','FIMMinEigenvalue', ...
        'ProxyMinEigenvalue'};
    for f=1:numel(fields),local.(fields{f})=nan(shape);end
    if retainFull
        local.FullCovariance=nan(4,4,nMaterial,nCandidate,nCase);
        local.MarginalVariances=nan(nMaterial,nCandidate,nCase,4);
    end
    local.Valid=false(shape);
    local.ValidityCode=zeros(shape,'uint8');
    local.StencilNumericCode=reshape(permute( ...
        derivative.stencilNumericCodeByPoint,[1 3 2]), ...
        nMaterial,nCandidate,4);
    target=double(provider.targetIndices);
    assert(isequal(target,[2 3]), ...
        'screening:evaluate_local_information:TargetOrder', ...
        'The provider''s target parameters must be parameters 2 and 3 (m3_e_RD, log10_k0_RD).');
    tolerance=double(policy.psdTolerance);
    symmetryTolerance=double(policy.symmetryTolerance);
    for candidate=1:nCandidate
        for material=1:nMaterial
            flat=(candidate-1)*nMaterial+material;
            if ~within(flat)
                local.ValidityCode(material,candidate,:)=1;continue
            end
            if any(~isfinite(centerMean(flat,:)))
                local.ValidityCode(material,candidate,:)=2;continue
            end
            if any(~isfinite(emulatorVariance(flat,:)))|| ...
                    any(emulatorVariance(flat,:)<0)
                local.ValidityCode(material,candidate,:)=3;continue
            end
            J=squeeze(jacobianZ(:,:,flat));
            if ~isequal(size(J),[6 4])||any(~isfinite(J(outputs,:)),'all')
                local.ValidityCode(material,candidate,:)=5;continue
            end
            J=J(outputs,:);
            for covarianceCase=1:nCase
                variances=varianceByCase(flat,outputs,covarianceCase);
                if any(~isfinite(variances))||any(variances<=0)
                    local.ValidityCode(material,candidate,covarianceCase)=4;
                    continue
                end
                covariance=diag(variances);
                symmetryError=norm(covariance-covariance.','fro')/ ...
                    max(norm(covariance,'fro'),eps);
                [L,covarianceFlag]=chol((covariance+covariance.')/2,'lower');
                if symmetryError>symmetryTolerance||covarianceFlag~=0
                    local.ValidityCode(material,candidate,covarianceCase)=4;
                    continue
                end
                white=L\J;
                F=white.'*white;F=(F+F.')/2;
                fimEigen=eig(F);fimScale=max(1,max(abs(fimEigen)));
                if any(~isfinite(F),'all')||min(fimEigen)<-tolerance*fimScale
                    local.ValidityCode(material,candidate,covarianceCase)=6;
                    continue
                end
                precision=eye(4)+F;
                [R,proxyFlag]=chol((precision+precision.')/2,'lower');
                if proxyFlag~=0
                    local.ValidityCode(material,candidate,covarianceCase)=7;
                    continue
                end
                proxy=R.'\(R\eye(4));proxy=(proxy+proxy.')/2;
                proxyEigen=eig(proxy);
                if any(~isfinite(proxy),'all')||min(proxyEigen)<=0|| ...
                        max(proxyEigen)>1+tolerance
                    local.ValidityCode(material,candidate,covarianceCase)=7;
                    continue
                end
                targetBlock=proxy(target,target);targetBlock= ...
                    (targetBlock+targetBlock.')/2;
                if retainFull
                    local.FullCovariance(:,:,material,candidate,covarianceCase)=proxy;
                    local.MarginalVariances(material,candidate,covarianceCase,:)=diag(proxy);
                end
                targetEigen=eig(targetBlock);
                local.TargetProxyLambdaMax(material,candidate,covarianceCase)= ...
                    max(targetEigen);
                local.TargetVar_m3_e(material,candidate,covarianceCase)= ...
                    targetBlock(1,1);
                local.TargetVar_log10_k0(material,candidate,covarianceCase)= ...
                    targetBlock(2,2);
                local.TargetTrace(material,candidate,covarianceCase)= ...
                    trace(targetBlock);
                local.TargetLogDet(material,candidate,covarianceCase)= ...
                    design_study.logdet_spd(targetBlock);
                local.Cq11(material,candidate,covarianceCase)=targetBlock(1,1);
                local.Cq12(material,candidate,covarianceCase)=targetBlock(1,2);
                local.Cq22(material,candidate,covarianceCase)=targetBlock(2,2);
                local.FIMMinEigenvalue(material,candidate,covarianceCase)= ...
                    min(fimEigen);
                local.ProxyMinEigenvalue(material,candidate,covarianceCase)= ...
                    min(proxyEigen);
                local.Valid(material,candidate,covarianceCase)=true;
            end
        end
    end
    local.SchemaVersion='stage9b_local_information_block_v1';
    if retainFull
        local.SchemaVersion='stage9b_local_information_block_v2';
        local.CovarianceParameterOrder=provider.materialParameterNames;
        local.CovarianceCoordinates='prior_SD_standardized_material';
    end
    local.CandidateIDs=cellstr(string(candidates.CandidateID));
    local.MaterialPointIDs=cellstr(string(materials.MaterialPointID));
    local.CovarianceCases=covarianceCases;
    local.ValidityCodeDefinitions={ ...
        '0=ELIGIBLE','1=OUT_OF_BOUNDS','2=NONFINITE_MEAN', ...
        '3=NONFINITE_VARIANCE','4=NON_PD_COVARIANCE', ...
        '5=INVALID_FINITE_DIFFERENCE','6=NON_PSD_FIM', ...
        '7=NON_PD_COVARIANCE_PROXY'};
    local.FiniteDifference=rmfield(derivative,intersect( ...
        fieldnames(derivative),{'matrix','rawMatrix','matrixByPoint', ...
        'rawMatrixByPoint','centerValues','stencilCodeByPoint', ...
        'centralOrOneSidedByPoint','stencilNumericCodeByPoint'}));
    local.FiniteDifference.FiniteDifferenceCoordinateSystem= ...
        derivative.parameterCoordinateSystem;
    local.FiniteDifference.PrimaryStepInHelperCoordinates= ...
        double(policy.finiteDifferenceStepUnitBox);
    local.FiniteDifference.CentralOrOneSidedPerParameter= ...
        ['localInformation.StencilNumericCode: 0=central, ' ...
         '+1=forward, -1=backward'];
    local.FiniteDifference.BoundaryHandlingPolicy= ...
        derivative.boundaryHandlingPolicy;
    local.FiniteDifference.JacobianConversionToPriorSD='J_z=J_u/sqrt(12)';
    local.FiniteDifference.EquivalentPhysicalStepPerParameter= ...
        double(policy.finiteDifferenceStepUnitBox).* ...
        (bounds(:,2)-bounds(:,1)).';
    local.FiniteDifference.EquivalentPriorSDStepPerParameter= ...
        sqrt(12)*double(policy.finiteDifferenceStepUnitBox)*ones(1,4);
    execution=struct( ...
        'schema_version','stage9b_local_execution_count_v1', ...
        'candidate_count',nCandidate,'material_count',nMaterial, ...
        'center_mean_rows',nMaterial*nCandidate, ...
        'center_active_variance_rows',nMaterial*nCandidate, ...
        'perturbation_mean_rows',derivative.perturbationRowsEvaluated, ...
        'total_mean_rows',nMaterial*nCandidate+ ...
            derivative.perturbationRowsEvaluated, ...
        'center_evaluator_calls',1, ...
        'perturbation_mean_evaluator_calls', ...
            derivative.perturbationForwardCallCount, ...
        'covariance_case_count',nCase);
end

function meanPrediction=evaluate_perturbation_mean( ...
        provider,unitCoordinates,baseProtocol,bounds)
    nBase=size(baseProtocol,1);
    assert(mod(size(unitCoordinates,1),nBase)==0, ...
        'screening:evaluate_local_information:PerturbationBatch', ...
        'Internal error: the perturbed points are not a whole number of protocol batches.');
    repeats=size(unitCoordinates,1)/nBase;
    theta=bounds(:,1).'+unitCoordinates.* ...
        (bounds(:,2)-bounds(:,1)).';
    protocol=repmat(baseProtocol,repeats,1);
    meanPrediction=provider.evaluateMean([theta protocol]);
end
