function evidence=aggregate_rankings(candidates,local,policy)
%AGGREGATE_RANKINGS The rankings of the protocol screen.
%   EVIDENCE = screening.aggregate_rankings(CANDIDATES, LOCAL, POLICY) ranks
%   the candidate protocols by the mean largest
%   eigenvalue of the weak-pair proxy covariance over the complete material
%   cohort, in the measurement and the operational covariance view
%   (LOCAL, screening.evaluate_local_information), and returns the
%   rankings, the top-10 protocols, the score gaps, the comparison of the
%   two views and the rank shifts between them, the operational rank-1
%   protocol and the template for the manual objective selection.
%   Side effects: none.

    assert(istable(candidates)&&isstruct(local)&&isstruct(policy), ...
        'screening:aggregate_rankings:Inputs', ...
        'The inputs must be the candidate table, the local information and the policy.');
    nCandidate=height(candidates);nMaterial=size(local.Valid,1);
    covarianceCases=cellstr(string(local.CovarianceCases));
    assert(size(local.Valid,2)==nCandidate&&size(local.Valid,3)==2&& ...
        isequal(covarianceCases,cellstr(string(policy.covarianceCases))), ...
        'screening:aggregate_rankings:Dimensions', ...
        ['The local information must cover the %d candidates and the two covariance ' ...
         'cases of the policy.'],nCandidate);
    defaultIndex=find(candidates.IsDefault);
    assert(isscalar(defaultIndex), ...
        'screening:aggregate_rankings:DefaultCandidate', ...
        'The candidate table must mark exactly one default protocol; it marks %d.', ...
        numel(defaultIndex));
    tolerance=double(policy.comparisonTolerance);

    anyFailure=squeeze(any(~local.Valid,3));
    failedMaterialCount=sum(anyFailure,1).';
    failureCount=squeeze(sum(sum(~local.Valid,1),3)).';
    eligible=failedMaterialCount==0;
    assert(eligible(defaultIndex), ...
        'screening:aggregate_rankings:InvalidDefaultCandidate', ...
        ['The exact default protocol must be computationally valid on the ' ...
         'complete declared material cohort for default-relative evidence.']);
    validityStatus=repmat("ELIGIBLE",nCandidate,1);
    validityReasons=strings(nCandidate,1);
    for candidate=1:nCandidate
        if eligible(candidate),continue;end
        codes=unique(reshape(local.ValidityCode(:,candidate,:),[],1));
        codes=codes(codes~=0);
        labels=arrayfun(@validity_label,double(codes), ...
            'UniformOutput',false);
        validityReasons(candidate)=strjoin(string(labels),' | ');
        validityStatus(candidate)="COMPUTATIONALLY_INVALID";
    end
    validityPerProtocol=table(candidates.CandidateID, ...
        candidates.CandidateIndex,validityStatus,failedMaterialCount, ...
        failureCount,repmat(nMaterial,nCandidate,1),validityReasons, ...
        'VariableNames',{'CandidateID','CandidateIndex','ValidityStatus', ...
        'FailedMaterialPointCount','FailureCountAcrossCovarianceCases', ...
        'RequiredMaterialPointCount','FailureReasons'});

    rowCount=nCandidate*numel(covarianceCases);
    aggregate=table('Size',[rowCount 21], ...
        'VariableTypes',{'string','double','string','double','double','double', ...
        'double','double','double','double','double','double','double', ...
        'double','double','double','double','double','double','string', ...
        'double'}, ...
        'VariableNames',{'CandidateID','CandidateIndex','CovarianceCase', ...
        'MeanTargetProxyLambdaMax','MeanTargetVar_m3_e', ...
        'MeanTargetVar_log10_k0','MeanTargetTrace','MeanTargetLogDet', ...
        'Q90TargetProxyLambdaMax','MeanTargetCovariance_C11', ...
        'MeanTargetCovariance_C12','MeanTargetCovariance_C22', ...
        'LambdaMaxOfMeanTargetCovariance','FractionBothImproved', ...
        'FractionBothNearEqual','FractionBothWorseOrMixed', ...
        'DeltaPrimaryScore','RelativePrimaryImprovement', ...
        'AggregateWorstDirectionSDImprovement','ValidityStatus', ...
        'ValidMaterialPointCount'});
    cursor=0;
    for covarianceCase=1:numel(covarianceCases)
        defaultVariance1=local.TargetVar_m3_e(:,defaultIndex,covarianceCase);
        defaultVariance2=local.TargetVar_log10_k0(:,defaultIndex,covarianceCase);
        defaultScore=NaN;
        if eligible(defaultIndex)
            defaultScore=mean(local.TargetProxyLambdaMax( ...
                :,defaultIndex,covarianceCase));
        end
        for candidate=1:nCandidate
            cursor=cursor+1;
            aggregate.CandidateID(cursor)=string(candidates.CandidateID(candidate));
            aggregate.CandidateIndex(cursor)=candidates.CandidateIndex(candidate);
            aggregate.CovarianceCase(cursor)=string(covarianceCases{covarianceCase});
            aggregate.ValidityStatus(cursor)=validityStatus(candidate);
            aggregate.ValidMaterialPointCount(cursor)=sum( ...
                local.Valid(:,candidate,covarianceCase));
            if ~eligible(candidate),continue;end
            lambda=local.TargetProxyLambdaMax(:,candidate,covarianceCase);
            variance1=local.TargetVar_m3_e(:,candidate,covarianceCase);
            variance2=local.TargetVar_log10_k0(:,candidate,covarianceCase);
            covarianceComponents=[ ...
                mean(local.Cq11(:,candidate,covarianceCase)) ...
                mean(local.Cq12(:,candidate,covarianceCase)) ...
                mean(local.Cq22(:,candidate,covarianceCase))];
            meanTarget=[covarianceComponents(1) covarianceComponents(2); ...
                covarianceComponents(2) covarianceComponents(3)];
            aggregate.MeanTargetProxyLambdaMax(cursor)=mean(lambda);
            aggregate.MeanTargetVar_m3_e(cursor)=mean(variance1);
            aggregate.MeanTargetVar_log10_k0(cursor)=mean(variance2);
            aggregate.MeanTargetTrace(cursor)=mean( ...
                local.TargetTrace(:,candidate,covarianceCase));
            aggregate.MeanTargetLogDet(cursor)=mean( ...
                local.TargetLogDet(:,candidate,covarianceCase));
            aggregate.Q90TargetProxyLambdaMax(cursor)= ...
                quantile(lambda,0.90);
            aggregate.MeanTargetCovariance_C11(cursor)=covarianceComponents(1);
            aggregate.MeanTargetCovariance_C12(cursor)=covarianceComponents(2);
            aggregate.MeanTargetCovariance_C22(cursor)=covarianceComponents(3);
            aggregate.LambdaMaxOfMeanTargetCovariance(cursor)= ...
                max(eig((meanTarget+meanTarget.')/2));
            scale1=max(1,max(abs([variance1 defaultVariance1]),[],2));
            scale2=max(1,max(abs([variance2 defaultVariance2]),[],2));
            improved=variance1<defaultVariance1-tolerance.*scale1& ...
                variance2<defaultVariance2-tolerance.*scale2;
            near=abs(variance1-defaultVariance1)<=tolerance.*scale1& ...
                abs(variance2-defaultVariance2)<=tolerance.*scale2;
            aggregate.FractionBothImproved(cursor)=mean(improved);
            aggregate.FractionBothNearEqual(cursor)=mean(near);
            aggregate.FractionBothWorseOrMixed(cursor)=mean(~improved&~near);
            score=aggregate.MeanTargetProxyLambdaMax(cursor);
            aggregate.DeltaPrimaryScore(cursor)=score-defaultScore;
            if isfinite(defaultScore)&&defaultScore>0
                aggregate.RelativePrimaryImprovement(cursor)= ...
                    (defaultScore-score)/defaultScore;
                aggregate.AggregateWorstDirectionSDImprovement(cursor)= ...
                    1-sqrt(score/defaultScore);
            end
            if candidate==defaultIndex
                aggregate.DeltaPrimaryScore(cursor)=0;
                aggregate.RelativePrimaryImprovement(cursor)=0;
                aggregate.AggregateWorstDirectionSDImprovement(cursor)=0;
            end
        end
    end

    measurement=ranking_for(aggregate,candidates,covarianceCases{1});
    operational=ranking_for(aggregate,candidates,covarianceCases{2});
    top10=[top_rows(measurement,10);top_rows(operational,10)];
    gaps=[score_gaps(measurement);score_gaps(operational)];
    defaultRelative=aggregate(:,{'CandidateID','CandidateIndex', ...
        'CovarianceCase','DeltaPrimaryScore','RelativePrimaryImprovement', ...
        'AggregateWorstDirectionSDImprovement','FractionBothImproved', ...
        'FractionBothNearEqual','FractionBothWorseOrMixed', ...
        'ValidityStatus'});
    [comparisonSummary,rankShift]=screening.ranking_comparison(measurement,operational);

    validitySummary=struct( ...
        'schema_version','stage9b_validity_summary_v1', ...
        'candidate_count',nCandidate,'material_point_count',nMaterial, ...
        'eligible_candidate_count',nnz(eligible), ...
        'computationally_invalid_candidate_count',nnz(~eligible), ...
        'candidate_complete_policy', ...
            'any_failed_tissue_invalidates_candidate_for_primary_ranking', ...
        'individual_tissue_rows_dropped',false);
    rank1=first_valid(operational);
    rank1Record=struct( ...
        'schema_version','stage9b_operational_rank1_candidate_v1', ...
        'record_role','factual_operational_rank1_not_scientific_selection', ...
        'CandidateID',char(rank1.CandidateID), ...
        'OperationalRank',double(rank1.Rank), ...
        'SignedRate_kPa_s',double(rank1.SignedRate_kPa_s), ...
        'RateMagnitude_kPa_s',double(rank1.RateMagnitude_kPa_s), ...
        'Log10AbsRate',double(rank1.Log10AbsRate), ...
        'Hold_s',double(rank1.Hold_s),'Pause_s',double(rank1.Pause_s), ...
        'MeanTargetProxyLambdaMax',double(rank1.MeanTargetProxyLambdaMax), ...
        'DeltaPrimaryScore',double(rank1.DeltaPrimaryScore), ...
        'RelativePrimaryImprovement',double(rank1.RelativePrimaryImprovement), ...
        'AggregateWorstDirectionSDImprovement', ...
            double(rank1.AggregateWorstDirectionSDImprovement), ...
        'MeanTargetVar_m3_e',double(rank1.MeanTargetVar_m3_e), ...
        'MeanTargetVar_log10_k0',double(rank1.MeanTargetVar_log10_k0), ...
        'MeanTargetTrace',double(rank1.MeanTargetTrace), ...
        'MeanTargetLogDet',double(rank1.MeanTargetLogDet), ...
        'Q90TargetProxyLambdaMax',double(rank1.Q90TargetProxyLambdaMax), ...
        'MeanTargetCovariance_C11',double(rank1.MeanTargetCovariance_C11), ...
        'MeanTargetCovariance_C12',double(rank1.MeanTargetCovariance_C12), ...
        'MeanTargetCovariance_C22',double(rank1.MeanTargetCovariance_C22), ...
        'LambdaMaxOfMeanTargetCovariance', ...
            double(rank1.LambdaMaxOfMeanTargetCovariance), ...
        'FractionBothImproved',double(rank1.FractionBothImproved), ...
        'FractionBothNearEqual',double(rank1.FractionBothNearEqual), ...
        'FractionBothWorseOrMixed',double(rank1.FractionBothWorseOrMixed), ...
        'IsDefault',logical(rank1.IsDefault), ...
        'IsRateBoundary',logical(rank1.IsRateBoundary), ...
        'IsHoldBoundary',logical(rank1.IsHoldBoundary), ...
        'IsPauseBoundary',logical(rank1.IsPauseBoundary), ...
        'IsAnyProtocolBoundary',logical(rank1.IsAnyProtocolBoundary), ...
        'ValidityStatus',char(string(rank1.ValidityStatus)));
    manualTemplate=struct( ...
        'schema_version','stage9b_manual_selection_template_v1', ...
        'SelectedCandidateID','', ...
        'SelectionScenario','operational_measurement_plus_emulator', ...
        'PrimaryMetric','MeanTargetProxyLambdaMax', ...
        'ManualReviewCompleted',false,'SelectionRationale','', ...
        'SelectionTimestampUTC','', ...
        'automatic_rank1_assignment_permitted',false, ...
        'confirmation_action_implemented',true);
    evidence=struct('aggregateScores',aggregate, ...
        'defaultRelativeMetrics',defaultRelative, ...
        'validityPerProtocol',validityPerProtocol, ...
        'validitySummary',validitySummary, ...
        'measurementRanking',measurement,'operationalRanking',operational, ...
        'top10Protocols',top10,'scoreGaps',gaps, ...
        'rankingComparisonSummary',comparisonSummary, ...
        'rankShift',rankShift,'operationalRank1',rank1Record, ...
        'manualSelectionTemplate',manualTemplate);
end

function ranking=ranking_for(aggregate,candidates,covarianceCase)
    rows=aggregate.CovarianceCase==string(covarianceCase);
    ranking=aggregate(rows,:);
    ranking=outerjoin(candidates,ranking,'Keys', ...
        {'CandidateID','CandidateIndex'},'MergeKeys',true,'Type','left');
    valid=ranking.ValidityStatus=="ELIGIBLE"& ...
        isfinite(ranking.MeanTargetProxyLambdaMax);
    validRows=ranking(valid,:);
    validRows=sortrows(validRows, ...
        {'MeanTargetProxyLambdaMax','CandidateID'},{'ascend','ascend'});
    validRows.Rank=(1:height(validRows)).';
    invalidRows=ranking(~valid,:);invalidRows.Rank=nan(height(invalidRows),1);
    ranking=[validRows;sortrows(invalidRows,'CandidateID')];
end

function rows=top_rows(ranking,count)
    rows=ranking(isfinite(ranking.Rank)&ranking.Rank<=count,:);
end

function gaps=score_gaps(ranking)
    top=top_rows(ranking,10);
    n=height(top);gapNext=nan(n,1);relativeNext=nan(n,1);
    if n>1
        gapNext(1:end-1)=diff(top.MeanTargetProxyLambdaMax);
        relativeNext(1:end-1)=gapNext(1:end-1)./max( ...
            abs(top.MeanTargetProxyLambdaMax(1:end-1)),eps);
    end
    gaps=table(top.CovarianceCase,top.Rank,top.CandidateID, ...
        top.MeanTargetProxyLambdaMax,gapNext,relativeNext, ...
        'VariableNames',{'CovarianceCase','Rank','CandidateID', ...
        'PrimaryScore','GapToNextRank','RelativeGapToNextRank'});
end

function row=first_valid(ranking)
    hit=find(ranking.Rank==1,1);
    assert(~isempty(hit),'screening:aggregate_rankings:NoRankableCandidate', ...
        'The ranking has no candidate of rank 1: no candidate is eligible.');
    row=ranking(hit,:);
end

function label=validity_label(code)
    labels={'ELIGIBLE','OUT_OF_BOUNDS','NONFINITE_MEAN', ...
        'NONFINITE_VARIANCE','NON_PD_COVARIANCE', ...
        'INVALID_FINITE_DIFFERENCE','NON_PSD_FIM', ...
        'NON_PD_COVARIANCE_PROXY'};
    assert(code>=0&&code<numel(labels), ...
        'screening:aggregate_rankings:ValidityCode','Unknown validity code %d.',code);
    label=labels{code+1};
end
