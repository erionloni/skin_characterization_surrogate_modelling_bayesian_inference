function inputs = screen_inputs(provider, candidates, materials, policy)
%SCREEN_INPUTS What a protocol screen and its six-objective supplement depend on, as plain data.
%   INPUTS = screening.screen_inputs(PROVIDER, CANDIDATES, MATERIALS, POLICY)
%   describes the model provider (screening.generalized_provider) by its
%   content: the approved GP (surrogates.model_content), the calibration of
%   its emulator variance (shared gamma, tau squared, variance formula,
%   kernel), the input, output, material, protocol and target names, the
%   prior of the material parameters, the measurement CV and the numerical
%   floor; with the protocols CANDIDATES and material points MATERIALS
%   (their tables, values included) and the numerical POLICY. The screen
%   stores it with its checkpoint and its local information, the supplement
%   with its checkpoints; an interrupted screen or supplement continues, and
%   a supplement uses a screen, only for equal inputs (isequaln).
%   Side effects: none.

    calibration = provider.cfg.emulatorErrorCalibration;
    model = struct( ...
        'gp', surrogates.model_content(provider.gp), ...
        'calibration', struct( ...
            'sharedGamma', double(calibration.shared_gamma), ...
            'tauSquared', reshape(double(calibration.tau_squared_mbar2), 1, []), ...
            'varianceFormulaVersion', char(string(calibration.variance_formula_version)), ...
            'kernel', char(string(calibration.kernel))), ...
        'inputNames', {cellstr(string(provider.inputNames))}, ...
        'outputNames', {cellstr(string(provider.outputNames))}, ...
        'materialParameterNames', {cellstr(string(provider.materialParameterNames))}, ...
        'protocolParameterNames', {cellstr(string(provider.protocolParameterNames))}, ...
        'materialBounds', double(provider.materialBounds), ...
        'priorMean', double(provider.priorMean), 'priorSD', double(provider.priorSD), ...
        'priorCovarianceZ', double(provider.priorCovarianceZ), ...
        'targetParameterNames', {cellstr(string(provider.targetParameterNames))}, ...
        'targetIndices', double(provider.targetIndices), ...
        'measurementCV', double(provider.measurementCV), ...
        'numericalFloorSD', double(provider.numericalFloorSD));
    inputs = struct('schemaVersion', 'stage9b_screen_inputs_v1', 'provider', model, ...
        'candidates', candidates, 'materials', materials, 'policy', policy);
end
