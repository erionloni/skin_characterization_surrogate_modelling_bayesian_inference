function registry=objective_registry()
%OBJECTIVE_REGISTRY The six covariance objectives of the protocol screen.
%   REGISTRY = screening.objective_registry() returns one row per objective,
%   all minimized over the prior-standard-deviation covariance C of (m3_f,
%   m3_e, log10 k0, thickness): joint_weak (largest eigenvalue of the
%   (m3_e, log10 k0) block; the original primary objective), permeability
%   (C(3,3)), dissipation (C(2,2)), stiffness (C(1,1)), thickness (C(4,4))
%   and weak_total_variance (C(2,2) + C(3,3)), with the formula, the role
%   in the confirmation, the aggregation (arithmetic mean over materials)
%   and the formula version.
%   Side effects: none.
    registry=table( ...
        ["joint_weak";"permeability";"dissipation";"stiffness";"thickness";"weak_total_variance"], ...
        ["lambda_max(C([2,3],[2,3]))";"C(3,3)";"C(2,2)";"C(1,1)";"C(4,4)";"C(2,2)+C(3,3)"], ...
        ["selected_joint";"selected_permeability";"selected_dissipation";"";"";""], ...
        [true;false;false;false;false;false],repmat("arithmetic_mean",6,1), ...
        repmat("stage9b_covariance_objectives_v1",6,1), ...
        'VariableNames',{'ObjectiveID','PerTissueFormula','ConfirmationRole', ...
        'OriginalPrimary','Aggregation','FormulaVersion'});
end
