function context = generalized_fit_context(data, cfg)
%GENERALIZED_FIT_CONTEXT The provenance identifiers of the generalized refit's dataset.
%   CONTEXT = surrogates.generalized_fit_context(DATA, CFG) returns the
%   source snapshot ID of the dataset DATA and the configured snapshot ID,
%   which the refit records.
%   Side effects: none.

    assert(isfield(data,'dataProvenance')&&isstruct(data.dataProvenance), ...
        'surrogates:generalized_fit_context:MissingProvenance', ...
        'The dataset lacks dataProvenance; rebuild it with the step ''dataset''.');
    provenance=data.dataProvenance;
    required={'snapshot_id','cohort_decision'};
    assert(all(isfield(provenance,required)), ...
        'surrogates:generalized_fit_context:IncompleteProvenance', ...
        'The dataset provenance lacks the snapshot, cohort or missing-count fields.');
    assert(isfield(provenance,'missing_probe_runids'), ...
        'surrogates:generalized_fit_context:MissingCountField', ...
        'The dataset''s provenance lacks the count of missing probe runs; rerun the step ''dataset''.');
    missing=double(provenance.missing_probe_runids);
    assert(isscalar(missing)&&isfinite(missing)&&missing>=0&& ...
        missing==floor(missing), ...
        'surrogates:generalized_fit_context:BadMissingCount', ...
        'missing_probe_runids must be a nonnegative integer.');
    context=struct( ...
        'schemaVersion','real_extended_stage2_context_v1', ...
        'snapshotID',char(string(provenance.snapshot_id)), ...
        'missingProbeRunIDs',missing, ...
        'cohortDecision',char(string(provenance.cohort_decision)), ...
        'claimScope','configured_generalized_surrogate_and_sensitivity', ...
        'noticeLines',{{ ...
            'CONFIGURED GENERALIZED SURROGATE', ...
            ['SCALAR OUTPUT MODELS USE ALL AVAILABLE DEVELOPMENT EVIDENCE; ' ...
             'PARTIAL CASES ARE NEVER EXTERNAL TEST'], ...
            'NO MISSING OUTPUT IS IMPUTED', ...
            sprintf('%d SOURCE PROBE RUNIDS ARE UNAVAILABLE',missing), ...
            'STAGE 9B IS OUTSIDE THIS S01-S03 RUN'}});
    if isfield(cfg.realExtended,'snapshotID')
        context.configuredSnapshotID=char(string(cfg.realExtended.snapshotID));
        if ~isempty(context.configuredSnapshotID)
            assert(strcmp(context.snapshotID,context.configuredSnapshotID), ...
                'surrogates:generalized_fit_context:SnapshotMismatch', ...
                ['The selected dataset snapshot differs from the configured ' ...
                 'real_extended snapshot.']);
        end
    else
        context.configuredSnapshotID='';
    end
end
