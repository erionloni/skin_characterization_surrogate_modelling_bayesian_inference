function result=quality_audit(dataSet,cfg,varargin)
%QUALITY_AUDIT The development audit of the surrogates: kernels, seeds, training size, error model.
%   RESULT = surrogates.quality_audit(DATASET, CFG, 'OutputDir', ROOT,
%   'RoleManifest', ROLES, 'ExcludedAssessmentRole', ROLE) audits the
%   surrogate family on the development arrays of DATASET (X_train, Y_train,
%   trainCaseIDs, names, bounds; externalHoldoutCaseIDs
%   lists the excluded cases, whose outcomes are never given): the fit
%   campaign (surrogates.surrogate_quality_fit_campaign), the out-of-fold
%   residual product and its variance semantics
%   (surrogates.surrogate_quality_variance_semantics) and the comparison of
%   emulator-variance models (surrogates.surrogate_quality_calibration).
%   ROLES is the development/external role manifest of the dataset: its
%   development and excluded cases must be those of DATASET. It
%   writes every table below ROOT, the configuration record, the result MAT,
%   the status and a short report. No candidate is selected and no
%   production surrogate or covariance is modified.
%   Side effects: writes the audit's tables and records (above).
%   Computation: several hours at the thesis settings (1,050 GP and PCE
%   fits).

    options=parse_options(varargin{:});
    [roleManifest,developmentIDs,excludedIDs,excludedRole]=validate_inputs( ...
        dataSet,cfg,options);
    outputTraining=surrogates.output_training_contract(dataSet,cfg);
    root=char(string(options.OutputDir));
    ensure_directories(root);

    fit=surrogates.surrogate_quality_fit_campaign(dataSet,cfg);
    [semantics,oofResiduals,varianceFactorization]= ...
        surrogates.surrogate_quality_variance_semantics( ...
        fit.kernelCVPredictions,fit.kernelCVHyperparameters, ...
        fit.kernelCVFolds,fit.calibrationFolds,cfg);

    calibrationCfg=cfg;
    calibrationCfg.surrogateQualityAudit.localVarianceModelsEnabled= ...
        logical(semantics.local_variance_models_permitted);
    calibration=surrogates.surrogate_quality_calibration( ...
        oofResiduals,varianceFactorization,fit.calibrationFolds, ...
        dataSet.outputNames,calibrationCfg);
    calibration=bind_output_data_contract(calibration,outputTraining, ...
        excludedIDs);

    auditConfiguration=configuration_record(cfg,fit,developmentIDs, ...
        excludedIDs,excludedRole);
    outputPaths=write_outputs(root,roleManifest,auditConfiguration,fit, ...
        calibration,semantics);

    result=struct( ...
        'schemaVersion','surrogate_development_quality_audit_result_v3', ...
        'status','complete', ...
        'configuration',auditConfiguration, ...
        'fitCounters',fit.fitCounters, ...
        'varianceSemantics',semantics, ...
        'developmentCaseCount',numel(developmentIDs), ...
        'outputDevelopmentCaseCounts', ...
            reshape(double([outputTraining.records.count]),[],1), ...
        'outputMissingDevelopmentCaseCounts', ...
            reshape(double([outputTraining.records.missingDevelopmentCount]),[],1), ...
        'excludedAssessmentRole',excludedRole, ...
        'excludedAssessmentCaseCount',numel(excludedIDs), ...
        'externalHoldoutCaseCount',double(is_fixed_external( ...
            cfg,excludedRole))*numel(excludedIDs), ...
        'externalTestCaseCount',double(strcmp(excludedRole, ...
            'external_test'))*numel(excludedIDs), ...
        'internalHeldoutCaseCount',double(strcmp(excludedRole, ...
            'internal_heldout'))*numel(excludedIDs), ...
        'externalHoldoutOutputsLoaded',false, ...
        'externalHoldoutEvaluationsPerformed',0, ...
        'candidateModelsRetained',false, ...
        'automaticScientificSelectionPerformed',false, ...
        'productionModelModified',false, ...
        'productionCovarianceModified',false, ...
        'outputPaths',outputPaths);
    resultPath=fullfile(root,'surrogate_quality_audit_result.mat');
    statusPath=fullfile(root,'status','surrogate_quality_audit_status.json');
    result.outputPaths.resultMAT=resultPath;
    result.outputPaths.status=statusPath;
    saved=struct('result',result,'fitCampaign',fit, ...
        'calibration',calibration,'roleManifest',roleManifest);
    utils.atomic_save_struct(resultPath,saved,'-v7.3');

    status=completion_status(result,fit,calibration,semantics);
    utils.atomic_write_json(statusPath,status,'AllowReplace',true);
    write_audit_report(fullfile(root,'status','audit_report.md'),status,fit, ...
        semantics);
    write_console_log(fullfile(root,'status', ...
        'surrogate_quality_audit_console.log'),fit,status);
end

function options=parse_options(varargin)
    parser=inputParser;
    addParameter(parser,'OutputDir','',@text_scalar);
    addParameter(parser,'RoleManifest',table(),@istable);
    addParameter(parser,'ExcludedAssessmentRole','external_holdout',@text_scalar);
    parse(parser,varargin{:});options=parser.Results;
    assert(strlength(string(options.OutputDir))>0&&height(options.RoleManifest)>0, ...
        'surrogates:quality_audit:Options', ...
        'The audit needs an output folder (OutputDir) and the role manifest (RoleManifest).');
end

function [roles,developmentIDs,excludedIDs,excludedRole]=validate_inputs( ...
        dataSet,cfg,options)
    required={'X_train','Y_train','inputNames','outputNames','inputBounds', ...
        'trainCaseIDs','externalHoldoutCaseIDs'};
    assert(isstruct(dataSet)&&isscalar(dataSet)&&all(isfield(dataSet,required))&& ...
        ~isfield(dataSet,'Y_validation')&&~isfield(dataSet,'Y_test')&& ...
        size(dataSet.X_train,1)>=2&&size(dataSet.X_train,2)>=1&& ...
        size(dataSet.Y_train,1)==size(dataSet.X_train,1)&& ...
        size(dataSet.Y_train,2)==6&& ...
        all(isfinite(dataSet.X_train),'all')&& ...
        ~any(isinf(dataSet.Y_train),'all')&& ...
        all(any(isfinite(dataSet.Y_train),1)), ...
        'surrogates:quality_audit:DevelopmentDataset', ...
        ['The audit takes development arrays only (%s; finite inputs, six ' ...
         'outputs with observed values, no held-out outcomes).'], ...
        strjoin(required,', '));
    developmentIDs=double(dataSet.trainCaseIDs(:));
    excludedIDs=double(dataSet.externalHoldoutCaseIDs(:));
    excludedRole=char(string(options.ExcludedAssessmentRole));
    assert(ismember(excludedRole, ...
        {'external_holdout','external_test','internal_heldout'})&& ...
        numel(developmentIDs)==size(dataSet.X_train,1)&& ...
        numel(unique(developmentIDs))==numel(developmentIDs)&& ...
        ~isempty(excludedIDs)&&numel(unique(excludedIDs))==numel(excludedIDs)&& ...
        isempty(intersect(developmentIDs,excludedIDs)), ...
        'surrogates:quality_audit:DevelopmentSplit', ...
        ['The development and excluded CaseIDs must be unique and disjoint, ' ...
         'one development CaseID per row.']);
    expectedNames=cellstr(string(cfg.paramNames(:))).';
    expectedBounds=double(cfg.paramBounds);
    if size(expectedBounds,1)==2&&size(expectedBounds,2)~=2
        expectedBounds=expectedBounds.';
    end
    assert(isequal(cellstr(string(dataSet.inputNames(:))).',expectedNames)&& ...
        isequal(size(double(dataSet.inputBounds)),size(expectedBounds))&& ...
        max(abs(double(dataSet.inputBounds)-expectedBounds),[],'all')<=1e-12, ...
        'surrogates:quality_audit:InputContract', ...
        'Audit input names/bounds differ from the active route contract.');
    roles=options.RoleManifest;
    requiredRole={'CaseID','MethodologicalRole'};
    assert(height(roles)==numel(developmentIDs)+numel(excludedIDs)&& ...
        all(ismember(requiredRole,roles.Properties.VariableNames))&& ...
        numel(unique(double(roles.CaseID)))==height(roles), ...
        'surrogates:quality_audit:RoleManifest', ...
        'The role manifest must list every development and excluded case once.');
    manifestDevelopment=double(roles.CaseID( ...
        string(roles.MethodologicalRole)=="development"));
    manifestExcluded=double(roles.CaseID( ...
        string(roles.MethodologicalRole)==string(excludedRole)));
    assert(isequal(sort(manifestDevelopment),sort(developmentIDs))&& ...
        isequal(sort(manifestExcluded),sort(excludedIDs)), ...
        'surrogates:quality_audit:MethodologicalRoles', ...
        'The role manifest assigns other cases to development or %s than the dataset.', ...
        excludedRole);
    if is_fixed_external(cfg,excludedRole)
        assert(all(ismember(double(cfg.inversion.caseIDs(:)),excludedIDs))&& ...
            numel(unique(double(cfg.inversion.caseIDs(:))))== ...
                numel(cfg.inversion.caseIDs), ...
            'surrogates:quality_audit:FixedMethodologicalRoles', ...
            'The configured inversion cases must be distinct external test cases.');
    end
end

function record=configuration_record(cfg,fit,developmentIDs,excludedIDs, ...
        excludedRole)
    roleStatement=sprintf([ ...
        'The %d %s cases were excluded from all audit fits, model selection, ' ...
        'and calibration.'],numel(excludedIDs),strrep(excludedRole,'_',' '));
    externalIDs=[];externalTestIDs=[];internalIDs=[];
    if strcmp(excludedRole,'external_holdout')
        externalIDs=excludedIDs;
    elseif strcmp(excludedRole,'external_test')
        externalTestIDs=excludedIDs;
        if is_fixed_external(cfg,excludedRole),externalIDs=excludedIDs;end
    else
        internalIDs=excludedIDs;
    end
    record=struct( ...
        'schema_version','surrogate_development_quality_audit_configuration_v4', ...
        'methodological_role_statement',roleStatement, ...
        'development_case_count',numel(developmentIDs), ...
        'output_development_case_counts', ...
            reshape(double(fit.outputTrainingCounts),1,[]), ...
        'excluded_assessment_role',excludedRole, ...
        'excluded_assessment_case_count',numel(excludedIDs), ...
        'external_holdout_case_count',double(is_fixed_external( ...
            cfg,excludedRole))*numel(excludedIDs), ...
        'external_test_case_count',double(strcmp(excludedRole, ...
            'external_test'))*numel(excludedIDs), ...
        'internal_heldout_case_count',double(strcmp(excludedRole, ...
            'internal_heldout'))*numel(excludedIDs), ...
        'development_case_ids',reshape(developmentIDs,1,[]), ...
        'excluded_assessment_case_ids',reshape(excludedIDs,1,[]), ...
        'external_holdout_case_ids',reshape(externalIDs,1,[]), ...
        'external_test_case_ids',reshape(externalTestIDs,1,[]), ...
        'internal_heldout_case_ids',reshape(internalIDs,1,[]), ...
        'audit_policy',cfg.surrogateQualityAudit, ...
        'resolved_fit_settings',fit.settings, ...
        'fit_count',fit.fitCounters, ...
        'external_holdout_outputs_loaded',false, ...
        'external_holdout_evaluations_performed',0, ...
        'external_holdout_legacy_alias_for_external_test', ...
            logical(is_fixed_external(cfg,excludedRole)&& ...
            strcmp(excludedRole,'external_test')), ...
        'candidate_models_retained',false, ...
        'automatic_scientific_selection_performed',false, ...
        'production_model_modified',false, ...
        'production_covariance_modified',false);
end

