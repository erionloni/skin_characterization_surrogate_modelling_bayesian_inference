function write_text_atomic(pathValue,value)
    folder=fileparts(pathValue);if ~isfolder(folder),mkdir(folder);end
    temporary=utils.atomic_temporary_path(pathValue);
    cleanup=onCleanup(@()delete_if_present(temporary));
    fid=fopen(temporary,'wb');assert(fid>=0,'surrogates:quality_audit:TextOpen', ...
        'Cannot write the file %s (fopen failed).',temporary);
    closer=onCleanup(@()close_if_open(fid));
    bytes=unicode2native(char(value),'UTF-8');assert(fwrite(fid,bytes,'uint8')==numel(bytes));
    fclose(fid);clear closer;utils.atomic_move_replace(temporary,pathValue);
end

function ensure_directories(root)
    names={'configuration','data_roles','kernel_cross_validation', ...
        'same_data_seed_stability','training_convergence','variance_semantics', ...
        'oof_residuals','calibration_crossfit','variance_model_comparison', ...
        'residual_distribution','residual_correlation','comparisons','status'};
    for index=1:numel(names)
        pathValue=fullfile(root,names{index});if ~isfolder(pathValue),mkdir(pathValue);end
    end
end

function delete_if_present(pathValue)
    if isfile(pathValue),delete(pathValue);end
end

function close_if_open(fid)
    if ~isempty(fopen(fid)),fclose(fid);end
end

function tf=is_fixed_external(cfg,excludedRole)
    tf=strcmp(excludedRole,'external_holdout')|| ...
        (strcmp(excludedRole,'external_test')&&isfield(cfg,'dataMode')&& ...
        strcmp(cfg.dataMode,'real'));
end

function tf=text_scalar(value)
    tf=ischar(value)||(isstring(value)&&isscalar(value));
end

function value=ternary(condition,left,right)
    if condition,value=left;else,value=right;end
end
