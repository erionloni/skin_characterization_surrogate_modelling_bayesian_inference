function status=completion_status(result,fit,calibration,semantics)
    assessmentStatus=[result.excludedAssessmentRole '_not_evaluated'];
    status=struct( ...
        'schema_version','surrogate_development_quality_audit_status_v3', ...
        'status','complete', ...
        'development_case_count',result.developmentCaseCount, ...
        'output_development_case_counts', ...
            reshape(double(result.outputDevelopmentCaseCounts),1,[]), ...
        'output_missing_development_case_counts', ...
            reshape(double(result.outputMissingDevelopmentCaseCounts),1,[]), ...
        'excluded_assessment_role',result.excludedAssessmentRole, ...
        'excluded_assessment_case_count',result.excludedAssessmentCaseCount, ...
        'internal_heldout_case_count',result.internalHeldoutCaseCount, ...
        'external_test_case_count',result.externalTestCaseCount, ...
        'external_holdout_case_count',result.externalHoldoutCaseCount, ...
        'excluded_assessment_status',assessmentStatus, ...
        'external_holdout_status',ternary(result.externalHoldoutCaseCount>0, ...
