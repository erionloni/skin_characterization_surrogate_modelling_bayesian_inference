function calibration=bind_output_data_contract(calibration,training,excludedIDs)
%BIND_OUTPUT_DATA_CONTRACT The cases behind the calibration comparison, per output.
%   Each output's record lists its development cohort, the excluded cases
%   and the out-of-fold cases: the record that a calibration fitted from
%   this audit carries.
    template=struct('output_index',0,'output','', ...
        'development_case_count',0,'development_case_ids',[], ...
        'external_case_count',0,'external_case_ids',[], ...
        'oof_case_count',0,'oof_case_ids',[]);
    records=repmat(template,6,1);R=calibration.developmentOOFResiduals;
    for outputIndex=1:6
        cohort=training.records(outputIndex);
        developmentIDs=reshape(double(cohort.caseIDs),[],1);
        observedOOF=unique(double(R.CaseID(R.OutputIndex==outputIndex)),'stable');
        assert(isequal(sort(observedOOF),sort(developmentIDs)), ...
            'surrogates:quality_audit:OutputOOFCohort', ...
            'Output %d OOF evidence does not cover its finite cohort.',outputIndex);
        records(outputIndex)=struct('output_index',outputIndex, ...
            'output',char(string(cohort.outputName)), ...
            'development_case_count',numel(developmentIDs), ...
            'development_case_ids',developmentIDs, ...
            'external_case_count',numel(excludedIDs), ...
            'external_case_ids',reshape(double(excludedIDs),[],1), ...
            'oof_case_count',numel(developmentIDs), ...
            'oof_case_ids',developmentIDs);
    end
    calibration.outputDataContract=records;
end

function T=complete_paired_kernel_comparison(metricPairs,H,tolerance)
    metricPairs.InputIndex=nan(height(metricPairs),1);
    metricPairs.Input=repmat("",height(metricPairs),1);
    metricPairs.EvidenceSource=repmat("prediction_metric",height(metricPairs),1);
    metricPairs=movevars(metricPairs,{'InputIndex','Input','EvidenceSource'}, ...
        'After','Output');
    kernels=unique(string(H.Kernel),'stable');pairs=nchoosek(1:numel(kernels),2);
    quantities={"Theta","NormalizedInverseThetaImportance", ...
        "ProcessVariance","OptimizerObjective","TrainTime_s"};
    parts=cell(0,1);
    for pairIndex=1:size(pairs,1)
        leftKernel=kernels(pairs(pairIndex,1));rightKernel=kernels(pairs(pairIndex,2));
        for quantityIndex=1:numel(quantities)
            quantity=quantities{quantityIndex};left=H(string(H.Kernel)==leftKernel,:);
            right=H(string(H.Kernel)==rightKernel,:);
            if ~ismember(quantity,H.Properties.VariableNames),continue;end
            if any(quantity==["ProcessVariance" "OptimizerObjective" "TrainTime_s"])
                left=left(left.InputIndex==1,:);right=right(right.InputIndex==1,:);
            end
            keys={'Repeat','Fold','OutputIndex','InputIndex'};
            left=sortrows(left,keys);right=sortrows(right,keys);
            assert(height(left)==height(right)&&all(left{:,keys}==right{:,keys},'all'), ...
                'surrogates:quality_audit:PairedHyperparameterKeys', ...
                ['The hyperparameter rows of the two compared fits must pair by repeat, fold, ' ...
                 'output and input.']);
            n=height(left);a=double(left.(quantity));b=double(right.(quantity));
            difference=a-b;numericTolerance=tolerance.*max([ones(n,1) abs(a) abs(b)],[],2);
            signValue=nan(n,1);finite=isfinite(difference);
            signValue(finite)=double(difference(finite)>numericTolerance(finite))- ...
                double(difference(finite)<-numericTolerance(finite));
            one=table(repmat("fold_hyperparameter",n,1),left.Repeat,left.Fold, ...
                left.OutputIndex,left.Output,left.InputIndex,left.Input, ...
                repmat("hyperparameter_or_fit_metadata",n,1), ...
                repmat(leftKernel,n,1),repmat(rightKernel,n,1), ...
                repmat(string(quantity),n,1),a,b,difference,numericTolerance,signValue, ...
                zeros(n,1),zeros(n,1),zeros(n,1),zeros(n,1), ...
                'VariableNames',metricPairs.Properties.VariableNames);
            groupKey=string(one.OutputIndex)+"|"+string(one.InputIndex)+"|"+one.Metric;
            [~,~,group]=unique(groupKey,'stable');
            for groupIndex=1:max(group)
                rows=group==groupIndex;values=one.DifferenceSign(rows);
                valid=isfinite(values);one.NegativeDifferenceCount(rows)=nnz(values(valid)<0);
                one.TiedDifferenceCount(rows)=nnz(values(valid)==0);
                one.PositiveDifferenceCount(rows)=nnz(values(valid)>0);
                one.PairCount(rows)=nnz(valid);
            end
            parts{end+1}=one; %#ok<AGROW>
        end
    end
    if isempty(parts),T=metricPairs;else,T=vertcat(metricPairs,parts{:});end
end

function T=hyperparameter_summary(H,keyNames)
    quantities={'Theta','NormalizedInverseThetaImportance','ProcessVariance', ...
        'OptimizerObjective','TrainTime_s'};
    keys=unique(H(:,keyNames),'rows','stable');parts=cell(0,1);
    for keyIndex=1:height(keys)
        rows=true(height(H),1);
        for nameIndex=1:numel(keyNames)
            name=keyNames{nameIndex};rows=rows&H.(name)==keys.(name)(keyIndex);
        end
        for quantityIndex=1:numel(quantities)
            name=quantities{quantityIndex};
            if ~ismember(name,H.Properties.VariableNames),continue;end
            values=sort(double(H.(name)(rows)));values=values(isfinite(values));
            [average,deviation,medianValue,q025,q975,minimum,maximum,cv]= ...
                descriptive_values(values);
            parts{end+1}=[keys(keyIndex,:) table(string(name),numel(values), ...
                average,deviation,medianValue,q025,q975,minimum,maximum,cv, ...
                'VariableNames',{'Quantity','ValueCount','Mean','SD','Median', ...
                'Q025','Q975','Minimum','Maximum','CoefficientOfVariation'})]; %#ok<AGROW>
        end
    end
    T=vertcat(parts{:});
end

function [average,deviation,medianValue,q025,q975,minimum,maximum,cv]= ...
        descriptive_values(values)
    if isempty(values)
        [average,deviation,medianValue,q025,q975,minimum,maximum,cv]=deal(NaN);return
    end
    average=mean(values);deviation=std(values,0);medianValue=linear_quantile(values,.5);
    q025=linear_quantile(values,.025);q975=linear_quantile(values,.975);
    minimum=min(values);maximum=max(values);cv=NaN;
    if abs(average)>eps,cv=deviation/abs(average);end
end

function value=linear_quantile(sorted,probability)
    if isempty(sorted),value=NaN;return;end
    if isscalar(sorted),value=sorted;return;end
    position=1+(numel(sorted)-1)*probability;lower=floor(position);upper=ceil(position);
    fraction=position-lower;value=sorted(lower)+fraction*(sorted(upper)-sorted(lower));
end

