function result=run_surrogate_quality_audit(cfg)
%RUN_SURROGATE_QUALITY_AUDIT The development audit of the fixed surrogates.
%   RESULT = surrogates.run_surrogate_quality_audit(CFG) loads the
%   development cases of the dataset CFG.files.dataset (inputs, responses,
%   CaseIDs, split groups) and the development/external role manifest
%   CFG.files.methodologicalRoleManifest, and runs surrogates.quality_audit
%   into CFG.paths.surrogateQualityAudit. Of the external test cases only
%   the CaseIDs are read, to keep them out of every audit fit and table;
%   their outcomes are never loaded. RESULT is the audit result.
%   Side effects: writes the audit below the run folder.
%   Computation: several hours (1,050 GP and PCE fits).

    assert(isstruct(cfg)&&isscalar(cfg)&&isfield(cfg,'dataMode')&& ...
        strcmp(char(string(cfg.dataMode)),'real'), ...
        'surrogates:run_surrogate_quality_audit:Route', ...
        'The development audit runs on the fixed route.');
    required={cfg.files.dataset,cfg.files.methodologicalRoleManifest};
    missing=required(~cellfun(@isfile,required));
    assert(isempty(missing), ...
        'surrogates:run_surrogate_quality_audit:MissingInput', ...
        ['The audit needs the dataset and its development/external role ' ...
         'manifest; missing: %s. Run the step ''dataset'' first.'], ...
        strjoin(missing,', '));

    % The loaded variables fix the training cohorts and their split groups,
    % from which the audit derives its folds and seeds.
    fields={'X_train','Y_train','inputNames','outputNames','inputBounds', ...
        'trainCaseIDs','dataProvenance','trainSourceRows', ...
        'validationCaseIDs','splitManifest'};
    available=who('-file',cfg.files.dataset);
    optional={'developmentOutputAvailability','outputTrainingEvidence', ...
        'counts','developmentSplitGroupIdentities'};
    fields=[fields reshape(intersect(optional,available,'stable'),1,[])];
    dataSet=utils.load_plain_mat(cfg.files.dataset,fields{:});
    assert(all(isfield(dataSet,fields))&&size(dataSet.X_train,1)>=2&& ...
        size(dataSet.X_train,2)==numel(dataSet.inputNames)&& ...
        isequal(size(dataSet.Y_train), ...
            [size(dataSet.X_train,1) numel(dataSet.outputNames)])&& ...
        numel(dataSet.outputNames)==6, ...
        'surrogates:run_surrogate_quality_audit:DevelopmentDataset', ...
        ['The dataset %s lacks development arrays of four inputs and six ' ...
         'outputs; rerun the step ''dataset''.'],cfg.files.dataset);
    excludedIDs=double(dataSet.validationCaseIDs(:));
    dataSet=rmfield(dataSet,'validationCaseIDs');
    roleManifest=readtable(cfg.files.methodologicalRoleManifest, ...
        'Delimiter',',','TextType','string');
    assert(numel(unique(double(dataSet.trainCaseIDs(:))))== ...
        numel(dataSet.trainCaseIDs)&&numel(unique(excludedIDs))== ...
        numel(excludedIDs)&&isempty(intersect( ...
        double(dataSet.trainCaseIDs(:)),excludedIDs)), ...
        'surrogates:run_surrogate_quality_audit:CohortDisjointness', ...
        ['The development and external CaseIDs of the dataset must be unique ' ...
         'and disjoint; rerun the step ''dataset''.']);
    dataSet.externalHoldoutCaseIDs=excludedIDs;
    dataSet.excludedAssessmentRole='external_test';

    root=cfg.paths.surrogateQualityAudit;
    result=surrogates.quality_audit(dataSet,cfg,'OutputDir',root, ...
        'RoleManifest',roleManifest,'ExcludedAssessmentRole','external_test');
end
