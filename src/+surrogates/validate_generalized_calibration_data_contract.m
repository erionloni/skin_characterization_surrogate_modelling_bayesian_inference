function validate_generalized_calibration_data_contract(calibration,data)
%VALIDATE_GENERALIZED_CALIBRATION_DATA_CONTRACT Check that the generalized calibration belongs to the dataset.
%   surrogates.validate_generalized_calibration_data_contract(CALIBRATION, DATA) refuses
%   when the frozen calibration CALIBRATION
%   (surrogates.load_generalized_emulator_calibration) was fitted on other data than
%   the generalized dataset DATA (variables of dataset.mat):
%   the development and held-out cases must be those the calibration lists,
%   in the same order, and every output must be observed on the
%   development cases that the calibration lists for it
%   (output_data_contract). The dataset must list the outputs in the
%   calibration's order, and every held-out case must have all six outputs.
%   Side effects: none.

    required={'developmentCaseIDsAll','developmentOutputAvailabilityMask', ...
        'testCaseIDs','Y_test','outputNames'};
    missing=setdiff(required,fieldnames(data),'stable');
    assert(isempty(missing), ...
        'surrogates:validate_generalized_calibration_data_contract:DatasetSchema', ...
        'The dataset lacks %s; rerun the step ''dataset''.',strjoin(missing,', '));
    development=reshape(double(data.developmentCaseIDsAll),[],1);
    heldout=reshape(double(data.testCaseIDs),[],1);
    yHeldout=double(data.Y_test);
    assert(size(yHeldout,1)==numel(heldout)&&size(yHeldout,2)==6&& ...
        all(isfinite(yHeldout),'all'), ...
        'surrogates:validate_generalized_calibration_data_contract:IncompleteHeldout', ...
        'Every held-out case of the dataset must have six finite outputs.');
    calibrationOrder=cellstr(string(calibration.output_order(:))).';
    dataOrder=cellstr(string(data.outputNames(:))).';
    assert(isequal(calibrationOrder,dataOrder), ...
        'surrogates:validate_generalized_calibration_data_contract:OutputOrder', ...
        'The calibration lists the outputs as %s, the dataset as %s.', ...
        strjoin(calibrationOrder,', '),strjoin(dataOrder,', '));
    calibrationDevelopment=reshape(double(calibration.development_case_ids),[],1);
    calibrationHeldout=reshape(double( ...
        calibration.internal_heldout_case_ids_excluded),[],1);
    assert(isequal(calibrationDevelopment,development)&& ...
        isequal(calibrationHeldout,heldout), ...
        'surrogates:validate_generalized_calibration_data_contract:Roles', ...
        ['The calibration was fitted for %d development and %d held-out cases, ' ...
         'the dataset has %d and %d, or other CaseIDs: the calibration %s ' ...
         'belongs to another dataset.'],numel(calibrationDevelopment), ...
        numel(calibrationHeldout),numel(development),numel(heldout), ...
        calibration_name(calibration));
    observed=double(logical(data.developmentOutputAvailabilityMask));
    observed(observed==0)=NaN;
    check_output_cases(calibration,development,observed, ...
        'surrogates:validate_generalized_calibration_data_contract');
end

function check_output_cases(calibration,caseIDs,Y,prefix)
%CHECK_OUTPUT_CASES Every output observed on the development cases the calibration lists for it.
    contract=reshape(calibration.output_data_contract,[],1);
    [~,order]=sort(double([contract.output_index]));contract=contract(order);
    assert(numel(contract)==size(Y,2), ...
        [prefix ':OutputCases'], ...
        'The calibration %s lists %d outputs, the dataset has %d.', ...
        calibration_name(calibration),numel(contract),size(Y,2));
    for j=1:numel(contract)
        observed=reshape(double(caseIDs(isfinite(Y(:,j)))),[],1);
        listed=reshape(double(contract(j).development_case_ids),[],1);
        assert(isequal(observed,listed),[prefix ':OutputCases'], ...
            ['Output %s is observed on other development cases (%d) than those ' ...
             'the calibration %s was fitted on (%d).'], ...
            char(string(contract(j).output)),numel(observed), ...
            calibration_name(calibration),numel(listed));
    end
end

function name=calibration_name(calibration)
    name='';
    if isfield(calibration,'artifact_path')
        [~,stem,extension]=fileparts(char(string(calibration.artifact_path)));
        name=[stem extension];
    end
end
