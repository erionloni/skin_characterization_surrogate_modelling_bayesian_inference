function M=surrogate_metric_primitives(truth,prediction,variance,varargin)
%SURROGATE_METRIC_PRIMITIVES Authoritative scalar-output metric formulas.
%   M = SURROGATES.SURROGATE_METRIC_PRIMITIVES(Y,MU,V) evaluates the
%   deterministic and Gaussian predictive-distribution primitives for one
%   scalar surrogate output. Context-specific callers remain responsible for
%   grouping observations (for example, by fold, output, or CaseID).
%   M: the point metrics (residuals, MAE, RMSE, NRMSE_range, relative
%   errors), the Gaussian predictive metrics (standardized residuals,
%   interval coverage, NLPD, CRPS, predictive standard deviations) and why
%   a metric is unavailable.
%   Options (name-value): 'IntervalLevels' ([0.50 0.80 0.90 0.95]),
%   'IntervalCriticalValues' (default the Gaussian quantiles of the levels),
%   'PredictiveSDSafeguard' (eps, the smallest predictive standard deviation
%   used), 'RangeTolerance' (1e-12: R2 and NRMSE_range need a larger spread
%   of the truths) and 'RelativeDenominatorTolerance' (1e-12: relative errors
%   use only truths larger in magnitude).
%   Side effects: none.

    parser=inputParser;
    addParameter(parser,'RelativeDenominatorTolerance',1e-12, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>=0);
    addParameter(parser,'RangeTolerance',1e-12, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>=0);
    addParameter(parser,'IntervalLevels',[0.50 0.80 0.90 0.95], ...
        @(x)isnumeric(x)&&isvector(x)&&all(isfinite(x))&&all(x>0&x<1));
    addParameter(parser,'IntervalCriticalValues',[], ...
        @(x)isnumeric(x)&&isvector(x)&&all(isfinite(x))&&all(x>=0));
    addParameter(parser,'PredictiveSDSafeguard',eps, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
    parse(parser,varargin{:});

    relativeTolerance=double(parser.Results.RelativeDenominatorTolerance);
    rangeTolerance=double(parser.Results.RangeTolerance);
    intervalLevels=reshape(double(parser.Results.IntervalLevels),1,[]);
    criticalValues=reshape(double(parser.Results.IntervalCriticalValues),1,[]);
    safeguard=double(parser.Results.PredictiveSDSafeguard);
    if isempty(criticalValues)
        criticalValues=sqrt(2)*erfinv(intervalLevels);
    end
    assert(numel(criticalValues)==numel(intervalLevels), ...
        'surrogates:surrogate_metric_primitives:IntervalCriticalValues', ...
        'Interval levels and critical values must have equal lengths.');

    truth=reshape(double(truth),[],1);
    prediction=reshape(double(prediction),[],1);
    variance=reshape(double(variance),[],1);
    assert(~isempty(truth)&&isequal(size(truth),size(prediction))&& ...
        isequal(size(truth),size(variance))&&all(isfinite(truth))&& ...
        all(isfinite(prediction)), ...
        'surrogates:surrogate_metric_primitives:Shape', ...
        'Truth, predictive means, and variances must be equally sized vectors.');
    assert(all(isfinite(variance)|isnan(variance))&& ...
        all(variance(isfinite(variance))>=0), ...
        'surrogates:surrogate_metric_primitives:Variance', ...
        'Finite predictive variances must be nonnegative.');

    observationCount=numel(truth);
    residual=prediction-truth;
    squaredResidual=residual.^2;
    absoluteResidual=abs(residual);
    rmse=sqrt(mean(squaredResidual));
    mae=mean(absoluteResidual);
    maximumAbsoluteError=max(absoluteResidual);

    centeredSumSquares=sum((truth-mean(truth)).^2);
    r2=NaN;
    if centeredSumSquares>rangeTolerance^2
        r2=1-sum(squaredResidual)/centeredSumSquares;
    end
    truthRange=max(truth)-min(truth);
    nrmse=NaN;nrmseReason="";
    if truthRange>rangeTolerance
        nrmse=rmse/truthRange;
    else
        nrmseReason="truth_range_numerically_near_zero";
    end

    relativeRows=abs(truth)>relativeTolerance;
    relativeMetricCount=sum(relativeRows);
    relativeErrorPercent=nan(observationCount,1);
    meanRelativeError=NaN;maximumRelativeError=NaN;relativeReason="";
    if any(relativeRows)
        relativeErrorPercent(relativeRows)= ...
            100*absoluteResidual(relativeRows)./abs(truth(relativeRows));
        meanRelativeError=mean(relativeErrorPercent(relativeRows));
        maximumRelativeError=max(relativeErrorPercent(relativeRows));
    else
        relativeReason="no_denominator_above_relative_tolerance";
    end

    probabilisticRows=isfinite(variance)&variance>=0;
    probabilisticMetricCount=sum(probabilisticRows);
    predictiveStdRaw=nan(observationCount,1);
    predictiveStdSafe=nan(observationCount,1);
    standardizedResidual=nan(observationCount,1);
    intervalIncluded=false(observationCount,numel(intervalLevels));
    pointNLPD=nan(observationCount,1);
    pointCRPS=nan(observationCount,1);
    coveragePercent=nan(1,numel(intervalLevels));
    meanPredictiveStd=NaN;meanStandardizedResidual=NaN;
    sdStandardizedResidual=NaN;rmsStandardizedResidual=NaN;
    predictiveSDToRMSE=NaN;gaussianNLPD=NaN;gaussianCRPS=NaN;
    probabilisticReason="";
    if any(probabilisticRows)
        predictiveStdRaw(probabilisticRows)= ...
            sqrt(max(variance(probabilisticRows),0));
        predictiveStdSafe(probabilisticRows)= ...
            max(predictiveStdRaw(probabilisticRows),safeguard);
        sigma=predictiveStdSafe(probabilisticRows);
        error=residual(probabilisticRows);
        standardizedResidual(probabilisticRows)=error./sigma;
        meanPredictiveStd=mean(predictiveStdRaw(probabilisticRows));
        meanStandardizedResidual=mean(standardizedResidual(probabilisticRows));
        sdStandardizedResidual=std(standardizedResidual(probabilisticRows),0);
        rmsStandardizedResidual= ...
            sqrt(mean(standardizedResidual(probabilisticRows).^2));
        if rmse>0
            predictiveSDToRMSE=meanPredictiveStd/rmse;
        end
        for levelIndex=1:numel(intervalLevels)
            intervalIncluded(probabilisticRows,levelIndex)= ...
                abs(error)<=criticalValues(levelIndex)*sigma;
            coveragePercent(levelIndex)=100*mean( ...
                intervalIncluded(probabilisticRows,levelIndex));
        end
        pointNLPD(probabilisticRows)=0.5*log(2*pi*sigma.^2)+ ...
            0.5*(error.^2)./sigma.^2;
        truthZ=(truth(probabilisticRows)-prediction(probabilisticRows))./sigma;
        normalCDF=0.5*(1+erf(truthZ/sqrt(2)));
        normalPDF=exp(-0.5*truthZ.^2)/sqrt(2*pi);
        pointCRPS(probabilisticRows)=sigma.*( ...
            truthZ.*(2*normalCDF-1)+2*normalPDF-1/sqrt(pi));
        gaussianNLPD=mean(pointNLPD(probabilisticRows));
        gaussianCRPS=mean(pointCRPS(probabilisticRows));
    else
        probabilisticReason="no_finite_nonnegative_predictive_variance";
    end

    M=struct( ...
        'ObservationCount',observationCount, ...
        'Residual',residual,'SquaredResidual',squaredResidual, ...
        'AbsoluteResidual',absoluteResidual, ...
        'R2',r2,'RMSE',rmse,'NRMSE_range',nrmse,'MAE',mae, ...
        'MeanAbsRelError_percent',meanRelativeError, ...
        'MaximumAbsoluteError',maximumAbsoluteError, ...
        'MaximumRelativeError_percent',maximumRelativeError, ...
        'RelativeError_percent',relativeErrorPercent, ...
        'RelativeMetricRows',relativeRows, ...
        'RelativeMetricCount',relativeMetricCount, ...
        'MeanPredictiveStd',meanPredictiveStd, ...
        'MeanStandardizedResidual',meanStandardizedResidual, ...
        'SDStandardizedResidual',sdStandardizedResidual, ...
        'RMSStandardizedResidual',rmsStandardizedResidual, ...
        'PredictiveSDToRMSE',predictiveSDToRMSE, ...
        'GaussianNLPD',gaussianNLPD,'GaussianCRPS',gaussianCRPS, ...
        'ProbabilisticMetricRows',probabilisticRows, ...
        'ProbabilisticMetricCount',probabilisticMetricCount, ...
        'PredictiveStdRaw',predictiveStdRaw, ...
        'PredictiveStdSafe',predictiveStdSafe, ...
        'StandardizedResidual',standardizedResidual, ...
        'IntervalLevels',intervalLevels, ...
        'IntervalCriticalValues',criticalValues, ...
        'IntervalIncluded',intervalIncluded, ...
        'CoveragePercent',coveragePercent, ...
        'GaussianPointNLPD',pointNLPD, ...
        'GaussianPointCRPS',pointCRPS, ...
        'NRMSEUnavailableReason',nrmseReason, ...
        'RelativeMetricUnavailableReason',relativeReason, ...
        'ProbabilisticMetricUnavailableReason',probabilisticReason, ...
        'PredictiveSDSafeguard',safeguard);
end
