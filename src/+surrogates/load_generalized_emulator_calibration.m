function calibration=load_generalized_emulator_calibration(pathValue,varargin)
%LOAD_GENERALIZED_EMULATOR_CALIBRATION Load the frozen emulator-error calibration of the generalized route.
%   CALIBRATION = surrogates.load_generalized_emulator_calibration(PATH, ...) reads
%   the calibration record PATH (setting generalized.surrogates.emulatorCalibration;
%   thesis: config/generalized_emulator_calibration.json): the
%   shared exponent gamma and the six output scales tau^2 of the calibrated
%   emulator variance of the generalized GP, with the development and
%   held-out cases and the training cohorts it was fitted on.
%   Name-value options: 'ExpectedInputOrder' and 'ExpectedOutputOrder' (the
%   route's seven inputs and six outputs), 'ExpectedSnapshot' (the name of
%   the configured dataset snapshot) and 'ExpectedSplitSeed'. It refuses a
%   record of another route, variance formula, snapshot or split seed, with
%   other input or output orders, or with an invalid gamma or tau^2. The GP
%   the record was fitted for is compared with the configured one where the
%   configuration is built (study.project_config).
%   CALIBRATION adds artifact_path, the record's file. The record is read
%   as it is.
%   Side effects: none.

    parser=inputParser;
    addParameter(parser,'ExpectedInputOrder',{},@(x)iscell(x)||isstring(x));
    addParameter(parser,'ExpectedOutputOrder',{},@(x)iscell(x)||isstring(x));
    addParameter(parser,'ExpectedSnapshot','',@text_scalar);
    addParameter(parser,'ExpectedSplitSeed',NaN,@numeric_scalar);
    parse(parser,varargin{:});

    pathValue=char(string(pathValue));
    assert(isfile(pathValue), ...
        'surrogates:load_generalized_emulator_calibration:MissingArtifact', ...
        'The frozen generalized calibration is missing: %s',pathValue);
    calibration=jsondecode(fileread(pathValue));
    required={'schema_version','route','variance_formula_version','kernel', ...
        'trend','correlation_type','optimizer','nugget','snapshot', ...
        'split_seed','input_order','output_order','development_case_ids', ...
        'internal_heldout_case_ids_excluded','shared_gamma', ...
        'tau_squared_mbar2','output_data_contract'};
    schema=char(string(calibration.schema_version));
    missing=setdiff(required,fieldnames(calibration),'stable');
    assert(isempty(missing), ...
        'surrogates:load_generalized_emulator_calibration:Schema', ...
        'The calibration %s lacks the fields %s.',pathValue,strjoin(missing,', '));
    assert(ismember(schema,{'routeR_emulator_error_calibration_v2', ...
            'routeR_emulator_error_calibration_v3'})&& ...
        strcmp(calibration.route,'real_extended')&& ...
        strcmp(calibration.variance_formula_version, ...
        'tempered_local_diagonal_v1'), ...
        'surrogates:load_generalized_emulator_calibration:ModelContract', ...
        ['The calibration %s is not a generalized-route calibration of the ' ...
         'tempered local diagonal emulator variance (schema %s, route %s, formula %s).'], ...
        pathValue,schema,calibration.route,calibration.variance_formula_version);

    inputOrder=cellstr(string(calibration.input_order(:))).';
    outputOrder=cellstr(string(calibration.output_order(:))).';
    expectedInputs=cellstr(string(parser.Results.ExpectedInputOrder(:))).';
    expectedOutputs=cellstr(string(parser.Results.ExpectedOutputOrder(:))).';
    assert(isequal(inputOrder,expectedInputs)&&isequal(outputOrder,expectedOutputs), ...
        'surrogates:load_generalized_emulator_calibration:InputOutputOrder', ...
        'The calibration lists its inputs and outputs in another order than the route.');
    expectedSeed=double(parser.Results.ExpectedSplitSeed);
    assert(strcmp(calibration.snapshot, ...
            char(string(parser.Results.ExpectedSnapshot)))&& ...
        double(calibration.split_seed)==expectedSeed, ...
        'surrogates:load_generalized_emulator_calibration:DatasetContract', ...
        ['The calibration was fitted on snapshot %s with split seed %d; the ' ...
         'configuration uses snapshot %s with split seed %d.'], ...
        calibration.snapshot,double(calibration.split_seed), ...
        char(string(parser.Results.ExpectedSnapshot)),expectedSeed);
    gamma=double(calibration.shared_gamma);
    tauSquared=reshape(double(calibration.tau_squared_mbar2),1,[]);
    assert(isscalar(gamma)&&isfinite(gamma)&&gamma>=0&&gamma<=1&& ...
        numel(tauSquared)==6&&all(isfinite(tauSquared))&&all(tauSquared>0), ...
        'surrogates:load_generalized_emulator_calibration:NumericalContract', ...
        ['The calibration needs a shared gamma in [0,1] and six finite ' ...
         'positive tau^2 values.']);

    calibration.input_order=inputOrder;
    calibration.output_order=outputOrder;
    calibration.shared_gamma=gamma;
    calibration.tau_squared_mbar2=tauSquared;
    calibration.development_case_ids= ...
        reshape(double(calibration.development_case_ids),1,[]);
    calibration.internal_heldout_case_ids_excluded=reshape(double( ...
        calibration.internal_heldout_case_ids_excluded),1,[]);
    calibration.artifact_path=pathValue;
end

function result=text_scalar(value)
    result=ischar(value)||(isstring(value)&&isscalar(value));
end

function result=numeric_scalar(value)
    result=isnumeric(value)&&isscalar(value);
end
