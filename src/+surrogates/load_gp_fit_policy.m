function policy=load_gp_fit_policy(path)
%LOAD_GP_FIT_POLICY Load the GP fit policy of the generalized route.
%   POLICY = surrogates.load_gp_fit_policy(PATH) reads the fit policy PATH
%   (setting generalized.surrogates.fitPolicy; thesis: config/generalized_gp_fit_policy.json): the kernel
%   and, for the outputs that select among declared starts, the starts, the
%   HGA iteration limit and the selection rule. It refuses an incomplete policy,
%   another kernel than Matern-3/2 or Matern-5/2, invalid starts and an
%   output listed twice. Side effects: none.
    policy=jsondecode(fileread(path));
    assert(isstruct(policy)&&isscalar(policy)&& ...
        all(isfield(policy,{'schemaVersion','kernel','outputPolicies'}))&& ...
        strcmp(policy.schemaVersion,'generalized_gp_fit_policy_v1')&& ...
        ismember(string(policy.kernel),["Matern-3_2","Matern-5_2"]), ...
        'surrogates:load_gp_fit_policy:Schema', ...
        ['The GP fit policy %s must be a generalized_gp_fit_policy_v1 record ' ...
         'with a Matern-3/2 or Matern-5/2 kernel and output policies.'],path);
    p=policy.outputPolicies;indexes=zeros(1,numel(p));
    for k=1:numel(p)
        assert(all(isfield(p(k),{'outputIndex','seeds','maxIter','selectionRule'})), ...
            'surrogates:load_gp_fit_policy:OutputSchema', ...
            'Output policy %d of %s needs outputIndex, seeds, maxIter and selectionRule.',k,path);
        validateattributes(p(k).outputIndex,{'numeric'}, ...
            {'scalar','integer','>=',1,'<=',6});
        validateattributes(p(k).maxIter,{'numeric'}, ...
            {'scalar','real','finite','integer','positive'});
        seeds=p(k).seeds;
        assert(isnumeric(seeds)&&isvector(seeds)&&~isempty(seeds)&& ...
            all(isfinite(seeds))&&all(seeds==fix(seeds))&& ...
            all(seeds>0&seeds<2^32)&&numel(unique(seeds))==numel(seeds)&& ...
            strcmp(p(k).selectionRule, ...
                'minimum_reevaluated_analytic_loo_mse_ordered_seed_tie_v1'), ...
            'surrogates:load_gp_fit_policy:Selection', ...
            ['Output policy %d of %s needs distinct integer starts from 1 to ' ...
             '2^32-1 and the rule minimum_reevaluated_analytic_loo_mse_ordered_seed_tie_v1.'],k,path);
        indexes(k)=p(k).outputIndex;
        policy.outputPolicies(k).seeds=reshape(double(seeds),1,[]);
    end
    assert(numel(unique(indexes))==numel(indexes), ...
        'surrogates:load_gp_fit_policy:DuplicateOutput', ...
        'The GP fit policy %s lists an output more than once.',path);
end
