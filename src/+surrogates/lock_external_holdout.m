function lock_external_holdout(cfg)
%LOCK_EXTERNAL_HOLDOUT Record that the external cases were left unevaluated.
%   surrogates.lock_external_holdout(CFG) writes CFG.files.externalHoldoutStatus
%   with status 'locked_not_evaluated' after a fit of the surrogates that
%   did not evaluate the held-out external cases. It refuses when the run
%   folder already holds an external assessment: that assessment describes
%   the models that the new fit replaced.
%   Side effects: writes one JSON file.

    validationRoot=cfg.paths.surrogateAssessment;
    assessment={cfg.files.validation, ...
        fullfile(validationRoot,'gp_validation_metrics.csv'), ...
        fullfile(validationRoot,'gp_validation_metrics_raw_uqlab.csv'), ...
        fullfile(validationRoot,'pce_validation_metrics.csv'), ...
        fullfile(validationRoot,'validation_predictions.csv')};
    present=assessment(cellfun(@isfile,assessment));
    if ~isempty(present)
        error('surrogates:lock_external_holdout:AssessmentPresent', ...
            ['This run already holds an external assessment of the earlier ' ...
             'surrogates (%s). Fit the surrogates in a new run, or run the ' ...
             'steps ''surrogates'' and ''surrogate_assessment'' together.'], ...
            present{1});
    end
    externalCount=external_case_count(cfg.files.dataset);
    status=struct( ...
        'schema_version','external_holdout_evaluation_status_v2', ...
        'status','locked_not_evaluated', ...
        'methodological_role','external_holdout', ...
        'case_count',externalCount,'prediction_row_count',0,'metric_row_count',0, ...
        'external_outputs_loaded',false, ...
        'statement',sprintf(['The %d complete external-test cases were excluded ' ...
            'from all fits and from ' ...
            'the prospective final model-selection/calibration procedure ' ...
            'and were locked for later external evaluation from this ' ...
            'development protocol onward.'],externalCount));
    utils.atomic_write_json(cfg.files.externalHoldoutStatus,status, ...
        'AllowReplace',true);
end

function count=external_case_count(datasetPath)
    saved=utils.load_plain_mat(datasetPath,'counts','validationCaseIDs');
    if isfield(saved,'counts')&&isfield(saved.counts,'externalTestCases')
        count=double(saved.counts.externalTestCases);
    else
        count=numel(saved.validationCaseIDs);
    end
end
