function calibration=load_emulator_error_calibration(pathValue,varargin)
%LOAD_EMULATOR_ERROR_CALIBRATION Load the frozen emulator-error calibration of the fixed route.
%   CALIBRATION = surrogates.load_emulator_error_calibration(PATH) reads the
%   calibration record PATH (config/emulator_error_calibration_*.json): the
%   shared exponent gamma and the six output scales tau^2 of the calibrated
%   emulator variance v = tau^2 h^gamma (surrogates.calibrated_emulator_variance),
%   with the development and external cases and the training cohorts it was
%   fitted on. It refuses a record that is not a fixed-route calibration of
%   the tempered local diagonal form, or whose gamma or tau^2 are invalid.
%   Name-value option: 'ExpectedOutputOrder', the canonical output order
%   (six names) that the record must list.
%   CALIBRATION adds artifact_path, the record's file. The record is read
%   as it is.
%   Side effects: none.

    parser=inputParser;
    addParameter(parser,'ExpectedOutputOrder',{},@(x)iscell(x)||isstring(x));
    parse(parser,varargin{:});
    pathValue=char(string(pathValue));
    assert(isfile(pathValue), ...
        'surrogates:load_emulator_error_calibration:MissingArtifact', ...
        'The frozen emulator-error calibration is missing: %s',pathValue);
    calibration=jsondecode(fileread(pathValue));
    required={'schema_version','route','variance_formula_version', ...
        'kernel','trend','correlation_type','optimizer','nugget', ...
        'development_case_ids','external_holdout_case_ids_excluded', ...
        'output_order','shared_gamma','tau_squared_mbar2', ...
        'output_data_contract'};
    missing=setdiff(required,fieldnames(calibration),'stable');
    assert(isempty(missing), ...
        'surrogates:load_emulator_error_calibration:Schema', ...
        'The calibration %s lacks the fields %s.',pathValue,strjoin(missing,', '));
    assert(strcmp(calibration.schema_version, ...
            'routeR_emulator_error_calibration_v2')&& ...
        strcmp(calibration.route,'real')&& ...
        strcmp(calibration.variance_formula_version, ...
        'tempered_local_diagonal_v1'), ...
        'surrogates:load_emulator_error_calibration:ModelContract', ...
        ['The calibration %s is not a fixed-route calibration of the tempered ' ...
         'local diagonal emulator variance (schema %s, route %s, formula %s).'], ...
        pathValue,calibration.schema_version,calibration.route, ...
        calibration.variance_formula_version);

    outputOrder=cellstr(string(calibration.output_order(:))).';
    expected=cellstr(string(parser.Results.ExpectedOutputOrder(:))).';
    if ~isempty(expected)
        assert(isequal(outputOrder,expected), ...
            'surrogates:load_emulator_error_calibration:OutputOrder', ...
            'The calibration lists the outputs as %s instead of %s.', ...
            strjoin(outputOrder,', '),strjoin(expected,', '));
    end
    gamma=double(calibration.shared_gamma);
    tauSquared=reshape(double(calibration.tau_squared_mbar2),1,[]);
    assert(numel(outputOrder)==6&&numel(unique(string(outputOrder)))==6&& ...
        isscalar(gamma)&&isfinite(gamma)&&gamma>=0&&gamma<=1&& ...
        numel(tauSquared)==6&&all(isfinite(tauSquared))&& ...
        all(tauSquared>0), ...
        'surrogates:load_emulator_error_calibration:NumericalContract', ...
        ['The calibration needs six distinct outputs, a shared gamma in [0,1] ' ...
         'and six finite positive tau^2 values.']);

    calibration.output_order=outputOrder;
    calibration.shared_gamma=gamma;
    calibration.tau_squared_mbar2=tauSquared;
    calibration.development_case_ids= ...
        reshape(double(calibration.development_case_ids),1,[]);
    calibration.external_holdout_case_ids_excluded=reshape(double( ...
        calibration.external_holdout_case_ids_excluded),1,[]);
    calibration.artifact_path=pathValue;
end
