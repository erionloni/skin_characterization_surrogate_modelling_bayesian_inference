function V = validate_generalized_refit(gp, pce, data, cfg)
%VALIDATE_GENERALIZED_REFIT The held-out validation of the refit's selected models, done once.
%   V = surrogates.validate_generalized_refit(GP, PCE, DATA, CFG) evaluates
%   the selected GP and PCE ensembles on the held-out cases of DATA
%   (X_test, Y_test) and returns the per-output metrics and support
%   information. The models were selected before, from development
%   evidence only; this function is the first to read the held-out data.
%   Side effects: none.
%   Computation: seconds (UQLab predictions).

    % Held-out outcomes are read only on explicit request (CLN-003 #15).
    assert(logical(cfg.stage2.evaluateExternalHoldout), ...
        'surrogates:validate_generalized_refit:ExternalEvaluationDisabled', ...
        ['The held-out validation reads held-out outcomes; it runs only when ' ...
         'external evaluation is requested explicitly.']);
    bounds=data.inputBounds;
    [developmentX,developmentY,developmentCaseIDs]= ...
        output_aware_development(data);
    [trainLeaveOneOut,testDistance,supportThreshold,weakThreshold, ...
        supportClass,supportTrainingCounts]=output_specific_support( ...
        developmentX,developmentY,data.X_test,bounds);
    assessmentRole=calibration_assessment_role(cfg);

    gpTest=surrogates.evaluate_generalized_gp(gp,data.X_test,cfg);
    gpMean=gpTest.GPMean;
    [pceMean,pceVar]=surrogates.evaluate(pce,data.X_test,'pce');
    family={"gp",gpMean,gpTest.CalibratedEmulatorVariance, ...
            "tempered_local_diagonal_production"; ...
        "pce",pceMean,pceVar,"not_available_for_pce"};
    metricsByFamily=cell(2,1);residualsByFamily=cell(2,1);
    protocolByFamily=cell(2,1);worstByFamily=cell(2,1);
    coverageByFamily=cell(2,1);inputErrorByFamily=cell(2,1);
    outputGroupsByFamily=cell(2,1);
    for familyIndex=1:size(family,1)
        familyName=family{familyIndex,1};
        mu=family{familyIndex,2};variance=family{familyIndex,3};
        [oneMetrics,oneResidual,oneCoverage]=family_metrics( ...
            familyName,mu,variance,data,cfg,testDistance,supportClass, ...
            family{familyIndex,4},assessmentRole);
        oneProtocol=protocol_metrics(familyName,mu,data,cfg, ...
            supportClass,bounds);
        oneWorst=worst_cases(familyName,mu,data,testDistance,supportClass,cfg);
        oneInput=input_error_relationship(familyName,mu,data,cfg);
        oneGroups=output_group_metrics(familyName,mu,data.Y_test);
        metricsByFamily{familyIndex}=oneMetrics;
        residualsByFamily{familyIndex}=oneResidual;
        coverageByFamily{familyIndex}=oneCoverage;
        protocolByFamily{familyIndex}=oneProtocol;
        worstByFamily{familyIndex}=oneWorst;
        inputErrorByFamily{familyIndex}=oneInput;
        outputGroupsByFamily{familyIndex}=oneGroups;
    end
    metrics=vertcat(metricsByFamily{:});
    residuals=vertcat(residualsByFamily{:});
    coverage=vertcat(coverageByFamily{:});
    protocol=vertcat(protocolByFamily{:});
    worst=vertcat(worstByFamily{:});
    inputError=vertcat(inputErrorByFamily{:});
    outputGroups=vertcat(outputGroupsByFamily{:});
    [gpRawMetrics,gpRawResiduals,gpRawCoverage]=family_metrics( ...
        "gp",gpMean,gpTest.RawUQLabVariance,data,cfg,testDistance, ...
        supportClass,"raw_uqlab_predictive_variance_reference",assessmentRole);
    gpTraining=surrogates.evaluate_generalized_gp(gp,developmentX,cfg);
    gpTrainingMean=gpTraining.GPMean;
    [pceTrainingMean,pceTrainingVariance]= ...
        surrogates.evaluate(pce,developmentX,'pce');
    gpCV=cv_prediction_matrix(gp,developmentCaseIDs,nOutput(data));
    pceCV=cv_prediction_matrix(pce,developmentCaseIDs,nOutput(data));
    cohortMetrics=[ ...
        cohort_metric_rows("gp","training",developmentY,gpTrainingMean, ...
            gpTraining.CalibratedEmulatorVariance,data.outputNames, ...
            "tempered_local_diagonal_production"); ...
        cohort_metric_rows("gp","cross_validation",developmentY,gpCV, ...
            nan(size(gpCV)),data.outputNames, ...
            "not_saved_by_canonical_training_cv"); ...
        cohort_metric_rows("gp",assessmentRole,data.Y_test,gpMean, ...
            gpTest.CalibratedEmulatorVariance,data.outputNames, ...
            "tempered_local_diagonal_production"); ...
        cohort_metric_rows("pce","training",developmentY,pceTrainingMean, ...
            pceTrainingVariance,data.outputNames,"not_available_for_pce"); ...
        cohort_metric_rows("pce","cross_validation",developmentY,pceCV, ...
            nan(size(pceCV)),data.outputNames,"not_available_for_pce"); ...
        cohort_metric_rows("pce",assessmentRole,data.Y_test,pceMean, ...
            pceVar,data.outputNames,"not_available_for_pce")];
    predictions=wide_prediction_table(gpTest,pceMean, ...
        data,testDistance,supportClass,assessmentRole);
    trainingPredictions=cohort_prediction_table( ...
        developmentCaseIDs,developmentY,gpTraining,pceTrainingMean, ...
        pceTrainingVariance,data,"training");
    emptyGP=empty_gp_prediction(size(gpCV,1),size(gpCV,2));
    emptyGP.GPMean=gpCV;
    crossValidationPredictions=cohort_prediction_table( ...
        developmentCaseIDs,developmentY,emptyGP,pceCV,nan(size(pceCV)), ...
        data,"cross_validation");
    V=struct( ...
        'schemaVersion', ...
            'real_extended_stage2_validation_v4_output_specific_support', ...
        'heldoutUsedForModelSelection',false, ...
        'metrics',metrics,'residuals',residuals, ...
        'gpRawMetrics',gpRawMetrics,'gpRawResiduals',gpRawResiduals, ...
        'predictions',predictions, ...
        'trainingPredictions',trainingPredictions, ...
        'crossValidationPredictions',crossValidationPredictions, ...
        'cohortMetrics',cohortMetrics, ...
        'predictiveCoverage',coverage,'protocolMetrics',protocol, ...
        'gpRawPredictiveCoverage',gpRawCoverage, ...
        'worstCases',worst,'inputErrorRelationships',inputError, ...
        'outputGroupMetrics',outputGroups, ...
        'gpMean',gpMean, ...
        'gpRawUQLabVariance',gpTest.RawUQLabVariance, ...
        'gpRawUQLabSD',gpTest.RawUQLabSD, ...
        'gpProcessVariance',gpTest.ProcessVariance, ...
        'gpLocalVarianceShapeH',gpTest.LocalVarianceShapeH, ...
        'gpCalibratedEmulatorVariance', ...
            gpTest.CalibratedEmulatorVariance, ...
        'gpCalibratedEmulatorSD',gpTest.CalibratedEmulatorSD, ...
        'pceMean',pceMean,'pceVariance',pceVar, ...
        'testNearestTrainingDistance',testDistance, ...
        'trainLeaveOneOutDistance',trainLeaveOneOut, ...
        'supportClass',supportClass, ...
        'supportThreshold',supportThreshold, ...
        'extrapolationThreshold',weakThreshold, ...
        'supportTrainingCounts',supportTrainingCounts, ...
        'supportCohortSemantics', ...
            'finite_output_specific_development_rows_no_imputation', ...
        'assessmentRole',assessmentRole);
end

function T=cohort_prediction_table(caseIDs,truth,gpPrediction, ...
        pceMean,pceVariance,data,cohort)
    families={"gp",gpPrediction.GPMean, ...
            gpPrediction.CalibratedEmulatorVariance; ...
        "pce",pceMean,pceVariance};
    nCase=size(truth,1);nOutput=numel(data.outputNames);
    parts=cell(2*nOutput,1);cursor=0;
    for f=1:2
        prediction=double(families{f,2});variance=double(families{f,3});
        for j=1:nOutput
            cursor=cursor+1;mu=prediction(:,j);oneTruth=double(truth(:,j));
            oneVariance=variance(:,j);sd=sqrt(max(oneVariance,0));
            sd(~isfinite(oneVariance))=NaN;residual=mu-oneTruth;
            if f==1
                rawVariance=gpPrediction.RawUQLabVariance(:,j);
                rawSD=gpPrediction.RawUQLabSD(:,j);
                calibratedVariance= ...
                    gpPrediction.CalibratedEmulatorVariance(:,j);
                calibratedSD=gpPrediction.CalibratedEmulatorSD(:,j);
                processVariance=repmat( ...
                    gpPrediction.ProcessVariance(j),nCase,1);
                localShape=gpPrediction.LocalVarianceShapeH(:,j);
            else
                rawVariance=nan(nCase,1);rawSD=nan(nCase,1);
                calibratedVariance=nan(nCase,1);calibratedSD=nan(nCase,1);
                processVariance=nan(nCase,1);localShape=nan(nCase,1);
            end
            parts{cursor}=table(repmat(string(families{f,1}),nCase,1), ...
                repmat(string(cohort),nCase,1),double(caseIDs(:)), ...
                repmat(j,nCase,1),repmat(string(data.outputNames{j}),nCase,1), ...
                oneTruth,mu,oneVariance,sd,rawVariance,rawSD, ...
                calibratedVariance,calibratedSD,processVariance,localShape, ...
                residual,abs(residual), ...
                'VariableNames',{'Family','Cohort','CaseID','OutputIndex', ...
                'Output','COMSOL','Prediction','PredictiveVariance', ...
                'PredictiveSD','RawUQLabVariance','RawUQLabSD', ...
                'CalibratedEmulatorVariance','CalibratedEmulatorSD', ...
                'ProcessVariance','LocalVarianceShapeH','Residual', ...
                'AbsoluteError'});
        end
    end
    T=vertcat(parts{:});
end

function tableOut=output_group_metrics(family,prediction,truth)
    definitions={ ...
        'probe','D2',1:3;'probe','D6',4:6; ...
        'cycle','cycle1',[1 4];'cycle','cycle2',[2 5]; ...
        'cycle','cycle3',[3 6]};
    rows=cell(size(definitions,1),1);
    for i=1:size(definitions,1)
        columns=definitions{i,3};
        residual=prediction(:,columns)-truth(:,columns);
        scale=max(truth(:,columns),[],1)-min(truth(:,columns),[],1);
        normalized=residual./max(scale,eps);
        rows{i}=table(string(family),string(definitions{i,1}), ...
            string(definitions{i,2}),numel(residual), ...
            sqrt(mean(residual(:).^2,'omitnan')), ...
            sqrt(mean(normalized(:).^2,'omitnan')), ...
            mean(abs(residual(:)),'omitnan'), ...
            'VariableNames',{'Family','Grouping','Level','NScalarErrors', ...
            'RMSE','NRMSE','MAE'});
    end
    tableOut=vertcat(rows{:});
end

function [metrics,residualTable,coverageTable]=family_metrics( ...
        family,mu,variance,data,cfg,distance,supportClass,semantics,cohort)
    nOutput=numel(data.outputNames);
    coverageLevels=[0.50,0.80,0.90,0.95];
    covValues=nan(nOutput,numel(coverageLevels));
    rows=cell(nOutput,1);metricRows=cell(nOutput,1);
    for j=1:nOutput
        output=string(data.outputNames{j});
        truth=data.Y_test(:,j);prediction=mu(:,j);
        available=isfinite(prediction)&isfinite(truth);
        if ~any(available)
            metricRows{j}=unavailable_metric_row( ...
                output,j,string(family),cohort);
            rows{j}=empty_residual_table(cfg);
            continue;
        end
        metric=surrogates.surrogate_quality_metrics( ...
            truth(available),prediction(available),variance(available,j), ...
            output,'IntervalLevels',coverageLevels);
        metric.OutputIndex(:)=j;
        varianceErrorCorrelation=NaN;
        residual=prediction-truth;
        if strcmp(family,'gp')
            good=available&isfinite(variance(:,j));
            if nnz(good)>=3
                varianceErrorCorrelation=utils.pearson_correlation( ...
                    variance(good,j),residual(good).^2);
            end
        end
        metricRows{j}=decorate_metric_row(metric,string(family), ...
            varianceErrorCorrelation,string(semantics),cohort);
        primitive=surrogates.surrogate_metric_primitives( ...
            truth(available),prediction(available),variance(available,j), ...
            'IntervalLevels',coverageLevels);
        predictionStd=nan(size(truth));z=nan(size(truth));
        relativeError=nan(size(truth));pointNLPD=nan(size(truth));
        pointCRPS=nan(size(truth));included=false(numel(truth),4);
        predictionStd(available)=primitive.PredictiveStdRaw;
        z(available)=primitive.StandardizedResidual;
        relativeError(available)=primitive.RelativeError_percent;
        pointNLPD(available)=primitive.GaussianPointNLPD;
        pointCRPS(available)=primitive.GaussianPointCRPS;
        included(available,:)=primitive.IntervalIncluded;
        covValues(j,:)=primitive.CoveragePercent/100;
        n=numel(truth);
        rows{j}=table(repmat(string(family),n,1), ...
            repmat(j,n,1),repmat(output,n,1),double(data.testCaseIDs(:)),truth, ...
            prediction,variance(:,j),predictionStd,residual,abs(residual), ...
            residual.^2,relativeError,z,included(:,1),included(:,2), ...
            included(:,3),included(:,4),pointNLPD,pointCRPS, ...
            distance(:,j),supportClass(:,j), ...
            'VariableNames',{'Family','OutputIndex','Output','CaseID','Truth_mbar', ...
            'Prediction_mbar','PredictiveVariance_mbar2', ...
            'PredictiveStd_mbar','Residual_mbar','AbsoluteError_mbar', ...
            'SquaredError_mbar2','RelativeError_percent', ...
            'StandardizedResidual','Included50','Included80','Included90', ...
            'Included95','GaussianPointNLPD','GaussianPointCRPS', ...
            'NearestTrainingDistance7D','SupportClass'});
        rows{j}.UncertaintySemantics=repmat(string(semantics),n,1);
        for p=1:numel(cfg.realExtended.learningInputNames)
            rows{j}.(cfg.realExtended.learningInputNames{p})=data.X_test(:,p);
        end
    end
    metrics=vertcat(metricRows{:});
    residualTable=vertcat(rows{:});
    [fGrid,oGrid,lGrid]=ndgrid(string(family),string(data.outputNames), ...
        coverageLevels);
    coverageTable=table(fGrid(:),oGrid(:),lGrid(:),covValues(:), ...
        repmat(string(semantics),numel(fGrid),1), ...
        'VariableNames',{'Family','Output','NominalCoverage', ...
        'EmpiricalCoverage','UncertaintySemantics'});
end

function row=decorate_metric_row( ...
        row,family,varianceErrorCorrelation,semantics,cohort)
    row.Family=repmat(family,height(row),1);
    row=movevars(row,'Family','Before',1);
    row.Cohort=repmat(string(cohort),height(row),1);
    row.Units=repmat("mbar",height(row),1);
    row.UncertaintySemantics=repmat(string(semantics),height(row),1);
    row.MeanSquaredStandardizedResidual=row.RMSStandardizedResidual.^2;
    row.VarianceSquaredErrorCorrelation(:)=varianceErrorCorrelation;
    row.Status=repmat("COMPUTED",height(row),1);
end

function row=unavailable_metric_row(output,outputIndex,family,cohort)
    row=surrogates.surrogate_quality_metrics([0;1],[0;1],[NaN;NaN],output);
    numericNames=row.Properties.VariableNames( ...
        varfun(@isnumeric,row,'OutputFormat','uniform'));
    for i=1:numel(numericNames),row.(numericNames{i})(:)=NaN;end
    row.OutputIndex(:)=outputIndex;row.Output(:)=output;
    row.ObservationCount(:)=0;
    row.NRMSEUnavailableReason(:)="prediction_unavailable";
    row.RelativeMetricUnavailableReason(:)="prediction_unavailable";
    row.ProbabilisticMetricUnavailableReason(:)="prediction_unavailable";
    row=decorate_metric_row(row,family,NaN,"not_available",cohort);
    row.Status(:)="UNAVAILABLE";
end

function count=nOutput(data)
    count=numel(data.outputNames);
end

function prediction=cv_prediction_matrix(ensemble,caseIDs,nOutputs)
    prediction=nan(numel(caseIDs),nOutputs);
    if ~isstruct(ensemble)||~isfield(ensemble,'records'),return;end
    records=ensemble.records;
    for j=1:min(nOutputs,numel(records))
        record=records(j);
        if isfield(record,'executionStatus')&& ...
                strcmp(record.executionStatus,'completed')&& ...
                isfield(record,'cv')&&isstruct(record.cv)&& ...
                isfield(record.cv,'prediction')&& ...
                isfield(record,'trainingCaseIDs')&& ...
                numel(record.cv.prediction)==numel(record.trainingCaseIDs)
            [found,loc]=ismember(double(record.trainingCaseIDs(:)), ...
                double(caseIDs(:)));
            assert(all(found)&&numel(unique(loc))==numel(loc), ...
                'surrogates:validate_generalized_refit:CVCaseIDs', ...
                'Saved scalar CV CaseIDs do not match the development pool.');
            prediction(loc,j)=double(record.cv.prediction(:));
        end
    end
end

function [X,Y,caseIDs]=output_aware_development(data)
    if all(isfield(data,{'X_development_all','Y_development_all', ...
            'developmentCaseIDsAll'}))
        X=double(data.X_development_all);
        Y=double(data.Y_development_all);
        caseIDs=double(data.developmentCaseIDsAll(:));
    else
        X=double(data.X_train);Y=double(data.Y_train);
        caseIDs=double(data.trainCaseIDs(:));
    end
    assert(size(X,1)==size(Y,1)&&size(Y,2)==6&& ...
        numel(caseIDs)==size(X,1)&&all(isfinite(X),'all')&& ...
        ~any(isinf(Y),'all'), ...
        'surrogates:validate_generalized_refit:DevelopmentContract', ...
        ['The development cases need one finite value per input, six outputs (no ' ...
         'infinite values) and one case ID each.']);
end

function rows=cohort_metric_rows(family,cohort,truth,prediction,variance, ...
        outputNames,uncertaintySemantics)
    n=numel(outputNames);parts=cell(n,1);
    for j=1:n
        available=isfinite(truth(:,j))&isfinite(prediction(:,j));
        if any(available)
            one=surrogates.surrogate_quality_metrics(truth(available,j), ...
                prediction(available,j),variance(available,j), ...
                outputNames{j});
            one.OutputIndex(:)=j;
        else
            one=unavailable_metric_row( ...
                string(outputNames{j}),j,string(family),cohort);
            one(:,intersect({'Family','Cohort','Units', ...
                'UncertaintySemantics', ...
                'MeanSquaredStandardizedResidual', ...
                'VarianceSquaredErrorCorrelation','Status'}, ...
                one.Properties.VariableNames,'stable'))=[];
        end
        one.Family=repmat(string(family),height(one),1);
        one.Cohort=repmat(string(cohort),height(one),1);
        one.Units=repmat("mbar",height(one),1);
        one.UncertaintySemantics=repmat( ...
            string(uncertaintySemantics),height(one),1);
        one=movevars(one,{'Family','Cohort'},'Before',1);
        parts{j}=one;
    end
    rows=vertcat(parts{:});
end

function T=wide_prediction_table(gpPrediction,pceMean,data, ...
        distance,supportClass,assessmentRole)
    nCase=size(data.Y_test,1);nOut=numel(data.outputNames);
    parts=cell(nOut,1);
    for j=1:nOut
        truth=double(data.Y_test(:,j));mu=double(gpPrediction.GPMean(:,j));
        rawVariance=double(gpPrediction.RawUQLabVariance(:,j));
        calibratedVariance=double( ...
            gpPrediction.CalibratedEmulatorVariance(:,j));
        rawMetric=surrogates.surrogate_metric_primitives( ...
            truth,mu,rawVariance);
        calibratedMetric=surrogates.surrogate_metric_primitives( ...
            truth,mu,calibratedVariance);
        pceMu=double(pceMean(:,j));pceResidual=pceMu-truth;
        OutputIndex=repmat(j,nCase,1);
        Output=repmat(string(data.outputNames{j}),nCase,1);
        Units=repmat("mbar",nCase,1);
        CaseID=double(data.testCaseIDs(:));
        MethodologicalRole=repmat(string(assessmentRole),nCase,1);
        COMSOL=truth;GPMean=mu;
        RawUQLabVariance=rawVariance;RawUQLabSD=rawMetric.PredictiveStdRaw;
        ProcessVariance=repmat(gpPrediction.ProcessVariance(j),nCase,1);
        LocalVarianceShapeH=gpPrediction.LocalVarianceShapeH(:,j);
        CalibratedEmulatorVariance=calibratedVariance;
        CalibratedEmulatorSD=calibratedMetric.PredictiveStdRaw;
        GPResidual=calibratedMetric.Residual;
        GPAbsoluteError=calibratedMetric.AbsoluteResidual;
        GPRelativeErrorPercent=calibratedMetric.RelativeError_percent;
        RawUQLabStandardizedResidual=rawMetric.StandardizedResidual;
        CalibratedStandardizedResidual= ...
            calibratedMetric.StandardizedResidual;
        RawIncluded50=rawMetric.IntervalIncluded(:,1);
        RawIncluded80=rawMetric.IntervalIncluded(:,2);
        RawIncluded90=rawMetric.IntervalIncluded(:,3);
        RawIncluded95=rawMetric.IntervalIncluded(:,4);
        CalibratedIncluded50=calibratedMetric.IntervalIncluded(:,1);
        CalibratedIncluded80=calibratedMetric.IntervalIncluded(:,2);
        CalibratedIncluded90=calibratedMetric.IntervalIncluded(:,3);
        CalibratedIncluded95=calibratedMetric.IntervalIncluded(:,4);
        RawGaussianNLPD=rawMetric.GaussianPointNLPD;
        RawGaussianCRPS=rawMetric.GaussianPointCRPS;
        CalibratedGaussianNLPD=calibratedMetric.GaussianPointNLPD;
        CalibratedGaussianCRPS=calibratedMetric.GaussianPointCRPS;
        PCEMean=pceMu;PCEResidual=pceResidual;
        PCEAbsoluteError=abs(pceResidual);
        NearestGeneralizedTrainingDistance=distance(:,j);
        SupportClass=supportClass(:,j);
        VarianceFormulaVersion=repmat( ...
            string(gpPrediction.VarianceFormulaVersion),nCase,1);
        UncertaintySemantics=repmat( ...
            "production_tempered_local_diagonal_emulator_variance", ...
            nCase,1);
        one=table(CaseID,MethodologicalRole,OutputIndex,Output,Units,COMSOL, ...
            GPMean,RawUQLabVariance,RawUQLabSD,ProcessVariance, ...
            LocalVarianceShapeH,CalibratedEmulatorVariance, ...
            CalibratedEmulatorSD,GPResidual,GPAbsoluteError, ...
            GPRelativeErrorPercent,RawUQLabStandardizedResidual, ...
            CalibratedStandardizedResidual,RawIncluded50,RawIncluded80, ...
            RawIncluded90,RawIncluded95,CalibratedIncluded50, ...
            CalibratedIncluded80,CalibratedIncluded90,CalibratedIncluded95, ...
            RawGaussianNLPD,RawGaussianCRPS,CalibratedGaussianNLPD, ...
            CalibratedGaussianCRPS,PCEMean, ...
            PCEResidual,PCEAbsoluteError,NearestGeneralizedTrainingDistance, ...
            SupportClass,VarianceFormulaVersion,UncertaintySemantics);
        for p=1:numel(data.inputNames)
            one.(data.inputNames{p})=double(data.X_test(:,p));
        end
        parts{j}=one;
    end
    T=vertcat(parts{:});
end

function tableOut=protocol_metrics(family,mu,data,cfg,supportClass,bounds)
    X=data.X_test;Y=data.Y_test;
    protocolX=X(:,5:7);
    normalized=(protocolX-bounds(5:7,1).')./ ...
        (bounds(5:7,2)-bounds(5:7,1)).';
    default=[cfg.realExtended.defaultProtocol.log10_abs_suction_rate, ...
        cfg.realExtended.defaultProtocol.hold_dur_s, ...
        cfg.realExtended.defaultProtocol.pause_dur_s];
    defaultNormalized=(default-bounds(5:7,1).')./ ...
        (bounds(5:7,2)-bounds(5:7,1)).';
    defaultDistance=sqrt(sum((normalized-defaultNormalized).^2,2));
    corner=any(normalized<=0.15|normalized>=0.85,2);
    definitions={ ...
        'rate_bin',X(:,5)<=median(X(:,5)),"slow","fast"; ...
        'hold_bin',X(:,6)<=median(X(:,6)),"short","long"; ...
        'pause_bin',X(:,7)<=median(X(:,7)),"short","long"; ...
        'protocol_corner',corner,"corner","interior"; ...
        'default_neighbourhood',defaultDistance<=0.25,"near_default","away_default"; ...
        'support',[],"well_supported","weak_or_extrapolative"};
    rows=cell(size(definitions,1)*2*numel(data.outputNames),1);
    cursor=0;
    for d=1:size(definitions,1)
        axisName=string(definitions{d,1});baseSelector=definitions{d,2};
        labels=[string(definitions{d,3}),string(definitions{d,4})];
        for level=1:2
            for j=1:numel(data.outputNames)
                if axisName=="support"
                    selector=supportClass(:,j)=="well_supported";
                else
                    selector=baseSelector;
                end
                if level==1,selected=selector;else,selected=~selector;end
                truth=Y(selected,j);prediction=mu(selected,j);
                valid=isfinite(truth)&isfinite(prediction);
                residual=prediction(valid)-truth(valid);
                if isempty(residual)
                    rmse=NaN;nrmse=NaN;mae=NaN;r2=NaN;
                else
                    rmse=sqrt(mean(residual.^2));
                    nrmse=rmse/max(max(truth(valid))-min(truth(valid)),eps);
                    mae=mean(abs(residual));
                    r2=1-sum(residual.^2)/max(sum((truth(valid)- ...
                        mean(truth(valid))).^2),eps);
                end
                cursor=cursor+1;
                rows{cursor}=table(string(family), ...
                    string(data.outputNames{j}),axisName,labels(level), ...
                    nnz(valid),rmse,nrmse,mae,r2, ...
                    'VariableNames',{'Family','Output','Stratification', ...
                    'Level','N','RMSE','NRMSE_range','MAE','R2'});
            end
        end
    end
    tableOut=vertcat(rows{:});
end

function tableOut=worst_cases(family,mu,data,distance,supportClass,cfg)
    rows=cell(numel(data.outputNames),1);
    for j=1:numel(data.outputNames)
        absoluteError=abs(mu(:,j)-data.Y_test(:,j));
        [~,order]=sort(absoluteError,'descend','MissingPlacement','last');
        order=order(1:min(5,numel(order)));
        n=numel(order);
        one=table(repmat(string(family),n,1), ...
            repmat(string(data.outputNames{j}),n,1), ...
            double(data.testCaseIDs(order)),data.Y_test(order,j),mu(order,j), ...
            absoluteError(order),distance(order,j),supportClass(order,j), ...
            'VariableNames',{'Family','Output','CaseID','Truth_mbar', ...
            'Prediction_mbar','AbsoluteError_mbar', ...
            'NearestTrainingDistance7D','SupportClass'});
        for p=1:numel(cfg.realExtended.learningInputNames)
            one.(cfg.realExtended.learningInputNames{p})=data.X_test(order,p);
        end
        rows{j}=one;
    end
    tableOut=vertcat(rows{:});
end

function tableOut=input_error_relationship(family,mu,data,cfg)
    n=numel(data.outputNames)*numel(cfg.realExtended.learningInputNames);
    Family=repmat(string(family),n,1);Output=strings(n,1);Input=strings(n,1);
    PearsonResidual=nan(n,1);PearsonAbsoluteError=nan(n,1);
    row=0;
    for j=1:numel(data.outputNames)
        residual=mu(:,j)-data.Y_test(:,j);
        for p=1:numel(cfg.realExtended.learningInputNames)
            row=row+1;Output(row)=string(data.outputNames{j});
            Input(row)=string(cfg.realExtended.learningInputNames{p});
            valid=isfinite(residual)&isfinite(data.X_test(:,p));
            if nnz(valid)>=3
                PearsonResidual(row)=utils.pearson_correlation( ...
                    data.X_test(valid,p),residual(valid));
                PearsonAbsoluteError(row)=utils.pearson_correlation( ...
                    data.X_test(valid,p), ...
                    abs(residual(valid)));
            end
        end
    end
    tableOut=table(Family,Output,Input,PearsonResidual,PearsonAbsoluteError);
end

