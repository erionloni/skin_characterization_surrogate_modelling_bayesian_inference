function [developmentDistance,testDistance,supportThreshold, ...
        extrapolationThreshold,supportClass,trainingCounts]= ...
        output_specific_support(developmentX,developmentY,testX,bounds)
    nDevelopment=size(developmentX,1);nTest=size(testX,1);
    nOutput=size(developmentY,2);
    developmentDistance=nan(nDevelopment,nOutput);
    testDistance=nan(nTest,nOutput);
    supportThreshold=nan(1,nOutput);
    extrapolationThreshold=nan(1,nOutput);
    supportClass=strings(nTest,nOutput);
    trainingCounts=zeros(1,nOutput);
    for outputIndex=1:nOutput
        available=isfinite(developmentY(:,outputIndex));
        trainingX=developmentX(available,:);
        trainingCounts(outputIndex)=size(trainingX,1);
        assert(trainingCounts(outputIndex)>=2, ...
            'surrogates:validate_generalized_refit:OutputSupportCohort', ...
            'Output %d has fewer than two development rows.',outputIndex);
        developmentDistance(available,outputIndex)= ...
            leave_one_out_distance(trainingX,bounds);
        testDistance(:,outputIndex)= ...
            surrogates.nearest_normalized_distance( ...
            testX,trainingX,bounds.');
        supportThreshold(outputIndex)=local_quantile( ...
            developmentDistance(available,outputIndex),0.95);
        extrapolationThreshold(outputIndex)=max( ...
            1.5*supportThreshold(outputIndex), ...
            supportThreshold(outputIndex)+eps( ...
            supportThreshold(outputIndex)));
        supportClass(:,outputIndex)="well_supported";
        supportClass(testDistance(:,outputIndex)> ...
            supportThreshold(outputIndex),outputIndex)="weakly_supported";
        supportClass(testDistance(:,outputIndex)> ...
            extrapolationThreshold(outputIndex),outputIndex)="extrapolative";
    end
end

