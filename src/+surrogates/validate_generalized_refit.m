function distance=leave_one_out_distance(X,bounds)
    n=size(X,1);distance=nan(n,1);
    for i=1:n
        reference=X([1:i-1 i+1:n],:);
        distance(i)=surrogates.nearest_normalized_distance( ...
            X(i,:),reference,bounds.');
    end
end

function value=local_quantile(x,p)
    x=sort(x(isfinite(x)));
    if isempty(x),value=NaN;return;end
    index=1+(numel(x)-1)*p;
    lo=floor(index);hi=ceil(index);
    value=x(lo)+(index-lo)*(x(hi)-x(lo));
end

