function status=run_default_protocol_cross_route(cfg,varargin)
%RUN_DEFAULT_PROTOCOL_CROSS_ROUTE Compare the generalized surrogates with the fixed COMSOL results at the default protocol.
%   STATUS = surrogates.run_default_protocol_cross_route(CFG) evaluates the
%   generalized GP (calibrated emulator variance and raw UQLab variance) and
%   PCE (CFG.files.gp, CFG.files.pce) at the default protocol for the
%   fixed-route COMSOL cases of
%   CFG.realExtended.defaultProtocolComparison.referenceDatasetPath, and
%   writes the compatibility record, the reference manifest, predictions,
%   metrics, support, overlap and worst-case tables and the status into
%   CFG.paths.defaultProtocolCrossRoute (or the folder of the name-value
%   option 'OutputRoot'). STATUS is the status record. It reads held-out
%   outcomes, so it runs only when CFG.stage2.evaluateExternalHoldout is
%   true; it trains nothing and never reads a fixed-route surrogate.
%   Side effects: writes the comparison tables (above).
%   Computation: about a minute (UQLab predictions).

    parser=inputParser;
    addParameter(parser,'OutputRoot','', ...
        @(x)ischar(x)||(isstring(x)&&isscalar(x)));
    parse(parser,varargin{:});
    assert(strcmp(cfg.dataMode,'real_extended'), ...
        'surrogates:run_default_protocol_cross_route:Route', ...
        'The default-protocol comparison runs on the generalized route.');
    % Held-out outcomes (Y_test) are read only on explicit request (CLN-003 #15).
    assert(logical(cfg.stage2.evaluateExternalHoldout), ...
        'surrogates:run_default_protocol_cross_route:ExternalEvaluationDisabled', ...
        ['The default-protocol comparison reads held-out outcomes; it runs only ' ...
         'when external evaluation is requested explicitly.']);

    root=char(string(parser.Results.OutputRoot));
    if isempty(root)
        root=cfg.paths.defaultProtocolCrossRoute;
    end
    if ~isfolder(root),mkdir(root);end

    fields={'X_train','Y_train','X_test','Y_test','inputNames','outputNames', ...
        'inputBounds','trainCaseIDs','testCaseIDs'};
    available=who('-file',cfg.files.dataset);
    optional={'X_development_all','Y_development_all', ...
        'developmentCaseIDsAll','developmentOutputAvailabilityMask', ...
        'outputTrainingEvidence'};
    fields=[fields reshape(intersect(optional,available,'stable'),1,[])];
    data=utils.load_plain_mat(cfg.files.dataset,fields{:});
    gp=surrogates.load_ensemble(cfg.files.gp,'gp');
    pce=surrogates.load_ensemble(cfg.files.pce,'pce');
    surrogates.validate_surrogate_ensemble_scope(gp,data,cfg,'gp');
    surrogates.validate_surrogate_ensemble_scope(pce,data,cfg,'pce');
    result=surrogates.default_protocol_comparison(gp,pce,data,cfg);
    result=attach_context(result);
    calibration=cfg.emulatorErrorCalibration;
    result.compatibilityReceipt.variance_formula_version= ...
        calibration.variance_formula_version;
    write_outputs(root,result);
    status=struct( ...
        'schema_version','default_protocol_cross_route_status_v3', ...
        'status',result.status, ...
        'compatibility_status',result.compatibilityStatus, ...
        'provenance_source',result.compatibilityReceipt.provenance_source, ...
        'variance_formula_version',calibration.variance_formula_version, ...
        'eligible_reference_count',result.eligibleReferenceCount, ...
        'primary_external_slice_count',result.primaryExternalSliceCount, ...
        'primary_external_scalar_count', ...
            result.primaryExternalScalarCount, ...
        'fixed_reference_outputs_loaded', ...
            result.fixedReferenceOutputsLoaded, ...
        'reason',result.reason, ...
        'fixed_reference_used_for_training',false, ...
        'fixed_reference_used_for_model_selection',false, ...
        'fixed_route_GP_loaded_or_evaluated',false, ...
        'generalized_models_refitted',false, ...
        'uncertainty_semantics', ...
            'tempered_local_diagonal_calibrated_emulator_variance', ...
        'raw_uqlab_uncertainty_retained_as_reference',true, ...
        'evidence_scope', ...
            'development_only_default_protocol_cross_route_validation', ...
        'environment',utils.environment_line());
    utils.atomic_write_json(fullfile(root, ...
        'default_protocol_comparison_status.json'),status,'AllowReplace',true);
end

function result=attach_context(result)
%ATTACH_CONTEXT The variance formula, compatibility status and evidence scope on every table.
    tableFields={'fixedReferenceManifest','predictions','gpMetrics', ...
        'gpMetricsRawUQLab','pceMetrics','support','overlapSummary', ...
        'worstCases'};
    for i=1:numel(tableFields)
        name=tableFields{i};T=result.(name);
        if isempty(T),continue;end
        n=height(T);
        if ismember(name,{'predictions','gpMetrics','gpMetricsRawUQLab'})&& ...
                ~ismember('VarianceFormulaVersion',T.Properties.VariableNames)
            T.VarianceFormulaVersion=repmat( ...
                string(result.varianceFormulaVersion),n,1);
        end
        if ~ismember('CompatibilityStatus',T.Properties.VariableNames)
            T.CompatibilityStatus=repmat( ...
                string(result.compatibilityStatus),n,1);
        end
        if ~ismember('EvidenceScope',T.Properties.VariableNames)
            T.EvidenceScope=repmat( ...
                "development_only_cross_route_reference",n,1);
        end
        result.(name)=T;
    end
end

function write_outputs(root,result)
    utils.atomic_write_json(fullfile(root,'compatibility_checks.json'), ...
        result.compatibilityReceipt,'AllowReplace',true);
    write_table(fullfile(root,'fixed_reference_manifest.csv'), ...
        result.fixedReferenceManifest);
    write_table(fullfile(root,'default_protocol_predictions.csv'), ...
        result.predictions);
    write_table(fullfile(root,'default_protocol_gp_metrics.csv'), ...
        result.gpMetrics);
    write_table(fullfile(root, ...
        'default_protocol_gp_metrics_raw_uqlab.csv'), ...
        result.gpMetricsRawUQLab);
    write_table(fullfile(root,'default_protocol_pce_metrics.csv'), ...
        result.pceMetrics);
    write_table(fullfile(root,'default_protocol_support.csv'),result.support);
    write_table(fullfile(root,'default_protocol_overlap_summary.csv'), ...
        result.overlapSummary);
    write_table(fullfile(root,'default_protocol_worst_cases.csv'), ...
        result.worstCases);
end

function write_table(pathValue,T)
    if width(T)==0
        T=table(strings(0,1),'VariableNames',{'NoRowsReason'});
    end
    utils.atomic_write_table(pathValue,T);
end
