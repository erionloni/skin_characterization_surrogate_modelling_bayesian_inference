function result=write_generalized_assessment_tables(V,data,cfg)
%WRITE_GENERALIZED_ASSESSMENT_TABLES Write the core tables of the generalized assessment.
%   RESULT = surrogates.write_generalized_assessment_tables(V, DATA, CFG) writes the
%   tables of V (the output of surrogates.validate_generalized_refit) into
%   CFG.paths.surrogateAssessment: held-out predictions and metrics (GP with
%   the calibrated emulator variance, GP with the raw UQLab variance, PCE),
%   training and cross-validation predictions and metrics, predictive
%   coverage, and the uncertainty semantics. RESULT names the tables
%   (run-relative paths). It performs no model fit or evaluation.
%   Side effects: writes the tables (above).

    assert(strcmp(cfg.dataMode,'real_extended')&&isstruct(V)&&isstruct(data)&& ...
        all(isfield(V,{'predictions','trainingPredictions', ...
        'crossValidationPredictions','metrics','gpRawMetrics', ...
        'cohortMetrics','predictiveCoverage', ...
        'gpRawPredictiveCoverage'})), ...
        'surrogates:write_generalized_assessment_tables:Contract', ...
        'The assessment V lacks the tables that surrogates.validate_generalized_refit returns.');
    root=cfg.paths.surrogateAssessment;
    if ~isfolder(root),mkdir(root);end
    predictionsPath=fullfile(root,'validation_predictions.csv');
    metricsPath=fullfile(root,'validation_metrics.csv');
    gpMetricsPath=fullfile(root,'gp_validation_metrics.csv');
    gpRawMetricsPath=fullfile(root,'gp_validation_metrics_raw_uqlab.csv');
    pceMetricsPath=fullfile(root,'pce_validation_metrics.csv');
    cohortPath=fullfile(root,'training_cv_internal_heldout_metrics.csv');
    trainingPredictionPath=fullfile(root,'training_predictions.csv');
    cvPredictionPath=fullfile(root,'cross_validation_predictions.csv');
    rawCoveragePath=fullfile(root,'gp_predictive_coverage_raw_uqlab.csv');
    calibratedCoveragePath=fullfile(root,'gp_predictive_coverage.csv');
    uncertaintyPath=fullfile(root,'generalized_uncertainty_semantics.json');
    utils.atomic_write_table(predictionsPath,V.predictions);
    utils.atomic_write_table(metricsPath,V.metrics);
    utils.atomic_write_table(gpMetricsPath,V.metrics(V.metrics.Family=="gp",:));
    utils.atomic_write_table(gpRawMetricsPath,V.gpRawMetrics);
    utils.atomic_write_table(pceMetricsPath,V.metrics(V.metrics.Family=="pce",:));
    utils.atomic_write_table(cohortPath,V.cohortMetrics);
    utils.atomic_write_table(trainingPredictionPath,V.trainingPredictions);
    utils.atomic_write_table(cvPredictionPath,V.crossValidationPredictions);
    utils.atomic_write_table(calibratedCoveragePath, ...
        V.predictiveCoverage(V.predictiveCoverage.Family=="gp",:));
    utils.atomic_write_table(rawCoveragePath,V.gpRawPredictiveCoverage);
    uncertainty=struct( ...
        'schema_version','real_extended_active_uncertainty_v3', ...
        'route','real_extended', ...
        'active_emulator_variance','tempered_local_diagonal', ...
        'raw_reference_variance','uqlab_latent_predictive_variance', ...
        'variance_formula_version', ...
            cfg.emulatorErrorCalibration.variance_formula_version, ...
        'tempered_calibration_applied',true, ...
        'cross_output_correlation_applied',false, ...
        'units','mbar^2', ...
        'claim_scope','configured_generalized_surrogate');
    utils.atomic_write_json(uncertaintyPath,uncertainty,'AllowReplace',true);
    result=struct( ...
        'schema_version','real_extended_stage2_core_parity_v4', ...
        'prediction_table',run_relative(predictionsPath,cfg.paths.runRoot), ...
        'metrics_table',run_relative(metricsPath,cfg.paths.runRoot), ...
        'gp_raw_metrics_table',run_relative( ...
            gpRawMetricsPath,cfg.paths.runRoot), ...
        'cohort_metrics_table',run_relative(cohortPath,cfg.paths.runRoot), ...
        'training_prediction_table',run_relative( ...
            trainingPredictionPath,cfg.paths.runRoot), ...
        'cross_validation_prediction_table',run_relative( ...
            cvPredictionPath,cfg.paths.runRoot), ...
        'calibrated_coverage_table',run_relative( ...
            calibratedCoveragePath,cfg.paths.runRoot), ...
        'raw_coverage_table',run_relative(rawCoveragePath,cfg.paths.runRoot), ...
        'uncertainty_semantics',run_relative(uncertaintyPath,cfg.paths.runRoot), ...
        'surrogate_fits_performed',0,'surrogate_evaluations_performed',1);
end

function value=run_relative(pathValue,runRoot)
    pathValue=utils.absolute_path(pathValue);runRoot=utils.absolute_path(runRoot);
    prefix=[runRoot filesep];
    if ispc,inside=startsWith(lower(pathValue),lower(prefix)); ...
    else,inside=startsWith(pathValue,prefix);end
    assert(inside,'surrogates:write_generalized_assessment_tables:PathBoundary', ...
        'The table %s lies outside the run folder %s.',pathValue,runRoot);
    value=strrep(pathValue(numel(prefix)+1:end),'\','/');
end
