function policy = generalized_pce_policy(cfg)
%GENERALIZED_PCE_POLICY The frozen PCE policy of the generalized refit.
%   POLICY = surrogates.generalized_pce_policy(CFG) returns the staged
%   degree search: initial and escalation degrees, q-norm candidates, the
%   method, the cross-validation folds and metric, the adequacy thresholds
%   (mean and maximum fold NRMSE), the retry policy and the numbers of terms
%   of the full degree-4 to 6 bases; the held-out cases are not used for
%   the selection.
%   Side effects: none.
    policy=struct( ...
        'schemaVersion','real_extended_pce_staged_policy_v1', ...
        'initialDegrees',cfg.pce.initialDegrees,'escalationDegrees',cfg.pce.escalationDegrees, ...
        'qNormCandidates',cfg.pce.q_norm, ...
        'method',cfg.pce.method,'cvFolds',cfg.pce.cvFolds, ...
        'retryAttempt',surrogates.generalized_retry_attempt(cfg), ...
        'retryPolicy',[ ...
            'terminal failures are immutable; retry only with a larger ' ...
            'GeneralizedRetryAttempt option'], ...
        'cvMetric','NRMSE_training_range', ...
        'adequateMeanCVNRMSE',cfg.pce.adequateMeanCVNRMSE, ...
        'adequateMaxFoldNRMSE',cfg.pce.adequateMaxFoldNRMSE, ...
        'heldoutUsedForSelection',false, ...
        'degree4FullTotalTerms',330, ...
        'degree5FullTotalTerms',792, ...
        'degree6FullTotalTerms',1716);
end
