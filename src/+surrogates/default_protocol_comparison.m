function result=default_protocol_comparison(gpExtended,pceExtended, ...
        dataExtended,cfg)
%DEFAULT_PROTOCOL_COMPARISON Compare the generalized surrogates with fixed-route COMSOL results.
%   RESULT = surrogates.default_protocol_comparison(GP, PCE, DATA, CFG)
%   evaluates the generalized GP (calibrated emulator variance, with the raw
%   UQLab variance as a separately named reference;
%   surrogates.evaluate_generalized_gp) and PCE at the default protocol for the
%   fixed-route COMSOL cases of
%   CFG.realExtended.defaultProtocolComparison.referenceDatasetPath, and
%   returns predictions, metrics, support, overlap and worst-case tables
%   with the compatibility record of the two routes' contracts. The fixed
%   cases are never added to the generalized training data, and no
%   fixed-route surrogate is loaded. A critical contract mismatch (inputs,
%   outputs, units, transform, default protocol) suppresses the accuracy
%   metrics. The provenance that the fixed CSV does not carry (model,
%   geometry, extraction, units, protocol: eight fields) is resolved by the
%   source of the settings (B.5; thesis: the author's statement that both
%   datasets come from the same COMSOL model), not by comparing fields;
%   without a source it is recorded as unresolved. DATA is the generalized
%   dataset, which must belong to the calibration
%   (surrogates.validate_generalized_calibration_data_contract). It reads held-out
%   outcomes, so it runs only when CFG.stage2.evaluateExternalHoldout is true.
%   Side effects: none.
%   Computation: seconds (UQLab predictions).

    assert(strcmp(cfg.dataMode,'real_extended'), ...
        'surrogates:default_protocol_comparison:Route', ...
        'Default-protocol cross-route evidence belongs to real_extended.');
    % Held-out outcomes (Y_test) are read only on explicit request (CLN-003 #15).
    assert(logical(cfg.stage2.evaluateExternalHoldout), ...
        'surrogates:default_protocol_comparison:ExternalEvaluationDisabled', ...
        ['The default-protocol comparison reads held-out outcomes; it runs only ' ...
         'when external evaluation is requested explicitly.']);
    validate_extended_data(dataExtended,cfg);
    fixedSourcePath=char(string( ...
        cfg.realExtended.defaultProtocolComparison.referenceDatasetPath));
    fixedSourceExists=isfile(fixedSourcePath);
    if fixedSourceExists
        fixedTable=readtable(fixedSourcePath,'Delimiter',',','TextType','string', ...
            'VariableNamingRule','preserve');
    else
        fixedTable=table();
    end

    compatibility=compatibility_receipt( ...
        fixedTable,fixedSourcePath,fixedSourceExists,dataExtended,cfg);
    result=empty_result(compatibility);
    if ~compatibility.metrics_allowed
        result.reason=['Cross-route metrics were suppressed because the ' ...
            'critical mathematical contract is incompatible.'];
        return
    end

    reference=reference_data(fixedTable,dataExtended,cfg);
    result.fixedReferenceManifest=reference.manifest;
    eligible=reference.eligible;
    if ~any(eligible)
        result.status='unavailable_no_eligible_reference_rows';
        result.reason=['No finite fixed-reference COMSOL row lies inside the ' ...
            'configured generalized material bounds.'];
        return
    end

    defaultProtocol=default_protocol_vector(cfg);
    X=[reference.material(eligible,:), ...
        repmat(defaultProtocol,nnz(eligible),1)];
    truth=reference.truth(eligible,:);
    sourceRows=reference.sourceRows(eligible);
    caseIDs=reference.caseIDs(eligible);
    gpPrediction=surrogates.evaluate_generalized_gp(gpExtended,X,cfg);
    validate_gp_prediction(gpPrediction,truth,dataExtended,cfg);
    gpMean=double(gpPrediction.GPMean);
    gpRawVariance=double(gpPrediction.RawUQLabVariance);
    gpCalibratedVariance=double( ...
        gpPrediction.CalibratedEmulatorVariance);
    [pceMean,pceVariance]=surrogates.evaluate(pceExtended,X,'pce');
    validate_predictions(gpMean,gpRawVariance,gpCalibratedVariance, ...
        pceMean,pceVariance,truth);

    bounds=double(dataExtended.inputBounds);
    tolerance=double(cfg.realExtended.transformTolerance);
    [trainingOverlap,trainingMatchCount,heldoutOverlap,heldoutMatchCount, ...
        distance,supportThreshold,supportStatus]= ...
        output_specific_reference_support(dataExtended,X,bounds,tolerance);
    supportStatus(heldoutOverlap)="EXACT_EXTENDED_HELDOUT_OVERLAP";
    supportStatus(trainingOverlap)="EXACT_EXTENDED_TRAINING_OVERLAP";
    primary=~trainingOverlap;

    predictions=prediction_table(sourceRows,caseIDs,X,truth,gpMean, ...
        gpRawVariance,gpCalibratedVariance,pceMean,pceVariance,distance, ...
        trainingOverlap, ...
        heldoutOverlap,primary,supportStatus,compatibility.status, ...
        gpPrediction,dataExtended,cfg);
    gpMetrics=metric_table(truth,gpMean,gpCalibratedVariance,primary, ...
        dataExtended.outputNames,"gp", ...
        "tempered_local_diagonal_calibrated_emulator_variance", ...
        compatibility.status);
    gpMetricsRawUQLab=metric_table(truth,gpMean,gpRawVariance,primary, ...
        dataExtended.outputNames,"gp", ...
        "raw_uqlab_predictive_variance_reference", ...
        compatibility.status);
    pceMetrics=metric_table(truth,pceMean,pceVariance,primary, ...
        dataExtended.outputNames,"pce","not_available_for_pce", ...
        compatibility.status);
    support=reference_support_table(sourceRows,caseIDs,distance, ...
        trainingOverlap,trainingMatchCount,heldoutOverlap, ...
        heldoutMatchCount,primary,supportStatus,supportThreshold, ...
        tolerance,dataExtended.outputNames);
    overlapSummary=reference_overlap_summary(trainingOverlap,heldoutOverlap, ...
        primary,height(fixedTable),nnz(eligible),tolerance,supportThreshold, ...
        dataExtended.outputNames);
    worst=worst_cases(predictions,dataExtended.outputNames);

    result.status=status_for_compatibility(compatibility.status);
    result.reason=['Fixed COMSOL truths were evaluated at the configured ' ...
        'default protocol; fixed-route GP predictions were not used.'];
    result.predictions=predictions;
    result.gpMetrics=gpMetrics;
    result.gpMetricsRawUQLab=gpMetricsRawUQLab;
    result.pceMetrics=pceMetrics;
    result.support=support;
    result.overlapSummary=overlapSummary;
    result.worstCases=worst;
    result.fixedReferenceManifest=reference.manifest;
    result.eligibleReferenceCount=nnz(eligible);
    result.primaryExternalSliceCount=nnz(any(primary,2));
    result.primaryExternalScalarCount=nnz(primary);
    result.fixedReferenceOutputsLoaded=true;
    result.fixedReferenceUsedForTraining=false;
    result.fixedReferenceUsedForModelSelection=false;
    result.varianceFormulaVersion=char(string( ...
        gpPrediction.VarianceFormulaVersion));
end

function result=empty_result(compatibility)
    result=struct( ...
        'schemaVersion', ...
            'real_extended_default_protocol_cross_route_v4_output_specific', ...
        'status','incompatible_contract_metrics_suppressed','reason','', ...
        'compatibilityStatus',compatibility.status, ...
        'compatibilityReceipt',compatibility, ...
        'fixedReferenceManifest',table(),'predictions',table(), ...
        'gpMetrics',table(),'gpMetricsRawUQLab',table(), ...
        'pceMetrics',table(),'support',table(), ...
        'overlapSummary',table(),'worstCases',table(), ...
        'eligibleReferenceCount',0,'primaryExternalSliceCount',0, ...
        'primaryExternalScalarCount',0, ...
        'fixedReferenceOutputsLoaded',false, ...
        'fixedReferenceUsedForTraining',false, ...
        'fixedReferenceUsedForModelSelection',false, ...
        'varianceFormulaVersion','');
end

function validate_extended_data(data,cfg)
    required={'X_train','Y_train','X_test','Y_test','inputNames', ...
        'outputNames','inputBounds','trainCaseIDs','testCaseIDs'};
    assert(all(isfield(data,required))&& ...
        size(data.X_train,2)==7&&size(data.X_test,2)==7&& ...
        size(data.Y_train,2)==6&&size(data.Y_test,2)==6&& ...
        isequal(cellstr(string(data.inputNames(:))).', ...
            cfg.realExtended.learningInputNames)&& ...
        isequal(cellstr(string(data.outputNames(:))).', ...
            cfg.realExtended.outputNames)&& ...
        isequal(size(double(data.inputBounds)),[7 2])&& ...
        all(isfinite(double(data.inputBounds)),'all')&& ...
        all(diff(double(data.inputBounds),1,2)>0)&& ...
        max(abs(double(data.inputBounds)- ...
            double(cfg.realExtended.learningBounds)),[],'all')<=1e-12&& ...
        isempty(intersect(double(data.trainCaseIDs),double(data.testCaseIDs))), ...
        'surrogates:default_protocol_comparison:ExtendedDataset', ...
        'Generalized data do not satisfy the certified seven-input contract.');
    surrogates.validate_generalized_calibration_data_contract( ...
        cfg.emulatorErrorCalibration,data);
end

function receipt=compatibility_receipt(T,pathValue,pathExists,data,cfg)
    % The fixed reference named as the repository names it (data/fixed/...), not by this computer's folders.
    pathValue=repository_relative(pathValue);
    fixedInputs=cellstr(string(cfg.realData.inputCols(:))).';
    fixedOutputs=cellstr(string(cfg.realData.outputCols(:))).';
    transformedInputs={'m3_f_RD','m3_e_RD','log10_k0_RD','Thickness_RD'};
    checks=cell(0,1);
    checks{end+1}=check_row('critical_mathematical','fixed_source_exists', ...
        pathExists||~isempty(T),pathValue,'readable configured fixed source');
    checks{end+1}=check_row('critical_mathematical','fixed_input_columns', ...
        all(ismember(fixedInputs,T.Properties.VariableNames)), ...
        strjoin(fixedInputs,','),'all configured raw columns present');
    checks{end+1}=check_row('critical_mathematical','fixed_output_columns', ...
        all(ismember(fixedOutputs,T.Properties.VariableNames)), ...
        strjoin(fixedOutputs,','),'all six fixed COMSOL outputs present');
    checks{end+1}=check_row('critical_mathematical','fixed_caseid_column', ...
        ismember('CaseID',T.Properties.VariableNames), ...
        'CaseID column presence','CaseID');
    numericColumns=[{'CaseID'} fixedInputs fixedOutputs];
    checks{end+1}=check_row('critical_mathematical', ...
        'fixed_numeric_columns_readable', ...
        numeric_columns_readable(T,numericColumns), ...
        strjoin(numericColumns,','),'finite-or-explicitly-missing numeric values');
    checks{end+1}=check_row('critical_mathematical','material_order', ...
        isequal(data.inputNames(1:4),transformedInputs), ...
        strjoin(data.inputNames(1:4),','),strjoin(transformedInputs,','));
    checks{end+1}=check_row('critical_mathematical','output_order', ...
        isequal(data.outputNames,fixedOutputs), ...
        strjoin(data.outputNames,','),strjoin(fixedOutputs,','));
    checks{end+1}=check_row('critical_mathematical','permeability_transform', ...
        cfg.realData.k0Col==3&&strcmp(fixedInputs{3},'k0_RD')&& ...
        strcmp(data.inputNames{3},'log10_k0_RD'), ...
        'log10(k0_RD)','log10(k0_RD)');
    expectedUnits={'-','-','log10(mm^4/(N s))','mm'};
    checks{end+1}=check_row('critical_mathematical','configured_material_units', ...
        isequal(cfg.paramUnits(1:4),expectedUnits), ...
        strjoin(cfg.paramUnits(1:4),','),strjoin(expectedUnits,','));
    checks{end+1}=check_row('critical_mathematical', ...
        'configured_pressure_naming_units', ...
        all(endsWith(string(fixedOutputs),'_mbar')), ...
        'output names end in _mbar','mbar');
    phi=default_protocol_vector(cfg);
    expectedPhi=[log10(abs(-0.4)),30,12];
    checks{end+1}=check_row('critical_mathematical','configured_default_protocol', ...
        isequaln(phi,expectedPhi)&& ...
        cfg.realExtended.defaultProtocol.suction_rate_kPa_s==-0.4, ...
        mat2str(phi,17),mat2str(expectedPhi,17));
    inside=all(phi>=data.inputBounds(5:7,1).'-eps & ...
        phi<=data.inputBounds(5:7,2).'+eps);
    checks{end+1}=check_row('critical_mathematical','default_inside_bounds', ...
        inside,mat2str(phi,17),mat2str(data.inputBounds(5:7,:),17));
    unresolved={ ...
        'constitutive_model_identity', ...
        'D2_geometry_identity', ...
        'D6_geometry_identity', ...
        'm3_f_effective_swelling_semantics', ...
        'closing_pressure_extraction_definition', ...
        'fixed_reference_units_provenance', ...
        'fixed_reference_default_protocol_provenance', ...
        'fixed_protocol_phase_interpretation'};
    % The fixed CSV does not carry these fields: a source of the settings
    % (B.5; thesis: the author's statement that both datasets come from the
    % same COMSOL model) resolves them, not a comparison of fields.
    source=char(string(cfg.realExtended.defaultProtocolComparison.provenanceSource));
    for i=1:numel(unresolved)
        if isempty(source)
            checks{end+1}=unresolved_row('provenance',unresolved{i}, ...
                'not published by configured fixed CSV'); %#ok<AGROW>
        else
            checks{end+1}=resolved_row('provenance',unresolved{i},source); %#ok<AGROW>
        end
    end
    checkTable=vertcat(checks{:});
    incompatible=any(checkTable.Scope=="critical_mathematical" & ...
        checkTable.Status=="INCOMPATIBLE");
    unresolvedAny=any(checkTable.Status=="UNRESOLVED");
    if incompatible
        status='INCOMPATIBLE_CONTRACT';metricsAllowed=false;
    elseif unresolvedAny
        status='COMPATIBILITY_UNRESOLVED';metricsAllowed=true;
    else
        status='COMPATIBLE_REFERENCE';metricsAllowed=true;
    end
    receipt=struct( ...
        'schema_version','default_protocol_compatibility_receipt_v3', ...
        'status',status,'metrics_allowed',metricsAllowed, ...
        'comparison_scope', ...
            'development_only_cross_route_reference_not_model_selection', ...
        'unresolved_policy',[ ...
            'Existing extended comparison policy permits development-only ' ...
            'metrics when the numerical schema is exact and unavailable ' ...
            'cross-campaign provenance is retained explicitly.'], ...
        'fixed_reference_path',pathValue, ...
        'fixed_reference_role','fixed_default_protocol_COMSOL_reference', ...
        'target_is_fixed_COMSOL_truth',true, ...
        'fixed_GP_loaded_or_evaluated',false, ...
        'critical_mismatch_count',nnz(checkTable.Scope== ...
            "critical_mathematical"&checkTable.Status=="INCOMPATIBLE"), ...
        'unresolved_count',nnz(checkTable.Status=="UNRESOLVED"), ...
        'provenance_source',source, ...
        'provenance_resolved_by_statement_count', ...
            nnz(checkTable.Status=="RESOLVED_BY_STATEMENT"), ...
        'checks',table2struct(checkTable));
end

function tf=numeric_columns_readable(T,names)
    tf=all(ismember(names,T.Properties.VariableNames));
    if ~tf,return;end
    try
        for i=1:numel(names)
            value=T.(names{i});
            if isnumeric(value),continue;end
            converted=str2double(string(value));
            original=strip(string(value));
            explicitMissing=ismissing(original)|original=="";
            if any(~isfinite(converted)&~explicitMissing),tf=false;return;end
        end
    catch
        tf=false;
    end
end

function row=check_row(scope,item,compatible,actual,expected)
    if compatible,status="COMPATIBLE";else,status="INCOMPATIBLE";end
    row=table(string(scope),string(item),status,string(actual), ...
        string(expected),'VariableNames', ...
        {'Scope','Item','Status','Actual','Expected'});
end

function row=resolved_row(scope,item,source)
%RESOLVED_ROW A provenance field that the fixed CSV does not carry, resolved by the settings' source (no field compared).
    row=table(string(scope),string(item),"RESOLVED_BY_STATEMENT", ...
        "not carried by the fixed CSV",string(source),'VariableNames', ...
        {'Scope','Item','Status','Actual','Expected'});
end

function row=unresolved_row(scope,item,reason)
    row=table(string(scope),string(item),"UNRESOLVED",string(reason), ...
        "published matching provenance",'VariableNames', ...
        {'Scope','Item','Status','Actual','Expected'});
end

function reference=reference_data(T,data,cfg)
    n=height(T);sourceRows=(1:n).';
    material=nan(n,4);truth=nan(n,6);caseIDs=nan(n,1);
    columnsPresent=all(ismember([cfg.realData.inputCols ...
        cfg.realData.outputCols {'CaseID'}],T.Properties.VariableNames));
    if columnsPresent
        material=double(T{:,cfg.realData.inputCols});
        truth=double(T{:,cfg.realData.outputCols});
        caseIDs=double(T.CaseID);
        positiveK0=isfinite(material(:,cfg.realData.k0Col)) & ...
            material(:,cfg.realData.k0Col)>0;
        material(positiveK0,cfg.realData.k0Col)= ...
            log10(material(positiveK0,cfg.realData.k0Col));
        material(~positiveK0,cfg.realData.k0Col)=NaN;
    end
    materialFinite=all(isfinite(material),2);
    truthFinite=all(isfinite(truth),2);
    bounds=double(data.inputBounds(1:4,:));
    insideBounds=materialFinite & all(material>=bounds(:,1).'-eps & ...
        material<=bounds(:,2).'+eps,2);
    eligible=materialFinite&truthFinite&insideBounds&isfinite(caseIDs);
    reason=repmat("eligible",n,1);
    reason(~materialFinite)="nonfinite_or_nonpositive_material_input";
    reason(materialFinite&~truthFinite)="nonfinite_COMSOL_truth";
    reason(materialFinite&truthFinite&~insideBounds)= ...
        "material_outside_generalized_bounds";
    reason(~isfinite(caseIDs))="nonfinite_CaseID";
    FixedReferenceRole=repmat("fixed_default_protocol_COMSOL_reference",n,1);
    manifest=table(sourceRows,caseIDs,materialFinite,truthFinite, ...
        insideBounds,eligible,reason,FixedReferenceRole, ...
        'VariableNames',{'FixedSourceRow','CaseID','MaterialInputsFinite', ...
        'COMSOLTruthFinite','InsideGeneralizedMaterialBounds', ...
        'EligibleReference','ExclusionReason','FixedReferenceRole'});
    for p=1:4
        manifest.(cfg.realExtended.learningInputNames{p})=material(:,p);
    end
    reference=struct('material',material,'truth',truth,'caseIDs',caseIDs, ...
        'sourceRows',sourceRows,'eligible',eligible,'manifest',manifest);
end

function phi=default_protocol_vector(cfg)
    protocol=cfg.realExtended.defaultProtocol;
    calculated=log10(abs(double(protocol.suction_rate_kPa_s)));
    tolerance=double(cfg.realExtended.transformTolerance);
    assert(protocol.suction_rate_kPa_s<0&& ...
        abs(calculated-double(protocol.log10_abs_suction_rate))<=tolerance, ...
        'surrogates:default_protocol_comparison:DefaultProtocolTransform', ...
        'The configured signed/default learning-coordinate rate disagrees.');
    phi=[calculated,double(protocol.hold_dur_s), ...
        double(protocol.pause_dur_s)];
end

function validate_gp_prediction(prediction,truth,data,cfg)
    required={'GPMean','RawUQLabVariance','RawUQLabSD', ...
        'ProcessVariance','LocalVarianceShapeH', ...
        'CalibratedEmulatorVariance','CalibratedEmulatorSD', ...
        'VarianceFormulaVersion','OutputOrder'};
    assert(isstruct(prediction)&&isscalar(prediction)&& ...
        all(isfield(prediction,required))&& ...
        isequal(size(prediction.GPMean),size(truth))&& ...
        isequal(size(prediction.RawUQLabVariance),size(truth))&& ...
        isequal(size(prediction.CalibratedEmulatorVariance),size(truth))&& ...
        numel(prediction.ProcessVariance)==size(truth,2)&& ...
        isequal(cellstr(string(prediction.OutputOrder(:))).', ...
            cellstr(string(data.outputNames(:))).')&& ...
        strcmp(cfg.dataMode,'real_extended'), ...
        'surrogates:default_protocol_comparison:GPPredictionContract', ...
        'The authoritative generalized evaluator returned an invalid contract.');
end

function validate_predictions(gpMean,gpRawVariance, ...
        gpCalibratedVariance,pceMean,pceVariance,truth)
    expected=size(truth);
    assert(isequal(size(gpMean),expected)&& ...
        isequal(size(gpRawVariance),expected)&& ...
        isequal(size(gpCalibratedVariance),expected)&& ...
        isequal(size(pceMean),expected)&& ...
        isequal(size(pceVariance),expected)&& ...
        all(isfinite(gpMean),'all')&& ...
        all(isfinite(gpRawVariance),'all')&& ...
        all(gpRawVariance>=0,'all')&& ...
        all(isfinite(gpCalibratedVariance),'all')&& ...
        all(gpCalibratedVariance>=0,'all')&& ...
        all(isfinite(pceMean)|isnan(pceMean),'all')&& ...
        all(isfinite(pceVariance)|isnan(pceVariance),'all'), ...
        'surrogates:default_protocol_comparison:PredictionShape', ...
        'Generalized GP/PCE predictions do not match the reference table.');
end

function [overlap,count]=exact_overlap(query,reference,bounds,tolerance)
    width=(bounds(:,2)-bounds(:,1)).';
    q=(query-bounds(:,1).')./width;
    r=(reference-bounds(:,1).')./width;
    overlap=false(size(query,1),1);count=zeros(size(query,1),1);
    for i=1:size(query,1)
        count(i)=nnz(max(abs(r-q(i,:)),[],2)<=tolerance);
        overlap(i)=count(i)>0;
    end
end

function [trainingOverlap,trainingCount,heldoutOverlap,heldoutCount, ...
        distance,threshold,status]=output_specific_reference_support( ...
        data,query,bounds,tolerance)
    if all(isfield(data,{'X_development_all','Y_development_all'}))
        developmentX=double(data.X_development_all);
        developmentY=double(data.Y_development_all);
    else
        developmentX=double(data.X_train);
        developmentY=double(data.Y_train);
    end
    n=size(query,1);nOutput=numel(data.outputNames);
    trainingOverlap=false(n,nOutput);trainingCount=zeros(n,nOutput);
    heldoutOverlap=false(n,nOutput);heldoutCount=zeros(n,nOutput);
    distance=nan(n,nOutput);threshold=nan(1,nOutput);
    status=strings(n,nOutput);
    for outputIndex=1:nOutput
        available=isfinite(developmentY(:,outputIndex));
        reference=developmentX(available,:);
        assert(size(reference,1)>=2&&all(isfinite(reference),'all'), ...
            'surrogates:default_protocol_comparison:OutputTrainingSupport', ...
            'Output %d has fewer than two finite development rows.',outputIndex);
        [trainingOverlap(:,outputIndex),trainingCount(:,outputIndex)]= ...
            exact_overlap(query,reference,bounds,tolerance);
        [heldoutOverlap(:,outputIndex),heldoutCount(:,outputIndex)]= ...
            exact_overlap(query,double(data.X_test),bounds,tolerance);
        distance(:,outputIndex)=surrogates.nearest_normalized_distance( ...
            query,reference,bounds.');
        threshold(outputIndex)=linear_quantile( ...
            leave_one_out_distance(reference,bounds),0.95);
        status(:,outputIndex)="WITHIN_GENERALIZED_TRAINING_LOO95_RADIUS";
        status(distance(:,outputIndex)>threshold(outputIndex),outputIndex)= ...
            "OUTSIDE_GENERALIZED_TRAINING_LOO95_RADIUS";
    end
end

function T=reference_support_table(sourceRows,caseIDs,distance, ...
        trainingOverlap,trainingMatchCount,heldoutOverlap,heldoutMatchCount, ...
        primary,supportStatus,supportThreshold,tolerance,outputNames)
    [caseIndex,outputIndex]=ndgrid(1:numel(caseIDs),1:numel(outputNames));
    linear=sub2ind(size(distance),caseIndex(:),outputIndex(:));
    FixedSourceRow=sourceRows(caseIndex(:));CaseID=caseIDs(caseIndex(:));
    OutputIndex=outputIndex(:);
    Output=reshape(string(outputNames(OutputIndex)),[],1);
    NearestGeneralizedTrainingDistance=distance(linear);
    ExactExtendedTrainingOverlap=trainingOverlap(linear);
    ExtendedTrainingMatchCount=trainingMatchCount(linear);
    ExactExtendedHeldoutOverlap=heldoutOverlap(linear);
    ExtendedHeldoutMatchCount=heldoutMatchCount(linear);
    PrimaryExternalSliceIncluded=primary(linear);
    DefaultProtocolSupportStatus=supportStatus(linear);
    GeneralizedTrainingLOO95Distance=reshape( ...
        supportThreshold(OutputIndex),[],1);
    ExactOverlapToleranceNormalized=repmat(tolerance,numel(linear),1);
    T=table(FixedSourceRow,CaseID,OutputIndex,Output, ...
        NearestGeneralizedTrainingDistance,ExactExtendedTrainingOverlap, ...
        ExtendedTrainingMatchCount,ExactExtendedHeldoutOverlap, ...
        ExtendedHeldoutMatchCount,PrimaryExternalSliceIncluded, ...
        DefaultProtocolSupportStatus,GeneralizedTrainingLOO95Distance, ...
        ExactOverlapToleranceNormalized);
end

function T=reference_overlap_summary(trainingOverlap,heldoutOverlap,primary, ...
        sourceCount,eligibleCount,tolerance,supportThreshold,outputNames)
    n=numel(outputNames);OutputIndex=(1:n).';Output=string(outputNames(:));
    FixedReferenceRowCount=repmat(sourceCount,n,1);
    EligibleReferenceCount=repmat(eligibleCount,n,1);
    ExactExtendedTrainingOverlapCount=sum(trainingOverlap,1).';
    ExactExtendedHeldoutOverlapCount=sum(heldoutOverlap,1).';
    NeitherExactOverlapCount=sum(~trainingOverlap&~heldoutOverlap,1).';
    PrimaryExternalSliceCount=sum(primary,1).';
    ExactOverlapToleranceNormalized=repmat(tolerance,n,1);
    GeneralizedTrainingLOO95Distance=supportThreshold(:);
    T=table(OutputIndex,Output,FixedReferenceRowCount, ...
        EligibleReferenceCount,ExactExtendedTrainingOverlapCount, ...
        ExactExtendedHeldoutOverlapCount,NeitherExactOverlapCount, ...
        PrimaryExternalSliceCount,ExactOverlapToleranceNormalized, ...
        GeneralizedTrainingLOO95Distance);
end

function distance=leave_one_out_distance(X,bounds)
    n=size(X,1);distance=nan(n,1);
    assert(n>=2,'surrogates:default_protocol_comparison:TrainingSupport', ...
        'The leave-one-out support radius needs at least two development cases.');
    for i=1:n
        distance(i)=surrogates.nearest_normalized_distance( ...
            X(i,:),X([1:i-1 i+1:n],:),bounds.');
    end
end

function value=linear_quantile(values,probability)
    values=sort(values(isfinite(values)));
    if isempty(values),value=NaN;return;end
    index=1+(numel(values)-1)*probability;
    lo=floor(index);hi=ceil(index);
    value=values(lo)+(index-lo)*(values(hi)-values(lo));
end

function T=prediction_table(sourceRows,caseIDs,X,truth,gpMean, ...
        gpRawVariance,gpCalibratedVariance,pceMean,~,distance, ...
        trainingOverlap,heldoutOverlap,primary, ...
        supportStatus,compatibilityStatus,gpPrediction,data,cfg)
    n=size(truth,1);m=size(truth,2);
    [caseIndex,outputIndex]=ndgrid(1:n,1:m);
    linear=sub2ind([n m],caseIndex(:),outputIndex(:));
    FixedSourceRow=sourceRows(caseIndex(:));CaseID=caseIDs(caseIndex(:));
    OutputIndex=outputIndex(:);
    Output=reshape(string(data.outputNames(OutputIndex)),[],1);
    FixedCOMSOLTruth_mbar=truth(linear);
    GeneralizedGPMean_mbar=gpMean(linear);
    GPRawUQLabVariance_mbar2=gpRawVariance(linear);
    GPRawUQLabSD_mbar=sqrt(GPRawUQLabVariance_mbar2);
    GPCalibratedEmulatorVariance_mbar2=gpCalibratedVariance(linear);
    GPCalibratedEmulatorSD_mbar= ...
        sqrt(GPCalibratedEmulatorVariance_mbar2);
    GeneralizedPCEMean_mbar=pceMean(linear);
    GPResidual_mbar=GeneralizedGPMean_mbar-FixedCOMSOLTruth_mbar;
    PCEResidual_mbar=GeneralizedPCEMean_mbar-FixedCOMSOLTruth_mbar;
    GPAbsoluteError_mbar=abs(GPResidual_mbar);
    PCEAbsoluteError_mbar=abs(PCEResidual_mbar);
    [rawIncluded,rawNLPD,rawCRPS, ...
        GPRawUQLabStandardizedResidual]=distribution_rows( ...
        FixedCOMSOLTruth_mbar,GeneralizedGPMean_mbar, ...
        GPRawUQLabVariance_mbar2,OutputIndex,m);
    [calibratedIncluded,calibratedNLPD,calibratedCRPS, ...
        GPCalibratedStandardizedResidual]=distribution_rows( ...
        FixedCOMSOLTruth_mbar,GeneralizedGPMean_mbar, ...
        GPCalibratedEmulatorVariance_mbar2,OutputIndex,m);
    scale=nan(m,1);
    for j=1:m
        rows=primary(:,j)&isfinite(truth(:,j));
        if any(rows),scale(j)=max(truth(rows,j))-min(truth(rows,j));end
    end
    ReferenceTruthRange_mbar=scale(OutputIndex);
    GPNormalizedAbsoluteError=GPAbsoluteError_mbar./ReferenceTruthRange_mbar;
    PCENormalizedAbsoluteError=PCEAbsoluteError_mbar./ReferenceTruthRange_mbar;
    nearZero=~isfinite(ReferenceTruthRange_mbar)| ...
        ReferenceTruthRange_mbar<=1e-12;
    GPNormalizedAbsoluteError(nearZero)=NaN;
    PCENormalizedAbsoluteError(nearZero)=NaN;
    NearestGeneralizedTrainingDistance=distance(linear);
    ExactExtendedTrainingOverlap=trainingOverlap(linear);
    ExactExtendedHeldoutOverlap=heldoutOverlap(linear);
    PrimaryExternalSliceIncluded=primary(linear);
    DefaultProtocolSupportStatus=supportStatus(linear);
    CompatibilityStatus=repmat(string(compatibilityStatus),numel(linear),1);
    ActiveUncertaintySemantics=repmat( ...
        "tempered_local_diagonal_calibrated_emulator_variance", ...
        numel(linear),1);
    VarianceFormulaVersion=repmat(string( ...
        gpPrediction.VarianceFormulaVersion),numel(linear),1);
    FixedTruthTarget=repmat("fixed_COMSOL_not_fixed_GP",numel(linear),1);
    signedRate=repmat(double( ...
        cfg.realExtended.defaultProtocol.suction_rate_kPa_s),numel(linear),1);
    T=table(FixedSourceRow,CaseID,OutputIndex,Output, ...
        FixedCOMSOLTruth_mbar,GeneralizedGPMean_mbar, ...
        GPRawUQLabVariance_mbar2,GPRawUQLabSD_mbar, ...
        GPCalibratedEmulatorVariance_mbar2, ...
        GPCalibratedEmulatorSD_mbar, ...
        GeneralizedPCEMean_mbar,GPResidual_mbar,PCEResidual_mbar, ...
        GPAbsoluteError_mbar,PCEAbsoluteError_mbar, ...
        ReferenceTruthRange_mbar,GPNormalizedAbsoluteError, ...
        PCENormalizedAbsoluteError,GPRawUQLabStandardizedResidual, ...
        GPCalibratedStandardizedResidual, ...
        rawIncluded(:,1),rawIncluded(:,2),rawIncluded(:,3), ...
        rawIncluded(:,4),calibratedIncluded(:,1), ...
        calibratedIncluded(:,2),calibratedIncluded(:,3), ...
        calibratedIncluded(:,4),rawNLPD,rawCRPS, ...
        calibratedNLPD,calibratedCRPS, ...
        NearestGeneralizedTrainingDistance, ...
        ExactExtendedTrainingOverlap,ExactExtendedHeldoutOverlap, ...
        PrimaryExternalSliceIncluded,DefaultProtocolSupportStatus, ...
        CompatibilityStatus,VarianceFormulaVersion, ...
        ActiveUncertaintySemantics,FixedTruthTarget, ...
        'VariableNames',{'FixedSourceRow','CaseID','OutputIndex','Output', ...
        'FixedCOMSOLTruth_mbar','GeneralizedGPMean_mbar', ...
        'GPRawUQLabVariance_mbar2','GPRawUQLabSD_mbar', ...
        'GPCalibratedEmulatorVariance_mbar2', ...
        'GPCalibratedEmulatorSD_mbar', ...
        'GeneralizedPCEMean_mbar','GPResidual_mbar','PCEResidual_mbar', ...
        'GPAbsoluteError_mbar','PCEAbsoluteError_mbar', ...
        'ReferenceTruthRange_mbar','GPNormalizedAbsoluteError', ...
        'PCENormalizedAbsoluteError', ...
        'GPRawUQLabStandardizedResidual', ...
        'GPCalibratedStandardizedResidual', ...
        'GPRawUQLabIncluded50','GPRawUQLabIncluded80', ...
        'GPRawUQLabIncluded90','GPRawUQLabIncluded95', ...
        'GPCalibratedIncluded50','GPCalibratedIncluded80', ...
        'GPCalibratedIncluded90','GPCalibratedIncluded95', ...
        'GPRawUQLabGaussianNLPD','GPRawUQLabGaussianCRPS', ...
        'GPCalibratedGaussianNLPD','GPCalibratedGaussianCRPS', ...
        'NearestGeneralizedTrainingDistance', ...
        'ExactExtendedTrainingOverlap','ExactExtendedHeldoutOverlap', ...
        'PrimaryExternalSliceIncluded','DefaultProtocolSupportStatus', ...
        'CompatibilityStatus','VarianceFormulaVersion', ...
        'ActiveUncertaintySemantics','FixedTruthTarget'});
    T.suction_rate_kPa_s=signedRate;
    inputNames=cfg.realExtended.learningInputNames;
    for p=1:numel(inputNames)
        T.(inputNames{p})=X(caseIndex(:),p);
    end
end

function [included,nlpd,crps,standardized]=distribution_rows( ...
        truth,prediction,variance, ...
        outputIndex,outputCount)
    included=false(numel(truth),4);nlpd=nan(numel(truth),1);crps=nlpd;
    standardized=nlpd;
    for j=1:outputCount
        rows=outputIndex==j;
        M=surrogates.surrogate_metric_primitives( ...
            truth(rows),prediction(rows),variance(rows));
        included(rows,:)=M.IntervalIncluded;
        nlpd(rows)=M.GaussianPointNLPD;
        crps(rows)=M.GaussianPointCRPS;
        standardized(rows)=M.StandardizedResidual;
    end
end

function T=metric_table(truth,prediction,variance,primary,outputNames, ...
        family,uncertaintySemantics,compatibilityStatus)
    parts=cell(numel(outputNames),1);
    for j=1:numel(outputNames)
        rows=primary(:,j)&isfinite(truth(:,j))&isfinite(prediction(:,j));
        if any(rows)
            one=surrogates.surrogate_quality_metrics( ...
                truth(rows,j),prediction(rows,j),variance(rows,j), ...
                outputNames(j));
        else
            one=surrogates.surrogate_quality_metrics(0,0,NaN,outputNames(j));
            numeric=varfun(@isnumeric,one,'OutputFormat','uniform');
            names=one.Properties.VariableNames(numeric);
            for k=1:numel(names),one.(names{k})(:)=NaN;end
            one.OutputIndex=j;one.ObservationCount=0;
            one.ProbabilisticMetricUnavailableReason(:)="fit_unavailable";
        end
        one.OutputIndex(:)=j;
        Family=repmat(string(family),height(one),1);
        Cohort=repmat("fixed_reference_nontraining_overlap",height(one),1);
        CompatibilityStatus=repmat(string(compatibilityStatus),height(one),1);
        UncertaintySemantics=repmat( ...
            string(uncertaintySemantics),height(one),1);
        parts{j}=[table(Family,Cohort,CompatibilityStatus, ...
            UncertaintySemantics) one];
    end
    T=vertcat(parts{:});
end

function T=worst_cases(predictions,outputNames)
    families=["gp" "pce"];
    parts=cell(numel(families)*numel(outputNames),1);cursor=0;
    for f=1:numel(families)
        if families(f)=="gp"
            normalized='GPNormalizedAbsoluteError';native='GPAbsoluteError_mbar';
            residual='GPResidual_mbar';prediction='GeneralizedGPMean_mbar';
        else
            normalized='PCENormalizedAbsoluteError';native='PCEAbsoluteError_mbar';
            residual='PCEResidual_mbar';prediction='GeneralizedPCEMean_mbar';
        end
        for j=1:numel(outputNames)
            rows=predictions.PrimaryExternalSliceIncluded & ...
                predictions.Output==string(outputNames{j}) & ...
                isfinite(predictions.(normalized));
            one=predictions(rows,:);
            cursor=cursor+1;
            if isempty(one)
                parts{cursor}=table(families(f),j,string(outputNames{j}), ...
                    NaN,NaN,NaN,NaN,NaN,NaN, ...
                    'VariableNames',{'Family','OutputIndex','Output', ...
                    'CaseID','FixedSourceRow','NormalizedAbsoluteError', ...
                    'AbsoluteError_mbar','SignedResidual_mbar', ...
                    'Prediction_mbar'});
                continue
            end
            one=sortrows(one,{normalized,'CaseID','FixedSourceRow'}, ...
                {'descend','ascend','ascend'});
            parts{cursor}=table(families(f),j,string(outputNames{j}), ...
                one.CaseID(1),one.FixedSourceRow(1),one.(normalized)(1), ...
                one.(native)(1),one.(residual)(1),one.(prediction)(1), ...
                'VariableNames',{'Family','OutputIndex','Output', ...
                'CaseID','FixedSourceRow','NormalizedAbsoluteError', ...
                'AbsoluteError_mbar','SignedResidual_mbar','Prediction_mbar'});
        end
    end
    T=vertcat(parts{:});
end

function status=status_for_compatibility(compatibility)
    if strcmp(compatibility,'COMPATIBLE_REFERENCE')
        status='completed_compatible_reference';
    else
        status='completed_development_only_compatibility_unresolved';
    end
end

