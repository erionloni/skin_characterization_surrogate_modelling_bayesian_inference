function validate_dataset(dataSet)
    required={'X_train','Y_train','trainCaseIDs'};
    assert(isstruct(dataSet)&&isscalar(dataSet)&&all(isfield(dataSet,required)), ...
        'surrogates:surrogate_quality_fit_campaign:DatasetFields', ...
        'The dataset must be one struct with X_train, Y_train and trainCaseIDs.');
    X=double(dataSet.X_train);Y=double(dataSet.Y_train);
    ids=double(dataSet.trainCaseIDs(:));
