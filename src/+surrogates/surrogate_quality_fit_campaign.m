        size(Y,2)==6&&all(isfinite(X),'all')&&~any(isinf(Y),'all')&& ...
        numel(ids)==size(X,1)&&numel(unique(ids))==numel(ids)&& ...
        all(isfinite(ids))&&all(ids==fix(ids)), ...
        'surrogates:surrogate_quality_fit_campaign:DevelopmentShape', ...
        ['The development data need at least two cases with finite inputs, six ' ...
         'outputs (no infinite values) and distinct integer case IDs.']);
