function stats=descriptive(values)
    if isempty(values),stats=nan(1,8);return;end
    average=mean(values);deviation=std(values,0);coefficient=NaN;
    if abs(average)>eps,coefficient=deviation/abs(average);end
    stats=[average deviation linear_quantile(values,.5) ...
        linear_quantile(values,.025) linear_quantile(values,.975) ...
        min(values) max(values) coefficient];
end

function value=linear_quantile(sorted,probability)
    if isempty(sorted),value=NaN;return;end
    if isscalar(sorted),value=sorted;return;end
    position=1+(numel(sorted)-1)*probability;lower=floor(position);upper=ceil(position);
    fraction=position-lower;value=sorted(lower)+fraction*(sorted(upper)-sorted(lower));
end

