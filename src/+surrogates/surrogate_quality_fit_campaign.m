function result=surrogate_quality_fit_campaign(dataSet,cfg)
%SURROGATE_QUALITY_FIT_CAMPAIGN Run the fit plan of the development audit.
%   RESULT = surrogates.surrogate_quality_fit_campaign(DATASET, CFG) performs
%   the disposable supporting fits of the audit plan
%   (surrogates.surrogate_quality_seed_schedule: the output-specific scalar
%   plan, 175 fits per output). It uses only development inputs, observed targets
%   and development CaseIDs, fits with surrogates.train_gp and
%   surrogates.train_pce, and returns in-memory tables; persistence,
%   calibration, residual modelling and figures belong to the audit
%   (surrogates.quality_audit). The first failed fit stops the campaign.
%   Side effects: none on files (the caller saves); creates the UQLab models
%   of the fits in the session; the random number generator's state is
%   restored.
%   Computation: hours for the full plan.

    validate_dataset(dataSet);
    X=double(dataSet.X_train);Y=double(dataSet.Y_train);
    nDevelopment=size(X,1);nInput=size(X,2);nOutput=size(Y,2);
    caseIDs=reshape(double(dataSet.trainCaseIDs),[],1);
    inputNames=resolved_names(dataSet,cfg,'input',size(X,2));
    outputNames=resolved_names(dataSet,cfg,'output',size(Y,2));
    contractData=dataSet;
    contractData.inputNames=cellstr(inputNames);
    contractData.outputNames=cellstr(outputNames);
    outputTraining=surrogates.output_training_contract(contractData,cfg);
    % Shared material groups must use the scalar/output-aware schedule even
    % when every response is present, so a material group cannot be split
    % across fold roles under distinct CaseIDs.
    outputSpecific=~outputTraining.allOutputsComplete|| ...
        outputTraining.hasGroupedCases;
    scheduleBounds=[];
    if isfield(dataSet,'inputBounds'),scheduleBounds=dataSet.inputBounds;end
    [schedule,design,settings]= ...
        surrogates.surrogate_quality_seed_schedule(caseIDs,cfg, ...
        'InputNames',cellstr(inputNames), ...
        'InputBounds',scheduleBounds, ...
        'OutputNames',cellstr(outputNames), ...
        'OutputTrainingContract',outputTraining);
    probeX=probe_matrix(design.probePoints,settings.inputNames);
    bounds=double(settings.bounds);

    nRequest=height(schedule);
    fitParts=cell(nRequest,1);operationParts=cell(nRequest,1);
    nCV=nnz(schedule.Campaign=="kernel_cross_validation");
    nSame=nnz(schedule.Campaign=="same_data_seed_stability");
    nConvergence=nnz(schedule.Campaign=="training_convergence");
    cvPredictionParts=cell(nCV,1);cvMetricParts=cell(nCV,1);
    cvHyperParts=cell(nCV,1);samePredictionParts=cell(nSame,1);
    sameHyperParts=cell(nSame,1);convergenceMetricParts=cell(nConvergence,1);
    cvIndex=0;sameIndex=0;convergenceIndex=0;
    attempted=0;completed=0;failed=0;modelsCreated=0;modelsDiscarded=0;
    state=rng;restoreRandomState=onCleanup(@()rng(state));

    for requestIndex=1:nRequest
        request=schedule(requestIndex,:);attempted=attempted+1;
        [trainingRows,assessmentRows,assessmentX,assessmentY,assessmentIDs]= ...
            request_data(request,design,X,Y,caseIDs,probeX);
        assert(isempty(intersect(trainingRows,assessmentRows))|| ...
            request.Campaign=="same_data_seed_stability", ...
            'surrogates:surrogate_quality_fit_campaign:AssessmentLeakage', ...
            'Request %d assesses cases it was fitted on.',requestIndex);
        context=context_from_request(request);
        fitOutputNames=outputNames;
        trainingY=Y(trainingRows,:);
        if isfield(context,'OutputIndex')&&context.OutputIndex>0
            fitOutputNames=outputNames(context.OutputIndex);
            trainingY=Y(trainingRows,context.OutputIndex);
        end
        fit=execute_fit(X(trainingRows,:),trainingY,assessmentX, ...
            assessmentY,cfg,context,inputNames,fitOutputNames);
        modelsCreated=modelsCreated+double(fit.modelCreated);
        modelsDiscarded=modelsDiscarded+double(fit.modelDiscarded);
        if fit.status=="completed",completed=completed+1;else,failed=failed+1;end
        fitParts{requestIndex}=fit_summary(context,fit,size(trainingRows,1), ...
            size(assessmentX,1));
        operationParts{requestIndex}=operation_row(context,fit);

        switch request.Campaign
            case "kernel_cross_validation"
                cvIndex=cvIndex+1;
                cvMetricParts{cvIndex}=add_metric_context( ...
                    fit.metrics,context,"development_out_of_fold",fit);
                if fit.status=="completed"
                    nearest=surrogates.nearest_normalized_distance( ...
                        assessmentX,X(trainingRows,:),bounds);
                    cvPredictionParts{cvIndex}=prediction_rows(context, ...
                        assessmentIDs,assessmentRows,assessmentX,assessmentY, ...
                        fit.mean,fit.variance,nearest,inputNames,outputNames,bounds);
                else
                    cvPredictionParts{cvIndex}=empty_cv_predictions(inputNames);
                end
                cvHyperParts{cvIndex}=fit.hyperparameters;
            case "same_data_seed_stability"
                sameIndex=sameIndex+1;
                if fit.status=="completed"
                    samePredictionParts{sameIndex}=probe_prediction_rows( ...
                        context,design.probePoints,fit.mean,fit.variance,outputNames);
                else
                    samePredictionParts{sameIndex}=empty_probe_predictions( ...
                        design.probePoints,outputNames);
                end
                sameHyperParts{sameIndex}=fit.hyperparameters;
            case "training_convergence"
                convergenceIndex=convergenceIndex+1;
                convergenceMetricParts{convergenceIndex}=add_metric_context( ...
                    fit.metrics,context,"temporary_development_validation",fit);
            otherwise
                error('surrogates:surrogate_quality_fit_campaign:Campaign', ...
                    'Unknown fit campaign %s.',request.Campaign);
        end
        if fit.status~="completed",rethrow(fit.exception);end
    end

    allFits=vertcat(fitParts{:});operationLog=vertcat(operationParts{:});
    cvPredictions=vertcat_nonempty(cvPredictionParts,empty_cv_predictions(inputNames));
    cvMetrics=vertcat(cvMetricParts{:});cvHyperparameters=vertcat(cvHyperParts{:});
    samePredictions=vertcat_nonempty(samePredictionParts, ...
        empty_probe_predictions(design.probePoints,outputNames));
    sameHyperparameters=vertcat(sameHyperParts{:});
    convergenceMetrics=vertcat(convergenceMetricParts{:});
    cvPooled=pooled_oof_metrics(cvPredictions,outputNames,settings);
    cvSummary=metric_summary(cvPooled,{'Kernel','OutputIndex','Output'});
    pairedKernel=paired_kernel_comparison(cvMetrics,cvPooled,settings);
    [sameMeanStability,sameSDStability]=same_data_stability( ...
        samePredictions,design.probePoints,outputNames,settings);
    convergenceSummary=metric_summary(convergenceMetrics, ...
        {'ModelFamily','Candidate','NominalGlobalDevelopmentCaseCount', ...
        'ActualTrainingCaseCount', ...
        'OutputIndex','Output'});

    assert(attempted==height(schedule)&&cvIndex==nCV&&sameIndex==nSame&& ...
        convergenceIndex==nConvergence&&height(allFits)==height(schedule), ...
        'surrogates:surrogate_quality_fit_campaign:ExactFitCount', ...
        'Internal error: the fit campaign did not account for every scheduled fit exactly once.');
    if failed==0
        if outputSpecific
            expectedCV=3*settings.cvRepeats*sum( ...
                double(settings.outputDevelopmentCounts));
            expectedSame=numel(settings.sameDataKernels)* ...
                settings.sameDataReplicates*settings.probeCount*nOutput;
            expectedCVMetric=nCV;expectedCVHyper=nCV*nInput;
            expectedSameHyper=nSame*nInput;expectedConvergence=nConvergence;
        else
            expectedCV=3*5*nDevelopment*nOutput;
            expectedSame=2*5*settings.probeCount*nOutput;
            expectedCVMetric=75*nOutput;expectedCVHyper=75*nOutput*nInput;
            expectedSameHyper=10*nOutput*nInput;expectedConvergence=90*nOutput;
        end
        assert(height(cvPredictions)==expectedCV&& ...
            height(samePredictions)==expectedSame&& ...
            height(cvMetrics)==expectedCVMetric&&height(cvPooled)==3*5*nOutput&& ...
            height(cvHyperparameters)==expectedCVHyper&& ...
            height(sameHyperparameters)==expectedSameHyper&& ...
            height(convergenceMetrics)==expectedConvergence&& ...
            modelsCreated==height(schedule)&&modelsDiscarded==height(schedule), ...
            'surrogates:surrogate_quality_fit_campaign:CompleteEvidenceShape', ...
            ['Internal error: the tables of a complete fit campaign do not have the ' ...
             'scheduled numbers of rows.']);
    end
    assert(modelsCreated==modelsDiscarded, ...
        'surrogates:surrogate_quality_fit_campaign:ModelDiscardBalance', ...
        'Internal error: %d models were created and %d discarded.',modelsCreated,modelsDiscarded);
    assert(all(ismember(cvPredictions.CaseID,caseIDs)), ...
        'surrogates:surrogate_quality_fit_campaign:DevelopmentOnlyPredictions', ...
        'The cross-validation predictions include cases outside the development cohort.');
    if failed==0&&~outputSpecific
        assert(numel(unique(cvPredictions.CaseID))==nDevelopment, ...
            'surrogates:surrogate_quality_fit_campaign:CompleteDevelopmentCohort', ...
            'The cross-validation predictions cover %d development cases, not all %d.', ...
            numel(unique(cvPredictions.CaseID)),nDevelopment);
    end

    result=struct( ...
        'schemaVersion',ternary(outputSpecific, ...
        'surrogate_development_fit_campaign_output_specific_v1', ...
        'surrogate_development_fit_campaign_v1'), ...
        'settings',settings, ...
        'outputTrainingCounts',reshape(double([outputTraining.records.count]),[],1), ...
        'seedSchedule',schedule,'design',design, ...
        'kernelCVFolds',design.kernelCVFolds, ...
        'kernelCVPredictions',cvPredictions, ...
        'kernelCVMetricsPerFold',cvMetrics, ...
        'kernelCVMetricsPooledOOF',cvPooled, ...
        'kernelCVSummary',cvSummary, ...
        'kernelCVHyperparameters',cvHyperparameters, ...
        'pairedKernelComparison',pairedKernel, ...
        'sameDataFitSummary',allFits( ...
            allFits.Campaign=="same_data_seed_stability",:), ...
        'sameDataProbePredictions',samePredictions, ...
        'sameDataMeanStability',sameMeanStability, ...
        'sameDataSDStability',sameSDStability, ...
        'sameDataHyperparameters',sameHyperparameters, ...
        'trainingConvergenceFitSummary',allFits( ...
            allFits.Campaign=="training_convergence",:), ...
        'trainingConvergencePerOutputMetrics',convergenceMetrics, ...
        'trainingConvergenceRoles',design.trainingConvergenceRoles, ...
        'trainingConvergenceMembership',design.trainingConvergenceMembership, ...
        'trainingConvergenceSummary',convergenceSummary, ...
        'calibrationFolds',design.calibrationFolds, ...
        'allFitSummary',allFits,'operationLog',operationLog, ...
        'fitCounters',struct('expected',height(schedule),'attempted',attempted, ...
        'completed',completed,'failed',failed, ...
        'gpExpected',nnz(schedule.ModelFamily=="GP"), ...
        'pceExpected',nnz(schedule.ModelFamily=="PCE"), ...
        'modelsCreated',modelsCreated, ...
        'modelsDiscarded',modelsDiscarded), ...
        'excludedAssessmentAccessPermitted',false, ...
        'externalHoldoutAccessPermitted',false, ...
        'candidateModelsRetained',false);
end

function fit=execute_fit(Xtrain,Ytrain,Xassessment,Yassessment,cfg, ...
        context,inputNames,outputNames)
    fit=struct('status',"failed",'error',"",'exception',[], ...
        'trainTime',NaN,'mean',[],'variance',[],'metrics', ...
        missing_metrics(outputNames),'hyperparameters',table(), ...
        'modelCreated',false,'modelDiscarded',false);
    model=[];
    try
        rng(context.FitSeed,'twister');
        fitOptions=struct('modelFamily',char(context.ModelFamily), ...
            'candidate',char(context.Candidate),'kernel',char(context.Kernel), ...
            'optimMethod',char(context.Optimizer),'nugget',context.Nugget);
        [model,info]=train_request(Xtrain,Ytrain,cfg,fitOptions);
        fit.modelCreated=~isempty(model);
        if isstruct(info)&&isfield(info,'trainTime')
            fit.trainTime=double(info.trainTime);
        end
        [mu,variance]=evaluate_request(model,Xassessment,context);
        mu=double(mu);variance=double(variance);
        assert(isequal(size(mu),[size(Xassessment,1) numel(outputNames)])&& ...
            all(isfinite(mu),'all'), ...
            'surrogates:surrogate_quality_fit_campaign:PredictionMeanShape', ...
            'A fitted model returned predicted means that are not finite or not of size %d x %d.', ...
            size(Xassessment,1),numel(outputNames));
        if context.ModelFamily=="GP"
            assert(isequal(size(variance),size(mu))&& ...
                all(isfinite(variance),'all')&&all(variance>=0,'all'), ...
                'surrogates:surrogate_quality_fit_campaign:PredictionVarianceShape', ...
                ['A fitted GP returned predictive variances that are not finite and ' ...
                 'non-negative or not of the size of its means.']);
        else
            variance=nan(size(mu));
        end
        fit.mean=mu;fit.variance=variance;
        if ~isempty(Yassessment)
            fit.metrics=surrogates.surrogate_quality_metrics( ...
                Yassessment,mu,variance,outputNames, ...
                'RelativeDenominatorTolerance',1e-12, ...
                'RangeTolerance',1e-12, ...
                'IntervalLevels',[.5 .8 .9 .95]);
        end
        fit.status="completed";
    catch ME
        fit.error=string(sprintf('%s: %s',ME.identifier,ME.message));
        fit.exception=ME;
    end
    hyperContext=struct('Campaign',context.Campaign,'Repeat',context.Repeat, ...
        'Fold',context.Fold,'Kernel',context.Kernel, ...
        'Optimizer',context.Optimizer,'Nugget',context.Nugget, ...
        'SeedBasis',context.SeedBasis,'FitSeed',context.FitSeed, ...
        'FitRequest',context.FitRequest, ...
        'TrainTime_s',fit.trainTime,'FitStatus',fit.status);
    if context.ModelFamily=="GP"
        fit.hyperparameters=surrogates.surrogate_quality_hyperparameters( ...
            model,inputNames,outputNames,hyperContext);
        fit.hyperparameters.Candidate=repmat( ...
            string(context.Candidate),height(fit.hyperparameters),1);
        fit.hyperparameters=movevars(fit.hyperparameters,'Candidate', ...
            'After','Kernel');
    end
    if isfield(context,'OutputIndex')&&context.OutputIndex>0
        if ~isempty(fit.metrics)
            fit.metrics.OutputIndex(:)=double(context.OutputIndex);
        end
        if ~isempty(fit.hyperparameters)
            fit.hyperparameters.OutputIndex(:)=double(context.OutputIndex);
        end
    end
    if fit.modelCreated
        try
            discard_model(model);fit.modelDiscarded=true;
        catch discardError
            if fit.status=="completed"
                fit.status="failed";fit.exception=discardError;
                fit.error=string(sprintf('%s: %s',discardError.identifier, ...
                    discardError.message));
            end
        end
    end
    model=[]; %#ok<NASGU>
end

function [trainingRows,assessmentRows,assessmentX,assessmentY,assessmentIDs]= ...
        request_data(request,design,X,Y,caseIDs,probeX)
    assessmentRows=zeros(0,1);assessmentIDs=zeros(0,1);assessmentY=[];
    outputIndex=0;
    if ismember('OutputIndex',request.Properties.VariableNames)
        outputIndex=double(request.OutputIndex);
    end
    switch request.Campaign
        case "kernel_cross_validation"
            held=design.kernelCVFolds.Repeat==request.Repeat& ...
                design.kernelCVFolds.Fold==request.Fold;
            if outputIndex>0
                held=held&design.kernelCVFolds.OutputIndex==outputIndex;
                available=design.kernelCVFolds.OutputIndex==outputIndex;
                eligibleRows=double( ...
                    design.kernelCVFolds.DevelopmentRowIndex(available));
            else
                eligibleRows=(1:size(X,1)).';
            end
            assessmentRows=double(design.kernelCVFolds.DevelopmentRowIndex(held));
            trainingRows=setdiff(eligibleRows,assessmentRows,'stable');
            assessmentX=X(assessmentRows,:);
            if outputIndex>0,assessmentY=Y(assessmentRows,outputIndex); ...
            else,assessmentY=Y(assessmentRows,:);end
            assessmentIDs=caseIDs(assessmentRows);
        case "same_data_seed_stability"
            if outputIndex>0
                trainingRows=find(logical( ...
                    design.outputAvailabilityMask(:,outputIndex)));
            else
                trainingRows=(1:size(X,1)).';
            end
            assessmentX=probeX;
        case "training_convergence"
            rows=design.trainingConvergenceMembership.Repeat==request.Repeat& ...
                design.trainingConvergenceMembership. ...
                    NominalGlobalDevelopmentCaseCount== ...
                    request.NominalGlobalDevelopmentCaseCount;
            if outputIndex>0
                rows=rows& ...
                    design.trainingConvergenceMembership.OutputIndex==outputIndex;
            end
            one=design.trainingConvergenceMembership(rows,:);
            trainingRows=double(one.DevelopmentRowIndex(one.SelectedForTraining));
            assessmentRows=double(one.DevelopmentRowIndex(one.TemporaryValidation));
            assessmentX=X(assessmentRows,:);
            if outputIndex>0,assessmentY=Y(assessmentRows,outputIndex); ...
            else,assessmentY=Y(assessmentRows,:);end
            assessmentIDs=caseIDs(assessmentRows);
        otherwise
            error('surrogates:surrogate_quality_fit_campaign:Campaign', ...
                'Unknown supporting fit campaign: %s',request.Campaign);
    end
    assert(numel(trainingRows)==request.TrainCaseCount&& ...
        size(assessmentX,1)==request.AssessmentCaseCount&& ...
        all(ismember(trainingRows,(1:size(X,1)).'))&& ...
        all(ismember(assessmentRows,(1:size(X,1)).')), ...
        'surrogates:surrogate_quality_fit_campaign:RequestMembership', ...
        ['A fit request''s training and assessment rows must be development cases ' ...
         'in the numbers it declares.']);
end

function context=context_from_request(request)
    names={'Campaign','Repeat','Fold','NominalGlobalDevelopmentCaseCount', ...
        'TrainCaseCount', ...
        'AssessmentCaseCount','ModelFamily','Candidate', ...
        'Kernel','Optimizer','Nugget','SeedBasis','FitSeed','FitRequest'};
    context=struct();
    for index=1:numel(names),context.(names{index})=request.(names{index})(1);end
    optional={'OutputIndex','Output'};
    for index=1:numel(optional)
        if ismember(optional{index},request.Properties.VariableNames)
            context.(optional{index})=request.(optional{index})(1);
        end
    end
end

function T=prediction_rows(context,caseIDs,developmentRows,X,truth,mu,variance, ...
        nearest,inputNames,outputNames,bounds)
    [caseIndex,outputIndex]=ndgrid(1:size(truth,1),1:size(truth,2));
    linear=sub2ind(size(truth),caseIndex(:),outputIndex(:));n=numel(linear);
    primitive=surrogates.surrogate_metric_primitives( ...
        truth(linear),mu(linear),variance(linear));
    residual=primitive.Residual;sigma=primitive.PredictiveStdRaw;
    standardized=primitive.StandardizedResidual;
    included50=primitive.IntervalIncluded(:,1);
    included80=primitive.IntervalIncluded(:,2);
    included90=primitive.IntervalIncluded(:,3);
    included95=primitive.IntervalIncluded(:,4);
    nlpd=primitive.GaussianPointNLPD;crps=primitive.GaussianPointCRPS;
    globalOutputIndex=outputIndex(:);
    rowOutput=reshape(string(outputNames(outputIndex(:))),[],1);
    if isfield(context,'OutputIndex')&&context.OutputIndex>0
        globalOutputIndex(:)=double(context.OutputIndex);
        rowOutput(:)=string(context.Output);
    end
    T=table(repmat(string(context.Campaign),n,1), ...
        repmat(double(context.Repeat),n,1),repmat(double(context.Fold),n,1), ...
        repmat(string(context.Kernel),n,1),repmat(string(context.Candidate),n,1), ...
        repmat(double(context.FitSeed),n,1), ...
        repmat(string(context.FitRequest),n,1), ...
        double(caseIDs(caseIndex(:))),double(developmentRows(caseIndex(:))), ...
        globalOutputIndex,rowOutput, ...
        truth(linear),mu(linear),variance(linear),sigma,residual,standardized, ...
        included50,included80,included90,included95,nlpd,crps, ...
        nearest(caseIndex(:)), ...
        'VariableNames',{'Campaign','Repeat','Fold','Kernel','Candidate', ...
        'FitSeed','FitRequest','CaseID','DevelopmentRowIndex', ...
        'OutputIndex','Output','Truth','GPMean','GPVariance','GPStd','Residual', ...
        'StandardizedResidual','Included50','Included80','Included90', ...
        'Included95','GaussianPointNLPD','GaussianPointCRPS', ...
        'NearestDevelopmentTrainingDistance'});
    normalized=(X-bounds(1,:))./(bounds(2,:)-bounds(1,:));
    for inputIndex=1:numel(inputNames)
        name=matlab.lang.makeValidName(char(inputNames(inputIndex)));
        T.(name)=X(caseIndex(:),inputIndex);
        T.(['Normalized_' name])=normalized(caseIndex(:),inputIndex);
    end
end

function T=probe_prediction_rows(context,probe,mu,variance,outputNames)
    nProbe=size(mu,1);nOutput=size(mu,2);
    [probeIndex,outputIndex]=ndgrid(1:nProbe,1:nOutput);
    linear=sub2ind(size(mu),probeIndex(:),outputIndex(:));n=numel(linear);
    globalOutputIndex=outputIndex(:);
    rowOutput=reshape(string(outputNames(outputIndex(:))),[],1);
    if isfield(context,'OutputIndex')&&context.OutputIndex>0
        globalOutputIndex(:)=double(context.OutputIndex);
        rowOutput(:)=string(context.Output);
    end
    T=table(repmat(string(context.Campaign),n,1), ...
        repmat(double(context.Repeat),n,1),repmat(string(context.Kernel),n,1), ...
        repmat(string(context.Candidate),n,1), ...
        repmat(double(context.FitSeed),n,1), ...
        repmat(string(context.FitRequest),n,1),probeIndex(:), ...
        globalOutputIndex,rowOutput,mu(linear), ...
        variance(linear),sqrt(variance(linear)), ...
        'VariableNames',{'Campaign','Repeat','Kernel','Candidate','FitSeed', ...
        'FitRequest','ProbeIndex','OutputIndex','Output', ...
        'GPMean','GPVariance','GPStd'});
    names=setdiff(probe.Properties.VariableNames, ...
        {'ProbeIndex','ProbeSeed'},'stable');
    for index=1:numel(names)
        T.(names{index})=probe.(names{index})(probeIndex(:));
    end
end

function T=add_metric_context(metrics,context,cohort,fit)
    n=height(metrics);
    actualTraining=double(context.NominalGlobalDevelopmentCaseCount);
    actualAssessment=NaN;
    if isfield(context,'TrainCaseCount')
        actualTraining=double(context.TrainCaseCount);
    end
    if isfield(context,'AssessmentCaseCount')
        actualAssessment=double(context.AssessmentCaseCount);
    end
    prefix=table(repmat(string(context.Campaign),n,1), ...
        repmat(double(context.Repeat),n,1),repmat(double(context.Fold),n,1), ...
        repmat(double(context.NominalGlobalDevelopmentCaseCount),n,1), ...
        repmat(actualTraining,n,1),repmat(actualAssessment,n,1), ...
        repmat(string(context.ModelFamily),n,1), ...
        repmat(string(context.Candidate),n,1), ...
        repmat(string(context.Kernel),n,1), ...
        repmat(double(context.FitSeed),n,1), ...
        repmat(string(context.FitRequest),n,1), ...
        repmat(string(cohort),n,1),repmat(string(fit.status),n,1), ...
        repmat(string(fit.error),n,1), ...
        'VariableNames',{'Campaign','Repeat','Fold', ...
        'NominalGlobalDevelopmentCaseCount', ...
        'ActualTrainingCaseCount','ActualAssessmentCaseCount','ModelFamily', ...
        'Candidate','Kernel','FitSeed','FitRequest','Cohort', ...
        'FitStatus','ErrorMessage'});
    T=[prefix metrics];
end

function T=pooled_oof_metrics(predictions,outputNames,settings)
    outputSpecific=isfield(settings,'outputSpecificAvailability')&& ...
        logical(settings.outputSpecificAvailability);
    outputMultiplier=1;
    if outputSpecific,outputMultiplier=numel(outputNames);end
    parts=cell(numel(settings.cvKernels)*settings.cvRepeats* ...
        outputMultiplier,1);part=0;
    for kernelIndex=1:numel(settings.cvKernels)
        kernel=string(settings.cvKernels{kernelIndex});
        for repeat=1:settings.cvRepeats
            outputIndexes=0;
            if outputSpecific,outputIndexes=1:numel(outputNames);end
            for requestedOutput=outputIndexes
                part=part+1;rows=predictions.Kernel==kernel& ...
                    predictions.Repeat==repeat;
                if requestedOutput>0
                    rows=rows&predictions.OutputIndex==requestedOutput;
                end
                one=sortrows(predictions(rows,:),{'CaseID','OutputIndex'});
                nDevelopment=numel(unique(one.CaseID));
                if requestedOutput>0
                    expected=double(settings.outputDevelopmentCounts(requestedOutput));
                    assert(nDevelopment==expected&&height(one)==expected, ...
                        'surrogates:surrogate_quality_fit_campaign:PooledOOFShape', ...
                        ['The pooled out-of-fold predictions do not cover each development case ' ...
                         'once per output.']);
                    metricOutputs=outputNames(requestedOutput);
                    truth=one.Truth;mu=one.GPMean;variance=one.GPVariance;
                else
                    assert(nDevelopment==settings.developmentCount&& ...
                        height(one)==nDevelopment*numel(outputNames), ...
                        'surrogates:surrogate_quality_fit_campaign:PooledOOFShape', ...
                        ['The pooled out-of-fold predictions do not cover each development case ' ...
                         'once per output.']);
                    truth=reshape(one.Truth,numel(outputNames),nDevelopment).';
                    mu=reshape(one.GPMean,numel(outputNames),nDevelopment).';
                    variance=reshape(one.GPVariance,numel(outputNames),nDevelopment).';
                    metricOutputs=outputNames;
                end
                metrics=surrogates.surrogate_quality_metrics(truth,mu,variance, ...
                    metricOutputs,'RelativeDenominatorTolerance', ...
                    settings.relativeDenominatorTolerance,'RangeTolerance', ...
                    settings.rangeTolerance,'IntervalLevels',settings.intervalLevels);
                if requestedOutput>0,metrics.OutputIndex(:)=requestedOutput;end
                context=struct('Campaign',"kernel_cross_validation", ...
                    'Repeat',repeat,'Fold',0, ...
                    'NominalGlobalDevelopmentCaseCount',NaN, ...
                    'ModelFamily',"GP",'Candidate',kernel,'Kernel',kernel, ...
                    'FitSeed',NaN,'FitRequest',string(sprintf( ...
                    'kernel_cross_validation/o%d/r%d/pooled/%s', ...
                    requestedOutput,repeat,char(kernel))));
                fit=struct('status',"completed",'error',"");
                parts{part}=add_metric_context(metrics,context, ...
                    "pooled_development_oof",fit);
            end
        end
    end
    T=vertcat(parts{:});
end

function T=metric_summary(metrics,keyNames)
    names=metric_names();keys=unique(metrics(:,keyNames),'rows','stable');
    parts=cell(height(keys)*numel(names),1);part=0;
    for keyIndex=1:height(keys)
        rows=matching_rows(metrics,keys(keyIndex,:),keyNames);
        for metricIndex=1:numel(names)
            part=part+1;values=double(metrics.(names{metricIndex})(rows));
            values=sort(values(isfinite(values)));
            stats=descriptive(values);
            parts{part}=[keys(keyIndex,:) table(string(names{metricIndex}), ...
                numel(values),stats(1),stats(2),stats(3),stats(4),stats(5), ...
                stats(6),stats(7),stats(8),'VariableNames',{'Metric','ValueCount', ...
                'Mean','SD','Median','Q025','Q975','Minimum','Maximum', ...
                'CoefficientOfVariation'})];
        end
    end
    T=vertcat(parts{:});
end

function rows=matching_rows(T,key,keyNames)
    rows=true(height(T),1);
    for index=1:numel(keyNames)
        name=keyNames{index};rows=rows&T.(name)==key.(name)(1);
    end
end

function T=paired_kernel_comparison(perFold,pooled,settings)
    foldParts=paired_kernel_level(perFold,"fold",{'Repeat','Fold','OutputIndex'}, ...
        settings);
    pooledParts=paired_kernel_level(pooled,"pooled_oof", ...
        {'Repeat','OutputIndex'},settings);
    T=vertcat(foldParts,pooledParts);
    groupKey=T.ComparisonLevel+"|"+T.LeftKernel+"|"+T.RightKernel+ ...
        "|"+string(T.OutputIndex)+"|"+T.Metric;
    [~,~,group]=unique(groupKey,'stable');
    T.NegativeDifferenceCount=zeros(height(T),1);
    T.TiedDifferenceCount=zeros(height(T),1);
    T.PositiveDifferenceCount=zeros(height(T),1);T.PairCount=zeros(height(T),1);
    for index=1:max(group)
        rows=group==index;values=T.DifferenceSign(rows);finite=isfinite(values);
        T.NegativeDifferenceCount(rows)=nnz(values(finite)<0);
        T.TiedDifferenceCount(rows)=nnz(values(finite)==0);
        T.PositiveDifferenceCount(rows)=nnz(values(finite)>0);
        T.PairCount(rows)=nnz(finite);
    end
end

function T=paired_kernel_level(metrics,comparisonLevel,keyNames,settings)
    pairs=nchoosek(1:numel(settings.cvKernels),2);names=metric_names();
    rowsPerKernel=height(metrics)/numel(settings.cvKernels);
    assert(rowsPerKernel==fix(rowsPerKernel));
    parts=cell(size(pairs,1)*rowsPerKernel*numel(names),1);part=0;
    for pairIndex=1:size(pairs,1)
        leftKernel=string(settings.cvKernels{pairs(pairIndex,1)});
        rightKernel=string(settings.cvKernels{pairs(pairIndex,2)});
        left=sortrows(metrics(metrics.Kernel==leftKernel,:),keyNames);
        right=sortrows(metrics(metrics.Kernel==rightKernel,:),keyNames);
        assert(height(left)==height(right));
        for keyIndex=1:numel(keyNames)
            assert(all(left.(keyNames{keyIndex})==right.(keyNames{keyIndex})), ...
                'surrogates:surrogate_quality_fit_campaign:PairedKernelKeys', ...
                'The metric rows of the two compared kernels must pair by %s.',keyNames{keyIndex});
        end
        for rowIndex=1:height(left)
            for metricIndex=1:numel(names)
                part=part+1;
                name=names{metricIndex};a=left.(name)(rowIndex);b=right.(name)(rowIndex);
                tolerance=settings.pairDifferenceTolerance* ...
                    max([1 abs(a) abs(b)]);difference=a-b;
                signValue=NaN;
                if isfinite(difference)
                    signValue=double(difference>tolerance)-double(difference<-tolerance);
                end
                parts{part}=table(string(comparisonLevel), ...
                    left.Repeat(rowIndex),left.Fold(rowIndex), ...
                    left.OutputIndex(rowIndex),left.Output(rowIndex),leftKernel, ...
                    rightKernel,string(name),a,b,difference,tolerance,signValue, ...
                    'VariableNames',{'ComparisonLevel','Repeat','Fold', ...
                    'OutputIndex','Output','LeftKernel','RightKernel','Metric', ...
                    'LeftValue','RightValue','DifferenceLeftMinusRight', ...
                    'NumericTieTolerance','DifferenceSign'});
            end
        end
    end
    T=vertcat(parts{:});
end

function [meanTable,sdTable]=same_data_stability(predictions,probe, ...
        outputNames,settings)
    meanParts=cell(numel(settings.sameDataKernels)*numel(outputNames)* ...
        settings.probeCount,1);part=0;
    sdRowsPerOutput=2*settings.probeCount+6+ ...
        nchoosek(settings.sameDataReplicates,2);
    sdParts=cell(numel(settings.sameDataKernels)*numel(outputNames)* ...
        sdRowsPerOutput,1);sdPart=0;
    for kernelIndex=1:numel(settings.sameDataKernels)
        kernel=string(settings.sameDataKernels{kernelIndex});
        for outputIndex=1:numel(outputNames)
            one=predictions(predictions.Kernel==kernel& ...
                predictions.OutputIndex==outputIndex,:);
            meanSurface=nan(settings.probeCount,settings.sameDataReplicates);
            sdSurface=meanSurface;
            for repeat=1:settings.sameDataReplicates
                rows=one.Repeat==repeat;ordered=sortrows(one(rows,:),'ProbeIndex');
                assert(height(ordered)==settings.probeCount);
                meanSurface(:,repeat)=ordered.GPMean;sdSurface(:,repeat)=ordered.GPStd;
            end
            for probeIndex=1:settings.probeCount
                part=part+1;values=meanSurface(probeIndex,:);
                differences=pairwise_absolute_differences(values);
                meanParts{part}=table(kernel,outputIndex,string(outputNames(outputIndex)), ...
                    probeIndex,mean(values),std(values,0),mean(differences), ...
                    max(differences),'VariableNames',{'Kernel','OutputIndex', ...
                    'Output','ProbeIndex','MeanGPMeanAcrossSeeds', ...
                    'SDGPMeanAcrossSeeds','MeanAbsolutePairwiseDifference', ...
                    'MaximumAbsolutePairwiseDifference'});
                sdValues=sdSurface(probeIndex,:);cv=NaN;
                if abs(mean(sdValues))>eps,cv=std(sdValues,0)/abs(mean(sdValues));end
                ratio=NaN;if min(sdValues)>0,ratio=max(sdValues)/min(sdValues);end
                sdPart=sdPart+1;
                sdParts{sdPart}=stability_long_row("pointwise",kernel, ...
                    outputIndex,outputNames(outputIndex),probeIndex,NaN,NaN, ...
                    "predictive_sd_coefficient_of_variation",cv);
                sdPart=sdPart+1;
                sdParts{sdPart}=stability_long_row("pointwise",kernel, ...
                    outputIndex,outputNames(outputIndex),probeIndex,NaN,NaN, ...
                    "predictive_sd_maximum_to_minimum_ratio",ratio);
            end
            pointCV=std(sdSurface,0,2)./max(abs(mean(sdSurface,2)),eps);
            pointRatio=max(sdSurface,[],2)./max(min(sdSurface,[],2),eps);
            for statistic=["mean" "median" "maximum"]
                sdPart=sdPart+1;
                sdParts{sdPart}=stability_long_row("across_probe_summary", ...
                    kernel,outputIndex,outputNames(outputIndex),NaN,NaN,NaN, ...
                    "predictive_sd_cv_"+statistic,summary_stat(pointCV,statistic));
                sdPart=sdPart+1;
                sdParts{sdPart}=stability_long_row("across_probe_summary", ...
                    kernel,outputIndex,outputNames(outputIndex),NaN,NaN,NaN, ...
                    "predictive_sd_ratio_"+statistic, ...
                    summary_stat(pointRatio,statistic));
            end
            for left=1:settings.sameDataReplicates-1
                for right=left+1:settings.sameDataReplicates
                    matrix=corrcoef(sdSurface(:,left),sdSurface(:,right));rho=NaN;
                    if isequal(size(matrix),[2 2]),rho=matrix(1,2);end
                    sdPart=sdPart+1;
                    sdParts{sdPart}=stability_long_row( ...
                        "pairwise_sd_surface",kernel,outputIndex, ...
                        outputNames(outputIndex),NaN,left,right, ...
                        "pearson_surface_correlation",rho);
                end
            end
        end
    end
    assert(part==numel(meanParts)&&sdPart==numel(sdParts));
    meanTable=vertcat(meanParts{:});sdTable=vertcat(sdParts{:});
    probeNames=setdiff(probe.Properties.VariableNames, ...
        {'ProbeIndex','ProbeSeed'},'stable');
    for index=1:numel(probeNames)
        meanTable.(probeNames{index})=probe.(probeNames{index})(meanTable.ProbeIndex);
    end
end

