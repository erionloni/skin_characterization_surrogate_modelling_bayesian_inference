function folds = pce_shared_folds(nRows, outputName, ~, cvFolds, trainingContract)
%PCE_SHARED_FOLDS The one cross-validation partition shared by every PCE candidate of an output.
%   FOLDS = surrogates.pce_shared_folds(NROWS, OUTPUTNAME, OUTPUTINDEX,
%   CVFOLDS, TRAININGCONTRACT) returns the fold of each of the NROWS
%   development cases of one output: its part of the one global
%   material-group assignment (TRAININGCONTRACT.cvFoldAssignment, from
%   surrogates.fit_generalized), so that all candidates are compared on the same
%   folds. It refuses a partition that does not cover all CVFOLDS folds or
%   that splits a material group over two folds. Side effects: none.

    groups=string(trainingContract.trainingSplitGroupIdentities(:));
    folds=double(trainingContract.cvFoldAssignment(:));
    assert(numel(groups)==nRows&&all(strlength(groups)>0)&& ...
        numel(folds)==nRows&&all(isfinite(folds))&&all(folds==fix(folds))&& ...
        all(folds>=1&folds<=cvFolds)&& ...
        isequal(unique(folds).',(1:cvFolds)), ...
        'surrogates:pce_shared_folds:TrainingGroups', ...
        ['Output %s needs a split group and a fold (1 to %d, all used) for each ' ...
         'of its %d development cases.'],outputName,cvFolds,nRows);
    % The global schedule is authoritative; the output uses only its subset.
    [uniqueGroups,~,groupIndex]=unique(groups,'stable');
    assert(numel(uniqueGroups)>=cvFolds, ...
        'surrogates:pce_shared_folds:CVGroups', ...
        'The scalar training cohort has fewer material groups than CV folds.');
    for i=1:numel(uniqueGroups)
        assert(isscalar(unique(folds(groupIndex==i))), ...
            'surrogates:pce_shared_folds:CVGroupLeakage', ...
            'Material group %s of output %s lies in more than one CV fold.', ...
            uniqueGroups(i),outputName);
    end
end
