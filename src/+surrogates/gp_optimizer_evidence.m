function evidence=gp_optimizer_evidence(model)
%GP_OPTIMIZER_EVIDENCE Re-evaluate a fitted GP's analytic leave-one-out objective.
%   EVIDENCE = surrogates.gp_optimizer_evidence(MODEL) evaluates UQLab's
%   analytic leave-one-out MSE (uq_Kriging_eval_J_of_theta_CV) of the
%   single-output Kriging MODEL at its fitted hyperparameters and requires
%   it to agree with the objective UQLab saved (1e-9 absolute plus relative).
%   The multi-start selection ranks candidates by this re-evaluated
%   objective, and a candidate for which it fails is not eligible
%   (surrogates.fit_gp_candidates). EVIDENCE records the objective, the
%   optimizer settings and ceilings, theta, the process variance and the
%   trend coefficients. No optimization; the model is not changed.
%   Side effects: none.
    assert(size(model.ExpDesign.Y,2)==1, ...
        'surrogates:gp_optimizer_evidence:ScalarOutput','Check failed: surrogates:gp_optimizer_evidence:ScalarOutput.');
    k=model.Internal.Kriging(1);r=model.Internal.Regression(1);
    assert(strcmpi(k.GP.EstimMethod,'CV')&&r.IsRegression&& ...
        ~r.EstimNoise&&isscalar(r.SigmaNSQ)&& ...
        all(cellfun(@numel,model.Internal.Runtime.CV.RandIdx)==1), ...
        'surrogates:gp_optimizer_evidence:AnalyticLOOContract','Check failed: surrogates:gp_optimizer_evidence:AnalyticLOOContract.');
    n=size(model.ExpDesign.Y,1);
    p=struct('X',model.ExpDesign.U,'Y',model.ExpDesign.Y,'N',n, ...
        'F',k.Trend.F,'trend_type',k.Trend.Type,'CorrOptions',k.GP.Corr, ...
        'RandIdx',{model.Internal.Runtime.CV.RandIdx}, ...
        'IsRegression',r.IsRegression,'EstimNoise',r.EstimNoise, ...
        'sigmaNSQ',eye(n)*r.SigmaNSQ);
    theta=model.Kriging(1).theta(:).';
    process=surrogates.gp_process_variance(model,1);
    objective=uq_Kriging_eval_J_of_theta_CV([theta process],p);
    assert(isscalar(objective)&&isfinite(objective)&&objective>=0&& ...
        objective<realmax&&isfinite(k.Optim.ObjFun), ...
        'surrogates:gp_optimizer_evidence:Objective','Check failed: surrogates:gp_optimizer_evidence:Objective.');
    discrepancy=abs(objective-k.Optim.ObjFun);
    tolerance=1e-9+1e-9*abs(k.Optim.ObjFun);
    assert(discrepancy<=tolerance, ...
        'surrogates:gp_optimizer_evidence:ObjectiveReevaluation','Check failed: surrogates:gp_optimizer_evidence:ObjectiveReevaluation.');
    localDefaults=optimoptions('fmincon','Algorithm','interior-point');
    evidence=struct('schemaVersion','scalar_gp_optimizer_evidence_v1', ...
        'objectiveName','analytic_leave_one_out_MSE_mbar2', ...
        'objectiveDirection','minimize','savedObjective',k.Optim.ObjFun, ...
        'reevaluatedObjective',objective,'reevaluationAbsDifference',discrepancy, ...
        'reevaluationTolerance',tolerance,'optimizer',k.Optim, ...
        'gaGenerationCeiling',k.Optim.MaxIter, ...
        'localIterationCeiling',k.Optim.MaxIter, ...
        'localFunctionEvaluationCeiling',localDefaults.MaxFunctionEvaluations, ...
        'localFunctionEvaluationCeilingSource', ...
            'installed_fmincon_interior_point_default_not_overridden_by_UQLab', ...
        'iterationCountMeaning','UQLab_records_GA_generations_only', ...
        'localIterationCountRecorded',false, ...
        'inputNormalizationMean',model.Internal.ExpDesign.muX, ...
        'inputNormalizationSD',model.Internal.ExpDesign.sigmaX, ...
        'theta',theta,'processVariance',process, ...
        'trendCoefficients',model.Kriging(1).beta);
end
