function [semantics,oof,factorization]=surrogate_quality_variance_semantics( ...
        predictions,hyperparameters,kernelFolds,calibrationFolds,cfg)
%SURROGATE_QUALITY_VARIANCE_SEMANTICS The out-of-fold variance product of the audit.
%   [SEMANTICS, OOF, FACTORIZATION] =
%   surrogates.surrogate_quality_variance_semantics(PREDICTIONS,
%   HYPERPARAMETERS, KERNELFOLDS, CALIBRATIONFOLDS, CFG) joins the
%   development-only
%   out-of-fold GP predictions with the fitted process variance, the local
%   variance shape h = v_raw / sigma^2 and the declared GP and calibration
%   folds, and checks the factorization v_raw = sigma^2 h row by row.
%   SEMANTICS states what the variances mean (UQLab's second output is the
%   predictive variance of the latent Kriging predictor, in mbar^2) and
%   whether the local variance models may enter the calibration
%   comparison: only when every row factorizes within the tolerance with a
%   positive local shape. It performs no model fit or evaluation.
%   Side effects: none.

    arguments
        predictions table
        hyperparameters table
        kernelFolds table
        calibrationFolds table
        cfg (1,1) struct
    end
    % The tolerance of the settings (A.4).
    tolerance=double(cfg.surrogateQualityAudit.varianceFactorizationTolerance);
    [oof,factorization]=authoritative_oof_product(predictions, ...
        hyperparameters,kernelFolds,calibrationFolds,tolerance);

    required={'GPVariance','ProcessVariance','LocalShape', ...
        'FactorizedVariance','FactorizationAbsoluteError', ...
        'FactorizationRelativeError','FactorizationWithinTolerance'};
    assert(all(ismember(required,factorization.Properties.VariableNames)), ...
        'surrogates:surrogate_quality_variance_semantics:Schema', ...
        'The variance-factorization table is missing a required field.');

    finiteRows=isfinite(factorization.GPVariance)& ...
        isfinite(factorization.ProcessVariance)& ...
        factorization.ProcessVariance>0& ...
        isfinite(factorization.LocalShape)&factorization.LocalShape>=0& ...
        isfinite(factorization.FactorizedVariance)& ...
        isfinite(factorization.FactorizationAbsoluteError)& ...
        isfinite(factorization.FactorizationRelativeError);
    allRowsVerified=height(factorization)>0&&all(finiteRows);
    maxAbsolute=max_or_nan( ...
        factorization.FactorizationAbsoluteError(finiteRows));
    maxRelative=max_or_nan( ...
        factorization.FactorizationRelativeError(finiteRows));
    factorizationVerified=allRowsVerified&& ...
        all(factorization.FactorizationWithinTolerance);

    verified=factorizationVerified;
    reason='';
    if ~allRowsVerified
        reason='nonfinite_or_nonpositive_process_variance_factorization_rows';
    elseif ~factorizationVerified
        reason='variance_factorization_tolerance_exceeded';
    end
    semantics=struct( ...
        'schema_version','uqlab_kriging_variance_semantics_audit_v2', ...
        'status',ternary(verified,'verified','not_verified'), ...
        'verification_reason',reason, ...
        'environment',utils.environment_line(), ...
        'second_uq_evalModel_output','predictive_variance_not_standard_deviation', ...
        'prediction_quantity', ...
            'latent_kriging_predictor_mean_squared_error', ...
        'process_variance_field','Internal.Kriging(output).GP.sigmaSQ', ...
        'process_variance_units','mbar^2', ...
        'returned_variance_units','mbar^2', ...
        'returned_standard_deviation_units','mbar', ...
        'output_normalization_reversal', ...
            'UQLab_returns_predictions_in_original_physical_output_units', ...
        'nugget_value',double(cfg.gp.nugget), ...
        'nugget_role', ...
            'homoscedastic_regression_numerical_nugget_in_training_covariance', ...
        'new_point_measurement_variance_included',false, ...
        'measurement_variance_included',false, ...
        'variance_squaring_count',0, ...
        'factorization_formula','v_raw=process_variance*h', ...
        'factorization_row_count',height(factorization), ...
        'finite_factorization_row_count',nnz(finiteRows), ...
        'factorization_relative_tolerance',tolerance, ...
        'maximum_absolute_factorization_error',maxAbsolute, ...
        'maximum_relative_factorization_error',maxRelative, ...
        'factorization_verified',factorizationVerified, ...
        'local_variance_models_permitted',verified, ...
        'production_covariance_modified',false);
end

function [O,F]=authoritative_oof_product(P,H,kernelFolds,calibrationFolds,tolerance)
    requiredP={'Kernel','Repeat','Fold','FitSeed','FitRequest', ...
        'CaseID','OutputIndex','Output','Truth','GPMean','GPVariance','GPStd', ...
        'Residual','StandardizedResidual','NearestDevelopmentTrainingDistance'};
    requiredH={'Kernel','Repeat','Fold','FitRequest','OutputIndex', ...
        'InputIndex','ProcessVariance'};
    requiredKernelFolds={'Repeat','Fold','FoldAssignmentSeed','CaseID'};
    requiredCalibrationFolds={'CaseID','CalibrationFold', ...
        'CalibrationFoldAssignmentSeed'};
    assert(all(ismember(requiredP,P.Properties.VariableNames))&& ...
        all(ismember(requiredH,H.Properties.VariableNames))&& ...
        all(ismember(requiredKernelFolds,kernelFolds.Properties.VariableNames))&& ...
        all(ismember(requiredCalibrationFolds, ...
        calibrationFolds.Properties.VariableNames)), ...
        'surrogates:surrogate_quality_variance_semantics:InputSchema', ...
        ['The prediction, hyperparameter, kernel-fold and calibration-fold tables lack ' ...
         'required columns; rerun the step ''surrogate_audit''.']);

    O=P;O.Kernel=string(O.Kernel);O.FitRequest=string(O.FitRequest);
    O.Repeat=double(O.Repeat);O.Fold=double(O.Fold);O.CaseID=double(O.CaseID);
    O.OutputIndex=double(O.OutputIndex);O.GPVariance=double(O.GPVariance);
    H=H(double(H.InputIndex)==1,:);H.Kernel=string(H.Kernel);
    H.FitRequest=string(H.FitRequest);
    H.OutputIndex=double(H.OutputIndex);H.ProcessVariance=double(H.ProcessVariance);
    predictionKey=O.FitRequest+"|"+string(O.OutputIndex);
    hyperparameterKey=H.FitRequest+"|"+string(H.OutputIndex);
    assert(numel(unique(hyperparameterKey))==height(H), ...
        'surrogates:surrogate_quality_variance_semantics:HyperparameterUniqueness', ...
        'The hyperparameter table repeats a fit request and output.');
    [foundProcess,processIndex]=ismember(predictionKey,hyperparameterKey);
    assert(all(foundProcess)&&all(O.Kernel==H.Kernel(processIndex))&& ...
        all(O.Repeat==double(H.Repeat(processIndex)))&& ...
        all(O.Fold==double(H.Fold(processIndex))), ...
        'surrogates:surrogate_quality_variance_semantics:HyperparameterJoin', ...
        ['Every prediction must have the hyperparameters of its fit request and ' ...
         'output, with the same kernel, repeat and fold.']);

    outputSpecificKernel=ismember('OutputIndex', ...
        kernelFolds.Properties.VariableNames);
    if outputSpecificKernel
        foldKey=string(double(kernelFolds.OutputIndex))+"|"+ ...
            string(double(kernelFolds.Repeat))+"|"+ ...
            string(double(kernelFolds.CaseID));
        predictionFoldKey=string(O.OutputIndex)+"|"+string(O.Repeat)+"|"+ ...
            string(O.CaseID);
    else
        foldKey=string(double(kernelFolds.Repeat))+"|"+ ...
            string(double(kernelFolds.CaseID));
        predictionFoldKey=string(O.Repeat)+"|"+string(O.CaseID);
    end
    assert(numel(unique(foldKey))==height(kernelFolds), ...
        'surrogates:surrogate_quality_variance_semantics:KernelFoldUniqueness', ...
        'The kernel-fold table repeats a case (of a repeat).');
    [foundFold,foldIndex]=ismember(predictionFoldKey,foldKey);
    assert(all(foundFold)&& ...
        all(O.Fold==double(kernelFolds.Fold(foldIndex))), ...
        'surrogates:surrogate_quality_variance_semantics:KernelFoldJoin', ...
        'Every prediction must have its case''s kernel fold, and the same fold.');

    outputSpecificCalibration=ismember('OutputIndex', ...
        calibrationFolds.Properties.VariableNames);
    if outputSpecificCalibration
        calibrationKey=string(double(calibrationFolds.OutputIndex))+"|"+ ...
            string(double(calibrationFolds.CaseID));
        predictionCalibrationKey=string(O.OutputIndex)+"|"+string(O.CaseID);
    else
        calibrationKey=string(double(calibrationFolds.CaseID));
        predictionCalibrationKey=string(O.CaseID);
    end
    assert(numel(unique(calibrationKey))==height(calibrationFolds), ...
        'surrogates:surrogate_quality_variance_semantics:CalibrationFoldUniqueness', ...
        'The calibration-fold table repeats a case (of a repeat).');
    [foundCalibration,calibrationIndex]=ismember( ...
        predictionCalibrationKey,calibrationKey);
    assert(all(foundCalibration), ...
        'surrogates:surrogate_quality_variance_semantics:CalibrationFoldJoin', ...
        'Every prediction must have its case''s calibration fold.');

    O.FoldAssignmentSeed=double(kernelFolds.FoldAssignmentSeed(foldIndex));
    O.ProcessVariance=H.ProcessVariance(processIndex);
    O.ProcessVarianceUnits=repmat("mbar^2",height(O),1);
    O.LocalShape=O.GPVariance./O.ProcessVariance;
    invalid=~isfinite(O.ProcessVariance)|O.ProcessVariance<=0| ...
        ~isfinite(O.GPVariance)|O.GPVariance<0;
    O.LocalShape(invalid)=NaN;
    O.LocalShapeUnits=repmat("dimensionless",height(O),1);
    O.FactorizedVariance=O.ProcessVariance.*O.LocalShape;
    O.FactorizationAbsoluteError=abs(O.GPVariance-O.FactorizedVariance);
    O.FactorizationRelativeError=O.FactorizationAbsoluteError./ ...
        max(abs(O.GPVariance),eps);
    O.VarianceSafeguardSD=repmat(eps,height(O),1);
    O.NearestDevelopmentTrainingDistanceUnits=repmat( ...
        "Euclidean_distance_in_canonical_unit_box",height(O),1);
    O.CalibrationFold=double( ...
        calibrationFolds.CalibrationFold(calibrationIndex));
    O=sortrows(O,{'Kernel','Repeat','CaseID','OutputIndex'});

    F=O(:,{'Kernel','Repeat','Fold','CalibrationFold', ...
        'CaseID','OutputIndex','Output', ...
        'GPVariance','ProcessVariance','LocalShape','FactorizedVariance', ...
        'FactorizationAbsoluteError','FactorizationRelativeError'});
    F.FactorizationTolerance=tolerance*max(1,abs(F.GPVariance));
    F.FactorizationWithinTolerance= ...
        F.FactorizationAbsoluteError<=F.FactorizationTolerance;
    F.SecondUQEvalModelOutputSemantics=repmat( ...
        "native_UQLab_predictor_variance_consumed_as_variance",height(F),1);
    F.VarianceUnits=repmat("mbar^2",height(F),1);
end

function value=max_or_nan(values)
    values=double(values(:));
    if isempty(values),value=NaN;else,value=max(values);end
end

function value=ternary(condition,left,right)
    if condition,value=left;else,value=right;end
end
