function value=run_relative(pathValue,runRoot)
    pathValue=utils.absolute_path(pathValue);
    runRoot=utils.absolute_path(runRoot);
    prefix=[runRoot filesep];
    if ispc
        contained=startsWith(lower(pathValue),lower(prefix));
    else
        contained=startsWith(pathValue,prefix);
    end
    assert(contained, ...
        'surrogates:fit_generalized:ResultPathOutsideRun', ...
        'The result record of the refit lies outside the run folder.');
    value=strrep(pathValue(numel(prefix)+1:end),'\','/');
end

function values=run_relative_paths(paths,runRoot)
    paths=string(paths);values=strings(size(paths));
    for i=1:numel(paths)
        if strlength(paths(i))>0
            values(i)=string(run_relative(paths(i),runRoot));
        end
    end
end
