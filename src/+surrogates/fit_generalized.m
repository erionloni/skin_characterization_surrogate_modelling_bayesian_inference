function result = fit_generalized(cfg, varargin)
%FIT_GENERALIZED Refit the generalized GPs and PCEs of the six closing pressures.
%   RESULT = surrogates.fit_generalized(CFG) fits, for each output in the order
%   1, 6, 2, 3, 4, 5, the GP (surrogates.train_generalized_gp) and the PCE
%   (surrogates.train_generalized_pce) on the development cases of the dataset
%   CFG.files.dataset that observe the output, each after its 5-fold
%   cross-validation on the one global material-group fold assignment. It
%   then assembles the two ensembles, writes them with their resolvers
%   (CFG.files.gp, CFG.files.pce) and the tables of the fits (training-only
%   CV, training status, PCE complexity, GP hyperparameters and fit seeds),
%   and records the refit's status (stage2_gate_decision.json). Outputs
%   already fitted (their checkpoints exist) are reused.
%   surrogates.fit_generalized(CFG,'WorkerKind','gp'|'pce','WorkerOutput',J) fits
%   only output J of one family (for example one cluster job per output); a
%   later call without them assembles the ensembles.
%   It refuses a configuration that binds the approved package (the
%   approved models are used as they are) and a dataset whose cohort
%   decision does not allow fitting (step 'dataset').
%   Computation: about 1.5 h at the thesis settings; minutes with a
%   demonstration budget (cfg.gp.demonstrationIterations).
%   Side effects: writes the files above; the random number generator's
%   state is restored afterwards.

    assert(strcmp(cfg.dataMode,'real_extended'), ...
        'surrogates:fit_generalized:WrongRoute', ...
        'The generalized refit runs on the generalized route.');
    assert(~cfg.realExtended.packageBound, ...
        'surrogates:fit_generalized:ApprovedPackageBound', ...
        'The approved package is used as it is; a refit runs without binding it.');
    worker=parse_options(varargin{:});
    roots=make_roots(cfg);
    [data,gate]=load_and_validate_stage1(cfg);
    write_execution_plan(cfg,data,gate,roots);

    workerKind=worker.WorkerKind;
    workerMode=~isempty(workerKind)||~isempty(worker.WorkerOutput);
    if workerMode
        assert(any(strcmp(workerKind,{'gp','pce'}))&&~isempty(worker.WorkerOutput), ...
            'surrogates:fit_generalized:WorkerOptions', ...
            'Pass both WorkerKind (gp or pce) and WorkerOutput (1 to 6).');
        outputIndex=double(worker.WorkerOutput);
        assert(isscalar(outputIndex)&&isfinite(outputIndex)&& ...
            outputIndex==floor(outputIndex)&&outputIndex>=1&&outputIndex<=6, ...
            'surrogates:fit_generalized:WorkerOutputIndex', ...
            'WorkerOutput must be an integer from 1 to 6.');
        execute_one(workerKind,outputIndex,data,cfg,roots);
        write_progress(data,cfg,roots);
        result=struct('schemaVersion','real_extended_stage2_result_v2', ...
            'status','WORKER_OUTPUT_TERMINAL','family',workerKind, ...
            'outputIndex',outputIndex, ...
            'retryAttempt',surrogates.generalized_retry_attempt(cfg));
        return;
    end

    for outputIndex=[1 6 2 3 4 5]
        execute_one('gp',outputIndex,data,cfg,roots);
        write_progress(data,cfg,roots);
        execute_one('pce',outputIndex,data,cfg,roots);
        write_progress(data,cfg,roots);
    end
    result=finalize_stage2(data,gate,cfg,roots);
end

function execute_one(family,outputIndex,data,cfg,roots)
    outputName=data.outputNames{outputIndex};
    cohort=output_training_cohort(data,outputIndex,cfg);
    context=surrogates.generalized_fit_context(data,cfg);
    fprintf('[real_extended s02] %s output %d/6: %s (%d rows)\n', ...
        upper(family),outputIndex,outputName,size(cohort.X,1));
    if strcmp(family,'gp')
        fit=surrogates.train_generalized_gp(cohort.X,cohort.y, ...
            cfg,outputName,outputIndex,roots.gpModels,cohort.contract);
    else
        fit=surrogates.train_generalized_pce(cohort.X,cohort.y, ...
            cfg,outputName,outputIndex,roots.pceModels,cohort.contract);
    end
    logPath=fullfile(roots.logs,sprintf('%s_%02d_%s.txt', ...
        family,outputIndex,outputName));
    message=sprintf([ ...
        'CONFIGURED GENERALIZED SURROGATE\n' ...
        '%d SOURCE PROBE RUNIDS ARE UNAVAILABLE\n' ...
        'STAGE 9B IS OUTSIDE THIS RUN\n\n' ...
        'family: %s\noutput_index: %d\noutput_name: %s\n' ...
        'retry_attempt: %d\nexecution_status: %s\ncheckpoint: %s\n'], ...
        context.missingProbeRunIDs, ...
        family,outputIndex,outputName, ...
        retry_attempt_from_record(fit.record,family),fit.record.executionStatus, ...
        run_relative(fit.path,cfg.paths.runRoot));
    utils.atomic_write_text(logPath,message);
end

function cohort=output_training_cohort(data,outputIndex,cfg)
%OUTPUT_TRAINING_COHORT The development cases that observe one output, with their folds.
    y=double(data.Y_development_all(:,outputIndex));
    mask=isfinite(y);
    assert(any(mask),'surrogates:fit_generalized:OutputTrainingEmpty', ...
        'No development case observes output %s.',data.outputNames{outputIndex});
    splitGroups=string(data.developmentSplitGroupIdentities(mask));
    materialGroups=string(data.developmentMaterialGroupIdentities(mask));
    globalFolds=global_cv_folds(data,cfg);
    contract=struct( ...
        'schemaVersion','real_extended_output_training_contract_v3', ...
        'outputIndex',outputIndex,'outputName',data.outputNames{outputIndex}, ...
        'trainingCount',nnz(mask), ...
        'trainingCaseIDs',reshape(double(data.developmentCaseIDsAll(mask)),1,[]), ...
        'trainingMaterialGroupIdentities',{cellstr(materialGroups).'}, ...
        'trainingSplitGroupIdentities',{cellstr(splitGroups).'}, ...
        'cvFoldAssignment',reshape(double(globalFolds(mask)),[],1), ...
        'trainingX',double(data.X_development_all(mask,:)), ...
        'trainingY',y(mask), ...
        'noImputation',true);
    cohort=struct('X',double(data.X_development_all(mask,:)), ...
        'y',y(mask),'contract',contract);
end

function folds=global_cv_folds(data,cfg)
    gpPolicy=surrogates.generalized_gp_policy(cfg);
    pcePolicy=surrogates.generalized_pce_policy(cfg);
    assert(gpPolicy.cvFolds==pcePolicy.cvFolds, ...
        'surrogates:fit_generalized:CVFoldPolicy', ...
        'GP and PCE must use one shared global material-group CV assignment.');
    groups=string(data.developmentSplitGroupIdentities(:));
    [uniqueGroups,~,groupIndex]=unique(groups,'stable');
    k=double(gpPolicy.cvFolds);
    assert(numel(uniqueGroups)>=k,'surrogates:fit_generalized:CVGroups', ...
        'The development cohort has fewer material groups than CV folds.');
    groupFolds=surrogates.deterministic_folds(numel(uniqueGroups),k, ...
        seeds.surrogate_fit(cfg,'generalized','cv_folds',[],[],[]));
    folds=groupFolds(groupIndex);
    for i=1:numel(uniqueGroups)
        assert(isscalar(unique(folds(groupIndex==i))), ...
            'surrogates:fit_generalized:CVGroupLeakage', ...
            'Material group %s lies in more than one CV fold.',uniqueGroups(i));
    end
    availability=logical(data.developmentOutputAvailabilityMask);
    minimumTraining=size(data.X_development_all,2)+1;
    for outputIndex=1:size(availability,2)
        outputFolds=folds(availability(:,outputIndex));
        validationCounts=accumarray(outputFolds,1,[k 1]);
        trainingCounts=numel(outputFolds)-validationCounts;
        assert(isequal(unique(outputFolds).',(1:k))&& ...
            all(validationCounts>=1)&&all(trainingCounts>=minimumTraining), ...
            'surrogates:fit_generalized:CVOutputFoldCoverage', ...
            ['The one global material-group assignment leaves output %d ' ...
             'without a nonempty validation fold or at least M+1 training ' ...
             'rows in every fold.'],outputIndex);
    end
end

function result=finalize_stage2(data,gate,cfg,roots)
    context=surrogates.generalized_fit_context(data,cfg);
    [gpRecords,gpModels,gpPaths]=collect_family('gp',data,cfg,roots);
    [pceRecords,pceModels,pcePaths]=collect_family('pce',data,cfg,roots);
    gpTerminal=all(~strcmp({gpRecords.executionStatus},'pending'));
    pceTerminal=all(~strcmp({pceRecords.executionStatus},'pending'));
    if ~(gpTerminal&&pceTerminal)
        decision=struct('schemaVersion','real_extended_stage2_gate_v2', ...
            'status','STAGE2_INCOMPLETE_RESUMABLE', ...
            'stage3Allowed',false, ...
            'sourceSnapshotID',context.snapshotID, ...
            'cohortDecision',context.cohortDecision, ...
            'missingProbeRunIDs',context.missingProbeRunIDs, ...
            'missingGPOutputs',{data.outputNames(strcmp( ...
                {gpRecords.executionStatus},'pending'))}, ...
            'missingPCEOutputs',{data.outputNames(strcmp( ...
                {pceRecords.executionStatus},'pending'))});
        utils.atomic_write_json(fullfile(roots.reports, ...
            'stage2_gate_decision.json'),decision,'AllowReplace',true);
        error('surrogates:fit_generalized:CanonicalTrainingIncomplete', ...
            ['Canonical generalized fitting is incomplete; partial ' ...
             'checkpoints and the factual gate report were preserved.']);
    end

    gp=build_ensemble('gp',gpRecords,gpModels,gpPaths,data,cfg);
    pce=build_ensemble('pce',pceRecords,pceModels,pcePaths,data,cfg);
    [gpArtifact,gpResolver]=publish_ensemble(gp,'gp',cfg,roots,data);
    [pceArtifact,pceResolver]=publish_ensemble(pce,'pce',cfg,roots,data);
    write_resolver(cfg.files.gp,'gpResolver',gpResolver);
    write_resolver(cfg.files.pce,'pceResolver',pceResolver);

    modelStatus=build_model_status(gpRecords,pceRecords,data);
    cvTable=build_cv_table(gpRecords,pceRecords,data);
    pceComplexity=build_pce_complexity(pceRecords,data);
    gpHyperparameters=build_gp_hyperparameters(gpRecords,gp,data,cfg);
    seedMetadata=build_model_seed_metadata( ...
        gpRecords,pceRecords,data,cfg);
    write_model_tables(modelStatus,cvTable,pceComplexity, ...
        gpHyperparameters,seedMetadata,roots);

    gpCompleted=all(strcmp({gpRecords.executionStatus},'completed'));
    pceCompleted=all(strcmp({pceRecords.executionStatus},'completed'));
    if ~gpCompleted
        stageStatus='STAGE2_INCOMPLETE_GP_TECHNICAL_FAILURE';
        stage3Allowed=false;
    elseif ~pceCompleted
        stageStatus='STAGE2_INCOMPLETE_PCE_TECHNICAL_FAILURE';
        stage3Allowed=false;
    else
        stageStatus='STAGE2_COMPLETE';
        stage3Allowed=true;
    end
    decision=struct( ...
        'schemaVersion','real_extended_stage2_gate_v2', ...
        'status',stageStatus,'stage3Allowed',stage3Allowed, ...
        'outputTrainingCounts',reshape(double( ...
            [data.outputTrainingEvidence.trainingCount]),1,[]), ...
        'stage1GateStatus',gate.status, ...
        'gpAllCompleted',gpCompleted,'pceAllCompleted',pceCompleted, ...
        'pceFailureDoesNotInvalidateGP',true, ...
        'heldoutUsedForModelSelection',false, ...
        'primarySurrogateFamily','gp', ...
        'posteriorCertification','supporting_validation_no_posterior', ...
        'claimScope',context.claimScope, ...
        'sourceSnapshotID',context.snapshotID, ...
        'cohortDecision',context.cohortDecision, ...
        'missingProbeRunIDs',context.missingProbeRunIDs, ...
        'internalHeldoutEvaluationOwnedBySeparateAction',true);
    utils.atomic_write_json(fullfile(roots.reports, ...
        'stage2_gate_decision.json'),decision,'AllowReplace',true);
    write_stage2_report(modelStatus,roots,cfg,data);
    result=struct('schemaVersion','real_extended_stage2_result_v2', ...
        'status',stageStatus,'gate',decision, ...
        'outputTrainingCounts',reshape(double( ...
            [data.outputTrainingEvidence.trainingCount]),1,[]), ...
        'gpArtifact',run_relative(gpArtifact,cfg.paths.runRoot), ...
        'pceArtifact',run_relative(pceArtifact,cfg.paths.runRoot), ...
        'internalHeldoutEvaluation','separate_consume_only_s02_action', ...
        'modelStatus',modelStatus);
    utils.atomic_write_json(fullfile(roots.reports,'stage2_result.json'), ...
        json_safe_result(result,roots,cfg),'AllowReplace',true);
    if ~strcmp(stageStatus,'STAGE2_COMPLETE')
        error('surrogates:fit_generalized:CanonicalTrainingIncomplete', ...
            ['Canonical generalized fitting did not complete for every GP ' ...
             'and PCE output; reports and terminal checkpoints were preserved.']);
    end
end

function [records,models,paths]=collect_family(family,data,cfg,roots)
%COLLECT_FAMILY The terminal checkpoint of every output of one family, for the current request.
%   A checkpoint is used when its stored request equals the request of the
%   current data, folds and settings (any retry attempt); among several
%   attempts the newest completed one is used (surrogates.select_generalized_attempt).
    n=numel(data.outputNames);
    records=repmat(pending_record(family),1,n);
    models=cell(1,n);paths=strings(1,n);
    if strcmp(family,'gp')
        familyRoot=roots.gpModels;
        pattern='gp_*.mat';
    else
        familyRoot=roots.pceModels;
        pattern='pce_selected_*.mat';
    end
    for j=1:n
        cohort=output_training_cohort(data,j,cfg);
        folder=fullfile(familyRoot,matlab.lang.makeValidName(data.outputNames{j}));
        if ~isfolder(folder),continue;end
        hits=dir(fullfile(folder,pattern));
        matches=cell(numel(hits),1);
        matchCount=0;
        for h=1:numel(hits)
            pathValue=fullfile(hits(h).folder,hits(h).name);
            try
                loaded=load(pathValue,'record','model');
                r=loaded.record;
                if strcmp(r.outputName,data.outputNames{j}) && ...
                        strcmp(r.scientificVersion, ...
                        cfg.realExtended.scientificVersion) && ...
                        checkpoint_matches_current_scope( ...
                        r,family,cohort.contract,cfg,data.outputNames{j},j)
                    matchCount=matchCount+1;
                    matches{matchCount}=struct('record',r, ...
                        'model',loaded.model,'path',pathValue);
                end
            catch
                % A corrupt checkpoint is never selected as a valid match.
            end
        end
        matches=matches(1:matchCount);
        if ~isempty(matches)
            matchRecords=cellfun(@(x)x.record,matches, ...
                'UniformOutput',false);
            matchRecords=[matchRecords{:}];
            selected=surrogates.select_generalized_attempt(matchRecords,family);
            matches=matches(selected);
        end
        assert(isempty(matches)||isscalar(matches), ...
            'surrogates:fit_generalized:AmbiguousCheckpoint', ...
            'Multiple current-policy %s checkpoints match output %s.', ...
            family,data.outputNames{j});
        if isscalar(matches)
            records(j)=orderfields(matches{1}.record,records(j));
            models{j}=matches{1}.model;
            paths(j)=string(matches{1}.path);
        end
    end
end

function attempt=retry_attempt_from_record(record,family)
    attempt=NaN;
    if strcmp(family,'gp') && isfield(record,'settings') && ...
            isstruct(record.settings) && isfield(record.settings,'retryAttempt')
        attempt=record.settings.retryAttempt;
    elseif strcmp(family,'pce') && isfield(record,'policy') && ...
            isstruct(record.policy) && isfield(record.policy,'retryAttempt')
        attempt=record.policy.retryAttempt;
    end
end

function same=checkpoint_matches_current_scope(record,family,contract,cfg, ...
        outputName,outputIndex)
%CHECKPOINT_MATCHES_CURRENT_SCOPE The checkpoint's request is the current one, at its retry attempt.
    try
        if strcmp(family,'gp')
            settings=surrogates.generalized_gp_policy(cfg,outputIndex);
            settings.retryAttempt=record.settings.retryAttempt;
            expected=surrogates.generalized_fit_request(cfg,'gp',outputName, ...
                settings,contract);
        else
            policy=surrogates.generalized_pce_policy(cfg);
            policy.retryAttempt=record.policy.retryAttempt;
            expected=surrogates.generalized_fit_request(cfg,'pce_selection', ...
                outputName,surrogates.generalized_pce_selection_settings( ...
                policy,record.candidateTable),contract);
        end
        same=isfield(record,'request')&&isequaln(record.request,expected);
        if same&&strcmp(record.executionStatus,'completed')&& ...
                isfield(record,'cv')&&isfield(record.cv,'foldAssignment')
            same=isequal(reshape(double(record.cv.foldAssignment),1,[]), ...
                reshape(double(contract.cvFoldAssignment),1,[]));
        end
    catch
        same=false;
    end
end

function ensemble=build_ensemble(family,records,models,paths,data,cfg)
    trainingCounts=[records.trainingCount];
    hasPartialDevelopment=~all(logical( ...
        data.developmentOutputAvailabilityMask),'all');
    ensemble=struct( ...
        'schemaVersion','real_extended_surrogate_ensemble_v4_development_scoped', ...
        'family',family, ...
        'route','real_extended', ...
        'scientificVersion',cfg.realExtended.scientificVersion, ...
        'models',{models},'records',{records}, ...
        'checkpointPaths',run_relative_paths(paths,cfg.paths.runRoot), ...
        'inputNames',{data.inputNames}, ...
        'outputNames',{data.outputNames}, ...
        'inputBounds',data.inputBounds, ...
        'outputTrainingCounts',trainingCounts, ...
        'partialOutputTrainingEnabled',hasPartialDevelopment, ...
        'outputImputationUsed',false, ...
        'posteriorCertification','supporting_validation_no_posterior');
end

function [artifact,resolver]=publish_ensemble(ensemble,family,cfg,roots,data)
    ensembleFolder=fullfile(roots.base,family,'ensembles');
    artifact=fullfile(ensembleFolder,sprintf('%s_ensemble.mat',family));
    variable=struct();variable.(family)=ensemble;
    utils.atomic_save_struct(artifact,variable,'-v7.3');
    context=surrogates.generalized_fit_context(data,cfg);
    resolver=struct( ...
        'schemaVersion','real_extended_surrogate_resolver_v4', ...
        'family',family,'artifactPath', ...
            run_relative(artifact,cfg.paths.runRoot), ...
        'sourceSnapshotID',context.snapshotID, ...
        'scientificVersion',cfg.realExtended.scientificVersion);
    latestPath=fullfile(roots.base,sprintf( ...
        '%s_surrogate_routeR_latest.json',family));
    utils.atomic_write_json(latestPath,resolver,'AllowReplace',true);
end

function write_resolver(pathValue,name,resolver)
    folder=fileparts(pathValue);if ~isfolder(folder),mkdir(folder);end
    temporary=utils.atomic_temporary_path(pathValue);
    cleanup=onCleanup(@()delete_if_present(temporary));
    payload=struct();payload.(name)=resolver;
    save(temporary,'-struct','payload','-v7');
    utils.atomic_move_replace(temporary,pathValue);
    clear cleanup
end

function delete_if_present(pathValue)
    if isfile(pathValue),delete(pathValue);end
end

function status=build_model_status(gpRecords,pceRecords,data)
    rows=cell(12,1);cursor=0;
    families={'gp','pce'};records={gpRecords,pceRecords};
    for f=1:2
        for j=1:6
            cursor=cursor+1;
            rows{cursor}=table(string(families{f}), ...
                string(data.outputNames{j}),j, ...
                string(records{f}(j).executionStatus), ...
                double(records{f}(j).trainingCount), ...
                retry_attempt_from_record(records{f}(j),families{f}), ...
                string(records{f}(j).failureIdentifier), ...
                string(records{f}(j).failureMessage), ...
                'VariableNames',{'Family','Output','OutputIndex', ...
                'ExecutionStatus','TrainingCount', ...
                'RetryAttempt','FailureIdentifier','FailureMessage'});
        end
    end
    status=vertcat(rows{:});
end

function tableOut=build_cv_table(gpRecords,pceRecords,data)
    rows=cell(12,1);cursor=0;
    for j=1:6
        r=gpRecords(j);
        if strcmp(r.executionStatus,'completed')
            values=[r.cv.RMSE r.cv.NRMSE r.cv.MAE r.cv.R2 ...
                max(r.cv.foldNRMSE) r.fitRuntimeSeconds];
        else
            values=nan(1,6);
        end
        cursor=cursor+1;
        rows{cursor}=table("gp",string(data.outputNames{j}),j, ...
            values(1),values(2),values(3),values(4),values(5),values(6), ...
            false,'VariableNames',{'Family','Output','OutputIndex','CV_RMSE', ...
            'CV_NRMSE','CV_MAE','CV_R2','MaxFoldNRMSE', ...
            'FitRuntimeSeconds','HeldoutUsedForSelection'});
        r=pceRecords(j);
        if strcmp(r.executionStatus,'completed')
            c=selected_candidate(r);
            values=[c.CVRMSE c.MeanCVNRMSE c.CVMAE c.CVR2 c.MaxFoldNRMSE ...
                c.FitRuntimeSeconds];
        else
            values=nan(1,6);
        end
        cursor=cursor+1;
        rows{cursor}=table("pce",string(data.outputNames{j}),j, ...
            values(1),values(2),values(3),values(4),values(5),values(6), ...
            false,'VariableNames',{'Family','Output','OutputIndex','CV_RMSE', ...
            'CV_NRMSE','CV_MAE','CV_R2','MaxFoldNRMSE', ...
            'FitRuntimeSeconds','HeldoutUsedForSelection'});
    end
    tableOut=vertcat(rows{:});
end

function tableOut=build_pce_complexity(records,data)
    rows=cell(6,1);
    for j=1:6
        r=records(j);
        if strcmp(r.executionStatus,'completed')
            c=selected_candidate(r);
            rows{j}=table(string(data.outputNames{j}), ...
                r.selectedDegree,r.selectedQNorm,c.FullTotalDegreeBasisSize, ...
                c.HyperbolicCandidateSize,c.ObservedCandidateSize, ...
                c.TrainingRowsPerCandidateTerm,c.ActiveTermCount, ...
                c.ActiveCandidateRatio,c.LOOError,c.MeanCVNRMSE, ...
                c.MaxFoldNRMSE,c.FoldActiveTermCountCV, ...
                c.ActiveBasisJaccardMean,c.ActiveBasisJaccardMinimum, ...
                r.trainingAdequacyMet, ...
                'VariableNames',{'Output','SelectedDegree','QNorm', ...
                'FullTotalDegreeBasisSize','HyperbolicCandidateSize', ...
                'ObservedCandidateSize','TrainingRowsPerCandidateTerm', ...
                'ActiveTermCount','ActiveCandidateRatio','LOOError', ...
                'TrainingCVNRMSE','MaxFoldNRMSE', ...
                'FoldActiveTermCountCV','ActiveBasisJaccardMean', ...
                'ActiveBasisJaccardMinimum','TrainingAdequacyMet'});
        else
            rows{j}=table(string(data.outputNames{j}),nan,nan,nan, ...
                nan,nan,nan,nan,nan,nan,nan,nan,nan,nan,nan,false, ...
                'VariableNames',{'Output','SelectedDegree','QNorm', ...
                'FullTotalDegreeBasisSize','HyperbolicCandidateSize', ...
                'ObservedCandidateSize','TrainingRowsPerCandidateTerm', ...
                'ActiveTermCount','ActiveCandidateRatio','LOOError', ...
                'TrainingCVNRMSE','MaxFoldNRMSE', ...
                'FoldActiveTermCountCV','ActiveBasisJaccardMean', ...
                'ActiveBasisJaccardMinimum','TrainingAdequacyMet'});
        end
    end
    tableOut=vertcat(rows{:});
end

function c=selected_candidate(record)
%SELECTED_CANDIDATE The candidate-table row of the selected degree and q-norm.
    hit=record.candidateTable.Degree==record.selectedDegree& ...
        record.candidateTable.QNorm==record.selectedQNorm;
    assert(nnz(hit)==1,'surrogates:fit_generalized:SelectedCandidate', ...
        'The PCE selection of output %s has %d candidates of its selected degree.', ...
        record.outputName,nnz(hit));
    c=record.candidateTable(hit,:);
end

function [seed,policy]=gp_full_fit_seed(record,outputIndex,cfg)
%GP_FULL_FIT_SEED Seed of a GP output's full fit and where it came from.
%   The recorded thesis seed when the fit policy carries one
%   (config/seeds/surrogate_fit_seeds.csv); the selected start of a
%   declared multi-start selection; otherwise the seed of the settings'
%   seed rule (seeds.surrogate_fit; NaN for an output without a fit).
    seed=NaN;policy="seed_rule_v1";
    if isfield(record.settings,'fullFitSeed')
        seed=double(record.settings.fullFitSeed);policy="thesis_seed_record_v1";
    elseif isfield(record.cv,'fullFitSelection')
        seed=double(record.cv.fullFitSelection.selectedSeed);
        policy="declared_multistart_selected_start_v1";
    elseif ~strcmp(record.executionStatus,'pending')
        seed=seeds.surrogate_fit(cfg,'generalized','gp',outputIndex,[],0);
    end
end

function [seed,policy]=pce_full_fit_seed(record,outputIndex,cfg)
%PCE_FULL_FIT_SEED Seed of the selected PCE candidate's full fit and where it came from.
%   The recorded thesis seed of that candidate
%   (config/seeds/surrogate_fit_seeds.csv), otherwise the seed of the
%   settings' seed rule (seeds.surrogate_fit); NaN for an output without a
%   fit.
    seed=NaN;policy="seed_rule_v1";
    if strcmp(record.executionStatus,'completed')
        [seed,source]=seeds.surrogate_fit(cfg,'generalized','pce',outputIndex, ...
            record.selectedDegree,0);
        if strcmp(source,'recorded'),policy="thesis_seed_record_v1";end
    end
end

function tableOut=build_gp_hyperparameters(records,gp,data,cfg)
    n=numel(records);theta=nan(n,numel(data.inputNames));
    processVariance=nan(n,1);
    Output=string(data.outputNames(:));OutputIndex=(1:n).';
    Kernel=strings(n,1);Trend=strings(n,1);
    CorrelationType=strings(n,1);Optimizer=strings(n,1);
    Nugget=nan(n,1);MasterSeed=repmat(double(cfg.seed),n,1);
    FullFitComponentSeed=nan(n,1);
    SeedPolicyVersion=repmat("seed_rule_v1",n,1);
    ComponentRoleLabel=strings(n,1);
    for j=1:n
        r=records(j);
        Kernel(j)=string(r.settings.kernel);Trend(j)=string(r.settings.trend);
        CorrelationType(j)=string(r.settings.correlationType);
        Optimizer(j)=string(r.settings.optimizer);Nugget(j)=r.settings.nugget;
        if strcmp(r.executionStatus,'completed')
            assert(numel(r.theta)==numel(data.inputNames), ...
                'surrogates:fit_generalized:ThetaShape', ...
                'Completed GP output %d has an unexpected ARD-theta shape.',j);
            theta(j,:)=reshape(double(r.theta),1,[]);
            assert(all(isfinite(theta(j,:)))&&all(theta(j,:)>0), ...
                'surrogates:fit_generalized:ThetaValue', ...
                'Completed GP output %d has unavailable/invalid ARD theta.',j);
            processVariance(j)=surrogates.gp_process_variance( ...
                gp.models{j},1);
            [FullFitComponentSeed(j),SeedPolicyVersion(j)]=gp_full_fit_seed(r,j,cfg);
        end
        ComponentRoleLabel(j)="canonical_generalized_gp_output_"+string(j);
    end
    tableOut=table(Output,OutputIndex,Kernel,Trend, ...
        CorrelationType,Optimizer,Nugget,MasterSeed,FullFitComponentSeed, ...
        ComponentRoleLabel,repmat("twister",n,1), ...
        SeedPolicyVersion,processVariance, ...
        'VariableNames',{'Output','OutputIndex','Kernel', ...
        'Trend','CorrelationType','Optimizer','Nugget','MasterSeed', ...
        'FullFitComponentSeed','ComponentRoleLabel','RNGAlgorithm', ...
        'SeedPolicyVersion','ProcessVariance_mbar2'});
    thetaNames=matlab.lang.makeValidName("Theta_"+string(data.inputNames));
    tableOut=[tableOut array2table(theta,'VariableNames',thetaNames)];
end

function tableOut=build_model_seed_metadata(gpRecords,pceRecords,data,cfg)
    n=numel(data.outputNames);rows=cell(2*n,1);cursor=0;
    for j=1:n
        cursor=cursor+1;r=gpRecords(j);
        [seed,seedPolicy]=gp_full_fit_seed(r,j,cfg);
        rows{cursor}=seed_row("gp",data.outputNames{j},j,cfg.seed, ...
            "canonical_generalized_gp_output_"+string(j),seed,seedPolicy);
        cursor=cursor+1;r=pceRecords(j);
        [seed,seedPolicy]=pce_full_fit_seed(r,j,cfg);
        rows{cursor}=seed_row("pce",data.outputNames{j},j,cfg.seed, ...
            "canonical_generalized_pce_output_"+string(j),seed,seedPolicy);
    end
    tableOut=vertcat(rows{:});
end

