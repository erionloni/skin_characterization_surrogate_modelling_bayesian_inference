function [data,gate]=load_and_validate_stage1(cfg)
    gatePath=fullfile(cfg.paths.stage01,'metadata','surrogates_gate.json');
    assert(isfile(gatePath),'surrogates:fit_generalized:MissingStage1Gate', ...
        ['The dataset''s cohort decision (%s) is missing; run the step ' ...
         '''dataset'' first.'],gatePath);
    gate=jsondecode(fileread(gatePath));
    % The cohort decision of the dataset step decides whether surrogates
    % may be fitted (an ambiguous cohort needs a review first).
    assert(strcmp(gate.status,'STAGE1_COMPLETE')&&logical(gate.stage2_allowed), ...
        'surrogates:fit_generalized:Stage1GateClosed', ...
        'The dataset''s cohort decision does not allow fitting: %s.',gate.status);
    fields={'X_train','Y_train','inputNames','outputNames', ...
        'inputBounds','trainCaseIDs','testCaseIDs','dataProvenance', ...
        'X_development_all','Y_development_all','developmentCaseIDsAll', ...
        'developmentMaterialGroupIdentities', ...
        'developmentSplitGroupIdentities', ...
        'developmentOutputAvailabilityMask','outputTrainingEvidence'};
    missing=setdiff(fields,who('-file',cfg.files.dataset),'stable');
    assert(isempty(missing),'surrogates:fit_generalized:DatasetSchema', ...
        'The dataset %s lacks %s; rerun the step ''dataset''.', ...
        cfg.files.dataset,strjoin(missing,', '));
    data=utils.load_plain_mat(cfg.files.dataset,fields{:});
    nInput=numel(cfg.paramNames);
    nOutput=numel(cfg.outputNames);
    assert(size(data.X_train,2)==nInput&& ...
        size(data.Y_train,2)==nOutput&& ...
        size(data.X_train,1)==size(data.Y_train,1)&& ...
        size(data.X_train,1)==numel(data.trainCaseIDs)&& ...
        ~isempty(data.testCaseIDs), ...
        'surrogates:fit_generalized:DatasetShape', ...
        ['The training matrices must follow the route contract and have matching ' ...
         'input, output and CaseID row counts.']);
    assert(size(data.X_development_all,2)==nInput&& ...
        size(data.Y_development_all,2)==nOutput&& ...
        size(data.X_development_all,1)==size(data.Y_development_all,1)&& ...
        size(data.X_development_all,1)==numel(data.developmentCaseIDsAll)&& ...
        isequal(size(data.developmentOutputAvailabilityMask), ...
            size(data.Y_development_all))&& ...
        numel(data.developmentMaterialGroupIdentities)== ...
            size(data.X_development_all,1)&& ...
        numel(data.developmentSplitGroupIdentities)== ...
            size(data.X_development_all,1)&& ...
        numel(data.outputTrainingEvidence)==nOutput, ...
        'surrogates:fit_generalized:OutputAwareDatasetShape', ...
        'Output-aware development matrices or evidence have invalid dimensions.');
    assert(isequal(data.inputNames,cfg.realExtended.learningInputNames)&& ...
        isequal(data.outputNames,cfg.realExtended.outputNames), ...
        'surrogates:fit_generalized:DatasetMapping', ...
        'The dataset orders its inputs or outputs differently from the route.');
    surrogates.generalized_fit_context(data,cfg);
    assert(all(isfinite(data.X_train),'all')&& ...
        all(isfinite(data.Y_train),'all')&& ...
        all(isfinite(data.X_development_all),'all')&& ...
        isequal(logical(data.developmentOutputAvailabilityMask), ...
            isfinite(data.Y_development_all)), ...
        'surrogates:fit_generalized:NonfiniteDataset', ...
        ['The development inputs must be finite, and a missing development ' ...
         'output must be NaN in Y_development_all and unmarked in the availability mask.']);
    assert(isempty(intersect(data.developmentCaseIDsAll,data.testCaseIDs)), ...
        'surrogates:fit_generalized:SplitLeakage', ...
        'Development and external-test CaseIDs overlap; rerun the step ''dataset''.');
end

