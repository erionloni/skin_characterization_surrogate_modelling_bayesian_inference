function [calibratedVariance,localShape]=calibrated_emulator_variance( ...
        rawUQLabVariance,processVariance,calibration)
%CALIBRATED_EMULATOR_VARIANCE The calibrated emulator variance of GP predictions (the frozen tempered-local formula).
%   [CALIBRATEDVARIANCE, LOCALSHAPE] = surrogates.calibrated_emulator_variance(
%   RAWUQLABVARIANCE, PROCESSVARIANCE, CALIBRATION) returns, per prediction
%   and output, tau^2 * h^gamma with the local shape h = raw UQLab
%   predictive variance / fitted process variance (PROCESSVARIANCE, one per
%   output), and tau^2 and gamma from the frozen calibration CALIBRATION;
%   variances in mbar^2.
%   Side effects: none.

    rawUQLabVariance=double(rawUQLabVariance);
    processVariance=reshape(double(processVariance),1,[]);
    assert(ismatrix(rawUQLabVariance)&&~isempty(rawUQLabVariance)&& ...
        size(rawUQLabVariance,2)==numel(processVariance)&& ...
        all(isfinite(rawUQLabVariance),'all')&& ...
        all(rawUQLabVariance>=0,'all')&& ...
        all(isfinite(processVariance))&&all(processVariance>0), ...
        'surrogates:calibrated_emulator_variance:RawVariance', ...
        'Raw and process variances must be finite and nonnegative/positive.');
    required={'shared_gamma','tau_squared_mbar2','variance_formula_version'};
    assert(isstruct(calibration)&&isscalar(calibration)&& ...
        all(isfield(calibration,required))&&strcmp( ...
        calibration.variance_formula_version,'tempered_local_diagonal_v1'), ...
        'surrogates:calibrated_emulator_variance:Calibration','Check failed: surrogates:calibrated_emulator_variance:Calibration.');
    gamma=double(calibration.shared_gamma);
    tauSquared=reshape(double(calibration.tau_squared_mbar2),1,[]);
    assert(isscalar(gamma)&&isfinite(gamma)&&gamma>=0&&gamma<=1&& ...
        numel(tauSquared)==numel(processVariance)&& ...
        all(isfinite(tauSquared))&&all(tauSquared>0), ...
        'surrogates:calibrated_emulator_variance:Parameters','Check failed: surrogates:calibrated_emulator_variance:Parameters.');

    localShape=rawUQLabVariance./processVariance;
    assert(all(isfinite(localShape),'all')&&all(localShape>=0,'all'), ...
        'surrogates:calibrated_emulator_variance:LocalShape','Check failed: surrogates:calibrated_emulator_variance:LocalShape.');
    calibratedVariance=tauSquared.*localShape.^gamma;
    assert(all(isfinite(calibratedVariance),'all')&& ...
        all(calibratedVariance>=0,'all'), ...
        'surrogates:calibrated_emulator_variance:Result','Check failed: surrogates:calibrated_emulator_variance:Result.');
end
