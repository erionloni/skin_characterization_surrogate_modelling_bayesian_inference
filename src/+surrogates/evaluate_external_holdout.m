function status=evaluate_external_holdout(cfg)
%EVALUATE_EXTERNAL_HOLDOUT Score the fitted surrogates on the external test cases.
%   STATUS = surrogates.evaluate_external_holdout(CFG) predicts the held-out
%   external cases of the dataset CFG.files.dataset with the GP
%   (CFG.files.gp: mean, raw UQLab variance and calibrated emulator
%   variance, surrogates.evaluate_canonical_gp) and the PCE (CFG.files.pce).
%   It writes into CFG.paths.surrogateAssessment the metrics per output
%   (gp_validation_metrics.csv with the calibrated variance,
%   gp_validation_metrics_raw_uqlab.csv, pce_validation_metrics.csv), one
%   row per case and output (validation_predictions.csv), the MAT file
%   CFG.files.validation (its tables as plain values,
%   utils.plain_mat_encode) and the status CFG.files.externalHoldoutStatus,
%   which STATUS returns. It reads held-out outcomes, so it runs only when
%   CFG.stage2.evaluateExternalHoldout is true, and it never trains a model.
%   Side effects: writes the files above.
%   Computation: seconds (UQLab predictions).

    assert(strcmp(cfg.dataMode,'real')&& ...
        logical(cfg.stage2.evaluateExternalHoldout), ...
        'surrogates:evaluate_external_holdout:Disabled', ...
        ['The external assessment reads held-out outcomes: request it ' ...
         'explicitly (step ''surrogate_assessment'' of the fixed route).']);
    saved=load(cfg.files.gp,'gp');gp=saved.gp;
    saved=load(cfg.files.pce,'pce');pce=saved.pce;
    required={'X_train','Y_train','X_validation','Y_validation','trainCaseIDs', ...
        'validationCaseIDs','validationSourceRows','inputNames','outputNames'};
    % The per-output training evidence of the dataset step names the
    % training cohorts that the calibration was fitted on.
    optional=intersect({'outputTrainingEvidence'},who('-file',cfg.files.dataset));
    fields=[required reshape(optional,1,[])];
    dataSet=utils.load_plain_mat(cfg.files.dataset,fields{:});
    nExternal=size(dataSet.X_validation,1);
    assert(all(isfield(dataSet,required))&&nExternal>=1&& ...
        size(dataSet.X_validation,2)==4&& ...
        isequal(size(dataSet.Y_validation),[nExternal 6])&& ...
        numel(unique(double(dataSet.validationCaseIDs)))==nExternal&& ...
        all(isfinite(dataSet.X_validation),'all')&& ...
        all(isfinite(dataSet.Y_validation),'all'), ...
        'surrogates:evaluate_external_holdout:Cohort', ...
        ['The dataset %s must hold the external cases with four finite inputs ' ...
         'and six finite outputs each; rerun the step ''dataset''.'], ...
        cfg.files.dataset);
    P=parameters.parameter_space(cfg);
    surrogates.validate_calibration_data_contract( ...
        cfg.emulatorErrorCalibration,dataSet,P.outputNames);
    gpPrediction=surrogates.evaluate_canonical_gp( ...
        gp,dataSet.X_validation,cfg);
    mGP=metrics_by_output(dataSet.Y_validation, ...
        gpPrediction.GPMean,gpPrediction.CalibratedEmulatorVariance, ...
        P.outputNames,'RelativeDenominatorTolerance',0,'RangeTolerance',0);
    mGPRaw=metrics_by_output(dataSet.Y_validation, ...
        gpPrediction.GPMean,gpPrediction.RawUQLabVariance,P.outputNames, ...
        'RelativeDenominatorTolerance',0,'RangeTolerance',0);
    [pceMean,~]=surrogates.evaluate(pce,dataSet.X_validation,'pce');
    predPCE=struct('mu',double(pceMean));
    mPCE=metrics_by_output(dataSet.Y_validation,predPCE.mu, ...
        nan(size(predPCE.mu)),P.outputNames, ...
        'RelativeDenominatorTolerance',0,'RangeTolerance',0);
    predictionTable=prediction_rows(dataSet,P,gpPrediction,predPCE);
    % Tables as plain values, format -v7: the file opens without MATLAB.
    utils.atomic_save_struct(cfg.files.validation,utils.plain_mat_encode(struct( ...
        'mGP',mGP,'mGPRawUQLab',mGPRaw,'mPCE',mPCE, ...
        'gpPrediction',gpPrediction,'predPCE',predPCE, ...
        'validationPredictionTable',predictionTable)),'-v7');
    root=cfg.paths.surrogateAssessment;
    utils.atomic_write_table(fullfile(root,'gp_validation_metrics.csv'),mGP);
    utils.atomic_write_table(fullfile(root, ...
        'gp_validation_metrics_raw_uqlab.csv'),mGPRaw);
    utils.atomic_write_table(fullfile(root,'pce_validation_metrics.csv'),mPCE);
    utils.atomic_write_table(fullfile(root,'validation_predictions.csv'), ...
        predictionTable);
    status=struct( ...
        'schema_version','external_holdout_evaluation_status_v2', ...
        'status','evaluated','methodological_role','external_holdout', ...
        'case_count',nExternal,'prediction_row_count',height(predictionTable), ...
        'observed_scalar_count',nnz(isfinite(dataSet.Y_validation)), ...
        'complete_six_output_case_count',nnz( ...
            all(isfinite(dataSet.Y_validation),2)), ...
        'per_output_observed_case_count',reshape(sum( ...
            isfinite(dataSet.Y_validation),1),1,[]), ...
        'metric_row_count',height(mGP)+height(mGPRaw)+height(mPCE), ...
        'external_outputs_loaded',true, ...
        'raw_uqlab_metrics_saved',true, ...
        'production_calibrated_metrics_saved',true);
    utils.atomic_write_json(cfg.files.externalHoldoutStatus,status, ...
        'AllowReplace',true);
end

function T=metrics_by_output(truth,meanPrediction,variance,outputNames,varargin)
    truth=double(truth);meanPrediction=double(meanPrediction);
    variance=double(variance);outputNames=reshape(string(outputNames),[],1);
    assert(isequal(size(truth),size(meanPrediction))&& ...
        isequal(size(truth),size(variance))&&size(truth,2)==numel(outputNames)&& ...
        all(isfinite(meanPrediction),'all')&&~any(isinf(truth),'all'), ...
        'surrogates:evaluate_external_holdout:MetricInputs', ...
        ['The held-out metrics need truth, mean and variance of one size with one ' ...
         'column per output, finite means and no infinite truth.']);
    parts=cell(numel(outputNames),1);
    for outputIndex=1:numel(outputNames)
        available=isfinite(truth(:,outputIndex));
        if any(available)
            one=surrogates.surrogate_quality_metrics( ...
                truth(available,outputIndex),meanPrediction(available,outputIndex), ...
                variance(available,outputIndex),outputNames(outputIndex),varargin{:});
        else
            one=surrogates.surrogate_quality_metrics(0,0,NaN, ...
                outputNames(outputIndex),varargin{:});
            numeric=varfun(@isnumeric,one,'OutputFormat','uniform');
            names=one.Properties.VariableNames(numeric);
            for name=string(names),one.(name)(:)=NaN;end
            one.ObservationCount(:)=0;one.RelativeMetricCount(:)=0;
            one.ProbabilisticMetricCount(:)=0;
            one.NRMSEUnavailableReason(:)="no_observed_external_values";
            one.RelativeMetricUnavailableReason(:)="no_observed_external_values";
            one.ProbabilisticMetricUnavailableReason(:)= ...
                "no_observed_external_values";
        end
        one.OutputIndex(:)=outputIndex;parts{outputIndex}=one;
    end
    T=vertcat(parts{:});
end

function T=prediction_rows(dataSet,P,gp,pce)
    n=size(dataSet.Y_validation,1);m=size(dataSet.Y_validation,2);
    expected=[n m];
    assert(isequal(size(gp.GPMean),expected)&& ...
        isequal(size(gp.RawUQLabVariance),expected)&& ...
        isequal(size(gp.CalibratedEmulatorVariance),expected)&& ...
        isequal(size(pce.mu),expected)&&all(isfinite(gp.GPMean),'all')&& ...
        all(isfinite(gp.RawUQLabVariance),'all')&& ...
        all(isfinite(gp.CalibratedEmulatorVariance),'all')&& ...
        all(isfinite(pce.mu),'all'), ...
        'surrogates:evaluate_external_holdout:PredictionShape', ...
        ['The surrogates must predict finite means and variances of size %d x %d for ' ...
         'the held-out cases.'],expected(1),expected(2));
    [caseIndex,outputIndex]=ndgrid(1:n,1:m);
    linear=sub2ind([n m],caseIndex(:),outputIndex(:));
    ValidationRow=caseIndex(:);
    SourceRow=double(dataSet.validationSourceRows(ValidationRow));
    CaseID=double(dataSet.validationCaseIDs(ValidationRow));
    OutputIndex=outputIndex(:);
    Output=reshape(string(P.outputNames(OutputIndex)),[],1);
    COMSOL=double(dataSet.Y_validation(linear));
    ObservationAvailable=isfinite(COMSOL);
    GPMean=double(gp.GPMean(linear));
    RawUQLabVariance=double(gp.RawUQLabVariance(linear));
    RawUQLabSD=sqrt(RawUQLabVariance);
    CalibratedEmulatorVariance=double( ...
        gp.CalibratedEmulatorVariance(linear));
    CalibratedEmulatorSD=sqrt(CalibratedEmulatorVariance);
    ProcessVariance=reshape(double(gp.ProcessVariance(OutputIndex)),[],1);
    LocalVarianceShapeH=double(gp.LocalVarianceShapeH(linear));
    PCEMean=double(pce.mu(linear));
    GPResidual=GPMean-COMSOL;PCEResidual=PCEMean-COMSOL;
    RawUQLabStandardizedResidual=GPResidual./max(RawUQLabSD,eps);
    CalibratedStandardizedResidual= ...
        GPResidual./max(CalibratedEmulatorSD,eps);
    GPAbsoluteError=abs(GPResidual);PCEAbsoluteError=abs(PCEResidual);
    [rawIncluded,rawNLPD,rawCRPS]=distribution_rows( ...
        COMSOL,GPMean,RawUQLabVariance,OutputIndex,m);
    [calibratedIncluded,calibratedNLPD,calibratedCRPS]= ...
        distribution_rows(COMSOL,GPMean,CalibratedEmulatorVariance, ...
        OutputIndex,m);
    UncertaintySemantics=repmat( ...
        "production_tempered_local_diagonal_emulator_variance", ...
        numel(linear),1);
    T=table(ValidationRow,SourceRow,CaseID,OutputIndex,Output, ...
        ObservationAvailable,COMSOL, ...
        GPMean,GPResidual,GPAbsoluteError, ...
        RawUQLabVariance,RawUQLabSD,RawUQLabStandardizedResidual, ...
        CalibratedEmulatorVariance,CalibratedEmulatorSD, ...
        CalibratedStandardizedResidual,ProcessVariance,LocalVarianceShapeH, ...
        rawIncluded(:,1),rawIncluded(:,2),rawIncluded(:,3),rawIncluded(:,4), ...
        calibratedIncluded(:,1),calibratedIncluded(:,2), ...
        calibratedIncluded(:,3),calibratedIncluded(:,4), ...
        rawNLPD,calibratedNLPD,rawCRPS,calibratedCRPS, ...
        UncertaintySemantics, ...
        PCEMean,PCEResidual,PCEAbsoluteError, ...
        'VariableNames',{'ValidationRow','SourceRow','CaseID','OutputIndex', ...
        'Output','ObservationAvailable','COMSOL','GPMean','GPResidual', ...
        'GPAbsoluteError', ...
        'RawUQLabVariance','RawUQLabSD', ...
        'RawUQLabStandardizedResidual','CalibratedEmulatorVariance', ...
        'CalibratedEmulatorSD','CalibratedStandardizedResidual', ...
        'ProcessVariance','LocalVarianceShapeH','RawIncluded50', ...
        'RawIncluded80','RawIncluded90','RawIncluded95', ...
        'CalibratedIncluded50','CalibratedIncluded80', ...
        'CalibratedIncluded90','CalibratedIncluded95','RawGaussianNLPD', ...
        'CalibratedGaussianNLPD','RawGaussianCRPS', ...
        'CalibratedGaussianCRPS', ...
        'UncertaintySemantics','PCEMean','PCEResidual','PCEAbsoluteError'});
end

function [included,nlpd,crps]=distribution_rows(truth,meanPrediction, ...
        variance,outputIndex,outputCount)
    n=numel(truth);included=false(n,4);nlpd=nan(n,1);crps=nan(n,1);
    for j=1:outputCount
        rows=outputIndex==j&isfinite(truth)&isfinite(meanPrediction)& ...
            isfinite(variance)&variance>=0;
        if ~any(rows),continue;end
        primitive=surrogates.surrogate_metric_primitives( ...
            truth(rows),meanPrediction(rows),variance(rows));
        included(rows,:)=primitive.IntervalIncluded;
        nlpd(rows)=primitive.GaussianPointNLPD;
        crps(rows)=primitive.GaussianPointCRPS;
    end
end
