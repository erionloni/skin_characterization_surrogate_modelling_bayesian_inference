function validate_calibration_data_contract(calibration,dataSet,outputOrder)
%VALIDATE_CALIBRATION_DATA_CONTRACT Check that the emulator-error calibration belongs to the dataset.
%   surrogates.validate_calibration_data_contract(CALIBRATION, DATASET,
%   OUTPUTORDER) refuses when the frozen calibration CALIBRATION
%   (surrogates.load_emulator_error_calibration) was fitted on other data
%   than the fixed dataset DATASET (variables of dataset.mat):
%   the development and external cases must be those the calibration lists,
%   in the same order, and every output must be observed on the
%   development cases that the calibration lists for it
%   (output_data_contract). OUTPUTORDER is the canonical output order (six
%   names). The external cases must have all six outputs.
%   Side effects: none.

    required={'Y_train','trainCaseIDs','validationCaseIDs','Y_validation'};
    missing=setdiff(required,fieldnames(dataSet),'stable');
    assert(isempty(missing), ...
        'surrogates:validate_calibration_data_contract:DatasetSchema', ...
        'The dataset lacks %s; rerun the step ''dataset''.',strjoin(missing,', '));
    development=reshape(double(dataSet.trainCaseIDs),[],1);
    external=reshape(double(dataSet.validationCaseIDs),[],1);
    yExternal=double(dataSet.Y_validation);
    assert(size(yExternal,1)==numel(external)&&size(yExternal,2)==6&& ...
        all(isfinite(yExternal),'all'), ...
        'surrogates:validate_calibration_data_contract:IncompleteExternalTest', ...
        'Every external-test case of the dataset must have six finite outputs.');
    calibrationOrder=cellstr(string(calibration.output_order(:))).';
    assert(isequal(calibrationOrder,cellstr(string(outputOrder(:))).'), ...
        'surrogates:validate_calibration_data_contract:OutputOrder', ...
        'The calibration lists the outputs as %s, the model as %s.', ...
        strjoin(calibrationOrder,', '),strjoin(cellstr(string(outputOrder(:))).',', '));
    calibrationDevelopment=reshape(double(calibration.development_case_ids),[],1);
    calibrationExternal=reshape(double( ...
        calibration.external_holdout_case_ids_excluded),[],1);
    assert(isequal(calibrationDevelopment,development)&& ...
        isequal(calibrationExternal,external), ...
        'surrogates:validate_calibration_data_contract:Roles', ...
        ['The calibration was fitted for %d development and %d external cases, ' ...
         'the dataset has %d and %d, or other CaseIDs: the calibration %s ' ...
         'belongs to another dataset.'],numel(calibrationDevelopment), ...
        numel(calibrationExternal),numel(development),numel(external), ...
        calibration_name(calibration));
    check_output_cases(calibration,development,double(dataSet.Y_train), ...
        'surrogates:validate_calibration_data_contract');
end

function check_output_cases(calibration,caseIDs,Y,prefix)
%CHECK_OUTPUT_CASES Every output observed on the development cases the calibration lists for it.
    contract=reshape(calibration.output_data_contract,[],1);
    [~,order]=sort(double([contract.output_index]));contract=contract(order);
    assert(numel(contract)==size(Y,2), ...
        [prefix ':OutputCases'], ...
        'The calibration %s lists %d outputs, the dataset has %d.', ...
        calibration_name(calibration),numel(contract),size(Y,2));
    for j=1:numel(contract)
        observed=reshape(double(caseIDs(isfinite(Y(:,j)))),[],1);
        listed=reshape(double(contract(j).development_case_ids),[],1);
        assert(isequal(observed,listed),[prefix ':OutputCases'], ...
            ['Output %s is observed on other development cases (%d) than those ' ...
             'the calibration %s was fitted on (%d).'], ...
            char(string(contract(j).output)),numel(observed), ...
            calibration_name(calibration),numel(listed));
    end
end

function name=calibration_name(calibration)
    name='';
    if isfield(calibration,'artifact_path')
        [~,stem,extension]=fileparts(char(string(calibration.artifact_path)));
        name=[stem extension];
    end
end
