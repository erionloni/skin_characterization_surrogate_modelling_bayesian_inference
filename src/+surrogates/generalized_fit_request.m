function request = generalized_fit_request(cfg, family, outputName, settings, trainingContract)
%GENERALIZED_FIT_REQUEST What one fit of the generalized refit computes.
%   REQUEST = surrogates.generalized_fit_request(CFG, FAMILY, OUTPUTNAME,
%   SETTINGS, TRAININGCONTRACT) describes one fit of surrogates.fit_generalized:
%   FAMILY 'gp' (one output's GP), 'pce_candidate' (one degree of its staged
%   PCE) or 'pce_selection' (the selected PCE), with the fit SETTINGS and the
%   output's training cohort (its cases, groups and cross-validation folds,
%   and its training inputs and responses: TRAININGCONTRACT, from
%   surrogates.fit_generalized), and the route's input names, bounds and
%   output order. A fit's checkpoint stores its request; a later call reuses
%   the checkpoint only for an equal request (isequaln).
%   Side effects: none.

    assert(isstruct(cfg)&&ischar(family)&&ischar(outputName)&& ...
        isstruct(settings)&&isstruct(trainingContract), ...
        'surrogates:generalized_fit_request:Arguments', ...
        'A fit request needs the configuration, family, output name, settings and training contract.');
    request = struct( ...
        'schemaVersion','real_extended_stage2_fit_request_v6', ...
        'route','real_extended', ...
        'scientificVersion',cfg.realExtended.scientificVersion, ...
        'dataScope',data_scope(trainingContract), ...
        'family',lower(family), ...
        'outputName',outputName, ...
        'inputNames',{cfg.realExtended.learningInputNames}, ...
        'inputBounds',double(cfg.realExtended.learningBounds), ...
        'outputOrder',{cfg.realExtended.outputNames}, ...
        'settings',settings);
end

function scope=data_scope(contract)
% One scalar output is bound only to its own observed cohort, its training
% data and the fold assignment its fit uses, so a change of another output's
% data does not invalidate its checkpoint.
    required={'outputIndex','outputName','trainingCount','trainingCaseIDs', ...
        'trainingMaterialGroupIdentities','trainingSplitGroupIdentities', ...
        'cvFoldAssignment','trainingX','trainingY','noImputation'};
    missing=setdiff(required,fieldnames(contract),'stable');
    assert(isempty(missing)&&logical(contract.noImputation), ...
        'surrogates:generalized_fit_request:OutputTrainingScope', ...
        'The output training contract lacks %s or allows imputation.', ...
        strjoin(missing,', '));
    scope=struct( ...
        'schemaVersion','real_extended_scalar_output_fit_scope_v3', ...
        'outputIndex',double(contract.outputIndex), ...
        'outputName',char(string(contract.outputName)), ...
        'trainingCount',double(contract.trainingCount), ...
        'trainingCaseIDs',reshape(double(contract.trainingCaseIDs),1,[]), ...
        'trainingMaterialGroupIdentities',{cellstr(string( ...
            contract.trainingMaterialGroupIdentities(:))).'}, ...
        'trainingSplitGroupIdentities',{cellstr(string( ...
            contract.trainingSplitGroupIdentities(:))).'}, ...
        'cvFoldAssignment',reshape(double(contract.cvFoldAssignment),1,[]), ...
        'trainingX',double(contract.trainingX), ...
        'trainingY',reshape(double(contract.trainingY),[],1), ...
        'noImputation',true);
end
