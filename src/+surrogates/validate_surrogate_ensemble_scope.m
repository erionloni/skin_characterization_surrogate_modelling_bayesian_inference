function validate_surrogate_ensemble_scope(model,dataSet,cfg,family)
%VALIDATE_SURROGATE_ENSEMBLE_SCOPE Check that a generalized GP or PCE ensemble belongs to the dataset.
%   surrogates.validate_surrogate_ensemble_scope(MODEL, DATASET, CFG, FAMILY)
%   refuses a saved generalized ensemble (FAMILY 'gp' or 'pce'; loaded with
%   surrogates.load_ensemble) that does not fit the route's input and output
%   contract (six scalar models, the seven inputs and six outputs in order,
%   the input bounds) or whose scalar models were fitted on other
%   development cases than those of the dataset DATASET (variables of
%   dataset.mat: developmentCaseIDsAll and
%   developmentOutputAvailabilityMask): every output's model lists the
%   development cases that observe that output. It fits and evaluates
%   nothing. Side effects: none.

    family=lower(strtrim(char(string(family))));
    assert(ismember(family,{'gp','pce'})&& ...
        isstruct(model)&&isscalar(model)&&isstruct(dataSet)&& ...
        isscalar(dataSet)&&isstruct(cfg)&&isscalar(cfg)&& ...
        strcmp(cfg.dataMode,'real_extended'), ...
        'surrogates:validate_surrogate_ensemble_scope:Input', ...
        'A scalar generalized GP/PCE model, dataset, and configuration are required.');
    requiredBase={'models','inputNames','outputNames','inputBounds','family'};
    assert(all(isfield(model,requiredBase))&&numel(model.models)==6&& ...
        strcmpi(char(string(model.family)),family)&& ...
        isequal(cellstr(string(model.inputNames(:))).', ...
            cellstr(string(cfg.realExtended.learningInputNames(:))).')&& ...
        isequal(cellstr(string(model.outputNames(:))).', ...
            cellstr(string(cfg.realExtended.outputNames(:))).')&& ...
        isequal(size(model.inputBounds),[7 2])&& ...
        max(abs(double(model.inputBounds)- ...
            double(cfg.realExtended.learningBounds)),[],'all')<=1e-12, ...
        'surrogates:validate_surrogate_ensemble_scope:ModelContract', ...
        ['The saved generalized %s ensemble does not have the route''s six ' ...
         'outputs, seven inputs and input bounds.'],upper(family));
    assert(all(isfield(dataSet,{'developmentCaseIDsAll', ...
        'developmentOutputAvailabilityMask'})), ...
        'surrogates:validate_surrogate_ensemble_scope:DatasetSchema', ...
        ['The dataset lacks developmentCaseIDsAll or ' ...
         'developmentOutputAvailabilityMask; rerun the step ''dataset''.']);
    caseIDs=reshape(double(dataSet.developmentCaseIDsAll),[],1);
    mask=logical(dataSet.developmentOutputAvailabilityMask);
    assert(isfield(model,'records')&&numel(model.records)==6&& ...
        isfield(model.records,'trainingCaseIDs')&& ...
        isequal(size(mask),[numel(caseIDs) 6]), ...
        'surrogates:validate_surrogate_ensemble_scope:DevelopmentBinding', ...
        'The saved generalized %s ensemble does not list the training cases of its outputs.', ...
        upper(family));
    for j=1:6
        fitted=reshape(double(model.records(j).trainingCaseIDs),[],1);
        assert(isequal(fitted,caseIDs(mask(:,j))), ...
            'surrogates:validate_surrogate_ensemble_scope:DevelopmentBinding', ...
            ['The saved generalized %s ensemble was fitted on other development ' ...
             'cases (output %d) than those of the dataset: refit the surrogates ' ...
             '(step ''surrogates'') or use the dataset they were fitted on.'], ...
            upper(family),j);
    end
end
