function result=surrogate_quality_calibration(oofResiduals, ...
        varianceFactorization,calibrationFolds,outputNames,cfg)
%SURROGATE_QUALITY_CALIBRATION Development-only emulator-error audit.
%   RESULT = SURROGATES.SURROGATE_QUALITY_CALIBRATION(R,F,FOLDS,OUT,CFG)
%   consumes the authoritative enriched OOF residual product R, variance
%   factorization F, and the declared CaseID-level calibration folds. It
%   performs no GP fit, prediction, fold generation, distance calculation,
%   input normalization, or variance factorization.
%
%   Residual is GPMean-Truth. The diagonal candidates are factual audit
%   models only:
%     raw_uqlab            v = GPVariance
%     constant_oof         v = s_j^2
%     full_local_shape     v = tau_j^2 h
%     tempered_local_shape v = tau_j^2 h^gamma, 0 <= gamma <= 1
%   where h=GPVariance/ProcessVariance. Gamma is shared over the six outputs
%   and output-specific scales use a CaseID-balanced Gaussian working
%   objective. No candidate is selected for production by this function.
%   The out-of-fold evidence covers the three audit kernels (Matern-3/2,
%   Matern-5/2, Gaussian).
%   Side effects: none (the random number generator's state is restored).

    [residuals,factorization,folds,caseIDs,inputNames,outputNames,settings]= ...
        validate_inputs(oofResiduals,varianceFactorization, ...
        calibrationFolds,outputNames,cfg);
    state=rng;restoreState=onCleanup(@()rng(state));

    phaseNames=strings(8,1);phaseSeconds=zeros(8,1);phase=0;
    timer=tic;
    phase=phase+1;phaseNames(phase)="authoritative_residual_product_validation";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));timer=tic;
    localShapeVerified=settings.localVarianceModelsEnabled&& ...
        all(factorization.FactorizationWithinTolerance)&& ...
        all(factorization.LocalShape>0)&&all(isfinite(factorization.LocalShape));
    definitions=candidate_definitions(settings,localShapeVerified);

    [crossfit,gammaSearch]=crossfit_candidates( ...
        residuals,folds,outputNames,settings,localShapeVerified);
    phase=phase+1;phaseNames(phase)="variance_candidate_crossfit";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));timer=tic;
    crossfitMetrics=crossfit_metric_table(crossfit,outputNames,settings);
    comparison=variance_model_comparison(crossfitMetrics,settings);
    phase=phase+1;phaseNames(phase)="crossfit_metrics_and_comparisons";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));timer=tic;
    repetitionScales=repetition_scale_table( ...
        residuals,outputNames,settings,localShapeVerified);
    bootstrap=cluster_bootstrap_table( ...
        residuals,crossfit,caseIDs,outputNames,settings,localShapeVerified);
    phase=phase+1;phaseNames(phase)="repetition_and_cluster_bootstrap";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));timer=tic;
    [localBins,localAssociations]=local_shape_diagnostics( ...
        crossfit,residuals,inputNames,settings);
    phase=phase+1;phaseNames(phase)="local_shape_diagnostics";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));timer=tic;
    [residualSummary,residualQuantiles,qq,pit,tail,pitEdges]= ...
        residual_distribution_tables(crossfit,settings);
    [pitBins,qqPoints]=surrogates.residual_distribution_summaries(qq,pit,pitEdges);
    phase=phase+1;phaseNames(phase)="residual_distribution";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));timer=tic;
    [correlationEmpirical,correlationShrunk,correlationBootstrap, ...
        jointComparison]=residual_correlation_tables( ...
        residuals,folds,gammaSearch,outputNames,settings,localShapeVerified);
    phase=phase+1;phaseNames(phase)="residual_correlation";
    phaseSeconds(phase)=toc(timer);fprintf('[surrogate audit] calibration %s: %.3f s\n', ...
        phaseNames(phase),phaseSeconds(phase));
    phaseTimings=table(phaseNames(1:phase),phaseSeconds(1:phase), ...
        'VariableNames',{'Phase','ElapsedSeconds'});

    schemaVersion='surrogate_quality_calibration_v1';
    if settings.outputSpecificFolds
        schemaVersion='surrogate_quality_calibration_output_specific_v1';
    end
    result=struct( ...
        'schemaVersion',schemaVersion, ...
        'settings',settings, ...
        'outputDevelopmentCaseCounts',reshape(double(settings.outputCaseCounts),[],1), ...
        'calibrationFolds',folds, ...
        'varianceCandidateDefinitions',definitions, ...
        'varianceFactorizationCheck',factorization, ...
        'developmentOOFResiduals',residuals, ...
        'crossfitPredictions',crossfit, ...
        'crossfitMetrics',crossfitMetrics, ...
        'varianceModelComparison',comparison, ...
        'gammaSearch',gammaSearch, ...
        'repetitionScaleEstimates',repetitionScales, ...
        'clusterBootstrapIntervals',bootstrap, ...
        'localShapeCalibrationBins',localBins, ...
        'localShapeAssociations',localAssociations, ...
        'standardizedResidualSummary',residualSummary, ...
        'standardizedResidualQuantiles',residualQuantiles, ...
        'qqData',qq, ...
        'pitData',pit, ...
        'pitBins',pitBins, ...
        'qqPoints',qqPoints, ...
        'tailProvenance',tail, ...
        'residualCorrelationEmpirical',correlationEmpirical, ...
        'residualCorrelationShrunk',correlationShrunk, ...
        'residualCorrelationBootstrap',correlationBootstrap, ...
        'diagonalVsCorrelatedScoreComparison',jointComparison, ...
        'phaseTimings',phaseTimings, ...
        'localShapeVerified',localShapeVerified, ...
        'externalHoldoutUsed',false, ...
        'automaticScientificSelectionPerformed',false);
end

function [R,F,folds,caseIDs,inputNames,outputNames,s]=validate_inputs( ...
        R,F,folds,outputNames,cfg)
    assert(istable(R)&&istable(F)&&istable(folds)&& ...
        isstruct(cfg)&&isscalar(cfg), ...
        'surrogates:surrogate_quality_calibration:InputTypes','Expected evidence tables and a scalar configuration.');
    requiredR={'Kernel','Repeat','Fold','CaseID','OutputIndex','Output', ...
        'Truth','GPMean','GPVariance','GPStd','Residual', ...
        'StandardizedResidual','ProcessVariance','LocalShape', ...
        'FactorizedVariance','FactorizationAbsoluteError', ...
        'FactorizationRelativeError','NearestDevelopmentTrainingDistance', ...
        'CalibrationFold'};
    requiredF={'Kernel','Repeat','Fold','CalibrationFold', ...
        'CaseID','OutputIndex','GPVariance', ...
        'ProcessVariance','LocalShape','FactorizedVariance', ...
        'FactorizationAbsoluteError','FactorizationRelativeError', ...
        'FactorizationTolerance','FactorizationWithinTolerance'};
    requiredFolds={'CaseID','CalibrationFold', ...
        'CalibrationFoldAssignmentSeed','MethodologicalRole'};
    assert(all(ismember(requiredR,R.Properties.VariableNames))&& ...
        all(ismember(requiredF,F.Properties.VariableNames))&& ...
        all(ismember(requiredFolds,folds.Properties.VariableNames)), ...
        'surrogates:surrogate_quality_calibration:TableSchema', ...
        'Residual, variance-factorization or calibration-fold columns are missing.');
    kernels=["Matern-3_2";"Matern-5_2";"Gaussian"];
    observed=unique(string(R.Kernel));observedF=unique(string(F.Kernel));
    assert(isequal(sort(observed),sort(kernels))&&isequal(sort(observedF),sort(kernels)), ...
        'surrogates:surrogate_quality_calibration:KernelSet', ...
        'Expected kernels [%s]; observed residual kernels [%s], factorization kernels [%s].', ...
        strjoin(kernels,', '),strjoin(observed,', '),strjoin(observedF,', '));
    outputSpecificFolds=ismember('OutputIndex',folds.Properties.VariableNames);
    if outputSpecificFolds,folds=sortrows(folds,{'OutputIndex','CaseID'}); ...
    else,folds=sortrows(folds,'CaseID');end
    caseIDs=unique(reshape(double(folds.CaseID),[],1),'stable');
    if isfield(cfg,'paramNames')
        inputNames=reshape(string(cfg.paramNames),[],1);
    else
        inputNames=reshape(["m3_f_RD" "m3_e_RD" ...
            "log10_k0_RD" "Thickness_RD"],[],1);
    end
    outputNames=reshape(string(outputNames),[],1);
    nCase=numel(caseIDs);nInput=numel(inputNames);nOutput=numel(outputNames);
    assert(nCase>=2&&numel(unique(caseIDs))==nCase&& ...
        nInput>=1&&nOutput==6&& ...
        all(isfinite(caseIDs))&&all( ...
        string(folds.MethodologicalRole)=="development_calibration_crossfit"), ...
        'surrogates:surrogate_quality_calibration:DevelopmentShape','Invalid development cohort, output count or methodological role.');
    R.Kernel=string(R.Kernel);R.Repeat=double(R.Repeat);R.Fold=double(R.Fold);
    R.CaseID=double(R.CaseID);R.OutputIndex=double(R.OutputIndex);
    R.Truth=double(R.Truth);R.GPMean=double(R.GPMean);
    R.GPVariance=double(R.GPVariance);
    F.Kernel=string(F.Kernel);F.Repeat=double(F.Repeat);F.Fold=double(F.Fold);
    F.CaseID=double(F.CaseID);F.OutputIndex=double(F.OutputIndex);
    outputCounts=zeros(nOutput,1);
    for outputIndex=1:nOutput
        outputCounts(outputIndex)=numel(unique(R.CaseID( ...
            R.OutputIndex==outputIndex)));
    end
    assert(all(outputCounts>=2)&& ...
        height(R)==numel(kernels)*5*sum(outputCounts)&&height(F)==height(R)&& ...
        isequal(sort(unique(R.Kernel)),sort(kernels))&& ...
        isequal(sort(unique(R.Repeat)),(1:5).')&& ...
        isequal(sort(unique(R.OutputIndex)),(1:nOutput).')&& ...
        isequal(sort(unique(R.CaseID)),sort(caseIDs))&& ...
        all(isfinite(R{:,{'Repeat','Fold','CaseID','OutputIndex','Truth', ...
            'GPMean','GPVariance'}}),'all')&&all(R.GPVariance>=0), ...
        'surrogates:surrogate_quality_calibration:OOFContract', ...
        ['Incomplete or invalid development OOF evidence for expected kernels [%s] ' ...
        '(observed [%s]): require all six outputs, five repeats, declared CaseIDs and finite values.'], ...
        strjoin(kernels,', '),strjoin(unique(R.Kernel),', '));
    for outputIndex=1:nOutput
        assert(all(string(R.Output(R.OutputIndex==outputIndex))==outputNames(outputIndex)), ...
            'surrogates:surrogate_quality_calibration:OutputOrder', ...
            'OOF output labels do not match the declared output order.');
    end
    key=string(R.Kernel)+"|"+string(R.Repeat)+"|"+string(R.CaseID)+ ...
        "|"+string(R.OutputIndex);
    assert(numel(unique(key))==height(R), ...
        'surrogates:surrogate_quality_calibration:OOFUniqueness','Duplicate kernel/repeat/case/output OOF rows.');
    for outputIndex=1:nOutput
        expectedIDs=sort(unique(R.CaseID(R.OutputIndex==outputIndex)));
        for kernelIndex=1:numel(kernels)
            for repeat=1:5
                observedIDs=sort(R.CaseID(R.OutputIndex==outputIndex& ...
                    R.Kernel==kernels(kernelIndex)&R.Repeat==repeat));
                assert(isequal(observedIDs,expectedIDs), ...
                    'surrogates:surrogate_quality_calibration:OutputCohortCompleteness','Output-specific OOF cohort is incomplete.');
            end
        end
    end
    for repeat=1:5
        one=R(R.Repeat==repeat,:);
        foldKey=string(one.Kernel)+"|"+string(one.OutputIndex)+"|"+ ...
            string(one.CaseID);
        [~,~,group]=unique(foldKey,'stable');
        foldValue=splitapply(@(v)numel(unique(v)),one.Fold,group);
        assert(all(foldValue==1), ...
            'surrogates:surrogate_quality_calibration:GroupedOutputFolds','A case/output has inconsistent CV folds.');
        uniqueOutputCase=unique(one(:,{'OutputIndex','CaseID'}),'rows');
        for c=1:height(uniqueOutputCase)
            rows=one.OutputIndex==uniqueOutputCase.OutputIndex(c)& ...
                one.CaseID==uniqueOutputCase.CaseID(c);
            values=unique(one.Fold(rows));
            assert(isscalar(values), ...
                'surrogates:surrogate_quality_calibration:PairedKernelFolds','Kernel comparisons do not share CV folds.');
        end
        repeatedCaseIDs=unique(one.CaseID);
        for caseIndex=1:numel(repeatedCaseIDs)
            values=unique(one.Fold(one.CaseID==repeatedCaseIDs(caseIndex)));
            assert(isscalar(values), ...
                'surrogates:surrogate_quality_calibration:GlobalCaseFolds', ...
                'A development CaseID has different CV folds by output.');
        end
    end
    if outputSpecificFolds
        foldKey=string(double(folds.OutputIndex))+"|"+ ...
            string(double(folds.CaseID));
        residualFoldKey=string(R.OutputIndex)+"|"+string(R.CaseID);
    else
        foldKey=string(double(folds.CaseID));
        residualFoldKey=string(R.CaseID);
    end
    assert(numel(unique(foldKey))==height(folds), ...
        'surrogates:surrogate_quality_calibration:CalibrationFoldUniqueness','Duplicate calibration-fold assignments.');
    if outputSpecificFolds
        repeatedCaseIDs=unique(double(folds.CaseID));
        for caseIndex=1:numel(repeatedCaseIDs)
            values=unique(double(folds.CalibrationFold( ...
                double(folds.CaseID)==repeatedCaseIDs(caseIndex))));
            assert(isscalar(values), ...
                'surrogates:surrogate_quality_calibration:GlobalCalibrationFolds', ...
                'A development CaseID has different calibration folds by output.');
        end
        if ismember('SplitGroup',folds.Properties.VariableNames)
            groups=unique(string(folds.SplitGroup));
            for groupIndex=1:numel(groups)
                values=unique(double(folds.CalibrationFold( ...
                    string(folds.SplitGroup)==groups(groupIndex))));
                assert(isscalar(values), ...
                    'surrogates:surrogate_quality_calibration:GroupedCalibrationFolds', ...
                    'A split group has different calibration folds.');
            end
        end
    end
    [foundFold,foldIndex]=ismember(residualFoldKey,foldKey);
    assert(all(foundFold)&&all(R.CalibrationFold== ...
        double(folds.CalibrationFold(foldIndex)))&& ...
        all(ismember(R.CaseID,caseIDs)), ...
        'surrogates:surrogate_quality_calibration:DevelopmentOnly','OOF CaseIDs or calibration folds do not match development evidence.');

    factorKey=F.Kernel+"|"+string(F.Repeat)+"|"+string(F.CaseID)+ ...
        "|"+string(F.OutputIndex);
    [foundFactor,factorIndex]=ismember(key,factorKey);
    assert(all(foundFactor)&&numel(unique(factorKey))==height(F)&& ...
        isequaln(R.GPVariance,double(F.GPVariance(factorIndex)))&& ...
        isequaln(R.ProcessVariance,double(F.ProcessVariance(factorIndex)))&& ...
        isequaln(R.LocalShape,double(F.LocalShape(factorIndex)))&& ...
        isequaln(R.FactorizedVariance,double(F.FactorizedVariance(factorIndex))), ...
        'surrogates:surrogate_quality_calibration:FactorizationJoin','Variance-factorization evidence does not match the OOF rows.');
    for inputIndex=1:numel(inputNames)
        name=matlab.lang.makeValidName(char("Normalized_"+inputNames(inputIndex)));
        assert(ismember(name,R.Properties.VariableNames)&& ...
            all(isfinite(R.(name)))&&all(R.(name)>=-1e-12&R.(name)<=1+1e-12), ...
            'surrogates:surrogate_quality_calibration:NormalizedInputs','Missing, nonfinite or out-of-bounds normalized inputs.');
    end
    assert(all(isfinite(R.NearestDevelopmentTrainingDistance))&& ...
        all(R.NearestDevelopmentTrainingDistance>=0), ...
        'surrogates:surrogate_quality_calibration:NearestTrainingDistance','Nearest-training distances must be finite and nonnegative.');
    s=resolved_settings(cfg,kernels);
    foldSeeds=unique(double(folds.CalibrationFoldAssignmentSeed));
    assert(~isempty(foldSeeds)&&all(isfinite(foldSeeds)), ...
        'surrogates:surrogate_quality_calibration:CalibrationFoldSeed','Invalid calibration-fold seed.');
    s.calibrationSeed=reshape(foldSeeds,1,[]);
    s.outputCaseCounts=reshape(outputCounts,1,[]);
    s.outputSpecificFolds=outputSpecificFolds;
end

function s=resolved_settings(cfg,kernels)
    % Every value comes from the settings (A.4, cfg.surrogateQualityAudit);
    % the literals below only fix the order of the fields.
    supplied=cfg.surrogateQualityAudit;
    needed={'calibrationFolds','gammaGrid','clusterBootstrapReplicates', ...
        'residualCorrelationBootstrapReplicates','localShapeBinCount', ...
        'residualTailCount','comparisonTolerance','varianceFactorizationTolerance'};
    lacking=needed(~isfield(supplied,needed));
    assert(isempty(lacking),'surrogates:surrogate_quality_calibration:Settings', ...
        'The audit configuration lacks %s (settings A.4).',strjoin(lacking,', '));
    bootstrapSeed=seeds.surrogate_audit(cfg,'calibration_cluster_bootstrap', ...
        struct(),struct('output',0,'repeat',0,'index',0));
    s=struct('schemaVersion','surrogate_quality_calibration_settings_v1', ...
        'kernels',{cellstr(kernels)},'calibrationFoldCount',5, ...
        'calibrationSeed',NaN,'gammaGrid',0:0.025:1, ...
        'bootstrapReplicates',500,'bootstrapSeed',bootstrapSeed, ...
        'correlationBootstrapReplicates',200, ...
        'localShapeBinCount',5,'tailCount',10, ...
        'comparisonTolerance',1e-12,'factorizationTolerance',1e-12, ...
        'varianceSafeguardSD',eps, ...
        'scaleEstimator', ...
            'CaseID-balanced mean of residual_squared/local_shape_power', ...
        'gammaObjective', ...
            'equal-output CaseID-balanced Gaussian working NLPD', ...
        'shrinkageMethod', ...
            'OAS on CaseID-aggregated standardized residual correlation toward identity', ...
        'correlationCaseAggregation', ...
            'mean standardized residual over five OOF repetitions per CaseID/output');
    aliases={'calibrationFoldCount','calibrationFoldCount'; ...
        'calibrationFolds','calibrationFoldCount'; ...
        'gammaGrid','gammaGrid'; ...
        'bootstrapReplicates','bootstrapReplicates'; ...
        'clusterBootstrapReplicates','bootstrapReplicates'; ...
        'bootstrapSeed','bootstrapSeed'; ...
        'correlationBootstrapReplicates','correlationBootstrapReplicates'; ...
        'residualCorrelationBootstrapReplicates', ...
            'correlationBootstrapReplicates'; ...
        'localVarianceModelsEnabled','localVarianceModelsEnabled'; ...
        'localShapeBinCount','localShapeBinCount'; ...
        'tailCount','tailCount';'residualTailCount','tailCount'; ...
        'comparisonTolerance','comparisonTolerance'; ...
        'factorizationTolerance','factorizationTolerance'; ...
        'varianceFactorizationTolerance','factorizationTolerance'};
    for i=1:size(aliases,1)
        if isfield(supplied,aliases{i,1}),s.(aliases{i,2})=supplied.(aliases{i,1});end
    end
    if ~isfield(s,'localVarianceModelsEnabled')
        s.localVarianceModelsEnabled=true;
    end
    s.localVarianceModelsEnabled=logical(s.localVarianceModelsEnabled);
    s.gammaGrid=reshape(double(s.gammaGrid),1,[]);
    assert(s.calibrationFoldCount>=2&&~isempty(s.gammaGrid)&& ...
        s.bootstrapReplicates>=1&&s.correlationBootstrapReplicates>=1&& ...
        s.localShapeBinCount>=2&&s.tailCount>=1&& ...
        isscalar(s.localVarianceModelsEnabled), ...
        'surrogates:surrogate_quality_calibration:Settings', ...
        ['The audit calibration needs at least two folds, a gamma grid, one bootstrap ' ...
         'and one correlation bootstrap replicate, two shape bins, one tail case and ' ...
         'one local-variance switch (settings A.4).']);
    s.correlationBootstrapSeeds=correlation_bootstrap_seeds(cfg,s);
end

function T=correlation_bootstrap_seeds(cfg,s)
%CORRELATION_BOOTSTRAP_SEEDS The seed of the correlation bootstrap of every kernel, fold and candidate.
%   The recorded seeds of the thesis audit, or those of the settings' rule
%   (seeds.surrogate_audit: the kernel's position, the candidate's position
%   in candidate_order and the fold).
    kernels=string(s.kernels);candidates=correlation_candidates();
    [k,f,c]=ndgrid(1:numel(kernels),1:s.calibrationFoldCount,1:numel(candidates));
    Kernel=kernels(k(:));CalibrationFold=f(:);Candidate=candidates(c(:));
    Seed=nan(numel(Kernel),1);
    for i=1:numel(Seed)
        Seed(i)=seeds.surrogate_audit(cfg,'residual_correlation_bootstrap', ...
            struct('Fold',CalibrationFold(i),'Kernel',Kernel(i), ...
            'Candidate',Candidate(i)),struct('output',k(i), ...
            'repeat',candidate_index(Candidate(i)),'index',CalibrationFold(i)));
    end
    T=table(Kernel,CalibrationFold,Candidate,Seed);
end

function candidates=correlation_candidates()
%CORRELATION_CANDIDATES The variance candidates whose residual correlation is estimated.
    candidates=["constant_oof";"full_local_shape";"tempered_local_shape"];
end

function T=candidate_definitions(s,localVerified)
    Candidate=["raw_uqlab";"constant_oof";"full_local_shape"; ...
        "tempered_local_shape"];
    Formula=["v=GPVariance";"v=s_j^2";"v=tau_j^2*h"; ...
        "v=tau_j^2*h^gamma"];
    GammaPolicy=["not_applicable";"gamma=0";"gamma=1"; ...
        "shared gamma on fixed grid [0,1]"];
    ScalePolicy=["none";s.scaleEstimator;s.scaleEstimator;s.scaleEstimator];
    CrossFitted=[false;true;true;true];
    LocalShapeRequired=[false;false;true;true];
    Available=[true;true;localVerified;localVerified];
    UnavailableReason=strings(4,1);
    if ~s.localVarianceModelsEnabled
        UnavailableReason(~Available)="local_variance_models_disabled_by_semantics_control";
    else
        UnavailableReason(~Available)= ...
            "process_variance_factorization_or_positive_local_shape_unverified";
    end
    ProductionModel=false(4,1);AutomaticSelection=false(4,1);
    T=table((1:4).',Candidate,Formula,GammaPolicy,ScalePolicy,CrossFitted, ...
        LocalShapeRequired,Available,UnavailableReason,ProductionModel, ...
        AutomaticSelection,'VariableNames',{'CandidateOrder','Candidate', ...
        'Formula','GammaPolicy','ScalePolicy','CrossFitted','LocalShapeRequired', ...
        'Available','UnavailableReason','ProductionModel','AutomaticSelection'});
end

function [C,G]=crossfit_candidates(R,~,outputNames,s,localVerified)
    kernels=string(s.kernels);candidates=candidate_order();
    parts=cell(numel(kernels)*s.calibrationFoldCount*numel(candidates),1);
    gammaParts=cell(numel(kernels)*s.calibrationFoldCount,1);
    cursor=0;gammaCursor=0;
    for k=1:numel(kernels)
        for fold=1:s.calibrationFoldCount
            train=R(R.Kernel==kernels(k)&R.CalibrationFold~=fold,:);
            validation=R(R.Kernel==kernels(k)&R.CalibrationFold==fold,:);
            trainingCounts=output_case_counts(train,numel(outputNames));
            validationCounts=output_case_counts(validation,numel(outputNames));
            [profile,gammaRows]=profile_gamma(train,outputNames,s,localVerified, ...
                kernels(k),fold,"calibration_crossfit");
            gammaCursor=gammaCursor+1;gammaParts{gammaCursor}=gammaRows;
            parameters=struct( ...
                'constant',profile.scaleGamma0, ...
                'full',profile.scaleGamma1, ...
                'tempered',profile.scaleSelected, ...
                'gamma',profile.selectedGamma);
            for candidateIndex=1:numel(candidates)
                cursor=cursor+1;
                parts{cursor}=candidate_prediction_rows(validation,fold, ...
                    trainingCounts,validationCounts,candidates(candidateIndex), ...
                    parameters,s,localVerified);
            end
        end
    end
    C=vertcat(parts{:});G=vertcat(gammaParts{:});
    C=sortrows(C,{'Kernel','CalibrationFold','CandidateOrder', ...
        'Repeat','CaseID','OutputIndex'});
end

function [profile,T]=profile_gamma(R,outputNames,s,available,kernel,fold,scope)
    nGamma=numel(s.gammaGrid);nOutput=numel(outputNames);
    scalesRaw=nan(nGamma,nOutput);scales=nan(nGamma,nOutput);
    objective=nan(nGamma,nOutput);equalObjective=nan(nGamma,1);
    for g=1:nGamma
        gamma=s.gammaGrid(g);
        if ~available&&gamma>0,continue;end
        for outputIndex=1:nOutput
            rows=R.OutputIndex==outputIndex;
            if gamma==0,shape=ones(sum(rows),1); ...
            else,shape=R.LocalShape(rows).^gamma;end
            ratio=R.Residual(rows).^2./shape;
            scalesRaw(g,outputIndex)=case_balanced_mean(ratio,R.CaseID(rows));
            scales(g,outputIndex)=max(scalesRaw(g,outputIndex),eps);
            variance=scales(g,outputIndex)*shape;
            objective(g,outputIndex)=case_balanced_mean( ...
                point_nlpd(R.Residual(rows),variance,s),R.CaseID(rows));
        end
        equalObjective(g)=mean(objective(g,:),'omitnan');
    end
    finite=find(isfinite(equalObjective));
    if ~available||isempty(finite),selectedIndex=1;selectedGamma=NaN;
    else
        [~,relative]=min(equalObjective(finite));selectedIndex=finite(relative);
        selectedGamma=s.gammaGrid(selectedIndex);
    end
    profile=struct('selectedGamma',selectedGamma, ...
        'scaleGamma0',reshape(scales(1,:),1,[]), ...
        'scaleGamma1',reshape(scales(end,:),1,[]), ...
        'scaleSelected',reshape(scales(selectedIndex,:),1,[]));
    rows=cell(nGamma*nOutput,1);cursor=0;
    for g=1:nGamma
