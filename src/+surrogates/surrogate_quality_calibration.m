                    'surrogates:surrogate_quality_calibration:ComparisonPair', ...
                    'The calibration comparison needs one row for each of the candidates %s and %s.', ...
                    string(candidates(left)),string(candidates(right)));
                for m=1:numel(metrics)
                    av=a.(metrics{m});bv=b.(metrics{m});
