        double(pearsonValue),double(spearmanValue), ...
        'VariableNames',{'Kernel','Candidate','OutputIndex','Predictor','Target', ...
        'RepeatedPredictionRowCount','CaseCount','PearsonCorrelation', ...
        'RankCorrelation'});
end

function [S,Q,QQ,PIT,Tail,edges]=residual_distribution_tables(C,s)
    keys=unique(C(:,{'Kernel','Candidate','OutputIndex'}),'rows','stable');
    summary=cell(height(keys),1);quantileParts=cell(height(keys),1);
    qqParts=cell(height(keys),1);pitParts=cell(height(keys),1);tailParts=cell(height(keys),1);
    probabilities=[.001 .01 .025 .05 .25 .5 .75 .95 .975 .99 .999];
    edges=(0:.05:1).';
    for i=1:height(keys)
        one=C(C.Kernel==keys.Kernel(i)&C.Candidate==keys.Candidate(i)& ...
            C.OutputIndex==keys.OutputIndex(i)&C.Available,:);
        primitive=surrogates.surrogate_metric_primitives( ...
            one.Truth,one.GPMean,one.CandidateVariance, ...
            'PredictiveSDSafeguard',s.varianceSafeguardSD);
        z=primitive.StandardizedResidual;
        center=primitive.MeanStandardizedResidual;
        sd=primitive.SDStandardizedResidual;
        m2=mean((z-center).^2);skew=NaN;kurt=NaN;
        if m2>0
            skew=mean((z-center).^3)/m2^(3/2);
            kurt=mean((z-center).^4)/m2^2-3;
        end
        summary{i}=table(keys.Kernel(i),keys.Candidate(i),keys.OutputIndex(i), ...
            numel(unique(one.CaseID)),height(one),center,sd, ...
            primitive.RMSStandardizedResidual,skew,kurt, ...
            primitive.CoveragePercent(1),primitive.CoveragePercent(2), ...
            primitive.CoveragePercent(3),primitive.CoveragePercent(4), ...
            primitive.GaussianNLPD,primitive.GaussianCRPS, ...
            'VariableNames',{'Kernel','Candidate','OutputIndex','CaseCount', ...
            'RepeatedPredictionRowCount','MeanStandardizedResidual', ...
            'SDStandardizedResidual','RMSStandardizedResidual','Skewness', ...
            'ExcessKurtosis','Coverage50_percent','Coverage80_percent', ...
            'Coverage90_percent','Coverage95_percent','GaussianNLPD','GaussianCRPS'});
        q=sort(z);values=arrayfun(@(p)linear_quantile(q,p),probabilities).';
        quantileParts{i}=table(repmat(keys.Kernel(i),numel(probabilities),1), ...
            repmat(keys.Candidate(i),numel(probabilities),1), ...
            repmat(keys.OutputIndex(i),numel(probabilities),1), ...
            probabilities.',values,'VariableNames',{'Kernel','Candidate', ...
            'OutputIndex','Probability','StandardizedResidualQuantile'});
        [sorted,order]=sort(z);n=numel(sorted);rank=(1:n).';
        theoretical=sqrt(2)*erfinv(2*((rank-.5)/n)-1);
        qqParts{i}=table(repmat(keys.Kernel(i),n,1), ...
            repmat(keys.Candidate(i),n,1),repmat(keys.OutputIndex(i),n,1), ...
            one.CaseID(order),one.Repeat(order),rank,theoretical,sorted, ...
            repmat(1/(5*numel(unique(one.CaseID))),n,1), ...
            'VariableNames',{'Kernel','Candidate','OutputIndex','CaseID', ...
            'Repeat','Rank','TheoreticalNormalQuantile', ...
            'ObservedStandardizedResidual','CaseBalancedRowWeight'});
        pit=0.5*(1+erf((-z)/sqrt(2)));
        bin=assign_bins(pit,edges);
        pitParts{i}=table(repmat(keys.Kernel(i),n,1), ...
            repmat(keys.Candidate(i),n,1),repmat(keys.OutputIndex(i),n,1), ...
            one.CaseID,one.Repeat,pit,bin, ...
            repmat(1/(5*numel(unique(one.CaseID))),n,1), ...
            'VariableNames',{'Kernel','Candidate','OutputIndex','CaseID', ...
            'Repeat','PIT','PITBin','CaseBalancedRowWeight'});
        [~,tailOrder]=sort(abs(z),'descend');tailOrder=tailOrder(1:min(s.tailCount,n));
        tailParts{i}=table(repmat(keys.Kernel(i),numel(tailOrder),1), ...
            repmat(keys.Candidate(i),numel(tailOrder),1), ...
            repmat(keys.OutputIndex(i),numel(tailOrder),1), ...
            (1:numel(tailOrder)).',one.CaseID(tailOrder),one.Repeat(tailOrder), ...
            one.Truth(tailOrder),one.GPMean(tailOrder),one.Residual(tailOrder), ...
            z(tailOrder),abs(z(tailOrder)), ...
            'VariableNames',{'Kernel','Candidate','OutputIndex','TailRank', ...
            'CaseID','Repeat','Truth','GPMean','Residual', ...
            'StandardizedResidual','AbsoluteStandardizedResidual'});
    end
    S=vertcat(summary{:});Q=vertcat(quantileParts{:});QQ=vertcat(qqParts{:});
    PIT=vertcat(pitParts{:});Tail=vertcat(tailParts{:});
    PIT.PITBinCount=zeros(height(PIT),1);PIT.PITBinFraction=nan(height(PIT),1);
    if ~isempty(PIT)
        groupKey=PIT.Kernel+"|"+PIT.Candidate+"|"+string(PIT.OutputIndex)+ ...
            "|"+string(PIT.PITBin);
        [~,~,group]=unique(groupKey,'stable');
        parentKey=PIT.Kernel+"|"+PIT.Candidate+"|"+string(PIT.OutputIndex);
        for i=1:max(group)
            rows=group==i;count=sum(rows);denominator=sum(parentKey==parentKey(find(rows,1)));
            PIT.PITBinCount(rows)=count;PIT.PITBinFraction(rows)=count/denominator;
        end
    end
end

function [E,S,B,J]=residual_correlation_tables(R,~,G,outputNames,s,available)
    kernels=string(s.kernels);candidates=correlation_candidates();
    empiricalParts=cell(0,1);shrunkParts=cell(0,1);bootstrapParts=cell(0,1);
    scoreParts=cell(0,1);
    for k=1:numel(kernels)
        for fold=1:s.calibrationFoldCount
            train=R(R.Kernel==kernels(k)&R.CalibrationFold~=fold,:);
            validation=R(R.Kernel==kernels(k)&R.CalibrationFold==fold,:);
            parameters=parameters_from_gamma(G,kernels(k),fold,outputNames);
            for c=1:numel(candidates)
                if ~available&&c>1,continue;end
                [trainZ,ids]=case_aggregated_z(train,candidates(c),parameters,s);
                [empirical,shrunk,lambda,valid,reason]=oas_correlation(trainZ);
                empiricalParts{end+1}=matrix_rows(empirical,kernels(k),fold, ...
                    candidates(c),outputNames,NaN,valid,reason,numel(ids)); %#ok<AGROW>
                shrunkParts{end+1}=matrix_rows(shrunk,kernels(k),fold, ...
                    candidates(c),outputNames,lambda,valid,reason,numel(ids)); %#ok<AGROW>
                bootstrapParts{end+1}=correlation_bootstrap_rows(trainZ,ids, ...
                    kernels(k),fold,candidates(c),outputNames,s); %#ok<AGROW>
                scoreParts{end+1}=joint_score_row(validation,empirical,shrunk, ...
                    lambda,valid,reason,kernels(k),fold,candidates(c),parameters,s); ...
                    %#ok<AGROW>
            end
        end
    end
    E=vertcat(empiricalParts{:});S=vertcat(shrunkParts{:});
    B=vertcat(bootstrapParts{:});J=vertcat(scoreParts{:});
    groupKey=J.Kernel+"|"+J.Candidate;[~,~,group]=unique(groupKey,'stable');
    J.NegativeDifferenceCount=zeros(height(J),1);J.ZeroDifferenceCount=zeros(height(J),1);
    J.PositiveDifferenceCount=zeros(height(J),1);J.PairCount=zeros(height(J),1);
    for i=1:max(group)
        rows=group==i;signs=J.DifferenceSign(rows);finite=isfinite(signs);
        J.NegativeDifferenceCount(rows)=sum(signs(finite)<0);
        J.ZeroDifferenceCount(rows)=sum(signs(finite)==0);
        J.PositiveDifferenceCount(rows)=sum(signs(finite)>0);
        J.PairCount(rows)=sum(finite);
    end
end

function parameters=parameters_from_gamma(G,kernel,fold,outputNames)
    one=G(G.Kernel==kernel&G.CalibrationFold==fold,:);n=numel(outputNames);
    parameters=struct('constant',nan(1,n),'full',nan(1,n), ...
        'tempered',nan(1,n),'gamma',NaN);
    for outputIndex=1:n
        rows=one.OutputIndex==outputIndex;
        parameters.constant(outputIndex)=one.ScaleUsed(rows&one.Gamma==0);
        parameters.full(outputIndex)=one.ScaleUsed(rows&one.Gamma==1);
        selected=rows&one.SelectedTemperedGamma;
        parameters.tempered(outputIndex)=one.ScaleUsed(selected);
        if any(selected),parameters.gamma=one.Gamma(find(selected,1));end
    end
end

function [Z,caseIDs]=case_aggregated_z(R,candidate,parameters,s)
    variance=candidate_variance(R,candidate,parameters);
    primitive=surrogates.surrogate_metric_primitives( ...
        R.Truth,R.GPMean,variance, ...
        'PredictiveSDSafeguard',s.varianceSafeguardSD);
    z=primitive.StandardizedResidual;
    caseIDs=unique(R.CaseID,'stable');Z=nan(numel(caseIDs),6);
    for i=1:numel(caseIDs)
        for outputIndex=1:6
            rows=R.CaseID==caseIDs(i)&R.OutputIndex==outputIndex;
            Z(i,outputIndex)=mean(z(rows));
        end
    end
    complete=all(isfinite(Z),2);
    Z=Z(complete,:);caseIDs=caseIDs(complete);
end

function variance=candidate_variance(R,candidate,p)
    index=R.OutputIndex;
    switch candidate
        case "constant_oof",variance=p.constant(index).';
        case "full_local_shape",variance=p.full(index).'.*R.LocalShape;
        case "tempered_local_shape"
            variance=p.tempered(index).'.*R.LocalShape.^p.gamma;
        otherwise
            error('surrogates:surrogate_quality_calibration:CorrelationCandidate', ...
                'Unknown residual-correlation candidate: %s',candidate);
    end
end

function [empirical,shrunk,lambda,valid,reason]=oas_correlation(Z)
    valid=all(isfinite(Z),'all')&&size(Z,1)>size(Z,2);reason="";
    if ~valid
        empirical=nan(6);shrunk=nan(6);lambda=NaN;
        reason="insufficient_complete_six_output_overlap";return
    end
    centered=Z-mean(Z,1);scale=sqrt(mean(centered.^2,1));
    if any(scale<=eps)
        empirical=nan(6);shrunk=nan(6);lambda=NaN;valid=false;
        reason="zero_case_level_standardized_residual_scale";return
    end
    standardized=centered./scale;empirical=(standardized.'*standardized)/size(Z,1);
    empirical=(empirical+empirical.')/2;empirical(1:7:end)=1;
    p=size(empirical,1);n=size(Z,1);traceS=trace(empirical);
    traceS2=sum(empirical.^2,'all');
    numerator=(1-2/p)*traceS2+traceS^2;
    denominator=(n+1-2/p)*(traceS2-traceS^2/p);
    if denominator<=0,lambda=1;else,lambda=min(1,max(0,numerator/denominator));end
    shrunk=(1-lambda)*empirical+lambda*eye(p);shrunk=(shrunk+shrunk.')/2;
    shrunk(1:p+1:end)=1;[~,flag]=chol(shrunk,'lower');valid=flag==0;
    if ~valid,reason="oas_shrunk_correlation_not_positive_definite";
    else
        assert(max(abs(empirical-empirical.'),[],'all')<1e-12&& ...
            max(abs(diag(empirical)-1))<1e-12&& ...
            max(abs(shrunk-shrunk.'),[],'all')<1e-12&& ...
            max(abs(diag(shrunk)-1))<1e-12, ...
            'surrogates:surrogate_quality_calibration:CorrelationMatrixValidity', ...
            'Internal error: a correlation matrix is not symmetric with a unit diagonal.');
    end
end

function T=matrix_rows(M,kernel,fold,candidate,outputNames,lambda,valid,reason, ...
        completeOverlapCount)
    [i,j]=ndgrid(1:6,1:6);n=36;
    positiveDefinite=false;minimumEigenvalue=NaN;
    if all(isfinite(M),'all')
        minimumEigenvalue=min(eig((M+M.')/2));
        [~,flag]=chol((M+M.')/2,'lower');positiveDefinite=flag==0;
    end
    T=table(repmat(string(kernel),n,1),repmat(double(fold),n,1), ...
        repmat(string(candidate),n,1),i(:),outputNames(i(:)),j(:), ...
        outputNames(j(:)),M(:),repmat(double(lambda),n,1), ...
        repmat(logical(valid),n,1),repmat(logical(positiveDefinite),n,1), ...
        repmat(double(minimumEigenvalue),n,1),repmat(string(reason),n,1), ...
        repmat(double(completeOverlapCount),n,1), ...
        'VariableNames',{'Kernel','CalibrationFold','Candidate','OutputIndex1', ...
        'Output1','OutputIndex2','Output2','Correlation','ShrinkageIntensity', ...
        'MatrixValid','MatrixPositiveDefinite','MinimumEigenvalue', ...
        'UnavailableReason','CompleteSixOutputOverlapCaseCount'});
end

function T=correlation_bootstrap_rows(Z,caseIDs,kernel,fold,candidate,outputNames,s)
    n=size(Z,1);nB=s.correlationBootstrapReplicates;
    empirical=nan(nB,6,6);shrunk=nan(nB,6,6);lambda=nan(nB,1);
    recorded=s.correlationBootstrapSeeds;
    seed=recorded.Seed(recorded.Kernel==string(kernel)& ...
        recorded.CalibrationFold==fold&recorded.Candidate==string(candidate));
    rng(seed,'twister'); % CaseIDs are retained as the cluster unit.
    if n>0
        for b=1:nB
            index=randi(n,n,1);[e,r,l,valid]=oas_correlation(Z(index,:));
            if valid,empirical(b,:,:)=e;shrunk(b,:,:)=r;lambda(b)=l;end
        end
    end
    parts=cell(36,1);cursor=0;
    for i=1:6
        for j=1:6
            cursor=cursor+1;e=sort(empirical(:,i,j));e=e(isfinite(e));
            r=sort(shrunk(:,i,j));r=r(isfinite(r));
            parts{cursor}=table(string(kernel),double(fold),string(candidate), ...
                i,outputNames(i),j,outputNames(j),double(seed),double(nB), ...
                numel(caseIDs),mean_or_nan(e),linear_quantile(e,.025), ...
                linear_quantile(e,.975),mean_or_nan(r),linear_quantile(r,.025), ...
                linear_quantile(r,.975),mean(lambda,'omitnan'), ...
                'VariableNames',{'Kernel','CalibrationFold','Candidate', ...
                'OutputIndex1','Output1','OutputIndex2','Output2','BootstrapSeed', ...
                'RequestedBootstrapReplicates','TrainingCaseCount', ...
                'EmpiricalMean','EmpiricalQ025','EmpiricalQ975','ShrunkMean', ...
                'ShrunkQ025','ShrunkQ975','MeanShrinkageIntensity'});
        end
    end
    T=vertcat(parts{:});
end

function row=joint_score_row(R,empirical,correlation,lambda,valid,reason, ...
        kernel,fold,candidate,p,s)
    variance=candidate_variance(R,candidate,p);
    candidateIDs=unique(R.CaseID,'stable');
    diagonalLoss=zeros(0,1);correlatedLoss=zeros(0,1);caseIDs=zeros(0,1);
    repeatedVectorCount=0;
    for caseIndex=1:numel(candidateIDs)
        perRepeatDiagonal=nan(5,1);perRepeatCorrelated=nan(5,1);
        for repeat=1:5
            rows=R.CaseID==candidateIDs(caseIndex)&R.Repeat==repeat;
            one=R(rows,:);v=variance(rows);
            if height(one)~=6||~isequal(sort(unique(one.OutputIndex)),(1:6).')
                continue
            end
            [~,order]=sort(one.OutputIndex);one=one(order,:);
            v=v(order);
            primitive=surrogates.surrogate_metric_primitives( ...
                one.Truth,one.GPMean,v, ...
                'PredictiveSDSafeguard',s.varianceSafeguardSD);
            sd=primitive.PredictiveStdSafe;z=primitive.StandardizedResidual;
            perRepeatDiagonal(repeat)=sum(primitive.GaussianPointNLPD);
            if valid
                L=chol(correlation,'lower');quadratic=sum((L\z).^2);
                perRepeatCorrelated(repeat)=0.5*(6*log(2*pi)+ ...
                    2*sum(log(sd))+2*sum(log(diag(L)))+quadratic);
            end
        end
        if all(isfinite(perRepeatDiagonal))
            caseIDs(end+1,1)=candidateIDs(caseIndex); %#ok<AGROW>
            diagonalLoss(end+1,1)=mean(perRepeatDiagonal); %#ok<AGROW>
            correlatedLoss(end+1,1)=mean(perRepeatCorrelated,'omitnan'); %#ok<AGROW>
            repeatedVectorCount=repeatedVectorCount+5;
        end
    end
    diagonal=mean(diagonalLoss,'omitnan');
    correlated=mean(correlatedLoss,'omitnan');
    if isempty(caseIDs)
        reason="no_complete_six_output_validation_overlap";
    end
    [difference,tolerance,signValue]=difference_record(correlated,diagonal, ...
        s.comparisonTolerance);
    empiricalMinimum=NaN;shrunkMinimum=NaN;
    if all(isfinite(empirical),'all')
        empiricalMinimum=min(eig((empirical+empirical.')/2));
    end
    if all(isfinite(correlation),'all')
        shrunkMinimum=min(eig((correlation+correlation.')/2));
    end
    row=table(string(kernel),double(fold),string(candidate),numel(caseIDs), ...
        repeatedVectorCount,double(lambda),logical(valid),string(reason), ...
        diagonal,correlated,difference,tolerance,signValue, ...
        empiricalMinimum,shrunkMinimum, ...
        'VariableNames',{'Kernel','CalibrationFold','Candidate', ...
        'ValidationCaseCount','RepeatedVectorCount','ShrinkageIntensity', ...
        'CorrelationValid','UnavailableReason','DiagonalJointGaussianNLPD', ...
        'CorrelatedJointGaussianNLPD','CorrelatedMinusDiagonal', ...
        'NumericTieTolerance','DifferenceSign','EmpiricalMinimumEigenvalue', ...
        'ShrunkMinimumEigenvalue'});
end

