function value=case_balanced_mean(values,caseIDs)
    [~,~,group]=unique(caseIDs);valid=isfinite(values);
    count=accumarray(group(valid),1,[max(group) 1],@sum,0);
    total=accumarray(group(valid),values(valid),[max(group) 1],@sum,0);
    means=nan(max(group),1);means(count>0)=total(count>0)./count(count>0);
    value=mean(means,'omitnan');
end

