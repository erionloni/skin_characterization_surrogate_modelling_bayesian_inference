        repmat(string(candidate),n,1), ...
        repmat(candidate_index(candidate),n,1),R.Truth,R.GPMean,R.Residual, ...
        R.GPVariance,R.ProcessVariance,R.LocalShape, ...
        repmat(double(gamma),n,1),scale,variance,sd,z,inc50,inc80,inc90,inc95, ...
        nlpd,crps,repmat(logical(available),n,1),repmat(string(reason),n,1), ...
        reshape(double(trainingCounts(outputIndex)),[],1), ...
