function [difference,tolerance,signValue]=difference_record(a,b,baseTolerance)
    if ~isfinite(a)||~isfinite(b)
        difference=NaN;tolerance=NaN;signValue=NaN;return
    end
    difference=a-b;tolerance=baseTolerance*max([1 abs(a) abs(b)]);
    signValue=double(difference>tolerance)-double(difference<-tolerance);
end

function edges=quantile_edges(values,nBin)
    sorted=sort(values(isfinite(values)));edges=nan(nBin+1,1);
    for i=0:nBin,edges(i+1)=linear_quantile(sorted,i/nBin);end
    edges(1)=-inf;edges(end)=inf;
end

function bin=assign_bins(values,edges)
    bin=zeros(numel(values),1);
    for i=1:numel(edges)-1
        if i==1,rows=values>=edges(i)&values<=edges(i+1);
        else,rows=values>edges(i)&values<=edges(i+1);end
        bin(rows)=i;
    end
    bin(bin==0)=numel(edges)-1;
end

function value=pearson(a,b)
    valid=isfinite(a)&isfinite(b);a=a(valid);b=b(valid);
    if numel(a)<2||std(a)==0||std(b)==0,value=NaN;return;end
    matrix=corrcoef(a,b);value=matrix(1,2);
end

function value=spearman(a,b)
    value=pearson(average_ranks(a),average_ranks(b));
end

function ranks=average_ranks(values)
    values=double(values(:));ranks=nan(size(values));valid=isfinite(values);
    [sorted,order]=sort(values(valid));base=find(valid);i=1;
    while i<=numel(sorted)
        j=i;while j<numel(sorted)&&sorted(j+1)==sorted(i),j=j+1;end
        ranks(base(order(i:j)))=(i+j)/2;i=j+1;
    end
end

function value=linear_quantile(sorted,probability)
    sorted=sort(double(sorted(isfinite(sorted))));
    if isempty(sorted),value=NaN;return;end
    if isscalar(sorted),value=sorted;return;end
    position=1+(numel(sorted)-1)*probability;lower=floor(position);upper=ceil(position);
    fraction=position-lower;value=sorted(lower)+fraction*(sorted(upper)-sorted(lower));
end

function value=mean_or_nan(values)
    values=values(isfinite(values));if isempty(values),value=NaN;else,value=mean(values);end
end

function T=vertcat_parts(parts)
    if isempty(parts),T=table();else,T=vertcat(parts{:});end
end

