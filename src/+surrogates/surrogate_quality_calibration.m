function scores=case_candidate_scores(C,kernel,outputIndex,candidates,caseIDs,names)
    scores=cell(numel(names),1);
    for metric=1:numel(names)
        matrix=nan(numel(caseIDs),numel(candidates));
        for c=1:numel(candidates)
            one=C(C.Kernel==kernel&C.Candidate==candidates(c)&C.Available,:);
            if isempty(one),continue;end
            for caseIndex=1:numel(caseIDs)
                rows=one.CaseID==caseIDs(caseIndex);
                if outputIndex>0
                    rows=rows&one.OutputIndex==outputIndex;
                    values=one.(names(metric))(rows);
                    matrix(caseIndex,c)=mean(values,'omitnan');
                else
                    values=nan(max(one.OutputIndex),1);
                    for o=1:numel(values)
                        values(o)=mean(one.(names(metric))(rows&one.OutputIndex==o),'omitnan');
                    end
                    matrix(caseIndex,c)=mean(values,'omitnan');
                end
            end
        end
        scores{metric}=matrix;
    end
end

