function T=cluster_bootstrap_table(R,C,caseIDs,outputNames,s,localVerified)
    kernels=string(s.kernels);candidates=["constant_oof"; ...
        "full_local_shape";"tempered_local_shape"];
    nB=s.bootstrapReplicates;nCase=numel(caseIDs);
    scaleValues=nan(nB,numel(kernels),numel(candidates),numel(outputNames));
    gammaValues=nan(nB,numel(kernels));
    rng(s.bootstrapSeed,'twister');
    weights=zeros(nCase,nB);
    for b=1:nB
        draw=randi(nCase,nCase,1);weights(:,b)=accumarray(draw,1,[nCase 1]);
    end
    for k=1:numel(kernels)
        one=R(R.Kernel==kernels(k),:);
        profiles=bootstrap_profiles(one,weights,caseIDs,outputNames,s,localVerified);
        gammaValues(:,k)=profiles.selectedGamma;
        scaleValues(:,k,1,:)=reshape(profiles.scaleGamma0, ...
            [nB 1 1 numel(outputNames)]);
        scaleValues(:,k,2,:)=reshape(profiles.scaleGamma1, ...
            [nB 1 1 numel(outputNames)]);
        scaleValues(:,k,3,:)=reshape(profiles.scaleSelected, ...
            [nB 1 1 numel(outputNames)]);
    end
    parts=cell(0,1);
    for k=1:numel(kernels)
        for c=1:numel(candidates)
            for outputIndex=1:numel(outputNames)
                values=scaleValues(:,k,c,outputIndex);
                parts{end+1}=bootstrap_summary_row(kernels(k), ...
                    "scale",candidates(c),"",outputIndex,outputNames(outputIndex), ...
                    values,s); %#ok<AGROW>
            end
        end
        parts{end+1}=bootstrap_summary_row(kernels(k),"gamma", ...
            "tempered_local_shape","",0,"shared_over_outputs", ...
            gammaValues(:,k),s); %#ok<AGROW>
    end
    scoreNames=["GaussianPointNLPD";"GaussianPointCRPS"];
    allCandidates=candidate_order();
    for k=1:numel(kernels)
        for outputIndex=0:numel(outputNames)
            caseScores=case_candidate_scores(C,kernels(k),outputIndex, ...
                allCandidates,caseIDs,scoreNames);
            for left=1:numel(allCandidates)-1
                for right=left+1:numel(allCandidates)
                    for metric=1:numel(scoreNames)
                        difference=nan(nB,1);
                        matrix=caseScores{metric};
                        for b=1:nB
                            w=weights(:,b);valid=isfinite(matrix(:,left))& ...
                                isfinite(matrix(:,right))&w>0;
                            if any(valid)
                                difference(b)=sum(w(valid).* ...
                                    (matrix(valid,left)-matrix(valid,right)))/sum(w(valid));
                            end
                        end
                        output="equal_output";if outputIndex>0,output=outputNames(outputIndex);end
                        candidatePair=allCandidates(left)+"_minus_"+allCandidates(right);
                        parts{end+1}=bootstrap_summary_row(kernels(k), ...
                            "score_difference_"+scoreNames(metric), ...
                            allCandidates(left),allCandidates(right), ...
                            outputIndex,output,difference,s); %#ok<AGROW>
                        parts{end}.CandidatePair(:)=candidatePair;
                    end
                end
            end
        end
    end
    T=vertcat(parts{:});
end

function profile=bootstrap_profiles(R,weights,caseIDs,outputNames,s,available)
    nB=size(weights,2);nGamma=numel(s.gammaGrid);nOutput=numel(outputNames);
    scales=nan(nB,nGamma,nOutput);objective=nan(nB,nGamma,nOutput);
    [found,caseIndex]=ismember(R.CaseID,caseIDs);assert(all(found));
    for outputIndex=1:nOutput
        rows=R.OutputIndex==outputIndex;index=caseIndex(rows);
        residualSquared=R.Residual(rows).^2;localShape=R.LocalShape(rows);
        for gammaIndex=1:nGamma
            gamma=s.gammaGrid(gammaIndex);
            if ~available&&gamma>0,continue;end
            if gamma==0
                shape=ones(sum(rows),1);logShape=zeros(sum(rows),1);
            else
                shape=localShape.^gamma;logShape=gamma*log(localShape);
            end
            caseRatio=accumarray(index,residualSquared./shape, ...
                [numel(caseIDs) 1],@mean,NaN);
            caseLogShape=accumarray(index,logShape, ...
                [numel(caseIDs) 1],@mean,NaN);
            observed=isfinite(caseRatio)&isfinite(caseLogShape);
            assert(any(observed), ...
                'surrogates:surrogate_quality_calibration:BootstrapProfile', ...
                'A bootstrap replicate has no case with a finite variance ratio and shape.');
            denominator=weights.'*double(observed);
            caseRatio(~observed)=0;caseLogShape(~observed)=0;
            scale=(weights.'*caseRatio)./denominator;
            meanLogShape=(weights.'*caseLogShape)./denominator;
            scale(denominator==0)=NaN;meanLogShape(denominator==0)=NaN;
            scale=max(scale,eps);
            scales(:,gammaIndex,outputIndex)=scale;
            objective(:,gammaIndex,outputIndex)= ...
                .5*log(2*pi*scale)+.5*meanLogShape+.5;
        end
    end
    equal=mean(objective,3,'omitnan');selected=ones(nB,1);gamma=nan(nB,1);
    if available
        for b=1:nB
            finite=find(isfinite(equal(b,:)));
            if isempty(finite),selected(b)=1;continue;end
            [~,relative]=min(equal(b,finite));selected(b)=finite(relative);
            gamma(b)=s.gammaGrid(selected(b));
        end
    end
    scale0=reshape(scales(:,1,:),nB,nOutput);
    scale1=reshape(scales(:,end,:),nB,nOutput);
    selectedScale=nan(nB,nOutput);
    for b=1:nB
        selectedScale(b,:)=reshape(scales(b,selected(b),:),1,nOutput);
    end
    profile=struct('selectedGamma',gamma,'scaleGamma0',scale0, ...
        'scaleGamma1',scale1,'scaleSelected',selectedScale);
end

