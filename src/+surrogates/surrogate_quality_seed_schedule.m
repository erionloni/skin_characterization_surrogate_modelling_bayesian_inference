function [schedule,design,settings]=surrogate_quality_seed_schedule( ...
        developmentCaseIDs,cfg,varargin)
%SURROGATE_QUALITY_SEED_SCHEDULE Development-only audit design and fit plan.
%   [SCHEDULE,DESIGN,SETTINGS] = surrogates.surrogate_quality_seed_schedule(
%   DEVELOPMENTCASEIDS, CFG, ...) creates the complete deterministic
%   surrogate-development plan without fitting a model or reading response
%   values. Per scalar output, on the output's observed cohort, it contains
%   exactly:
%     * 75 kernel-CV GP fits (3 kernels x 5 repeats x 5 folds),
%     * 10 same-data GP fits (2 kernels x 5 seeds), and
%     * 90 learning-curve fits (2 GPs + 1 PCE x 5 repeats x 6 sizes),
%   1050 fits for the six outputs. Every seed is the recorded seed of the
%   thesis audit, or for a request that the thesis audit did not make the
%   seed of the settings' rule (seeds.surrogate_audit).
%
%   DESIGN stores CaseID-grouped CV/calibration folds, a truth-free 512-point
%   Latin-hypercube probe, and development-only nested learning-curve roles.
%   Every fit request has a readable key (FitRequest: campaign, output,
%   repeat, fold, nominal training size and candidate).
%   No external-holdout array or CaseID is an input to this function.
%   Options (name-value), from the dataset (surrogates.surrogate_quality_fit_campaign
%   passes them): 'InputNames', 'InputBounds', 'OutputNames',
%   'OutputTrainingContract' and 'OutputAvailabilityMask'.
%   Side effects: none (the random number generator's state is restored).

    parser=inputParser;
    addParameter(parser,'InputNames',{},@(x)iscell(x)||isstring(x));
    addParameter(parser,'InputBounds',[],@isnumeric);
    addParameter(parser,'OutputNames',{},@(x)iscell(x)||isstring(x));
    addParameter(parser,'OutputTrainingContract',struct(), ...
        @(x)isstruct(x)&&isscalar(x));
    addParameter(parser,'OutputAvailabilityMask',[], ...
        @(x)islogical(x)||isnumeric(x));
    parse(parser,varargin{:});
    caseIDs=reshape(double(developmentCaseIDs),[],1);
    assert(numel(caseIDs)>=2&&numel(unique(caseIDs))==numel(caseIDs)&& ...
        all(isfinite(caseIDs))&&all(caseIDs==fix(caseIDs)), ...
        'surrogates:surrogate_quality_seed_schedule:DevelopmentCases', ...
        'The audit requires unique finite development CaseIDs.');

    settings=resolved_settings(cfg,numel(caseIDs), ...
        parser.Results.InputNames,parser.Results.InputBounds);
    outputContract=resolved_output_contract(caseIDs,cfg,parser.Results);

    [schedule,design,settings]=availability_aware_design( ...
        caseIDs,settings,outputContract,cfg);
end

function contract=resolved_output_contract(caseIDs,cfg,options)
    supplied=options.OutputTrainingContract;
    if ~isempty(fieldnames(supplied))
        required={'records','allOutputsComplete'};
        assert(all(isfield(supplied,required))&&numel(supplied.records)==6, ...
            'surrogates:surrogate_quality_seed_schedule:OutputContract', ...
            'The supplied output-training contract must contain six records.');
        contract=supplied;
        masks=false(numel(caseIDs),6);
        for outputIndex=1:6
            record=supplied.records(outputIndex);
            assert(isfield(record,'mask')&&numel(record.mask)==numel(caseIDs), ...
                'surrogates:surrogate_quality_seed_schedule:OutputContract', ...
                'Each output record must bind one mask entry per development case.');
            masks(:,outputIndex)=logical(record.mask(:));
        end
        assert(logical(contract.allOutputsComplete)==all(masks,'all'), ...
            'surrogates:surrogate_quality_seed_schedule:OutputContract', ...
            'The allOutputsComplete declaration disagrees with the masks.');
        if ~isfield(contract,'developmentSplitGroupIdentities')
            contract.developmentSplitGroupIdentities= ...
                "caseid_"+string(caseIDs);
        end
        contract.developmentSplitGroupIdentities= ...
            string(contract.developmentSplitGroupIdentities(:));
        assert(numel(contract.developmentSplitGroupIdentities)==numel(caseIDs)&& ...
            all(strlength(contract.developmentSplitGroupIdentities)>0), ...
            'surrogates:surrogate_quality_seed_schedule:SplitGroups', ...
            'Every development case must have one nonempty split group.');
        contract.hasGroupedCases=numel(unique( ...
            contract.developmentSplitGroupIdentities))<numel(caseIDs);
        contract.mask=masks;
        return
    end
    mask=options.OutputAvailabilityMask;
    if isempty(mask),mask=true(numel(caseIDs),6);end
    mask=logical(mask);
    assert(isequal(size(mask),[numel(caseIDs) 6]), ...
        'surrogates:surrogate_quality_seed_schedule:OutputAvailabilityShape', ...
        'The output-availability mask must be N-development-by-six.');
    outputNames=options.OutputNames;
    if isempty(outputNames)&&isfield(cfg,'outputNames'),outputNames=cfg.outputNames;end
    if isempty(outputNames)
        outputNames=arrayfun(@(index)sprintf('output_%d',index),1:6, ...
            'UniformOutput',false);
    end
    outputNames=reshape(string(outputNames),[],1);
    assert(numel(outputNames)==6, ...
        'surrogates:surrogate_quality_seed_schedule:OutputNames', ...
        'Exactly six ordered output names are required.');
    records=repmat(struct('mask',false(numel(caseIDs),1), ...
        'caseIDs',zeros(0,1),'count',0),6,1);
    for outputIndex=1:6
        ids=caseIDs(mask(:,outputIndex));
        records(outputIndex)=struct('mask',mask(:,outputIndex), ...
            'caseIDs',ids,'count',numel(ids));
    end
    groups="caseid_"+string(caseIDs);
    contract=struct('records',{records},'mask',mask, ...
        'developmentSplitGroupIdentities',groups, ...
        'hasGroupedCases',false,'allOutputsComplete',all(mask,'all'));
end

function [schedule,design,settings]=availability_aware_design( ...
        allCaseIDs,settings,contract,cfg)
    nOutput=numel(contract.records);
    assert(nOutput==6, ...
        'surrogates:surrogate_quality_seed_schedule:OutputCount', ...
        'The availability-aware audit requires six scalar-output records.');
    outputNames=strings(nOutput,1);counts=zeros(nOutput,1);
    splitGroups=string(contract.developmentSplitGroupIdentities(:));
    kernelParts=cell(nOutput,1);foldParts=cell(nOutput,1);
    calibrationParts=cell(nOutput,1);roleParts=cell(nOutput,1);
    membershipParts=cell(nOutput,1);convergenceParts=cell(nOutput,1);
    probePoints=probe_design(settings,cfg);
    sameParts=cell(nOutput,1);
    for outputIndex=1:nOutput
        record=contract.records(outputIndex);mask=logical(record.mask(:));
        rows=find(mask);ids=allCaseIDs(rows);counts(outputIndex)=numel(ids);
        outputName="output_"+string(outputIndex);
        if isfield(record,'outputName'),outputName=string(record.outputName);end
        outputNames(outputIndex)=outputName;
        assert(numel(ids)>=settings.cvFolds+settings.inputCount&& ...
            numel(ids)>=settings.inputCount+1, ...
            'surrogates:surrogate_quality_seed_schedule:OutputDevelopmentCapacity', ...
            'Output %d has too few finite development responses.', ...
            outputIndex);
        [foldParts{outputIndex},kernelParts{outputIndex}]= ...
            output_kernel_cv_design(rows,ids,outputIndex,outputName, ...
            splitGroups,settings,cfg);
        sameParts{outputIndex}=output_same_data_parts(outputIndex,outputName, ...
            numel(ids),probePoints,settings,cfg);
        calibrationParts{outputIndex}=output_calibration_design(rows,ids, ...
            outputIndex,outputName,splitGroups,settings,cfg);
        [roleParts{outputIndex},membershipParts{outputIndex}, ...
            convergenceParts{outputIndex}]=output_convergence_design( ...
            rows,ids,outputIndex,outputName,splitGroups,settings,cfg);
    end
    schedule=vertcat(kernelParts{:},sameParts{:},convergenceParts{:});
    schedule.RequestOrder=(1:height(schedule)).';
    schedule=movevars(schedule,'RequestOrder','After','ScheduleVersion');
    expectedPerOutput=75+10+90;
    assert(height(schedule)==nOutput*expectedPerOutput&& ...
        nnz(schedule.Campaign=="kernel_cross_validation")==nOutput*75&& ...
        nnz(schedule.Campaign=="same_data_seed_stability")==nOutput*10&& ...
        nnz(schedule.Campaign=="training_convergence")==nOutput*90&& ...
        numel(unique(schedule.FitRequest))==height(schedule), ...
        'surrogates:surrogate_quality_seed_schedule:OutputFitPlan', ...
        'The output-specific audit fit plan is inconsistent.');
    kernelFolds=vertcat(foldParts{:});
    calibrationFolds=vertcat(calibrationParts{:});
    convergenceRoles=vertcat(roleParts{:});
    convergenceMembership=vertcat(membershipParts{:});
    validate_global_output_design(kernelFolds,calibrationFolds, ...
        convergenceRoles,convergenceMembership);
    design=struct( ...
        'schemaVersion','surrogate_development_audit_design_output_specific_v2', ...
        'developmentCaseIDs',allCaseIDs, ...
        'developmentSplitGroupIdentities',splitGroups, ...
        'outputAvailabilityMask',logical(contract.mask), ...
        'outputNames',{cellstr(outputNames)}, ...
        'outputDevelopmentCounts',counts, ...
        'kernelCVFolds',kernelFolds, ...
        'probePoints',probePoints, ...
        'calibrationFolds',calibrationFolds, ...
        'trainingConvergenceRoles',convergenceRoles, ...
        'trainingConvergenceMembership',convergenceMembership);
    settings.outputSpecificAvailability=true;
    settings.outputDevelopmentCounts=counts;
    settings.outputNames=cellstr(outputNames);
    settings.fitCount=struct('total',height(schedule), ...
        'gp',nnz(schedule.ModelFamily=="GP"), ...
        'pce',nnz(schedule.ModelFamily=="PCE"), ...
        'kernelCrossValidationGP',nOutput*75, ...
        'sameDataGP',nOutput*10, ...
        'trainingConvergenceGP',nOutput*60, ...
        'trainingConvergencePCE',nOutput*30);
end

function [folds,parts]=output_kernel_cv_design(rows,caseIDs,outputIndex, ...
        outputName,splitGroups,settings,cfg)
    parts=cell(settings.cvRepeats*settings.cvFolds,1);
    foldParts=cell(settings.cvRepeats,1);part=0;
    for repeat=1:settings.cvRepeats
        foldSeed=seeds.surrogate_audit(cfg,'kernel_cv_fold_assignment', ...
            struct('Repeat',repeat),struct('output',0,'repeat',repeat,'index',0));
        globalAssignment=grouped_deterministic_folds( ...
            splitGroups,settings.cvFolds,foldSeed);
        assignment=globalAssignment(rows);
        assessmentSizes=arrayfun(@(value)sum(assignment==value),assignment);
        trainingSizes=numel(caseIDs)-assessmentSizes;
        foldParts{repeat}=table( ...
            repmat(double(outputIndex),numel(caseIDs),1), ...
            repmat(string(outputName),numel(caseIDs),1), ...
            repmat(double(repeat),numel(caseIDs),1),assignment, ...
            repmat(double(foldSeed),numel(caseIDs),1), ...
            rows,caseIDs,assessmentSizes,trainingSizes, ...
            splitGroups(rows), ...
            trainingSizes>=settings.inputCount+1,assessmentSizes>=1, ...
            'VariableNames',{'OutputIndex','Output', ...
            'Repeat','Fold','FoldAssignmentSeed', ...
            'DevelopmentRowIndex','CaseID','AssessmentFoldSize', ...
            'TrainingFoldSize','SplitGroup','TrainingAdequate', ...
            'AssessmentAdequate'});
        for fold=1:settings.cvFolds
            part=part+1;assessmentCount=nnz(assignment==fold);
            trainingCount=numel(caseIDs)-assessmentCount;
            assert(trainingCount>=settings.inputCount+1&&assessmentCount>=1, ...
                'surrogates:surrogate_quality_seed_schedule:OutputCVFoldAdequacy', ...
                'Output %d repeat %d fold %d has inadequate train/holdout counts.', ...
                outputIndex,repeat,fold);
            fitSeed=seeds.surrogate_audit(cfg,'kernel_cv_fit', ...
                struct('Output',outputIndex,'Repeat',repeat,'Fold',fold), ...
                struct('output',outputIndex,'repeat',repeat,'index',fold));
            basis=output_basis_record(settings,'kernel_cross_validation', ...
                outputIndex,repeat,fold);
            base=fit_rows(settings.cvKernels,"GP",repeat,fold,NaN, ...
                foldSeed,basis,fitSeed,trainingCount,assessmentCount,settings);
            parts{part}=bind_output(base,outputIndex,outputName);
        end
    end
    folds=vertcat(foldParts{:});
    parts=vertcat(parts{:});
end

function parts=output_same_data_parts(outputIndex,outputName, ...
        developmentCount,probe,settings,cfg)
    parts=cell(settings.sameDataReplicates,1);
    probeSeed=double(probe.ProbeSeed(1));
    for repeat=1:settings.sameDataReplicates
        fitSeed=seeds.surrogate_audit(cfg,'same_data_fit', ...
            struct('Output',outputIndex,'Repeat',repeat), ...
            struct('output',outputIndex,'repeat',repeat,'index',0));
        basis=output_basis_record(settings,'same_data_seed_stability', ...
            outputIndex,repeat,0);
        base=fit_rows(settings.sameDataKernels,"GP",repeat,0, ...
            developmentCount,probeSeed,basis,fitSeed, ...
            developmentCount,settings.probeCount,settings);
        parts{repeat}=bind_output(base,outputIndex,outputName);
    end
    parts=vertcat(parts{:});
end

function folds=output_calibration_design(rows,caseIDs,outputIndex, ...
        outputName,splitGroups,settings,cfg)
    seed=seeds.surrogate_audit(cfg,'calibration_fold_assignment',struct(), ...
        struct('output',0,'repeat',0,'index',0));
    globalAssignment=grouped_deterministic_folds( ...
        splitGroups,settings.calibrationFolds,seed);
    assignment=globalAssignment(rows);
    validationCounts=arrayfun(@(value)sum(assignment==value),assignment);
    trainingCounts=numel(caseIDs)-validationCounts;
    folds=table(repmat(double(outputIndex),numel(caseIDs),1), ...
        repmat(string(outputName),numel(caseIDs),1),caseIDs,rows,assignment, ...
        repmat(double(seed),numel(caseIDs),1), ...
        splitGroups(rows), ...
        trainingCounts,validationCounts, ...
        trainingCounts>=settings.inputCount+1,validationCounts>=1, ...
        repmat("development_calibration_crossfit",numel(caseIDs),1), ...
        'VariableNames',{'OutputIndex','Output','CaseID', ...
        'DevelopmentRowIndex','CalibrationFold', ...
        'CalibrationFoldAssignmentSeed', ...
        'SplitGroup', ...
        'CalibrationTrainingCaseCount','CalibrationValidationCaseCount', ...
        'TrainingAdequate','ValidationAdequate', ...
        'MethodologicalRole'});
    folds=sortrows(folds,{'OutputIndex','CaseID'});
    for fold=1:settings.calibrationFolds
        trainCount=nnz(assignment~=fold);testCount=nnz(assignment==fold);
        assert(trainCount>=settings.inputCount+1&&testCount>=1, ...
            'surrogates:surrogate_quality_seed_schedule:OutputCalibrationFoldAdequacy', ...
            'Output %d calibration fold %d lacks train or validation support.', ...
            outputIndex,fold);
    end
end

function [roles,membership,parts]=output_convergence_design(rows,caseIDs, ...
        outputIndex,outputName,splitGroups,settings,cfg)
    roleParts=cell(settings.convergenceRepeats,1);
    nSize=numel(settings.convergenceSizes);
    membershipParts=cell(settings.convergenceRepeats*nSize,1);
    fitParts=cell(size(membershipParts));part=0;
    methods=string([settings.convergenceGPKernels {'degree_adaptive_BCS_PCE'}]);
    validationCount=settings.convergenceValidationCount;
    for repeat=1:settings.convergenceRepeats
        partitionSeed=seeds.surrogate_audit(cfg,'convergence_partition', ...
            struct('Repeat',repeat),struct('output',0,'repeat',repeat,'index',0));
        [temporaryGlobal,poolGlobal,globalPoolOrder]= ...
            grouped_convergence_partition(splitGroups,validationCount, ...
            partitionSeed);
        assert(numel(poolGlobal)>=max(settings.convergenceSizes), ...
            'surrogates:surrogate_quality_seed_schedule:GroupedConvergenceCapacity', ...
            ['Repeat %d has only %d grouped development rows for a maximum ' ...
             'nominal training size of %d.'],repeat,numel(poolGlobal), ...
            max(settings.convergenceSizes));
        temporary=ismember(rows,temporaryGlobal);
        poolOrder=globalPoolOrder(rows);
        role=repmat("nested_training_pool",numel(caseIDs),1);
        role(temporary)="temporary_validation";
        roleParts{repeat}=table( ...
            repmat(double(outputIndex),numel(caseIDs),1), ...
            repmat(string(outputName),numel(caseIDs),1), ...
            repmat(double(repeat),numel(caseIDs),1),rows,caseIDs,role,poolOrder, ...
            splitGroups(rows), ...
            repmat(double(partitionSeed),numel(caseIDs),1), ...
            'VariableNames',{'OutputIndex','Output', ...
            'Repeat','DevelopmentRowIndex','CaseID','MethodologicalRole', ...
            'NestedPoolOrder','SplitGroup','PartitionSeed'});
        for sizeIndex=1:nSize
            part=part+1;trainSize=settings.convergenceSizes(sizeIndex);
            globalSelected=grouped_nested_selection( ...
                splitGroups,globalPoolOrder,trainSize);
            selected=globalSelected(rows);
            actualGlobalTrainCount=nnz(globalSelected);
            actualTrainCount=nnz(selected);
            actualValidationCount=nnz(temporary);
            assert(actualTrainCount>=settings.inputCount+1&& ...
                actualValidationCount>=1, ...
                'surrogates:surrogate_quality_seed_schedule:OutputConvergenceAdequacy', ...
                ['Output %d repeat %d nominal N=%d resolves to %d training and ' ...
                 '%d validation observations.'],outputIndex,repeat,trainSize, ...
                actualTrainCount,actualValidationCount);
            membershipRole=repmat("nested_pool_not_selected",numel(caseIDs),1);
            membershipRole(selected)="training_subset";
            membershipRole(temporary)="temporary_validation";
            membershipParts{part}=table( ...
                repmat(double(outputIndex),numel(caseIDs),1), ...
                repmat(string(outputName),numel(caseIDs),1), ...
                repmat(double(repeat),numel(caseIDs),1), ...
                repmat(double(trainSize),numel(caseIDs),1),rows,caseIDs, ...
                membershipRole,selected,temporary,poolOrder, ...
                splitGroups(rows), ...
                repmat(double(actualGlobalTrainCount),numel(caseIDs),1), ...
                repmat(double(actualTrainCount),numel(caseIDs),1), ...
                repmat(double(actualValidationCount),numel(caseIDs),1), ...
                'VariableNames',{'OutputIndex','Output', ...
                'Repeat','NominalGlobalDevelopmentCaseCount', ...
                'DevelopmentRowIndex','CaseID', ...
                'MembershipRole','SelectedForTraining','TemporaryValidation', ...
                'NestedPoolOrder','SplitGroup', ...
                'ActualGlobalTrainingCount','ActualOutputTrainingCount', ...
                'ActualOutputValidationCount'});
            modelRows=cell(numel(methods),1);
            sizeKey=struct('Output',outputIndex,'Repeat',repeat,'TrainingSize',trainSize);
            sizeNumbers=struct('output',outputIndex,'repeat',repeat,'index',sizeIndex);
            gpSeed=seeds.surrogate_audit(cfg,'convergence_gp_fit',sizeKey,sizeNumbers);
            pceSeed=seeds.surrogate_audit(cfg,'convergence_pce_fit',sizeKey,sizeNumbers);
            for methodIndex=1:numel(methods)
                candidate=methods(methodIndex);family="GP";fitSeed=gpSeed;
                if candidate=="degree_adaptive_BCS_PCE"
                    family="PCE";fitSeed=pceSeed;
                end
                basis=output_basis_record(settings,'training_convergence', ...
                    outputIndex,repeat,0);
                base=fit_rows(cellstr(candidate),family,repeat,0,trainSize, ...
                    partitionSeed,basis,fitSeed,actualTrainCount, ...
                    actualValidationCount,settings);
                modelRows{methodIndex}=bind_output(base,outputIndex,outputName);
            end
            fitParts{part}=vertcat(modelRows{:});
        end
    end
    roles=vertcat(roleParts{:});membership=vertcat(membershipParts{:});
    parts=vertcat(fitParts{:});
end

function validate_global_output_design(kernelFolds,calibrationFolds,roles,membership)
    assert_consistent(string(kernelFolds.Repeat)+"|case|"+ ...
        string(kernelFolds.CaseID),kernelFolds.Fold, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalKernelCaseFold');
    assert_consistent(string(kernelFolds.Repeat)+"|group|"+ ...
        kernelFolds.SplitGroup,kernelFolds.Fold, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalKernelGroupFold');
    assert_consistent("case|"+string(calibrationFolds.CaseID), ...
        calibrationFolds.CalibrationFold, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalCalibrationCaseFold');
    assert_consistent("group|"+calibrationFolds.SplitGroup, ...
        calibrationFolds.CalibrationFold, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalCalibrationGroupFold');
    roleKey=string(roles.Repeat)+"|case|"+string(roles.CaseID);
    assert_consistent(roleKey,roles.MethodologicalRole, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalConvergenceCaseRole');
    groupRoleKey=string(roles.Repeat)+"|group|"+roles.SplitGroup;
    assert_consistent(groupRoleKey,roles.MethodologicalRole, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalConvergenceGroupRole');
    membershipKey=string(membership.Repeat)+"|"+ ...
        string(membership.NominalGlobalDevelopmentCaseCount)+ ...
        "|case|"+string(membership.CaseID);
    assert_consistent(membershipKey,membership.SelectedForTraining, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalNestedCaseSelection');
    groupMembershipKey=string(membership.Repeat)+"|"+ ...
        string(membership.NominalGlobalDevelopmentCaseCount)+ ...
        "|group|"+membership.SplitGroup;
    assert_consistent(groupMembershipKey,membership.SelectedForTraining, ...
        'surrogates:surrogate_quality_seed_schedule:GlobalNestedGroupSelection');
end

function assert_consistent(keys,values,identifier)
    keys=string(keys(:));[uniqueKeys,~,group]=unique(keys,'sorted');
    for index=1:numel(uniqueKeys)
        one=values(group==index);
        if isnumeric(one)||islogical(one)
            matches=all(arrayfun(@(row)isequaln(one(row),one(1)), ...
                (1:numel(one)).'));
        else
            matches=all(string(one)==string(one(1)));
        end
        assert(matches,identifier, ...
            'A global CaseID/group role was assigned inconsistently by output.');
    end
end

function rows=bind_output(rows,outputIndex,outputName)
%BIND_OUTPUT The output of each fit request and its readable key (FitRequest).
%   The key names the campaign, output, repeat, fold, nominal training size
%   (0 for none) and candidate, for example
%   kernel_cross_validation/o1/r2/f3/n0/Matern-3_2.
    n=height(rows);
    rows=addvars(rows,repmat(double(outputIndex),n,1), ...
        repmat(string(outputName),n,1), ...
        'After','Campaign','NewVariableNames',{'OutputIndex','Output'});
    for index=1:n
        nominal=rows.NominalGlobalDevelopmentCaseCount(index);
        if ~isfinite(nominal),nominal=0;end
        rows.FitRequest(index)=string(sprintf('%s/o%d/r%d/f%d/n%d/%s', ...
            char(rows.Campaign(index)),outputIndex,rows.Repeat(index), ...
            rows.Fold(index),nominal,char(rows.Candidate(index))));
    end
end

function basis=output_basis_record(settings,campaign,outputIndex,repeat,fold)
    basis=struct('campaign',campaign, ...
        'text',sprintf('%s|master=%d|campaign=%s|output=%d|repeat=%d|fold=%d', ...
        settings.scheduleVersion,settings.masterSeed,campaign,outputIndex, ...
        repeat,fold));
end

function probe=probe_design(settings,cfg)
    probeSeed=seeds.surrogate_audit(cfg,'same_data_probe',struct(), ...
        struct('output',0,'repeat',0,'index',0));
    state=rng;restore=onCleanup(@()rng(state));
    rng(probeSeed,'twister');
    normalized=zeros(settings.probeCount,settings.inputCount);
    for inputIndex=1:settings.inputCount
        order=randperm(settings.probeCount).';
        normalized(:,inputIndex)=(order-0.5)/settings.probeCount;
    end
    clear restore
    physical=settings.lowerBounds+normalized.* ...
        (settings.upperBounds-settings.lowerBounds);
    probe=table((1:settings.probeCount).', ...
        repmat(double(probeSeed),settings.probeCount,1), ...
        'VariableNames',{'ProbeIndex','ProbeSeed'});
    for inputIndex=1:settings.inputCount
        name=matlab.lang.makeValidName(settings.inputNames{inputIndex});
        probe.(name)=physical(:,inputIndex);
        probe.(['Normalized_' name])=normalized(:,inputIndex);
    end
    assert(height(probe)==512&& ...
        all(normalized>0&normalized<1,'all')&& ...
        ~any(ismember(probe.Properties.VariableNames, ...
        {'CaseID','Truth','COMSOL'})), ...
        'surrogates:surrogate_quality_seed_schedule:TruthFreeProbe', ...
        'The deterministic truth-free probe contract is inconsistent.');
end

function rows=fit_rows(candidates,family,repeat,fold,trainSize,partitionSeed, ...
        basis,fitSeed,trainCount,assessmentCount,settings)
    candidates=reshape(string(candidates),[],1);n=numel(candidates);
    Campaign=repmat(string(basis.campaign),n,1);
    Repeat=repmat(double(repeat),n,1);Fold=repmat(double(fold),n,1);
    NominalGlobalDevelopmentCaseCount=repmat(double(trainSize),n,1);
    ModelFamily=repmat(string(family),n,1);Candidate=candidates;
    Kernel=candidates;Optimizer=repmat(string(settings.optimizer),n,1);
    Nugget=repmat(double(settings.nugget),n,1);
    pce=ModelFamily=="PCE";Kernel(pce)="";Optimizer(pce)=string(settings.pceMethod);
    Nugget(pce)=NaN;MasterSeed=repmat(settings.masterSeed,n,1);
    PartitionSeed=repmat(double(partitionSeed),n,1);
    SeedBasis=repmat(string(basis.text),n,1);
    FitSeed=repmat(double(fitSeed),n,1);
    TrainCaseCount=repmat(double(trainCount),n,1);
    AssessmentCaseCount=repmat(double(assessmentCount),n,1);
    FitRequest=strings(n,1);
    rows=table(repmat(string(settings.scheduleVersion),n,1),Campaign,Repeat, ...
        Fold,NominalGlobalDevelopmentCaseCount,ModelFamily,Candidate, ...
