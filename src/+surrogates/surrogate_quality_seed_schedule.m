        ['The audit needs at least one repeat, two folds, one same-data replicate and ' ...
         'probe point, and a pool as large as the largest training size (settings A.4).']);
end

function permutation=seeded_randperm(count,seed)
    state=rng;restore=onCleanup(@()rng(state));
    rng(seed,'twister');permutation=randperm(count).';
    clear restore
end

function assignment=grouped_deterministic_folds(groups,foldCount,seed)
    groups=string(groups(:));
    [uniqueGroups,~,groupIndex]=unique(groups,'sorted');
    assert(numel(uniqueGroups)>=foldCount&&all(strlength(groups)>0), ...
        'surrogates:surrogate_quality_seed_schedule:GroupedFoldCapacity', ...
        'The grouped cohort has fewer unique groups than folds.');
    groupAssignment=surrogates.deterministic_folds( ...
        numel(uniqueGroups),foldCount,seed);
    assignment=groupAssignment(groupIndex);
    assert(all(assignment>=1&assignment<=foldCount), ...
        'surrogates:surrogate_quality_seed_schedule:GroupedFoldAssignment', ...
        'The grouped fold assignment produced an invalid fold index.');
end

function [temporaryRows,poolRows,poolOrder]=grouped_convergence_partition( ...
        groups,requestedValidationCount,seed)
    groups=string(groups(:));n=numel(groups);
    [uniqueGroups,~,groupIndex]=unique(groups,'sorted');
    groupPermutation=seeded_randperm(numel(uniqueGroups),seed);
    groupCounts=accumarray(groupIndex,1,[numel(uniqueGroups) 1]);
    cumulative=cumsum(groupCounts(groupPermutation));
    validationGroupCount=find(cumulative>=requestedValidationCount,1,'first');
    assert(~isempty(validationGroupCount)&&validationGroupCount< ...
        numel(uniqueGroups), ...
        'surrogates:surrogate_quality_seed_schedule:GroupedValidationCapacity', ...
        'The grouped convergence partition cannot form train and validation sets.');
    validationGroups=groupPermutation(1:validationGroupCount);
    poolGroups=groupPermutation(validationGroupCount+1:end);
    temporaryMask=ismember(groupIndex,validationGroups);
    temporaryRows=find(temporaryMask);poolRows=zeros(0,1);poolOrder=nan(n,1);
    next=0;
    for index=1:numel(poolGroups)
        one=find(groupIndex==poolGroups(index));
        poolRows=[poolRows;one]; %#ok<AGROW>
        poolOrder(one)=next+(1:numel(one));
        next=next+numel(one);
    end
    assert(all(isfinite(poolOrder(~temporaryMask)))&& ...
        all(isnan(poolOrder(temporaryMask)))&& ...
        isempty(intersect(temporaryRows,poolRows))&& ...
        numel(temporaryRows)+numel(poolRows)==n, ...
        'surrogates:surrogate_quality_seed_schedule:GroupedConvergencePartition', ...
        'The grouped convergence partition is incomplete or overlapping.');
end

function selected=grouped_nested_selection(groups,poolOrder,nominalCount)
    groups=string(groups(:));poolOrder=double(poolOrder(:));
    inPool=isfinite(poolOrder);
    poolGroups=unique(groups(inPool),'sorted');
    firstOrder=nan(numel(poolGroups),1);counts=zeros(numel(poolGroups),1);
    for index=1:numel(poolGroups)
        rows=inPool&groups==poolGroups(index);
        firstOrder(index)=min(poolOrder(rows));counts(index)=nnz(rows);
    end
    [~,order]=sort(firstOrder);cumulative=cumsum(counts(order));
    include=cumulative<=nominalCount;
    if ~any(include)&&~isempty(order),include(1)=true;end
    selectedGroups=poolGroups(order(include));
    selected=inPool&ismember(groups,selectedGroups);
    assert(all(selected<=inPool), ...
        'surrogates:surrogate_quality_seed_schedule:GroupedNestedSelection', ...
        'A nested training selection contains a row outside its pool.');
end
