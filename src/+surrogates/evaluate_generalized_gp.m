function prediction=evaluate_generalized_gp(model,X,cfg,varargin)
%EVALUATE_GENERALIZED_GP The generalized GP mean and its calibrated emulator variance.
%   PREDICTION = surrogates.evaluate_generalized_gp(MODEL, X, CFG, ...)
%   evaluates the generalized GP ensemble MODEL at X (rows of the four
%   material and three protocol inputs) and returns the mean, the raw
%   UQLab variance (kept for reference) and the calibrated emulator
%   variance of the frozen generalized calibration, with the calibration's
%   variance formula and the input and output orders. The model must have
%   been fitted on the development cases the calibration lists per output.
%   Option (name-value): 'IncludeCalibrationMetadata' (false: true also
%   returns the calibration record in the metadata).
%   Side effects: none.
%   Computation: UQLab predictions.

    parser=inputParser;
    addParameter(parser,'IncludeCalibrationMetadata',false, ...
        @(x)islogical(x)&&isscalar(x));
    parse(parser,varargin{:});
    assert(isstruct(cfg)&&isscalar(cfg)&&strcmp(cfg.dataMode,'real_extended')&& ...
        isfield(cfg,'emulatorErrorCalibration')&& ...
        isfield(cfg,'realExtended')&& ...
        ismember(string(cfg.gp.kernel),["Matern-3_2","Matern-5_2"])&&size(X,2)==7&& ...
        all(isfinite(X),'all'), ...
        'surrogates:evaluate_generalized_gp:Configuration','Check failed: surrogates:evaluate_generalized_gp:Configuration.');
    calibration=cfg.emulatorErrorCalibration;
    assert(strcmp(calibration.route,'real_extended')&& ...
        strcmp(calibration.kernel,cfg.gp.kernel)&& ...
        isequal(calibration.input_order,cfg.realExtended.learningInputNames)&& ...
        isequal(calibration.output_order,cfg.realExtended.outputNames), ...
        'surrogates:evaluate_generalized_gp:CalibrationContract','Check failed: surrogates:evaluate_generalized_gp:CalibrationContract.');
    assert(isstruct(model)&&isscalar(model)&&isfield(model,'models')&& ...
        numel(model.models)==6&&isfield(model,'route')&& ...
        strcmp(model.route,'real_extended')&&isfield(model,'family')&& ...
        strcmpi(model.family,'gp')&& ...
        isfield(model,'inputNames')&&isequal(model.inputNames, ...
        cfg.realExtended.learningInputNames)&&isfield(model,'outputNames')&& ...
        isequal(model.outputNames,cfg.realExtended.outputNames), ...
        'surrogates:evaluate_generalized_gp:ModelContract', ...
        'The GP ensemble does not match the frozen generalized calibration.');
    validate_model_calibration(model,calibration);
    if isfield(model,'records')
        records=model.records;
        assert(numel(records)==6&&all(strcmp({records.executionStatus}, ...
            'completed'))&&all(arrayfun(@(record) ...
            isfield(record,'settings')&& ...
            strcmp(record.settings.kernel,cfg.gp.kernel)&& ...
            strcmp(record.settings.trend,'ordinary')&& ...
            strcmp(record.settings.correlationType,'Ellipsoidal')&& ...
            strcmp(record.settings.optimizer,'HGA')&& ...
            double(record.settings.nugget)==1e-10,records)), ...
            'surrogates:evaluate_generalized_gp:OutputModelContract','Check failed: surrogates:evaluate_generalized_gp:OutputModelContract.');
    end

    for j=1:6
        actual=model.models{j}.Internal.Kriging(1).GP.Corr.Family;
        assert(strcmpi(actual,cfg.gp.kernel), ...
            'surrogates:evaluate_generalized_gp:ActualModelKernel','Check failed: surrogates:evaluate_generalized_gp:ActualModelKernel.');
    end
    % Points per GP call (settings 0.3).
    [meanPrediction,rawVariance]=surrogates.evaluate(model,X,'gp',cfg.realExtended.predictionBatchSize);
    assert(isequal(size(meanPrediction),[size(X,1) 6])&& ...
        isequal(size(rawVariance),size(meanPrediction))&& ...
        all(isfinite(meanPrediction),'all')&&all(isfinite(rawVariance),'all'), ...
        'surrogates:evaluate_generalized_gp:OutputShape','Check failed: surrogates:evaluate_generalized_gp:OutputShape.');
    % surrogates.evaluate is the single sanitizer. For an output ensemble it
    % applies this documented relative tolerance independently per output.
    assert(all(rawVariance>=0,'all'), ...
        'surrogates:evaluate_generalized_gp:SanitizedRawVariance','Check failed: surrogates:evaluate_generalized_gp:SanitizedRawVariance.');
    negativeTolerance=1e-12*max(1,max(abs(rawVariance),[],1));
    processVariance=surrogates.gp_process_variance(model,6);
    [calibratedVariance,localShape]= ...
        surrogates.calibrated_emulator_variance( ...
        rawVariance,processVariance,calibration);
    metadata=struct();
    if parser.Results.IncludeCalibrationMetadata
        metadata=calibration;
    end
    prediction=struct( ...
        'GPMean',meanPrediction, ...
        'RawUQLabVariance',rawVariance, ...
        'RawUQLabSD',sqrt(rawVariance), ...
        'RawVarianceSanitizationToleranceByOutput',negativeTolerance, ...
        'RawVarianceSanitizationPolicy', ...
            'surrogates.evaluate_1e-12_relative_roundoff_v1', ...
        'ProcessVariance',processVariance, ...
        'LocalVarianceShapeH',localShape, ...
        'CalibratedEmulatorVariance',calibratedVariance, ...
        'CalibratedEmulatorSD',sqrt(calibratedVariance), ...
        'CalibrationMetadata',metadata, ...
        'VarianceFormulaVersion',calibration.variance_formula_version, ...
        'InputOrder',{calibration.input_order}, ...
        'OutputOrder',{calibration.output_order});
end

function validate_model_calibration(model,calibration)
%VALIDATE_MODEL_CALIBRATION The model was fitted on the development cases the calibration lists per output.
    schema=char(string(calibration.schema_version));
    assert(ismember(schema,{'routeR_emulator_error_calibration_v2', ...
        'routeR_emulator_error_calibration_v3'})&& ...
        isfield(model,'outputTrainingCounts')&& ...
        isfield(model,'partialOutputTrainingEnabled')&& ...
        islogical(model.partialOutputTrainingEnabled)&& ...
        isscalar(model.partialOutputTrainingEnabled), ...
        'surrogates:evaluate_generalized_gp:OutputSpecificCalibrationCohort', ...
        ['Output-aware generalized ensembles need a calibration that lists the ' ...
         'development cases of every output (schema v2 or v3).']);
    records=reshape(calibration.output_data_contract,[],1);
    indexes=reshape(double([records.output_index]),[],1);
    [~,order]=sort(indexes);records=records(order);
    expectedCounts=reshape(double([records.development_case_count]),1,[]);
    assert(isequal(reshape(double(model.outputTrainingCounts),1,[]),expectedCounts), ...
        'surrogates:evaluate_generalized_gp:OutputSpecificModelEvidence', ...
        'Per-output model cohorts differ from the frozen calibration.');
    if isfield(model,'records')
        for outputIndex=1:6
            assert(isequal(reshape(double( ...
                model.records(outputIndex).trainingCaseIDs),1,[]), ...
                reshape(double(records(outputIndex).development_case_ids),1,[])), ...
                'surrogates:evaluate_generalized_gp:OutputSpecificCaseIDs', ...
                'Output %d training CaseIDs differ from calibration.',outputIndex);
        end
    end
end
