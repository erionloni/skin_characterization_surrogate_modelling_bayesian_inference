function contract = output_training_contract(dataSet,cfg)
%OUTPUT_TRAINING_CONTRACT The training cohort of every output (development cases only).
%   CONTRACT = surrogates.output_training_contract(DATASET, CFG) returns, for
%   each of the six outputs, the development cases whose response is finite
%   (their CaseIDs, inputs X, responses Y, counts and split groups): the
%   data each scalar model is fitted on. DATASET holds the development
%   arrays of a dataset (X_train, Y_train, trainCaseIDs, input and output
%   names); the external cases are checked for overlap only, their outputs
%   are not read.
%   Side effects: none.

    required={'X_train','Y_train','trainCaseIDs','inputNames','outputNames'};
    assert(isstruct(dataSet)&&isscalar(dataSet)&&all(isfield(dataSet,required)), ...
        'surrogates:output_training_contract:DatasetSchema', ...
        'The dataset needs the variables %s; rerun the step ''dataset''.', ...
        strjoin(required,', '));
    X=double(dataSet.X_train);Y=double(dataSet.Y_train);
    ids=double(dataSet.trainCaseIDs(:));
    assert(size(X,1)==size(Y,1)&&size(Y,2)==6&& ...
        numel(ids)==size(X,1)&&numel(unique(ids))==numel(ids)&& ...
        all(isfinite(X),'all')&&~any(isinf(Y),'all'), ...
        'surrogates:output_training_contract:DatasetValues', ...
        'Development inputs must be finite and targets must be finite or NaN.');
    splitGroups=resolved_split_groups(dataSet,ids,Y);
    if isfield(dataSet,'validationCaseIDs')
        assert(isempty(intersect(ids,double(dataSet.validationCaseIDs(:)))), ...
            'surrogates:output_training_contract:ExternalLeakage', ...
            'Development and external cases of the dataset overlap; rerun the step ''dataset''.');
    end
    inputOrder=cellstr(string(dataSet.inputNames(:))).';
    outputOrder=cellstr(string(dataSet.outputNames(:))).';
    assert(isequal(inputOrder,cellstr(string(cfg.paramNames(:))).')&& ...
        isequal(outputOrder,cellstr(string(cfg.outputNames(:))).'), ...
        'surrogates:output_training_contract:Order', ...
        ['The dataset orders its inputs or outputs differently from the ' ...
         'configuration (inputs %s; outputs %s).'],strjoin(inputOrder,', '), ...
        strjoin(outputOrder,', '));
    % These are properties of the configured fitting procedures, not a
    % route-wide arbitrary cohort threshold. Ordinary Kriging needs at least
    % two distinct observations around its constant trend. The configured
    % adaptive PCE includes the complete degree-1 basis (constant plus M
    % inputs), so that basis sets the binding minimum for the paired GP/PCE
    % publication contract.
    gpMinimum=2;
    pceMinimum=size(X,2)+1;
    minimum=max(gpMinimum,pceMinimum);
    records=cell(1,6);
    for j=1:6
        mask=isfinite(Y(:,j));
        assert(nnz(mask)>=minimum, ...
            'surrogates:output_training_contract:InsufficientObservations', ...
            ['Output %s has %d valid development observations; the ordinary ' ...
             'trend/degree-1 basis requires at least M+1=%d.'], ...
             outputOrder{j},nnz(mask),minimum);
        records{j}=struct( ...
            'outputIndex',j,'outputName',outputOrder{j},'mask',mask, ...
            'X',X(mask,:),'Y',Y(mask,j),'caseIDs',ids(mask), ...
            'count',nnz(mask),'missingDevelopmentCount',nnz(~mask), ...
            'completeContributorCount',NaN,'partialContributorCount',NaN, ...
            'materialGroupIdentities',strings(nnz(mask),1), ...
            'splitGroupIdentities',splitGroups(mask), ...
            'minimumRequired',minimum, ...
            'gpMinimumRequired',gpMinimum, ...
            'pceMinimumRequired',pceMinimum, ...
            'inputSupportMinMax',[min(X(mask,:),[],1).' max(X(mask,:),[],1).']);
        if isfield(dataSet,'outputTrainingEvidence')&& ...
                numel(dataSet.outputTrainingEvidence)==6
            source=dataSet.outputTrainingEvidence(j);
            sourceGroups=string(source.trainingSplitGroupIdentities(:));
            records{j}.completeContributorCount= ...
                double(source.completeContributorCount);
            records{j}.partialContributorCount= ...
                double(source.partialContributorCount);
            records{j}.materialGroupIdentities= ...
                string(source.trainingMaterialGroupIdentities(:));
            records{j}.splitGroupIdentities=sourceGroups;
        end
    end
    records=[records{:}];
    contract=struct( ...
        'schemaVersion','routeR_output_training_contract_v1', ...
        'inputOrder',{inputOrder},'outputOrder',{outputOrder}, ...
        'developmentCaseIDs',ids, ...
        'developmentSplitGroupIdentities',splitGroups, ...
        'records',{records},'allOutputsComplete',all(isfinite(Y),'all'), ...
        'hasGroupedCases',numel(unique(splitGroups))<numel(splitGroups));
end

function groups=resolved_split_groups(dataSet,ids,Y)
    n=numel(ids);groups=strings(n,1);
    if isfield(dataSet,'developmentSplitGroupIdentities')&& ...
            numel(dataSet.developmentSplitGroupIdentities)==n
        groups=string(dataSet.developmentSplitGroupIdentities(:));
    elseif isfield(dataSet,'splitManifest')&&istable(dataSet.splitManifest)&& ...
            all(ismember({'CaseID','SplitGroup'}, ...
            dataSet.splitManifest.Properties.VariableNames))
        [present,location]=ismember(ids,double(dataSet.splitManifest.CaseID));
        assert(all(present),'surrogates:output_training_contract:SplitGroups', ...
            'The split groups of the development cases in the dataset are incomplete; rerun the step ''dataset''.');
        groups=string(dataSet.splitManifest.SplitGroup(location));
    elseif isfield(dataSet,'outputTrainingEvidence')&& ...
            numel(dataSet.outputTrainingEvidence)==6
        for outputIndex=1:6
            source=dataSet.outputTrainingEvidence(outputIndex);
            if ~isfield(source,'trainingSplitGroupIdentities'),continue;end
            sourceIDs=double(source.trainingCaseIDs(:));
            sourceGroups=string(source.trainingSplitGroupIdentities(:));
            assert(numel(sourceIDs)==numel(sourceGroups)&& ...
                isequal(sourceIDs,ids(isfinite(Y(:,outputIndex)))), ...
                'surrogates:output_training_contract:SplitGroups', ...
                'The split groups of the development cases in the dataset are incomplete; rerun the step ''dataset''.');
            [present,location]=ismember(sourceIDs,ids);
            assert(all(present),'surrogates:output_training_contract:SplitGroups', ...
                'The split groups of the development cases in the dataset are incomplete; rerun the step ''dataset''.');
            existing=groups(location);assigned=strlength(existing)>0;
            assert(all(~assigned|existing==sourceGroups), ...
                'surrogates:output_training_contract:SplitGroupConflict', ...
                'The dataset assigns one development case to two split groups; rerun the step ''dataset''.');
            groups(location)=sourceGroups;
        end
    end
    empty=ismissing(groups)|strlength(groups)==0;
    groups(empty)="caseid_"+string(ids(empty));
    assert(numel(groups)==n&&all(~ismissing(groups))&&all(strlength(groups)>0), ...
        'surrogates:output_training_contract:SplitGroups', ...
        'The split groups of the development cases in the dataset are incomplete; rerun the step ''dataset''.');
end
