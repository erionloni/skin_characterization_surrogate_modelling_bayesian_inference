function T=surrogate_quality_metrics(truth,prediction,variance,outputNames,varargin)
%SURROGATE_QUALITY_METRICS Per-output table wrapper for shared primitives.
%   T = SURROGATES.SURROGATE_QUALITY_METRICS(Y,MU,V,NAMES) preserves the
%   published audit schema while delegating every scalar-output formula to
%   SURROGATES.SURROGATE_METRIC_PRIMITIVES.
%   T: one row per output.
%   Options (name-value): 'IntervalLevels' ([0.50 0.80 0.90 0.95]),
%   'IntervalCriticalValues' (default the Gaussian quantiles of the levels),
%   'PredictiveSDSafeguard' (eps, the smallest predictive standard deviation
%   used), 'RangeTolerance' (1e-12: R2 and NRMSE_range need a larger spread
%   of the truths) and 'RelativeDenominatorTolerance' (1e-12: relative errors
%   use only truths larger in magnitude).
%   Side effects: none.

    parser=inputParser;
    addParameter(parser,'RelativeDenominatorTolerance',1e-12, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>=0);
    addParameter(parser,'RangeTolerance',1e-12, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>=0);
    addParameter(parser,'IntervalLevels',[0.50 0.80 0.90 0.95], ...
        @(x)isnumeric(x)&&isvector(x)&&all(isfinite(x))&&all(x>0&x<1));
    addParameter(parser,'IntervalCriticalValues',[], ...
        @(x)isnumeric(x)&&isvector(x)&&all(isfinite(x))&&all(x>=0));
    addParameter(parser,'PredictiveSDSafeguard',eps, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
    parse(parser,varargin{:});
    relativeTolerance=double(parser.Results.RelativeDenominatorTolerance);
    rangeTolerance=double(parser.Results.RangeTolerance);
    intervalLevels=reshape(double(parser.Results.IntervalLevels),1,[]);
    intervalCriticalValues=reshape( ...
        double(parser.Results.IntervalCriticalValues),1,[]);
    predictiveSDSafeguard=double(parser.Results.PredictiveSDSafeguard);

    truth=double(truth);prediction=double(prediction);variance=double(variance);
    assert(ismatrix(truth)&&isequal(size(truth),size(prediction))&& ...
        isequal(size(truth),size(variance))&&all(isfinite(truth),'all')&& ...
        all(isfinite(prediction),'all'), ...
        'surrogates:surrogate_quality_metrics:Shape', ...
        'Truth, predictive means, and variances must have equal shapes.');
    assert(all(isfinite(variance(:))|isnan(variance(:)))&& ...
        all(variance(isfinite(variance))>=0), ...
        'surrogates:surrogate_quality_metrics:Variance', ...
        'Finite predictive variances must be nonnegative.');
    outputNames=reshape(string(outputNames),[],1);
    nOutput=size(truth,2);
    assert(numel(outputNames)==nOutput, ...
        'surrogates:surrogate_quality_metrics:OutputNames', ...
        'There are %d output names for %d outputs.',numel(outputNames),nOutput);

    OutputIndex=(1:nOutput).';Output=outputNames;
    ObservationCount=repmat(size(truth,1),nOutput,1);
    [R2,RMSE,NRMSE_range,MAE,MeanAbsRelError_percent, ...
        MaximumAbsoluteError,MaximumRelativeError_percent, ...
        MeanPredictiveStd,MeanStandardizedResidual, ...
        SDStandardizedResidual,RMSStandardizedResidual, ...
        PredictiveSDToRMSE,GaussianNLPD,GaussianCRPS]=deal(nan(nOutput,1));
    [RelativeMetricCount,ProbabilisticMetricCount]=deal(zeros(nOutput,1));
    [NRMSEUnavailableReason,RelativeMetricUnavailableReason, ...
        ProbabilisticMetricUnavailableReason]=deal(strings(nOutput,1));
    PredictiveVarianceSafeguard=repmat( ...
        "sigma_raw=sqrt(max(variance,0)); sigma_safe=max(sigma_raw,eps)", ...
        nOutput,1);
    VarianceSafeguardEpsilon=repmat(predictiveSDSafeguard,nOutput,1);
    coverage=nan(nOutput,numel(intervalLevels));

    primitiveArgs={'RelativeDenominatorTolerance',relativeTolerance, ...
        'RangeTolerance',rangeTolerance,'IntervalLevels',intervalLevels, ...
        'PredictiveSDSafeguard',predictiveSDSafeguard};
    if ~isempty(intervalCriticalValues)
        primitiveArgs=[primitiveArgs ...
            {'IntervalCriticalValues',intervalCriticalValues}];
    end
    for j=1:nOutput
        M=surrogates.surrogate_metric_primitives(truth(:,j),prediction(:,j), ...
            variance(:,j),primitiveArgs{:});
        R2(j)=M.R2;RMSE(j)=M.RMSE;NRMSE_range(j)=M.NRMSE_range;
        MAE(j)=M.MAE;MeanAbsRelError_percent(j)=M.MeanAbsRelError_percent;
        MaximumAbsoluteError(j)=M.MaximumAbsoluteError;
        MaximumRelativeError_percent(j)=M.MaximumRelativeError_percent;
        MeanPredictiveStd(j)=M.MeanPredictiveStd;
        MeanStandardizedResidual(j)=M.MeanStandardizedResidual;
        SDStandardizedResidual(j)=M.SDStandardizedResidual;
        RMSStandardizedResidual(j)=M.RMSStandardizedResidual;
        PredictiveSDToRMSE(j)=M.PredictiveSDToRMSE;
        GaussianNLPD(j)=M.GaussianNLPD;GaussianCRPS(j)=M.GaussianCRPS;
        RelativeMetricCount(j)=M.RelativeMetricCount;
        ProbabilisticMetricCount(j)=M.ProbabilisticMetricCount;
        NRMSEUnavailableReason(j)=M.NRMSEUnavailableReason;
        RelativeMetricUnavailableReason(j)=M.RelativeMetricUnavailableReason;
        ProbabilisticMetricUnavailableReason(j)= ...
            M.ProbabilisticMetricUnavailableReason;
        coverage(j,:)=M.CoveragePercent;
    end

    T=table(OutputIndex,Output,ObservationCount,R2,RMSE,NRMSE_range,MAE, ...
        MeanAbsRelError_percent,MaximumAbsoluteError, ...
        MaximumRelativeError_percent,MeanPredictiveStd, ...
        MeanStandardizedResidual,SDStandardizedResidual, ...
        RMSStandardizedResidual,PredictiveSDToRMSE,GaussianNLPD,GaussianCRPS, ...
        RelativeMetricCount,ProbabilisticMetricCount, ...
        NRMSEUnavailableReason,RelativeMetricUnavailableReason, ...
        ProbabilisticMetricUnavailableReason,PredictiveVarianceSafeguard, ...
        VarianceSafeguardEpsilon);
    for levelIndex=1:numel(intervalLevels)
        field=sprintf('Coverage%d_percent',round(100*intervalLevels(levelIndex)));
        T.(field)=coverage(:,levelIndex);
    end
end
