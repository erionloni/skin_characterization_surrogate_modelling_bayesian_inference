function prediction=evaluate_canonical_gp(model,X,cfg)
%EVALUATE_CANONICAL_GP The fixed route's GP mean and its calibrated emulator variance.
%   PREDICTION = surrogates.evaluate_canonical_gp(MODEL, X, CFG) evaluates
%   the fixed GP ensemble MODEL at X (rows of the four material parameters)
%   and returns the mean (GPMean), the raw UQLab variance and standard
%   deviation (kept for reference), the fitted process variance, the local
%   variance shape and the calibrated emulator variance and standard
%   deviation of the frozen development-only calibration
%   (CFG.emulatorErrorCalibration; surrogates.calibrated_emulator_variance),
%   with the calibration's variance formula and the output order.
%   Side effects: none.
%   Computation: UQLab predictions.

    assert(isstruct(cfg)&&isscalar(cfg)&&strcmp(cfg.dataMode,'real')&& ...
        isfield(cfg,'emulatorErrorCalibration')&& ...
        strcmp(cfg.gp.kernel,'Matern-3_2'), ...
        'surrogates:evaluate_canonical_gp:Configuration','Check failed: surrogates:evaluate_canonical_gp:Configuration.');
    [meanPrediction,rawVariance]=surrogates.evaluate(model,X,'gp');
    assert(size(meanPrediction,2)==6&&isequal(size(rawVariance), ...
        size(meanPrediction)), ...
        'surrogates:evaluate_canonical_gp:OutputShape','Check failed: surrogates:evaluate_canonical_gp:OutputShape.');
    processVariance=surrogates.gp_process_variance(model,6);
    [calibratedVariance,localShape]= ...
        surrogates.calibrated_emulator_variance( ...
        rawVariance,processVariance,cfg.emulatorErrorCalibration);
    prediction=struct( ...
        'GPMean',meanPrediction, ...
        'RawUQLabVariance',rawVariance, ...
        'RawUQLabSD',sqrt(rawVariance), ...
        'ProcessVariance',processVariance, ...
        'LocalVarianceShapeH',localShape, ...
        'CalibratedEmulatorVariance',calibratedVariance, ...
        'CalibratedEmulatorSD',sqrt(calibratedVariance), ...
        'VarianceFormulaVersion', ...
            cfg.emulatorErrorCalibration.variance_formula_version, ...
        'OutputOrder',{cfg.emulatorErrorCalibration.output_order});
end
