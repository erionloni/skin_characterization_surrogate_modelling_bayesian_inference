function status=evaluate_generalized_holdout(cfg)
%EVALUATE_GENERALIZED_HOLDOUT Assess the approved generalized surrogates on the held-out cases.
%   STATUS = surrogates.evaluate_generalized_holdout(CFG) predicts the
%   held-out external cases of the dataset CFG.files.dataset with the
%   generalized GP (calibrated emulator variance and raw UQLab variance,
%   surrogates.evaluate_generalized_gp) and PCE (CFG.files.gp, CFG.files.pce),
%   and writes into CFG.paths.surrogateAssessment the residuals, metrics,
%   protocol-stratified and worst-case tables, the support table, the core
%   tables (surrogates.write_generalized_assessment_tables), the validation record
%   CFG.files.validation (surrogate_validation.mat, as on the fixed route)
%   and the status CFG.files.internalHeldoutEvaluationStatus, which STATUS
%   returns. It reads held-out outcomes, so it runs only when
%   CFG.stage2.evaluateExternalHoldout is true, and it fits nothing.
%   Side effects: writes the assessment tables (above).
%   Computation: about a minute (UQLab predictions).

    assert(strcmp(cfg.dataMode,'real_extended'), ...
        'surrogates:evaluate_generalized_holdout:Route', ...
        'The held-out assessment of the generalized surrogates runs on the generalized route.');
    % Held-out outcomes (Y_test) are read only on explicit request (CLN-003 #15).
    assert(logical(cfg.stage2.evaluateExternalHoldout), ...
        'surrogates:evaluate_generalized_holdout:ExternalEvaluationDisabled', ...
        ['The held-out evaluation reads held-out outcomes; it runs only when ' ...
         'external evaluation is requested explicitly.']);
    root=cfg.paths.surrogateAssessment;
    if ~isfolder(root),mkdir(root);end

    fields={'X_train','Y_train','X_test','Y_test','inputNames','outputNames', ...
        'inputBounds','trainCaseIDs','testCaseIDs','dataProvenance'};
    data=utils.load_plain_mat(cfg.files.dataset,fields{:});
    optional={'X_development_all','Y_development_all', ...
        'developmentCaseIDsAll','developmentOutputAvailabilityMask', ...
        'outputTrainingEvidence'};
    inventory=whos('-file',cfg.files.dataset);
    available=intersect(optional,{inventory.name},'stable');
    if ~isempty(available)
        additions=utils.load_plain_mat(cfg.files.dataset,available{:});
        names=fieldnames(additions);
        for i=1:numel(names),data.(names{i})=additions.(names{i});end
    end
    assert(all(isfield(data,fields))&& ...
        isequal(data.inputNames,cfg.realExtended.learningInputNames)&& ...
        isequal(data.outputNames,cfg.realExtended.outputNames)&& ...
        isempty(intersect(double(data.trainCaseIDs(:)), ...
            double(data.testCaseIDs(:)))), ...
        'surrogates:evaluate_generalized_holdout:DatasetContract', ...
        ['The dataset %s must hold the generalized development and held-out ' ...
         'arrays in the route''s input and output order, with disjoint cases; ' ...
         'rerun the step ''dataset''.'],cfg.files.dataset);
    surrogates.validate_generalized_calibration_data_contract(cfg.emulatorErrorCalibration,data);
    gp=surrogates.load_ensemble(cfg.files.gp,'gp');
    pce=surrogates.load_ensemble(cfg.files.pce,'pce');
    surrogates.validate_surrogate_ensemble_scope(gp,data,cfg,'gp');
    surrogates.validate_surrogate_ensemble_scope(pce,data,cfg,'pce');
    V=surrogates.validate_generalized_refit(gp,pce,data,cfg);
    core=surrogates.write_generalized_assessment_tables(V,data,cfg);

    utils.atomic_write_table(fullfile(root,'heldout_residuals.csv'),V.residuals);
    utils.atomic_write_table(fullfile(root,'heldout_residuals_raw_uqlab.csv'), ...
        V.gpRawResiduals);
    utils.atomic_write_table(fullfile(root,'protocol_stratified_validation.csv'), ...
        V.protocolMetrics);
    utils.atomic_write_table(fullfile(root,'worst_validation_cases.csv'),V.worstCases);
    utils.atomic_write_table(fullfile(root,'error_vs_input_summary.csv'), ...
        V.inputErrorRelationships);
    utils.atomic_write_table(fullfile(root,'probe_cycle_validation.csv'), ...
        V.outputGroupMetrics);
    support=output_support_table(data,V);
    utils.atomic_write_table(fullfile(root,'nearest_training_distance.csv'),support);

    utils.atomic_save_struct(cfg.files.validation,struct( ...
        'validation',V,'coreParity',core),'-v7.3');

    status=struct( ...
        'schema_version','real_extended_assessment_status_v3', ...
        'status','complete', ...
        'assessment_role',char(string(V.assessmentRole)), ...
        'assessment_case_count',numel(data.testCaseIDs), ...
        'internal_heldout_case_count',double(string(V.assessmentRole)== ...
            "internal_heldout")*numel(data.testCaseIDs), ...
        'external_test_case_count',double(string(V.assessmentRole)== ...
            "external_test")*numel(data.testCaseIDs), ...
        'prediction_row_count',height(V.predictions), ...
        'canonical_gp_fit_count',0,'canonical_pce_fit_count',0, ...
        'audit_fit_count',0,'automatic_scientific_interpretation',false, ...
        'environment',utils.environment_line());
    utils.atomic_write_json(cfg.files.internalHeldoutEvaluationStatus,status, ...
        'AllowReplace',true);
end

function T=output_support_table(data,V)
    nCase=numel(data.testCaseIDs);nOutput=numel(data.outputNames);
    parts=cell(nOutput,1);
    for outputIndex=1:nOutput
        parts{outputIndex}=table(double(data.testCaseIDs(:)), ...
            repmat(outputIndex,nCase,1), ...
            repmat(string(data.outputNames{outputIndex}),nCase,1), ...
            repmat(double(V.supportTrainingCounts(outputIndex)),nCase,1), ...
            V.testNearestTrainingDistance(:,outputIndex), ...
            V.supportClass(:,outputIndex), ...
            'VariableNames',{'CaseID','OutputIndex','Output', ...
            'DevelopmentTrainingCount','NearestTrainingDistance7D', ...
            'SupportClass'});
    end
    T=vertcat(parts{:});
end
