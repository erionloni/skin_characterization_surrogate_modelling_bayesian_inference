function result = covariance_eigensystem(covariance,varargin)
%COVARIANCE_EIGENSYSTEM Neutral eigensystem of a 4-D standardized covariance.
%   Eigenvalues are ascending. Only negative eigenvalues whose magnitude is
%   no greater than NegativeEigenvalueTolerance*MAX(1,NORM(C,2)) are set to
%   zero. A materially negative eigenvalue makes RESULT.valid false.
%   RESULT = recovery.covariance_eigensystem(COVARIANCE, ...) returns the
%   eigenvalues and eigenvectors of COVARIANCE (4-by-4), the tight and
%   sloppy directions and their two-dimensional projectors, the
%   reconstructed covariance and whether it is valid.
%   Side effects: none.

    options=parse_options(varargin{:});
    validate_options(options);
    assert(isnumeric(covariance)&&isreal(covariance)&& ...
        isequal(size(covariance),[4 4])&&all(isfinite(covariance(:))), ...
        'recovery:covariance_eigensystem:Covariance', ...
        'covariance must be a finite real 4-by-4 matrix.');
    covariance=double(covariance);
    covarianceScale=max(1,norm(covariance,'fro'));
    symmetryError=norm(covariance-covariance.','fro')/covarianceScale;
    symmetricCovariance=(covariance+covariance.')/2;
    psdScale=max(1,norm(symmetricCovariance,2));
    appliedTolerance=options.NegativeEigenvalueTolerance*psdScale;
    [vectors,diagonal]=eig(symmetricCovariance);
    [rawEigenvalues,order]=sort(real(diag(diagonal)),'ascend');
    vectors=real(vectors(:,order));

    result=base_result(covariance,symmetricCovariance,symmetryError, ...
        psdScale,appliedTolerance,rawEigenvalues,options);
    if symmetryError>options.SymmetryTolerance
        result.invalidReason='material_covariance_asymmetry';
        return;
    end
    if any(rawEigenvalues < -appliedTolerance)
        result.invalidReason='material_negative_covariance_eigenvalue';
        result.materialNegativeEigenvalue=true;
        return;
    end

    correctedEigenvalues=rawEigenvalues;
    clamped=correctedEigenvalues<0;
    correctedEigenvalues(clamped)=0;
    signFlips=false(4,1);pivots=zeros(4,1);
    for k=1:4
        [vectors(:,k),signFlips(k),pivots(k)]= ...
            recovery.align_vector_sign(vectors(:,k));
    end
    posteriorSDRatio=sqrt(correctedEigenvalues);
    directionalContraction=1-posteriorSDRatio;
    totalVariance=sum(correctedEigenvalues);
    if totalVariance>0
        varianceFraction=correctedEigenvalues/totalVariance;
    else
        varianceFraction=nan(4,1);
    end
    gapEpsilon=eps(max(1,max(abs(correctedEigenvalues))));
    gaps=zeros(3,1);
    for k=1:3
        gaps(k)=(correctedEigenvalues(k+1)-correctedEigenvalues(k))/ ...
            max(correctedEigenvalues(k+1),gapEpsilon);
    end
    nearAdjacent=gaps<=options.NearDegenerateGap;
    gapBelow=[NaN;gaps];gapAbove=[gaps;NaN];
    nearBelow=[false;nearAdjacent];nearAbove=[nearAdjacent;false];
    axisProjectors=zeros(4,4,4);
    for k=1:4
        axisProjectors(:,:,k)=vectors(:,k)*vectors(:,k).';
    end
    tight2D=vectors(:,1:2)*vectors(:,1:2).';
    sloppy2D=vectors(:,3:4)*vectors(:,3:4).';

    result.valid=true;result.invalidReason='';
    result.correctedEigenvalues=correctedEigenvalues;
    result.tinyNegativeEigenvalueZeroed=clamped;
    result.anyTinyNegativeEigenvalueZeroed=any(clamped);
    result.eigenvectorsSignAligned=vectors;
    result.signFlipApplied=signFlips;
    result.signPivotIndex=pivots;
    result.directionalPosteriorSDRatio=posteriorSDRatio;
    result.directionalContraction=directionalContraction;
    result.posteriorVarianceFraction=varianceFraction;
    result.relativeAdjacentGaps=gaps;
    result.relativeGapDenominatorEpsilon=gapEpsilon;
    result.gapBelow=gapBelow;result.gapAbove=gapAbove;
    result.nearDegenerateAdjacent=nearAdjacent;
    result.nearDegenerateBelow=nearBelow;
    result.nearDegenerateAbove=nearAbove;
    result.tightestDirectionNearDegenerate=nearAdjacent(1);
    result.sloppiestDirectionNearDegenerate=nearAdjacent(3);
    result.anyAdjacentNearDegeneracy=any(nearAdjacent);
    result.axisProjectors=axisProjectors;
    result.tight2DProjector=(tight2D+tight2D.')/2;
    result.sloppy2DProjector=(sloppy2D+sloppy2D.')/2;
    result.covarianceReconstructed=vectors* ...
        diag(correctedEigenvalues)*vectors.';
end

function result=base_result(raw,symmetric,symmetryError,psdScale, ...
        appliedTolerance,rawEigenvalues,options)
    labels={'tightest_direction';'intermediate_direction_1'; ...
        'intermediate_direction_2';'sloppiest_direction'};
    result=struct( ...
        'schemaVersion','posterior_covariance_eigensystem_kernel_v1', ...
        'parameterCoordinateSystem','independent_uniform_prior_mean_sd_standardized', ...
        'dimension',4, ...
        'valid',false, ...
        'invalidReason','', ...
        'covarianceInputRaw',raw, ...
        'covarianceSymmetrized',symmetric, ...
        'covarianceSymmetryRelativeError',symmetryError, ...
        'symmetryTolerance',options.SymmetryTolerance, ...
        'negativeEigenvalueToleranceRelative', ...
            options.NegativeEigenvalueTolerance, ...
        'negativeEigenvalueToleranceScale',psdScale, ...
        'negativeEigenvalueToleranceAppliedAbsolute',appliedTolerance, ...
        'rawEigenvalues',rawEigenvalues, ...
        'materialNegativeEigenvalue',false, ...
        'correctedEigenvalues',nan(4,1), ...
        'tinyNegativeEigenvalueZeroed',false(4,1), ...
        'anyTinyNegativeEigenvalueZeroed',false, ...
        'eigenvectorsSignAligned',nan(4), ...
        'signFlipApplied',false(4,1), ...
        'signPivotIndex',nan(4,1), ...
        'directionRank',(1:4).', ...
        'directionLabels',{labels}, ...
        'directionalPosteriorSDRatio',nan(4,1), ...
        'directionalContraction',nan(4,1), ...
        'posteriorVarianceFraction',nan(4,1), ...
        'relativeAdjacentGaps',nan(3,1), ...
        'relativeGapDenominatorEpsilon',NaN, ...
        'nearDegenerateGapThreshold',options.NearDegenerateGap, ...
        'gapBelow',nan(4,1), ...
        'gapAbove',nan(4,1), ...
        'nearDegenerateAdjacent',false(3,1), ...
        'nearDegenerateBelow',false(4,1), ...
        'nearDegenerateAbove',false(4,1), ...
        'tightestDirectionNearDegenerate',false, ...
        'sloppiestDirectionNearDegenerate',false, ...
        'anyAdjacentNearDegeneracy',false, ...
        'axisProjectors',nan(4,4,4), ...
        'tight2DProjector',nan(4), ...
        'sloppy2DProjector',nan(4), ...
        'covarianceReconstructed',nan(4));
end

function options=parse_options(varargin)
%PARSE_OPTIONS The three thresholds, all required (settings A.7: the recovery's eigendecomposition).
    options=struct('NearDegenerateGap',NaN, ...
        'NegativeEigenvalueTolerance',NaN, ...
        'SymmetryTolerance',NaN);
    assert(mod(numel(varargin),2)==0, ...
        'recovery:covariance_eigensystem:Options', ...
        'Options must be supplied as name/value pairs.');
    for i=1:2:numel(varargin)
        name=lower(char(string(varargin{i})));value=varargin{i+1};
        switch name
            case 'neardegenerategap'
                options.NearDegenerateGap=value;
            case 'negativeeigenvaluetolerance'
                options.NegativeEigenvalueTolerance=value;
            case 'symmetrytolerance'
                options.SymmetryTolerance=value;
            otherwise
                error('recovery:covariance_eigensystem:UnknownOption', ...
                    'Unknown option "%s".',name);
        end
    end
    assert(all(isfinite([options.NearDegenerateGap,options.NegativeEigenvalueTolerance, ...
        options.SymmetryTolerance])), 'recovery:covariance_eigensystem:Thresholds', ...
        ['The eigensystem needs ''NearDegenerateGap'', ''NegativeEigenvalueTolerance'' and ' ...
         '''SymmetryTolerance'' (settings A.7).']);
end

function validate_options(options)
    assert(isscalar(options.NearDegenerateGap)&& ...
        isfinite(options.NearDegenerateGap)&& ...
        options.NearDegenerateGap>=0&&options.NearDegenerateGap<=1, ...
        'recovery:covariance_eigensystem:NearDegenerateGap', ...
        'NearDegenerateGap must be a finite scalar in [0,1].');
    assert(isscalar(options.NegativeEigenvalueTolerance)&& ...
        isfinite(options.NegativeEigenvalueTolerance)&& ...
        options.NegativeEigenvalueTolerance>=0, ...
        'recovery:covariance_eigensystem:NegativeTolerance', ...
        'NegativeEigenvalueTolerance must be nonnegative and finite.');
    assert(isscalar(options.SymmetryTolerance)&& ...
        isfinite(options.SymmetryTolerance)&&options.SymmetryTolerance>=0, ...
        'recovery:covariance_eigensystem:SymmetryTolerance', ...
        'SymmetryTolerance must be nonnegative and finite.');
end
