function result = posterior_covariance_eigensystem(drawsPhysical,bounds,varargin)
%POSTERIOR_COVARIANCE_EIGENSYSTEM Eigensystem from posterior draws.
%   DRAWSPHYSICAL holds the draws in model coordinates (log10(k0) for the
%   permeability; the name is the recorded field of the posterior files).
%   This calculation reads saved draws only; it standardizes each canonical parameter
%   by the mean and standard deviation of its independent uniform prior:
%       Z_i = (theta_i-(a_i+b_i)/2)/((b_i-a_i)/sqrt(12)).
%   The primary covariance is calculated directly as COV(Z). The algebraic
%   relation C_z=12*C_u is recorded as a deterministic consistency check.
%   RESULT = recovery.posterior_covariance_eigensystem(DRAWSPHYSICAL,
%   BOUNDS, ...) returns the standardized covariance, its eigensystem
%   (recovery.covariance_eigensystem) and the consistency errors.
%   Side effects: none.

    options=parse_options(varargin{:});
    canonicalNames={'m3_f_RD','m3_e_RD','log10_k0_RD','Thickness_RD'};
    assert(isnumeric(drawsPhysical)&&isreal(drawsPhysical)&& ...
        ismatrix(drawsPhysical)&&size(drawsPhysical,2)==4&& ...
        size(drawsPhysical,1)>=2&&all(isfinite(drawsPhysical(:))), ...
        'recovery:posterior_covariance_eigensystem:Draws', ...
        'drawsPhysical must be a finite real N-by-4 matrix with N at least two.');
    assert(isnumeric(bounds)&&isreal(bounds)&&isequal(size(bounds),[4 2])&& ...
        all(isfinite(bounds(:)))&&all(bounds(:,2)>bounds(:,1)), ...
        'recovery:posterior_covariance_eigensystem:Bounds', ...
        'bounds must be finite ordered 4-by-2 canonical prior limits.');
    names=cellstr(string(options.ParameterNames));
    assert(isequal(reshape(names,1,[]),canonicalNames), ...
        'recovery:posterior_covariance_eigensystem:ParameterOrder', ...
        'ParameterNames must use the exact canonical four-parameter order.');

    drawsPhysical=double(drawsPhysical);bounds=double(bounds);
    lower=bounds(:,1).';upper=bounds(:,2).';width=upper-lower;
    priorMean=(lower+upper)/2;priorSD=width/sqrt(12);
    standardizedDraws=(drawsPhysical-priorMean)./priorSD;
    unitBoxDraws=(drawsPhysical-lower)./width;
    covarianceStandardized=cov(standardizedDraws,0);
    covarianceUnitBox=cov(unitBoxDraws,0);
    covarianceFromUnitBox=12*covarianceUnitBox;
    directDifference=covarianceStandardized-covarianceFromUnitBox;
    directMaxError=max(abs(directDifference),[],'all');
    directFroError=norm(directDifference,'fro');
    directRelativeError=directFroError/max(norm(covarianceStandardized,'fro'),eps);

    suppliedAvailable=~isempty(options.UnitBoxCovariance);
    if suppliedAvailable
        supplied=double(options.UnitBoxCovariance);
        assert(isreal(supplied)&&isequal(size(supplied),[4 4])&& ...
            all(isfinite(supplied(:))), ...
            'recovery:posterior_covariance_eigensystem:UnitBoxCovariance', ...
            'UnitBoxCovariance must be empty or a finite real 4-by-4 matrix.');
        suppliedDifference=covarianceStandardized-12*supplied;
        suppliedMaxError=max(abs(suppliedDifference),[],'all');
        suppliedFroError=norm(suppliedDifference,'fro');
        suppliedRelativeError=suppliedFroError/ ...
            max(norm(covarianceStandardized,'fro'),eps);
    else
        supplied=nan(4);suppliedMaxError=NaN;
        suppliedFroError=NaN;suppliedRelativeError=NaN;
    end

    eigensystem=recovery.covariance_eigensystem( ...
        covarianceStandardized, ...
        'NearDegenerateGap',options.NearDegenerateGap, ...
        'NegativeEigenvalueTolerance',options.NegativeEigenvalueTolerance, ...
        'SymmetryTolerance',options.SymmetryTolerance);
    result=struct( ...
        'schemaVersion','posterior_covariance_from_certified_draws_v1', ...
        'parameterNames',{canonicalNames}, ...
        'parameterCoordinateSystem', ...
            'independent_uniform_prior_mean_sd_standardized', ...
        'priorBounds',bounds, ...
        'priorMean',priorMean, ...
        'priorSD',priorSD, ...
        'priorCovarianceStandardized',eye(4), ...
        'standardizedDraws',standardizedDraws, ...
        'unitBoxDraws',unitBoxDraws, ...
        'covarianceStandardizedDirect',covarianceStandardized, ...
        'covarianceUnitBoxDirect',covarianceUnitBox, ...
        'covarianceStandardizedFromUnitBoxDirect',covarianceFromUnitBox, ...
        'directUnitBoxConsistencyMaximumAbsoluteError',directMaxError, ...
        'directUnitBoxConsistencyFrobeniusError',directFroError, ...
        'directUnitBoxConsistencyRelativeFrobeniusError',directRelativeError, ...
        'suppliedUnitBoxCovarianceAvailable',suppliedAvailable, ...
        'suppliedUnitBoxCovariance',supplied, ...
        'suppliedUnitBoxConsistencyMaximumAbsoluteError',suppliedMaxError, ...
        'suppliedUnitBoxConsistencyFrobeniusError',suppliedFroError, ...
        'suppliedUnitBoxConsistencyRelativeFrobeniusError', ...
            suppliedRelativeError, ...
        'eigensystem',eigensystem);
end

function options=parse_options(varargin)
    % The thresholds are required (settings A.7), the parameter names are
    % the four canonical ones unless given.
    options=struct('ParameterNames',{{'m3_f_RD','m3_e_RD', ...
        'log10_k0_RD','Thickness_RD'}}, ...
        'NearDegenerateGap',NaN, ...
        'NegativeEigenvalueTolerance',NaN, ...
        'SymmetryTolerance',NaN, ...
        'UnitBoxCovariance',[]);
    assert(mod(numel(varargin),2)==0, ...
        'recovery:posterior_covariance_eigensystem:Options', ...
        'Options must be supplied as name/value pairs.');
    for i=1:2:numel(varargin)
        name=lower(char(string(varargin{i})));value=varargin{i+1};
        switch name
            case 'parameternames'
                options.ParameterNames=value;
            case 'neardegenerategap'
                options.NearDegenerateGap=value;
            case 'negativeeigenvaluetolerance'
                options.NegativeEigenvalueTolerance=value;
            case 'symmetrytolerance'
                options.SymmetryTolerance=value;
            case 'unitboxcovariance'
                options.UnitBoxCovariance=value;
            otherwise
                error('recovery:posterior_covariance_eigensystem:UnknownOption', ...
                    'Unknown option "%s".',name);
        end
    end
end
