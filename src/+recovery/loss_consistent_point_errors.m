function metrics = loss_consistent_point_errors( ...
        truth,posteriorMean,posteriorMedian,scale)
%LOSS_CONSISTENT_POINT_ERRORS Deterministic L1/L2 posterior point errors.
%   Absolute-error quantities use the posterior median. Squared-error
%   quantities use the posterior mean (posterior expected response). Optional
%   normalized quantities are unavailable where SCALE is not finite/positive.
%   METRICS = recovery.loss_consistent_point_errors(TRUTH, POSTERIORMEAN,
%   POSTERIORMEDIAN, SCALE) returns the signed and absolute errors of the
%   median, the squared error of the mean and, where SCALE is positive,
%   their normalized versions.
%   Side effects: none.

    if nargin<4||isempty(scale),scale=nan(size(truth));end
    truth=double(truth);posteriorMean=double(posteriorMean);
    posteriorMedian=double(posteriorMedian);scale=double(scale);
    assert(isequal(size(truth),size(posteriorMean),size(posteriorMedian)), ...
        'recovery:loss_consistent_point_errors:Shape', ...
        'Truth, posterior mean, and posterior median must have equal size.');
    if isscalar(scale),scale=repmat(scale,size(truth));end
    assert(isequal(size(scale),size(truth)), ...
        'recovery:loss_consistent_point_errors:ScaleShape', ...
        'The scale must be a scalar or have the size of the truth.');

    signedMean=posteriorMean-truth;
    signedMedian=posteriorMedian-truth;
    normalizedAbsolute=nan(size(truth));normalizedSquared=nan(size(truth));
    usable=isfinite(scale)&scale>0;
    normalizedAbsolute(usable)=abs(signedMedian(usable))./scale(usable);
    normalizedSquared(usable)=(signedMean(usable)./scale(usable)).^2;
    metrics=struct( ...
        'signedErrorFromPosteriorMean',signedMean, ...
        'signedErrorFromPosteriorMedian',signedMedian, ...
        'absoluteErrorFromPosteriorMedian',abs(signedMedian), ...
        'squaredErrorFromPosteriorMean',signedMean.^2, ...
        'normalizedAbsoluteErrorFromPosteriorMedian',normalizedAbsolute, ...
        'normalizedSquaredErrorFromPosteriorMean',normalizedSquared, ...
        'absoluteLossPointEstimator','posterior_median', ...
        'squaredLossPointEstimator','posterior_mean');
end
