function similarity = subspace_similarity(firstProjector,secondProjector,rankValue)
%SUBSPACE_SIMILARITY Projector similarity TRACE(P1*P2)/R in [0,1].
%   SIMILARITY = recovery.subspace_similarity(FIRSTPROJECTOR,
%   SECONDPROJECTOR, RANKVALUE) for two rank-RANKVALUE orthogonal
%   projectors: 1 for the same subspace, 0 for orthogonal ones.
%   Side effects: none.

    validate_projector_pair(firstProjector,secondProjector);
    firstProjector=(double(firstProjector)+double(firstProjector).')/2;
    secondProjector=(double(secondProjector)+double(secondProjector).')/2;
    if nargin<3||isempty(rankValue)
        rankValue=round((trace(firstProjector)+trace(secondProjector))/2);
    end
    n=size(firstProjector,1);
    assert(isscalar(rankValue)&&isfinite(rankValue)&& ...
        rankValue==fix(rankValue)&&rankValue>=1&&rankValue<=n, ...
        'recovery:subspace_similarity:Rank', ...
        'rankValue must be a positive integer no larger than the matrix size.');
    scale=max(1,sqrt(n));tolerance=1e-10*scale;
    assert(norm(firstProjector^2-firstProjector,'fro')<=tolerance&& ...
        norm(secondProjector^2-secondProjector,'fro')<=tolerance&& ...
        abs(trace(firstProjector)-rankValue)<=tolerance&& ...
        abs(trace(secondProjector)-rankValue)<=tolerance, ...
        'recovery:subspace_similarity:Projector', ...
        'Inputs must be rank-r orthogonal projectors.');
    similarity=trace(firstProjector*secondProjector)/rankValue;
    rangeTolerance=64*eps(max(1,abs(similarity)));
    assert(similarity>=-rangeTolerance&&similarity<=1+rangeTolerance, ...
        'recovery:subspace_similarity:NumericalRange', ...
        'Computed subspace similarity is materially outside [0,1].');
    if similarity<0,similarity=0;end
    if similarity>1,similarity=1;end
end

function validate_projector_pair(firstProjector,secondProjector)
    assert(isnumeric(firstProjector)&&isreal(firstProjector)&& ...
        ismatrix(firstProjector)&&size(firstProjector,1)== ...
        size(firstProjector,2)&&all(isfinite(firstProjector(:)))&& ...
        isnumeric(secondProjector)&&isreal(secondProjector)&& ...
        isequal(size(firstProjector),size(secondProjector))&& ...
        all(isfinite(secondProjector(:))), ...
        'recovery:subspace_similarity:Shape', ...
        'Projectors must be finite real square matrices of equal size.');
    tolerance=1e-10*max([1 norm(firstProjector,'fro') ...
        norm(secondProjector,'fro')]);
    assert(norm(firstProjector-firstProjector.','fro')<=tolerance&& ...
        norm(secondProjector-secondProjector.','fro')<=tolerance, ...
        'recovery:subspace_similarity:Symmetry', ...
        'Projectors must be symmetric within numerical tolerance.');
end
