function A=availability_table(comparison,flags)
%AVAILABILITY_TABLE One row per cell (its first parameter row) and whether it counts in the certified-only values.
    columns={'CaseID','Scenario','Design', ...
        'ConditionCode','ConditionID','ConditionRole','CanonicalReference', ...
        'Scheduled','ArtifactSource','CellID','ArtifactLoaded', ...
        'CertificationStatus','FailureReason','ErrorIdentifier', ...
        'CertifiedSampler','CertifiedReplicate','CertifiedStepCount', ...
        'CertificationMechanism', ...
        'PosteriorProvenanceRunRelative', ...
        'CertificationProvenanceRunRelative'};
    A=comparison(comparison.ParameterIndex==1,columns);
    A.CanonicalReference=logical(A.CanonicalReference);
    A.Scheduled=logical(A.Scheduled);
    A.ArtifactLoaded=logical(A.ArtifactLoaded);
    A.InCertifiedOnlyValues=reshape(logical(flags),[],1)&A.ArtifactLoaded;
end

function draws=extract_draws(artifact,condition,n)
    assert(isstruct(artifact)&&isscalar(artifact), ...
        'recovery:summarize_conditional_inversion:Draws', ...
        'A loaded posterior artifact is required.');
    if isfield(artifact,'drawsCanonicalCoordinates')
        raw=double(artifact.drawsCanonicalCoordinates);
    elseif isfield(artifact,'drawsPhysical')
        % The canonical condition A and lightweight injected fixtures use this name.
        raw=double(artifact.drawsPhysical);
    else
        error('recovery:summarize_conditional_inversion:Draws', ...
            'Loaded artifact lacks canonical coordinate rows.');
    end
    free=condition.freeParameterIndices;
    assert(~isempty(raw)&&all(isfinite(raw),'all')&& ...
        ismember(size(raw,2),[numel(free) n]), ...
        'recovery:summarize_conditional_inversion:Draws', ...
        'Retained draws must contain either free coordinates or all four coordinates.');
    draws=nan(size(raw,1),n);
    if size(raw,2)==n,draws=raw;else,draws(:,free)=raw;end
end

function [sampler,replicate,steps,mechanism,posterior,certification]= ...
        provenance(artifact,status,cfg)
    sampler="";replicate=NaN;steps=NaN;mechanism="";
    posterior="";certification="";
    if ~status.loaded,return;end
    assert(isfield(artifact,'certification')&& ...
        isfield(artifact.certification,'provider')&& ...
        isfield(artifact.certification,'certificationMechanism')&& ...
        isfield(artifact,'paths')&&isfield(artifact.paths,'posteriorPath')&& ...
        isfield(artifact,'certificationPath'), ...
        'recovery:summarize_conditional_inversion:Provenance', ...
        'Loaded posterior lacks certification or run-relative path provenance.');
    provider=artifact.certification.provider;
    sampler=string(provider.sampler);replicate=double(provider.replicateID);
    steps=double(provider.stepCount);
    mechanism=string(artifact.certification.certificationMechanism);
    posterior=relative(artifact.paths.posteriorPath,cfg);
    certification="";
    if ~isempty(artifact.certificationPath)
        certification=relative(artifact.certificationPath,cfg);
    end
end

function value=relative(pathValue,cfg)
%RELATIVE A path below the run root, relative to it; a shipped file, relative to the repository.
    pathValue=utils.absolute_path(pathValue);
    roots={utils.absolute_path(cfg.paths.runRoot)};
    if isfield(cfg,'native')&&isstruct(cfg.native)&&isfield(cfg.native,'shippedDraws')&& ...
            ~isempty(cfg.native.shippedDraws)
        roots{end+1}=fileparts(utils.absolute_path(cfg.native.shippedDraws.results));
    end
    for k=1:numel(roots)
        prefix=[roots{k} filesep];
        if startsWith(lower(pathValue),lower(prefix))
            value=string(strrep(pathValue(numel(prefix)+1:end),'\','/'));
            return
        end
    end
    error('recovery:summarize_conditional_inversion:PathEscape', ...
        'Posterior provenance path %s lies outside the run and the shipped results.',pathValue);
end

function status=normalize_status(status)
    required={'loaded','state','reason','errorIdentifier'};
    assert(isstruct(status)&&isscalar(status)&&all(isfield(status,required)), ...
        'recovery:summarize_conditional_inversion:LoaderStatus', ...
        'Artifact loader returned an invalid status record.');
    status.loaded=logical(status.loaded);
end

function status=not_scheduled_status()
    status=struct('loaded',false,'state','not_scheduled', ...
        'reason','not_scheduled_by_supplementary_scientific_design', ...
        'errorIdentifier','');
end

function status=skipped_status(reason)
    status=struct('loaded',false,'state','not_run', ...
        'reason',reason,'errorIdentifier','');
end

function [detail,summary]=matched_tables(A,caseIDs,scenarios,conditions)
%MATCHED_TABLES The matched cohorts of each scenario: every condition against the reference, and all together.
    reference=conditions([conditions.canonicalReference]).code;
    definitions=cell(0,3);
    for s=1:numel(scenarios)
        scheduled=conditions(~[conditions.canonicalReference]& ...
            cellfun(@(x) ismember(scenarios{s},x),{conditions.scheduledScenarios}));
        codes={scheduled.code};
        if numel(codes)>1
            definitions(end+1,:)={sprintf('%s_all_%s',scenarios{s}, ...
                strjoin([{reference} codes],'_')),scenarios{s},[{reference} codes]}; %#ok<AGROW>
        end
        for k=1:numel(codes)
            definitions(end+1,:)={sprintf('%s_%s_vs_%s',scenarios{s},reference,codes{k}), ...
                scenarios{s},{reference,codes{k}}}; %#ok<AGROW>
        end
    end
    rows=cell(size(definitions,1)*numel(caseIDs),1);cursor=0;
    summaries=cell(size(definitions,1),1);
    for d=1:size(definitions,1)
        analysisID=string(definitions{d,1});scenario=string(definitions{d,2});
        required=string(definitions{d,3});includedIDs=[];
        for c=1:numel(caseIDs)
            cursor=cursor+1;hit=A.CaseID==caseIDs(c)&A.Scenario==scenario& ...
                ismember(A.ConditionCode,required);
            one=A(hit,:);found=sort(one.ConditionCode)==sort(required).';
            complete=height(one)==numel(required)&&all(found,'all')&& ...
                all(one.ArtifactLoaded);
            reason="included_all_required_conditions_certified";
            if complete&&any(string(one.CertificationMechanism)~= ...
                    "CERTIFIED_AIES_REPLICATE_AGREEMENT")
                reason="included_all_required_providers_available";
            end
            if ~complete
                missing=one.ConditionCode(~one.ArtifactLoaded);
                if height(one)<numel(required)
                    missing=setdiff(required,one.ConditionCode,'stable');
                end
                if isempty(missing),missing=required;end
                reason="excluded_missing_or_unresolved_conditions:"+ ...
                    strjoin(missing,";");
            else
                includedIDs(end+1)=caseIDs(c); %#ok<AGROW>
            end
            rows{cursor}=table(analysisID,scenario,strjoin(required,"|"), ...
                double(caseIDs(c)),logical(complete),reason, ...
                'VariableNames',{'AnalysisID','Scenario', ...
                'RequiredConditions','CaseID','Included','Reason'});
        end
        excluded=setdiff(caseIDs,includedIDs,'stable');
        summaries{d}=table(analysisID,scenario,strjoin(required,"|"), ...
            numel(caseIDs), ...
            numel(includedIDs),strjoin(string(includedIDs),";"), ...
            strjoin(string(excluded),";"), ...
            'VariableNames',{'AnalysisID','Scenario','RequiredConditions', ...
            'ExpectedCaseCount','MatchedCaseCount', ...
            'IncludedCaseIDs','ExcludedCaseIDs'});
    end
    detail=vertcat(rows{:});summary=vertcat(summaries{:});
end

function [ids,truth]=case_data(cases)
    assert(isstruct(cases)&&~isempty(cases)&&isfield(cases,'truth'), ...
        'recovery:summarize_conditional_inversion:Cases', ...
        'A nonempty configured set of case records with truth values is required.');
    if isfield(cases,'case_id')
        ids=reshape(double([cases.case_id]),1,[]);
    elseif isfield(cases,'caseID')
        ids=reshape(double([cases.caseID]),1,[]);
    else
        error('recovery:summarize_conditional_inversion:Cases', ...
            'Case records lack their CaseIDs.');
    end
    truth=vertcat(cases.truth);
    assert(isequal(size(truth),[numel(cases) 4])&&all(isfinite(truth),'all'), ...
        'recovery:summarize_conditional_inversion:Truth', ...
        'Each case must contain four finite truth parameters.');
end
