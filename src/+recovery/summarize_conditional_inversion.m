function summary = summarize_conditional_inversion(cfg,prep,notRun)
%SUMMARIZE_CONDITIONAL_INVERSION The canonical and conditional posteriors of the conditional cases, side by side.
%   SUMMARY = recovery.summarize_conditional_inversion(CFG, PREP) reads, for
%   every case of the prepared conditional campaign PREP
%   (inversion.prepare_conditional_campaign), every scenario of the campaign
%   (in the order its rows first name them) and every condition of the
%   settings' table (A.9, in its order), the posterior of the cell's selected
%   provider: the reference (the condition that fixes nothing, the canonical
%   all_six cell) from the canonical campaign of this run or from the
%   shipped canonical results; a cell this campaign ran from the campaign
%   (certified, or its healthy completed fallback,
%   inversion.load_conditional_available_posterior); a
%   reused cell from the shipped conditional results (conditions of the
%   table that the campaign does not run have no rows). The rows of shipped
%   cells (reused cells, and the reference when the canonical cells are the
%   shipped ones) are taken from the shipped comparison as they are, so that
%   their values stay digit for digit; their label and description are those
%   of the settings. Every condition has rows for every scenario and
%   parameter: metrics of fixed parameters, of cells that are not scheduled
%   and of cells without a posterior are NaN, never zero.
%   SUMMARY = recovery.summarize_conditional_inversion(CFG, PREP, NOTRUN)
%   treats the cells to run whose CellIDs NOTRUN lists as unavailable, "not
%   run in this campaign" (a partial campaign published as an example).
%   The availability holds one row per cell, with InCertifiedOnlyValues:
%   whether the cell counts in the certified-only values (a certified cell
%   of this run; for the shipped cells as their status tables record, a
%   reused cell as the shipped conditional status table records it when
%   the summary is made: a campaign prepared earlier keeps its actions).
%   The matched cohorts, per scenario of the campaign: each condition of the
%   scenario against the reference and, when the scenario has more than one
%   condition, all of them together; a case counts when every required cell
%   has a posterior (certified or healthy fallback). The matched summary
%   gives next to each count and case list those of the cells that count in
%   the certified-only values (<column>_certified_only).
%   Side effects: none.

    if nargin<3,notRun={};end
    grid=prep.grid;
    C=cfg.conditionalInversion;
    assert(isstruct(grid)&&isscalar(grid)&& ...
        grid.cellCount==double(C.expectedNewCellCount)&& ...
        numel(grid.cells)==grid.cellCount, ...
        'recovery:summarize_conditional_inversion:Grid', ...
        'The complete conditional grid of the settings (A.9) is required.');
    [caseIDs,caseTruth]=case_data(prep.cases);
    assert(isequal(caseIDs,reshape(double(C.caseIDs),1,[]))&& ...
        numel(cfg.paramNames)==4&&isequal(size(cfg.paramBounds),[4 2]), ...
        'recovery:summarize_conditional_inversion:Configuration', ...
        'The configured conditional cases and the four-parameter model are required.');
    % The reference and the conditions that the campaign runs in some scenario.
    conditions=inversion.conditional_inversion_conditions(cfg);
    conditions=conditions([conditions.canonicalReference]| ...
        ~cellfun(@isempty,{conditions.scheduledScenarios}));
    reference=conditions([conditions.canonicalReference]);
    scenarios=reference.scheduledScenarios;
    shipped=shipped_comparison(cfg,prep);
    shippedStatus=shipped_status(cfg,prep);
    parts=cell(numel(caseIDs)*numel(scenarios)*numel(conditions),1);
    flags=false(size(parts));cursor=0;
    for c=1:numel(caseIDs)
        for s=1:numel(scenarios)
            scenario=inversion.scenario_registry(scenarios{s});
            for q=1:numel(conditions)
                cursor=cursor+1;
                condition=conditions(q);
                scheduled=ismember(scenario.tag,condition.scheduledScenarios);
                record=cell_record(grid,caseIDs(c),caseTruth(c,:),scenario,condition,scheduled);
                [parts{cursor},flags(cursor)]=cell_rows(cfg,prep,record,condition,scheduled, ...
                    caseTruth(c,:),shipped,shippedStatus,notRun);
            end
        end
    end
    comparison=vertcat(parts{:});
    availability=availability_table(comparison,flags);
    expectedAvailabilityRows=numel(caseIDs)*numel(scenarios)*numel(conditions);
    assert(height(comparison)==expectedAvailabilityRows*numel(cfg.paramNames)&& ...
        height(availability)==expectedAvailabilityRows, ...
        'recovery:summarize_conditional_inversion:Rows', ...
        'The comparison must hold every condition and parameter of every case and scenario.');
    [matchedCohorts,matchedSummary]=matched_tables(availability,caseIDs,scenarios,conditions);
    % The matched cohorts of the cells that count in the certified-only values.
    certifiedOnly=availability;
    certifiedOnly.ArtifactLoaded=certifiedOnly.ArtifactLoaded&certifiedOnly.InCertifiedOnlyValues;
    [~,certifiedSummary]=matched_tables(certifiedOnly,caseIDs,scenarios,conditions);
    matchedSummary=utils.add_certified_only(matchedSummary,certifiedSummary, ...
        {'AnalysisID','Scenario','RequiredConditions','ExpectedCaseCount'});
    summary=struct( ...
        'schemaVersion', ...
            'conditional_inversion_summary_v5_settings_conditions', ...
        'comparison',comparison, ...
        'availability',availability,'matchedCohorts',matchedCohorts, ...
        'matchedSummary',matchedSummary, ...
        'newConditionalCellCount',grid.cellCount, ...
        'canonicalPosteriorCopiesCreated',0, ...
        'mcmcRunsPerformedBySummary',0, ...
        'missingAndUnresolvedRetainedExplicitly',true);
end

function [T,flag]=cell_rows(cfg,prep,record,condition,scheduled,truth,shipped,shippedStatus,notRun)
%CELL_ROWS The comparison rows of one cell and whether it counts in the certified-only values.
    flag=false;
    if ~scheduled
        T=parameter_rows(record,condition,false,'not_scheduled',struct([]), ...
            not_scheduled_status(),truth,cfg);
        return
    end
    if condition.canonicalReference
        barrier=prep.canonicalBarrier;
        baseline=barrier.records(strcmp({barrier.records.cellID},record.cellID));
        assert(isscalar(baseline), ...
            'recovery:summarize_conditional_inversion:Baseline', ...
            'The canonical baseline %s is not in the prepared campaign.',record.cellID);
        flag=logical(baseline.inCertifiedOnlyValues);
        if strcmp(barrier.source,'shipped')
            T=shipped_rows(shipped,record,condition);
            if ~isempty(T),return;end
            [artifact,status]=study.load_shipped_posterior(cfg,record);
        else
            [artifact,status]=inversion.load_certified_posterior(cfg,record);
        end
        T=parameter_rows(record,condition,true,'canonical_stage04_all_six_reference', ...
            artifact,normalize_status(status),truth,cfg);
        return
    end
    action=prep.actions(strcmp({prep.actions.cellID},record.cellID));
    assert(isscalar(action), ...
        'recovery:summarize_conditional_inversion:CellBinding', ...
        'The conditional cell %s has no action in the prepared campaign.',record.cellID);
    switch action.action
        case 'reuse'
            T=shipped_rows(shipped,record,condition);
            assert(~isempty(T), ...
                'recovery:summarize_conditional_inversion:ShippedCell', ...
                'The shipped comparison lacks the reused cell %s.',record.cellID);
            flag=shipped_flag(shippedStatus,record,condition);
        case 'skip'
            T=parameter_rows(record,condition,true,'supplementary_conditional_inversion', ...
                struct([]),skipped_status(action.reason),truth,cfg);
        otherwise
            if ismember(record.cellID,notRun)
                T=parameter_rows(record,condition,true,'supplementary_conditional_inversion', ...
                    struct([]),skipped_status('not run in this campaign'),truth,cfg);
                return
            end
            [artifact,status]=inversion.load_conditional_available_posterior(cfg,record);
            status=normalize_status(status);
            % A cell of this campaign has a posterior when it is certified or
            % has a healthy completed request (the rule of the thesis's cells);
            % only a certified one counts in the certified-only values.
            flag=status.loaded&&logical(status.certified);
            T=parameter_rows(record,condition,true,'supplementary_conditional_inversion', ...
                artifact,status,truth,cfg);
    end
end

function shipped=shipped_comparison(cfg,prep)
%SHIPPED_COMPARISON The comparison of the shipped conditional results, when shipped rows are used.
%   Read when the canonical cells are the shipped ones (their reference rows)
%   or cells are reused; empty otherwise.
    shipped=[];
    if ~(strcmp(prep.canonicalBarrier.source,'shipped')|| ...
            any(strcmp({prep.actions.action},'reuse')))
        return
    end
    file=fullfile(cfg.native.shippedDraws.results,'fixed','07_conditional_inversion','data', ...
        'reports','conditional_inversion_comparison.csv');
    if ~isfile(file),return;end
    shipped=utils.read_csv_table(file,{'Scenario','ScenarioLabel','Design','ConditionCode', ...
        'ConditionID','ConditionLabel','ConditionRole','ArtifactSource','CellID','Parameter', ...
        'ParameterRole','CertificationStatus','FailureReason','ErrorIdentifier', ...
        'CertifiedSampler','CertificationMechanism','PosteriorProvenanceRunRelative', ...
        'CertificationProvenanceRunRelative'});
    assert(isequal(shipped.Properties.VariableNames,[comparison_names() alias_names()]), ...
        'recovery:summarize_conditional_inversion:ShippedColumns', ...
        'The shipped comparison %s does not have the columns of the comparison.',file);
end

function S=shipped_status(cfg,prep)
%SHIPPED_STATUS The shipped conditional status table, when cells are reused; empty otherwise.
    S=[];
    if ~any(strcmp({prep.actions.action},'reuse')),return;end
    file=fullfile(cfg.native.shippedDraws.results,'fixed','07_conditional_inversion','data', ...
        'cell_status.csv');
    assert(isfile(file),'recovery:summarize_conditional_inversion:ShippedStatus', ...
        'The reused cells need the shipped status table %s.',file);
    S=utils.read_csv_table(file,{'Scenario','Design','Condition','Status','ProviderSampler', ...
        'Reason'});
end

function flag=shipped_flag(S,record,condition)
%SHIPPED_FLAG Whether a reused cell counts in the certified-only values, as the shipped status table records it.
    hit=S.CaseID==double(record.caseID)&S.Scenario==string(record.scenario)& ...
        S.Design==string(record.design)&S.Condition==string(condition.id);
    assert(nnz(hit)==1,'recovery:summarize_conditional_inversion:ShippedStatus', ...
        'The shipped status table does not list the reused cell %s once.',record.cellID);
    flag=logical(S.InCertifiedOnlyValues(hit));
end

function T=shipped_rows(shipped,record,condition)
%SHIPPED_ROWS The shipped comparison rows of one cell, with the condition's label of the settings.
    T=[];
    if isempty(shipped),return;end
    hit=shipped.CaseID==double(record.caseID)&shipped.Scenario==string(record.scenario)& ...
        shipped.Design==string(record.design)&shipped.ConditionID==string(condition.id);
    if ~any(hit),return;end
    T=shipped(hit,:);
    assert(height(T)==4&&isequal(T.ParameterIndex.',1:4), ...
        'recovery:summarize_conditional_inversion:ShippedRows', ...
        'The shipped comparison does not hold the four parameter rows of %s.',record.cellID);
    T.ConditionCode(:)=string(condition.code);
    T.ConditionLabel(:)=string(condition.label);
end

function record=cell_record(grid,caseID,truth,scenario, ...
        condition,scheduled)
    if condition.canonicalReference
        cellID=sprintf('case_%d|%s|all_six',caseID,scenario.tag);
        cellIndex=NaN;
    elseif scheduled
        hit=[grid.cells.caseID]==caseID& ...
            strcmp({grid.cells.scenario},scenario.tag)& ...
            strcmp({grid.cells.conditionID},condition.id);
        assert(nnz(hit)==1, ...
            'recovery:summarize_conditional_inversion:CellBinding', ...
            'Scheduled condition does not bind to exactly one grid cell.');
        source=grid.cells(hit);cellID=source.cellID;cellIndex=source.cellIndex;
    else
        cellID=sprintf('case_%d|%s|all_six|condition_%s', ...
            caseID,scenario.tag,condition.id);
        cellIndex=NaN;
    end
    record=struct('cellIndex',cellIndex,'cellID',cellID, ...
        'caseID',caseID,'case_id',caseID,'truth',truth, ...
        'scenario',scenario.tag,'scenarioLabel',scenario.label, ...
        'primaryScenario',scenario.primaryScientificScenario, ...
        'design','all_six','designLabel','All six', ...
        'conditionCode',condition.code,'conditionID',condition.id, ...
        'conditionLabel',condition.label, ...
        'conditionRole',condition.role, ...
        'freeParameterIndices',condition.freeParameterIndices, ...
        'fixedParameterIndices',condition.fixedParameterIndices, ...
        'fixedValueSource',condition.fixedValueSource);
end

function T=parameter_rows(record,condition,scheduled,source,artifact,status, ...
        truth,cfg)
    n=4;names=string(cfg.paramNames(:));truth=reshape(double(truth),[],1);
    bounds=double(cfg.paramBounds);priorWidth=bounds(:,2)-bounds(:,1);
    priorSD=priorWidth/sqrt(12);
    [meanValue,medianValue,sdValue,normalizedSD,sdOverPriorRange, ...
        contraction,q025,q25,q75,q975,width50,width95,covered50,covered95, ...
        meanError,medianError]=deal(nan(n,1));
    free=false(n,1);free(condition.freeParameterIndices)=true;
    fixed=false(n,1);fixed(condition.fixedParameterIndices)=true;
    fixedValue=nan(n,1);fixedValue(fixed)=truth(fixed);
    if status.loaded
        draws=extract_draws(artifact,condition,n);
        for j=find(free).'
            x=draws(:,j);meanValue(j)=mean(x);medianValue(j)=median(x);
            sdValue(j)=std(x,0);normalizedSD(j)=sdValue(j)/priorSD(j);
            sdOverPriorRange(j)=sdValue(j)/priorWidth(j);
            contraction(j)=1-normalizedSD(j);
            quantiles=quantile(x,[0.025 0.25 0.75 0.975]);
            q025(j)=quantiles(1);q25(j)=quantiles(2);
            q75(j)=quantiles(3);q975(j)=quantiles(4);
            width50(j)=q75(j)-q25(j);width95(j)=q975(j)-q025(j);
            covered50(j)=double(truth(j)>=q25(j)&&truth(j)<=q75(j));
            covered95(j)=double(truth(j)>=q025(j)&&truth(j)<=q975(j));
            meanError(j)=abs(meanValue(j)-truth(j))/priorWidth(j);
            medianError(j)=abs(medianValue(j)-truth(j))/priorWidth(j);
        end
    end
    [sampler,replicate,steps,mechanism, ...
        posteriorPath,certificationPath]=provenance(artifact,status,cfg);
    parameterRole=repmat("FREE",n,1);
    parameterRole(fixed)="FIXED_TO_TRUTH";
    if ~scheduled,parameterRole(:)="NOT_SCHEDULED";end
    T=table(repmat(double(record.caseID),n,1), ...
        repmat(string(record.scenario),n,1), ...
        repmat(string(record.scenarioLabel),n,1), ...
        repmat(string(record.design),n,1), ...
        repmat(string(condition.code),n,1), ...
        repmat(string(condition.id),n,1), ...
        repmat(string(condition.label),n,1), ...
        repmat(string(condition.role),n,1), ...
        repmat(logical(condition.canonicalReference),n,1), ...
        repmat(logical(scheduled),n,1), ...
        repmat(string(source),n,1),repmat(string(record.cellID),n,1), ...
        (1:n).',names,parameterRole,free,fixed,fixedValue,truth, ...
        meanValue,medianValue,sdValue,normalizedSD,sdOverPriorRange, ...
        contraction,q025,q25,q75,q975,width50,width95,covered50,covered95, ...
        meanError,medianError, ...
        repmat(logical(status.loaded),n,1), ...
        repmat(string(status.state),n,1), ...
        repmat(string(status.reason),n,1), ...
        repmat(string(status.errorIdentifier),n,1), ...
        repmat(string(sampler),n,1),repmat(replicate,n,1), ...
        repmat(steps,n,1),repmat(string(mechanism),n,1), ...
        repmat(string(posteriorPath),n,1), ...
        repmat(string(certificationPath),n,1), ...
        'VariableNames',comparison_names());
    % Plain publication aliases are retained alongside unit-explicit names.
    T.FixedValue=T.FixedValuePhysical;
    T.Truth=T.TruthPhysical;
    T.Mean=T.PosteriorMeanPhysical;
    T.Median=T.PosteriorMedianPhysical;
    T.SD=T.PosteriorSDPhysical;
    T.Q025=T.CI025Physical;
    T.Q25=T.CI25Physical;
    T.Q75=T.CI75Physical;
    T.Q975=T.CI975Physical;
    T.CertificationLevel=T.CertifiedStepCount;
end

