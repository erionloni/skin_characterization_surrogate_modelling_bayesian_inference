function T = posterior_parameter_rows(cellRecord,A,P,status)
%POSTERIOR_PARAMETER_ROWS The posterior summary of one inversion cell, one row per parameter.
%   T = recovery.posterior_parameter_rows(CELLRECORD, A, P, STATUS) returns
%   the rows of posterior_parameter_cells.csv (the recovery's summary of
%   every cell, recovery.summarize_posterior_grid) for the cell CELLRECORD
%   (caseID, scenario, scenarioLabel, primaryScenario, design, designLabel,
%   cellID) over the parameter space P: from the provider's draws A
%   (drawsPhysical, truth and its provider record) the truth, posterior
%   mean, median and SD, the SD normalized by the prior SD, the contraction,
%   the central 50 % and 95 % intervals and their widths, whether the truth
%   lies inside them, the recovery errors (normalized by the prior width,
%   recovery.loss_consistent_point_errors), the provider and the status
%   STATUS (state, reason); for a cell without a posterior (A empty or
%   STATUS.loaded false) the same rows with NaN values. Model coordinates
%   (log10 of the permeability); the prior is uniform on P.bounds.
%   Side effects: none.

    priorWidth=P.bounds(:,2)-P.bounds(:,1);
    priorSD=priorWidth/sqrt(12);
    if isempty(A)||~logical(status.loaded)
        T=missing_parameter_rows(cellRecord,P,status,P.M);
    else
        T=parameter_rows(cellRecord,A,P,priorWidth,priorSD,status);
    end
end

function T=parameter_rows(cellRecord,A,P,priorWidth,priorSD,status)
    draws=double(A.drawsPhysical);truth=double(A.truth(:));
    assert(size(draws,2)==P.M&&numel(truth)==P.M, ...
        'recovery:summarize_posterior_grid:PosteriorShape', ...
        'A saved posterior needs draws and a true value for each of the %d parameters.',P.M);
    meanValue=mean(draws,1).';medianValue=median(draws,1).';
    sdValue=std(draws,0,1).';
    q=quantile(draws,[0.025 0.25 0.75 0.975],1).';
    normalizedSD=sdValue./priorSD;
    contraction=1-normalizedSD;
    covered=truth>=q(:,1)&truth<=q(:,4);
    covered50=truth>=q(:,2)&truth<=q(:,3);
    meanNormalizedError=abs(meanValue-truth)./priorWidth;
    medianNormalizedError=abs(medianValue-truth)./priorWidth;
    intervalWidth=q(:,4)-q(:,1);
    [sampler,replicate,steps]=provider_axes(A);
    mechanism=certification_mechanism(A);
    semantics=design_study.design_semantics(cellRecord.design);
    n=P.M;
    T=table(repmat(double(cellRecord.caseID),n,1), ...
        repmat(string(cellRecord.scenario),n,1), ...
        repmat(string(cellRecord.scenarioLabel),n,1), ...
        repmat(logical(cellRecord.primaryScenario),n,1), ...
        repmat(string(cellRecord.design),n,1), ...
        repmat(string(cellRecord.designLabel),n,1), ...
        repmat(string(semantics.role),n,1), ...
        repmat(string(semantics.comparison_class),n,1), ...
        repmat(string(cellRecord.cellID),n,1),string(P.names(:)), ...
        truth,meanValue,medianValue,sdValue,normalizedSD,contraction, ...
        q(:,1),q(:,4),intervalWidth,double(covered),meanNormalizedError, ...
        medianNormalizedError, ...
        repmat(string(sampler),n,1),repmat(double(replicate),n,1), ...
        repmat(double(steps),n,1),true(n,1), ...
        repmat(string(mechanism),n,1), ...
        repmat(string(status.state),n,1),repmat(string(status.reason),n,1), ...
        'VariableNames',parameter_names());
    errors=recovery.loss_consistent_point_errors( ...
        truth,meanValue,medianValue,priorWidth);
    T.SignedErrorFromPosteriorMeanPhysical= ...
        errors.signedErrorFromPosteriorMean;
    T.SignedErrorFromPosteriorMedianPhysical= ...
        errors.signedErrorFromPosteriorMedian;
    T.AbsoluteErrorFromPosteriorMedianPhysical= ...
        errors.absoluteErrorFromPosteriorMedian;
    T.SquaredErrorFromPosteriorMeanPhysical= ...
        errors.squaredErrorFromPosteriorMean;
    T.NormalizedAbsoluteErrorFromPosteriorMedian= ...
        errors.normalizedAbsoluteErrorFromPosteriorMedian;
    T.NormalizedSquaredErrorFromPosteriorMean= ...
        errors.normalizedSquaredErrorFromPosteriorMean;
    T.CI25Physical=q(:,2);
    T.CI75Physical=q(:,3);
    T.CIWidth50Physical=q(:,3)-q(:,2);
    T.TruthCovered50=double(covered50);
end

function T=missing_parameter_rows(cellRecord,P,status,n)
    missing=nan(n,1);
    semantics=design_study.design_semantics(cellRecord.design);
    T=table(repmat(double(cellRecord.caseID),n,1), ...
        repmat(string(cellRecord.scenario),n,1), ...
        repmat(string(cellRecord.scenarioLabel),n,1), ...
        repmat(logical(cellRecord.primaryScenario),n,1), ...
        repmat(string(cellRecord.design),n,1), ...
        repmat(string(cellRecord.designLabel),n,1), ...
        repmat(string(semantics.role),n,1), ...
        repmat(string(semantics.comparison_class),n,1), ...
        repmat(string(cellRecord.cellID),n,1),string(P.names(:)), ...
        missing,missing,missing,missing,missing,missing,missing,missing, ...
        missing,missing,missing,missing,repmat("",n,1),missing,missing, ...
        false(n,1),repmat("",n,1), ...
        repmat(string(status.state),n,1),repmat(string(status.reason),n,1), ...
        'VariableNames',parameter_names());
    T.SignedErrorFromPosteriorMeanPhysical=missing;
    T.SignedErrorFromPosteriorMedianPhysical=missing;
    T.AbsoluteErrorFromPosteriorMedianPhysical=missing;
    T.SquaredErrorFromPosteriorMeanPhysical=missing;
    T.NormalizedAbsoluteErrorFromPosteriorMedian=missing;
    T.NormalizedSquaredErrorFromPosteriorMean=missing;
    T.CI25Physical=missing;
    T.CI75Physical=missing;
    T.CIWidth50Physical=missing;
    T.TruthCovered50=missing;
end

function names=parameter_names()
    names={'CaseID','Scenario','ScenarioLabel', ...
        'PrimaryScientificScenario','Design','DesignLabel','DesignRole', ...
        'ComparisonClass','CellID', ...
        'Parameter','TruthPhysical','PosteriorMeanPhysical', ...
        'PosteriorMedianPhysical','PosteriorSDPhysical', ...
        'NormalizedPosteriorSD','ContractionAmount','CI025Physical', ...
        'CI975Physical','CIWidthPhysical','TruthCovered95', ...
        'PosteriorMeanNormalizedRecoveryError', ...
        'PosteriorMedianNormalizedRecoveryError', ...
        'CertifiedSampler','CertifiedReplicate', ...
        'CertifiedStepCount','ArtifactLoaded','CertificationMechanism', ...
        'ExecutionStatus','FailureReason'};
end

function [sampler,replicate,steps]=provider_axes(A)
    provenance=recovery.posterior_provider_provenance(A);
    provider=provenance.provider;
    sampler=char(string(provider.sampler));
    replicate=double(provider.replicateID);steps=double(provider.stepCount);
end

function mechanism=certification_mechanism(A)
    provenance=recovery.posterior_provider_provenance(A);
    mechanism=char(string(provenance.certificationMechanism));
end
