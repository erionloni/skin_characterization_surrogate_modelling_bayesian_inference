function result = posterior_joint_geometry_replicates( ...
        drawsReplicate1,drawsReplicate2,bounds,varargin)
%POSTERIOR_JOINT_GEOMETRY_REPLICATES Factual accepted-replicate geometry.
%   This helper compares two unpooled retained-draw matrices (saved draws only).
%   It delegates prior standardization and the full covariance eigensystem to
%   the established posterior-covariance engine.  It defines no threshold,
%   pass/fail state, certification decision, or posterior-provider choice.
%   RESULT = recovery.posterior_joint_geometry_replicates(DRAWSREPLICATE1,
%   DRAWSREPLICATE2, BOUNDS, ...) returns, for the full four-dimensional
%   and the weak-pair covariance of both replicates: the largest eigenvalue
%   and its absolute and relative difference, the normalized Frobenius
%   difference of the covariances, the alignment and angle of the leading
%   eigenvectors, the leading eigengaps, traces and log determinants, and
%   the retained draw counts.
%   Options (name-value): 'ParameterNames' (default the four canonical
%   parameters), 'WeakPairIndices' (the positions of the weak pair,
%   required; thesis [2 3]: m3_e_RD and log10_k0_RD) and 'Eigensystem' (the
%   thresholds of recovery.covariance_eigensystem as name-value pairs,
%   required; settings A.7).
%   Side effects: none.

    parser=inputParser;
    parser.FunctionName='recovery.posterior_joint_geometry_replicates';
    addParameter(parser,'ParameterNames', ...
        {'m3_f_RD','m3_e_RD','log10_k0_RD','Thickness_RD'},@text_list);
    addParameter(parser,'WeakPairIndices',[],@(x)isempty(x)||index_pair(x));
    addParameter(parser,'Eigensystem',{},@iscell);
    parse(parser,varargin{:});options=parser.Results;
    assert(~isempty(options.WeakPairIndices)&&~isempty(options.Eigensystem), ...
        'recovery:posterior_joint_geometry_replicates:Options', ...
        'The comparison needs ''WeakPairIndices'' and the eigensystem thresholds (settings A.7).');
    names=cellstr(string(options.ParameterNames));
    assert(isequal(reshape(names,1,[]), ...
            {'m3_f_RD','m3_e_RD','log10_k0_RD','Thickness_RD'}), ...
        'recovery:posterior_joint_geometry_replicates:ParameterOrder', ...
        'The exact canonical four-parameter order is required.');
    weak=reshape(double(options.WeakPairIndices),1,[]);

    first=recovery.posterior_covariance_eigensystem( ...
        drawsReplicate1,bounds,'ParameterNames',names,options.Eigensystem{:});
    second=recovery.posterior_covariance_eigensystem( ...
        drawsReplicate2,bounds,'ParameterNames',names,options.Eigensystem{:});
    assert(first.eigensystem.valid&&second.eigensystem.valid, ...
        'recovery:posterior_joint_geometry_replicates:Eigensystem', ...
        'Both accepted-replicate covariance eigensystems must be valid.');
    fullFirst=first.eigensystem.covarianceSymmetrized;
    fullSecond=second.eigensystem.covarianceSymmetrized;
    result=struct( ...
        'schemaVersion','posterior_joint_geometry_replicates_v1', ...
        'parameterCoordinateSystem', ...
            'independent_uniform_prior_mean_sd_standardized', ...
        'parameterNames',{names},'weakPairIndices',weak, ...
        'weakPairNames',{names(weak)}, ...
        'replicateDrawsPooled',false, ...
        'acceptanceThresholdDefined',false, ...
        'certificationChanged',false, ...
        'full4D',geometry(fullFirst,fullSecond, ...
            first.eigensystem,second.eigensystem, ...
            size(drawsReplicate1,1),size(drawsReplicate2,1)), ...
        'weakPair',geometry(fullFirst(weak,weak),fullSecond(weak,weak), ...
            [],[],size(drawsReplicate1,1),size(drawsReplicate2,1)));
end

function value=geometry(C1,C2,E1,E2,n1,n2)
    [lambda1,v1]=ordered_eigensystem(C1,E1);
    [lambda2,v2]=ordered_eigensystem(C2,E2);
    maximum1=lambda1(end);maximum2=lambda2(end);
    absoluteDifference=abs(maximum1-maximum2);
    lambdaScale=abs(maximum1)+abs(maximum2);
    if lambdaScale==0
        relativeDifference=0;
    else
        relativeDifference=2*absoluteDifference/lambdaScale;
    end
    covarianceScale=norm(C1,'fro')+norm(C2,'fro');
    if covarianceScale==0
        normalizedFrobenius=0;
    else
        normalizedFrobenius=2*norm(C1-C2,'fro')/covarianceScale;
    end
    alignment=recovery.axis_similarity(v1(:,end),v2(:,end));
    angle=acosd(min(1,max(0,alignment)));
    value=struct( ...
        'dimension',size(C1,1), ...
        'covarianceReplicate1',C1, ...
        'covarianceReplicate2',C2, ...
        'lambdaMaxReplicate1',maximum1, ...
        'lambdaMaxReplicate2',maximum2, ...
        'lambdaMaxAbsoluteDifference',absoluteDifference, ...
        'lambdaMaxRelativeDifference',relativeDifference, ...
        'normalizedCovarianceFrobeniusDifference',normalizedFrobenius, ...
        'leadingEigenvectorAbsoluteAlignment',alignment, ...
        'leadingEigenvectorAngleDegrees',angle, ...
        'leadingEigengapReplicate1',maximum1-lambda1(end-1), ...
        'leadingEigengapReplicate2',maximum2-lambda2(end-1), ...
        'traceReplicate1',trace(C1), ...
        'traceReplicate2',trace(C2), ...
        'logDeterminantReplicate1',log_determinant(lambda1), ...
        'logDeterminantReplicate2',log_determinant(lambda2), ...
        'retainedDrawCountReplicate1',double(n1), ...
        'retainedDrawCountReplicate2',double(n2));
end

function [lambda,vectors]=ordered_eigensystem(C,established)
    C=(double(C)+double(C).')/2;
    if ~isempty(established)
        lambda=double(established.correctedEigenvalues(:));
        vectors=double(established.eigenvectorsSignAligned);
        return
    end
    [vectors,diagonal]=eig(C);
    [lambda,order]=sort(real(diag(diagonal)),'ascend');
    vectors=real(vectors(:,order));
    tolerance=1e-12*max(1,norm(C,2));
    assert(~any(lambda < -tolerance), ...
        'recovery:posterior_joint_geometry_replicates:NegativeEigenvalue', ...
        'A covariance block has a materially negative eigenvalue.');
    lambda(lambda<0)=0;
    for i=1:numel(lambda)
        vectors(:,i)=recovery.align_vector_sign(vectors(:,i));
    end
end

function value=log_determinant(lambda)
    if any(lambda<0)
        value=NaN;
    elseif any(lambda==0)
        value=-Inf;
    else
        value=sum(log(lambda));
    end
end

function tf=text_list(value)
    tf=(iscell(value)||isstring(value))&&numel(value)==4;
end

function tf=index_pair(value)
    tf=isnumeric(value)&&isequal(size(value),[1 2])&& ...
        all(isfinite(value))&&all(value==fix(value))&& ...
        all(value>=1)&&all(value<=4)&&numel(unique(value))==2;
end
