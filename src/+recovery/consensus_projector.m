function result = consensus_projector(projectors,varargin)
%CONSENSUS_PROJECTOR Mean-projector consensus for axes or subspaces.
%   RESULT = recovery.consensus_projector(P,'TargetRank',R) accepts an
%   M-by-M-by-N stack of orthogonal projectors. The leading R eigenvectors
%   of their mean projector define a neutral cohort consensus subspace.
%   RESULT: the mean projector, its eigenvalues and eigenvectors, the
%   dominant axis, the consensus basis and projector.
%   Side effects: none.

    options=parse_options(varargin{:});
    assert(isnumeric(projectors)&&isreal(projectors)&&ndims(projectors)<=3&& ...
        size(projectors,1)==size(projectors,2)&&size(projectors,3)>=1&& ...
        all(isfinite(projectors(:))), ...
        'recovery:consensus_projector:Projectors', ...
        'projectors must be a finite real square M-by-M-by-N array.');
    projectors=double(projectors);dimension=size(projectors,1);
    count=size(projectors,3);inputRanks=zeros(count,1);
    for i=1:count
        one=(projectors(:,:,i)+projectors(:,:,i).')/2;
        tolerance=1e-10*max(1,norm(one,'fro'));
        assert(norm(projectors(:,:,i)-projectors(:,:,i).','fro')<= ...
            tolerance&&norm(one^2-one,'fro')<=tolerance, ...
            'recovery:consensus_projector:OrthogonalProjector', ...
            'Every input must be an orthogonal projector.');
        inputRanks(i)=round(trace(one));projectors(:,:,i)=one;
    end
    assert(all(inputRanks==inputRanks(1))&&inputRanks(1)>=1&& ...
        inputRanks(1)<=dimension, ...
        'recovery:consensus_projector:InputRanks', ...
        'All input projectors must have the same positive rank.');
    if isempty(options.TargetRank),options.TargetRank=inputRanks(1);end
    assert(isscalar(options.TargetRank)&&isfinite(options.TargetRank)&& ...
        options.TargetRank==fix(options.TargetRank)&& ...
        options.TargetRank>=1&&options.TargetRank<=dimension, ...
        'recovery:consensus_projector:TargetRank', ...
        'TargetRank must be a positive integer no larger than M.');

    meanProjector=mean(projectors,3);
    meanProjector=(meanProjector+meanProjector.')/2;
    [vectors,diagonal]=eig(meanProjector);
    [eigenvalues,order]=sort(real(diag(diagonal)),'descend');
    vectors=real(vectors(:,order));signFlips=false(dimension,1);
    for k=1:dimension
        [vectors(:,k),signFlips(k)]=recovery.align_vector_sign(vectors(:,k));
    end
    basis=vectors(:,1:options.TargetRank);
    consensusProjector=basis*basis.';
    consensusProjector=(consensusProjector+consensusProjector.')/2;
    result=struct( ...
        'schemaVersion','posterior_consensus_projector_v1', ...
        'inputProjectorCount',count, ...
        'inputProjectorRank',inputRanks(1), ...
        'targetRank',options.TargetRank, ...
        'meanProjector',meanProjector, ...
        'meanProjectorEigenvaluesDescending',eigenvalues, ...
        'meanProjectorEigenvectorsSignAligned',vectors, ...
        'signFlipApplied',signFlips, ...
        'dominantAxis',vectors(:,1), ...
        'dominantProjectorEigenvalue',eigenvalues(1), ...
        'consensusBasis',basis, ...
        'consensusProjector',consensusProjector);
end

function options=parse_options(varargin)
    options=struct('TargetRank',[]);
    assert(mod(numel(varargin),2)==0, ...
        'recovery:consensus_projector:Options', ...
        'Options must be supplied as name/value pairs.');
    for i=1:2:numel(varargin)
        name=lower(char(string(varargin{i})));
        switch name
            case 'targetrank'
                options.TargetRank=varargin{i+1};
            otherwise
                error('recovery:consensus_projector:UnknownOption', ...
                    'Unknown option "%s".',name);
        end
    end
end
