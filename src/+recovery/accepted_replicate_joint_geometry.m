function result = accepted_replicate_joint_geometry( ...
        cfg,cellRecord,primaryArtifact,varargin)
%ACCEPTED_REPLICATE_JOINT_GEOMETRY Bind accepted independent replicates.
%   Replicate 2 is the successful AIES replicate that the certification
%   decision accepted at the replicate-1 step count; ReplicateLoader loads it
%   (inversion.load_posterior_artifact by default; the recovery passes
%   recovery.load_posterior_provider, which also reads shipped draws).
%   Missing or invalid comparison evidence is returned explicitly and never
%   changes the certified provider or marginal downstream usability.
%   RESULT = recovery.accepted_replicate_joint_geometry(CFG, CELLRECORD,
%   PRIMARYARTIFACT, 'ReplicateLoader', F) loads replicate 2 of the cell at
%   the provider's level and compares the joint geometry of the two
%   replicates (recovery.posterior_joint_geometry_replicates); RESULT holds
%   the comparison or the reason it is missing.
%   Options (name-value) besides 'ReplicateLoader': 'ParameterNames' (default
%   CFG.paramNames), 'Bounds' (M-by-2, default CFG.paramBounds) and
%   'WeakPairIndices' (required; thesis [2 3]: m3_e_RD and log10_k0_RD).
%   The eigensystem thresholds are those of the settings
%   (CFG.analysis.posteriorEigendecomposition, A.7).
%   Side effects: none.

    parser=inputParser;
    parser.FunctionName='recovery.accepted_replicate_joint_geometry';
    addParameter(parser,'ReplicateLoader',@inversion.load_posterior_artifact, ...
        @(x)isa(x,'function_handle'));
    addParameter(parser,'ParameterNames',cfg.paramNames,@(x)iscell(x)||isstring(x));
    addParameter(parser,'Bounds',cfg.paramBounds,@isnumeric);
    addParameter(parser,'WeakPairIndices',[],@isnumeric);
    parse(parser,varargin{:});options=parser.Results;
    assert(~isempty(options.WeakPairIndices), ...
        'recovery:accepted_replicate_joint_geometry:WeakPair', ...
        'The comparison needs ''WeakPairIndices''.');
    eigensystemOptions=eigensystem_options(cfg);
    result=unavailable('comparison_not_attempted');
    try
        validate_primary(primaryArtifact,options.ParameterNames,options.Bounds);
        provider=primaryArtifact.certification.provider;
        result.acceptedStepCount=double(provider.stepCount);
        decision=primaryArtifact.certification.reliabilityDecision;
        evidence=reshape(decision.executedEvidence,1,[]);
        required={'sampler','replicateID','stepCount','executionSucceeded'};
        assert(all(isfield(evidence,required)), ...
            'recovery:accepted_replicate_joint_geometry:EvidenceSchema', ...
            'The certification lacks complete accepted-replicate evidence.');
        hit=strcmpi({evidence.sampler},'AIES')&[evidence.replicateID]==2& ...
            [evidence.stepCount]==double(provider.stepCount)& ...
            logical([evidence.executionSucceeded]);
        assert(nnz(hit)==1, ...
            'recovery:accepted_replicate_joint_geometry:ReplicateEvidence', ...
            ['Certification must bind exactly one successful AIES replicate ' ...
             '2 artifact at the accepted level.']);
        [second,status]=options.ReplicateLoader(cfg,cellRecord,'AIES',2, ...
            double(provider.stepCount));
        result.loadState=status_field(status,'state','unavailable');
        if ~(status_field(status,'loaded',false)&& ...
                status_field(status,'valid',false))
            result.reason=nonempty(status_field(status,'reason',''), ...
                'accepted_replicate_2_unavailable');
            return
        end
        result.artifactAvailable=true;
        validate_second(second,options.ParameterNames,options.Bounds, ...
            provider.stepCount);
        result.available=true;result.reason='';
        if isfield(second,'paths')&&isfield(second.paths,'posteriorPath')
            result.replicate2ArtifactPath=char(string(second.paths.posteriorPath));
        end
        secondAnalysis=recovery.posterior_covariance_eigensystem( ...
            second.drawsPhysical,options.Bounds, ...
            'ParameterNames',options.ParameterNames,eigensystemOptions{:});
        result.replicate2Eigensystem=secondAnalysis.eigensystem;
        result.diagnostics=recovery.posterior_joint_geometry_replicates( ...
            primaryArtifact.drawsPhysical,second.drawsPhysical,options.Bounds, ...
            'ParameterNames',options.ParameterNames, ...
            'WeakPairIndices',options.WeakPairIndices,'Eigensystem',eigensystemOptions);
        result.loadState='complete_reusable';
    catch exception
        result.available=false;
        result.reason=exception_reason(exception);
        result.errorIdentifier=char(string(exception.identifier));
        if isempty(result.loadState),result.loadState='invalid';end
    end
end

function validate_primary(A,names,bounds)
    required={'drawsPhysical','parameterNames','bounds','request', ...
        'certification','samplesPooled'};
    certificationPoolOK=~isfield(A.certification, ...
        'samplesPooledAcrossReplicates')|| ...
        ~logical(A.certification.samplesPooledAcrossReplicates);
    assert(isstruct(A)&&isscalar(A)&&all(isfield(A,required))&& ...
        isequal(cellstr(string(A.parameterNames)),reshape(cellstr(string(names)),1,[]))&& ...
        isequal(double(A.bounds),double(bounds))&&~logical(A.samplesPooled)&& ...
        strcmpi(char(string(A.request.sampler)),'AIES')&& ...
        double(A.request.replicateID)==1&& ...
        strcmp(char(string(A.certification.certificationMechanism)), ...
            'CERTIFIED_AIES_REPLICATE_AGREEMENT')&& ...
        double(A.certification.provider.replicateID)==1&&certificationPoolOK, ...
        'recovery:accepted_replicate_joint_geometry:Primary', ...
        'The primary artifact is not the accepted unpooled AIES replicate 1.');
end

function validate_second(A,names,bounds,steps)
    assert(isstruct(A)&&isscalar(A)&& ...
        all(isfield(A,{'drawsPhysical','parameterNames','bounds','request', ...
            'samplesPooled'}))&& ...
        isequal(cellstr(string(A.parameterNames)),reshape(cellstr(string(names)),1,[]))&& ...
        isequal(double(A.bounds),double(bounds))&&~logical(A.samplesPooled)&& ...
        strcmpi(char(string(A.request.sampler)),'AIES')&& ...
        double(A.request.replicateID)==2&& ...
        double(A.request.stepCount)==double(steps), ...
        'recovery:accepted_replicate_joint_geometry:Replicate2', ...
        ['Replicate 2 is not the independent unpooled AIES replicate at the ' ...
         'accepted level.']);
end

function value=unavailable(reason)
    value=struct('schemaVersion', ...
        'accepted_replicate_joint_geometry_binding_v1', ...
        'available',false,'artifactAvailable',false, ...
        'reason',char(string(reason)), ...
        'errorIdentifier','','loadState','not_attempted', ...
        'acceptedStepCount',NaN,'replicate2ArtifactPath','', ...
        'replicate2Eigensystem',struct([]),'diagnostics',struct([]), ...
        'replicateDrawsPooled',false,'certificationChanged',false);
end

function value=status_field(status,name,fallback)
    value=fallback;
    if isstruct(status)&&isscalar(status)&&isfield(status,name)
        value=status.(name);
    end
end

function value=nonempty(value,fallback)
    value=char(string(value));if isempty(value),value=fallback;end
end

function value=exception_reason(exception)
    value=char(string(exception.identifier));
    if isempty(value),value=char(string(exception.message));end
    value=strrep(value,newline,' ');
end

function options=eigensystem_options(cfg)
%EIGENSYSTEM_OPTIONS The thresholds of the eigensystem, from the settings (A.7).
    policy=cfg.analysis.posteriorEigendecomposition;
    options={'NearDegenerateGap',policy.nearDegenerateGapThreshold, ...
        'NegativeEigenvalueTolerance',policy.negativeEigenvalueTolerance, ...
        'SymmetryTolerance',policy.symmetryTolerance};
end
