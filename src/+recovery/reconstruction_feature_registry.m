function registry = reconstruction_feature_registry()
%RECONSTRUCTION_FEATURE_REGISTRY Canonical response-space feature registry.
%   The registry is the single factual definition used to transform raw
%   pressure reconstructions and held-out truth values.  The first six spaces
%   are the active inversion designs; the remaining three are supplementary
%   diagnostic families.  Raw order is
%       [p1_D2 p2_D2 p3_D2 p1_D6 p2_D6 p3_D6].
%   REGISTRY = recovery.reconstruction_feature_registry() returns the
%   evaluation spaces with their features (IDs, families, units) and the
%   fitting designs.
%   Side effects: none.

    designs=inversion.design_registry();
    fittingDesigns={designs.name};
    expectedDesigns={'all_six','d2_only','d6_only','cycle_1_only', ...
        'ratios_only','physics_guided_full_rank_six'};
    assert(isequal(fittingDesigns,expectedDesigns), ...
        'recovery:reconstruction_feature_registry:DesignOrder', ...
        'The fitting-design order must match the active inversion registry.');

    rawIDs={'p1_D2','p2_D2','p3_D2','p1_D6','p2_D6','p3_D6'};
    rawLabels=rawIDs;
    rawFormulas={'y1','y2','y3','y4','y5','y6'};
    rawFamilies=repmat({'raw_pressure'},1,6);
    pressureUnits=repmat({'mbar'},1,6);
    noDenominator=repmat({'none'},1,6);

    ratioIDs={'p2_D2_over_p1_D2','p3_D2_over_p1_D2', ...
        'p2_D6_over_p1_D6','p3_D6_over_p1_D6'};
    ratioFormulas={'y2/y1','y3/y1','y5/y4','y6/y4'};
    ratioFamilies=repmat({'within_probe_ratio'},1,4);
    ratioUnits=repmat({'dimensionless'},1,4);
    guardedRatios=repmat({'absolute_denominator_above_configured_floor'},1,4);

    physicsIDs={'p3_D2','p3_D2_over_p1_D2', ...
        'p1_D2_minus_p2_D2','p1_D2_over_p3_D6', ...
        'p3_D6_over_p1_D6','p2_D6_over_p1_D6'};
    physicsFormulas={'y3','y3/y1','y1-y2','y1/y6','y6/y4','y5/y4'};
    physicsFamilies={'raw_pressure','within_probe_ratio', ...
        'within_probe_drop','cross_probe_ratio', ...
        'within_probe_ratio','within_probe_ratio'};
    physicsUnits={'mbar','dimensionless','mbar','dimensionless', ...
        'dimensionless','dimensionless'};
    physicsDenominators={'none',guardedRatios{1},'none', ...
        guardedRatios{1},guardedRatios{1},guardedRatios{1}};

    dropIDs={'p1_D2_minus_p2_D2','p1_D2_minus_p3_D2', ...
        'p2_D2_minus_p3_D2','p1_D6_minus_p2_D6', ...
        'p1_D6_minus_p3_D6','p2_D6_minus_p3_D6'};
    dropFormulas={'y1-y2','y1-y3','y2-y3', ...
        'y4-y5','y4-y6','y5-y6'};
    dropFamilies=repmat({'within_probe_drop'},1,6);
    dropUnits=repmat({'mbar'},1,6);

    [crossRatioIDs,crossRatioFormulas,crossDifferenceIDs, ...
        crossDifferenceFormulas]=cross_probe_features();
    crossRatioFamilies=repmat({'cross_probe_ratio'},1,9);
    crossDifferenceFamilies=repmat({'cross_probe_difference'},1,9);
    crossRatioUnits=repmat({'dimensionless'},1,9);
    crossDifferenceUnits=repmat({'mbar'},1,9);

    spaces=[ ...
        make_space(1,'all_six','All six raw pressures','core_active', ...
            rawIDs,rawLabels,rawFamilies,pressureUnits,rawFormulas, ...
            false(1,6),noDenominator), ...
        make_space(2,'d2_only','D2 raw pressures','core_active', ...
            rawIDs(1:3),rawLabels(1:3),rawFamilies(1:3), ...
            pressureUnits(1:3),rawFormulas(1:3),false(1,3), ...
            noDenominator(1:3)), ...
        make_space(3,'d6_only','D6 raw pressures','core_active', ...
            rawIDs(4:6),rawLabels(4:6),rawFamilies(4:6), ...
            pressureUnits(4:6),rawFormulas(4:6),false(1,3), ...
            noDenominator(4:6)), ...
        make_space(4,'cycle_1_only','Cycle-1 raw pressures','core_active', ...
            rawIDs([1 4]),rawLabels([1 4]),rawFamilies([1 4]), ...
            pressureUnits([1 4]),rawFormulas([1 4]),false(1,2), ...
            noDenominator([1 4])), ...
        make_space(5,'ratios_only','Canonical within-probe ratios', ...
            'core_active',ratioIDs,ratioIDs,ratioFamilies,ratioUnits, ...
            ratioFormulas,true(1,4),guardedRatios), ...
        make_space(6,'physics_guided_full_rank_six', ...
            'Physics-guided full-rank representation','core_active', ...
            physicsIDs,physicsIDs,physicsFamilies,physicsUnits, ...
            physicsFormulas,[false true false true true true], ...
            physicsDenominators), ...
        make_space(7,'within_probe_drops','Within-probe pressure drops', ...
            'expanded_diagnostic',dropIDs,dropIDs,dropFamilies,dropUnits, ...
            dropFormulas,false(1,6),repmat({'none'},1,6)), ...
        make_space(8,'cross_probe_ratios','All D2-over-D6 cycle ratios', ...
            'expanded_diagnostic',crossRatioIDs,crossRatioIDs, ...
            crossRatioFamilies,crossRatioUnits,crossRatioFormulas, ...
            true(1,9),repmat(guardedRatios(1),1,9)), ...
        make_space(9,'cross_probe_differences', ...
            'All D2-minus-D6 cycle differences','expanded_diagnostic', ...
            crossDifferenceIDs,crossDifferenceIDs, ...
            crossDifferenceFamilies,crossDifferenceUnits, ...
            crossDifferenceFormulas,false(1,9),repmat({'none'},1,9))];

    scalarFeatures=registry_table(spaces);
    fittingDesignTable=table((1:6).',string(fittingDesigns(:)), ...
        string({designs.label}).', ...
        'VariableNames',{'FittingDesignOrder','FittingDesign', ...
        'FittingDesignLabel'});
    activeNames={spaces(1:6).id};diagnosticNames={spaces(7:9).id};
    assert(isequal(activeNames,expectedDesigns)&& ...
        isequal(diagnosticNames,{'within_probe_drops', ...
        'cross_probe_ratios','cross_probe_differences'})&& ...
        height(scalarFeatures)==48&&sum([spaces.featureCount])==48, ...
        'recovery:reconstruction_feature_registry:RegistryShape', ...
        'The registry must contain six active and three diagnostic spaces.');

    registry=struct( ...
        'schemaVersion','posterior_feature_reconstruction_registry_v1', ...
        'rawOutputOrder',{rawIDs}, ...
        'fittingDesigns',{fittingDesigns}, ...
        'fittingDesignTable',fittingDesignTable, ...
        'activeSpaces',{activeNames}, ...
        'diagnosticSpaces',{diagnosticNames}, ...
        'allSpaces',{{spaces.id}}, ...
        'spaces',spaces, ...
        'scalarFeatures',scalarFeatures, ...
        'coreMatrixShape',[6 6], ...
        'expandedMatrixShape',[6 9], ...
        'transformationSemantics', ...
            'transform_each_raw_six_pressure_draw_before_summary', ...
        'createsNewInversionDesigns',false);
end

function space=make_space(order,id,label,className,featureIDs,featureLabels, ...
        featureFamilies,units,formulas,nonlinear,denominatorPolicies)
    n=numel(featureIDs);
    assert(all([numel(featureLabels) numel(featureFamilies) numel(units) ...
        numel(formulas) numel(nonlinear) numel(denominatorPolicies)]==n), ...
        'recovery:reconstruction_feature_registry:SpaceShape', ...
        ['Every feature of evaluation space %s needs a label, family, unit, formula, ' ...
         'nonlinearity flag and denominator policy.'],char(string(id)));
    space=struct('order',order,'id',id,'label',label, ...
        'evaluationClass',className,'featureCount',n, ...
        'featureIDs',{featureIDs},'featureLabels',{featureLabels}, ...
        'featureFamilies',{featureFamilies},'units',{units}, ...
        'formulas',{formulas},'nonlinear',logical(nonlinear), ...
        'denominatorPolicies',{denominatorPolicies});
end

function T=registry_table(spaces)
    count=sum([spaces.featureCount]);
    [spaceOrder,featureIndex]=deal(nan(count,1));
    [evaluationSpace,evaluationSpaceLabel,evaluationClass,scalarFeature, ...
        featureID,featureFamily,units,formula,denominatorPolicy]= ...
        deal(strings(count,1));
    nonlinear=false(count,1);cursor=0;
    for s=1:numel(spaces)
        for j=1:spaces(s).featureCount
            cursor=cursor+1;spaceOrder(cursor)=spaces(s).order;
            evaluationSpace(cursor)=string(spaces(s).id);
            evaluationSpaceLabel(cursor)=string(spaces(s).label);
            evaluationClass(cursor)=string(spaces(s).evaluationClass);
            featureIndex(cursor)=j;
            scalarFeature(cursor)=string(spaces(s).featureLabels{j});
            featureID(cursor)=string(spaces(s).featureIDs{j});
            featureFamily(cursor)=string(spaces(s).featureFamilies{j});
            units(cursor)=string(spaces(s).units{j});
            formula(cursor)=string(spaces(s).formulas{j});
            nonlinear(cursor)=spaces(s).nonlinear(j);
            denominatorPolicy(cursor)= ...
                string(spaces(s).denominatorPolicies{j});
        end
    end
    T=table(spaceOrder,evaluationSpace,evaluationSpaceLabel, ...
        evaluationClass,featureIndex,scalarFeature,featureID,featureFamily, ...
        units,formula,nonlinear,denominatorPolicy, ...
        'VariableNames',{'EvaluationSpaceOrder','EvaluationSpace', ...
        'EvaluationSpaceLabel','EvaluationClass','FeatureIndex', ...
        'ScalarFeature','FeatureID','FeatureFamily','Units','Formula', ...
        'Nonlinear','DenominatorPolicy'});
end

function [ratioIDs,ratioFormulas,differenceIDs,differenceFormulas]= ...
        cross_probe_features()
    ratioIDs=cell(1,9);ratioFormulas=cell(1,9);
    differenceIDs=cell(1,9);differenceFormulas=cell(1,9);cursor=0;
    for i=1:3
        for j=1:3
            cursor=cursor+1;
            ratioIDs{cursor}=sprintf('p%d_D2_over_p%d_D6',i,j);
            ratioFormulas{cursor}=sprintf('y%d/y%d',i,j+3);
            differenceIDs{cursor}=sprintf('p%d_D2_minus_p%d_D6',i,j);
            differenceFormulas{cursor}=sprintf('y%d-y%d',i,j+3);
        end
    end
end
