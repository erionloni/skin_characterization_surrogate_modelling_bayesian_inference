    for i=1:height(caseRows)
        rows=T.Scenario==caseRows.Scenario(i)&T.CaseID==caseRows.CaseID(i);
        T.IncludedInMatchedCohort(rows)= ...
            logical(caseRows.IncludedInMatchedCohort(i));
    end
end

