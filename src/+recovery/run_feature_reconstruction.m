function result = run_feature_reconstruction(cfg,grid,varargin)
%RUN_FEATURE_RECONSTRUCTION The feature reconstruction of the posteriors, with its error budget.
%   RESULT = recovery.run_feature_reconstruction(CFG, GRID, ...) maps the
%   unpooled posterior draws of the selected provider of every cell of GRID
%   (certified, or a healthy fallback of the shipped draws) through the
%   six-output GP once per cell, transforms every response feature sample
%   by sample
%   (recovery.reconstruction_feature_values) and compares the posterior
%   reconstructions with the held-out truths: point errors, interval
%   coverage and the matched cohorts, and the surrogate-only reference. It
%   then characterizes the downstream error budget
%   (recovery.characterize_downstream_error_budget), which evaluates the
%   trained GP once at the development inputs, when
%   CFG.analysis.runDownstreamErrorBudget is true (the run switch
%   error_budget); RESULT.downstreamErrorBudget is empty otherwise.
%   No sampler, fit, likelihood or measurement-noise realization.
%   Options (name-value): 'OutputRoot' (default
%   CFG.paths.featureReconstruction), 'BatchSize' (GP evaluations per batch,
%   default CFG.analysis.featureReconstruction.gpEvaluationBatchSize) and
%   'WriteOutputs' (true).
%   Side effects: writes the tables and records below the feature
%   reconstruction folder of the recovery.
%   Computation: minutes to about an hour (the GP at every posterior draw).

    parser=inputParser;
    parser.FunctionName='recovery.run_feature_reconstruction';
    addParameter(parser,'OutputRoot',cfg.paths.featureReconstruction,@text_scalar);
    addParameter(parser,'BatchSize', ...
        cfg.analysis.featureReconstruction.gpEvaluationBatchSize, ...
        @(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x==fix(x)&&x>0);
    addParameter(parser,'WriteOutputs',true,@(x)islogical(x)&&isscalar(x));
    parse(parser,varargin{:});options=parser.Results;

    policy=validate_policy(cfg,grid);
    expectedPosteriorCellCount=double(policy.expectedPosteriorCellCount);
    registry=recovery.reconstruction_feature_registry();
    assert(isequal(registry.fittingDesigns,policy.fittingDesigns)&& ...
        isequal(registry.activeSpaces,policy.activeEvaluationSpaces)&& ...
        isequal(registry.diagnosticSpaces,policy.diagnosticEvaluationSpaces), ...
        'recovery:run_feature_reconstruction:RegistryPolicy', ...
        'The configured study and canonical feature registry disagree.');
    selectedCells=select_cells(grid.cells,policy);
    assert(numel(selectedCells)==policy.expectedPosteriorCellCount, ...
        'recovery:run_feature_reconstruction:CellCount', ...
        'The reconstruction selects %d posterior cells, not the %d of its policy.', ...
        numel(selectedCells),policy.expectedPosteriorCellCount);

    outputRoot=char(string(options.OutputRoot));
    paths=output_paths(outputRoot);

    [validation,policy]=validation_data(cfg,policy);
    scales=recovery.reconstruction_feature_scales( ...
        validation.Y,validation.caseIDs, ...
        'DenominatorFloor',policy.denominatorFloor, ...
        'ExpectedCaseCount',policy.validationCohortSize, ...
        'NearZeroAbsoluteTolerance',policy.nearZeroRangeTolerance, ...
        'NearZeroRelativeTolerance',policy.nearZeroRangeTolerance);
    featureRegistry=attach_scales(registry.scalarFeatures,scales);
    gpState=struct('loaded',false,'model',[]);

    [surrogateRaw,surrogateSource,surrogateReference,gpState, ...
        truthEvaluationPasses, ...
        truthEvaluationBatches]=surrogate_reference_raw( ...
        cfg,validation,options,gpState);
    surrogateOnlyReference=surrogate_reference_rows( ...
        validation,surrogateRaw,featureRegistry,registry,policy, ...
        surrogateSource,surrogateReference);

    nCell=numel(selectedCells);
    longParts=cell(nCell,1);availabilityParts=cell(nCell,1);
    posteriorGPEvaluationPasses=0;posteriorGPEvaluationBatches=0;
    for i=1:nCell
        record=selectedCells(i);
        [artifact,loadStatus]=recovery.load_posterior_provider(cfg,record);
        prediction=[];
        featurePredictions=cell(1,numel(registry.allSpaces));
        info=empty_prediction_info();
        reconstructionValid=false;
        reason=char(string(loadStatus.reason));
        errorIdentifier=field_text(loadStatus,'errorIdentifier');
        if logical(loadStatus.loaded)
            try
                [prediction,info,gpState]=raw_latent_predictions( ...
                    cfg,artifact,options,gpState);
                featurePredictions=transform_all( ...
                    prediction,registry,policy.denominatorFloor);
                reconstructionValid=true;reason='';errorIdentifier='';
                posteriorGPEvaluationPasses=posteriorGPEvaluationPasses+ ...
                    info.gpEvaluationPassCount;
                posteriorGPEvaluationBatches=posteriorGPEvaluationBatches+ ...
                    info.gpBatchEvaluationCount;
            catch exception
                reconstructionValid=false;
                reason=exception.message;errorIdentifier=exception.identifier;
            end
        end
        longParts{i}=cell_rows(record,artifact,loadStatus, ...
            reconstructionValid,prediction,featureRegistry,registry, ...
            validation,policy,info,reason,featurePredictions,cfg);
        availabilityParts{i}=availability_row(record,artifact,loadStatus, ...
            reconstructionValid,info,reason,errorIdentifier,cfg);
    end
    reconstructionLongForm=vertcat(longParts{:});
    availability=vertcat(availabilityParts{:});
    availability.ProviderAvailable=availability.ReconstructionValid;
    assert(height(availability)==expectedPosteriorCellCount&& ...
        height(reconstructionLongForm)== ...
            expectedPosteriorCellCount*height(featureRegistry), ...
        'recovery:run_feature_reconstruction:ExplicitRows', ...
        ['Internal error: the reconstruction tables need one row per cell and per ' ...
         'cell and feature.']);
    assert(all(availability.GPCellEvaluationPassCount<=1)&& ...
        all(availability.GPCellEvaluationPassCount>=0), ...
        'recovery:run_feature_reconstruction:OneGPPassPerCell', ...
        'A posterior cell must have at most one raw six-output GP pass.');

    [matchedCaseRows,matchedSummary]= ...
        recovery.reconstruction_matched_cohorts(availability, ...
        policy.caseIDs,policy.fittingDesigns,policy.scenarios);
    availability=mark_availability_matched(availability,matchedCaseRows);
    reconstructionLongForm=mark_matched_rows( ...
        reconstructionLongForm,matchedCaseRows);
    summaries=recovery.summarize_feature_reconstruction( ...
        reconstructionLongForm,'MatchedCohorts',matchedCaseRows);

    % The downstream error budget (run switch error_budget, settings 0.2):
    % from the objects above, after every reconstruction output exists.
    downstreamErrorBudget=struct([]);
    if logical(cfg.analysis.runDownstreamErrorBudget)
        downstreamArguments={ ...
            'SurrogateOnlyReference',surrogateOnlyReference, ...
            'FeatureRegistryTable',featureRegistry, ...
            'OutputRoot',fullfile(outputRoot,'error_budget'), ...
            'BatchSize',options.BatchSize,'WriteOutputs',options.WriteOutputs};
        if gpState.loaded
            downstreamArguments=[downstreamArguments {'GPModel',gpState.model}];
        end
        downstreamErrorBudget=recovery.characterize_downstream_error_budget( ...
            cfg,downstreamArguments{:});
    end

    status=struct( ...
        'schema_version','feature_reconstruction_status_v2', ...
        'enabled',true,'complete',all(availability.ReconstructionValid), ...
        'expected_posterior_cells',expectedPosteriorCellCount, ...
        'certified_posterior_cells',sum( ...
            availability.CertifiedPosteriorAvailable), ...
        'valid_reconstruction_cells',sum(availability.ReconstructionValid), ...
        'unavailable_or_invalid_cells',sum(~availability.ReconstructionValid), ...
        'posterior_gp_evaluation_passes',posteriorGPEvaluationPasses, ...
        'posterior_gp_batch_evaluations',posteriorGPEvaluationBatches, ...
        'surrogate_reference_source',surrogateSource, ...
        'surrogate_reference_artifact',surrogateReference, ...
        'surrogate_truth_gp_evaluation_passes',truthEvaluationPasses, ...
        'surrogate_truth_gp_batch_evaluations',truthEvaluationBatches, ...
        'surrogate_reference_valid_rows',sum( ...
            surrogateOnlyReference.ReconstructionValid), ...
        'surrogate_reference_invalid_rows',sum( ...
            ~surrogateOnlyReference.ReconstructionValid), ...
        'latent_response_semantics',policy.latentResponseSemantics, ...
        'gp_predictive_variance_sampled_in_latent_reconstruction',false, ...
        'gp_uncertainty_role', ...
            'already_enters_certified_posterior_through_scenario_likelihood', ...
        'measurement_noise_draws_added',false, ...
        'posterior_draws_pooled',false, ...
        'absolute_loss_point_estimator','posterior_median', ...
        'squared_loss_point_estimator','posterior_mean', ...
        'worst_feature_metric', ...
            'normalized_absolute_error_from_posterior_median', ...
        'worst_feature_tie_break_policy', ...
            'lowest_canonical_feature_index', ...
        'worst_feature_per_case_rows', ...
            height(summaries.worstFeaturePerCase), ...
        'worst_feature_frequency_rows', ...
            height(summaries.worstFeatureFrequency), ...
        'matched_cohorts',table2struct(matchedSummary), ...
        'mcmc_runs_performed',0,'likelihood_evaluations_performed',0, ...
        'surrogate_fits_performed',0,'conditional_inversions_performed',0, ...
        'scientific_interpretation_generated',false);

    if options.WriteOutputs
        if ~isfolder(outputRoot),mkdir(outputRoot);end
        write_outputs(paths,featureRegistry,reconstructionLongForm, ...
            summaries,surrogateOnlyReference,availability,matchedCaseRows,status);
    end
    result=struct('status',status,'paths',paths, ...
        'featureRegistry',featureRegistry, ...
        'reconstructionLongForm',reconstructionLongForm, ...
        'perFeatureSummary',summaries.perFeatureSummary, ...
        'matrixSummary',summaries.matrixSummary, ...
        'maximumDeviationSummary',summaries.maximumDeviation, ...
        'worstFeaturePerCase',summaries.worstFeaturePerCase, ...
        'worstFeatureFrequency',summaries.worstFeatureFrequency, ...
        'surrogateOnlyReference',surrogateOnlyReference, ...
        'availability',availability,'matchedCohorts',matchedCaseRows, ...
        'matchedCohortSummary',matchedSummary);
    result.downstreamErrorBudget=downstreamErrorBudget;
end

function policy=validate_policy(cfg,grid)
    assert(strcmp(cfg.dataMode,'real')&&isstruct(grid)&&isscalar(grid)&& ...
        isfield(grid,'cells')&& ...
        numel(grid.cells)==double(cfg.inversion.expectedCellCount)&& ...
        isfield(cfg.analysis,'featureReconstruction'), ...
        'recovery:run_feature_reconstruction:Configuration', ...
        ['The feature reconstruction needs the fixed route, the inversion grid of ' ...
         '%d cells and the configuration analysis.featureReconstruction.'], ...
        double(cfg.inversion.expectedCellCount));
    policy=cfg.analysis.featureReconstruction;
    expectedDesigns={'all_six','d2_only','d6_only','cycle_1_only', ...
        'ratios_only','physics_guided_full_rank_six'};
    expectedPosteriorCellCount=numel(policy.caseIDs)* ...
        numel(policy.fittingDesigns)*numel(policy.scenarios);
    assert(isequal(reshape(double(policy.caseIDs),1,[]), ...
            reshape(double(cfg.inversion.caseIDs),1,[]))&& ...
        ~isempty(policy.caseIDs)&& ...
        numel(unique(policy.caseIDs))==numel(policy.caseIDs)&& ...
        isequal(policy.fittingDesigns,expectedDesigns)&& ...
        isequal(policy.scenarios,{'measurement_plus_gp','gp_only'})&& ...
        isequal(policy.excludedScenarios,{'gp_self_det'})&& ...
        double(policy.expectedPosteriorCellCount)==expectedPosteriorCellCount&& ...
        (isnan(double(policy.validationCohortSize))|| ...
        (isfinite(double(policy.validationCohortSize))&& ...
        double(policy.validationCohortSize)>0))&& ...
        ~logical(policy.measurementNoiseDrawsAdded)&& ...
        ~logical(policy.posteriorPoolingPermitted), ...
        'recovery:run_feature_reconstruction:Policy','Check failed: recovery:run_feature_reconstruction:Policy.');
end

function cells=select_cells(cells,policy)
    keep=ismember(string({cells.scenario}),string(policy.scenarios))& ...
        ismember(string({cells.design}),string(policy.fittingDesigns));
    cells=cells(keep);
    key=string({cells.caseID})+"|"+string({cells.scenario})+"|"+ ...
        string({cells.design});
    assert(numel(unique(key))==numel(key), ...
        'recovery:run_feature_reconstruction:DuplicateCell', ...
        'The inversion grid lists a case, scenario and design more than once.');
end

function [validation,policy]=validation_data(cfg,policy)
    supplied=utils.load_plain_mat(cfg.files.dataset,'X_validation','Y_validation', ...
        'validationCaseIDs');
    required={'X_validation','Y_validation','validationCaseIDs'};
    assert(all(isfield(supplied,required)), ...
        'recovery:run_feature_reconstruction:ValidationData', ...
        ['The fixed dataset %s lacks X_validation, Y_validation or validationCaseIDs; ' ...
         'rerun the step ''dataset''.'],cfg.files.dataset);
    validation=struct('X',double(supplied.X_validation), ...
        'Y',double(supplied.Y_validation), ...
        'caseIDs',reshape(double(supplied.validationCaseIDs),[],1));
    if isnan(double(policy.validationCohortSize))
        policy.validationCohortSize=numel(validation.caseIDs);
    end
    assert(isequal(size(validation.X),[policy.validationCohortSize 4])&& ...
        isequal(size(validation.Y),[policy.validationCohortSize 6])&& ...
        numel(validation.caseIDs)==policy.validationCohortSize&& ...
        numel(unique(validation.caseIDs))==policy.validationCohortSize&& ...
        all(isfinite(validation.X),'all')&&all(isfinite(validation.Y),'all')&& ...
        all(ismember(policy.caseIDs,validation.caseIDs)), ...
        'recovery:run_feature_reconstruction:ValidationShape', ...
        ['The validation cohort of the fixed dataset must have %d distinct, complete ' ...
         'cases among which the inversion cases are; rerun the step ''dataset''.'], ...
        policy.validationCohortSize);
end

function T=attach_scales(T,scales)
    [hit,index]=ismember(string(T.FeatureID),string(scales.FeatureID));
    assert(all(hit),'recovery:run_feature_reconstruction:FeatureScales', ...
        'Some features have no scale: %s.',strjoin(unique(string(T.FeatureID(~hit))),', '));
    names=setdiff(scales.Properties.VariableNames,{'FeatureID'},'stable');
    for i=1:numel(names),T.(names{i})=scales.(names{i})(index);end
end

function [raw,source,reference,state,passes,batches]= ...
        surrogate_reference_raw( ...
        cfg,validation,options,state)
    passes=0;batches=0;
    T=table();
    if isfile(cfg.files.validation)
        saved=utils.load_plain_mat(cfg.files.validation,'validationPredictionTable');
        if isfield(saved,'validationPredictionTable')
            T=saved.validationPredictionTable;
        end
    end
    [raw,valid]=raw_from_s02_table(T,validation.caseIDs);
    if valid
        source='saved_S02_validation_prediction_table';
        reference=relative_reference(cfg.files.validation,cfg,true);
        return;
    end
    [raw,state,batches]=evaluate_in_batches( ...
        cfg,validation.X,options,state);
    passes=1;
    source=sprintf('canonical_GP_evaluated_once_at_%d_external_test_truth_parameters', ...
        numel(validation.caseIDs));
    reference=relative_reference(cfg.files.gp,cfg,true);
end

function [raw,valid]=raw_from_s02_table(T,caseIDs)
    raw=nan(numel(caseIDs),6);valid=false;
    required={'CaseID','OutputIndex','GPMean'};
    if ~istable(T)||~all(ismember(required,T.Properties.VariableNames)),return;end
    try
        for i=1:numel(caseIDs)
            for j=1:6
                rows=double(T.CaseID)==caseIDs(i)&double(T.OutputIndex)==j;
                if nnz(rows)~=1,return;end
                raw(i,j)=double(T.GPMean(rows));
            end
        end
        valid=all(isfinite(raw),'all');
    catch
        valid=false;
    end
end

function rows=surrogate_reference_rows(validation,raw,featureRegistry, ...
        registry,policy,source,sourceReference)
    nCase=numel(validation.caseIDs);rows=cell(numel(registry.allSpaces),1);
    for s=1:numel(registry.allSpaces)
        space=registry.allSpaces{s};
        truth=recovery.reconstruction_feature_values(validation.Y,space, ...
            'DenominatorFloor',policy.denominatorFloor);
        meta=featureRegistry(featureRegistry.EvaluationSpace==string(space),:);
        k=height(meta);prediction=nan(nCase,k);validCase=false(nCase,1);
        failureReason=strings(nCase,1);
        for c=1:nCase
            try
                prediction(c,:)=recovery.reconstruction_feature_values( ...
                    raw(c,:),space,'DenominatorFloor',policy.denominatorFloor);
                validCase(c)=true;
            catch exception
                failureReason(c)=string(exception.identifier)+":"+ ...
                    string(exception.message);
            end
        end
        [caseIndex,featureIndex]=ndgrid(1:nCase,1:k);
        linear=sub2ind([nCase k],caseIndex(:),featureIndex(:));
        scale=double(meta.FeatureScale(featureIndex(:)));
        scaleAvailable=logical(meta.NormalizedMetricAvailable(featureIndex(:)));
        signed=prediction(linear)-truth(linear);absolute=abs(signed);
        normalized=nan(size(absolute));
        rowValid=validCase(caseIndex(:));
        normalized(scaleAvailable&rowValid)= ...
            absolute(scaleAvailable&rowValid)./scale(scaleAvailable&rowValid);
        rows{s}=table(validation.caseIDs(caseIndex(:)), ...
            repmat(string(space),numel(linear),1), ...
            repmat(meta.EvaluationSpaceLabel(1),numel(linear),1), ...
            repmat(meta.EvaluationClass(1),numel(linear),1), ...
            meta.FeatureIndex(featureIndex(:)), ...
            meta.ScalarFeature(featureIndex(:)),meta.FeatureID(featureIndex(:)), ...
            meta.FeatureFamily(featureIndex(:)),meta.Units(featureIndex(:)), ...
            truth(linear),prediction(linear),signed,absolute,scale,normalized, ...
            scaleAvailable,meta.NormalizationUnavailableReason(featureIndex(:)), ...
            rowValid,failureReason(caseIndex(:)), ...
            repmat(string(source),numel(linear),1), ...
            repmat(string(sourceReference),numel(linear),1), ...
            'VariableNames',{'CaseID','EvaluationSpace', ...
            'EvaluationSpaceLabel','EvaluationClass','FeatureIndex', ...
            'ScalarFeature','FeatureID','FeatureFamily','Units','Truth', ...
            'SurrogatePrediction','SignedNativeError','AbsoluteNativeError', ...
            'FeatureScale','NormalizedAbsoluteError', ...
            'NormalizedMetricAvailable','NormalizationUnavailableReason', ...
            'ReconstructionValid','FailureReason','PredictionSource', ...
            'SourceArtifactReference'});
    end
    rows=vertcat(rows{:});
end

function [prediction,info,state]=raw_latent_predictions( ...
        cfg,artifact,options,state)
%RAW_LATENT_PREDICTIONS The six-output GP mean at every posterior draw of one cell.
    [prediction,state,batchCount]=evaluate_in_batches( ...
        cfg,double(artifact.drawsPhysical),options,state);
    info=empty_prediction_info();info.gpEvaluationPassCount=1;
    info.gpBatchEvaluationCount=batchCount;
    info.source='canonical_GP_single_cell_evaluation_pass';
end

function [mu,state,batchCount]=evaluate_in_batches(cfg,X,options,state)
    if ~state.loaded
        assert(isfile(cfg.files.gp), ...
            'recovery:run_feature_reconstruction:MissingGP', ...
            'The GP of the step ''surrogates'' (cfg.files.gp) is missing.');
        saved=load(cfg.files.gp,'gp');
        assert(isfield(saved,'gp'), ...
            'recovery:run_feature_reconstruction:GPArtifact', ...
            'The GP file %s holds no variable gp; rerun the step ''surrogates''.',cfg.files.gp);
        state.model=saved.gp;state.loaded=true;
    end
    n=size(X,1);mu=nan(n,6);batchCount=0;
    for first=1:double(options.BatchSize):n
        last=min(n,first+double(options.BatchSize)-1);
        [one,~]=default_gp_evaluator(state.model,double(X(first:last,:)),cfg);
        one=double(one);
        assert(isequal(size(one),[last-first+1 6])&&all(isfinite(one),'all'), ...
            'recovery:run_feature_reconstruction:GPEvaluation', ...
            'The GP returned predictions that are not finite or not of size %d x 6.',last-first+1);
        mu(first:last,:)=one;batchCount=batchCount+1;
    end
end

function T=cell_rows(record,A,loadStatus,valid,prediction,featureRegistry, ...
        registry,validation,policy,info,reason,featurePredictions,cfg)
    truthRaw=validation.Y(validation.caseIDs==double(record.caseID),:);
    assert(isequal(size(truthRaw),[1 6]), ...
        'recovery:run_feature_reconstruction:CaseTruth', ...
        'The validation cohort has no single row for case %d.',double(record.caseID));
    parts=cell(numel(registry.allSpaces),1);
    [posteriorPath,steps,mechanism]= ...
        artifact_provenance(A,loadStatus,cfg);
    for s=1:numel(registry.allSpaces)
        space=registry.allSpaces{s};
        meta=featureRegistry(featureRegistry.EvaluationSpace==string(space),:);
        truth=recovery.reconstruction_feature_values(truthRaw,space, ...
            'DenominatorFloor',policy.denominatorFloor).';
        k=height(meta);missing=nan(k,1);
        [meanValue,medianValue,q025,q975]=deal(missing);
        if valid
            transformed=featurePredictions{s};
            assert(size(transformed,1)==size(prediction,1)&& ...
                size(transformed,2)==k, ...
                'recovery:run_feature_reconstruction:FeaturePredictionShape', ...
                'Internal error: the feature predictions of evaluation space %d have the wrong size.',s);
            meanValue=mean(transformed,1).';
            q=nan(k,3);
            for j=1:k
                q(j,:)=utils.weighted_quantile( ...
                    transformed(:,j),[0.025 0.5 0.975]);
            end
            q025=q(:,1);medianValue=q(:,2);q975=q(:,3);
        end
        width=q975-q025;
        scale=double(meta.FeatureScale);scaleAvailable= ...
            logical(meta.NormalizedMetricAvailable);
        effectiveScale=scale;effectiveScale(~scaleAvailable)=NaN;
        errors=recovery.loss_consistent_point_errors( ...
            truth,meanValue,medianValue,effectiveScale);
        signedFromMean=errors.signedErrorFromPosteriorMean;
        signedFromMedian=errors.signedErrorFromPosteriorMedian;
        absoluteFromMedian=errors.absoluteErrorFromPosteriorMedian;
        squaredFromMean=errors.squaredErrorFromPosteriorMean;
        normalizedAbsoluteFromMedian= ...
            errors.normalizedAbsoluteErrorFromPosteriorMedian;
        normalizedSquaredFromMean= ...
            errors.normalizedSquaredErrorFromPosteriorMean;
        covered=nan(k,1);
        if valid,covered=double(truth>=q025&truth<=q975);end
        execution=repmat("unresolved_or_invalid",k,1);
        if valid,execution(:)="completed";end
        parts{s}=table(repmat(string(record.scenario),k,1), ...
            repmat(double(record.caseID),k,1), ...
            repmat(string(record.design),k,1), ...
            repmat(string(space),k,1),meta.EvaluationSpaceLabel, ...
            meta.EvaluationClass,meta.FeatureIndex,meta.ScalarFeature, ...
            meta.FeatureID,meta.FeatureFamily,meta.Units,truth,meanValue, ...
            medianValue,q025,q975,width,signedFromMean,signedFromMedian, ...
            absoluteFromMedian,squaredFromMean,scale, ...
            normalizedAbsoluteFromMedian,normalizedSquaredFromMean, ...
            signedFromMedian,absoluteFromMedian, ...
            normalizedAbsoluteFromMedian, ...
            scaleAvailable,meta.NormalizationUnavailableReason,covered, ...
            repmat(logical(loadStatus.loaded),k,1),repmat(logical(valid),k,1), ...
            repmat(string(loadStatus.state),k,1), ...
            repmat(double(steps),k,1),repmat(string(mechanism),k,1), ...
            repmat(string(posteriorPath),k,1), ...
            repmat(string(info.source),k,1),execution, ...
            repmat(string(reason),k,1), ...
            repmat("row_specific_available",k,1),false(k,1), ...
            'VariableNames',{'Scenario','CaseID', ...
            'FittingDesign','EvaluationSpace', ...
            'EvaluationSpaceLabel','EvaluationClass','FeatureIndex', ...
            'ScalarFeature','FeatureID','FeatureFamily','Units','Truth', ...
            'PosteriorMean','PosteriorMedian','Q025','Q975','IntervalWidth', ...
            'SignedErrorFromPosteriorMean', ...
            'SignedErrorFromPosteriorMedian', ...
            'AbsoluteErrorFromPosteriorMedian', ...
            'SquaredErrorFromPosteriorMean','FeatureScale', ...
            'NormalizedAbsoluteErrorFromPosteriorMedian', ...
            'NormalizedSquaredErrorFromPosteriorMean', ...
            'SignedMedianError','AbsoluteMedianError', ...
            'NormalizedAbsoluteError','NormalizedMetricAvailable', ...
            'NormalizationUnavailableReason','Covered95','ArtifactLoaded', ...
            'ReconstructionValid','CertificationStatus','CertifiedStepCount', ...
            'CertificationMechanism','PosteriorArtifactReference', ...
            'RawPredictionSource','ExecutionStatus','FailureReason', ...
            'CohortType','IncludedInMatchedCohort'});
    end
    T=vertcat(parts{:});
end

function T=availability_row( ...
        record,A,status,valid,info,reason,errorIdentifier,cfg)
    certified=logical(status.loaded);
    if isfield(status,'certified'),certified=certified&&status.certified;end
    [posteriorPath,steps,mechanism]= ...
        artifact_provenance(A,status,cfg);
    T=table(string(record.scenario),double(record.caseID), ...
        string(record.design),true,certified, ...
        logical(valid),string(status.state),string(reason), ...
        string(errorIdentifier),double(steps),string(mechanism), ...
        string(posteriorPath), ...
        string(info.source), ...
        double(info.gpEvaluationPassCount), ...
        double(info.gpBatchEvaluationCount), ...
        'VariableNames',{'Scenario','CaseID','FittingDesign', ...
        'Expected','CertifiedPosteriorAvailable', ...
        'ReconstructionValid','CertificationState','ExclusionReason', ...
        'ErrorIdentifier','CertifiedStepCount','CertificationMechanism', ...
        'PosteriorArtifactReference', ...
        'RawPredictionSource', ...
        'GPCellEvaluationPassCount','GPBatchEvaluationCount'});
end

function [pathValue,steps,mechanism]=artifact_provenance(A,status,cfg)
    pathValue='';steps=NaN;mechanism='';
    if ~logical(status.loaded)||isempty(A),return;end
    if isfield(A,'certification')&&isfield(A.certification,'provider')&& ...
            isfield(A.certification.provider,'stepCount')
        steps=double(A.certification.provider.stepCount);
    end
    if isfield(A,'certification')&& ...
            isfield(A.certification,'certificationMechanism')
        mechanism=char(string( ...
            A.certification.certificationMechanism));
    end
    % The shipped full draws lie outside the run, in thesis_results/.
    shipped=study.reads_shipped_draws(cfg);
    try
        if isfield(A,'paths')&&isfield(A.paths,'posteriorPath')
            pathValue=relative_reference(A.paths.posteriorPath,cfg,shipped);
        elseif isfield(A,'certificationPath')
            pathValue=relative_reference(A.certificationPath,cfg,shipped);
        end
    catch
        pathValue='';
    end
end

