function value=relative_reference(pathValue,cfg,shippedSource)
%RELATIVE_REFERENCE A source path relative to the run root.
%   Posterior artifacts of the run's own campaign lie below the run root. A
%   shipped source (SHIPPEDSOURCE true) may lie outside it: a native rerun
%   reads the shipped models, and without an inversion of its own the
%   shipped posterior draws, from thesis_results/. Its path is then recorded
%   relative to the repository (thesis_results/...), or as it is, with '/', when
%   it lies elsewhere.
    if nargin<3,shippedSource=false;end
    value=char(string(pathValue));
    if isempty(value),return;end
    pathValue=utils.absolute_path(value);
    root=utils.absolute_path(cfg.paths.runRoot);
    prefix=[root filesep];
    inside=startsWith(lower(pathValue),lower(prefix));
    assert(inside||shippedSource, ...
        'recovery:run_feature_reconstruction:ArtifactPath', ...
        'A saved reconstruction source path escapes the bound run root.');
    repository=[utils.absolute_path(study.root()) filesep];
    if inside
        value=strrep(pathValue(numel(prefix)+1:end),'\','/');
    elseif startsWith(lower(pathValue),lower(repository))
        value=strrep(pathValue(numel(repository)+1:end),'\','/');
    else
        value=strrep(pathValue,'\','/');
    end
end

