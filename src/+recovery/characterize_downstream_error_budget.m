function [T,status]=training_predictions(cfg,options,csvPath)
    status=struct('source','','reference','', ...
        'gpEvaluationPasses',0,'gpBatchEvaluations',0);
    assert(isfile(cfg.files.dataset), ...
        'recovery:characterize_downstream_error_budget:MissingDataset', ...
        'The saved canonical training dataset is required.');
    % Datasets name the case IDs and source rows in one of two ways; load
    % the variables the file has (no warning for the other names).
    present=whos('-file',cfg.files.dataset);
    names=intersect({'X_train','Y_train','trainCaseIDs','trainingCaseIDs', ...
        'trainSourceRows','trainingSourceRows'},{present.name},'stable');
    data=utils.load_plain_mat(cfg.files.dataset,names{:});
    [X,Y,caseIDs,sourceRows]=canonical_training_data(data);
    model=options.GPModel;
    if isempty(model)
        assert(isfile(cfg.files.gp), ...
            'recovery:characterize_downstream_error_budget:MissingGPArtifact', ...
            'The saved canonical GP artifact is required.');
        saved=load(cfg.files.gp,'gp');
        assert(isfield(saved,'gp'), ...
            'recovery:characterize_downstream_error_budget:GPArtifact', ...
            'The canonical GP artifact does not contain gp.');
        model=saved.gp;
    end
    [meanPrediction,calibratedVariance,rawUQLabVariance,batches]= ...
        evaluate_in_batches( ...
        model,X,@(m,x)default_gp_evaluator(m,x,cfg),double(options.BatchSize));
    T=make_prediction_table(caseIDs,sourceRows,Y,meanPrediction, ...
        rawUQLabVariance,calibratedVariance,cfg.outputNames);
    status.source='canonical_GP_evaluated_once_at_saved_training_inputs';
    status.reference=relative_reference(csvPath,cfg);
    status.gpEvaluationPasses=1;status.gpBatchEvaluations=batches;
    if options.WriteOutputs
        utils.atomic_write_table(csvPath,T);
    end
end

function T=canonical_prediction_table(T,cohort,outputNames,expectedCaseCount)
    required={'CaseID','OutputIndex','COMSOL','GPMean', ...
        'RawUQLabVariance','CalibratedEmulatorVariance'};
    assert(istable(T)&&all(ismember(required,T.Properties.VariableNames))&& ...
        ~isempty(T),'recovery:characterize_downstream_error_budget:PredictionSchema', ...
        'A saved prediction table is missing required columns or rows.');
    T.CaseID=double(T.CaseID);T.OutputIndex=double(T.OutputIndex);
    T.COMSOL=double(T.COMSOL);T.GPMean=double(T.GPMean);
    T.RawUQLabVariance=double(T.RawUQLabVariance);
    T.CalibratedEmulatorVariance=double(T.CalibratedEmulatorVariance);
    assert(all(isfinite(T{:,required}),'all')&& ...
        all(T.RawUQLabVariance>=0)&& ...
        all(T.CalibratedEmulatorVariance>=0)&& ...
        all(ismember(T.OutputIndex,1:6)), ...
        'recovery:characterize_downstream_error_budget:PredictionValues', ...
        'Saved predictions must be finite with nonnegative GP variances.');
    caseIDs=unique(T.CaseID,'stable');
    if ~isempty(expectedCaseCount)
        assert(numel(caseIDs)==expectedCaseCount, ...
            'recovery:characterize_downstream_error_budget:CohortSize', ...
            'The saved prediction cohort has an unexpected case count.');
    end
    requireComplete=~isempty(expectedCaseCount);
    for i=1:numel(caseIDs)
        rows=T.CaseID==caseIDs(i);
        observed=sort(T.OutputIndex(rows));
        assert(numel(unique(observed))==numel(observed)&& ...
            (~requireComplete|| ...
            (nnz(rows)==6&&isequal(observed,(1:6).'))), ...
            'recovery:characterize_downstream_error_budget:OutputCoverage', ...
            ['Prediction rows must be unique by case/output; complete external ' ...
             'and feature cohorts require all six outputs.']);
    end
    [~,caseOrder]=ismember(T.CaseID,caseIDs);
    [~,order]=sortrows([caseOrder T.OutputIndex],[1 2]);T=T(order,:);
    if ~ismember('Output',T.Properties.VariableNames)
        T.Output=string(outputNames(T.OutputIndex)).';
        T.Output=reshape(T.Output,[],1);
    else
        T.Output=string(T.Output);
        expectedOutput=reshape(string(outputNames(T.OutputIndex)),[],1);
        assert(all(T.Output==expectedOutput), ...
            'recovery:characterize_downstream_error_budget:OutputOrder', ...
            'Saved prediction output names do not match canonical ordering.');
    end
    T.Cohort=repmat(string(cohort),height(T),1);
end

function T=complete_prediction_cases(T)
    caseIDs=unique(T.CaseID,'stable');complete=false(numel(caseIDs),1);
    for i=1:numel(caseIDs)
        outputs=sort(double(T.OutputIndex(T.CaseID==caseIDs(i))));
