function result = characterize_downstream_error_budget(cfg,varargin)
%CHARACTERIZE_DOWNSTREAM_ERROR_BUDGET The error budget of the reconstructed features: surrogate error against measurement noise.
%   RESULT = recovery.characterize_downstream_error_budget(CFG, ...) combines
%   the saved GP predictions of the held-out and the development cases
%   (surrogates.fit_fixed and the assessment), the surrogate-only feature
%   reconstruction ('SurrogateOnlyReference'), the frozen measurement model
%   (8% CV of each pressure) and the analytic delta-method Jacobians of the
%   features (recovery.reconstruction_feature_jacobian): per feature and
%   case, the surrogate error, the propagated measurement uncertainty and
%   their ratio, and the GP's in-sample against held-out metrics
%   (recovery.gp_train_validation_metrics). It reports the numbers only: no
%   acceptance threshold or adequacy decision.
%   Options: 'SurrogateOnlyReference', 'FeatureRegistryTable', 'GPModel',
%   'OutputRoot', 'BatchSize' (5000), 'WriteOutputs'
%   (true), 'MeasurementScaleFloor' (1e-8: the smallest |mean| in the
%   measurement variance) and 'DenominatorFloor' (default the configured
%   floor of the feature reconstruction, else of the ratios, else 1e-12).
%   Side effects: with 'WriteOutputs', writes the long-form, per-feature,
%   raw-output and active-feature tables and the GP's predictions at the
%   development inputs below 'OutputRoot'.
%   Computation: about a minute (the GP at the development inputs).

    parser=inputParser;
    parser.FunctionName='recovery.characterize_downstream_error_budget';
    addParameter(parser,'SurrogateOnlyReference',table(),@istable);
    addParameter(parser,'FeatureRegistryTable',table(),@istable);
    addParameter(parser,'GPModel',[],@(x)true);
    addParameter(parser,'OutputRoot',default_output_root(cfg),@text_scalar);
    addParameter(parser,'BatchSize',5000,@positive_integer);
    addParameter(parser,'WriteOutputs',true,@logical_scalar);
    addParameter(parser,'MeasurementScaleFloor',1e-8,@positive_scalar);
    addParameter(parser,'DenominatorFloor',default_denominator_floor(cfg), ...
        @positive_scalar);
    parse(parser,varargin{:});options=parser.Results;

    assert(isfield(cfg,'dataMode')&&strcmp(cfg.dataMode,'real')&& ...
        isfield(cfg,'meas_cv')&&double(cfg.meas_cv)>0&& ...
        isfield(cfg,'emulatorErrorCalibration')&& ...
        isfield(cfg.emulatorErrorCalibration,'tau_squared_mbar2')&& ...
        numel(cfg.emulatorErrorCalibration.tau_squared_mbar2)==6, ...
        'recovery:characterize_downstream_error_budget:Configuration', ...
        ['The error budget is defined for the fixed route with a measurement CV ' ...
         '(settings A.2) and the calibration of its six outputs.']);
    outputRoot=char(string(options.OutputRoot));
    paths=output_paths(outputRoot);
    [validationPredictions,validationReference]= ...
        validation_predictions(cfg);
    validationPredictions=canonical_prediction_table( ...
        validationPredictions,'validation',cfg.outputNames, ...
        expected_external_count(cfg));
    [trainingPredictions,trainingStatus]=training_predictions( ...
        cfg,options,paths.trainingPredictions);
    trainingPredictions=canonical_prediction_table( ...
        trainingPredictions,'training',cfg.outputNames,[]);
    completeTrainingPredictions=complete_prediction_cases(trainingPredictions);
    gpTrainValidation=recovery.gp_train_validation_metrics( ...
        trainingPredictions,validationPredictions,cfg.outputNames);

    registry=recovery.reconstruction_feature_registry();
    task8Reference=task8_reference(cfg,options.SurrogateOnlyReference);
    featureRegistry=feature_registry_with_scales(cfg, ...
        options.FeatureRegistryTable,registry,validationPredictions, ...
        options.DenominatorFloor);
    % Raw per-output diagnostics use every observed development scalar. The
    % six-output reconstruction features deliberately use only complete
    % development vectors; no missing target is imputed.
    predictionTables={completeTrainingPredictions,validationPredictions};
    cohortNames={'training','validation'};
    longParts=cell(2,1);
    for i=1:2
        longParts{i}=characterize_cohort(predictionTables{i},cohortNames{i}, ...
            registry,featureRegistry,task8Reference,cfg,options, ...
            trainingStatus,validationReference);
    end
    longForm=vertcat(longParts{:});
    perFeature=summarize_per_feature(longForm,double(cfg.meas_cv));
    rawOutput=perFeature(perFeature.EvaluationSpace=="all_six",:);
    activeFeatures=perFeature(ismember(perFeature.EvaluationSpace, ...
        ["ratios_only","physics_guided_full_rank_six"]),:);
    diagnosticFamilies=summarize_diagnostic_families(perFeature);
    predictiveCalibration=perFeature(:,{ ...
        'Cohort','EvaluationSpace','EvaluationClass','FeatureIndex', ...
        'FeatureID','FeatureFamily','Units','Formula','IncludedCaseCount', ...
        'CalibratedPredictiveIntervalCoverage95', ...
        'MeanCalibratedStandardizedResidual', ...
        'RMSCalibratedStandardizedResidual', ...
        'MeanCalibratedEmulatorVarianceShare', ...
        'AggregateCalibratedEmulatorVarianceShare', ...
        'RawUQLabPredictiveIntervalCoverage95'});
    trainValidationComparison=train_validation_comparison(perFeature);
    maximumProvenance=maximum_provenance(longForm);

    status=struct( ...
        'schema_version','downstream_surrogate_error_budget_status_v2', ...
        'enabled',true, ...
        'computationally_complete',all(longForm.ComputationallyValid), ...
        'measurement_cv',double(cfg.meas_cv), ...
        'raw_measurement_sd_formula', ...
            [num2str(double(cfg.meas_cv)) ' * max(abs(saved_GP_mean_at_truth), 1e-8)'], ...
        'raw_measurement_covariance', ...
            ['diag((' num2str(double(cfg.meas_cv)) '*max(abs(saved_GP_mean_at_truth),1e-8)).^2)'], ...
        'derived_measurement_covariance','J_f * Sigma_meas_p * J_f''', ...
        'raw_uqlab_reference_covariance', ...
            'diag(saved_S02_RawUQLabVariance)', ...
        'production_calibrated_emulator_covariance', ...
            'diag(saved_S02_CalibratedEmulatorVariance)', ...
        'derived_gp_covariance', ...
            'J_f * Sigma_emu_calibrated_p * J_f''', ...
        'empirical_standardized_error_formula', ...
            '(GP_feature_mean_at_truth-COMSOL_feature_truth)/MeasurementSD', ...
        'empirical_mse_share_formula', ...
            'EmpiricalMSE/(EmpiricalMSE+MeanMeasurementVariance)', ...
        'gp_reported_variance_share_formula', ...
            ['CalibratedEmulatorVariance/' ...
             '(MeasurementVariance+CalibratedEmulatorVariance)'], ...
        'raw_cross_output_gp_covariance_assumption', ...
            'diagonal_only_no_cross_output_covariance_invented', ...
        'delta_method_semantics', ...
            'analytic_Jacobian_at_saved_GP_mean_at_truth', ...
        'validation_prediction_reference',validationReference, ...
        'task8_reference_available',~isempty(task8Reference), ...
        'task8_reference_rows_reused',sum(longForm.Task8ReferenceUsed), ...
        'training_prediction_source',trainingStatus.source, ...
        'training_prediction_reference',trainingStatus.reference, ...
        'training_gp_evaluation_passes',trainingStatus.gpEvaluationPasses, ...
        'training_gp_batch_evaluations',trainingStatus.gpBatchEvaluations, ...
        'training_case_count',numel(unique(trainingPredictions.CaseID)), ...
        'training_complete_vector_case_count', ...
            numel(unique(completeTrainingPredictions.CaseID)), ...
        'training_observed_scalar_count',height(trainingPredictions), ...
        'validation_case_count',numel(unique(validationPredictions.CaseID)), ...
        'raw_train_validation_metric_rows',height(gpTrainValidation.metrics), ...
        'raw_train_validation_difference_rows', ...
            height(gpTrainValidation.differences), ...
        'scalar_feature_rows',height(longForm), ...
        'mcmc_runs_performed',0, ...
        'likelihood_evaluations_performed',0, ...
        'surrogate_fits_performed',0, ...
        'conditional_inversions_performed',0, ...
        'comsol_runs_performed',0);

    if options.WriteOutputs
        if ~isfolder(outputRoot),mkdir(outputRoot);end
        write_outputs(paths,longForm,perFeature,rawOutput,activeFeatures, ...
            diagnosticFamilies,predictiveCalibration, ...
            trainValidationComparison,maximumProvenance,gpTrainValidation, ...
            status);
    end
    result=struct('paths',paths,'status',status,'longForm',longForm, ...
        'perFeature',perFeature,'rawOutputSummary',rawOutput, ...
        'activeFeatureSummary',activeFeatures, ...
        'diagnosticFeatureFamilySummary',diagnosticFamilies, ...
        'predictiveCalibration',predictiveCalibration, ...
        'trainValidationMetricComparison',trainValidationComparison, ...
        'maximumStandardizedErrorProvenance',maximumProvenance, ...
        'gpTrainValidationMetrics',gpTrainValidation.metrics, ...
        'gpTrainValidationMetricDifferences',gpTrainValidation.differences, ...
        'trainingPredictions',trainingPredictions, ...
        'trainingCompleteVectorPredictions',completeTrainingPredictions, ...
        'validationPredictions',validationPredictions);
end

function rows=characterize_cohort(rawTable,cohort,registry,featureRegistry, ...
        task8Reference,cfg,options,trainingStatus,validationReference)
    caseIDs=unique(rawTable.CaseID,'stable');
    parts=cell(numel(caseIDs)*numel(registry.allSpaces),1);cursor=0;
    for c=1:numel(caseIDs)
        raw=case_raw_vectors(rawTable,caseIDs(c));
        sigmaMeasurementRaw=diag((double(cfg.meas_cv).*max( ...
            abs(raw.mean),double(options.MeasurementScaleFloor))).^2);
        sigmaRawUQLab=diag(raw.rawUQLabVariance);
        sigmaCalibratedEmulator=diag(raw.calibratedEmulatorVariance);
        for s=1:numel(registry.allSpaces)
            cursor=cursor+1;space=registry.allSpaces{s};
            meta=featureRegistry( ...
                featureRegistry.EvaluationSpace==string(space),:);
            predicted=recovery.reconstruction_feature_values( ...
                raw.mean,space,'DenominatorFloor',options.DenominatorFloor).';
            truth=recovery.reconstruction_feature_values( ...
                raw.truth,space,'DenominatorFloor',options.DenominatorFloor).';
            [predicted,truth,task8Used,consistencyError]= ...
                reuse_task8_reference(task8Reference,cohort,caseIDs(c), ...
                space,predicted,truth);
            J=recovery.reconstruction_feature_jacobian( ...
                raw.mean,space,'DenominatorFloor',options.DenominatorFloor);
            measurementCovariance=propagate_covariance( ...
                J,sigmaMeasurementRaw,'measurement',caseIDs(c),space);
            calibratedCovariance=propagate_covariance( ...
                J,sigmaCalibratedEmulator,'calibrated emulator', ...
                caseIDs(c),space);
            rawUQLabCovariance=propagate_covariance( ...
                J,sigmaRawUQLab,'raw UQLab',caseIDs(c),space);
            measurementVariance=diag(measurementCovariance);
            calibratedVariance=diag(calibratedCovariance);
            rawUQLabVariance=diag(rawUQLabCovariance);
            measurementSD=sqrt(measurementVariance);
            calibratedSD=sqrt(calibratedVariance);
            rawUQLabSD=sqrt(rawUQLabVariance);
            empiricalError=predicted-truth;
            standardized=empiricalError./measurementSD;
            calibratedShare=calibratedVariance./ ...
                (measurementVariance+calibratedVariance);
            empiricalSquaredShare=empiricalError.^2./ ...
                (empiricalError.^2+measurementVariance);
            calibratedResidualAvailable=calibratedSD>0&isfinite(calibratedSD);
            calibratedStandardized=nan(size(calibratedSD));
            calibratedStandardized(calibratedResidualAvailable)= ...
                empiricalError(calibratedResidualAvailable)./ ...
                calibratedSD(calibratedResidualAvailable);
            calibratedMissingReason=repmat("",numel(calibratedSD),1);
            calibratedMissingReason(~calibratedResidualAvailable)= ...
                "zero_calibrated_emulator_SD";
            rawResidualAvailable=rawUQLabSD>0&isfinite(rawUQLabSD);
            rawStandardized=nan(size(rawUQLabSD));
            rawStandardized(rawResidualAvailable)= ...
                empiricalError(rawResidualAvailable)./ ...
                rawUQLabSD(rawResidualAvailable);
            rawMissingReason=repmat("",numel(rawUQLabSD),1);
            rawMissingReason(~rawResidualAvailable)= ...
                "zero_raw_UQLab_predictive_SD";
            calibratedLower=predicted-1.96*calibratedSD;
            calibratedUpper=predicted+1.96*calibratedSD;
            calibratedCovered=double( ...
                truth>=calibratedLower&truth<=calibratedUpper);
            rawLower=predicted-1.96*rawUQLabSD;
            rawUpper=predicted+1.96*rawUQLabSD;
            rawCovered=double(truth>=rawLower&truth<=rawUpper);
            k=height(meta);
            if strcmp(cohort,'training')
                source=trainingStatus.source;reference=trainingStatus.reference;
            else
                source='saved_S02_validation_predictions';
                reference=validationReference;
            end
            rows=table(repmat(string(cohort),k,1), ...
                repmat(caseIDs(c),k,1),repmat(string(space),k,1), ...
                meta.EvaluationSpaceLabel,meta.EvaluationClass, ...
                meta.FeatureIndex,meta.ScalarFeature,meta.FeatureID, ...
                meta.FeatureFamily,meta.Units,meta.Formula,truth,predicted, ...
                empiricalError,abs(empiricalError),empiricalError.^2, ...
                measurementVariance,measurementSD,standardized, ...
                abs(standardized),standardized.^2,calibratedVariance, ...
                calibratedSD,calibratedShare,rawUQLabVariance,rawUQLabSD, ...
                empiricalSquaredShare,calibratedLower,calibratedUpper, ...
                calibratedCovered,rawLower,rawUpper,rawCovered, ...
                calibratedStandardized,calibratedResidualAvailable, ...
                calibratedMissingReason,rawStandardized, ...
                rawResidualAvailable,rawMissingReason, ...
                repmat(task8Used,k,1),consistencyError, ...
                meta.FeatureScale,meta.NormalizedMetricAvailable, ...
                meta.NormalizationUnavailableReason, ...
                true(k,1),repmat("",k,1),repmat(string(source),k,1), ...
                repmat(string(reference),k,1), ...
                repmat("independent_raw_pressure_measurement_errors",k,1), ...
                repmat("diagonal_calibrated_raw_pressure_emulator_covariance", ...
                    k,1), ...
                'VariableNames',{'Cohort','CaseID','EvaluationSpace', ...
                'EvaluationSpaceLabel','EvaluationClass','FeatureIndex', ...
                'ScalarFeature','FeatureID','FeatureFamily','Units','Formula', ...
                'Truth','GPFeatureMeanAtTruth','EmpiricalSurrogateError', ...
                'AbsoluteEmpiricalSurrogateError', ...
                'SquaredEmpiricalSurrogateError','MeasurementVariance', ...
                'MeasurementSD','EmpiricalStandardizedSurrogateError', ...
                'AbsoluteEmpiricalStandardizedSurrogateError', ...
                'SquaredEmpiricalStandardizedSurrogateError', ...
                'CalibratedEmulatorVariance','CalibratedEmulatorSD', ...
                'CalibratedEmulatorVarianceShare','RawUQLabFeatureVariance', ...
                'RawUQLabFeatureSD','PerCaseEmpiricalSquaredErrorShare', ...
                'CalibratedIntervalLower95','CalibratedIntervalUpper95', ...
                'CalibratedIntervalCovered95','RawUQLabIntervalLower95', ...
                'RawUQLabIntervalUpper95','RawUQLabIntervalCovered95', ...
                'CalibratedStandardizedResidual', ...
                'CalibratedStandardizedResidualAvailable', ...
                'CalibratedStandardizedResidualMissingReason', ...
                'RawUQLabStandardizedResidual', ...
                'RawUQLabStandardizedResidualAvailable', ...
                'RawUQLabStandardizedResidualMissingReason', ...
                'Task8ReferenceUsed','Task8ConsistencyAbsoluteError', ...
                'FeatureScale','NormalizedMetricAvailable', ...
                'NormalizationUnavailableReason','ComputationallyValid', ...
                'MissingValueReason','PredictionSource', ...
                'SourceArtifactReference','MeasurementCovarianceAssumption', ...
                'GPCovarianceAssumption'});
            parts{cursor}=rows;
        end
    end
    rows=vertcat(parts{:});
end

function covariance=propagate_covariance(J,rawCovariance,label,caseID,space)
    covariance=J*((rawCovariance+rawCovariance.')/2)*J.';
    covariance=(covariance+covariance.')/2;
    assert(all(isfinite(covariance),'all')&& ...
        size(covariance,1)==size(J,1)&&size(covariance,2)==size(J,1), ...
        'recovery:characterize_downstream_error_budget:CovarianceShape', ...
        '%s covariance is invalid for CaseID %d, space %s.', ...
        label,caseID,space);
    eigenvalues=eig(covariance);
    tolerance=1e-12*max(1,norm(covariance,'fro'));
    assert(min(eigenvalues)>=-tolerance, ...
        'recovery:characterize_downstream_error_budget:CovariancePSD', ...
        '%s covariance is materially non-PSD for CaseID %d, space %s.', ...
        label,caseID,space);
    diagonal=diag(covariance);
    tiny=diagonal<0&diagonal>=-tolerance;
    if any(tiny)
        covariance=covariance-diag(diagonal)+diag(max(diagonal,0));
        covariance=(covariance+covariance.')/2;
    end
end

function [prediction,truth,used,errorValue]=reuse_task8_reference( ...
        T,cohort,caseID,space,prediction,truth)
    k=numel(prediction);used=false;errorValue=zeros(k,1);
    if ~strcmp(cohort,'validation')||isempty(T),return;end
    required={'CaseID','EvaluationSpace','FeatureIndex', ...
        'SurrogatePrediction','Truth','ReconstructionValid'};
    assert(all(ismember(required,T.Properties.VariableNames)), ...
        'recovery:characterize_downstream_error_budget:Task8Schema', ...
        ['The saved feature-reconstruction table lacks the column(s) %s; rerun the ' ...
         'step ''recovery''.'],strjoin(setdiff(required,T.Properties.VariableNames),', '));
    rows=double(T.CaseID)==caseID& ...
        string(T.EvaluationSpace)==string(space)&logical(T.ReconstructionValid);
    one=T(rows,:);[~,order]=sort(double(one.FeatureIndex));one=one(order,:);
    assert(height(one)==k&&isequal(double(one.FeatureIndex),(1:k).'), ...
        'recovery:characterize_downstream_error_budget:Task8Coverage', ...
        'Task-8 reference is incomplete for CaseID %d, space %s.',caseID,space);
    savedPrediction=double(one.SurrogatePrediction);
    savedTruth=double(one.Truth);
    errorValue=max(abs(savedPrediction-prediction),abs(savedTruth-truth));
    tolerance=1e-10*max(1,max(abs([prediction;truth])));
    assert(all(errorValue<=tolerance), ...
        'recovery:characterize_downstream_error_budget:Task8Consistency', ...
        'Task-8 and direct feature transforms disagree for CaseID %d.',caseID);
    prediction=savedPrediction;truth=savedTruth;used=true;
end

function T=summarize_per_feature(longForm,measurementCV)
    keys={'Cohort','EvaluationSpace','EvaluationSpaceLabel', ...
        'EvaluationClass','FeatureIndex','ScalarFeature','FeatureID', ...
        'FeatureFamily','Units','Formula'};
    [groupID,groups]=findgroups(longForm(:,keys));
    parts=cell(height(groups),1);
    for g=1:height(groups)
        one=longForm(groupID==g&longForm.ComputationallyValid,:);
        prefix=groups(g,:);n=height(one);
        assert(n>0,'recovery:characterize_downstream_error_budget:EmptyGroup', ...
            'Every reported feature group must contain a valid case.');
        empirical=one.EmpiricalSurrogateError;
        standardized=one.EmpiricalStandardizedSurrogateError;
        empiricalMSE=mean(empirical.^2);
        meanMeasurementVariance=mean(one.MeasurementVariance);
        meanCalibratedVariance=mean(one.CalibratedEmulatorVariance);
        prefix.IncludedCaseCount=n;
        prefix.EmpiricalBias=mean(empirical);
        prefix.EmpiricalMAE=mean(abs(empirical));
        prefix.EmpiricalMSE=empiricalMSE;
        prefix.EmpiricalRMSE=sqrt(empiricalMSE);
        prefix.BiasInMeasurementSDUnits=mean(standardized);
        prefix.RMSErrorInMeasurementSDUnits=sqrt(mean(standardized.^2));
        prefix.MaximumAbsoluteStandardizedSurrogateError= ...
            max(abs(standardized));
        prefix.MaximumAbsoluteNativeSurrogateError=max(abs(empirical));
        prefix.MeanMeasurementVariance=meanMeasurementVariance;
        prefix.MeanCalibratedEmulatorVariance=meanCalibratedVariance;
        prefix.MeanRawUQLabFeatureVariance=mean(one.RawUQLabFeatureVariance);
        prefix.EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance= ...
            empiricalMSE/(empiricalMSE+meanMeasurementVariance);
        prefix.MeanCalibratedEmulatorVarianceShare=mean( ...
            one.CalibratedEmulatorVarianceShare);
        prefix.AggregateCalibratedEmulatorVarianceShare= ...
            meanCalibratedVariance/ ...
            (meanMeasurementVariance+meanCalibratedVariance);
        prefix.CalibratedPredictiveIntervalCoverage95=mean( ...
            one.CalibratedIntervalCovered95);
        calibratedAvailable=one.CalibratedStandardizedResidualAvailable;
        prefix.MeanCalibratedStandardizedResidual=mean_or_nan( ...
            one.CalibratedStandardizedResidual(calibratedAvailable));
        prefix.RMSCalibratedStandardizedResidual=sqrt(mean_or_nan( ...
            one.CalibratedStandardizedResidual(calibratedAvailable).^2));
        prefix.RawUQLabPredictiveIntervalCoverage95=mean( ...
            one.RawUQLabIntervalCovered95);
        rawAvailable=one.RawUQLabStandardizedResidualAvailable;
        prefix.MeanRawUQLabStandardizedResidual=mean_or_nan( ...
            one.RawUQLabStandardizedResidual(rawAvailable));
        prefix.RMSRawUQLabStandardizedResidual=sqrt(mean_or_nan( ...
            one.RawUQLabStandardizedResidual(rawAvailable).^2));
        prefix.MeasurementCV=measurementCV;
        parts{g}=prefix;
    end
    T=vertcat(parts{:});
end

function T=summarize_diagnostic_families(perFeature)
    input=perFeature(perFeature.EvaluationClass=="expanded_diagnostic",:);
    keys={'Cohort','EvaluationSpace','EvaluationSpaceLabel', ...
        'EvaluationClass','FeatureFamily'};
    [groupID,groups]=findgroups(input(:,keys));parts=cell(height(groups),1);
    for g=1:height(groups)
        one=input(groupID==g,:);row=groups(g,:);
        row.NumberScalarFeatures=height(one);
        row.IncludedCaseCount=min(one.IncludedCaseCount);
        row.MeanEmpiricalBiasAcrossFeatures=mean(one.EmpiricalBias);
        row.MeanEmpiricalMAEAcrossFeatures=mean(one.EmpiricalMAE);
        row.RMSEAcrossEquallyWeightedFeatureMSE=sqrt(mean(one.EmpiricalMSE));
        row.MeanRMSMeasurementStandardizedErrorAcrossFeatures= ...
            mean(one.RMSErrorInMeasurementSDUnits);
        row.MaximumAbsoluteStandardizedSurrogateError= ...
            max(one.MaximumAbsoluteStandardizedSurrogateError);
        row.MeanEmpiricalMSEShare=mean( ...
            one.EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance);
        row.MeanCalibratedEmulatorVarianceShare=mean( ...
            one.MeanCalibratedEmulatorVarianceShare);
        row.MeanCalibratedPredictiveIntervalCoverage95= ...
            mean(one.CalibratedPredictiveIntervalCoverage95);
        row.MeanRawUQLabPredictiveIntervalCoverage95= ...
            mean(one.RawUQLabPredictiveIntervalCoverage95);
        row.EqualScalarFeatureWeighting=true;
        parts{g}=row;
    end
    T=vertcat(parts{:});
end

function T=train_validation_comparison(perFeature)
    keys={'EvaluationSpace','EvaluationSpaceLabel','EvaluationClass', ...
        'FeatureIndex','ScalarFeature','FeatureID','FeatureFamily','Units', ...
        'Formula'};
    training=perFeature(perFeature.Cohort=="training",:);
    validation=perFeature(perFeature.Cohort=="validation",:);
    [hit,index]=ismember(validation(:,keys),training(:,keys),'rows');
    assert(all(hit)&&numel(unique(index))==height(validation), ...
        'recovery:characterize_downstream_error_budget:CohortPairing', ...
        'Every validation feature row needs one training row with the same keys.');
    training=training(index,:);T=validation(:,keys);
    T.TrainingCaseCount=training.IncludedCaseCount;
    T.ValidationCaseCount=validation.IncludedCaseCount;
    metricNames={'EmpiricalBias','EmpiricalMAE','EmpiricalRMSE', ...
        'BiasInMeasurementSDUnits','RMSErrorInMeasurementSDUnits', ...
        'MaximumAbsoluteStandardizedSurrogateError', ...
        'MaximumAbsoluteNativeSurrogateError', ...
        'CalibratedPredictiveIntervalCoverage95', ...
        'MeanCalibratedEmulatorVarianceShare', ...
        'RawUQLabPredictiveIntervalCoverage95', ...
        'EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance'};
    for i=1:numel(metricNames)
        name=metricNames{i};
        prefixes={'Training_','Validation_','ValidationMinusTraining_'};
        values={training.(name),validation.(name),validation.(name)-training.(name)};
        for k=1:numel(prefixes)
            column=comparison_column_name(prefixes{k},name);
            T.(column)=values{k};
            index=strcmp(T.Properties.VariableNames,column);
            T.Properties.VariableDescriptions{index}=[prefixes{k} name];
        end
    end
    T.ScientificInterpretation=repmat("not_generated",height(T),1);
end

function column=comparison_column_name(prefix,metric)
    column=[prefix metric];
    % R2024a permits 63 characters. Keep existing valid names unchanged.
    if numel(column)>63
        switch metric
            case 'MaximumAbsoluteStandardizedSurrogateError'
                metric='MaxAbsStandardizedSurrogateError';
            case 'EmpiricalMSEShareOfEmpiricalMSEPlusMeanMeasurementVariance'
                metric='EmpiricalMSEShare';
        end
        column=[prefix metric];
    end
    assert(numel(column)<=63, ...
        'recovery:characterize_downstream_error_budget:ComparisonColumnName', ...
        'A comparison column needs an explicit portable alias.');
end

function T=maximum_provenance(longForm)
    keys={'Cohort','EvaluationSpace','EvaluationSpaceLabel', ...
        'EvaluationClass','FeatureIndex','ScalarFeature','FeatureID', ...
        'FeatureFamily','Units','Formula'};
    [groupID,groups]=findgroups(longForm(:,keys));parts=cell(2*height(groups),1);
    cursor=0;
    for g=1:height(groups)
        one=longForm(groupID==g&longForm.ComputationallyValid,:);
        [~,standardizedIndex]=max( ...
            one.AbsoluteEmpiricalStandardizedSurrogateError);
        [~,nativeIndex]=max(one.AbsoluteEmpiricalSurrogateError);
        cursor=cursor+1;parts{cursor}=provenance_row(groups(g,:), ...
            one(standardizedIndex,:), ...
            "absolute_empirical_error_in_measurement_SD_units", ...
            one.AbsoluteEmpiricalStandardizedSurrogateError(standardizedIndex));
