function value=relative_reference(pathValue,cfg)
%RELATIVE_REFERENCE A source path relative to the run, or to the repository for a shipped source.
%   A rerun on the shipped results reads the saved validation predictions
%   from thesis_results/ (outside the run); their path is then recorded
%   relative to the repository (thesis_results/...), as
%   recovery.run_feature_reconstruction records it.
    value=char(string(pathValue));if isempty(value),return;end
    pathValue=utils.absolute_path(value);root=utils.absolute_path(cfg.paths.runRoot);
    prefix=[root filesep];
    repository=[utils.absolute_path(study.root()) filesep];
    if startsWith(lower(pathValue),lower(prefix))
        value=strrep(pathValue(numel(prefix)+1:end),'\','/');
    elseif startsWith(lower(pathValue),lower(repository))
        value=strrep(pathValue(numel(repository)+1:end),'\','/');
    end
end

