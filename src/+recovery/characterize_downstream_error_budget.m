function [X,Y,caseIDs,sourceRows]=canonical_training_data(data)
    assert(isfield(data,'X_train')&&isfield(data,'Y_train'), ...
        'recovery:characterize_downstream_error_budget:TrainingData', ...
        'Saved training inputs and truths are required.');
    X=double(data.X_train);Y=double(data.Y_train);n=size(X,1);
    assert(isequal(size(Y),[n 6])&&size(X,2)==4&&n>0&& ...
        all(isfinite(X),'all')&&~any(isinf(Y),'all'), ...
        'recovery:characterize_downstream_error_budget:TrainingShape', ...
        ['Training inputs must be finite; unavailable targets must be NaN. ' ...
         'Complete-vector feature comparisons use complete development rows.']);
    if isfield(data,'trainCaseIDs')
        caseIDs=double(data.trainCaseIDs(:));
    elseif isfield(data,'trainingCaseIDs')
        caseIDs=double(data.trainingCaseIDs(:));
    else
        caseIDs=(1:n).';
    end
    if isfield(data,'trainSourceRows')
        sourceRows=double(data.trainSourceRows(:));
    elseif isfield(data,'trainingSourceRows')
        sourceRows=double(data.trainingSourceRows(:));
    else
        sourceRows=(1:n).';
    end
    assert(numel(caseIDs)==n&&numel(unique(caseIDs))==n&& ...
        numel(sourceRows)==n, ...
        'recovery:characterize_downstream_error_budget:TrainingIDs', ...
        'Training case and source-row identifiers must match the input rows.');
    assert(any(all(isfinite(Y),2)), ...
        'recovery:characterize_downstream_error_budget:NoCompleteDevelopmentCase', ...
        'Complete-vector downstream features require complete development cases.');
end

function [mu,calibratedVariance,rawUQLabVariance,batches]= ...
        evaluate_in_batches(model,X,evaluator,batchSize)
    n=size(X,1);mu=nan(n,6);calibratedVariance=nan(n,6);
    rawUQLabVariance=nan(n,6);batches=0;
    for first=1:batchSize:n
        last=min(n,first+batchSize-1);
        [oneMean,oneCalibrated,oneRaw]=evaluator( ...
            model,double(X(first:last,:)));
        oneMean=double(oneMean);oneCalibrated=double(oneCalibrated);
        oneRaw=double(oneRaw);
        assert(isequal(size(oneMean),[last-first+1 6])&& ...
            isequal(size(oneCalibrated),size(oneMean))&& ...
            isequal(size(oneRaw),size(oneMean))&& ...
            all(isfinite(oneMean),'all')&& ...
            all(isfinite(oneCalibrated),'all')&& ...
            all(isfinite(oneRaw),'all')&& ...
            all(oneCalibrated>=0,'all')&&all(oneRaw>=0,'all'), ...
            'recovery:characterize_downstream_error_budget:GPEvaluation', ...
            'The injected/canonical evaluator returned invalid six-output data.');
        mu(first:last,:)=oneMean;
        calibratedVariance(first:last,:)=oneCalibrated;
        rawUQLabVariance(first:last,:)=oneRaw;
        batches=batches+1;
    end
end

function T=make_prediction_table(caseIDs,sourceRows,truth,mu, ...
        rawUQLabVariance,calibratedVariance,outputNames)
    [caseIndex,outputIndex]=ndgrid(1:numel(caseIDs),1:6);
    linear=sub2ind(size(truth),caseIndex(:),outputIndex(:));
    CaseID=caseIDs(caseIndex(:));SourceRow=sourceRows(caseIndex(:));
    OutputIndex=outputIndex(:);Output=reshape(string(outputNames(OutputIndex)),[],1);
    COMSOL=truth(linear);GPMean=mu(linear);
    RawUQLabVariance=rawUQLabVariance(linear);
    RawUQLabSD=sqrt(RawUQLabVariance);
    CalibratedEmulatorVariance=calibratedVariance(linear);
    CalibratedEmulatorSD=sqrt(CalibratedEmulatorVariance);
    GPResidual=GPMean-COMSOL;
    CalibratedStandardizedResidual=nan(size(CalibratedEmulatorSD));
    available=CalibratedEmulatorSD>0;
    CalibratedStandardizedResidual(available)= ...
        GPResidual(available)./CalibratedEmulatorSD(available);
    GPAbsoluteError=abs(GPResidual);
    T=table(SourceRow,CaseID,OutputIndex,Output,COMSOL,GPMean, ...
        RawUQLabVariance,RawUQLabSD,CalibratedEmulatorVariance, ...
        CalibratedEmulatorSD,GPResidual,CalibratedStandardizedResidual, ...
        GPAbsoluteError);
    T=T(isfinite(T.COMSOL),:);
end

