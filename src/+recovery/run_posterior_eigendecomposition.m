function result = run_posterior_eigendecomposition(cfg,grid,varargin)
%RUN_POSTERIOR_EIGENDECOMPOSITION The posterior-covariance eigendecomposition of the inversion grid.
%   RESULT = recovery.run_posterior_eigendecomposition(CFG, GRID, ...) reads
%   the selected providers' posteriors (recovery.load_posterior_provider), computes
%   the standardized covariance eigensystems of every cell and their
%   cohort consensus (recovery.summarize_posterior_eigendecomposition) and
%   the replicate stability, and writes the tables.
%   Options (name-value): 'OutputRoot' (default
%   CFG.paths.posteriorEigendecomposition) and 'WriteOutputs' (true).
%   Side effects: writes only below the posterior_eigendecomposition folder
%   of the recovery.
%   Computation: seconds to minutes.

    parser=inputParser;
    parser.FunctionName='recovery.run_posterior_eigendecomposition';
    addParameter(parser,'OutputRoot',cfg.paths.posteriorEigendecomposition, ...
        @(x)ischar(x)||(isstring(x)&&isscalar(x)));
    addParameter(parser,'WriteOutputs',true,@(x)islogical(x)&&isscalar(x));
    parse(parser,varargin{:});options=parser.Results;

    summary=recovery.summarize_posterior_eigendecomposition(cfg,grid);
    outputRoot=utils.absolute_path(options.OutputRoot);
    status=status_payload(cfg,summary,outputRoot);
    if options.WriteOutputs
        publish_outputs(outputRoot,summary,status);
    end
    result=struct('summary',summary,'status',status, ...
        'outputRoot',outputRoot,'outputsWritten',logical(options.WriteOutputs));
end

function publish_outputs(root,summary,status)
    similarityRoot=fullfile(root,'similarity');
    if ~isfolder(root),mkdir(root);end
    if ~isfolder(similarityRoot),mkdir(similarityRoot);end
    write(summary.directions,'posterior_eigendirections.csv');
    write(summary.directionalSDRatioSummary,'directional_sd_ratio_summary.csv');
    write(summary.covariance,'posterior_covariance_standardized.csv');
    write(summary.correlation,'posterior_correlation.csv');
    write(summary.gaps,'eigenvalue_gaps.csv');
    write(summary.axisProjectors,'axis_projectors.csv');
    write(summary.subspaceProjectors,'subspace_projectors.csv');
    write(summary.replicateStability,'replicate_eigensystem_stability.csv');
    write(summary.jointGeometryFull4D, ...
        'joint_geometry_replicate_full_4d.csv');
    write(summary.jointGeometryWeakPair, ...
        'joint_geometry_replicate_weak_pair.csv');
    write(summary.availability,'availability.csv');
    write(summary.matchedCohorts,'matched_cohorts.csv');
    write(summary.consensusAxes,'consensus_axes.csv');
    write(summary.consensusSubspaces,'consensus_subspaces.csv');
    write(summary.consensusProjectors,'consensus_mean_projectors.csv');
    write(summary.crossScenarioComparison,'cross_scenario_comparison.csv');
    fields=fieldnames(summary.similarity);
    for i=1:numel(fields)
        value=summary.similarity.(fields{i});
        tableValue=wide_similarity_table(value.caseIDs,value.matrix);
        utils.atomic_write_table(fullfile(similarityRoot, ...
            [value.scenario '_' value.kind '_similarity.csv']),tableValue);
    end
    utils.atomic_save_struct(fullfile(root, ...
        'posterior_eigendecomposition_summary.mat'),struct('summary',summary), ...
        '-v7.3');
    status=jsondecode(jsonencode(status));
    utils.atomic_write_json(fullfile(root, ...
        'posterior_eigendecomposition_status.json'),status,'AllowReplace',true);

    function write(tableValue,name)
        utils.atomic_write_table(fullfile(root,name),tableValue);
    end
end

function T=wide_similarity_table(caseIDs,matrix)
    caseIDs=reshape(double(caseIDs),[],1);
    assert(isequal(size(matrix),[numel(caseIDs) numel(caseIDs)]), ...
        'recovery:run_posterior_eigendecomposition:SimilarityShape', ...
        'Internal error: the similarity matrix must be %d x %d.',numel(caseIDs),numel(caseIDs));
    names=cellstr(matlab.lang.makeValidName("Case_"+string(caseIDs.')));
    T=array2table(matrix,'VariableNames',names);
    T=addvars(T,caseIDs,'Before',1,'NewVariableNames','CaseID');
end

function status=status_payload(cfg,summary,root)
    policy=cfg.analysis.posteriorEigendecomposition;
    status=struct( ...
        'schema_version','posterior_covariance_eigendecomposition_status_v2', ...
        'enabled',true,'consume_only',true, ...
        'case_ids',reshape(double(policy.caseIDs),1,[]), ...
        'design',policy.design,'scenarios',{policy.scenarios}, ...
        'excluded_scenarios',{policy.excludedScenarios}, ...
        'expected_cell_count',summary.expectedCellCount, ...
        'valid_cell_count',summary.validCellCount, ...
        'missing_or_invalid_cell_count',summary.missingOrInvalidCellCount, ...
        'replicate_2_available_count',summary.replicate2AvailableCount, ...
        'joint_geometry_replicate_pair_available_count', ...
            nnz(summary.jointGeometryFull4D.ReplicatePairAvailable), ...
        'matched_cross_scenario_case_ids', ...
            reshape(double(summary.matchedCrossScenarioCaseIDs),1,[]), ...
        'matched_cross_scenario_case_count', ...
            numel(summary.matchedCrossScenarioCaseIDs), ...
        'near_degenerate_gap_warning_threshold', ...
            policy.nearDegenerateGapThreshold, ...
        'negative_eigenvalue_relative_tolerance', ...
            policy.negativeEigenvalueTolerance, ...
        'symmetry_relative_tolerance',policy.symmetryTolerance, ...
        'output_root_metadata',run_relative(root,cfg.paths.runRoot), ...
        'primary_provider_semantics',policy.primaryPosteriorSemantics, ...
        'replicate_2_semantics',policy.replicate2Semantics, ...
        'posterior_draws_pooled',false,'certification_changed',false, ...
        'joint_geometry_acceptance_threshold_defined',false, ...
        'joint_geometry_role', ...
            'warning_and_manual_review_reproducibility_evidence', ...
        'stage04_artifacts_modified',false, ...
        'mcmc_runs_performed',0,'conditional_inversion_runs_performed',0, ...
        'likelihood_evaluations_performed',0,'gp_evaluations_performed',0, ...
        'surrogate_fits_performed',0,'stage05_recomputations_performed',0, ...
        'stage06_recomputations_performed',0);
end

function value=run_relative(pathValue,runRoot)
%RUN_RELATIVE A folder relative to the run root, with '/' (as it is when it lies outside the run).
    pathValue=utils.absolute_path(pathValue);
    prefix=[utils.absolute_path(runRoot) filesep];
    value=strrep(pathValue,'\','/');
    if startsWith(lower(pathValue),lower(prefix))
        value=strrep(pathValue(numel(prefix)+1:end),'\','/');
    end
end
