function provider = design_study_provider(cfg,grid,gp,P,cases,scenarioTag,coverage)
%DESIGN_STUDY_PROVIDER The design study's provider of the inversion grid.
%   PROVIDER = recovery.design_study_provider(CFG, GRID, GP, P, CASES,
%   SCENARIOTAG, COVERAGE) returns, for the scenario SCENARIOTAG of the
%   inversion grid GRID, the provider the design study reads
%   (design_study.generate): the cases and their truths, the six designs,
%   the forward map through the GP (for the local FIM and Jacobians and the
%   output transforms), the local observation covariances, the prior, and
%   the posteriors of the selected providers (recovery.load_posterior_provider;
%   the provider has no inversion path), with the coverage COVERAGE and the
%   certification and provenance metadata.
%   Side effects: none.

    scenario=design_study.real_scenario_policy(scenarioTag);
    designs=design_study.candidate_designs();
    selected=grid.cells(strcmp({grid.cells.scenario},scenario.tag));
    assert(numel(selected)==numel(cases)*6, ...
        'recovery:design_study_provider:ScenarioGrid', ...
        ['The inversion grid holds %d cells of scenario %s; the design study ' ...
         'needs one per case and design (%d cases x 6 designs).'], ...
        numel(selected),scenario.tag,numel(cases));
    providerCases=convert_cases(cfg,gp,P,cases,scenario);
    assert(nargin>=7&&istable(coverage), ...
        'recovery:design_study_provider:CoverageRequired', ...
        ['The design study needs the explicit certification coverage table of ' ...
         'the inversion; it does not infer a dense posterior grid.']);
    cohorts=design_study.certification_cohorts(coverage, ...
        {providerCases.case_id},{designs.name},scenario.tag);
    % The MATLAB and UQLab versions of the run (provenance, not a check).
    environment=utils.environment_line();
    transformOptions=transform_options(cfg);

    provider=struct();
    provider.schema_version='direct_mcmc_stage9_provider_v2';
    provider.route='real';
    provider.case_ids={providerCases.case_id};
    provider.n_cases=numel(providerCases);
    provider.cases=providerCases;
    provider.parameter_names=P.names;
    provider.parameter_bounds=P.bounds;
    provider.parameter_units=P.units;
    provider.prior_definition=struct( ...
        'distribution','independent_uniform_box', ...
        'mean_u',0.5*ones(4,1),'covariance_u',eye(4)/12);
    provider.target_parameter_names={'m3_e_RD','log10_k0_RD'};
    provider.target_indices=[2 3];
    provider.output_names={'p1_D2','p2_D2','p3_D2', ...
        'p1_D6','p2_D6','p3_D6'};
    provider.designs=designs;
    provider.transform_options=transformOptions;
    provider.subset_dimensions=design_study.subset_dimensions(designs);
    provider.certification_coverage=cohorts.coverage_table;
    provider.certification_cohorts=cohorts;
    provider.forward_evaluator=@(caseIndex,u)forward(gp,P,cfg,u);
    provider.observation_covariance_provider=@(caseIndex,design) ...
        design_covariance(cfg,providerCases,caseIndex,design);
    provider.posterior_provider=@(caseIndex,design)posterior_for_cell( ...
        cfg,grid,P,providerCases,caseIndex,design,scenario.tag,cohorts);
    provider.posterior_certification=scenario.certification;
    provider.claim_scope=scenario.providerClaimScope;
    if cohorts.all_cells_certified
        evidenceStatus='reliable_complete_grid';
    else
        evidenceStatus='reliable_partial_grid';
    end
    provider.reliability_metadata=struct( ...
        'schema_version','direct_mcmc_stage9_reliability_evidence_v1', ...
        'status',evidenceStatus, ...
        'all_cells_certified',cohorts.all_cells_certified, ...
        'all_consumed_posteriors_certified',cohorts.available_cell_count>0&&all( ...
            cohorts.coverage_table.Certified(cohorts.coverage_table.ArtifactLoaded)), ...
        'samples_pooled',false, ...
        'planned_cell_count',cohorts.planned_cell_count, ...
        'certified_cell_count',cohorts.certified_cell_count, ...
        'missing_cell_count',cohorts.missing_cell_count, ...
        'all_design_matched_case_count', ...
            cohorts.all_design.matched_case_count, ...
        'minimum_evidence_policy', ...
            'two_independent_AIES_ensembles_distribution_reproducibility_v2');
    provider.scenario_tag=scenario.tag;
    provider.observation_source=scenario.observationSource;
    provider.uncertainty_mode=scenario.uncertaintyMode;
    provider.thesis_primary=scenario.thesisPrimary;
    provider.likelihood=scenario.likelihood;
    provider.scientific_version=cfg.scientificVersion;
    provider.diagnostic_version=cfg.diagnosticVersion;
    provider.environment=environment;
    provider.capabilities=struct('posterior',true, ...
        'deterministic_identifiability',true,'posterior_predictive',true);
end

function converted=convert_cases(cfg,gp,P,cases,scenario)
    converted=repmat(struct(),1,numel(cases));
    opts=struct('uncertaintyMode',scenario.uncertaintyMode, ...
        'measurementCV',cfg.meas_cv);
    for i=1:numel(cases)
        prediction=surrogates.evaluate_canonical_gp( ...
            gp,cases(i).truth,cfg);
        mu=prediction.GPMean;
        sigma2=inversion.raw_observation_variance(mu, ...
            prediction.CalibratedEmulatorVariance,cfg,opts,1:6);
        if strcmp(scenario.observationSource,'gp_mean')
            observation=mu;
        else
            observation=cases(i).heldout_response;
        end
        converted(i).case_id=sprintf('%d',cases(i).case_id);
        converted(i).classification=['direct_mcmc_' scenario.tag];
        converted(i).truth_u=reshape(P.normalize(cases(i).truth),1,[]);
        converted(i).theta_physical=reshape(cases(i).truth,1,[]);
        converted(i).observation=reshape(observation,1,[]);
        converted(i).Sigma=diag(reshape(sigma2,1,[]));
        converted(i).scenario_tag=scenario.tag;
    end
end

function [mu,variance]=forward(gp,P,cfg,u)
    u=reshape(double(u),[],P.M);
    assert(all(u>=0&u<=1,'all'),'recovery:design_study_provider:NormalizedBounds', ...
        'Normalized parameters must lie in [0, 1].');
    prediction=surrogates.evaluate_canonical_gp(gp,P.denormalize(u),cfg);
    mu=prediction.GPMean;
    variance=prediction.CalibratedEmulatorVariance;
end

function covariance=design_covariance(cfg,cases,caseIndex,design)
    if ~isstruct(design),design=design_study.get_design( ...
            struct('designs',design_study.candidate_designs()),design);end
    raw=cases(caseIndex).Sigma;
    switch design.type
        case 'raw'
            covariance=raw(design.indices,design.indices);
        case 'ratio'
            [~,~,covariance]=design_study.ratio_transform( ...
                cases(caseIndex).observation,raw,cfg.ratios.denFloor);
        case 'transformed_full_rank'
            [~,~,covariance]=inversion.physics_guided_full_rank_transform( ...
                cases(caseIndex).observation,raw, ...
                cfg.physicsGuidedFullRankSix.denominatorFloor);
        otherwise
            error('recovery:design_study_provider:DesignTransform', ...
                'Unsupported design transform "%s".',design.type);
    end
end

function value=transform_options(cfg)
    assert(isfield(cfg,'physicsGuidedFullRankSix')&& ...
        all(isfield(cfg.physicsGuidedFullRankSix, ...
        {'denominatorFloor','transformVersion'})), ...
        'recovery:design_study_provider:PhysicsTransformConfiguration', ...
        ['The configuration lacks the physics-guided full-rank transform ' ...
         '(physicsGuidedFullRankSix.denominatorFloor and .transformVersion).']);
    assert(strcmp(cfg.physicsGuidedFullRankSix.transformVersion, ...
        'physics_guided_full_rank_six_full_delta_cov_v1'), ...
        'recovery:design_study_provider:PhysicsTransformVersion', ...
        ['The design study uses the transform ' ...
         'physics_guided_full_rank_six_full_delta_cov_v1; the configuration names %s.'], ...
        char(string(cfg.physicsGuidedFullRankSix.transformVersion)));
    value=struct('ratio_denominator_floor',cfg.ratios.denFloor, ...
        'physics_guided_denominator_floor', ...
            cfg.physicsGuidedFullRankSix.denominatorFloor, ...
        'physics_guided_transform_version', ...
            cfg.physicsGuidedFullRankSix.transformVersion);
end

function posterior=posterior_for_cell( ...
        cfg,grid,P,cases,caseIndex,design,scenario,cohorts)
    if ~isstruct(design),design=design_study.get_design( ...
            struct('designs',design_study.candidate_designs()),design);end
    caseID=str2double(cases(caseIndex).case_id);
    hit=find([grid.cells.caseID]==caseID& ...
        strcmp({grid.cells.scenario},scenario)& ...
        strcmp({grid.cells.design},design.name));
    assert(isscalar(hit),'recovery:design_study_provider:PosteriorCell', ...
        'The inversion grid holds %d cells for case %d, scenario %s and design %s; expected one.', ...
        numel(hit),caseID,scenario,design.name);
    designIndex=find(strcmp(cohorts.design_names,design.name));
    assert(isscalar(designIndex)&& ...
        cohorts.available_matrix(caseIndex,designIndex), ...
        'recovery:design_study_provider:PosteriorOutsideMatchedCoverage', ...
        ['The design study requested a posterior outside its matched certified ' ...
         'cohort; every analysis uses its predeclared matched cohort.']);
    [artifact,status]=recovery.load_posterior_provider(cfg,grid.cells(hit));
    assert(status.loaded,'recovery:design_study_provider:PosteriorUnavailable', ...
        'Certified posterior is unavailable: %s',status.reason);
    coverageHit=string(cohorts.coverage_table.CaseID)==string(caseID)& ...
        string(cohorts.coverage_table.Design)==string(design.name);
    provenance=recovery.posterior_provider_provenance(artifact);
    assert(nnz(coverageHit)==1,'recovery:design_study_provider:CoverageRow', ...
        'Cell %d/%s is not once in the certification coverage.',caseID,design.name);
    mechanism=char(string( ...
        cohorts.coverage_table.CertificationMechanism(coverageHit)));
    drawsU=P.normalize(double(artifact.drawsPhysical));
    meanU=mean(drawsU,1).';covariance=cov(drawsU);
    covariance=(covariance+covariance.')/2;
    q=quantile(drawsU,[0.025 0.975],1).';
    kind='certified_direct_mcmc';
    if ~status.certified,kind='exploratory_noncertified_direct_mcmc';end
    posterior=struct( ...
        'schema_version','direct_mcmc_stage9_posterior_v1', ...
        'case_id',cases(caseIndex).case_id, ...
        'design_name',design.name, ...
        'posterior_kind',kind, ...
        'mean_u',meanU,'covariance_u',covariance, ...
        'sd_u',sqrt(diag(covariance)), ...
        'credible_interval_95_u',q,'correlation',corrcoef(drawsU), ...
        'q_covariance_u',covariance([2 3],[2 3]), ...
        'draws_u',drawsU, ...
        'reliability',struct('reliable',logical(status.certified), ...
        'analysisEligible',logical(status.loaded), ...
        'certification_mechanism',mechanism, ...
        'provider',provenance.provider, ...
        'samples_pooled',false));
end
