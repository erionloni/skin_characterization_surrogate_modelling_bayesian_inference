        'replicate2Eigensystem',struct([]), ...
        'jointGeometry',struct([]), ...
        'includedInCrossScenarioComparison',false);
end

function record=consume_one(cfg,record,bounds,names,policy)
    try
        [artifact,status]=recovery.load_posterior_provider(cfg,record.cellRecord);
        % The loader decides which providers count: a run's own campaign
        % certified ones, the shipped draws also the healthy fallbacks
        % (as the thesis's analysis of the combined cells).
        [loaded,state,reason]=normalize_status(status,false);
        record.primaryLoadState=state;record.primaryLoadReason=reason;
        record.certifiedPosteriorAvailable=loaded&&status.certified;
        if ~loaded
            record.exclusionReason=nonempty(reason,'certified_posterior_unavailable');
            record.replicate2Reason='provider_posterior_unavailable';
            return;
        end
        provenance=extract_provenance(artifact,cfg);
        record.certifiedStepCount=provenance.stepCount;
        record.certificationMechanism=provenance.mechanism;
        record.posteriorArtifactReference=provenance.reference;
        draws=double(artifact.drawsPhysical);
        width=(bounds(:,2)-bounds(:,1)).';
        unitBox=(draws-bounds(:,1).')./width;
        unitBoxCovariance=cov(unitBox,0);
        analysisResult=recovery.posterior_covariance_eigensystem(draws,bounds, ...
            'ParameterNames',names, ...
            'NearDegenerateGap',policy.nearDegenerateGapThreshold, ...
            'NegativeEigenvalueTolerance',policy.negativeEigenvalueTolerance, ...
            'SymmetryTolerance',policy.symmetryTolerance, ...
            'UnitBoxCovariance',unitBoxCovariance);
        record.eigensystem=analysisResult.eigensystem;
        record.covariance=analysisResult.eigensystem.covarianceSymmetrized;
        record.correlation=correlation_from_covariance(record.covariance);
        record.consistencyMaxError= ...
            analysisResult.suppliedUnitBoxConsistencyMaximumAbsoluteError;
        record.consistencyFrobeniusError= ...
            analysisResult.suppliedUnitBoxConsistencyFrobeniusError;
        record.consistencyRelativeError= ...
            analysisResult.suppliedUnitBoxConsistencyRelativeFrobeniusError;
        record.eigensystemValid=logical(analysisResult.eigensystem.valid);
        if record.eigensystemValid
            record.exclusionReason='';
        else
            record.exclusionReason=char(string( ...
                analysisResult.eigensystem.invalidReason));
        end
        if status.certified
            record=consume_replicate2(cfg,record,artifact,bounds,names);
        else
            record.replicate2Reason='accepted_same_level_pair_unavailable_for_fallback';
        end
    catch exception
        record.eigensystemValid=false;
        record.exclusionReason=exception_reason(exception);
        if isempty(record.replicate2Reason)
            record.replicate2Reason='replicate2_not_compared_after_primary_error';
        end
    end
end

function record=consume_replicate2( ...
        cfg,record,primaryArtifact,bounds,names)
    try
        comparison=recovery.accepted_replicate_joint_geometry( ...
            cfg,record.cellRecord,primaryArtifact, ...
            'ReplicateLoader',@recovery.load_posterior_provider, ...
            'ParameterNames',names,'Bounds',bounds, ...
            'WeakPairIndices',cfg.analysis.weakPairIndices);
        record.replicate2LoadState=comparison.loadState;
        record.replicate2Reason=comparison.reason;
        record.replicate2Available=comparison.artifactAvailable;
        if ~comparison.available
            record.replicate2Reason=nonempty(comparison.reason, ...
                'replicate2_unavailable');
            return;
        end
        record.replicate2ArtifactReference=portable_reference( ...
            comparison.replicate2ArtifactPath,cfg.paths.runRoot);
        record.replicate2EvidenceBound=true;
        record.replicate2Eigensystem=comparison.replicate2Eigensystem;
        record.replicate2Valid=logical( ...
            comparison.replicate2Eigensystem.valid);
        record.jointGeometry=comparison.diagnostics;
        if ~record.replicate2Valid
            record.replicate2Reason=char(string( ...
                comparison.replicate2Eigensystem.invalidReason));
        end
    catch exception
        record.replicate2Valid=false;
        record.replicate2LoadState='invalid';
        record.replicate2Reason=exception_reason(exception);
    end
end

function [loaded,state,reason]=normalize_status(status,requireCertified)
    loaded=isstruct(status)&&isscalar(status)&&isfield(status,'loaded')&& ...
        logical(status.loaded);
    state='unresolved';reason='';
    if isstruct(status)&&isscalar(status)
        if isfield(status,'state'),state=char(string(status.state));end
        if isfield(status,'reason'),reason=char(string(status.reason));end
        if isfield(status,'valid'),loaded=loaded&&logical(status.valid);end
        if requireCertified
            loaded=loaded&&isfield(status,'certified')&& ...
                logical(status.certified);
        end
    end
end

function value=extract_provenance(artifact,cfg)
    if isstruct(artifact)&&isscalar(artifact)&&isfield(artifact,'certification')&& ...
            isfield(artifact.certification,'certified')&& ...
            ~logical(artifact.certification.certified)
        % A healthy fallback (the shipped draws, study.load_shipped_posterior):
        % its provider, with no certification evidence to check, as in the
        % thesis's analysis of the combined cells; its replicate pair is not
        % compared (consume_one).
        provider=artifact.certification.provider;
        assert(strcmpi(char(string(provider.sampler)),'AIES')&& ...
            ~logical(artifact.samplesPooled), ...
            'recovery:summarize_posterior_eigendecomposition:Provider', ...
            'A healthy fallback must be one unpooled AIES replicate.');
        value=struct('stepCount',double(provider.stepCount), ...
            'mechanism',char(string(artifact.certification.certificationMechanism)), ...
            'reference',portable_reference(artifact.paths.posteriorPath, ...
                cfg.paths.runRoot));
        return
    end
    assert(isstruct(artifact)&&isscalar(artifact)&& ...
        all(isfield(artifact,{'drawsPhysical','request', ...
        'certification','paths'}))&& ...
        isfield(artifact.certification,'provider')&& ...
        isfield(artifact.certification,'reliabilityDecision')&& ...
        isfield(artifact.certification,'certificationMechanism')&& ...
        isfield(artifact.paths,'posteriorPath'), ...
        'recovery:summarize_posterior_eigendecomposition:Provenance', ...
        'The certified provider lacks its certification or posterior path.');
    provider=artifact.certification.provider;
    assert(strcmpi(char(string(provider.sampler)),'AIES')&& ...
        double(provider.replicateID)==1&& ...
        double(provider.stepCount)==double(artifact.request.stepCount)&& ...
        strcmp(char(string(artifact.certification.certificationMechanism)), ...
            'CERTIFIED_AIES_REPLICATE_AGREEMENT')&& ...
        ~logical(artifact.samplesPooled), ...
        'recovery:summarize_posterior_eigendecomposition:Provider', ...
        'Primary eigensystem must use certified unpooled AIES replicate 1.');
    decision=artifact.certification.reliabilityDecision;
    assert(isstruct(decision)&&isscalar(decision)&& ...
        isfield(decision,'executedEvidence'), ...
        'recovery:summarize_posterior_eigendecomposition:ExecutedEvidence', ...
        'The certification lacks the executed evidence of its decision.');
    evidence=reshape(decision.executedEvidence,1,[]);
    requiredEvidence={'sampler','replicateID','stepCount','executionSucceeded'};
    assert(all(isfield(evidence,requiredEvidence)), ...
        'recovery:summarize_posterior_eigendecomposition:ExecutedEvidence', ...
        'Executed-evidence records are incomplete.');
    hit=strcmpi({evidence.sampler},'AIES')&[evidence.replicateID]==2& ...
        [evidence.stepCount]==double(provider.stepCount)& ...
        logical([evidence.executionSucceeded]);
    assert(nnz(hit)==1, ...
        'recovery:summarize_posterior_eigendecomposition:ReplicateEvidence', ...
        ['Certification must bind exactly one successful independent AIES ' ...
         'replicate 2 at the accepted step count.']);
    value=struct('stepCount',double(provider.stepCount), ...
        'mechanism',char(string(artifact.certification.certificationMechanism)), ...
        'reference',portable_reference(artifact.paths.posteriorPath, ...
            cfg.paths.runRoot));
end

function reference=portable_reference(pathValue,runRoot)
%PORTABLE_REFERENCE A posterior file relative to the run, or to the repository for the shipped draws.
%   A rerun on the shipped results reads the full draws from thesis_results/
%   (outside the run); their path is then recorded relative to the
%   repository (thesis_results/...), as recovery.run_feature_reconstruction
%   records it.
    pathValue=utils.absolute_path(pathValue);
    runRoot=utils.absolute_path(runRoot);
    prefix=[runRoot filesep];
    repository=[utils.absolute_path(study.root()) filesep];
    if startsWith(lower(pathValue),lower(prefix))
        reference=strrep(pathValue(numel(prefix)+1:end),'\','/');
    elseif startsWith(lower(pathValue),lower(repository))
        reference=strrep(pathValue(numel(repository)+1:end),'\','/');
    else
        reference=strrep(pathValue,'\','/');
    end
end

function R=correlation_from_covariance(C)
    sd=sqrt(max(diag(C),0));denominator=sd*sd.';
    R=C./denominator;
    R(denominator==0)=NaN;
    for i=1:4
        if sd(i)>0,R(i,i)=1;end
    end
    R=(R+R.')/2;
end

function T=direction_rows(record,names)
    n=4;labels=["tightest_direction";"intermediate_direction_1"; ...
        "intermediate_direction_2";"sloppiest_direction"];
    [raw,eigenvalue,zeroed,ratio,contraction,fraction,loadings,flip, ...
        gapBelow,gapAbove,nearBelow,nearAbove,appliedTolerance]= ...
        deal(nan(n,1),nan(n,1),false(n,1),nan(n,1),nan(n,1), ...
        nan(n,1),nan(n,4),false(n,1),nan(n,1),nan(n,1), ...
        false(n,1),false(n,1),NaN);
    if ~isempty(record.eigensystem)
        E=record.eigensystem;raw=E.rawEigenvalues;
        zeroed=E.tinyNegativeEigenvalueZeroed;
        appliedTolerance=E.negativeEigenvalueToleranceAppliedAbsolute;
    end
    if record.eigensystemValid
        E=record.eigensystem;
        eigenvalue=E.correctedEigenvalues;
        ratio=E.directionalPosteriorSDRatio;
        contraction=E.directionalContraction;
        fraction=E.posteriorVarianceFraction;
        loadings=E.eigenvectorsSignAligned.';flip=E.signFlipApplied;
        gapBelow=E.gapBelow;gapAbove=E.gapAbove;
        nearBelow=E.nearDegenerateBelow;nearAbove=E.nearDegenerateAbove;
    end
    T=table(repmat(string(record.scenario),n,1), ...
        repmat(record.caseID,n,1),repmat(string(record.design),n,1), ...
        (1:n).',labels,raw,eigenvalue,zeroed,ratio,contraction,fraction, ...
        loadings(:,1),loadings(:,2),loadings(:,3),loadings(:,4),flip, ...
        gapBelow,gapAbove,nearBelow,nearAbove, ...
        repmat(record.eigensystemValid,n,1), ...
        repmat(string(record.exclusionReason),n,1), ...
        repmat(record.consistencyMaxError,n,1), ...
        repmat(record.consistencyFrobeniusError,n,1), ...
        repmat(record.consistencyRelativeError,n,1), ...
        repmat(appliedTolerance,n,1), ...
        repmat(record.certifiedStepCount,n,1), ...
        repmat(string(record.certificationMechanism),n,1), ...
        repmat(string(record.posteriorArtifactReference),n,1), ...
        'VariableNames',{'Scenario','CaseID','Design','DirectionRank', ...
        'DirectionLabel','RawEigenvalue','Eigenvalue', ...
        'TinyNegativeEigenvalueZeroed','DirectionalPosteriorSDRatio', ...
        'DirectionalContraction','PosteriorVarianceFraction', ...
        ['Loading_' names{1}],['Loading_' names{2}],['Loading_' names{3}], ...
        ['Loading_' names{4}],'SignFlipApplied','GapBelow','GapAbove', ...
        'NearDegenerateBelow','NearDegenerateAbove','EigensystemValid', ...
        'EigensystemExclusionReason', ...
        'UnitBoxConsistencyMaximumAbsoluteError', ...
        'UnitBoxConsistencyFrobeniusError', ...
        'UnitBoxConsistencyRelativeFrobeniusError', ...
        'AppliedNegativeEigenvalueTolerance','CertifiedStepCount', ...
        'CertificationMechanism','PosteriorArtifactReference'});
end

function T=matrix_rows(record,names,M,valueName)
    [rowIndex,columnIndex]=ndgrid(1:4,1:4);n=16;
    T=table(repmat(string(record.scenario),n,1), ...
        repmat(record.caseID,n,1),repmat(string(record.design),n,1), ...
        reshape(string(names(rowIndex(:))),[],1), ...
        reshape(string(names(columnIndex(:))),[],1),M(:), ...
        repmat(record.eigensystemValid,n,1), ...
        'VariableNames',{'Scenario','CaseID','Design','RowParameter', ...
        'ColumnParameter',valueName,'EigensystemValid'});
    T.RowParameter=T.RowParameter(:);T.ColumnParameter=T.ColumnParameter(:);
end

function T=gap_rows(record)
    gap=nan(3,1);near=false(3,1);threshold=NaN;
    if record.eigensystemValid
        gap=record.eigensystem.relativeAdjacentGaps;
        near=record.eigensystem.nearDegenerateAdjacent;
        threshold=record.eigensystem.nearDegenerateGapThreshold;
    end
    T=table(repmat(string(record.scenario),3,1), ...
        repmat(record.caseID,3,1),repmat(string(record.design),3,1), ...
        (1:3).',(2:4).',gap,near,repmat(threshold,3,1), ...
        repmat(record.eigensystemValid,3,1), ...
        'VariableNames',{'Scenario','CaseID','Design','LowerDirectionRank', ...
        'UpperDirectionRank','RelativeGap','NearDegenerate', ...
        'WarningThreshold','EigensystemValid'});
end

function T=axis_projector_rows(record,names)
    parts=cell(4,1);
    for k=1:4
        M=nan(4);if record.eigensystemValid,M=record.eigensystem.axisProjectors(:,:,k);end
        parts{k}=projector_matrix_rows(record,names,M, ...
            "direction_"+string(k),k,1,record.eigensystemValid);
    end
    T=vertcat(parts{:});
end

function T=subspace_projector_rows(record,names)
    labels=["tight_2d" "sloppy_2d"];
    parts=cell(2,1);
    for k=1:2
        M=nan(4);
        if record.eigensystemValid
            if k==1,M=record.eigensystem.tight2DProjector;
            else,M=record.eigensystem.sloppy2DProjector;end
        end
        parts{k}=projector_matrix_rows(record,names,M,labels(k),NaN,2, ...
            record.eigensystemValid);
    end
    T=vertcat(parts{:});
end

function T=projector_matrix_rows( ...
        record,names,M,label,directionRank,rankValue,valid)
    [rowIndex,columnIndex]=ndgrid(1:4,1:4);n=16;
