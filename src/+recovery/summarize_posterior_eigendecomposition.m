        repmat(record.caseID,n,1),repmat(string(record.design),n,1), ...
        repmat(string(label),n,1),repmat(directionRank,n,1), ...
        repmat(rankValue,n,1), ...
        reshape(string(names(rowIndex(:))),[],1), ...
        reshape(string(names(columnIndex(:))),[],1),M(:), ...
        repmat(valid,n,1), ...
        'VariableNames',{'Scenario','CaseID','Design','ProjectorLabel', ...
        'DirectionRank','ProjectorRank','RowParameter','ColumnParameter', ...
        'ProjectorValue','EigensystemValid'});
    T.RowParameter=T.RowParameter(:);T.ColumnParameter=T.ColumnParameter(:);
end

function T=replicate_rows(record,divisionFloor)
    n=4;primary=nan(n,1);second=nan(n,1);difference=nan(n,1);
    alignment=nan(n,1);tightSimilarity=NaN;sloppySimilarity=NaN;
    primaryNear=nan(n,1);secondNear=nan(n,1);
    if record.eigensystemValid
        primary=record.eigensystem.correctedEigenvalues;
        primaryNear=double(record.eigensystem.nearDegenerateBelow| ...
            record.eigensystem.nearDegenerateAbove);
    end
    if record.eigensystemValid&&record.replicate2Valid
        E1=record.eigensystem;E2=record.replicate2Eigensystem;
        second=E2.correctedEigenvalues;
        difference=abs(second-primary)./max(abs(primary),divisionFloor);
        for k=1:4
            alignment(k)=recovery.axis_similarity( ...
                E1.eigenvectorsSignAligned(:,k), ...
                E2.eigenvectorsSignAligned(:,k));
        end
        tightSimilarity=recovery.subspace_similarity( ...
            E1.tight2DProjector,E2.tight2DProjector,2);
        sloppySimilarity=recovery.subspace_similarity( ...
            E1.sloppy2DProjector,E2.sloppy2DProjector,2);
        secondNear=double(E2.nearDegenerateBelow|E2.nearDegenerateAbove);
    end
    if ~record.eigensystemValid
        warningStatus="PRIMARY_EIGENSYSTEM_INVALID";
    elseif ~record.replicate2Available
        warningStatus="REPLICATE_2_UNAVAILABLE";
    elseif ~record.replicate2Valid
        if isempty(record.replicate2Eigensystem)
            warningStatus="REPLICATE_2_INVALID_OR_UNREADABLE";
        else
            warningStatus="REPLICATE_2_EIGENSYSTEM_INVALID";
        end
    elseif any(primaryNear==1)||any(secondNear==1)
        warningStatus="NEAR_DEGENERACY_WARNING";
    else
        warningStatus="AVAILABLE_NO_CONFIGURED_WARNING";
    end
    T=table(repmat(string(record.scenario),n,1), ...
        repmat(record.caseID,n,1),repmat(record.certifiedStepCount,n,1), ...
        (1:n).',primary,second,difference,alignment, ...
        repmat(tightSimilarity,n,1),repmat(sloppySimilarity,n,1), ...
        primaryNear,secondNear,repmat(record.replicate2Available,n,1), ...
        repmat(record.replicate2Valid,n,1), ...
        repmat(record.replicate2EvidenceBound,n,1), ...
        repmat(string(record.replicate2ArtifactReference),n,1), ...
        repmat(string(record.replicate2LoadState),n,1), ...
        repmat(string(record.replicate2Reason),n,1), ...
        repmat(warningStatus,n,1), ...
        'VariableNames',{'Scenario','CaseID','CertifiedStepCount', ...
        'DirectionRank','PrimaryEigenvalue','Replicate2Eigenvalue', ...
        'RelativeEigenvalueDifference','AxisAlignment', ...
        'Tight2DSubspaceSimilarity','Sloppy2DSubspaceSimilarity', ...
        'PrimaryNearDegenerate','Replicate2NearDegenerate', ...
        'Replicate2Available','Replicate2EigensystemValid', ...
        'Replicate2EvidenceBound','Replicate2ArtifactReference', ...
        'Replicate2LoadState','Replicate2Reason','WarningStatus'});
end

