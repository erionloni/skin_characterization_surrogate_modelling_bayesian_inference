function T=cross_scenario_table(records,policy,matchedIDs,divisionFloor)
    parts=cell(numel(policy.caseIDs),1);
    for c=1:numel(policy.caseIDs)
        caseID=policy.caseIDs(c);
        practical=find_record(records,caseID,'measurement_plus_gp');
        diagnostic=find_record(records,caseID,'gp_only');
        matched=ismember(caseID,matchedIDs);n=4;
        [practicalEigen,diagnosticEigen,difference,ratio,contractionDifference, ...
            alignment]=deal(nan(n,1));tight=NaN;sloppy=NaN;guarded=false(n,1);
        if matched
            E1=practical.eigensystem;E2=diagnostic.eigensystem;
            practicalEigen=E1.correctedEigenvalues;
            diagnosticEigen=E2.correctedEigenvalues;
            difference=practicalEigen-diagnosticEigen;
            guarded=abs(diagnosticEigen)<divisionFloor;
            ratio=practicalEigen./max(abs(diagnosticEigen),divisionFloor);
            contractionDifference=E1.directionalContraction- ...
                E2.directionalContraction;
            for k=1:4
                alignment(k)=recovery.axis_similarity( ...
                    E1.eigenvectorsSignAligned(:,k), ...
                    E2.eigenvectorsSignAligned(:,k));
            end
            tight=recovery.subspace_similarity( ...
                E1.tight2DProjector,E2.tight2DProjector,2);
            sloppy=recovery.subspace_similarity( ...
                E1.sloppy2DProjector,E2.sloppy2DProjector,2);
            reason="";
        else
            reason=string(cross_case_reason(practical,diagnostic));
        end
        parts{c}=table(repmat(caseID,n,1),(1:n).', ...
            repmat(matched,n,1),practicalEigen,diagnosticEigen,difference, ...
            ratio,guarded,contractionDifference,alignment, ...
            repmat(tight,n,1),repmat(sloppy,n,1),repmat(reason,n,1), ...
            'VariableNames',{'CaseID','DirectionRank','Matched', ...
            'MeasurementPlusGPEigenvalue','GPOnlyEigenvalue', ...
            'EigenvalueDifferenceMeasurementPlusGPMinusGPOnly', ...
            'EigenvalueRatioMeasurementPlusGPToGPOnly','RatioFloorApplied', ...
            'DirectionalContractionDifference','AxisAlignment', ...
            'Tight2DSubspaceSimilarity','Sloppy2DSubspaceSimilarity', ...
            'ExclusionReason'});
    end
    T=vertcat(parts{:});
end

function ids=cross_scenario_ids(records,policy)
    ids=[];
    for caseID=policy.caseIDs
        first=find_record(records,caseID,'measurement_plus_gp');
        second=find_record(records,caseID,'gp_only');
        if first.eigensystemValid&&second.eigensystemValid
            ids(end+1)=caseID; %#ok<AGROW>
        end
    end
end

function one=find_record(records,caseID,scenario)
    hit=[records.caseID]==caseID&strcmp({records.scenario},scenario);
    assert(nnz(hit)==1, ...
        'recovery:summarize_posterior_eigendecomposition:RecordBinding', ...
        'There are %d eigendecomposition records for case %d and scenario %s, not one.', ...
        nnz(hit),caseID,scenario);
    one=records(hit);
end

function value=cross_case_reason(first,second)
    parts=strings(0,1);
    if ~first.eigensystemValid
        parts(end+1,1)="measurement_plus_gp="+ ...
            string(nonempty(first.exclusionReason,'unspecified'));
    end
    if ~second.eigensystemValid
        parts(end+1,1)="gp_only="+ ...
            string(nonempty(second.exclusionReason,'unspecified'));
    end
    value=char(strjoin(parts,';'));
end

