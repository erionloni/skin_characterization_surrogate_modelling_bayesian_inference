function summary = summarize_posterior_eigendecomposition(cfg,grid)
%SUMMARIZE_POSTERIOR_EIGENDECOMPOSITION The eigensystems of the certified all_six posteriors.
%   SUMMARY = recovery.summarize_posterior_eigendecomposition(CFG, GRID)
%   computes, from the certified AIES replicate-1 draws of every all_six
%   cell, the standardized posterior covariance eigensystem
%   (recovery.posterior_covariance_eigensystem), the cohort consensus axes
%   and, per scenario and direction, the median and quartiles of the
%   directional posterior SD ratios (recovery.directional_sd_ratio_summary).
%   Replicate 2, loaded at the same accepted level, serves only a
%   warning-only stability comparison. A cell that fails is reported, and
%   the others continue. No posterior draws are created.
%   Side effects: none.

    policy=validate_configuration(cfg,grid);
    names=cellstr(string(policy.parameterNames));
    bounds=double(cfg.paramBounds);
    records=expected_records(cfg,grid,policy);
    for i=1:numel(records)
        records(i)=consume_one(cfg,records(i),bounds,names,policy);
    end

    matchedIDs=cross_scenario_ids(records,policy);
    for i=1:numel(records)
        records(i).includedInCrossScenarioComparison= ...
            records(i).eigensystemValid&&ismember(records(i).caseID,matchedIDs);
    end

    directionParts=cell(numel(records),1);
    covarianceParts=cell(numel(records),1);
    correlationParts=cell(numel(records),1);
    gapParts=cell(numel(records),1);
    axisProjectorParts=cell(numel(records),1);
    subspaceProjectorParts=cell(numel(records),1);
    replicateParts=cell(numel(records),1);
    fullGeometryParts=cell(numel(records),1);
    weakGeometryParts=cell(numel(records),1);
    availabilityParts=cell(numel(records),1);
    for i=1:numel(records)
        directionParts{i}=direction_rows(records(i),names);
        covarianceParts{i}=matrix_rows(records(i),names, ...
            records(i).covariance,'CovarianceValue');
        correlationParts{i}=matrix_rows(records(i),names, ...
            records(i).correlation,'CorrelationValue');
        gapParts{i}=gap_rows(records(i));
        axisProjectorParts{i}=axis_projector_rows(records(i),names);
        subspaceProjectorParts{i}=subspace_projector_rows(records(i),names);
        replicateParts{i}=replicate_rows(records(i),policy.divisionFloor);
        fullGeometryParts{i}=joint_geometry_row(records(i),names, ...
            'full_4d',1:4);
        weakGeometryParts{i}=joint_geometry_row(records(i),names, ...
            'weak_pair',[2 3]);
        availabilityParts{i}=availability_row(records(i));
    end

    directions=vertcat(directionParts{:});
    covariance=vertcat(covarianceParts{:});
    correlation=vertcat(correlationParts{:});
    gaps=vertcat(gapParts{:});
    axisProjectors=vertcat(axisProjectorParts{:});
    subspaceProjectors=vertcat(subspaceProjectorParts{:});
    replicateStability=vertcat(replicateParts{:});
    jointGeometryFull4D=vertcat(fullGeometryParts{:});
    jointGeometryWeakPair=vertcat(weakGeometryParts{:});
    availability=vertcat(availabilityParts{:});
    [matchedCohorts,scenarioIncluded]=cohort_table(records,policy,matchedIDs);
    similarity=similarity_matrices(records,policy);
    [consensusAxes,consensusSubspaces,consensusProjectors]= ...
        consensus_tables(records,policy,names);
    crossScenario=cross_scenario_table(records,policy,matchedIDs, ...
        policy.divisionFloor);

    expectedCellCount=numel(records);parameterCount=numel(names);
    assert(height(directions)==expectedCellCount*parameterCount&& ...
        height(covariance)==expectedCellCount*parameterCount^2&& ...
        height(correlation)==expectedCellCount*parameterCount^2&& ...
        height(gaps)==expectedCellCount*(parameterCount-1)&& ...
        height(axisProjectors)==expectedCellCount*parameterCount^3&& ...
        height(subspaceProjectors)==expectedCellCount*2*parameterCount^2&& ...
        height(replicateStability)==expectedCellCount*parameterCount&& ...
        height(availability)==expectedCellCount&& ...
        height(jointGeometryFull4D)==expectedCellCount&& ...
        height(jointGeometryWeakPair)==expectedCellCount&& ...
        height(crossScenario)==numel(policy.caseIDs)*parameterCount, ...
        'recovery:summarize_posterior_eigendecomposition:RowCounts', ...
        'The eigen-analysis tables do not have the row counts of the configured grid.');
    summary=struct( ...
        'schemaVersion','posterior_covariance_eigendecomposition_summary_v2', ...
        'parameterNames',{names},'priorBounds',bounds, ...
        'priorMean',mean(bounds,2).', ...
        'priorSD',((bounds(:,2)-bounds(:,1))/sqrt(12)).', ...
        'priorCovarianceStandardized',eye(4), ...
        'directions',directions, ...
        'directionalSDRatioSummary',recovery.directional_sd_ratio_summary(directions), ...
        'covariance',covariance, ...
        'correlation',correlation,'gaps',gaps, ...
        'axisProjectors',axisProjectors, ...
        'subspaceProjectors',subspaceProjectors, ...
        'replicateStability',replicateStability, ...
        'jointGeometryFull4D',jointGeometryFull4D, ...
        'jointGeometryWeakPair',jointGeometryWeakPair, ...
        'availability',availability,'matchedCohorts',matchedCohorts, ...
        'consensusAxes',consensusAxes, ...
        'consensusSubspaces',consensusSubspaces, ...
        'consensusProjectors',consensusProjectors, ...
        'crossScenarioComparison',crossScenario, ...
        'similarity',similarity, ...
        'scenarioIncludedCaseIDs',scenarioIncluded, ...
        'matchedCrossScenarioCaseIDs',matchedIDs, ...
        'expectedCellCount',expectedCellCount, ...
        'validCellCount',sum(availability.EigensystemValid), ...
        'missingOrInvalidCellCount',sum(~availability.EigensystemValid), ...
        'replicate2AvailableCount',sum(availability.Replicate2Available), ...
        'posteriorDrawsPooled',false, ...
        'certificationChanged',false, ...
        'mcmcRunsPerformed',0,'likelihoodEvaluationsPerformed',0, ...
        'gpEvaluationsPerformed',0,'surrogateFitsPerformed',0);
end

function policy=validate_configuration(cfg,grid)
    canonical={'m3_f_RD','m3_e_RD','log10_k0_RD','Thickness_RD'};
    assert(strcmp(cfg.dataMode,'real')&&isequal(cfg.paramNames,canonical)&& ...
        isequal(size(cfg.paramBounds),[4 2])&& ...
        isfield(cfg,'analysis')&& ...
        isfield(cfg.analysis,'posteriorEigendecomposition'), ...
        'recovery:summarize_posterior_eigendecomposition:Configuration', ...
        'The canonical real-route four-parameter configuration is required.');
    policy=cfg.analysis.posteriorEigendecomposition;
    expectedCellCount=numel(cfg.inversion.caseIDs)*2;
    assert(isequal(reshape(double(policy.caseIDs),1,[]), ...
            reshape(double(cfg.inversion.caseIDs),1,[]))&& ...
        ~isempty(policy.caseIDs)&& ...
        numel(unique(policy.caseIDs))==numel(policy.caseIDs)&& ...
        strcmp(policy.design,'all_six')&& ...
        isequal(policy.scenarios,{'measurement_plus_gp','gp_only'})&& ...
        isequal(policy.excludedScenarios,{'gp_self_det'})&& ...
        isequal(policy.parameterNames,canonical)&& ...
        double(policy.expectedCellCount)==expectedCellCount&& ...
        ~logical(policy.poolingPermitted)&& ...
        ~logical(policy.automaticPosteriorGenerationPermitted), ...
        'recovery:summarize_posterior_eigendecomposition:Policy', ...
        ['The eigen-analysis policy must be the configured cases, the design ' ...
         'all_six and the scenarios measurement_plus_gp and gp_only.']);
    assert(isstruct(grid)&&isscalar(grid)&&isfield(grid,'cells')&& ...
        numel(grid.cells)==double(cfg.inversion.expectedCellCount)&& ...
        double(grid.cellCount)==double(cfg.inversion.expectedCellCount), ...
        'recovery:summarize_posterior_eigendecomposition:Grid', ...
        'The complete configured inversion grid is required to locate the posteriors.');
end

function records=expected_records(cfg,grid,policy)
    template=empty_record();records=repmat(template,policy.expectedCellCount,1);
    cursor=0;
    for c=1:numel(policy.caseIDs)
        for s=1:numel(policy.scenarios)
            hit=[grid.cells.caseID]==policy.caseIDs(c)& ...
                strcmp({grid.cells.scenario},policy.scenarios{s})& ...
                strcmp({grid.cells.design},policy.design);
            assert(nnz(hit)==1, ...
                'recovery:summarize_posterior_eigendecomposition:CellBinding', ...
                'Each expected CaseID/scenario must bind one canonical all_six cell.');
            cursor=cursor+1;one=grid.cells(hit);
            records(cursor)=template;
            records(cursor).cellRecord=one;
            records(cursor).caseID=double(one.caseID);
            records(cursor).scenario=char(string(one.scenario));
            records(cursor).design=char(string(one.design));
        end
    end
    assert(cursor==double(policy.expectedCellCount)&& ...
        isequal([records.caseID], ...
        repelem(double(cfg.inversion.caseIDs),2)), ...
        'recovery:summarize_posterior_eigendecomposition:Order', ...
        'Expected records must retain canonical case order and scenario order.');
end

