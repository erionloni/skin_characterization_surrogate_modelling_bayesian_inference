function [T,includedByScenario]=cohort_table(records,policy,matchedIDs)
    parts=cell(3,1);includedByScenario=struct();
    for s=1:2
        scenario=policy.scenarios{s};one=records(strcmp({records.scenario},scenario));
        included=[one([one.eigensystemValid]).caseID];
        excluded=[one(~[one.eigensystemValid]).caseID];
        includedByScenario.(matlab.lang.makeValidName(scenario))=included;
        reasons=compose_exclusions(one);
        parts{s}=cohort_row("scenario",scenario,numel(policy.caseIDs), ...
            included,excluded,reasons);
    end
    excluded=setdiff(double(policy.caseIDs),matchedIDs,'stable');
    reasons=cross_exclusions(records,excluded,policy);
    parts{3}=cohort_row("cross_scenario", ...
        'measurement_plus_gp_vs_gp_only',numel(policy.caseIDs), ...
        matchedIDs,excluded,reasons);
    T=vertcat(parts{:});
end

function T=cohort_row(kind,scenario,expected,included,excluded,reasons)
    T=table(string(kind),string(scenario),expected,numel(included), ...
        numel(excluded),string(integer_list(included)), ...
        string(integer_list(excluded)),string(reasons), ...
        'VariableNames',{'CohortType','Scenario','ExpectedCaseCount', ...
        'IncludedCaseCount','ExcludedCaseCount','IncludedCaseIDs', ...
        'ExcludedCaseIDs','ExclusionReasons'});
end

function value=compose_exclusions(records)
    parts=strings(0,1);
    for i=1:numel(records)
        if ~records(i).eigensystemValid
            parts(end+1,1)=string(records(i).caseID)+":"+ ...
                string(nonempty(records(i).exclusionReason,'unspecified')); %#ok<AGROW>
        end
    end
    value=char(strjoin(parts,';'));
end

function value=cross_exclusions(records,excluded,policy)
    parts=strings(0,1);
    for c=excluded
        reasons=strings(0,1);
        for s=1:2
            one=find_record(records,c,policy.scenarios{s});
            if ~one.eigensystemValid
                reasons(end+1,1)=string(policy.scenarios{s})+"="+ ...
                    string(nonempty(one.exclusionReason,'unspecified')); %#ok<AGROW>
            end
        end
        parts(end+1,1)=string(c)+":"+strjoin(reasons,","); %#ok<AGROW>
    end
    value=char(strjoin(parts,';'));
end

function similarity=similarity_matrices(records,policy)
    similarity=struct();
    kinds={'tightest_axis','sloppiest_axis','tight2d','sloppy2d'};
    for s=1:2
        scenario=policy.scenarios{s};one=records(strcmp({records.scenario},scenario));
        one=one([one.eigensystemValid]);ids=[one.caseID];n=numel(one);
        for q=1:numel(kinds)
            matrix=nan(n);
            for i=1:n
                for j=1:n
                    matrix(i,j)=pair_similarity(one(i),one(j),kinds{q});
                end
            end
            field=matlab.lang.makeValidName([scenario '_' kinds{q}]);
            similarity.(field)=struct('scenario',scenario,'kind',kinds{q}, ...
                'caseIDs',ids,'matrix',matrix);
        end
    end
end

function value=pair_similarity(first,second,kind)
    E1=first.eigensystem;E2=second.eigensystem;
    switch kind
        case 'tightest_axis'
            value=recovery.axis_similarity(E1.eigenvectorsSignAligned(:,1), ...
                E2.eigenvectorsSignAligned(:,1));
        case 'sloppiest_axis'
            value=recovery.axis_similarity(E1.eigenvectorsSignAligned(:,4), ...
                E2.eigenvectorsSignAligned(:,4));
        case 'tight2d'
            value=recovery.subspace_similarity( ...
                E1.tight2DProjector,E2.tight2DProjector,2);
        case 'sloppy2d'
            value=recovery.subspace_similarity( ...
                E1.sloppy2DProjector,E2.sloppy2DProjector,2);
        otherwise
            error('recovery:summarize_posterior_eigendecomposition:SimilarityKind', ...
                'Unsupported axis/subspace similarity kind: %s.',kind);
    end
end

function [axesTable,subspaceTable,projectorTable]= ...
        consensus_tables(records,policy,names)
    axisParts={};subspaceParts={};projectorParts={};
    for s=1:2
        scenario=policy.scenarios{s};one=records(strcmp({records.scenario},scenario));
        one=one([one.eigensystemValid]);
        if isempty(one),continue;end
        ids=[one.caseID];
        definitions={ ...
            'tightest_axis',1,@(E)E.axisProjectors(:,:,1); ...
            'sloppiest_axis',1,@(E)E.axisProjectors(:,:,4); ...
            'tight_2d',2,@(E)E.tight2DProjector; ...
            'sloppy_2d',2,@(E)E.sloppy2DProjector};
        for q=1:size(definitions,1)
            stack=zeros(4,4,numel(one));
            extractor=definitions{q,3};
            for i=1:numel(one),stack(:,:,i)=extractor(one(i).eigensystem);end
            rankValue=definitions{q,2};label=definitions{q,1};
            consensus=recovery.consensus_projector(stack,'TargetRank',rankValue);
            if rankValue==1
                axisParts{end+1,1}=consensus_axis_row( ...
                    scenario,label,ids,consensus,names); %#ok<AGROW>
            else
                subspaceParts{end+1,1}=consensus_subspace_row( ...
                    scenario,label,ids,consensus); %#ok<AGROW>
            end
            projectorParts{end+1,1}=consensus_projector_rows( ...
                scenario,label,ids,consensus.meanProjector,names); %#ok<AGROW>
        end
    end
    axesTable=vertcat_or_empty(axisParts,empty_consensus_axes(names));
    subspaceTable=vertcat_or_empty(subspaceParts,empty_consensus_subspaces());
    projectorTable=vertcat_or_empty(projectorParts,empty_consensus_projectors());
end

