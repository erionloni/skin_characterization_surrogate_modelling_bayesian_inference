function similarity = axis_similarity(firstAxis,secondAxis)
%AXIS_SIMILARITY Sign-invariant similarity between two one-dimensional axes.
%   The returned value is ABS(V1'*V2) after numerical unit normalization.
%   SIMILARITY = recovery.axis_similarity(FIRSTAXIS, SECONDAXIS) returns a
%   value in [0, 1].
%   Side effects: none.

    assert(isnumeric(firstAxis)&&isreal(firstAxis)&&isvector(firstAxis)&& ...
        isnumeric(secondAxis)&&isreal(secondAxis)&&isvector(secondAxis)&& ...
        numel(firstAxis)==numel(secondAxis)&&~isempty(firstAxis)&& ...
        all(isfinite(firstAxis(:)))&&all(isfinite(secondAxis(:))), ...
        'recovery:axis_similarity:Axes', ...
        'Axes must be finite real vectors of the same nonzero length.');
    firstAxis=double(firstAxis(:));secondAxis=double(secondAxis(:));
    firstNorm=norm(firstAxis);secondNorm=norm(secondAxis);
    assert(firstNorm>0&&secondNorm>0,'recovery:axis_similarity:ZeroAxis', ...
        'Axis vectors must have nonzero norm.');
    similarity=abs((firstAxis/firstNorm).'*(secondAxis/secondNorm));
    tolerance=64*eps(max(1,similarity));
    assert(similarity<=1+tolerance, ...
        'recovery:axis_similarity:NumericalRange', ...
        'Computed axis similarity is materially outside [0,1].');
    if similarity>1,similarity=1;end
end
